let lang = "en";

export const getLang = () => lang;

export function setLang(l) {
  lang = l === "ja" ? "ja" : "en";
}

/** Chooses the language: the stored choice, else the browser language (ja* gives Japanese). */
export function initLang(stored, browser) {
  if (stored === "en" || stored === "ja") setLang(stored);
  else setLang(String(browser ?? "").toLowerCase().startsWith("ja") ? "ja" : "en");
}

export function t(key, ...args) {
  const s = messages[lang][key] ?? messages.en[key] ?? key;
  return args.length ? s.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)])) : s;
}

/** Updates every element with data-i18n (text) or data-i18n-attr ("attr:key;attr:key") under root. */
export function applyI18n(root) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-attr]")) {
    for (const pair of el.dataset.i18nAttr.split(";")) {
      if (!pair) continue;
      const [attr, key] = pair.split(":");
      el.setAttribute(attr, t(key));
    }
  }
}
