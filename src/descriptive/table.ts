// Counting and binning: R's tabulate, table (for one vector), unique, cut (codes) and findInterval.
//
// Written for rStats.js. cut's generation of breaks from a number of intervals follows R's behaviour: equal spacing
// over the range, ends widened by 1/1000 of the range, and a special case for a zero range. NaN stands for R's NA:
// unique keeps one NaN; table counts it according to `useNA`; cut and findInterval return NaN for it. table's levels
// are made as R's factor() makes them: numbers with the same 15-digit text are one level (src/internal/levels.ts).

import { numberLevels } from "../internal/levels.js";
import { seqLength } from "../internal/seq.js";
import type { Sample } from "../htest/types.js";
import { maxOf, minOf } from "../internal/extremes.js";
import { optionalArgs } from "../internal/optionalArgs.js";
// Generated by `node scripts/option-keys.mjs --write` from the option types; do not edit (begin)
import { checkOptions } from "../internal/checkOptions.js";
import { optionsIn } from "../internal/optionalArgs.js";
const TABULATE_KEYS = ["nbins"] as const;
const TABLE_KEYS = ["useNA"] as const;
const CUT_KEYS = ["right", "includeLowest"] as const;
const FIND_INTERVAL_KEYS = ["rightmostClosed", "allInside", "leftOpen"] as const;
// Generated by `node scripts/option-keys.mjs --write` (end)

/**
 * Options for {@link tabulate}.
 *
 * @category Descriptive statistics
 */
export interface TabulateOptions {
  /** Number of bins. Default max(1, bin); truncated towards 0, as R does. */
  nbins?: number;
}

/**
 * Counts of the integers 1..nbins in `bin` (values truncated towards 0; others, NaN, infinite values and values
 * beyond the integer range of R are not counted).
 * Equivalent to R's `tabulate()`. `nbins` defaults to max(1, bin) and is truncated towards 0, as R does; it is the
 * second argument or the option `nbins` (giving both is a RangeError).
 *
 * @example
 * ```ts
 * tabulate([1, 2, 2, 5]);    // [1, 2, 0, 0, 1]
 * tabulate([1, 2, 2, 5], 3); // [1, 2, 0]
 * ```
 *
 * @category Descriptive statistics
 */
export function tabulate(bin: Sample, nbins?: number): number[];
/**
 * Counts of the integers 1..nbins in `bin`, with the number of bins in the options: `tabulate(bin, { nbins: 3 })`.
 *
 * @example
 * ```ts
 * tabulate([1, 2, 2, 5], { nbins: 3 }); // [1, 2, 0]
 * ```
 */
export function tabulate(bin: Sample, options: TabulateOptions): number[];
export function tabulate(bin: Sample, ...args: unknown[]): number[] {
  checkOptions(optionsIn(args), TABULATE_KEYS, "tabulate"); // generated: option-keys.mjs
  const { nbins } = optionalArgs<TabulateOptions>(["nbins"], args);
  // as R's as.integer: truncated, and NA (here NaN) when infinite or outside the integer range, so such a value is
  // not counted and does not set the default nbins (Infinity was an array of infinite length, 3e9 ran out of memory,
  // #225)
  const b = Array.from(bin, (v) => {
    const t = Math.trunc(v);
    return t >= -2147483647 && t <= 2147483647 ? t : NaN;
  });
  if (nbins !== undefined) {
    if (Number.isNaN(nbins)) throw new RangeError("missing value where TRUE/FALSE needed");
    if (Math.trunc(nbins) < 0) throw new RangeError("invalid 'nbin' argument");
    if (Math.trunc(nbins) >= 2 ** 31) throw new RangeError("attempt to make a table with >= 2^31 elements");
  }
  const nb = nbins === undefined ? Math.max(1, maxOf(b.filter((v) => !Number.isNaN(v)))) : Math.trunc(nbins);
  const out = new Array<number>(Math.max(0, nb)).fill(0);
  for (const v of b) if (v >= 1 && v <= nb) out[v - 1]!++;
  return out;
}

/**
 * Options for {@link table}.
 *
 * @category Descriptive statistics
 */
export interface TableOptions {
  /** Count missing values: `"no"` (default), `"ifany"` (when there are some) or `"always"`. */
  useNA?: "no" | "ifany" | "always";
}

/**
 * Frequency table of the distinct values. Equivalent to R's `table()`. For one numeric vector: `values` in increasing
 * order (NaN last when counted) with their `counts`. As in R, values with the same text (15 significant digits, as
 * R's `as.character`) are counted as one, under the smallest of them.
 *
 * @example
 * ```ts
 * table([3, 1, 3, 2, 3]); // { values: [1, 2, 3], counts: [1, 1, 3] }
 * ```
 *
 * @category Descriptive statistics
 */
export function table(
  x: Sample,
  options: TableOptions = {},
): {
  /** The distinct values, in increasing order (NaN last when missing values are counted); R's names. */
  values: number[];
  /** How often each value occurs. */
  counts: number[];
} {
  checkOptions(options, TABLE_KEYS, "table"); // generated: option-keys.mjs
  const useNA = options.useNA ?? "no";
  // (as R's match.arg; any other value was taken as "no", silently dropping the count of missing values; issue #18)
  if (useNA !== "no" && useNA !== "ifany" && useNA !== "always") throw new RangeError("'arg' should be one of “no”, “ifany”, “always”");
  const xs = numberLevels(Array.from(x));
  const map = new Map<number, number>();
  let nas = 0;
  for (const v of xs) {
    if (Number.isNaN(v)) nas++;
    else map.set(v, (map.get(v) ?? 0) + 1);
  }
  const values = Array.from(map.keys()).sort((a, b) => a - b);
  const counts = values.map((v) => map.get(v)!);
  if (useNA === "always" || (useNA === "ifany" && nas > 0)) {
    values.push(NaN);
    counts.push(nas);
  }
  return { values, counts };
}

/**
 * Distinct values in order of first appearance (one NaN at most). Equivalent to R's `unique()`.
 *
 * @example
 * ```ts
 * unique([3, 1, 3, 2, 1]); // [3, 1, 2]
 * ```
 *
 * @category Descriptive statistics
 */
export function unique(x: Sample): number[] {
  const seen = new Set<number>();
  const out: number[] = [];
  for (const v of Array.from(x)) {
    const k = v === 0 ? 0 : v; // -0 and 0 are the same value
    if (!seen.has(k)) {
      seen.add(k);
      out.push(v);
    }
  }
  return out;
}

/**
 * Options for {@link cut}.
 *
 * @category Descriptive statistics
 */
export interface CutOptions {
  /** Intervals closed on the right, (a, b] (default `true`); otherwise [a, b). */
  right?: boolean;
  /** Close the first interval on the left (or the last on the right when `right` is false). Default `false`. */
  includeLowest?: boolean;
}

/**
 * Interval numbers (1-based) of the values, or NaN outside the breaks. Equivalent to R's `cut(..., labels = FALSE)`.
 *
 * @param breaks The break points (NaN among them is dropped, as R does; fewer than 2 left are an error), or a
 *   number of intervals (at least 2): then equal intervals over the range of `x`, widened by 1/1000 of the range at
 *   each end, as R does. That range must be finite.
 *
 * @example
 * ```ts
 * cut([1, 2.5, 4, 6], [0, 2, 4, 6]);                  // [1, 2, 2, 3]
 * cut([1, 2.5, 4, 6], [0, 2, 4, 6], { right: false }); // [1, 2, 3, NaN]
 * ```
 *
 * @category Descriptive statistics
 */
export function cut(x: Sample, breaks: number | readonly number[], options: CutOptions = {}): number[] {
  checkOptions(options, CUT_KEYS, "cut"); // generated: option-keys.mjs
  const right = options.right ?? true;
  const includeLowest = options.includeLowest ?? false;
  const xs = Array.from(x);
  let br: number[];
  if (typeof breaks === "number" || breaks.length === 1) {
    const k = typeof breaks === "number" ? breaks : breaks[0]!;
    if (!(k >= 2)) throw new RangeError("invalid number of intervals");
    const nb = Math.trunc(k + 1);
    const present = xs.filter((v) => !Number.isNaN(v));
    const lo = minOf(present);
    const hi = maxOf(present);
    // R's errors for a range that is not finite: the same infinity everywhere fails before the checks of the ends
    if (present.length > 0 && lo === hi && !Number.isFinite(lo)) throw new RangeError("missing value where TRUE/FALSE needed");
    if (present.length === 0 || lo === -Infinity) throw new RangeError("'from' must be a finite number");
    if (hi === Infinity) throw new RangeError("'to' must be a finite number");
    let dx = hi - lo;
    if (dx === 0) {
      dx = lo !== 0 ? Math.abs(lo) : 1;
      br = seqLength(lo - dx / 1000, hi + dx / 1000, nb);
    } else {
      br = seqLength(lo, hi, nb);
      br[0] = lo - dx / 1000;
      br[nb - 1] = hi + dx / 1000;
    }
  } else {
    br = breaks.filter((v) => !Number.isNaN(v)).sort((a, b) => a - b);
    // no interval to code: the error of one break (R gives NA codes for none, or one left after dropping NaN; #227)
    if (br.length < 2) throw new RangeError("invalid number of intervals");
  }
  if (new Set(br).size < br.length) throw new RangeError("'breaks' are not unique");
  return binCode(xs, br, right, includeLowest);
}

/** Interval codes as R's .bincode */
function binCode(xs: readonly number[], br: readonly number[], right: boolean, includeLowest: boolean): number[] {
  const nb = br.length;
  return xs.map((v) => {
    if (Number.isNaN(v)) return NaN;
    // first index i with br[i] >= v (right) or br[i] > v (left)
    let lo = 0;
    let hi = nb;
    while (lo < hi) {
      const mid = Math.floor((lo + hi) / 2); // not >> 1, which wraps beyond 2^31 breaks (issue #340)
      if (right ? br[mid]! < v : br[mid]! <= v) lo = mid + 1;
      else hi = mid;
    }
    let code = lo; // v in (br[code - 1], br[code]] (right) or [br[code - 1], br[code]) (left)
    if (includeLowest) {
      if (right && v === br[0]) code = 1;
      if (!right && v === br[nb - 1]) code = nb - 1;
    }
    return code >= 1 && code <= nb - 1 ? code : NaN;
  });
}

/**
 * Options for {@link findInterval}.
 *
 * @category Descriptive statistics
 */
export interface FindIntervalOptions {
  /** Treat the last interval as closed on the right (with `leftOpen`, the first as closed on the left). */
  rightmostClosed?: boolean;
  /** Give 1 instead of 0 left of the first point and N - 1 instead of N at or right of the last (N = `vec.length`). */
  allInside?: boolean;
  /** Intervals (v_i, v_(i+1)] instead of [v_i, v_(i+1)). */
  leftOpen?: boolean;
}

/**
 * For each value, the number of break points at or below it (the interval index). Equivalent to R's
 * `findInterval()`. `vec` must be non-decreasing.
 *
 * @example
 * ```ts
 * findInterval([0, 1.5, 3, 5], [1, 2, 3]); // [0, 1, 3, 3]
 * ```
 *
 * @category Descriptive statistics
 */
export function findInterval(x: Sample, vec: readonly number[], options: FindIntervalOptions = {}): number[] {
  checkOptions(options, FIND_INTERVAL_KEYS, "findInterval"); // generated: option-keys.mjs
  const n = vec.length;
  for (let i = 1; i < n; i++) {
    if (!(vec[i]! >= vec[i - 1]!)) throw new RangeError("'vec' must be sorted non-decreasingly and not contain NAs");
  }
  if (vec.some(Number.isNaN)) throw new RangeError("'vec' must be sorted non-decreasingly and not contain NAs");
  const { rightmostClosed = false, allInside = false, leftOpen = false } = options;
  return Array.from(x).map((v) => {
    if (Number.isNaN(v)) return NaN;
    if (n === 0) return 0;
    // The two ends are separate rules, as in R (with n = 1 the second can give 0 and the first 1)
    if (leftOpen ? v <= vec[0]! : v < vec[0]!) return allInside || (rightmostClosed && leftOpen && v === vec[0]) ? 1 : 0;
    if (leftOpen ? v > vec[n - 1]! : v >= vec[n - 1]!) return allInside || (rightmostClosed && !leftOpen && v === vec[n - 1]) ? n - 1 : n;
    // count of vec <= v (or < v when left-open)
    let lo = 0;
    let hi = n;
    while (lo < hi) {
      const mid = Math.floor((lo + hi) / 2); // not >> 1 (issue #340)
      if (leftOpen ? vec[mid]! < v : vec[mid]! <= v) lo = mid + 1;
      else hi = mid;
    }
    return lo;
  });
}
