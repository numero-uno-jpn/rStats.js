// Kernel density estimates and the normal-reference bandwidths: R's density (stats), bw.nrd0 and bw.nrd.
//
// Written for rStats.js to reproduce R's documented behaviour and output (experiments/plot121-log.md, experiments 1
// and 2). As ?density describes, the mass of the data is spread linearly over a regular grid, convolved with the
// kernel by the fast Fourier transform and interpolated linearly at the output points. The grid found by the
// experiments: [from - 4 bw, to + 4 bw] with 2m cells, m = max(n, 512) rounded up to a power of 2 above 512, the
// density on its first m points. The kernels are scaled so that bw is their standard deviation (?density).
