/**
 * The kernels of {@link density}.
 *
 * @category Descriptive statistics
 */
export type DensityKernel = "gaussian" | "epanechnikov" | "rectangular" | "triangular" | "biweight" | "cosine" | "optcosine";

const KERNELS: readonly DensityKernel[] = ["gaussian", "epanechnikov", "rectangular", "triangular", "biweight", "cosine", "optcosine"];

/**
 * Options for {@link density}.
 *
 * @category Descriptive statistics
 */
export interface KernelDensityOptions {
  /**
   * The bandwidth (the kernel's standard deviation): a positive number, or the rule `"nrd0"` (default, {@link bwNrd0})
   * or `"nrd"` ({@link bwNrd}), in any case (as R). R's `"ucv"`, `"bcv"` and `"SJ"` are not offered (an error).
   */
  bw?: number | string;
  /** The bandwidth is `adjust * bw`. Default `1`. */
  adjust?: number;
  /** The kernel; a unique prefix is accepted (as R). Default `"gaussian"`. */
  kernel?: DensityKernel | string;
  /**
   * Weights of the observations, non-negative and finite, one per value of `x` (before missing values are removed).
   * Default: 1 / n each. As in R, weights that do not sum to 1 are used as given (with a warning), and the automatic
   * bandwidth ignores the weights (with a warning, unless they are all equal). With `naRm`, the weights of the missing
   * values are dropped and, when the weights summed to 1, the others are rescaled to sum 1 (as R).
   */
  weights?: Sample;
  /** The number of equally spaced output points. Default `512`. */
  n?: number;
  /** The first output point. Default: the smallest value minus `cut * bw`. */
  from?: number;
  /** The last output point. Default: the largest value plus `cut * bw`. */
  to?: number;
  /** How many bandwidths beyond the data the default `from` and `to` reach. Default `3`. */
  cut?: number;
  /** Remove missing values (NaN) first. Default `false`: a missing value is an error (as R). */
  naRm?: boolean;
}

/**
 * The result of {@link density}.
 *
 * @category Descriptive statistics
 */
export interface KernelDensityResult {
  /** The output points, equally spaced from `from` to `to`. */
  x: number[];
  /** The estimated density at `x`. */
  y: number[];
  /** The bandwidth used (after `adjust`). */
  bw: number;
  /** The number of observations (after missing values are removed; infinite values count, as in R). */
  n: number;
  /** The kernel used. */
  kernel: DensityKernel;
  /** R's warnings, each once, in R's order (an empty array when there are none). */
  warnings: string[];
}

/** The finite values and the normal-reference scale min(sd, IQR / 1.34) shared by bw.nrd0 and bw.nrd */
function finiteValues(x: Sample, fn: string): number[] {
  const v = Array.from(x);
  if (v.length < 2) throw new RangeError("need at least 2 data points");
  if (v.some(Number.isNaN)) throw new RangeError("missing values and NaN's not allowed if 'na.rm' is FALSE");
  // R's bw.nrd0 with an infinite value stops with "missing value where TRUE/FALSE needed" (its spread is NaN); the
  // same condition here, with a message that says what is wrong
  if (v.some((t) => !Number.isFinite(t))) throw new RangeError(`${fn}: infinite values are not allowed`);
  return v;
}

/**
 * Silverman's rule-of-thumb bandwidth for a Gaussian kernel: 0.9 times the smaller of the standard deviation and the
 * interquartile range divided by 1.34, times n^(-1/5). Equivalent to R's `bw.nrd0()`. When that spread is 0, the
 * standard deviation is used, then |x[0]|, then 1 (so that the bandwidth is positive, as R).
 *
 * @example
 * ```ts
 * bwNrd0([1, 2, 3, 4, 10]); // 0.9735846228506357 (0.9 times IQR / 1.34, smaller than the sd, times 5^(-1/5))
 * ```
 *
 * @throws RangeError for fewer than 2 values, a missing value or an infinite value.
 * @category Descriptive statistics
 */
export function bwNrd0(x: Sample): number {
  const v = finiteValues(x, "bwNrd0");
  const s = sd(v);
  let lo = Math.min(s, IQR(v) / 1.34);
  // the fall-backs found in experiment 1 (log 5): R's help page only promises a positive result
  if (!(lo > 0)) lo = s > 0 ? s : Math.abs(v[0]!) || 1;
  return 0.9 * lo * v.length ** -0.2;
}

/**
 * Scott's variation of the normal-reference bandwidth: 1.06 times the smaller of the standard deviation and the
 * interquartile range divided by 1.34, times n^(-1/5). Equivalent to R's `bw.nrd()`. It is 0 for data whose quartiles
 * coincide and whose standard deviation is 0 (as R).
 *
 * @example
 * ```ts
 * bwNrd([1, 2, 3, 4, 10]); // 1.1466663335796377
 * ```
 *
 * @throws RangeError for fewer than 2 values, a missing value or an infinite value.
 * @category Descriptive statistics
 */
export function bwNrd(x: Sample): number {
  const v = finiteValues(x, "bwNrd");
  // as R: no fall-back, so constant data give 0 (and density then reports that the bandwidth is not positive)
  return 1.06 * Math.min(sd(v), IQR(v) / 1.34) * v.length ** -0.2;
}

/**
 * Whether weights sum to 1 for density's checks: to a relative 1.5e-8 (all.equal's tolerance; a candidate, the
 * experiments only had sums far from 1)
 */
function sumsToOne(total: number): boolean {
  return Math.abs(total - 1) <= 1.5e-8;
}

/** The kernel with standard deviation bw, as a function of the distance */
function kernelFunction(kernel: DensityKernel, bw: number): (t: number) => number {
  switch (kernel) {
    case "gaussian": {
      const c = 1 / (bw * Math.sqrt(2 * Math.PI));
      return (t) => c * Math.exp(-0.5 * (t / bw) ** 2);
    }
    case "rectangular": {
      const a = bw * Math.sqrt(3);
      return (t) => (Math.abs(t) < a ? 0.5 / a : 0);
    }
    case "triangular": {
      const a = bw * Math.sqrt(6);
      return (t) => (Math.abs(t) < a ? (1 - Math.abs(t) / a) / a : 0);
    }
    case "epanechnikov": {
      const a = bw * Math.sqrt(5);
      return (t) => (Math.abs(t) < a ? (0.75 * (1 - (t / a) ** 2)) / a : 0);
    }
    case "biweight": {
      const a = bw * Math.sqrt(7);
      return (t) => (Math.abs(t) < a ? ((15 / 16) * (1 - (t / a) ** 2) ** 2) / a : 0);
    }
    case "cosine": {
      const a = bw / Math.sqrt(1 / 3 - 2 / Math.PI ** 2);
      return (t) => (Math.abs(t) < a ? (1 + Math.cos((Math.PI * t) / a)) / (2 * a) : 0);
    }
    case "optcosine": {
      const a = bw / Math.sqrt(1 - 8 / Math.PI ** 2);
      return (t) => (Math.abs(t) < a ? ((Math.PI / 4) * Math.cos((Math.PI * t) / (2 * a))) / a : 0);
    }
  }
}

/** R's match.arg for the kernel: the full name or a unique prefix */
function matchKernel(k: unknown): DensityKernel {
  if (k === undefined) return "gaussian";
  if (typeof k === "string" && k.length > 0) {
    const hit = KERNELS.filter((v) => v.startsWith(k));
    if (hit.length === 1 || KERNELS.includes(k as DensityKernel)) return (KERNELS.includes(k as DensityKernel) ? k : hit[0]) as DensityKernel;
  }
  throw new RangeError(`'arg' should be one of ${KERNELS.map((v) => `"${v}"`).join(", ")}`);
}

/**
 * Kernel density estimate at equally spaced points. Equivalent to R's `density()`. The same
 * binned approximation (linear binning on a grid, convolution by FFT, linear interpolation), so the values are R's to
 * rounding, not the exact kernel sums (those differ by up to about 1e-3 of the peak, more for the rectangular kernel).
 *
 * @example
 * ```ts
 * const d = density([1.2, 2.3, 2.9, 3.1, 4.8]);
 * d.x.length; // 512
 * d.bw;       // bwNrd0 of the data
 * ```
 *
 * @throws RangeError for a missing value without `naRm`, fewer than 2 values with an automatic bandwidth, a bandwidth
 *   that is not positive, invalid weights or an unknown kernel.
 * @category Descriptive statistics
 */
export function density(x: Sample, options: KernelDensityOptions = {}): KernelDensityResult {
  checkOptions(options, DENSITY_KEYS, "density"); // generated: option-keys.mjs
  const warnings: string[] = [];
  const kernel = matchKernel(options.kernel);
  const all = Array.from(x);
  let w0 = options.weights === undefined ? undefined : Array.from(options.weights);
  if (w0 !== undefined) {
    if (w0.length !== all.length) throw new RangeError("'x' and 'weights' have unequal length");
    if (!w0.every(Number.isFinite)) throw new RangeError("'weights' must all be finite");
    if (w0.some((v) => v < 0)) throw new RangeError("'weights' must not be negative");
  }
  const naRm = options.naRm ?? false;
  const hasNa = all.some(Number.isNaN);
  if (hasNa && !naRm) throw new RangeError("'x' contains missing values");
  const keep = all.map((v) => !Number.isNaN(v));
  const xs = all.filter((_, i) => keep[i]);
  // with missing values removed, R rescales the remaining weights to sum 1 when the weights given summed to 1, and
  // uses them as they are otherwise (experiment 3)
  if (w0 !== undefined && hasNa) {
    const before = w0.reduce((s, v) => s + v, 0);
    const kept = w0.filter((_, i) => keep[i]);
    const after = kept.reduce((s, v) => s + v, 0);
    w0 = sumsToOne(before) ? kept.map((v) => v / after) : kept;
  }
  const n = xs.length;
  // infinite values count in n (each takes its weight 1 / n) but are not binned: their mass is lost, as in R
  const finite = xs.filter(Number.isFinite);
  let weights: number[];
  if (w0 === undefined) weights = xs.map(() => 1 / n);
  else {
    weights = w0;
    if (!sumsToOne(weights.reduce((s, v) => s + v, 0))) warnings.push("sum(weights) != 1  -- will not get true density");
  }
  let bw: number;
  const bwGiven = options.bw ?? "nrd0";
  if (typeof bwGiven === "string") {
    if (finite.length < 2) throw new RangeError("need at least 2 points to select a bandwidth automatically");
    const rule = bwGiven.toLowerCase();
    if (rule === "nrd0") bw = bwNrd0(finite);
    else if (rule === "nrd") bw = bwNrd(finite);
    else if (["ucv", "bcv", "sj", "sj-ste", "sj-dpi"].includes(rule)) {
      throw new RangeError(`density: the bandwidth rule '${bwGiven}' is not offered by rStats.js; give "nrd0", "nrd" or a number`);
    } else throw new RangeError("unknown bandwidth rule");
    if (w0 !== undefined && !w0.every((v) => v === w0![0])) warnings.push("Selecting bandwidth *not* using 'weights'");
  } else bw = bwGiven;
  if (!Number.isFinite(bw)) throw new RangeError("non-finite 'bw'");
  const adjust = options.adjust ?? 1;
  bw *= adjust;
  if (!(bw > 0)) throw new RangeError("'bw' is not positive.");
  const cut = options.cut ?? 3;
  const lo0 = finite.length > 0 ? Math.min(...finite) : Infinity;
  const hi0 = finite.length > 0 ? Math.max(...finite) : -Infinity;
  const from = options.from ?? lo0 - cut * bw;
  const to = options.to ?? hi0 + cut * bw;
  if (!Number.isFinite(from)) throw new RangeError("non-finite 'from'");
  if (!Number.isFinite(to)) throw new RangeError("non-finite 'to'");
  const nOut = options.n ?? 512;
  if (!Number.isFinite(nOut) || nOut < 1) throw new RangeError("'n' must be a positive number");
  let m = Math.max(Math.ceil(nOut), 512);
  if (m > 512) m = 2 ** Math.ceil(Math.log2(m));
  const lo = from - 4 * bw, up = to + 4 * bw;
  const M = 2 * m;
  const xdelta = (up - lo) / (m - 1);
  // linear binning of the weights on the grid lo + j xdelta, j = 0 .. 2m - 1
  const mass = new Array<number>(M).fill(0);
  xs.forEach((v, i) => {
    if (!Number.isFinite(v)) return;
    const p = (v - lo) / xdelta;
    const ix = Math.floor(p), fx = p - ix;
    const wi = weights[i]!;
    if (ix >= 0 && ix <= M - 2) {
      mass[ix] = mass[ix]! + wi * (1 - fx);
      mass[ix + 1] = mass[ix + 1]! + wi * fx;
    } else if (ix === -1) mass[0] = mass[0]! + wi * fx;
    else if (ix === M - 1) mass[ix] = mass[ix]! + wi * (1 - fx);
  });
  // circular convolution with the kernel at the lags 0, 1, ..., m, -(m - 1), ..., -1
  const K = kernelFunction(kernel, bw);
  const kr = Array.from({ length: M }, (_, j) => K((j <= m ? j : j - M) * xdelta));
  const ki = new Array<number>(M).fill(0);
  const yr = mass.slice(), yi = new Array<number>(M).fill(0);
  fftInPlace(yr, yi, false);
  fftInPlace(kr, ki, false);
  const pr = yr.map((a, j) => a * kr[j]! + yi[j]! * ki[j]!);
  const pi = yr.map((a, j) => yi[j]! * kr[j]! - a * ki[j]!);
  fftInPlace(pr, pi, true);
  // negative values from round-off are set to 0
  const dens = pr.slice(0, m).map((v) => Math.max(0, v / M));
  const grid = Array.from({ length: m }, (_, j) => lo + j * xdelta);
  const xout = seqLength(from, to, nOut);
  // R interpolates with approx, which merges equal grid points (a grid finer than the precision of the values, as
  // for data near 1e15, warns "collapsing to unique 'x' values" in R; the same merge here, by their mean)
  const distinct = grid.every((g, j) => j === 0 || g > grid[j - 1]!);
  if (!distinct) warnings.push("collapsing to unique 'x' values");
  const y = approx(grid, dens, { xout }).y;
  return reported("density", { x: xout, y, bw, n, kernel, warnings });
}
