const STLM_KEYS = ["frequency", "method", "etsModel", "sWindow", "robust", "lambda", "biasadj"] as const;
const FORECAST_STLM_KEYS = ["h", "level"] as const;
const FORECAST_KEYS = ["h", "level", "frequency"] as const;
// Generated by `node scripts/option-keys.mjs --write` (end)

/** Result of {@link stlm}. */
export interface StlmResult {
  kind: "stlm";
  /** The decomposition of the (Box-Cox transformed) series. */
  stl: MstlResult;
  /** The model of the seasonally adjusted series. */
  model: EtsResult | ForecastArimaResult;
  /** The seasonally adjusted series (transformed scale). */
  adjusted: number[];
  /** The in-sample fit on the original scale. */
  fitted: number[];
  residuals: number[];
  frequency: number;
  lambda: number | null;
  biasadj: boolean;
}

/** A forecast of {@link forecast}. */
export interface ForecastOutput { mean: number[]; lower: number[][]; upper: number[][]; level: number[]; method: string }

/**
 * STL decomposition with a model of the seasonally adjusted series (forecast's `stlm()`): mstl of the series (Box-Cox
 * transformed with `lambda`), then `ets(adjusted, etsModel)` (default "ZZN") or, with `method: "arima"`,
 * `auto.arima(adjusted, seasonal = FALSE)` (log 93: R's model has no seasonal part).
 *
 * @category Time series
 */
export function stlm(y: readonly number[], options: { frequency: number; method?: "ets" | "arima"; etsModel?: string; sWindow?: number | "periodic"; robust?: boolean; lambda?: number; biasadj?: boolean }): StlmResult {
  checkOptions(options, STLM_KEYS, "stlm"); // generated: option-keys.mjs
  const m = options.frequency; const lambda = options.lambda ?? null; const biasadj = options.biasadj ?? false;
  const x = lambda === null ? y.map(Number) : boxCox(y, lambda);
  const dec = mstl(x, { frequency: m, ...(options.sWindow !== undefined ? { sWindow: options.sWindow } : {}), ...(options.robust !== undefined ? { robust: options.robust } : {}) });
  const seas = dec.seasonal ?? new Array<number>(x.length).fill(0);
  const adjusted = x.map((v, i) => v - seas[i]!);
  const model: EtsResult | ForecastArimaResult = options.method === "arima"
    ? autoArima(adjusted, { frequency: m, seasonal: false })
    : ets(adjusted, { model: options.etsModel ?? "ZZN" });
  const fitAdj = model.fitted;
  const fittedT = fitAdj.map((v, i) => v + seas[i]!);
  const fitted = lambda === null ? fittedT : invBoxCox(fittedT, lambda);
  return { kind: "stlm", stl: dec, model, adjusted, fitted, residuals: y.map((v, i) => v - fitted[i]!), frequency: m, lambda, biasadj };
}

/**
 * Forecasts from an {@link stlm} fit (forecast's `forecast.stlm()`): the model's forecasts of the seasonally adjusted
 * series plus the last cycle of the seasonal component, back-transformed with the fit's lambda.
 *
 * @category Time series
 */
export function forecastStlm(fit: StlmResult, options: { h?: number; level?: readonly number[] } = {}): ForecastOutput {
  checkOptions(options, FORECAST_STLM_KEYS, "forecastStlm"); // generated: option-keys.mjs
  const m = fit.frequency; const h = options.h ?? 2 * m; const level = [...(options.level ?? [80, 95])];
  const fc = "spec" in fit.model ? forecastEts(fit.model, { h, level }) : forecastFromArima(fit.model, { h, level });
  const seas = fit.stl.seasonal ?? new Array<number>(fit.adjusted.length).fill(0);
  const last = seas.slice(seas.length - m); const add = (i: number): number => last[i % m] ?? 0;
  let mean = fc.mean.map((v, i) => v + add(i));
  let lower = fc.lower.map((r, i) => r.map((v) => v + add(i)));
  let upper = fc.upper.map((r, i) => r.map((v) => v + add(i)));
  if (fit.lambda !== null) {
    const lam = fit.lambda;
    mean = invBoxCox(mean, lam); lower = lower.map((r) => invBoxCox(r, lam)); upper = upper.map((r) => invBoxCox(r, lam));
  }
  return { mean, lower, upper, level, method: `STL +  ${fc.method}` };
}

const isEts = (o: object): o is EtsResult => "spec" in o && "par" in o;
const isForecastArima = (o: object): o is ForecastArimaResult => "arma" in o && "sigma2Mle" in o;
const isArima = (o: object): o is ArimaResult => "arma" in o && "mask" in o;
const isHoltWinters = (o: object): o is HoltWintersResult => "SSE" in o && "coefficientNames" in o;
const isAr = (o: object): o is ArResult => "varPred" in o && "order" in o;
const isStlm = (o: object): o is StlmResult => (o as { kind?: string }).kind === "stlm";

/**
 * Forecasts from a series or a fitted model (forecast's `forecast()`):
 * - a series (`frequency` in the options): ets, or stlf when the period is 13 or more and the series is longer than
 *   two periods (forecast's help; log 93);
 * - an {@link ets} fit, a {@link forecastArima} / {@link autoArima} fit, a stats {@link arima} fit (with its MLE
 *   innovations variance), an {@link stlm} fit, a {@link holtWinters} fit (stats' prediction intervals) or an
 *   {@link ar} fit (normal intervals from the prediction standard errors).
 * `h` defaults to twice the period for seasonal data, else 10.
 *
 * @category Time series
 */
export function forecast(
  object: readonly number[] | EtsResult | ForecastArimaResult | ArimaResult | StlmResult | HoltWintersResult | ArResult,
  options: { h?: number; level?: readonly number[]; frequency?: number } = {},
): ForecastOutput {
  checkOptions(options, FORECAST_KEYS, "forecast"); // generated: option-keys.mjs
  const level = [...(options.level ?? [80, 95])];
  const hFor = (m: number): number => options.h ?? (m > 1 ? 2 * m : 10);
  if (Array.isArray(object)) {
    const y = (object as readonly number[]).map(Number); const m = options.frequency ?? 1;
    if (m > 12 && y.length > 2 * m) return forecastStlm(stlm(y, { frequency: m }), { h: hFor(m), level });
    const f = ets(y, { frequency: m }); const fc = forecastEts(f, { h: hFor(m), level });
    return { mean: fc.mean, lower: fc.lower, upper: fc.upper, level, method: fc.method };
  }
  const o = object as object;
  if (isStlm(o)) return forecastStlm(o, { h: hFor(o.frequency), level });
  if (isEts(o)) { const fc = forecastEts(o, { h: hFor(o.spec.m), level }); return { mean: fc.mean, lower: fc.lower, upper: fc.upper, level, method: fc.method }; }
  if (isForecastArima(o)) { const fc = forecastFromArima(o, { h: hFor(o.arma[4]), level }); return { mean: fc.mean, lower: fc.lower, upper: fc.upper, level, method: fc.method }; }
  if (isArima(o)) {
    // a stats arima: no transformation or drift, its MLE variance
    const fa: ForecastArimaResult = { ...o, sigma2Mle: o.sigma2, aicc: NaN, bic: NaN, lambda: null, biasadj: false, fitted: o.x.map((v, i) => v - o.residuals[i]!), series: o.x.slice(), drift: false };
    const fc = forecastFromArima(fa, { h: hFor(o.arma[4]), level });
    return { mean: fc.mean, lower: fc.lower, upper: fc.upper, level, method: fc.method };
  }
  if (isHoltWinters(o)) {
    const h = hFor(o.frequency); const mean = predictHoltWinters(o, { nAhead: h }).fit;
    const bands = level.map((l) => predictHoltWinters(o, { nAhead: h, predictionInterval: true, level: l / 100 }));
    return { mean, lower: mean.map((_, i) => bands.map((b) => b.lwr![i]!)), upper: mean.map((_, i) => bands.map((b) => b.upr![i]!)), level, method: "HoltWinters" };
  }
  if (isAr(o)) {
    const h = hFor(1); const p = predictAr(o, h); const q = level.map((l) => qnorm(0.5 + l / 200));
    return { mean: p.pred, lower: p.pred.map((v, i) => q.map((z) => v - z * p.se[i]!)), upper: p.pred.map((v, i) => q.map((z) => v + z * p.se[i]!)), level, method: `AR(${o.order})` };
  }
  throw new TypeError("forecast: unsupported object");
}
