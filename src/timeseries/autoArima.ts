interface Spec { p: number; d: number; q: number; P: number; D: number; Q: number; constant: boolean }

/**
 * Chooses and fits an ARIMA model by forecast's `auto.arima()` rules: d by {@link ndiffs} (after the seasonal
 * differences), D by {@link nsdiffs}, then the stepwise search on the AICc (or all models up to maxOrder with
 * `stepwise: false`).
 * Equivalent to `forecast::auto.arima()` in R.
 *
 * With approximation, models are ranked by the CSS fits' AICc; R's printed trace adds a constant per series whose origin
 * is not known (it does not change the choice), so the trace values here are the CSS AICc themselves.
 *
 * @category Time series
 */
export function autoArima(y: readonly number[], options: AutoArimaOptions = {}): AutoArimaResult {
  checkOptions(options, AUTO_ARIMA_KEYS, "autoArima"); // generated: option-keys.mjs
  const m = options.frequency ?? 1; const seasonalOn = (options.seasonal ?? true) && m > 1;
  const x = y.map(Number); const n = x.filter(Number.isFinite).length;
  const maxP = options.maxP ?? 5, maxQ = options.maxQ ?? 5;
  const maxSP = seasonalOn ? options.maxSeasonalP ?? 2 : 0, maxSQ = seasonalOn ? options.maxSeasonalQ ?? 2 : 0;
  const maxOrder = options.maxOrder ?? 5; const ic = options.ic ?? "aicc";
  const nmodels = options.nmodels ?? 94; const stationary = options.stationary ?? false;
  const approximation = options.approximation ?? (n > 150 || m > 12);
  const allowdrift = options.allowdrift ?? true, allowmean = options.allowmean ?? true;
  const lambda = options.lambda === undefined ? null : options.lambda;
  const z0 = x;
  // differencing orders
  let D = options.D ?? (stationary || !seasonalOn ? 0 : nsdiffs(z0, { frequency: m, test: options.seasonalTest ?? "seas", maxD: options.maxSeasonalD ?? 1 }));
  if (!seasonalOn) D = 0;
  let dx = z0.filter(Number.isFinite);
  for (let k = 0; k < D; k++) dx = dx.slice(m).map((v, i) => v - dx[i]!);
  const d = options.d ?? (stationary ? 0 : ndiffs(dx, { test: options.test ?? "kpss", alpha: options.alpha ?? 0.05, maxD: options.maxD ?? 2 }));
  const constantAllowed = d + D <= 1 && (d + D === 0 ? allowmean : allowdrift);

  const fitted = new Map<string, { ic: number; fit?: ForecastArimaResult }>();
  const trace: AutoArimaTraceEntry[] = [];
  const key = (s: Spec): string => `${s.p},${s.d},${s.q},${s.P},${s.D},${s.Q},${s.constant}`;
  const evaluate = (s: Spec, approx: boolean): { ic: number; fit?: ForecastArimaResult } => {
    let fit: ForecastArimaResult;
    try {
      fit = forecastArima(z0, {
        order: [s.p, s.d, s.q], seasonal: [s.P, s.D, s.Q], frequency: m, includeConstant: s.constant,
        ...(lambda !== null ? { lambda } : {}), biasadj: options.biasadj ?? false, method: approx ? "CSS" : "CSS-ML",
        ...(options.xreg ? { xreg: options.xreg, ...(options.xregNames ? { xregNames: options.xregNames } : {}) } : {}),
      });
    } catch { return { ic: Infinity }; }
    // the AR and MA polynomials with the seasonal parts multiplied out: a root of modulus < 1.01 rejects the model
    const phi = fit.model.phi, theta = fit.model.theta;
    if (phi.length && minRootModulus(phi.map((v) => -v)) < 1.01) return { ic: Infinity, fit };
    if (theta.length && minRootModulus(theta) < 1.01) return { ic: Infinity, fit };
    let val: number;
    if (approx) {
      const npar = fit.mask.filter(Boolean).length + 1; const nobs = fit.nobs;
      const aic = -2 * fit.loglik + 2 * npar;
      val = ic === "aic" ? aic : ic === "bic" ? aic + npar * (Math.log(nobs) - 2) : aic + (2 * npar * (npar + 1)) / (nobs - npar - 1);
    } else val = ic === "aic" ? fit.aic : ic === "bic" ? fit.bic : fit.aicc;
    return { ic: Number.isFinite(val) ? val : Infinity, fit };
  };
  const tryModel = (s: Spec): number => {
    const k = key(s); const prev = fitted.get(k); if (prev) return prev.ic;
    const r = evaluate(s, approximation); fitted.set(k, r);
    trace.push({ order: [s.p, s.d, s.q], seasonal: [s.P, s.D, s.Q], constant: s.constant, ic: r.ic });
    return r.ic;
  };
  const inBounds = (s: Spec): boolean => s.p >= 0 && s.q >= 0 && s.P >= 0 && s.Q >= 0 && s.p <= maxP && s.q <= maxQ && s.P <= maxSP && s.Q <= maxSQ;

  let best: Spec | null = null; let bestIc = Infinity;
  const stepwise = options.stepwise ?? true;
  const consider = (s: Spec): boolean => {
    // nmodels limits the stepwise search only (the fixture's full USAccDeaths search fits 96 models)
    if (!inBounds(s) || fitted.has(key(s)) || (stepwise && fitted.size >= nmodels)) return false;
    const v = tryModel(s);
    if (v < bestIc) { bestIc = v; best = s; return true; }
    return false;
  };
  if (stepwise) {
    const c = constantAllowed;
    const sp = (p: number, q: number, P: number, Q: number, constant: boolean): Spec => ({ p, d, q, P: seasonalOn ? P : 0, D, Q: seasonalOn ? Q : 0, constant });
    const p0 = Math.min(options.startP ?? 2, maxP), q0 = Math.min(options.startQ ?? 2, maxQ);
    const P0 = Math.min(options.startSeasonalP ?? 1, maxSP), Q0 = Math.min(options.startSeasonalQ ?? 1, maxSQ);
    for (const s of [sp(p0, q0, P0, Q0, c), sp(0, 0, 0, 0, c), sp(1, 0, 1, 0, c), sp(0, 1, 0, 1, c)]) consider(s);
    // when this model becomes the best, the search goes on from it, without the constant. R continues from its orders
    // with the constant flag of the earlier best (16 of 16 traces, log 81) and so skips neighbours; not imitated
    // (Departures from R)
    if (c) consider(sp(0, 0, 0, 0, false));
    let improved = true;
    while (improved && fitted.size < nmodels) {
      improved = false;
      const b: Spec = best ?? sp(0, 0, 0, 0, c);
      const nb = (dp: number, dq: number, dP: number, dQ: number): Spec => ({ ...b, p: b.p + dp, q: b.q + dq, P: b.P + dP, Q: b.Q + dQ });
      const cands: Spec[] = [];
      // the diagonal neighbours in the order (-1, -1), (-1, +1), (+1, -1), (+1, +1) (the fixture's WWWusage, Nile and lynx
      // traces; log 43 had the middle two the other way round)
      if (seasonalOn) cands.push(nb(0, 0, -1, 0), nb(0, 0, 0, -1), nb(0, 0, 1, 0), nb(0, 0, 0, 1), nb(0, 0, -1, -1), nb(0, 0, -1, 1), nb(0, 0, 1, -1), nb(0, 0, 1, 1));
      cands.push(nb(-1, 0, 0, 0), nb(0, -1, 0, 0), nb(1, 0, 0, 0), nb(0, 1, 0, 0), nb(-1, -1, 0, 0), nb(-1, 1, 0, 0), nb(1, -1, 0, 0), nb(1, 1, 0, 0));
      if (constantAllowed) cands.push({ ...b, constant: !b.constant });
      for (const s of cands) if (consider(s)) { improved = true; break; }
    }
  } else {
    const consts = constantAllowed ? [false, true] : [false];
    for (let p = 0; p <= maxP; p++) for (let q = 0; q <= maxQ; q++) for (let P = 0; P <= maxSP; P++) for (let Q = 0; Q <= maxSQ; Q++) {
      if (p + q + P + Q > maxOrder) continue;
      for (const constant of consts) consider({ p, d, q, P, D, Q, constant });
    }
  }
  if (!best) throw new Error("auto.arima: no suitable ARIMA model found");
  let chosen: ForecastArimaResult | undefined;
  if (approximation) {
    // refit the best without approximation; when it is rejected, the next best
    const ranked = [...fitted.entries()].filter(([, v]) => Number.isFinite(v.ic)).sort((a, b) => a[1].ic - b[1].ic);
    for (const [k] of ranked) {
      const [p, dd, q, P, DD, Q, cs] = k.split(","); const s: Spec = { p: +p!, d: +dd!, q: +q!, P: +P!, D: +DD!, Q: +Q!, constant: cs === "true" };
      const r = evaluate(s, false);
      if (Number.isFinite(r.ic) && r.fit) { chosen = r.fit; break; }
    }
    if (!chosen) throw new Error("auto.arima: no suitable ARIMA model found");
  } else chosen = fitted.get(key(best))!.fit!;
  return { ...chosen, trace };
}
