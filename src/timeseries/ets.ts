const LOWER = { alpha: 1e-4, beta: 1e-4, gamma: 1e-4, phi: 0.8 };
const UPPER = { alpha: 0.9999, beta: 0.9999, gamma: 0.9999, phi: 0.98 };

/** The admissible region (Hyndman et al. 2008, ch. 10): the discount matrix F - g w' of the linear model is stable. */
export function admissible(spec: EtsSpec, al: number, be: number, ga: number, ph: number): boolean {
  const { trend, season, m } = spec;
  if (trend === "M") return true; // not linear; only the usual bounds
  // the roots of the characteristic polynomial of D = F - g w' (state x = (l, b, s1..sm), y = w'x + e, x' = F x + g e),
  // by the matrix determinant lemma det(zI - D) = det(zI - F) (1 + w' (zI - F)^-1 g):
  //   p(z) = (z - 1)(z - phi)(z^m - 1) + (z^m - 1)(alpha (z - phi) + phi beta) + phi beta (z - 1)(z^m - 1) + gamma (z - 1)(z - phi)
  // (without a trend the factors z - phi and the beta terms dropped, without a season z^m - 1 and gamma). With a season
  // p(1) = 0 (the level and the seasonal sum are not separately identified; the normalised model of ch. 10 does not
  // have that root): divided out. All other roots of modulus below 1 - 1e-10, by the Schur-Cohn recursion
  // (normalised at each step). The same decisions as the eigenvalues of D on 160000 random parameter sets, at a small
  // fraction of the cost (log 108)
  const hasB = trend !== "N"; const ms = season === "N" ? 0 : m;
  const mul = (a: readonly number[], b: readonly number[]): number[] => {
    const r = new Array<number>(a.length + b.length - 1).fill(0);
    for (let i = 0; i < a.length; i++) for (let j = 0; j < b.length; j++) r[i + j]! += a[i]! * b[j]!;
    return r;
  };
  const addTo = (r: number[], a: readonly number[], c: number): void => { for (let i = 0; i < a.length; i++) r[i]! += c * a[i]!; };
  const zm1 = [-1, 1]; const T = hasB ? [-ph, 1] : [1]; const zM = ms ? [-1, ...new Array<number>(ms - 1).fill(0), 1] : [1];
  const p = mul(mul(zm1, T), zM);
  addTo(p, mul(zM, hasB ? [al * -ph + ph * be, al] : [al]), 1);
  if (hasB) addTo(p, mul(zm1, zM), ph * be);
  if (ms) addTo(p, mul(zm1, T), ga);
  let a = p;
  if (ms) { const d = p.length - 1; const q = new Array<number>(d).fill(0); let r = p[d]!; for (let k = d - 1; k >= 0; k--) { q[k] = r; r = p[k]! + r; } a = q; }
  const rad = 1 - 1e-10; a = a.map((v, k) => v * rad ** k);
  while (a.length > 1) {
    const d = a.length - 1; const lead = a[d]!, c0 = a[0]!;
    if (!(Math.abs(c0) < Math.abs(lead))) return false;
    const nb = new Array<number>(d);
    for (let k = 0; k < d; k++) nb[k] = lead * a[k + 1]! - c0 * a[d - k - 1]!;
    const top = nb[d - 1]!; a = nb.map((v) => v / top);
  }
  return true;
}

interface FitOut { spec: EtsSpec; par: EtsParameters; filter: FilterOut; nParams: number }

/** Missing values replaced by linear interpolation (constant beyond the ends): for the starting states only. */
function interpolated(y: readonly number[]): number[] {
  if (!y.some((v) => Number.isNaN(v))) return y as number[];
  const obs = y.map((_, i) => i).filter((i) => !Number.isNaN(y[i]!));
  return y.map((v, i) => {
    if (!Number.isNaN(v)) return v;
    let j = 0; while (j < obs.length && obs[j]! < i) j++;
    if (j === 0) return y[obs[0]!]!; if (j === obs.length) return y[obs[obs.length - 1]!]!;
    const a = obs[j - 1]!, b = obs[j]!; return y[a]! + ((y[b]! - y[a]!) * (i - a)) / (b - a);
  });
}

function initialStates(y0: readonly number[], spec: EtsSpec): { l: number; b: number; s: number[] } {
  const { trend, season, m } = spec; const y = interpolated(y0); const n = y.length;
  let s: number[] = []; let adj = y.slice();
  if (season !== "N") {
    // a classical decomposition of the first (up to four) full cycles, seasonal indices averaged
    const nc = Math.max(2, Math.min(4, Math.floor(n / m))); const z = y.slice(0, nc * m);
    const ma: number[] = new Array<number>(z.length).fill(NaN); const half = Math.floor(m / 2);
    for (let t = half; t < z.length - half; t++) {
      let v = 0; if (m % 2 === 0) { for (let k = -half; k <= half; k++) v += (Math.abs(k) === half ? 0.5 : 1) * z[t + k]!; v /= m; }
      else { for (let k = -half; k <= half; k++) v += z[t + k]!; v /= m; }
      ma[t] = v;
    }
    const idx = new Array<number>(m).fill(0), cnt = new Array<number>(m).fill(0);
    z.forEach((v, t) => { if (Number.isFinite(ma[t]!)) { idx[t % m]! += season === "A" ? v - ma[t]! : v / ma[t]!; cnt[t % m]!++; } });
    let si = idx.map((v, i) => (cnt[i] ? v / cnt[i]! : season === "A" ? 0 : 1));
    const mean = si.reduce((a, b) => a + b, 0) / m;
    si = si.map((v) => (season === "A" ? v - mean : v / mean));
    // states: s1 = the most recent before t = 1, i.e. the season of period m, ..., sm = period 1
    s = si.slice().reverse();
    adj = y.map((v, t) => (season === "A" ? v - si[t % m]! : v / si[t % m]!));
  }
  const k = Math.min(10, n); const tt = Array.from({ length: k }, (_, i) => i + 1);
  const tm = tt.reduce((a, b) => a + b, 0) / k; const ym = adj.slice(0, k).reduce((a, b) => a + b, 0) / k;
  let sxy = 0, sxx = 0; for (let i = 0; i < k; i++) { sxy += (tt[i]! - tm) * (adj[i]! - ym); sxx += (tt[i]! - tm) ** 2; }
  const slope = sxx > 0 ? sxy / sxx : 0; let l = ym - slope * tm; let b = slope;
  if (trend === "N") { l = ym; b = 0; }
  // a fast-growing start can put the line's value at t = 0 below zero (uspop): start from the first value instead
  if (trend === "A" && !(l > 0) && adj[0]! > 0) { l = adj[0]!; b = k > 1 ? (adj[k - 1]! - adj[0]!) / (k - 1) : 0; }
  if (trend === "M") { b = Math.max(0.5, Math.min(1.5, 1 + slope / Math.max(1e-8, Math.abs(l)))); if (!(l > 0)) l = Math.max(1e-8, adj[0]!); }
  return { l, b, s };
}

/**
 * Fits one model by minimising lik (= -2 loglik) within the usual bounds and the admissible region. `bounds: "simple"`
 * is forecast's initial = "simple" (its own Holt-Winters filter, log 91): alpha, beta* = beta / alpha and gamma in
 * [0, 1], no admissibility check.
 */
export function fitModel(y: readonly number[], spec: EtsSpec, fixed: Partial<Record<"alpha" | "beta" | "gamma" | "phi", number>> = {}, fixedInit?: { l: number; b?: number; s?: number[] }, optCrit: "lik" | "mse" = "lik", bounds: "usual" | "simple" = "usual", start?: Partial<Record<"alpha" | "beta" | "gamma" | "phi", number>>): FitOut | null {
  const { trend, season, m } = spec; const n = y.length;
  const names: string[] = [];
  if (fixed.alpha === undefined) names.push("alpha");
  if (trend !== "N" && fixed.beta === undefined) names.push("beta");
  if (season !== "N" && fixed.gamma === undefined) names.push("gamma");
  if (spec.damped && fixed.phi === undefined) names.push("phi");
  const nSmooth = names.length;
  const init = fixedInit ?? initialStates(y, spec);
  const nState = fixedInit ? 0 : 1 + (trend !== "N" ? 1 : 0) + (season !== "N" ? m - 1 : 0);
  const yo = y.filter((v) => !Number.isNaN(v));
  const scale = Math.max(1e-8, Math.sqrt(yo.reduce((a, v) => a + v * v, 0) / yo.length));
  const sbuf = new Float64Array(Math.max(1, m));
  const decode = (u: readonly number[]): EtsParameters => {
    let j = 0; const v: Record<string, number> = { ...fixed };
    for (const nm of names) v[nm] = u[j++]!;
    let l = init.l, b = init.b ?? (trend === "M" ? 1 : 0), s = init.s ?? [];
    if (!fixedInit) {
      l = u[j++]! * scale; if (trend !== "N") b = trend === "M" ? u[j++]! : u[j++]! * scale;
      if (season !== "N") { s = []; for (let i = 0; i < m - 1; i++) s.push(season === "A" ? u[j++]! * scale : u[j++]!); }
    }
    return { alpha: v.alpha!, ...(trend !== "N" ? { beta: v.beta! } : {}), ...(season !== "N" ? { gamma: v.gamma! } : {}),
      ...(spec.damped ? { phi: v.phi! } : {}), l, ...(trend !== "N" ? { b } : {}), ...(season !== "N" ? { s } : {}) };
  };
  const objective = (u: number[]): number => {
    const p = decode(u); const al = p.alpha, be = p.beta ?? 0, ga = p.gamma ?? 0, ph = p.phi ?? 1;
    if (bounds === "simple") {
      if (!(al >= 0 && al <= 1) || (trend !== "N" && !(be >= 0 && be <= al)) || (season !== "N" && !(ga >= 0 && ga <= 1))) return Infinity;
      if (spec.damped && !(ph >= LOWER.phi && ph <= UPPER.phi)) return Infinity;
      if (season === "M" && fullSeason(spec, p.s ?? []).some((v) => !(v > 0))) return Infinity;
      const v = optCrit === "mse" ? etsMse(y, spec, p) : etsLik(y, spec, p, sbuf);
      return Number.isFinite(v) ? v : Infinity;
    }
    if (!(al >= LOWER.alpha && al <= UPPER.alpha)) return Infinity;
    if (trend !== "N" && !(be >= LOWER.beta && be <= al)) return Infinity;
    if (season !== "N" && !(ga >= LOWER.gamma && ga <= 1 - al)) return Infinity;
    if (spec.damped && !(ph >= LOWER.phi && ph <= UPPER.phi)) return Infinity;
    if (!admissible(spec, al, be, ga, ph)) return Infinity;
    if (season === "M" && fullSeason(spec, p.s ?? []).some((v) => !(v > 0))) return Infinity;
    if (trend === "M" && !((p.b ?? 1) > 0)) return Infinity;
    // "mse": the mean squared one-step error y - mu (forecast's opt.crit = "mse", used by thetaf's ses)
    const v = optCrit === "mse" ? etsMse(y, spec, p) : etsLik(y, spec, p, sbuf);
    return Number.isFinite(v) ? v : Infinity;
  };
  const u0: number[] = [];
  for (const nm of names) u0.push(start?.[nm as "alpha"] ?? (nm === "alpha" ? 0.5 : nm === "beta" ? 0.05 : nm === "gamma" ? 0.05 : 0.95));
  if (!fixedInit) {
    const ib = init.b ?? 0, is = init.s ?? [];
    u0.push(init.l / scale); if (trend !== "N") u0.push(trend === "M" ? ib : ib / scale);
    if (season !== "N") for (let i = 0; i < m - 1; i++) u0.push(season === "A" ? is[i]! / scale : is[i]!);
  }
  if (u0.length === 0) { const p = decode([]); const f = etsFilter(y, spec, p); return { spec, par: p, filter: f, nParams: 0 }; }
  // several starting values for the smoothing parameters, Nelder-Mead restarted until it stops improving
  const starts: number[][] = [u0];
  if (nSmooth > 0) for (const a of [0.1, 0.9]) { const u = u0.slice(); u[0] = a; if (names[1] === "beta") u[1] = Math.min(u[1]!, a / 2); if (names.includes("gamma")) u[names.indexOf("gamma")] = Math.min(0.05, (1 - a) / 2); starts.push(u); }
  // Nelder-Mead from each start (2000 iterations, as R's default), then refined from each: in the usual bounds,
  // L-BFGS-B within the box of the bounds alternated with restarted Nelder-Mead until neither improves (log 105).
  // Nelder-Mead alone stopped at different points of a flat optimum whose smoothing parameters sit at a bound
  // (USAccDeaths AAA: beta and gamma at 1e-4; log-likelihoods 1e-2 apart after exact changes of scale), which the box
  // handles exactly; refining every start, not only the best, finds the same one of several local optima (MAM) after
  // such changes. The coupled limits (beta <= alpha, gamma <= 1 - alpha, admissibility, positive means) stay in the
  // objective, as a large finite value for L-BFGS-B, which needs finite values; a polish that fails is dropped.
  const lo = [...names.map((nm) => LOWER[nm as keyof typeof LOWER]), ...new Array<number>(u0.length - nSmooth).fill(-Infinity)];
  const hi = [...names.map((nm) => UPPER[nm as keyof typeof UPPER]), ...new Array<number>(u0.length - nSmooth).fill(Infinity)];
  const boxed = (u: number[]): number => { const v = objective(u); return Number.isFinite(v) ? v : 1e100; };
  const refine = (u: number[], v: number): [number[], number] => {
    for (let round = 0; round < 10; round++) {
      const before = v;
      if (bounds === "usual") {
        try {
          const r = optim(u, boxed, { method: "L-BFGS-B", lower: lo, upper: hi, control: { factr: 1, ndeps: 1e-7 } });
          if (r.value < v) { v = r.value; u = r.par; }
        } catch { /* dropped */ }
      }
      const r2 = optim(u, objective, { method: "Nelder-Mead", control: { maxit: 4000, reltol: 1e-14 } });
      if (r2.value < v) { v = r2.value; u = r2.par; }
      if (!(before - v > 1e-12 * Math.max(1, Math.abs(v)))) break;
    }
    return [u, v];
  };
  let best: number[] | null = null; let bestV = Infinity;
  for (const st of starts) {
    if (!Number.isFinite(objective(st))) continue;
    const r = optim(st, objective, { method: "Nelder-Mead", control: { maxit: 2000, reltol: 1e-10 } });
    const [u, v] = refine(r.par, r.value);
    if (v < bestV) { bestV = v; best = u; }
  }
  if (!best || !Number.isFinite(bestV)) return null;
  const par = decode(best);
  return { spec, par, filter: etsFilter(y, spec, par), nParams: nSmooth + nState };
}

