/**
 * Options of {@link ets}.
 *
 * @category Time series
 */
export interface EtsOptions {
  frequency?: number;
  /** Three letters (error, trend, season) of A, M, N and Z (chosen); default "ZZZ". */
  model?: string;
  /** true / false, or undefined to try both when the trend is chosen. */
  damped?: boolean;
  alpha?: number; beta?: number; gamma?: number; phi?: number;
  additiveOnly?: boolean;
  allowMultiplicativeTrend?: boolean;
  restrict?: boolean;
  ic?: "aicc" | "aic" | "bic";
  lambda?: number;
  biasadj?: boolean;
  nmse?: number;
  /** The estimation criterion: the likelihood (default) or the mean squared one-step error. */
  optCrit?: "lik" | "mse";
}

/**
 * Result of {@link ets}.
 *
 * @category Time series
 */
export interface EtsResult {
  spec: EtsSpec;
  /** "ETS(M,Ad,M)" etc. */
  method: string;
  par: EtsParameters;
  /** Number of estimated parameters (smoothing parameters and initial states). */
  nParams: number;
  loglik: number; aic: number; bic: number; aicc: number;
  sigma2: number; mse: number; amse: number;
  fitted: number[]; residuals: number[];
  states: number[][];
  x: number[];
  lambda: number | null;
  biasadj: boolean;
}

function methodName(spec: EtsSpec): string {
  return `ETS(${spec.error},${spec.trend}${spec.damped ? "d" : ""},${spec.season})`;
}

function finish(y: readonly number[], f: FitOut, nmse: number, lambda: number | null, biasadj: boolean, x: number[]): EtsResult {
  const n = y.length; const p = f.nParams; const lik = f.filter.lik;
  const loglik = -0.5 * lik; const aic = -2 * loglik + 2 * (p + 1);
  // the AICc is undefined (Infinity: not a candidate) without a positive denominator n - p - 2 (a model with as many
  // parameters as observations reported a large negative AICc and was chosen; log 107)
  const bic = aic + (p + 1) * (Math.log(n) - 2); const aicc = n - p - 2 > 0 ? aic + (2 * (p + 1) * (p + 2)) / (n - p - 2) : Infinity;
  const sigma2 = f.filter.sse / (n - p);
  const obs = y.filter((v) => !Number.isNaN(v)).length;
  const mse = y.reduce((a, v, t) => (Number.isNaN(v) ? a : a + (v - f.filter.mu[t]!) ** 2), 0) / obs;
  // amse: the mean over h = 1..nmse of the in-sample h-step mean squared errors along the zero-error path (log 51)
  let amse = 0;
  for (let h = 1; h <= nmse; h++) {
    let s = 0, c = 0;
    for (let t = 0; t + h <= n; t++) { if (Number.isNaN(y[t + h - 1]!)) continue; const fc = zeroErrorPath(f.spec, f.par, f.filter.states[t]!, h)[h - 1]!; s += (y[t + h - 1]! - fc) ** 2; c++; }
    amse += s / c;
  }
  amse /= nmse;
  const fittedZ = f.filter.mu;
  const fitted = lambda === null ? fittedZ.slice() : invBoxCox(fittedZ, lambda, { biasadj, fvar: sigma2 });
  return { spec: f.spec, method: methodName(f.spec), par: f.par, nParams: p, loglik, aic, bic, aicc, sigma2, mse, amse,
    fitted, residuals: f.filter.e.slice(), states: f.filter.states, x, lambda, biasadj };
}

// ---------------------------------------------------------------------------------------------------------------
// fitting on a standardised series (1.20.0, log 104): the series divided by a power of two c near its largest
// absolute value, so that the fit does not depend on the scale (the bounds, the floor of the internal scale and the
// optimiser's stopping rule are otherwise absolute, and squares leave the range at 1e+-150). Dividing by a power of
// two is exact; the result is mapped back below, and forecastEts forecasts from the standardised fit.

const ETS_SCALED = new WeakMap<EtsResult, { fit: EtsResult; c: number }>();

/** The fit of the standardised series z / c expressed on the scale of z (the states and the additive quantities). */
function unscaleFit(fs: EtsResult, c: number, lambda: number | null, biasadj: boolean, x: number[]): EtsResult {
  const { spec } = fs; const tA = spec.trend === "A", sA = spec.season === "A", eA = spec.error === "A";
  const nb = spec.trend !== "N" ? 1 : 0;
  const par: EtsParameters = { ...fs.par, l: fs.par.l * c,
    ...(fs.par.b !== undefined ? { b: tA ? fs.par.b * c : fs.par.b } : {}),
    ...(fs.par.s ? { s: sA ? fs.par.s.map((v) => v * c) : fs.par.s.slice() } : {}) };
  const states = fs.states.map((r) => r.map((v, j) => (j === 0 || (j === 1 && nb === 1 && tA) || (j > nb && sA) ? v * c : v)));
  const n = fs.fitted.length; const logc = Math.log(c);
  const sigma2 = eA ? fs.sigma2 * c * c : fs.sigma2;
  const fittedZ = fs.fitted.map((v) => v * c);
  const fitted = lambda === null ? fittedZ : invBoxCox(fittedZ, lambda, { biasadj, fvar: sigma2 });
  // lik = n log(sum e^2) (+ 2 sum log mu for multiplicative errors) moves by 2 n log c in both cases
  const r: EtsResult = { ...fs, par, loglik: fs.loglik - n * logc, aic: fs.aic + 2 * n * logc, bic: fs.bic + 2 * n * logc,
    aicc: fs.aicc + 2 * n * logc, sigma2, mse: fs.mse * c * c, amse: fs.amse * c * c, fitted,
    residuals: eA ? fs.residuals.map((v) => v * c) : fs.residuals.slice(), states, x, lambda, biasadj };
  ETS_SCALED.set(r, { fit: fs, c });
  return r;
}

/**
 * Exponential smoothing state space model (forecast's `ets()`): one model, or the smallest information criterion
 * among the allowed models for the letters given as "Z". The parameters are estimated to the optimum of the
 * likelihood within the usual bounds and the admissible region (R's optimiser can stop earlier).
 * Equivalent to `forecast::ets()` in R.
 *
 * @category Time series
 */
export function ets(y: readonly number[], options: EtsOptions = {}): EtsResult {
  checkOptions(options, ETS_KEYS, "ets"); // generated: option-keys.mjs
  // missing values: skipped by the filter (the states move on without a correction), as R's (log 108)
  const m0 = options.frequency ?? 1; const x = tsInput(y, "ets", { missing: "allow", minLength: 1 });
  const lambda = options.lambda ?? null; const z = lambda === null ? x.slice() : boxCox(x, lambda);
  const model = (options.model ?? "ZZZ").toUpperCase();
  if (!/^[AMZ][ANMZ][ANMZ]$/.test(model)) throw new RangeError(`ets: invalid model '${options.model}'`);
  const positive = z.every((v) => Number.isNaN(v) || v > 0);
  const restrict = options.restrict ?? true; const additiveOnly = options.additiveOnly ?? false;
  const errs: EtsError[] = model[0] === "Z" ? (additiveOnly || !positive ? ["A"] : ["A", "M"]) : [model[0] as EtsError];
  const trends: EtsTrend[] = model[1] === "Z" ? (options.allowMultiplicativeTrend && !additiveOnly && positive ? ["N", "A", "M"] : ["N", "A"]) : [model[1] as EtsTrend];
  const seasonal = m0 > 1 && m0 <= 24;
  const seasons: EtsSeason[] = model[2] === "Z" ? (!seasonal ? ["N"] : additiveOnly || !positive ? ["N", "A"] : ["N", "A", "M"]) : [model[2] as EtsSeason];
  const fixed: Partial<Record<"alpha" | "beta" | "gamma" | "phi", number>> = {};
  for (const k of ["alpha", "beta", "gamma", "phi"] as const) if (options[k] !== undefined) fixed[k] = options[k]!;
  const ic = options.ic ?? "aicc"; const nmse = options.nmse ?? 3; const biasadj = options.biasadj ?? false;
  const c = powerOfTwoScale(z); const zs = z.map((v) => v / c);
  // a constant series: every model fits exactly (zero errors, the likelihood unbounded), so no criterion separates
  // the parameters; the model asked for (A, N, N for the letters Z) at the starting values of the smoothing
  // parameters and the constant level, sigma2 = 0 (R fits one with some parameters; log 107)
  const zObs = zs.filter((v) => !Number.isNaN(v));
  if (zObs.every((v) => v === zObs[0])) {
    const error: EtsError = model[0] === "M" && positive ? "M" : "A";
    const trend: EtsTrend = model[1] === "Z" ? "N" : (model[1] as EtsTrend); const season: EtsSeason = model[2] === "Z" || m0 <= 1 ? "N" : (model[2] as EtsSeason);
    if ((trend === "M" || season === "M") && !positive) throw new RangeError("ets: a multiplicative component needs positive data");
    const spec: EtsSpec = { error, trend, damped: trend !== "N" && (options.damped ?? false), season, m: season === "N" ? 1 : m0 };
    const v0 = zObs[0]!; const mult = (k: EtsTrend | EtsSeason): boolean => k === "M";
    const init = { l: v0, ...(trend !== "N" ? { b: mult(trend) ? 1 : 0 } : {}), ...(season !== "N" ? { s: new Array<number>(m0 - 1).fill(mult(season) ? 1 : 0) } : {}) };
    const start = { alpha: 0.5, ...(trend !== "N" ? { beta: 0.05 } : {}), ...(season !== "N" ? { gamma: 0.05 } : {}), ...(spec.damped ? { phi: 0.95 } : {}), ...fixed };
    const f = fitModel(zs, spec, start, init);
    if (!f) throw new Error("ets: no model able to be fitted");
    return unscaleFit(finish(zs, { ...f, nParams: Object.keys(start).length - Object.keys(fixed).length + 1 + (trend !== "N" ? 1 : 0) + (season !== "N" ? m0 - 1 : 0) }, nmse, null, false, zs), c, lambda, biasadj, x);
  }
  // short series as R's (log 107-108): with n <= m the seasonal component is dropped; a model with n <= npars + 4
  // (npars = the smoothing parameters and the initial states) is not fitted by the likelihood but by the one-step
  // squared errors from simple starting values (forecast's initial = "simple": l = y_1, b = y_2 - y_1; seasonal: the
  // first two cycles), damping dropped, a seasonal model with an additive trend and the season's kind of error, a
  // non-seasonal one with additive errors; its log-likelihood and criteria are NaN (R's NA). A seasonal model needs
  // 2m values there (R's starting trend is NA below, and so are all its forecasts): an error instead. With letters Z
  // the likelihood fits are compared; only when none has a criterion, the simple fits by their mean squared error
  const n = zs.length; const zi = interpolated(zs);
  const tried = new Set<string>(); const fits: { r: EtsResult; simple: boolean }[] = []; let firstError: Error | null = null;
  let best: EtsResult | null = null; let bestIc = Infinity;
  for (const error0 of errs) for (const trend0 of trends) for (const season0 of seasons) {
    if (season0 !== "N" && !seasonal) continue;
    if ((error0 === "M" || trend0 === "M" || season0 === "M") && !positive) continue;
    if (restrict && ((error0 === "A" && (trend0 === "M" || season0 === "M")) || (error0 === "M" && trend0 === "M" && season0 === "A"))) continue;
    const dampedSet = trend0 === "N" ? [false] : options.damped === undefined ? (model[1] === "Z" ? [true, false] : [false]) : [options.damped];
    for (const damped0 of dampedSet) {
      const season = n <= m0 ? "N" : season0; const m = season === "N" ? 1 : m0;
      const nSmooth = 1 + (trend0 !== "N" ? 1 : 0) + (season !== "N" ? 1 : 0) + (damped0 ? 1 : 0)
        - (["alpha", "beta", "gamma", "phi"] as const).filter((k) => fixed[k] !== undefined && (k === "alpha" || (k === "beta" && trend0 !== "N") || (k === "gamma" && season !== "N") || (k === "phi" && damped0))).length;
      const npars = nSmooth + 1 + (trend0 !== "N" ? 1 : 0) + (season !== "N" ? m - 1 : 0);
      const simple = n <= npars + 4;
      const spec: EtsSpec = simple
        ? { error: season === "N" ? "A" : (season as EtsError), trend: season !== "N" ? "A" : trend0, damped: false, season, m }
        : { error: error0, trend: trend0, damped: damped0, season, m };
      const key = `${spec.error}${spec.trend}${spec.damped}${spec.season}${simple}`; if (tried.has(key)) continue; tried.add(key);
      let r: EtsResult;
      if (simple) {
        try {
          if (season !== "N" && n < 2 * m) throw new RangeError(`ets: ${spec.error}${spec.trend}${spec.season} on ${n} values needs at least ${2 * m} (two seasonal periods)`);
          if (spec.trend !== "N" && n < 2) throw new RangeError("ets: a trend needs at least two values");
          const mean = (a: number[]): number => a.reduce((u, v) => u + v, 0) / a.length;
          const init = season !== "N"
            ? (() => { const l = mean(zi.slice(0, m)); const b = (mean(zi.slice(m, 2 * m)) - l) / m; return { l, b, s: zi.slice(0, m).map((v) => (season === "M" ? v / l : v - l)).reverse() }; })()
            : { l: zi[0]!, ...(spec.trend === "A" ? { b: zi[1]! - zi[0]! } : spec.trend === "M" ? { b: zi[1]! / zi[0]! } : {}) };
          // R's starting values (alpha 0.2 / m, beta 0.1 alpha, gamma 0.05 (1 - alpha)): where the squared errors do not
          // depend on a parameter (n = 2) the fit stays there, as R's
          const a0 = 0.2 / m; const f = fitModel(zs, spec, fixed, init, "mse", "simple", { alpha: a0, beta: 0.1 * a0, gamma: 0.05 * (1 - a0) });
          if (!f) continue;
          const fr = finish(zs, { ...f, nParams: npars }, nmse, null, false, zs);
          // sigma2 = SSE / n for the simple fits, as R's (n = 3: 811801 / 3; log 109)
          const sse = fr.residuals.reduce((a, v) => (Number.isNaN(v) ? a : a + v * v), 0);
          r = { ...fr, loglik: NaN, aic: NaN, bic: NaN, aicc: NaN, sigma2: sse / n };
        } catch (e) { firstError ??= e as Error; continue; }
      } else {
        const f = fitModel(zs, spec, fixed, undefined, options.optCrit ?? "lik");
        if (!f) continue;
        // the criteria of the standardised fits differ from the original ones by the same constant 2 n log c
        r = finish(zs, f, nmse, null, false, zs);
      }
      fits.push({ r, simple });
      const v = ic === "aic" ? r.aic : ic === "bic" ? r.bic : r.aicc;
      if (!simple && Number.isFinite(v) && v < bestIc) { bestIc = v; best = r; }
    }
  }
  // one model asked for: its fit, also when its AICc is undefined (Infinity); otherwise the simple ANN (log 108)
  if (!best && fits.length === 1) best = fits[0]!.r;
  // among simple fits only: the smallest mean squared error, the first on ties (R's choices at n = 2..6, log 108)
  if (!best) { let mse = Infinity; for (const f of fits) if (f.simple && f.r.mse < mse) { mse = f.r.mse; best = f.r; } }
  if (!best && firstError) throw firstError;
  if (!best) throw new Error("ets: no model able to be fitted");
  return unscaleFit(best, c, lambda, biasadj, x);
}

/** Fits a given model with given smoothing parameters and initial states (no estimation): for ses/holt/hw "simple". */
export function etsFixedInitial(y: readonly number[], spec: EtsSpec, init: { l: number; b?: number; s?: number[] }, fixed: Partial<Record<"alpha" | "beta" | "gamma" | "phi", number>> = {}, optCrit: "lik" | "mse" = "lik", bounds: "usual" | "simple" = "usual"): EtsResult {
  const c = powerOfTwoScale(y); const ys = y.map((v) => v / c);
  const initS = { l: init.l / c, ...(init.b !== undefined ? { b: spec.trend === "A" ? init.b / c : init.b } : {}),
    ...(init.s ? { s: spec.season === "A" ? init.s.map((v) => v / c) : init.s.slice() } : {}) };
  const f = fitModel(ys, spec, fixed, initS, optCrit, bounds);
  if (!f) throw new Error("ets: the model could not be fitted");
  return unscaleFit(finish(ys, f, 3, null, false, ys), c, null, false, y.slice());
}

/** The fit at given parameters (no estimation; for checks against R's own estimates). */
export function etsAt(y: readonly number[], spec: EtsSpec, par: EtsParameters, nParams: number): EtsResult {
  const f: FitOut = { spec, par, filter: etsFilter(y, spec, par), nParams };
  return finish(y, f, 3, null, false, y.slice());
}

