const DIRECTIONS = ["auto", "<", ">"] as const;

/** The label of a response value, as R's as.character (null for a missing value) */
function labelOf(v: RocResponseValue | undefined): string | null {
  if (v === null || v === undefined) return null;
  if (typeof v === "number") return Number.isNaN(v) ? null : formatR(v);
  if (typeof v === "boolean") return v ? "TRUE" : "FALSE";
  if (typeof v === "string") return v;
  throw new TypeError("the response must hold numbers, strings or booleans");
}

/** The sorted levels of a response (R's factor levels): numbers numerically, strings by code point, false first */
function sortedLevels(response: readonly RocResponseValue[]): string[] {
  const present = response.filter((v) => labelOf(v) !== null) as (number | string | boolean)[];
  const kinds = new Set(present.map((v) => typeof v));
  if (kinds.size > 1) throw new TypeError("the response mixes values of different types");
  const kind = [...kinds][0];
  let sorted: string[];
  if (kind === "number") sorted = [...new Set(present as number[])].sort((a, b) => a - b).map(formatR);
  else if (kind === "boolean") sorted = [...new Set(present as boolean[])].sort((a, b) => Number(a) - Number(b)).map((b) => (b ? "TRUE" : "FALSE"));
  else sorted = [...new Set(present as string[])].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  return [...new Set(sorted)];
}

/** Sorted copy */
function sortedCopy(x: readonly number[]): Float64Array {
  return Float64Array.from(x).sort();
}

/** Counts per distinct value: the distinct values u, and the controls and cases at most u[i] */
interface Tally {
  u: number[];
  ctrlLE: number[];
  caseLE: number[];
}

function tally(controls: readonly number[], cases: readonly number[]): Tally {
  const c = sortedCopy(controls);
  const k = sortedCopy(cases);
  const u: number[] = [];
  const ctrlLE: number[] = [];
  const caseLE: number[] = [];
  let i = 0;
  let j = 0;
  while (i < c.length || j < k.length) {
    const v = j >= k.length || (i < c.length && c[i]! <= k[j]!) ? c[i]! : k[j]!;
    while (i < c.length && c[i] === v) i++;
    while (j < k.length && k[j] === v) j++;
    u.push(v);
    ctrlLE.push(i);
    caseLE.push(j);
  }
  return { u, ctrlLE, caseLE };
}

/** Twice the Mann-Whitney U of the cases against the controls in the curve's direction (an integer) */
function twiceU(t: Tally, n: number, direction: RocDirection): number {
  let u2 = 0;
  for (let i = 0; i < t.u.length; i++) {
    const below = i > 0 ? t.ctrlLE[i - 1]! : 0;
    const casesAt = t.caseLE[i]! - (i > 0 ? t.caseLE[i - 1]! : 0);
    const ctrlAt = t.ctrlLE[i]! - below;
    const beaten = direction === "<" ? below : n - t.ctrlLE[i]!;
    u2 += casesAt * (2 * beaten + ctrlAt);
  }
  return u2;
}

/** The AUC of two samples in a direction: U/(mn) from integer counts, rounded once */
export function aucOf(controls: readonly number[], cases: readonly number[], direction: RocDirection): number {
  const n = controls.length;
  const m = cases.length;
  return twiceU(tally(controls, cases), n, direction) / (2 * m * n);
}

/** Twice the Mann-Whitney U of two samples in a direction (an integer; the AUC is this over 2mn) */
export function twiceUOf(controls: readonly number[], cases: readonly number[], direction: RocDirection): number {
  return twiceU(tally(controls, cases), controls.length, direction);
}

const bitLength = (v: bigint): number => (v === 0n ? 0 : v.toString(2).length);

/**
 * The rational num/den rounded once to the nearest double (den nonzero): the quotient to at least 55 bits, with a
 * sticky bit for a remainder, converted by Number (which rounds to nearest, ties to even). A quotient in the
 * subnormal range is rounded twice
 */
export function ratioToDouble(num: bigint, den: bigint): number {
  if (den < 0n) {
    num = -num;
    den = -den;
  }
  if (num === 0n) return 0;
  const neg = num < 0n;
  const a0 = neg ? -num : num;
  const shift = 55 - (bitLength(a0) - bitLength(den));
  const a = shift >= 0 ? a0 << BigInt(shift) : a0;
  const b = shift >= 0 ? den : den << BigInt(-shift);
  let q = a / b;
  if (q * b !== a) q |= 1n;
  const v = ldexpWide(Number(q), -shift);
  return neg ? -v : v;
}

/**
 * The threshold between consecutive distinct values a < b (pROC's): the midpoint, from the halves where the sum
 * would pass 1e100; where it rounds onto a or b, b for "<" and a for ">", so that it still separates them
 */
function thresholdBetween(a: number, b: number, direction: RocDirection): number {
  let t = (a + b) / 2;
  if (!(Math.abs(t) <= 1e100)) t = a / 2 + b / 2;
  if (t === a || t === b) t = direction === "<" ? b : a;
  return t;
}

/** The curve of two samples in a direction (pROC's stored order: increasing specificity) */
function curveOf(controls: readonly number[], cases: readonly number[], direction: RocDirection) {
  const t = tally(controls, cases);
  const n = controls.length;
  const m = cases.length;
  const k = t.u.length;
  const thresholds: number[] = [];
  const sensitivities: number[] = [];
  const specificities: number[] = [];
  // point i lies between u[i - 1] and u[i]: counts of the values at most u[i - 1]
  const at = (i: number): void => {
    const thr = i === 0 ? -Infinity : i === k ? Infinity : thresholdBetween(t.u[i - 1]!, t.u[i]!, direction);
    const caseLE = i === 0 ? 0 : t.caseLE[i - 1]!;
    const ctrlLE = i === 0 ? 0 : t.ctrlLE[i - 1]!;
    thresholds.push(thr);
    sensitivities.push((direction === "<" ? m - caseLE : caseLE) / m);
    specificities.push((direction === "<" ? ctrlLE : n - ctrlLE) / n);
  };
  if (direction === "<") for (let i = 0; i <= k; i++) at(i);
  else for (let i = k; i >= 0; i--) at(i);
  return { thresholds, sensitivities, specificities, auc: twiceU(t, n, direction) / (2 * m * n) };
}

/** The direction "auto" chooses: "<" when median(controls) <= median(cases) (pROC's rule) */
function autoDirection(controls: readonly number[], cases: readonly number[]): RocDirection {
  const med = (x: readonly number[]): number => {
    const s = sortedCopy(x);
    const h = s.length >> 1;
    return s.length % 2 === 1 ? s[h]! : midpoint(s[h - 1]!, s[h]!);
  };
  return med(controls) <= med(cases) ? "<" : ">";
}

/** Builds the curve from the classes (checked, without missing values), and records its data */
export function buildRoc(
  controls: number[],
  cases: number[],
  direction: "auto" | RocDirection,
  levels: [string, string],
  data: RocData,
  warnings: string[],
): RocResult {
  if (controls.length === 0) throw new Error("No control observation.");
  if (cases.length === 0) throw new Error("No case observation.");
  // (pROC returns NaN with a warning: the order of the values is defined, but pROC refuses them)
  if (controls.some((v) => !Number.isFinite(v)) || cases.some((v) => !Number.isFinite(v))) {
    throw new RangeError("infinite values in the predictor: cannot build a valid ROC curve");
  }
  const dir = direction === "auto" ? autoDirection(controls, cases) : direction;
  const curve = curveOf(controls, cases, dir);
  const result: RocResult = { ...curve, direction: dir, levels, controls, cases, warnings };
  ROC_DATA.set(result, data);
  return result;
}

function checkDirection(d: string | undefined): "auto" | RocDirection {
  if (d === undefined) return "auto";
  if (!(DIRECTIONS as readonly string[]).includes(d)) throw new RangeError(`'arg' should be one of “auto”, “<”, “>”`);
  return d as "auto" | RocDirection;
}

/**
 * The curve of a response and a predictor: observations with a missing response or predictor dropped (or an
 * error), the levels, and the classes
 */
export function rocFromResponse(
  response: readonly RocResponseValue[],
  predictor: readonly number[],
  options: { levels?: readonly RocResponseValue[] | undefined; direction?: string | undefined; naRm?: boolean | undefined },
): RocResult {
  const direction = checkDirection(options.direction);
  const w = new Warnings();
  const labels = response.map(labelOf);
  let levels: string[];
  if (options.levels === undefined) {
    levels = sortedLevels(response);
    if (levels.length > 2) {
      w.add("'response' has more than two levels. Consider setting 'levels' explicitly or using 'multiclass.roc' instead");
      levels = levels.slice(0, 2);
    }
    if (levels.length < 2) throw new RangeError("'response' must have two levels");
  } else {
    if (!Array.isArray(options.levels) || options.levels.length !== 2) throw new RangeError("'levels' argument must have length 2");
    levels = options.levels.map((v) => {
      const l = labelOf(v);
      if (l === null) throw new RangeError("'levels' must not be missing");
      return l;
    });
  }
  if (predictor.some((v) => typeof v !== "number")) throw new TypeError("Predictor must be numeric.");
  if (labels.length !== predictor.length) throw new TypeError("Response and predictor must be vectors of the same length.");
  const missing = labels.map((l, i) => l === null || Number.isNaN(predictor[i]!));
  if (options.naRm === false && missing.some((b) => b)) {
    throw new RangeError("missing values in the response or the predictor with naRm false");
  }
  const controls: number[] = [];
  const cases: number[] = [];
  const values: number[] = [];
  const isCase: boolean[] = [];
  const kept: number[] = [];
  labels.forEach((l, i) => {
    if (missing[i]) return;
    const v = predictor[i]!;
    if (l === levels[0]) controls.push(v);
    else if (l === levels[1]) cases.push(v);
    else return;
    values.push(v);
    isCase.push(l === levels[1]);
    kept.push(i);
  });
  const data: RocData = { labels, predictor: [...predictor], values, isCase, kept };
  return buildRoc(controls, cases, direction, [levels[0]!, levels[1]!], data, w.list);
}

/** The response and predictor of a formula `response ~ predictor` (rows with a missing value dropped) */
function formulaData(formula: string, data: DataFrame): { response: RocResponseValue[]; predictor: number[] } {
  const terms = termsOf(parseFormula(formula), Object.keys(data));
  if (terms.response !== 0 || terms.variables.length !== 2 || terms.terms.length !== 1) {
    throw new TypeError("the formula must be of the form response ~ predictor");
  }
  const frame = modelFrame(data, terms.variables);
  const [rv, pv] = frame.variables as [(typeof frame.variables)[0], (typeof frame.variables)[0]];
  if (pv.kind !== "numeric") throw new TypeError("Predictor must be numeric.");
  const response = rv.kind === "numeric" ? rv.values : rv.codes.map((c) => rv.levels[c]!);
  return { response, predictor: pv.values };
}

/** Whether a value is a plain object (not an array or a typed array) */
function isPlainObject(v: unknown): v is Record<string, unknown> {
  return typeof v === "object" && v !== null && !Array.isArray(v) && !ArrayBuffer.isView(v);
}

/**
 * The ROC curve of a numeric predictor of a binary response. Equivalent to `pROC::roc()` in R.
 *
 * The first level of the response is the control, the second the case (with more than two levels the first two are
 * used, with pROC's warning). The thresholds are the midpoints between consecutive distinct values, with `-Infinity`
 * and `Infinity` at the ends, and the points are stored as pROC stores them, by increasing specificity. The AUC is
 * computed from the counts as U/(mn) and rounded once. Infinite predictor values are an error (pROC returns NaN with
 * a warning), as are an empty class and, with `naRm: false`, missing values (pROC returns NA).
 *
 * @param response The outcome: numbers, strings or booleans (`null` or `NaN` for a missing value).
 * @param predictor The predictor, numeric, of the same length (`NaN` for a missing value).
 * @param options See {@link RocOptions}.
 *
 * @example
 * ```ts
 * const r = roc([0, 0, 0, 1, 1, 1], [1, 2, 4, 3, 5, 6]);
 * r.auc;        // 0.8888888888888888
 * r.thresholds; // [-Infinity, 1.5, 2.5, 3.5, 4.5, 5.5, Infinity]
 * ```
 *
 * @category Hypothesis tests
 */
export function roc(response: readonly RocResponseValue[] | Float64Array, predictor: Sample, options?: RocOptions): RocResult;
/**
 * The ROC curve from a formula `response ~ predictor` and a data frame; the rows where either is missing are dropped.
 *
 * @param formula `"response ~ predictor"`.
 * @param data The data frame: an object of columns (`null` or `NaN` for a missing value).
 * @param options See {@link RocOptions}.
 */
export function roc(formula: string, data: DataFrame, options?: RocOptions): RocResult;
/**
 * The ROC curve from the predictor values of the controls and of the cases (pROC's `roc(controls =, cases =)`).
 *
 * @param samples The two samples.
 * @param options See {@link RocOptions} (without `levels`).
 */
export function roc(samples: RocSamples, options?: RocOptions): RocResult;
export function roc(
  x: readonly RocResponseValue[] | Float64Array | string | RocSamples,
  y?: Sample | DataFrame | RocOptions,
  options: RocOptions = {},
): RocResult {
  if (isOptionsObject(x)) checkOptions(x, ROC_KEYS_0, "roc"); // generated: option-keys.mjs
  if (typeof x !== "string" && isOptionsObject(y)) checkOptions(y, ROC_KEYS_1, "roc"); // generated: option-keys.mjs
  checkOptions(options, ROC_KEYS_1, "roc"); // generated: option-keys.mjs
  if (typeof x === "string") {
    const d = formulaData(x, y as DataFrame);
    return reported("roc", rocFromResponse(d.response, d.predictor, options));
  }
  if (isPlainObject(x)) {
    const opts = (y ?? {}) as RocOptions;
    if (opts.levels !== undefined) throw new RangeError("'levels' cannot be given with controls and cases");
    const s = x as RocSamples;
    if (s.controls === undefined || s.cases === undefined) throw new TypeError("'controls' and 'cases' must both be given");
    const direction = checkDirection(opts.direction);
    const controls0 = Array.from(s.controls);
    const cases0 = Array.from(s.cases);
    if ([...controls0, ...cases0].some((v) => typeof v !== "number")) throw new TypeError("Predictor must be numeric.");
    if (opts.naRm === false && [...controls0, ...cases0].some(Number.isNaN)) {
      throw new RangeError("missing values in the controls or the cases with naRm false");
    }
    const controls = controls0.filter((v) => !Number.isNaN(v));
    const cases = cases0.filter((v) => !Number.isNaN(v));
    const values = [...controls, ...cases];
    const data: RocData = {
      labels: null,
      predictor: values,
      values,
      isCase: values.map((_, i) => i >= controls.length),
      kept: values.map((_, i) => i),
    };
    return reported("roc", buildRoc(controls, cases, direction, ["0", "1"], data, []));
  }
  return reported("roc", rocFromResponse(Array.from(x as ArrayLike<RocResponseValue>), Array.from(y as Sample), options));
}

