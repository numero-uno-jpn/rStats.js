// ROC curves of a numeric predictor of a binary outcome (pROC's roc, auc with the partial AUC, and coords).
//
// Written for rStats.js from oracle/roc-behaviour.md (no ported code; the source of pROC was not read):
// - The curve: the thresholds are the midpoints between consecutive distinct values, with -Inf and +Inf at the ends;
//   for direction "<" an observation is positive when its value is at least the threshold, for ">" when it is at most
//   the threshold. The points are stored by increasing specificity, as pROC stores them.
// - The AUC is the Mann-Whitney statistic U/(mn) (Hanley and McNeil, Radiology 143, 1982), computed from integer
//   counts and rounded once (pROC sums trapezoids, which agrees to an ulp or two).
// - The partial AUC is the area between two specificities (or sensitivities), with linear interpolation at the
//   limits, optionally standardised as McClish (Medical Decision Making 9, 1989).
// - coords computes every column from the integer counts of each threshold (pROC rebuilds the counts from the
//   proportions, which leaves them non-integer and loses digits in 1 - specificity), and compares the criteria of
//   "best" exactly (pROC compares rounded sums with ==, which loses ties). Youden's criterion is pROC's weighted
//   se + r sp (Youden, Cancer 3, 1950; Perkins and Schisterman, Am J Epidemiol 163, 2006; the weights r =
//   (1 - prevalence)/(cost prevalence) as Zweig and Campbell, Clin Chem 39, 1993).

