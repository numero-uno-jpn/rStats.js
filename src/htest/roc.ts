/**
 * Options for {@link coords}.
 *
 * @category Hypothesis tests
 */
export interface CoordsOptions {
  /**
   * The criterion of `"best"`: `"youden"` (default; the maximum of se + r·sp) or `"closest.topleft"` (the minimum of
   * (1 − se)² + r(1 − sp)²; `"topleft"` is the same); abbreviations are accepted.
   */
  bestMethod?: "youden" | "closest.topleft" | "topleft" | (string & {});
  /**
   * `[cost, prevalence]`: the weight r = (1 − prevalence)/(cost · prevalence) of the specificity in the criteria.
   * The cost must be positive and the prevalence in (0, 1). Default `[1, 0.5]` (r = 1).
   */
  bestWeights?: readonly number[];
}

/**
 * Result of {@link coords}: one array per column, one value per point (pROC's data frame with `ret = "all"`).
 *
 * @category Hypothesis tests
 */
export interface CoordsResult {
  /** The threshold of each point. */
  threshold: number[];
  /** Sensitivity tp/(tp + fn). */
  sensitivity: number[];
  /** Specificity tn/(tn + fp). */
  specificity: number[];
  /** Accuracy (tp + tn)/(number of observations). */
  accuracy: number[];
  /** True negatives. */
  tn: number[];
  /** True positives. */
  tp: number[];
  /** False negatives. */
  fn: number[];
  /** False positives. */
  fp: number[];
  /** Negative predictive value tn/(tn + fn) (`NaN` when no observation is negative). */
  npv: number[];
  /** Positive predictive value tp/(tp + fp) (`NaN` when no observation is positive). */
  ppv: number[];
  /** False positive rate fp/(fp + tn). */
  fpr: number[];
  /** Positive likelihood ratio se/(1 − sp). */
  lrPos: number[];
  /** Negative likelihood ratio (1 − se)/sp. */
  lrNeg: number[];
  /** pROC's Youden criterion se + r·sp (not se + sp − 1). */
  youden: number[];
  /** The squared distance to the top left corner (1 − se)² + r(1 − sp)². */
  closestTopleft: number[];
  /** R's warnings, each once, in R's order (an empty array when there are none). */
  warnings: string[];
}

/** A finite double as an exact rational num/den (den a power of 2) */
function toRational(v: number): [bigint, bigint] {
  if (v === 0) return [0n, 1n];
  let e = 0;
  let m = v;
  while (!Number.isInteger(m)) {
    m *= 2;
    e++;
  }
  return [BigInt(m), 1n << BigInt(e)];
}

/** The integer counts at given thresholds */
function countsAt(curve: RocResult, thresholds: readonly number[]): { tp: number[]; tn: number[] } {
  const c = sortedCopy(curve.controls);
  const k = sortedCopy(curve.cases);
  // the number of values below v (strictly, or at most v)
  const below = (s: Float64Array, v: number, orEqual: boolean): number => {
    let lo = 0;
    let hi = s.length;
    while (lo < hi) {
      const mid = (lo + hi) >> 1;
      if (orEqual ? s[mid]! <= v : s[mid]! < v) lo = mid + 1;
      else hi = mid;
    }
    return lo;
  };
  const lt = curve.direction === "<";
  return {
    tp: thresholds.map((t) => (lt ? k.length - below(k, t, false) : below(k, t, true))),
    tn: thresholds.map((t) => (lt ? below(c, t, false) : c.length - below(c, t, true))),
  };
}

/**
 * Coordinates of a ROC curve: sensitivity, specificity, the counts, predictive values, likelihood ratios and the
 * criteria of the best threshold, at every point of the curve, at the best threshold(s) or at given thresholds.
 * Equivalent to `pROC::coords(roc, x, ret = "all")` in R.
 *
 * Every column is computed from the integer counts of each threshold and rounded once (pROC rebuilds the counts from
 * the proportions, so that they are not always integers, and loses digits in 1 − specificity). The rows of `"best"`
 * are all the points whose criterion equals the best one exactly (pROC compares rounded sums and can lose ties). At a
 * given threshold, an observation equal to it counts as positive.
 *
 * @param curve A curve from {@link roc}.
 * @param x `"all"` (default: every point of the curve), `"best"`, or thresholds (a number or an array).
 * @param options See {@link CoordsOptions}.
 *
 * @example
 * ```ts
 * const r = roc({ controls: [1, 2, 2, 3, 5, 7], cases: [2, 4, 5, 5, 8, 9, 10] });
 * const best = coords(r, "best");
 * best.threshold;   // [3.5]
 * best.sensitivity; // [0.8571428571428571]
 * coords(r, [4, 6]).tp; // [6, 3]
 * ```
 *
 * @category Hypothesis tests
 */
export function coords(curve: RocResult, x: "all" | "best" | (string & {}) | number | readonly number[] = "all", options: CoordsOptions = {}): CoordsResult {
  checkOptions(options, COORDS_KEYS, "coords"); // generated: option-keys.mjs
  const bestMethod = matchChoice(options.bestMethod, ["youden", "closest.topleft", "topleft"] as const);
  const weights = options.bestWeights ?? [1, 0.5];
  if (!Array.isArray(weights) || weights.length !== 2 || weights.some((v) => typeof v !== "number")) {
    throw new TypeError("'best.weights' must be a numeric vector of length 2");
  }
  const [cost, prevalence] = weights as [number, number];
  if (!(prevalence > 0 && prevalence < 1)) throw new RangeError("prevalence ('best.weights[2]') must be in the interval ]0,1[.");
  // (pROC does not check the cost: 0 gives r = Inf, a negative cost a negative r)
  if (!(cost > 0 && cost < Infinity)) throw new RangeError("the cost ('bestWeights[0]') must be a positive finite number");
  const r = (1 - prevalence) / (cost * prevalence);
  let thresholds: number[];
  let pick: "all" | "best" | null = null;
  if (typeof x === "string") pick = matchChoice(x, ["all", "best"] as const);
  if (pick !== null) thresholds = [...curve.thresholds];
  else {
    thresholds = typeof x === "number" ? [x] : Array.from(x as readonly number[]);
    if (thresholds.length === 0) throw new RangeError("Numeric 'x' has length 0");
    if (thresholds.some((v) => typeof v !== "number" || Number.isNaN(v))) throw new RangeError("the thresholds must be numbers (not NaN)");
  }
  const P = curve.cases.length;
  const N = curve.controls.length;
  let { tp, tn } = countsAt(curve, thresholds);
  if (pick === "best") {
    // the criteria compared exactly: youden se + r sp times P N rd, closest.topleft minus its distance times P² N² rd,
    // with r = rn/rd the exact rational of the double weights: r = (1 - w2)/(w1 w2) = (d2 - n2) d1/(n1 n2)
    const [n1, d1] = toRational(cost);
    const [n2, d2] = toRational(prevalence);
    const rn = (d2 - n2) * d1;
    const rd = n1 * n2;
    const bP = BigInt(P);
    const bN = BigInt(N);
    const crit = tp.map((t, i) => {
      if (bestMethod === "youden") return BigInt(t) * bN * rd + rn * BigInt(tn[i]!) * bP;
      const fn = BigInt(P - t);
      const fp = BigInt(N - tn[i]!);
      return -(fn * fn * bN * bN * rd + rn * fp * fp * bP * bP);
    });
    const best = crit.reduce((a, b) => (b > a ? b : a));
    const rows = crit.map((c, i) => (c === best ? i : -1)).filter((i) => i >= 0);
    thresholds = rows.map((i) => thresholds[i]!);
    tp = rows.map((i) => tp[i]!);
    tn = rows.map((i) => tn[i]!);
  }
  const fn = tp.map((t) => P - t);
  const fp = tn.map((t) => N - t);
  return reported("coords", {
    threshold: thresholds,
    sensitivity: tp.map((t) => t / P),
    specificity: tn.map((t) => t / N),
    accuracy: tp.map((t, i) => (t + tn[i]!) / (P + N)),
    tn,
    tp,
    fn,
    fp,
    npv: tn.map((t, i) => t / (t + fn[i]!)),
    ppv: tp.map((t, i) => t / (t + fp[i]!)),
    fpr: fp.map((f) => f / N),
    // (tp N)/(P fp) and (fn N)/(P tn): integer products below 2^53, one rounding
    lrPos: tp.map((t, i) => (t * N) / (P * fp[i]!)),
    lrNeg: fn.map((f, i) => (f * N) / (P * tn[i]!)),
    youden: tp.map((t, i) => t / P + r * (tn[i]! / N)),
    closestTopleft: fn.map((f, i) => (f / P) ** 2 + r * (fp[i]! / N) ** 2),
    warnings: [],
  });
}
