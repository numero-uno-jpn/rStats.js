/**
 * Above this, both degrees of freedom of an F test are huge enough for {@link fPowerHugeDf} (pwrF2Test, pwrAnovaTest,
 * powerAnovaTest). (1e16: the exact path pf(qf(...)) already loses about 1e-8 of the power there, from the critical
 * value's few significant digits beyond 1, and up to 1e-5 just below 1e20; the approximation's error O(df^-1/2) is
 * below that.)
 */
const HUGE_DF = 1e16;

/** Whether an F test's power is taken from the normal approximation (df1 finite, both above 1e16) */
export const hugeDf = (df1: number, df2: number): boolean => df1 > HUGE_DF && df1 < Infinity && df2 > HUGE_DF;

/**
 * The power P[F > qf(sig)] of an F test with noncentrality ncp where both degrees of freedom exceed 1e16 (df2 may be
 * Infinity). There the critical value 1 + O(df^-1/2) keeps only a few significant digits beyond 1 in doubles (and
 * rounds to 1 for the largest), so that pf(qf(...)) loses the test; F = (χ²(df1, λ)/df1) / (χ²_df2/df2) is normal
 * instead, with mean 1 + μ, μ = λ/df1, and variance 2 (1 + 2μ)/df1 + 2 (1 + μ)²/df2 (2/df1 + 2/df2 under the null),
 * to within O(df1^-1/2) in the power (about 1e-8 at 1e16, 1e-10 at 1e20).
 * The standard deviation is formed as a hypot so that (1 + μ)² does not overflow.
 */
export function fPowerHugeDf(df1: number, df2: number, ncp: number, sig: number): number {
  const z = qnorm(sig, { lowerTail: false }) as number;
  const mu = ncp / df1;
  const sd0 = Math.sqrt(2 / df1 + 2 / df2);
  const sd1 = Math.hypot(Math.sqrt((2 * (1 + 2 * mu)) / df1), Math.sqrt(2 / df2) * (1 + mu));
  return pnorm((z * sd0 - mu) / sd1, { lowerTail: false }) as number;
}

/**
 * a b c / d for finite a, b, d > 0 and c >= 0, each factor scaled to [1, 2) by a power of 2 and the exponents added
 * back at the end, so that no partial product overflows or underflows unless the result does
 */
function scaledProductOver(a: number, b: number, c: number, d: number): number {
  if (c === 0) return 0;
  const k = (v: number): number => Math.floor(Math.log2(v));
  const [ka, kb, kc, kd] = [k(a), k(b), k(c), k(d)];
  return ldexp((ldexp(a, -ka) * ldexp(b, -kb) * ldexp(c, -kc)) / ldexp(d, -kd), ka + kb + kc - kd);
}

/**
 * Power of the F test of a balanced one-way analysis of variance, or one of the other quantities for a given power.
 * Equivalent to R's `power.anova.test()`.
 *
 * @example
 * ```ts
 * powerAnovaTest({ groups: 4, n: 5, betweenVar: 1, withinVar: 3 }).power;   // 0.3535594237229933
 * ```
 *
 * @category Effect sizes and power
 */
export function powerAnovaTest(options: PowerAnovaTestOptions = {}): PowerAnovaTestResult {
  checkOptions(options, POWER_ANOVA_TEST_KEYS, "powerAnovaTest"); // generated: option-keys.mjs
  let { groups, n, betweenVar, withinVar, power } = options;
  let sigLevel = options.sigLevel === undefined ? 0.05 : options.sigLevel;
  checkExactlyOne(
    [groups, n, betweenVar, withinVar, power, sigLevel],
    "exactly one of 'groups', 'n', 'between.var', 'within.var', 'power', and 'sig.level' must be NULL",
  );
  if (!isUnknown(groups) && !(groups >= 2)) throw new RangeError("number of groups must be at least 2");
  if (!isUnknown(n) && !(n >= 2)) throw new RangeError("number of observations in each group must be at least 2");
  checkSigLevel(sigLevel, SIG_MESSAGE);
  checkKnown(power, isProb, "'power' must be a probability");
  checkKnown(betweenVar, (v) => v >= 0 && v < Infinity, "'betweenVar' must be a nonnegative finite number");
  checkKnown(withinVar, isPositiveFinite, "'withinVar' must be a positive finite number");
  const powerOf = (groups: number, n: number, between: number, within: number, sig: number): number => {
    // (the ratio first where the product with between overflows but the noncentrality is in range; where
    // (groups - 1) n itself overflows, from the four factors scaled by powers of 2: groups 3, n 1e308, between 1,
    // within 1e308 gave the limit 1 for lambda = 2, and between 0 NaN for 0)
    let lambda = ((groups - 1) * n * between) / within;
    if (!(lambda < Infinity)) lambda = (groups - 1) * n * (between / within);
    if (!(lambda < Infinity) && Number.isFinite(groups) && Number.isFinite(n)) {
      lambda = scaledProductOver(groups - 1, n, between, within);
    }
    const df1 = groups - 1;
    const df2 = (n - 1) * groups;
    // (a noncentrality beyond the doubles: the limit 1)
    if (lambda === Infinity) return 1;
    // (both degrees of freedom above 1e16: the normal approximation, as in pwrAnovaTest; the critical value is 1 to a
    // few digits, and groups 1e200, n 1e200, between 1e8, within 1e308 gave 0.760 for 0.174. R gives NaN there)
    if (hugeDf(df1, df2)) return fPowerHugeDf(df1, df2, lambda, sig);
    return pf(qf(sig, df1, df2, { lowerTail: false }), df1, df2, { ncp: lambda, lowerTail: false });
  };
  if (isUnknown(power)) power = powerOf(groups!, n!, betweenVar!, withinVar!, sigLevel!);
  else {
    const target = power;
    if (isUnknown(groups)) groups = solveFor((x) => powerOf(x, n!, betweenVar!, withinVar!, sigLevel!) - target, 2, 100);
    else if (isUnknown(n)) {
      // (with betweenVar = 0 the power does not depend on n; R and before #311: "f() values at end points not of
      // opposite sign")
      if (betweenVar === 0) throw new RangeError("'n' cannot be determined when 'betweenVar' is 0: the power does not depend on it");
      n = solveFor((x) => powerOf(groups!, x, betweenVar!, withinVar!, sigLevel!) - target, 2, 1e5);
    }
    else if (isUnknown(withinVar)) {
      // (with betweenVar = 0 the power does not depend on withinVar; R: "lower < upper is not fulfilled")
      if (betweenVar === 0) throw new RangeError("'withinVar' cannot be determined when 'betweenVar' is 0: the power does not depend on it");
      withinVar = solveFor((x) => powerOf(groups!, n!, betweenVar!, x, sigLevel!) - target, betweenVar! * 1e-7, betweenVar! * 1e7);
    } else if (isUnknown(betweenVar)) {
      betweenVar = solveFor((x) => powerOf(groups!, n!, x, withinVar!, sigLevel!) - target, withinVar * 1e-7, withinVar * 1e7);
    } else {
      sigLevel = solveFor((x) => powerOf(groups!, n!, betweenVar!, withinVar!, x) - target, 1e-10, 1 - 1e-10);
    }
  }
  return {
    groups: groups!,
    n: n!,
    betweenVar: betweenVar!,
    withinVar: withinVar!,
    sigLevel: sigLevel!,
    power,
    note: "n is number in each group",
    method: "Balanced one-way analysis of variance power calculation",
  };
}
