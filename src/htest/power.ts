const SIG_MESSAGE = "'sig.level' must be numeric in [0, 1]";

/**
 * Power of a one- or two-sample t test, or the sample size, difference, standard deviation or significance level
 * for a given power. Equivalent to R's `power.t.test()`.
 *
 * @example
 * ```ts
 * powerTTest({ n: 20, delta: 1 }).power;           // 0.8689528016921269
 * powerTTest({ delta: 0.5, power: 0.8 }).n;        // 63.765763714280546
 * ```
 *
 * @category Effect sizes and power
 */
export function powerTTest(options: PowerTTestOptions = {}): PowerTTestResult {
  checkOptions(options, POWER_TTEST_KEYS, "powerTTest"); // generated: option-keys.mjs
  let { n, delta, power } = options;
  let sd = options.sd === undefined ? 1 : options.sd;
  let sigLevel = options.sigLevel === undefined ? 0.05 : options.sigLevel;
  checkExactlyOne([n, delta, sd, power, sigLevel], "exactly one of 'n', 'delta', 'sd', 'power', and 'sig.level' must be NULL");
  checkSigLevel(sigLevel, SIG_MESSAGE);
  checkKnown(power, isProb, "'power' must be a probability");
  checkKnown(sd, isPositiveFinite, "'sd' must be a positive finite number");
  checkKnown(n, (v) => v >= 2, "number of observations in each group must be at least 2");
  checkKnown(delta, (v) => !Number.isNaN(v), "'delta' must not be NaN");
  checkKnown(options.tol, isPositiveFinite, "'tol' must be a positive finite number");
  const type = matchChoice(options.type, ["two.sample", "one.sample", "paired"] as const);
  const alternative = matchChoice(options.alternative, ["two.sided", "one.sided"] as const);
  const strict = options.strict ?? false;
  const tol = options.tol ?? TOL;
  const ts = type === "two.sample" ? 2 : 1;
  const sides = alternative === "two.sided" ? 2 : 1;
  if (sides === 2 && !isUnknown(delta)) delta = Math.abs(delta);
  const powerOf = (n: number, delta: number, sd: number, sig: number): number => {
    const nu = Math.max(1e-7, n - 1) * ts;
    const q = qt(sig / sides, nu, { lowerTail: false });
    let ncp = (Math.sqrt(n / ts) * delta) / sd;
    // sqrt(n / ts) * delta can overflow before the division by a large sd (#197); with the ratio delta / sd first the
    // noncentrality is Infinity only where it is beyond the doubles itself (sqrt(n / ts) >= 1). Only there: elsewhere
    // R's order, with its bits
    if (!Number.isFinite(ncp)) ncp = Math.sqrt(n / ts) * (delta / sd);
    const p = ptNcp(q, nu, ncp, false);
    return strict && sides === 2 ? p + ptNcp(-q, nu, ncp, true) : p;
  };
  if (isUnknown(power)) power = powerOf(n!, delta!, sd!, sigLevel!);
  else {
    const target = power;
    if (isUnknown(n)) {
      // with delta = 0 the power does not depend on n (R and before #311: the search failed with "no sign change")
      if (delta === 0) throw new RangeError("'n' cannot be determined when 'delta' is 0: the power does not depend on it");
      n = solveFor((x) => powerOf(x, delta!, sd!, sigLevel!) - target, 2, 1e7, { tol, extendInt: "upX" });
    } else if (isUnknown(sd)) {
      // with delta = 0 the power does not depend on sd (R: "lower < upper is not fulfilled"); with a negative delta (one
      // sided) the power rises towards sigLevel as sd grows, so the search runs over |delta| the other way
      if (delta === 0) throw new RangeError("'sd' cannot be determined when 'delta' is 0: the power does not depend on it");
      const ad = Math.abs(delta!);
      sd = solveFor((x) => powerOf(n!, delta!, x, sigLevel!) - target, ad * 1e-7, ad * 1e7, { tol, extendInt: delta! > 0 ? "downX" : "upX" });
    } else if (isUnknown(delta)) {
      delta = solveFor((x) => powerOf(n!, x, sd!, sigLevel!) - target, sd * 1e-7, sd * 1e7, { tol, extendInt: "upX" });
    } else {
      sigLevel = solveFor((x) => powerOf(n!, delta!, sd!, x) - target, 1e-10, 1 - 1e-10, { tol, extendInt: "yes" });
    }
  }
  const note =
    type === "paired"
      ? "n is number of *pairs*, sd is std.dev. of *differences* within pairs"
      : type === "two.sample"
        ? "n is number in *each* group"
        : undefined;
  const method = { "two.sample": "Two-sample", "one.sample": "One-sample", paired: "Paired" }[type] + " t test power calculation";
  return {
    n: n!,
    delta: delta!,
    sd: sd!,
    sigLevel: sigLevel!,
    power,
    alternative,
    ...(note === undefined ? {} : { note }),
    method,
  };
}

