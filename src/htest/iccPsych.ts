// The six intraclass correlations of Shrout and Fleiss (psych's ICC): one-way and two-way, single and average
// raters, with their F tests and confidence intervals, from the ANOVA mean squares or from REML variance components.
//
// Written for rStats.js from oracle/methodcomparison-behaviour.md, section 3 (no R or package code), and the papers:
// - Shrout PE, Fleiss JL (1979) Intraclass correlations: uses in assessing rater reliability. Psychological Bulletin
//   86:420-428: the six forms, their F tests and intervals, ICC2's interval with Satterthwaite's df v.
// - The REML estimates of the balanced crossed model y = mu + s_i + r_j + e_ij: the REML likelihood of balanced data is
//   that of the three independent mean squares MS_t ~ lambda_t chi^2(df_t)/df_t, lambda_B = k s2_s + s2_e, lambda_J =
//   n s2_r + s2_e, lambda_E = s2_e (Searle, Casella and McCulloch 1992, Variance Components, ch. 6). The constraints
//   s2_s, s2_r >= 0 are lambda_E <= lambda_B and lambda_E <= lambda_J, and the maximum under this order is the
//   weighted isotonic regression of the mean squares with weights df_t (Robertson, Wright and Dykstra 1988, Order
//   Restricted Statistical Inference, ch. 1): the residual mean square is pooled with each of the others, smallest
//   first, that lies below the pooled value. Without pooling these are the ANOVA mean squares.

