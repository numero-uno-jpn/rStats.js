/**
 * Options for {@link ICC}.
 *
 * @category Agreement, reliability and factor analysis
 */
export interface ICCOptions {
  /** One minus the confidence level of the intervals, in (0, 1) (psych's `alpha`). Default `0.05`; overrides
   *  `confLevel`. */
  alpha?: number;
  /** Confidence level of the intervals, in (0, 1). Default `0.95`. */
  confLevel?: number;
  /**
   * `true` (default, as psych): the mean squares from the REML estimates of the variance components, which are not
   * negative (where a component would be negative, it is 0 and the coefficients that depend on it are 0, F 1);
   * `false`: the ANOVA mean squares (coefficients may be negative).
   */
  lmer?: boolean;
}

/**
 * One of the six forms in {@link ICCResult}.
 *
 * @category Agreement, reliability and factor analysis
 */
export interface ICCRow {
  /** `"ICC1"`, `"ICC2"`, `"ICC3"`, `"ICC1k"`, `"ICC2k"` or `"ICC3k"`. */
  type: "ICC1" | "ICC2" | "ICC3" | "ICC1k" | "ICC2k" | "ICC3k";
  /** psych's row name: `"Single_raters_absolute"`, `"Single_random_raters"`, ... */
  name: string;
  /** The intraclass correlation. */
  ICC: number;
  /** F statistic of the test of ICC = 0. */
  F: number;
  /** Numerator degrees of freedom. */
  df1: number;
  /** Denominator degrees of freedom. */
  df2: number;
  /** Upper-tail p-value of the F test. */
  pValue: number;
  /** Lower confidence limit. */
  lower: number;
  /** Upper confidence limit. */
  upper: number;
}

/**
 * Result of {@link ICC}.
 *
 * @category Agreement, reliability and factor analysis
 */
export interface ICCResult {
  /** The six forms, in psych's order ICC1, ICC2, ICC3, ICC1k, ICC2k, ICC3k. */
  results: ICCRow[];
  /** Mean square of subjects (REML: `k σ²_subject + σ²_e`). */
  MSB: number;
  /** Mean square of raters (REML: `n σ²_rater + σ²_e`). */
  MSJ: number;
  /** Residual mean square (REML: `σ²_e`). */
  MSE: number;
  /** Mean square within subjects, used by ICC1 and ICC1k (REML: `σ²_e + σ²_rater`). */
  MSW: number;
  /** Number of subjects (rows). */
  n: number;
  /** Number of raters (columns). */
  k: number;
  /** Confidence level of the intervals, `1 - alpha`. */
  confLevel: number;
  /** Whether the REML path was used. */
  lmer: boolean;
  /** R's warnings (aov's `essentially perfect fit` where the residual mean square is 0 on the ANOVA path). */
  warnings: string[];
}

const NAMES = {
  ICC1: "Single_raters_absolute",
  ICC2: "Single_random_raters",
  ICC3: "Single_fixed_raters",
  ICC1k: "Average_raters_absolute",
  ICC2k: "Average_random_raters",
  ICC3k: "Average_fixed_raters",
} as const;

/** a - b exactly, as an unevaluated sum [s, e] (Knuth's two-sum; error-free whatever the double-double switch) */
function exactDiff(a: number, b: number): [number, number] {
  const s = a - b;
  const bb = s - a;
  return [s, a - (s - bb) + (-b - bb)];
}

/** Whether the ratings are additive, x_ij - x_i1 = x_1j - x_11 for all i, j (the residual mean square is then 0) */
function isAdditive(rows: readonly (readonly number[])[]): boolean {
  const r0 = rows[0]!;
  return rows.every((r) =>
    r.every((v, j) => {
      const [s1, e1] = exactDiff(v, r[0]!);
      const [s2, e2] = exactDiff(r0[j]!, r0[0]!);
      return s1 === s2 && e1 === e2;
    }),
  );
}

const sameArray = (a: readonly number[], b: readonly number[]): boolean => a.every((v, i) => v === b[i]);

/** Mean of double-doubles */
function meanOfDD(v: readonly DD[]): DD {
  let s: DD = [0, 0];
  for (const u of v) s = ddAdd(s, u);
  return ddDivNum(s, v.length);
}

/** A nonnegative value v 2^e, v a double-double of moderate size: a sum or mean square in units of its own */
interface Scaled {
  v: DD;
  e: number;
}

const sDiv = (s: Scaled, d: number): Scaled => ({ v: ddDivNum(s.v, d), e: s.e });

/**
 * The values brought to the largest scale among them (zeros do not count), as doubles `at` in units 2^E: the smaller
 * ones lose only the digits (or the whole value) that are negligible beside the largest
 */
function inCommon(...s: Scaled[]): { at: number; E: number }[] {
  const nz = s.filter((t) => t.v[0] !== 0);
  const E = nz.length === 0 ? 0 : Math.max(...nz.map((t) => t.e));
  return s.map((t) => ({ at: ldexpWide(t.v[0], t.e - E), E }));
}

/** a + b, at the larger of their scales (in double-double) */
function sAdd(a: Scaled, b: Scaled): Scaled {
  if (b.v[0] === 0) return a;
  if (a.v[0] === 0) return b;
  const E = Math.max(a.e, b.e);
  const to = (t: Scaled): DD => [ldexpWide(t.v[0], t.e - E), ldexpWide(t.v[1], t.e - E)];
  return { v: ddAdd(to(a), to(b)), e: E };
}

/** a/b (Infinity for b = 0 < a, NaN for 0/0), formed from the ratio of the parts and one power of 2 */
const sRatio = (a: Scaled, b: Scaled): number => ldexpWide(a.v[0] / b.v[0], a.e - b.e);

const sLess = (a: Scaled, b: Scaled): boolean => {
  const [x, y] = inCommon(a, b);
  return x!.at < y!.at;
};
const sLessEq = (a: Scaled, b: Scaled): boolean => {
  const [x, y] = inCommon(a, b);
  return x!.at <= y!.at;
};

/** Sum of squared deviations of the means m from g, times w, in double-double */
function ssOfMeans(m: readonly DD[], g: DD, w: number): DD {
  let s: DD = [0, 0];
  for (const v of m) {
    const d = ddSub(v, g);
    s = ddAdd(s, ddMul(d, d));
  }
  return ddMul(s, [w, 0]);
}

/**
 * The six intraclass correlations of Shrout and Fleiss (1979), with their F tests and confidence intervals.
 * Equivalent to `psych::ICC(x, alpha, lmer)` in R. Only complete data are accepted.
 *
 * `x` is an n × k matrix (an array of rows): the ratings of the k raters for each of the n subjects. The forms are
 * ICC1 = (MSB − MSW)/(MSB + (k − 1)MSW) (one-way), ICC2 = (MSB − MSE)/(MSB + (k − 1)MSE + k(MSJ − MSE)/n) (two-way
 * random raters, absolute agreement), ICC3 = (MSB − MSE)/(MSB + (k − 1)MSE) (two-way fixed raters, consistency), and
 * their averages over k raters ICC1k, ICC2k, ICC3k. With `lmer: true` (the default, as psych) the mean squares are
 * rebuilt from the REML estimates of the variance components of the two-way random model, which are not negative;
 * where both ANOVA components are not negative they equal the ANOVA mean squares. psych fits that model with lme4,
 * whose optimiser stops early (results about 1e-5 relative off); here the REML estimates are computed exactly, in
 * closed form.
 *
 * ICC1, ICC3, ICC1k and ICC3k agree with {@link icc} (irr's forms); the interval of ICC2k is psych's (ICC2's bounds
 * transformed by Spearman-Brown), not irr's (McGraw and Wong's average-agreement interval).
 *
 * Where the residual mean square is 0 (ratings that differ between raters by constants), the F statistics of ICC2 and
 * ICC3 are Infinity with p-value 0, and ICC3, ICC3k and their bounds are 1.
 *
 * @param x An n × k matrix of ratings (array of rows), without missing values.
 * @param options See {@link ICCOptions}.
 * @returns See {@link ICCResult}.
 * @throws TypeError if x is not a matrix of numbers; RangeError for missing or infinite ratings (psych's REML path
 *   accepts missing ratings; here they are an error), fewer than 2 subjects or raters, ratings that are all equal or
 *   identical for every subject, or a level out of range.
 *
 * @example
 * ```ts
 * const r = ICC([[9, 2, 5, 8], [6, 1, 3, 2], [8, 4, 6, 8], [7, 1, 2, 6], [10, 5, 6, 9], [6, 2, 4, 7]]);
 * r.results[1]!.ICC;   // 0.28976377952755905 (ICC2)
 * r.results[4]!.lower; // 0.07113681530250335 (ICC2k)
 * ```
 *
 * @category Agreement, reliability and factor analysis
 */
export function ICC(x: readonly (readonly number[])[], options: ICCOptions = {}): ICCResult {
  checkOptions(options, ICC_KEYS, "ICC"); // generated: option-keys.mjs
  const lmer = options.lmer ?? true;
  if (typeof lmer !== "boolean") throw new TypeError("'lmer' must be true or false");
  let alpha: number;
  let confLevel: number;
  if (options.alpha !== undefined) {
    alpha = options.alpha;
    if (!(typeof alpha === "number" && alpha > 0 && alpha < 1)) throw new RangeError("'alpha' must be a single number in (0, 1)");
    confLevel = 1 - alpha;
  } else {
    confLevel = options.confLevel ?? 0.95;
    checkConfLevelOpen(confLevel);
    alpha = 1 - confLevel;
  }
  if (!Array.isArray(x) || x.length === 0 || !x.every((r) => Array.isArray(r))) {
    throw new TypeError("'x' must be a matrix (an array of rows)");
  }
  const k = x[0]!.length;
  if (x.some((r) => r.length !== k)) throw new TypeError("'x' must be a matrix (rows of equal length)");
  if (x.some((r) => r.some((v) => typeof v !== "number"))) throw new TypeError("'x' must contain numbers");
  if (x.some((r) => r.some(Number.isNaN))) throw new RangeError("'x' contains missing ratings (only complete data are supported)");
  if (x.some((r) => r.some((v) => !Number.isFinite(v)))) throw new RangeError("'x' contains infinite ratings");
  const n = x.length;
  if (n < 2 || k < 2) throw new RangeError("at least 2 subjects and 2 raters are needed");
  // the ratings scaled by one power of 2 (exact), for the checks below
  const { groups: rows } = scaleToUnit(x);
  if (rows.every((r) => sameArray(r, rows[0]!))) {
    throw new RangeError(
      rows[0]!.every((v) => v === rows[0]![0]) ? "all ratings are equal" : "every subject has the same ratings: the coefficients are undefined",
    );
  }
  const cols = Array.from({ length: k }, (_, j) => rows.map((r) => r[j]!));
  // SSB and SSE do not change when a constant is added to a column, SSJ and SSE not when one is added to a row: the
  // sums of squares come from the ratings minus the first row (SSB), minus the first column (SSJ) and minus both
  // (SSE), so that a rater or subject offset far beyond the spread of the ratings does not swamp them. Each difference
  // is exact (a double-double); they are formed from the unscaled ratings (halved where a difference would overflow)
  // and then scaled by one power of 2 of their own
  const half = x.some((r, i) => r.some((v, j) => !Number.isFinite(v - x[0]![j]!) || !Number.isFinite(v - x[i]![0]!)));
  const raw = half ? x.map((r) => r.map((v) => v / 2)) : x;
  const byCol = raw.map((r) => r.map((v, j) => exactDiff(v, raw[0]![j]!)));
  const byRow = raw.map((r) => r.map((v) => exactDiff(v, r[0]!)));
  const both = byRow.map((r) => r.map((v, j) => ddSub(v, byRow[0]![j]!)));
  // each scaled by its own power of 2, so that the squares of the small ones do not underflow beside a large offset
  const expOf = (m: DD[][]): number => {
    let big = 0;
    for (const r of m) for (const v of r) big = Math.max(big, Math.abs(v[0]));
    return big === 0 ? 0 : Math.floor(Math.log2(big));
  };
  const unit = (m: DD[][], e: number): DD[][] => m.map((r) => r.map((v) => [ldexp(v[0], -e), ldexp(v[1], -e)] as const));
  const [kB, kJ, kE] = [expOf(byCol), expOf(byRow), expOf(both)];
  const [yB, yJ, yE] = [unit(byCol, kB), unit(byRow, kJ), unit(both, kE)];
  const colsOf = (m: DD[][]): DD[][] => Array.from({ length: k }, (_, j) => m.map((r) => r[j]!));
  const ssB = ssOfMeans(yB.map(meanOfDD), meanOfDD(yB.flat()), k);
  // (identical columns: SSJ is exactly 0, which the double-double means need not give)
  const ssJ: DD = cols.every((c) => sameArray(c, cols[0]!)) ? [0, 0] : ssOfMeans(colsOf(yJ).map(meanOfDD), meanOfDD(yJ.flat()), n);
  let ssE: DD = [0, 0];
  if (!isAdditive(rows)) {
    // the residuals x - row mean - column mean + grand mean, in double-double (no cancellation of SST - SSB - SSJ)
    const rm = yE.map(meanOfDD);
    const cm = colsOf(yE).map(meanOfDD);
    const grand = meanOfDD(yE.flat());
    yE.forEach((r, i) =>
      r.forEach((v, j) => {
        const e = ddAdd(ddSub(ddSub(v, rm[i]!), cm[j]!), grand);
        ssE = ddAdd(ssE, ddMul(e, e));
      }),
    );
  }
  // Each sum of squares stays in its own units, 2^(2kB), 2^(2kJ), 2^(2kE) (times 4 where the ratings were halved): a
  // quantity brings only the mean squares it uses to the larger of their scales, so that it underflows only where its
  // true value does (a rater offset far beyond the spread makes SSJ huge, but MSB, MSE, ICC3 and F3 do not change)
  const h = half ? 1 : 0;
  const scaled = (ss: DD, kx: number): Scaled => ({ v: ss, e: 2 * (kx + h) });
  const SB = scaled(ssB, kB);
  const SJ = scaled(ssJ, kJ);
  const SE = scaled(ssE, kE);
  const dfB = n - 1;
  const dfJ = k - 1;
  const dfE = (n - 1) * (k - 1);
  let MSB = sDiv(SB, dfB);
  let MSJ = sDiv(SJ, dfJ);
  let MSE = sDiv(SE, dfE);
  let MSW = sDiv(sAdd(SJ, SE), dfJ + dfE);
  const warnings: string[] = [];
  if (lmer) {
    // REML: the isotonic regression of (MSB, MSJ) >= MSE with weights df (see the header)
    const parts = {
      B: { ss: SB, df: dfB, ms: MSB, pooled: false },
      J: { ss: SJ, df: dfJ, ms: MSJ, pooled: false },
    };
    let pooledSS = SE;
    let pooledDf = dfE;
    for (const t of sLessEq(MSB, MSJ) ? (["B", "J"] as const) : (["J", "B"] as const)) {
      const part = parts[t];
      if (sLess(part.ms, sDiv(pooledSS, pooledDf))) {
        pooledSS = sAdd(pooledSS, part.ss);
        pooledDf += part.df;
        part.pooled = true;
      }
    }
    const lambdaE = sDiv(pooledSS, pooledDf);
    if (parts.B.pooled) MSB = lambdaE;
    if (parts.J.pooled) MSJ = lambdaE;
    MSE = lambdaE;
    // sigma2_e + sigma2_rater = MSE + (MSJ - MSE)/n: the ANOVA MSW unless the subjects' mean square was pooled
    // (pooling the raters' gives (SSJ + SSE)/(dfJ + dfE) = MSW itself)
    if (parts.B.pooled) {
      const [e, j] = inCommon(MSE, MSJ) as [{ at: number; E: number }, { at: number; E: number }];
      MSW = { v: [e.at + (j.at - e.at) / n, 0], e: e.E };
    }
  } else if (ssE[0] === 0) warnings.push("essentially perfect fit for ‘1’: summary may be unreliable");
  // the upper alpha/2 quantile of F (rule 10: from the upper tail itself below 1e-8, as 1 - alpha/2 loses its digits)
  const q = (d1: number, d2: number): number =>
    alpha / 2 < 1e-8 ? qf1(alpha / 2, d1, d2, false, false) : qf1(1 - alpha / 2, d1, d2, true, false);
  const upperP = (F: number, d1: number, d2: number): number => pf1(F, d1, d2, false, false);
  // (F - 1)/(F + k - 1) and 1 - 1/F, with their limit 1 at F = Infinity
  const single = (f: number): number => (f === Infinity ? 1 : (f - 1) / (f + k - 1));
  const average = (f: number): number => 1 - 1 / f;
  const dfW = n * (k - 1);
  const F1 = sRatio(MSB, MSW);
  const F3 = sRatio(MSB, MSE);
  const [F1L, F1U] = [F1 / q(dfB, dfW), F1 * q(dfW, dfB)];
  const [F3L, F3U] = [F3 / q(dfB, dfE), F3 * q(dfE, dfB)];
  // ICC1 and ICC1k need MSB and MSW, ICC3 and ICC3k MSB and MSE, ICC2, ICC2k and ICC2's interval all three: each in
  // the units of the largest of those it uses
  const [b1, w1] = inCommon(MSB, MSW).map((t) => t.at) as [number, number];
  const [b3, e3] = inCommon(MSB, MSE).map((t) => t.at) as [number, number];
  const [b2, j2, e2] = inCommon(MSB, MSJ, MSE).map((t) => t.at) as [number, number, number];
  const icc1 = (b1 - w1) / (b1 + (k - 1) * w1);
  const icc2 = (b2 - e2) / (b2 + (k - 1) * e2 + (k * (j2 - e2)) / n);
  const icc3 = (b3 - e3) / (b3 + (k - 1) * e3);
  // ICC2's interval (Shrout and Fleiss 1979, eq. for case 2): Satterthwaite's v of the combination k ICC2 MSJ + (n(1 +
  // (k - 1) ICC2) - k ICC2) MSE, written with MSE multiplied through (Fj = MSJ/MSE in the paper), so that MSE = 0 gives
  // its limit k - 1 (and MSJ = MSE = 0, where any v gives the bounds 1, k - 1 too)
  const a = k * icc2 * j2;
  const c = (n * (1 + (k - 1) * icc2) - k * icc2) * e2;
  const vDen = (n - 1) * a * a + c * c;
  const v = vDen === 0 ? k - 1 : ((k - 1) * (n - 1) * (a + c) ** 2) / vDen;
  const G1 = q(dfB, v);
  const G2 = q(v, dfB);
  // the bounds with numerator and denominator divided by G1 (and by G2 where it is above 1), so that a quantile that
  // overflows (a tiny v, where ICC2 < 0 makes a and c nearly cancel) gives the limit G -> Infinity, not -Inf/Inf.
  // Above 1/2 a bound is formed as 1 minus its complement, (n MSE + kJE)/(kJE + n MSB/G), which keeps it <= 1
  const kJE = k * j2 + (k * n - k - n) * e2;
  const bound = (b: number, den: number): number => (b > 0.5 ? 1 - (n * e2 + kJE) / den : b);
  const l2 = bound((n * (b2 / G1 - e2)) / (kJE + (n * b2) / G1), kJE + (n * b2) / G1);
  const u2 =
    G2 > 1
      ? bound((n * (b2 - e2 / G2)) / (kJE / G2 + n * b2), kJE + n * G2 * b2)
      : bound((n * (G2 * b2 - e2)) / (kJE + n * G2 * b2), kJE + n * G2 * b2);
  const sb = (r: number): number => (r * k) / (1 + r * (k - 1));
  const p1 = upperP(F1, dfB, dfW);
  const p3 = upperP(F3, dfB, dfE);
  const row = (type: ICCRow["type"], ICCv: number, F: number, df2: number, p: number, lower: number, upper: number): ICCRow => ({
    type,
    name: NAMES[type],
    ICC: ICCv,
    F,
    df1: dfB,
    df2,
    pValue: p,
    lower,
    upper,
  });
  const results = [
    row("ICC1", icc1, F1, dfW, p1, single(F1L), single(F1U)),
    row("ICC2", icc2, F3, dfE, p3, l2, u2),
    row("ICC3", icc3, F3, dfE, p3, single(F3L), single(F3U)),
    row("ICC1k", (b1 - w1) / b1, F1, dfW, p1, average(F1L), average(F1U)),
    row("ICC2k", (b2 - e2) / (b2 + (j2 - e2) / n), F3, dfE, p3, sb(l2), sb(u2)),
    row("ICC3k", (b3 - e3) / b3, F3, dfE, p3, average(F3L), average(F3U)),
  ];
  // each mean square scaled back on its own
  const back = (ms: Scaled): number => ldexpWide(ms.v[0], ms.e);
  return reported("ICC", {
    results,
    MSB: back(MSB),
    MSJ: back(MSJ),
    MSE: back(MSE),
    MSW: back(MSW),
    n,
    k,
    confLevel,
    lmer,
    warnings,
  });
}
