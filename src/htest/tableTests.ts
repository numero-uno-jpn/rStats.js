// Tests and measures of r x c tables: the G-test (DescTools' GTest), the Stuart-Maxwell test (DescTools'
// StuartMaxwellTest), Goodman and Kruskal's gamma (DescTools' GoodmanKruskalGamma), the linear-by-linear association
// test (coin's lbl_test, asymptotic) and the Freeman-Tukey deviates used by chisqTest and gTest.
//
// Written for rStats.js from the published statistics and the packages' documented behaviour (no R or package code;
// oracle/contingency-behaviour.md section 5):
// - G-test (Sokal and Rohlf, Biometry, 3rd ed. 1995, section 17.4; Williams, Biometrika 63, 1976, for the correction
//   q): G = 2 sum x log(x / E) / q, chi-squared with (r - 1)(c - 1) df (k - 1 for goodness of fit). G is summed as the
//   deviance 2 sum (x log(x / E) + E - x), whose terms are nonnegative (bd0, Loader 2000), with E in double-double:
//   sum (E - x) is 0 for a table (exactly, for the unrounded E) and n (sum p - 1) for goodness of fit (added back). The
//   plain sum of x log(x / E) cancels where G is small against the counts. The p-value is the upper tail (DescTools
//   takes 1 - pchisq for a table, 0 below about 1.1e-16; rule 2)
// - Stuart-Maxwell (Stuart, Biometrika 42, 1955; Maxwell, Brit. J. Psychiatry 116, 1970): d' S^-1 d with d the
//   differences of the margins and S their covariance, for all but the last category, after removing the categories
//   without off-diagonal counts; df = K - 1 with K the categories left (choice 11; DescTools keeps the original size)
// - Goodman and Kruskal's gamma (Goodman and Kruskal, JASA 49, 1954) with the non-null asymptotic standard error ASE1
//   (Agresti, Analysis of Ordinal Categorical Data, 2nd ed. 2010, section 7.1)
// - Linear-by-linear association (Agresti, Categorical Data Analysis, 3rd ed. 2013, section 3.4.1; Mantel, JASA 58,
//   1963): Z = sqrt(N - 1) r, r the Pearson correlation of the row and column scores over the N observations, the
//   standardised linear statistic under the permutation (conditional) distribution; scores 1..k for every factor
//   (choice 14: coin codes a two-level factor by an indicator of its first level, which turns the sign, and refuses
//   2 x 2 tables)
// - Freeman-Tukey deviates (Freeman and Tukey, Ann. Math. Statist. 21, 1950; Bishop, Fienberg and Holland, Discrete
//   Multivariate Analysis, 1975, section 14.7): sqrt(O) + sqrt(O + 1) - sqrt(4E + 1), approximately N(0, 1)

