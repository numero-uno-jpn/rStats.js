const G_METHOD = "Log likelihood ratio (G-test)";

/**
 * Log-likelihood ratio (G) test of independence in a contingency table, or of goodness of fit of counts to given
 * probabilities. Equivalent to `DescTools::GTest()` in R.
 *
 * For a table (an array of rows), `G = 2 sum x log(x / E) / q` with `E` the products of the margins over the total and
 * `(r - 1)(c - 1)` degrees of freedom, counting empty rows and columns as DescTools; for a vector (or a table with one
 * row or column), `E = n p` and `k - 1` degrees of freedom. `correct: "williams"` divides by Williams' q
 * (`1 + (n sum 1/R_i - 1)(n sum 1/C_j - 1) / (6 n (r - 1)(c - 1))` for a table, which is infinite with an empty row or
 * column, and `1 + (k + 1) / (6n)` for a vector). `correct: "yates"` moves the counts of a 2 x 2 table by 0.5 toward
 * independence as DescTools does: the off-diagonal cells up and the diagonal down when `x11 x22 - x12 x21 > 0`, and
 * the other way otherwise, also when it is 0 (so that a table of exact independence gets a positive G), and without
 * stopping at 0 (a cell that becomes negative makes G NaN, with the warning "NaNs produced"). For two counts it moves
 * them by 0.5 toward `E` when they differ from it by more than 0.25.
 *
 * The p-value is the upper tail of chi-squared (DescTools computes `1 - pchisq` for a table, which is 0 below about
 * 1e-16). G is summed as a deviance, without the cancellation of the plain sum. The result also has the Freeman-Tukey
 * deviates `ftResiduals`.
 *
 * @param x Counts (nonnegative, finite; not all 0), or a contingency table as an array of rows.
 * @param options See {@link GTestOptions}.
 * @returns The test result, with `statisticName` `"G"`; see {@link GTestResult}.
 * @throws RangeError for negative or non-finite counts, a total of 0, fewer than 2 counts, `p` of the wrong length,
 *   negative or not summing to 1, and `"yates"` for anything but a 2 x 2 table or two counts.
 *
 * @example
 * ```ts
 * gTest([[12, 5], [7, 9]]).statistic;                      // 2.4600430077307167
 * gTest([[12, 5], [7, 9]], { correct: "williams" }).pValue; // 0.12530270793206313
 * gTest([10, 20, 30], { p: [0.2, 0.3, 0.5] }).pValue;      // 0.7527706003419717
 * ```
 *
 * @category Hypothesis tests
 */
export function gTest(x: Counts | readonly Counts[], options: GTestOptions = {}): GTestResult {
  checkOptions(options, G_TEST_KEYS, "gTest"); // generated: option-keys.mjs
  const correct = matchChoice(options.correct, G_CORRECTIONS);
  if (typeof x !== "object" || x === null || typeof x.length !== "number") throw new TypeError("'x' must be an array of counts or of rows");
  if (isMatrix(x)) {
    const rows = matrixOf(x);
    checkCounts(rows.flat());
    // a matrix with one row or column is a vector, as DescTools
    if (rows.length === 1) return reported("gTest", gGoodnessOfFit(rows[0]!, correct, options));
    if (rows[0]!.length === 1) return reported("gTest", gGoodnessOfFit(rows.map((r) => r[0]!), correct, options));
    return reported("gTest", gIndependence(rows, correct));
  }
  const v = Array.from(x as Counts);
  if (v.some((e) => typeof e !== "number")) throw new TypeError("the entries of 'x' must be numbers");
  checkCounts(v);
  return reported("gTest", gGoodnessOfFit(v, correct, options));
}

/** Nonnegative finite counts with a positive total (DescTools' checks) */
function checkCounts(v: readonly number[]): void {
  if (v.some((e) => !(e >= 0 && e < Infinity))) throw new RangeError("all entries of 'x' must be nonnegative and finite");
  if (!v.some((e) => e > 0)) throw new RangeError("at least one entry of 'x' must be positive");
}

/**
 * The power of 2, s, by which counts whose total overflows are divided (0 when it is finite): G is homogeneous of
 * degree 1 in the counts, so it is computed from x 2^-s and multiplied back
 */
function overflowShift(total: number, m: number): number {
  return total < Infinity ? 0 : Math.ceil(Math.log2(m)) + 1;
}

/**
 * sum x log(x / E) as sum bd0(x, E) (x log(x/E) + E - x >= 0), with the cells x < 0 (after Yates' correction) giving
 * NaN and x > 0 with E = 0 Inf
 */
function devianceSum(x: readonly number[], E: readonly DD[]): number {
  // a negative cell first: its log is NaN, which wins over an infinite term in the sum
  if (x.some((o) => o < 0)) return NaN;
  let s: DD = [0, 0];
  for (let i = 0; i < x.length; i++) {
    const o = x[i]!;
    const e = E[i]!;
    if (o > 0 && e[0] === 0) return Infinity;
    s = ddAdd(s, bd0dd(o, e));
  }
  return s[0] + s[1];
}

function gIndependence(x0: number[][], correct: GTestCorrection): GTestResult {
  const nr = x0.length;
  const nc = x0[0]!.length;
  if (correct === "yates" && (nr !== 2 || nc !== 2)) throw new RangeError("Yates' correction requires a 2 x 2 matrix");
  const total = ddSumOf(x0.flat());
  const sh = overflowShift(total[0], nr * nc);
  const xs = sh === 0 ? x0 : x0.map((r) => r.map((v) => ldexp(v, -sh)));
  const n = sh === 0 ? total : ddSumOf(xs.flat());
  const R = xs.map((r) => ddSumOf(r));
  const C = xs[0]!.map((_, j) => ddSumOf(xs.map((r) => r[j]!)));
  // E in double-double: sum E = n exactly in the mathematics, which the deviance form relies on. R (C / n): the product
  // of two margins can overflow where E cannot
  const Edd = R.map((a) => C.map((b) => ddMul(a, ddDiv(b, n))));
  let obs = xs;
  if (correct === "yates") {
    const [[a, b], [c, d]] = xs as [[number, number], [number, number]];
    // as DescTools: the diagonal moves down only when ad - bc > 0; at ad = bc (exact independence) it moves up too,
    // away from independence ([[5, 5], [5, 5]] gets G = 0.2003), and no cell is stopped at 0
    const s = a * d - b * c > 0 ? -0.5 : 0.5;
    const h = ldexp(0.5, -sh);
    const t = s < 0 ? -h : h;
    obs = [
      [a + t, b - t],
      [c - t, d + t],
    ];
  }
  const raw = devianceSum(obs.flat(), Edd.flat());
  const warnings = Number.isNaN(raw) ? ["NaNs produced"] : [];
  let q = 1;
  if (correct === "williams") {
    // n sum 1/R_i and n sum 1/C_j do not depend on the units; 6 n does (with the scaled n, 2^-sh back below)
    const nn = n[0] + n[1];
    const sr = R.reduce((acc, r) => acc + 1 / (r[0] + r[1]), 0);
    const sc = C.reduce((acc, r) => acc + 1 / (r[0] + r[1]), 0);
    q = 1 + ldexp(((nn * sr - 1) * (nn * sc - 1)) / (6 * nn * (nr - 1) * (nc - 1)), -sh);
  }
  const G = ldexp(2 * raw, sh) / q;
  const df = (nr - 1) * (nc - 1);
  const E = Edd.map((r) => r.map((e) => ldexp(e[0] + e[1], sh)));
  const method = `${G_METHOD} test of independence ${correct === "none" ? "without correction" : correct === "williams" ? "with Williams' correction" : "with Yates' correction"}`;
  return {
    method,
    statistic: G,
    statisticName: "G",
    parameter: df,
    // as DescTools
    parameterName: "X-squared df",
    pValue: upperChisq(G, df),
    observed: sh === 0 ? obs : obs.map((r) => r.map((v) => ldexp(v, sh))),
    expected: E,
    ftResiduals: freemanTukeyResiduals(x0, E),
    warnings,
  };
}

function gGoodnessOfFit(x0: number[], correct: GTestCorrection, options: GTestOptions): GTestResult {
  const k = x0.length;
  if (k < 2) throw new RangeError("'x' must have at least 2 elements");
  if (correct === "yates" && k !== 2) throw new RangeError("Yates' correction requires 2 data values");
  const rescale = options.rescaleP ?? false;
  if (typeof rescale !== "boolean") throw new TypeError("'rescaleP' must be a boolean");
  const p = options.p === undefined ? x0.map(() => 1 / k) : Array.from(options.p);
  if (p.length !== k) throw new RangeError("'x' and 'p' must have the same number of elements");
  if (p.some((v) => typeof v !== "number" || Number.isNaN(v))) throw new RangeError("'p' must not contain missing values");
  if (p.some((v) => v < 0)) throw new RangeError("probabilities must be non-negative");
  if (p.some((v) => v === Infinity)) throw new RangeError("probabilities must be finite");
  const pSum = ddSumOf(p);
  if (rescale) {
    if (!(pSum[0] > 0 && pSum[0] < Infinity)) throw new RangeError("the probabilities to rescale must have a positive finite sum");
  } else if (Math.abs(pSum[0] - 1 + pSum[1]) > Math.sqrt(Number.EPSILON)) {
    throw new RangeError("probabilities must sum to 1");
  }
  const total = ddSumOf(x0);
  const sh = overflowShift(total[0], k);
  const xs = sh === 0 ? x0 : x0.map((v) => ldexp(v, -sh));
  const n = sh === 0 ? total : ddSumOf(xs);
  // E = n p (rescaled: n p / sum p) in double-double
  const Edd = p.map((v) => (rescale ? ddDiv(ddMulNum(n, v), pSum) : ddMulNum(n, v)));
  const E = Edd.map((e) => e[0] + e[1]);
  let obs = xs;
  if (correct === "yates") {
    // as DescTools: 0.5 toward E where the first count differs from it by more than 0.25
    const h = ldexp(0.5, -sh);
    const d = xs[0]! - E[0]!;
    if (d > ldexp(0.25, -sh)) obs = [xs[0]! - h, xs[1]! + h];
    else if (-d > ldexp(0.25, -sh)) obs = [xs[0]! + h, xs[1]! - h];
  }
  let raw = devianceSum(obs, Edd);
  // sum x log(x / E) = sum bd0(x, E) - (sum E - n), and sum E - n = n (sum p - 1) unless p is rescaled
  if (!rescale && !Number.isNaN(raw)) {
    const nn = n[0] + n[1];
    raw -= nn * (pSum[0] - 1 + pSum[1]);
  }
  const warnings = Number.isNaN(raw) ? ["NaNs produced"] : [];
  // Williams: 1 + (k + 1) / (6 n), with the n of the counts given
  const q = correct === "williams" ? 1 + (k + 1) / (6 * ldexp(n[0] + n[1], sh)) : 1;
  const G = ldexp(2 * raw, sh) / q;
  const Eout = E.map((e) => ldexp(e, sh));
  return {
    method: `${G_METHOD} goodness of fit test`,
    statistic: G,
    statisticName: "G",
    parameter: k - 1,
    parameterName: "X-squared df",
    pValue: upperChisq(G, k - 1),
    observed: sh === 0 ? obs : obs.map((v) => ldexp(v, sh)),
    expected: Eout,
    ftResiduals: freemanTukeyResiduals(x0, Eout),
    warnings,
  };
}

