/** A square table of nonnegative finite counts with at least two rows */
function squareTable(x: readonly Counts[]): number[][] {
  if (typeof x !== "object" || x === null || !isMatrix(x as readonly Counts[])) {
    throw new RangeError("'x' must be square with at least two rows and columns");
  }
  const t = matrixOf(x);
  const r = t.length;
  if (r < 2 || t[0]!.length !== r) throw new RangeError("'x' must be square with at least two rows and columns");
  if (t.flat().some((v) => !(v >= 0 && v < Infinity))) throw new RangeError("all entries of 'x' must be nonnegative and finite");
  return t;
}

/**
 * Stuart-Maxwell test of marginal homogeneity of a square table (paired classifications into the same categories).
 * Equivalent to `DescTools::StuartMaxwellTest()` in R. The degrees of freedom differ where categories are removed.
 *
 * Categories with no counts off the diagonal (in their row and column) are removed. With the K categories left, `d`
 * the differences of the row and column sums of the first K - 1 and `S` their covariance (`S_ii = r_i + c_i - 2 x_ii`,
 * `S_ij = -(x_ij + x_ji)`), the statistic `d' S^-1 d` is chi-squared with K - 1 degrees of freedom (DescTools keeps the
 * original number of categories less 1). For a 2 x 2 table it is McNemar's statistic without correction.
 *
 * @param table A square table of counts as an array of rows.
 * @returns The test result, with `statisticName` `"chi-squared"`; see {@link StuartMaxwellTestResult}.
 * @throws RangeError for a table that is not square with at least two rows, negative or non-finite counts, fewer
 *   than 2 categories left ("Too many equal marginals, cannot compute") and categories whose off-diagonal counts fall
 *   into unconnected groups (S is then singular).
 *
 * @example
 * ```ts
 * stuartMaxwellTest([[20, 3, 2], [4, 15, 6], [1, 5, 30]]).statistic; // 0.30534351145038163
 * ```
 *
 * @category Hypothesis tests
 */
export function stuartMaxwellTest(table: readonly Counts[]): StuartMaxwellTestResult {
  const t = squareTable(table);
  const r = t.length;
  const rs = t.map((row) => ddSumOf(row));
  const cs = t.map((_, j) => ddSumOf(t.map((row) => row[j]!)));
  // the categories with counts off the diagonal
  const keep = t.map((_, i) => t[i]!.some((v, j) => j !== i && v > 0) || t.some((row, j) => j !== i && row[i]! > 0)).flatMap((k, i) => (k ? [i] : []));
  const K = keep.length;
  if (K < 2) throw new RangeError("Too many equal marginals, cannot compute");
  // S is a reduced graph Laplacian with the weights x_ij + x_ji: positive definite exactly when the categories kept
  // are connected through their off-diagonal counts (R's solve fails for unconnected groups, or gives rounding noise)
  const parent = keep.map((_, a) => a);
  const find = (a: number): number => (parent[a] === a ? a : (parent[a] = find(parent[a]!)));
  for (let a = 0; a < K; a++) {
    for (let b = a + 1; b < K; b++) if (t[keep[a]!]![keep[b]!]! + t[keep[b]!]![keep[a]!]! > 0) parent[find(a)] = find(b);
  }
  if (keep.some((_, a) => find(a) !== find(0))) {
    throw new RangeError("the categories fall into groups without counts between them: the covariance matrix is singular");
  }
  const m = K - 1;
  const d = keep.slice(0, m).map((i) => {
    const v = ddAdd(rs[i]!, [-cs[i]![0], -cs[i]![1]]);
    return v[0] + v[1];
  });
  const S = keep.slice(0, m).map((i) =>
    keep.slice(0, m).map((j) => {
      if (i !== j) return -(t[i]![j]! + t[j]![i]!);
      // the off-diagonal counts of row and column i (r_i + c_i - 2 x_ii without the cancellation)
      let s = 0;
      for (let l = 0; l < r; l++) if (l !== i) s += t[i]![l]! + t[l]![i]!;
      return s;
    }),
  );
  // d' S^-1 d by S = L D L' (S symmetric positive definite): sum z_k^2 / D_k with L z = d. For 2 x 2 this is
  // d^2 / S, McNemar's statistic, to the last bit
  const L = S.map((row) => row.map(() => 0));
  const D: number[] = [];
  for (let j = 0; j < m; j++) {
    let dj = S[j]![j]!;
    for (let k = 0; k < j; k++) dj -= L[j]![k]! * L[j]![k]! * D[k]!;
    D.push(dj);
    for (let i = j + 1; i < m; i++) {
      let v = S[i]![j]!;
      for (let k = 0; k < j; k++) v -= L[i]![k]! * L[j]![k]! * D[k]!;
      L[i]![j] = v / dj;
    }
  }
  let stat = 0;
  const z: number[] = [];
  for (let i = 0; i < m; i++) {
    let v = d[i]!;
    for (let k = 0; k < i; k++) v -= L[i]![k]! * z[k]!;
    z.push(v);
    stat += (v * v) / D[i]!;
  }
  const N = ddSumOf(keep.flatMap((i) => keep.map((j) => t[i]![j]!)));
  const df = K - 1;
  return reported("stuartMaxwellTest", {
    method: "Stuart-Maxwell test",
    statistic: stat,
    statisticName: "chi-squared",
    parameter: df,
    parameterName: "df",
    pValue: upperChisq(stat, df),
    N: N[0] + N[1],
    warnings: [],
  });
}

// ---- Goodman and Kruskal's gamma ----

/**
 * Options for {@link goodmanKruskalGamma}.
 *
 * @category Hypothesis tests
 */
export interface GoodmanKruskalGammaOptions {
  /** Confidence level of `confInt`, in (0, 1). Default `0.95`. */
  confLevel?: number;
}

/**
 * Result of {@link goodmanKruskalGamma}.
 *
 * @category Hypothesis tests
 */
export interface GoodmanKruskalGammaResult {
  /** Gamma, `(C - D) / (C + D)` with C and D the numbers of concordant and discordant pairs (NaN when both are 0). */
  estimate: number;
  /** The Wald interval `gamma -/+ z ase`, clipped to [-1, 1]. */
  confInt: [number, number];
  /** The confidence level of `confInt`. */
  confLevel: number;
  /** The asymptotic standard error ASE1 (not under the null hypothesis). */
  ase: number;
  /** Warnings (none: DescTools gives none either). */
  warnings: string[];
}

/**
 * Goodman and Kruskal's gamma of a table of two ordered classifications, with its asymptotic standard error and a
 * Wald confidence interval. Equivalent to `DescTools::GoodmanKruskalGamma()` in R.
 *
 * `gamma = (C - D) / (C + D)` with C and D the numbers of concordant and discordant pairs. The standard error is the
 * non-null ASE1 (Agresti 2010, section 7.1): `sqrt(sum x psi^2)` with `psi_ij = 2 (D Pc_ij - C Pd_ij) / (C + D)^2`,
 * `Pc_ij` the counts above-left and below-right of cell (i, j) and `Pd_ij` those above-right and below-left. The
 * interval is `[max(-1, gamma - z ase), min(1, gamma + z ase)]`, z the normal quantile of `1 - (1 - confLevel) / 2`.
 * Without concordant or discordant pairs (a table with one row, for example) gamma and the interval are NaN, as
 * DescTools. No test of gamma = 0 is given (it would need the null standard error).
 *
 * @param table A table of counts (nonnegative, finite) as an array of rows; rows and columns in their order.
 * @param options See {@link GoodmanKruskalGammaOptions}.
 * @returns See {@link GoodmanKruskalGammaResult}.
 * @throws RangeError for negative or non-finite counts, or a level outside (0, 1).
 *
 * @example
 * ```ts
 * const g = goodmanKruskalGamma([[10, 5, 2], [3, 8, 6], [1, 4, 9]]);
 * g.estimate; // 0.6703296703296703
 * g.confInt;  // [0.4241347346132843, 0.9165246060460562]
 * ```
 *
 * @category Hypothesis tests
 */
export function goodmanKruskalGamma(table: readonly Counts[], options: GoodmanKruskalGammaOptions = {}): GoodmanKruskalGammaResult {
  checkOptions(options, GOODMAN_KRUSKAL_GAMMA_KEYS, "goodmanKruskalGamma"); // generated: option-keys.mjs
  const confLevel = options.confLevel ?? 0.95;
  if (!(typeof confLevel === "number" && confLevel > 0 && confLevel < 1)) throw new RangeError("'confLevel' must be a single number in (0, 1)");
  const t = countTable(table);
  const { pc, pd } = pairCounts(t);
  let C = 0;
  let D = 0;
  t.forEach((row, i) =>
    row.forEach((v, j) => {
      C += v * pc[i]![j]!;
      D += v * pd[i]![j]!;
    }),
  );
  C /= 2;
  D /= 2;
  const gamma = (C - D) / (C + D);
  // sigma^2 = sum x psi^2 - (sum x psi)^2; the second sum is 0 in the mathematics (and below 1e-30 as DescTools
  // computes it), so it is left out
  const scale = 2 / ((C + D) * (C + D));
  let v2 = 0;
  t.forEach((row, i) =>
    row.forEach((v, j) => {
      const psi = scale * (D * pc[i]![j]! - C * pd[i]![j]!);
      v2 += v * psi * psi;
    }),
  );
  const ase = Math.sqrt(v2);
  const z = qnorm(1 - (1 - confLevel) / 2);
  return reported("goodmanKruskalGamma", {
    estimate: gamma,
    confInt: [Math.max(-1, gamma - z * ase), Math.min(1, gamma + z * ase)] as [number, number],
    confLevel,
    ase,
    warnings: [],
  });
}

/** A table of nonnegative finite counts with at least one row and column */
function countTable(x: readonly Counts[]): number[][] {
  if (typeof x !== "object" || x === null || !isMatrix(x as readonly Counts[])) throw new TypeError("'table' must be an array of rows");
  const t = matrixOf(x);
  if (t[0]!.length === 0) throw new RangeError("'table' must have at least one column");
  if (t.flat().some((v) => !(v >= 0 && v < Infinity))) throw new RangeError("all entries of 'table' must be nonnegative and finite");
  return t;
}

/** For each cell, the counts concordant with it (above-left and below-right) and discordant (above-right, below-left) */
function pairCounts(t: readonly (readonly number[])[]): { pc: number[][]; pd: number[][] } {
  const nr = t.length;
  const nc = t[0]!.length;
  // P[i][j] = sum of t[k][l] for k < i, l < j (prefix sums with a border of zeros)
  const P = Array.from({ length: nr + 1 }, () => new Array<number>(nc + 1).fill(0));
  for (let i = 0; i < nr; i++) {
    for (let j = 0; j < nc; j++) P[i + 1]![j + 1] = t[i]![j]! + P[i]![j + 1]! + P[i + 1]![j]! - P[i]![j]!;
  }
  const rect = (i0: number, i1: number, j0: number, j1: number): number =>
    i1 <= i0 || j1 <= j0 ? 0 : P[i1]![j1]! - P[i0]![j1]! - P[i1]![j0]! + P[i0]![j0]!;
  const pc = t.map((row, i) => row.map((_, j) => rect(0, i, 0, j) + rect(i + 1, nr, j + 1, nc)));
  const pd = t.map((row, i) => row.map((_, j) => rect(0, i, j + 1, nc) + rect(i + 1, nr, 0, j)));
  return { pc, pd };
}

// ---- linear-by-linear association ----

/**
 * Options for {@link lblTest}.
 *
 * @category Hypothesis tests
 */
export interface LblTestOptions {
  /** `"two.sided"` (default), `"less"` (negative association) or `"greater"` (positive association). */
  alternative?: Alternative | (string & {});
  /** Scores of the rows. Default `1, 2, ..., r`. */
  rowScores?: readonly number[];
  /** Scores of the columns. Default `1, 2, ..., c`. */
  colScores?: readonly number[];
}

/**
 * Result of {@link lblTest}.
 *
 * @category Hypothesis tests
 */
export type LblTestResult = HTest;

/**
 * Asymptotic linear-by-linear association test of a table of two ordered classifications (the Mantel test of trend).
 * Equivalent to `coin::lbl_test()` in R. As coin's asymptotic test, except for tables with a two-level factor.
 *
 * `Z = sqrt(N - 1) r`, r the Pearson correlation of the row and column scores over the N observations: the linear
 * statistic `sum x_ij u_i v_j` standardised by its permutation (conditional) mean and variance. The scores are 1..k
 * by default for every factor (the level index; empty rows and columns keep their place). coin leaves a two-level
 * factor unordered and codes it by an indicator of its first level, which turns the sign of Z, and refuses 2 x 2
 * tables; here two-level factors are scored like the others and a 2 x 2 table is tested (Z^2 is then the 'N - 1'
 * chi-squared statistic). p-values from the normal distribution: `"greater"` is positive association.
 *
 * @param table A table of counts (nonnegative, finite) as an array of rows.
 * @param options See {@link LblTestOptions}.
 * @returns The test result, with `statisticName` `"Z"`; see {@link LblTestResult}.
 * @throws RangeError for negative or non-finite counts, a total of at most 1, scores of the wrong length or not
 *   finite, and tables whose row or column scores do not vary over the observations (Z undefined).
 *
 * @example
 * ```ts
 * lblTest([[10, 5, 2], [3, 8, 6], [1, 4, 9]]).statistic; // 3.601652214003794
 * ```
 *
 * @category Hypothesis tests
 */
export function lblTest(table: readonly Counts[], options: LblTestOptions = {}): LblTestResult {
  checkOptions(options, LBL_TEST_KEYS, "lblTest"); // generated: option-keys.mjs
  const alternative = matchAlternative(options.alternative);
  const t = countTable(table);
  const nr = t.length;
  const nc = t[0]!.length;
  const scores = (s: readonly number[] | undefined, k: number, name: string): number[] => {
    if (s === undefined) return Array.from({ length: k }, (_, i) => i + 1);
    const v = Array.from(s);
    if (v.length !== k) throw new RangeError(`'${name}' must have one score for each ${name === "rowScores" ? "row" : "column"}`);
    if (v.some((e) => typeof e !== "number" || !Number.isFinite(e))) throw new RangeError(`'${name}' must be finite numbers`);
    return v;
  };
  const u = scores(options.rowScores, nr, "rowScores");
  const w = scores(options.colScores, nc, "colScores");
  const R = t.map((row) => ddSumOf(row)).map((s) => s[0] + s[1]);
  const C = t[0]!.map((_, j) => ddSumOf(t.map((row) => row[j]!))).map((s) => s[0] + s[1]);
  const N = R.reduce((a, b) => a + b, 0);
  if (!(N > 1)) throw new RangeError("the table must have a total above 1");
  const ubar = R.reduce((a, r, i) => a + r * u[i]!, 0) / N;
  const wbar = C.reduce((a, c, j) => a + c * w[j]!, 0) / N;
  const du = u.map((v) => v - ubar);
  const dw = w.map((v) => v - wbar);
  const Suu = R.reduce((a, r, i) => a + r * du[i]! * du[i]!, 0);
  const Sww = C.reduce((a, c, j) => a + c * dw[j]! * dw[j]!, 0);
  let Suw = 0;
  t.forEach((row, i) => row.forEach((v, j) => (Suw += v * du[i]! * dw[j]!)));
  if (!(Suu > 0 && Sww > 0)) throw new RangeError("the row and column scores must vary over the observations (the variance of the statistic is 0)");
  const r = Suw / Math.sqrt(Suu) / Math.sqrt(Sww);
  const Z = Math.sqrt(N - 1) * r;
  const pValue =
    alternative === "less"
      ? (pnorm(Z) as number)
      : alternative === "greater"
        ? (pnorm(Z, { lowerTail: false }) as number)
        : 2 * (pnorm(-Math.abs(Z)) as number);
  return reported("lblTest", {
    method: "Linear-by-Linear Association Test",
    alternative,
    statistic: Z,
    statisticName: "Z",
    pValue,
    warnings: [],
  });
}
