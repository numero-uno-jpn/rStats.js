/** Double-double sum of doubles */
function ddSumOf(x: readonly number[]): DD {
  let s: DD = [0, 0];
  for (const v of x) s = ddAdd(s, [v, 0]);
  return s;
}

/** A matrix given as an array of rows: copied, with rows of equal length */
function matrixOf(x: readonly Counts[]): number[][] {
  const rows = x.map((r) => {
    if (typeof r !== "object" || r === null || typeof (r as ArrayLike<number>).length !== "number") {
      throw new TypeError("'x' must be an array of numbers or an array of rows");
    }
    return Array.from(r);
  });
  const nc = rows[0]!.length;
  if (rows.some((r) => r.length !== nc)) throw new TypeError("all rows of the matrix must have the same length");
  if (rows.flat().some((v) => typeof v !== "number")) throw new TypeError("the entries of 'x' must be numbers");
  return rows;
}

/** Whether x is a matrix (an array of rows) rather than a vector */
const isMatrix = (x: Counts | readonly Counts[]): x is readonly Counts[] => x.length > 0 && typeof x[0] !== "number";

/** p-value of the upper tail of chi-squared with df degrees of freedom */
const upperChisq = (stat: number, df: number): number => (Number.isNaN(stat) ? NaN : pgamma1(stat, df / 2, 2, false, false));

/**
 * Freeman-Tukey deviate sqrt(O) + sqrt(O + 1) - sqrt(4E + 1) (Bishop, Fienberg and Holland 1975, 14.7). The plain
 * formula cancels for large counts (sqrt(O) + sqrt(O + 1) against sqrt(4E + 1), losing eps sqrt(O) absolute); here it
 * is (a^2 - b^2) / (a + b) with a = sqrt(O) + sqrt(O + 1), b = sqrt(4E + 1) and
 * a^2 - b^2 = 2(O - E) + 2 ((O - E)(O + E) + O) / (sqrt(O (O + 1)) + E), whose rounding is a few eps absolute
 */
export function freemanTukeyDeviate(O: number, E: number): number {
  if (!(O >= 0 && E >= 0 && O < Infinity && E < Infinity)) return NaN;
  const so = Math.sqrt(O);
  const so1 = Math.sqrt(O + 1);
  const den = so * so1 + E;
  // O = E = 0: a = b = 1
  const second = den === 0 ? 0 : ((O - E) * (O + E) + O) / den;
  return (2 * (O - E) + 2 * second) / (so + so1 + Math.sqrt(4 * E + 1));
}

/** Freeman-Tukey deviates of a vector or a table (rows) */
export function freemanTukeyResiduals(O: readonly number[], E: readonly number[]): number[];
export function freemanTukeyResiduals(O: readonly (readonly number[])[], E: readonly (readonly number[])[]): number[][];
export function freemanTukeyResiduals(O: readonly unknown[], E: readonly unknown[]): number[] | number[][] {
  if (O.length > 0 && Array.isArray(O[0])) {
    return (O as number[][]).map((r, i) => r.map((v, j) => freemanTukeyDeviate(v, (E as number[][])[i]![j]!)));
  }
  return (O as number[]).map((v, i) => freemanTukeyDeviate(v, (E as number[])[i]!));
}

