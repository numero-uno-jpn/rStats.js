/**
 * Wilcoxon signed rank and rank sum (Mann-Whitney) tests. Equivalent to R's `wilcox.test()`.
 *
 * With one sample (or `paired: true`) performs the signed rank test; with two samples the
 * rank sum test. The choice between exact and normal-approximation p-values, the
 * Hodges-Lehmann estimates and the confidence intervals follow R 4.6: with ties or zeros the
 * exact test is the conditional test given the mid-ranks, and an exact interval reports the
 * confidence level it achieves. Only `NaN` is dropped; infinite values are kept and ranked (as
 * R actually does). Where R 4.6.2 is wrong, the one-sample conditional interval and small
 * two-sided normal p-values, see docs/differences-from-r.md.
 *
 * @param x Sample.
 * @param y Second sample for a two-sample or paired test. May be omitted, and the options
 *   passed in its place: `wilcoxTest(x, { mu: 1 })`.
 * @param options See {@link WilcoxTestOptions}.
 * @returns The test result; see {@link WilcoxTestResult}.
 *
 * @example
 * ```ts
 * const x = [1.83, 0.50, 1.62, 2.48, 1.68, 1.88, 1.55, 3.06, 1.30];
 * const y = [0.878, 0.647, 0.598, 2.05, 1.06, 1.29, 1.06, 3.14, 1.29];
 * const r = wilcoxTest(x, y, { paired: true, alternative: "greater" });
 * r.statistic; // 40 (V)
 * r.pValue;    // 0.01953125
 * ```
 *
 * There is also a formula form, `wilcoxTest("y ~ g", data, options)` (next overload).
 *
 * @category Hypothesis tests
 */
export function wilcoxTest(x: Sample, y?: Sample | WilcoxTestOptions, options?: WilcoxTestOptions): WilcoxTestResult;
/**
 * Wilcoxon tests from a formula and a data frame. As R's `wilcox.test(formula, data)`: `"y ~ g"` is the
 * rank sum test of the two levels of `g` (the first level is `x`), `"y ~ 1"` the signed rank test and
 * `"Pair(a, b) ~ 1"` the paired test of `a` and `b` (the option `paired` is not allowed). Only the variables of the
 * formula count: the rows where one of them is missing are dropped.
 *
 * @param formula `"y ~ g"`, `"y ~ 1"` or `"Pair(a, b) ~ 1"`.
 * @param data The data frame: an object of columns (`null` or `NaN` for a missing value).
 * @param options See {@link WilcoxTestOptions}.
 */
export function wilcoxTest(formula: string, data: DataFrame, options?: WilcoxTestOptions): WilcoxTestResult;
export function wilcoxTest(
  x: Sample | string,
  y?: Sample | WilcoxTestOptions | DataFrame,
  options: WilcoxTestOptions = {},
): WilcoxTestResult {
  if (typeof x !== "string" && isOptionsObject(y)) checkOptions(y, WILCOX_TEST_KEYS, "wilcoxTest"); // generated: option-keys.mjs
  checkOptions(options, WILCOX_TEST_KEYS, "wilcoxTest"); // generated: option-keys.mjs
  if (typeof x === "string") {
    if (options.paired !== undefined) throw new Error("cannot use 'paired' in formula method");
    const d = twoSampleData(x, y as DataFrame, true);
    if (d.kind === "one") return wilcoxTest(d.x, options);
    return wilcoxTest(d.x, d.y, d.kind === "paired" ? { ...options, paired: true } : options);
  }
  // Also accept the form wilcoxTest(x, { mu: 1 })
  let ys: Sample | undefined;
  if (y !== undefined && !ArrayBuffer.isView(y) && !Array.isArray(y))
    options = y as WilcoxTestOptions;
  else ys = y as Sample | undefined;
  const alternative = matchAlternative(options.alternative);
  const mu = options.mu ?? 0;
  const paired = options.paired ?? false;
  const exact = options.exact ?? null;
  const correct = correctionTerms(options.correct ?? true);
  const confInt = options.confInt ?? false;
  const confLevel = options.confLevel ?? 0.95;
  const tolRoot = options.tolRoot ?? 1e-4;
  if (!Number.isFinite(mu))
    throw new RangeError("mu must be a single finite number");
  if (confInt && !(confLevel > 0 && confLevel < 1)) {
    throw new RangeError(
      "confLevel must be a number strictly between 0 and 1",
    );
  }
  if (paired && ys === undefined)
    throw new TypeError("y is required when paired is true");

  let xs: number[];
  let yv: number[] | undefined;
  if (paired) {
    const [a, b] = completePairs(Array.from(x), Array.from(ys!));
    // Also drop the NaN from Inf - Inf
    xs = dropNaN(a.map((v, i) => v - b[i]!));
  } else {
    xs = dropNaN(Array.from(x));
    if (ys !== undefined) yv = dropNaN(Array.from(ys));
  }
  if (xs.length < 1) throw new Error("not enough (non-missing) 'x' observations");
  if (yv !== undefined && yv.length < 1)
    throw new Error("not enough (non-missing) 'y' observations");

  const ctx: Context = {
    alternative,
    mu,
    correct,
    confInt,
    confLevel,
    tolRoot,
    warnings: new Warnings(),
  };
  return reported("wilcoxTest", yv === undefined ? signedRank(xs, exact, paired, ctx) : rankSum(xs, yv, exact, ctx));
}

interface Context {
  alternative: Alternative;
  mu: number;
  /** R 4.6's correct as a number: -1 none, 0 the continuity correction, 1..3 that plus as many Edgeworth terms */
  correct: number;
  confInt: boolean;
  confLevel: number;
  tolRoot: number;
  /** R's warnings of the call, in R's order */
  warnings: Warnings;
}

/** R 4.6's reading of correct: false -1, true 0, a number 0..3 itself; another number is an error */
function correctionTerms(correct: boolean | number): number {
  if (typeof correct === "boolean") return correct ? 0 : -1;
  if (!(Number.isInteger(correct) && correct >= 0 && correct <= 3)) {
    throw new RangeError("'correct' must be an integer between 0 and 3");
  }
  return correct;
}

/** Continuity correction amount (two-sided: 0.5 in the direction of the statistic's sign) */
function correction(
  z: number,
  alternative: Alternative,
  correct: boolean,
): number {
  if (!correct) return 0;
  if (alternative === "two.sided") return Math.sign(z) * 0.5;
  return alternative === "greater" ? 0.5 : -0.5;
}

/** 10 eps: R's slack in the exact intervals' tail comparisons */
const TAIL_TOL = 10 * Number.EPSILON;

/**
 * p-value from the standardised statistic z and the Edgeworth correction e(z) (0 for none): the lower tail
 * Phi(z) - e phi(z) and the upper tail Phi(-z) + e phi(z), each clamped to [0, 1]
 */
function normalP(z: number, alternative: Alternative, e = 0): number {
  const clamp = (p: number): number => Math.min(1, Math.max(p, 0));
  const lower = (): number => (e === 0 ? pnorm(z) : clamp(pnorm(z) - e * dnorm(z)));
  const upper = (): number => (e === 0 ? pnorm(z, { lowerTail: false }) : clamp(pnorm(z, { lowerTail: false }) + e * dnorm(z)));
  if (alternative === "less") return lower();
  if (alternative === "greater") return upper();
  // R 4.6.2 takes 2 min(F, 1 - F) with 1 - F formed from the lower tail F, which loses the digits of a small upper
  // tail (wilcox.test(1:300, exact = FALSE) gives 0 for 6.1e-51). Its value where 1 - F keeps them (at most 7 bits
  // lost from 1/64 on); the upper tail itself below (docs/differences-from-r.md)
  const F = lower();
  if (F <= 0.5) return 2 * F;
  const G = upper();
  return G >= 1 / 64 ? 2 * (1 - F) : 2 * G;
}

/** He3, He5, He7: the Hermite polynomials of the Edgeworth terms */
function hermite(z: number): [number, number, number] {
  const z2 = z * z;
  return [z * (z2 - 3), z * (z2 * (z2 - 10) + 15), z * (z2 * (z2 * (z2 - 21) + 105) - 105)];
}

/** Edgeworth correction e(z) of the signed rank statistic with n observations (Fellingham and Stoker 1964), k terms */
function edgeworthSignedRank(z: number, n: number, k: number): number {
  const D = n * (n + 1) * (2 * n + 1);
  const c4 = -(3 * n * n + 3 * n - 1) / (10 * D);
  const c6 = (4 * (3 * n ** 4 + 6 * n ** 3 - 3 * n + 1)) / (35 * D * D);
  return edgeworth(z, c4, c6, k);
}

/** Edgeworth correction e(z) of the rank sum statistic with sizes m and n (Fix and Hodges 1955), k terms */
function edgeworthRankSum(z: number, m: number, n: number, k: number): number {
  const N = m + n;
  const mn = m * n;
  const c3 = -(N * (N + 1) - mn) / (20 * mn * (N + 1));
  const c5 =
    (2 * (m ** 4 + n ** 4) + 4 * mn * (m * m + n * n) + 6 * mn * mn + 4 * (m ** 3 + n ** 3) + (7 * mn + N - 1) * N) /
    (210 * mn * mn * (N + 1) ** 2);
  return edgeworth(z, c3, c5, k);
}

function edgeworth(z: number, c1: number, c2: number, k: number): number {
  const [h3, h5, h7] = hermite(z);
  let e = c1 * h3;
  if (k >= 2) e += c2 * h5;
  if (k >= 3) e += ((c1 * c1) / 2) * h7;
  return e;
}

/** Median of an ascending array */
function sortedMedian(s: readonly number[]): number {
  const n = s.length;
  if (n === 0) return NaN;
  const h = Math.floor(n / 2);
  return n % 2 === 1 ? s[h]! : mean([s[h - 1]!, s[h]!]);
}

const ascending = (a: number, b: number): number => a - b;

