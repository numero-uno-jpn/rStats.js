// ---- One-sample / paired (signed rank test) ----

/** Signed rank statistic of x - d (zeros removed): [V - expectation, standard deviation] */
function signedRankStat(x: readonly number[]): [number, number, number] {
  const n = x.length;
  const r = rank(x.map(Math.abs));
  let v = 0;
  for (let i = 0; i < n; i++) if (x[i]! > 0) v += r[i]!;
  let ties = 0;
  for (const t of tieCounts(r)) ties += t * t * t - t;
  const sigma = Math.sqrt((n * (n + 1) * (2 * n + 1)) / 24 - ties / 48);
  return [v, v - (n * (n + 1)) / 4, sigma];
}

function signedRank(
  x0: number[],
  exactOpt: boolean | null,
  paired: boolean,
  ctx: Context,
): WilcoxTestResult {
  const { alternative, mu } = ctx;
  let x = x0.map((v) => v - mu);
  // A finite observation whose difference from mu overflows: the differences in half units (x / 2 - mu / 2). Then
  // abs(mu) >= 2^970, so each half difference is exactly half the rounded difference (a subnormal x / 2 rounds far
  // below the spacing of mu / 2) and the ranks, signs and zeros are those of the differences
  const halved = x.some((v, i) => !Number.isFinite(v) && Number.isFinite(x0[i]!));
  if (halved) x = x0.map((v) => v / 2 - mu / 2);
  const zeroes = x.some((v) => v === 0);
  // R 4.6 counts the zeros in the switch to the normal approximation
  const exact = exactOpt ?? x.length < 50;

  const result = (method: string, V: number, pValue: number): WilcoxTestResult => ({
    method,
    alternative,
    statistic: V,
    statisticName: "V",
    pValue,
    nullValue: mu,
    nullValueName: paired ? "location shift" : "location",
    warnings: ctx.warnings.list,
  });

  if (exact) {
    // Pratt: the zeros take the smallest ranks of |x|, add nothing to V and are not among the scores
    const r = rank(x.map(Math.abs));
    const ties = tieCounts(r).length > 0;
    let V = 0;
    for (let i = 0; i < x.length; i++) if (x[i]! > 0) V += r[i]!;
    const method = "Wilcoxon signed rank exact test";
    if (!ties && !zeroes) {
      const n = x.length;
      const total = (n * (n + 1)) / 2;
      let pValue: number;
      if (alternative === "less") pValue = psignrank1(V, n, true, false);
      else if (alternative === "greater") pValue = psignrank1(V - 1, n, false, false);
      else {
        const p = V > total / 2 ? psignrank1(V - 1, n, false, false) : psignrank1(V, n, true, false);
        pValue = Math.min(1, 2 * p);
      }
      const out = result(method, V, pValue);
      return ctx.confInt ? { ...out, ...signedRankExactCI(x0, ctx) } : out;
    }
    const scores = r.filter((_, i) => x[i] !== 0);
    checkedCost(signedScoreCost(scores), "distribution");
    const dist = signedScoreDistribution(scores);
    let pValue: number;
    if (alternative === "less") pValue = lowerTail(dist, V);
    else if (alternative === "greater") pValue = upperTail(dist, V - 0.25);
    else {
      let centre = 0;
      for (const s of scores) centre += s / 2;
      pValue = Math.min(1, 2 * (V > centre ? upperTail(dist, V - 0.25) : lowerTail(dist, V)));
    }
    const out = result(method, V, pValue);
    return ctx.confInt ? { ...out, ...signedRankConditionalCI(x0, ctx) } : out;
  }

  // Normal approximation: the zeros are dropped first (Wilcoxon), as in R
  const nonzero = zeroes ? x.filter((v) => v !== 0) : x;
  const n = nonzero.length;
  // only zero differences: nothing to rank (R returns a p-value of NaN)
  if (n === 0) throw new RangeError("no non-zero differences for the signed rank test");
  const [V, dz, sigma] = signedRankStat(nonzero);
  const ties = tieCounts(rank(nonzero.map(Math.abs))).length > 0;
  // the Edgeworth terms only without ties and zeros (R)
  const terms = ties || zeroes ? Math.min(ctx.correct, 0) : ctx.correct;
  const z = (dz - correction(dz, alternative, terms >= 0)) / sigma;
  const pValue = normalP(z, alternative, terms >= 1 ? edgeworthSignedRank(z, n, terms) : 0);
  const out = result(`Wilcoxon signed rank test${ctx.correct >= 0 ? " with continuity correction" : ""}`, V, pValue);
  if (!ctx.confInt) return out;
  // R 4.6 searches the interval on the observations themselves, the values equal to mu included (R 4.5 searched
  // x - mu without its zeros and added mu back, which lost the observations where mu dwarfs them, #502)
  return { ...out, ...signedRankNormalCI(x0, ctx) };
}

/** The interval part of the result */
interface CIPart {
  confInt: [number, number];
  confLevel: number;
  estimate?: number;
  estimateNames?: string;
}

/** Interval with the given finite ends, the other end(s) open according to the alternative */
function shape(alternative: Alternative, lower: number, upper: number): [number, number] {
  if (alternative === "less") return [-Infinity, upper];
  if (alternative === "greater") return [lower, Infinity];
  return [lower, upper];
}

/** Interval when no interval can be formed: the bounded end(s) are NaN and the confidence level 0 */
function noInterval(alternative: Alternative, estimate: number, estimateNames?: string): CIPart {
  const out: CIPart = { confInt: shape(alternative, NaN, NaN), confLevel: 0, estimate };
  if (estimateNames !== undefined) out.estimateNames = estimateNames;
  return out;
}

function checkTolRoot(tol: number): void {
  if (!(tol > 0 && tol < Infinity)) throw new RangeError("tolRoot must be a positive finite number");
}

/** Sorted Walsh averages (x_i + x_j) / 2, i <= j (NaN, from -Inf and Inf, left out as R's sort does) */
function walshAverages(x: readonly number[]): number[] {
  const n = x.length;
  const walsh: number[] = [];
  for (let i = 0; i < n; i++) {
    for (let j = i; j < n; j++) {
      const w = midpoint(x[i]!, x[j]!);
      if (!Number.isNaN(w)) walsh.push(w);
    }
  }
  return walsh.sort(ascending);
}

/**
 * Exact interval from order statistics (Bauer 1972), as R 4.6: q is the lower a'-quantile of the statistic, raised by
 * one where its tail is within 10 eps of a' (so that the excluded tail is at most a'); q = 0 gives (-Inf, Inf) with
 * level 1 for every alternative. The level reported is the achieved one
 */
function orderStatisticCI(
  sorted: readonly number[],
  cdf: (q: number) => number,
  quantile: (p: number) => number,
  ctx: Context,
  estimateNames: string,
): CIPart {
  const { alternative, confLevel } = ctx;
  const K = sorted.length;
  const a = alternative === "two.sided" ? (1 - confLevel) / 2 : 1 - confLevel;
  let q = quantile(a);
  if (cdf(q) <= a + TAIL_TOL) q++;
  const estimate = sortedMedian(sorted);
  if (q === 0) return { confInt: [-Infinity, Infinity], confLevel: 1, estimate, estimateNames };
  const tail = cdf(q - 1);
  return {
    confInt: shape(alternative, sorted[q - 1]!, sorted[K - q]!),
    confLevel: 1 - (alternative === "two.sided" ? 2 * tail : tail),
    estimate,
    estimateNames,
  };
}

/** Classical exact interval: order statistics of the Walsh averages; the estimate their median (Hodges-Lehmann) */
function signedRankExactCI(x: readonly number[], ctx: Context): CIPart {
  const n = x.length;
  return orderStatisticCI(
    walshAverages(x),
    (q) => psignrank1(q, n, true, false),
    (p) => qsignrank1(p, n, true, false),
    ctx,
    "(pseudo)median",
  );
}

/** Statistic, scores and the key of their multiset (for the cache of distributions) of the shifted data at a shift t */
interface Shifted {
  stat: number;
  scores: number[];
  key: string;
}

/**
 * Mid-ranks of v (no NaN) and a key of their multiset: the runs of ties in sorted order (the mid-ranks follow from
 * them). From a native sort and binary searches, as the interval's scan does this at every shift
 */
function ranksAndKey(v: readonly number[]): { ranks: number[]; key: string } {
  const n = v.length;
  const sorted = Float64Array.from(v).sort();
  const ranks = new Array<number>(n);
  for (let i = 0; i < n; i++) {
    const a = v[i]!;
    let lo = 0;
    let hi = n;
    while (lo < hi) {
      const m = (lo + hi) >>> 1;
      if (sorted[m]! < a) lo = m + 1;
      else hi = m;
    }
    let up = lo;
    hi = n;
    while (up < hi) {
      const m = (up + hi) >>> 1;
      if (sorted[m]! <= a) up = m + 1;
      else hi = m;
    }
    ranks[i] = (lo + 1 + up) / 2;
  }
  let key = "";
  for (let i = 0; i < n; ) {
    let j = i;
    while (j + 1 < n && sorted[j + 1] === sorted[i]) j++;
    if (j > i) key += `${i}:${j - i + 1},`;
    i = j + 1;
  }
  return { ranks, key };
}

/**
 * Exact conditional interval (ties or zeros): the conditional test inverted at the midpoints between consecutive
 * sorted Walsh averages (differences) A_1 <= ... <= A_K, as R 4.6. The lower end is the first A_k whose following
 * midpoint has upperP > a' + 10 eps (-Inf where already A_1 - 1 has), with the tail of the last rejected point; the
 * upper end likewise from the top with lowerP. The distribution is rebuilt for each multiset of scores (cached).
 *
 * An end at A_1 (A_K) is reported with the tail rejected there, at A_1 - 1 (A_K + 1). R 4.6.2 reports 0, which overstates
 * the level (wilcox.test(c(1, 2, 3), c(3, 4, 5), conf.int = TRUE, alternative = "greater", conf.level = 0.92) gives
 * level 1 where 0.95 is achieved; docs/differences-from-r.md)
 */
function conditionalCI(
  A: readonly number[],
  at: (t: number) => Shifted,
  distribution: (scores: number[]) => ScoreDistribution,
  cost: (scores: number[]) => number,
  upperP: (d: ScoreDistribution, stat: number) => number,
  lowerP: (d: ScoreDistribution, stat: number) => number,
  scale: { mean: number; sd: number },
  nScores: number,
  ctx: Context,
  estimateNames: string,
): CIPart {
  const { alternative, confLevel } = ctx;
  const K = A.length;
  const a = alternative === "two.sided" ? (1 - confLevel) / 2 : 1 - confLevel;
  const a2 = a + TAIL_TOL;
  const doLower = alternative !== "less";
  const doUpper = alternative !== "greater";
  const mid = (k: number): number => midpoint(A[k - 1]!, A[k]!);

  // The shifts the scan will try, as far as it is likely to go (the scan stops near the a'-quantile of the
  // statistic; a normal estimate plus a margin), evaluated first to check the time limit before starting: a
  // distribution is built for each change of the multiset of scores, a few kept at once. Their statistics and keys
  // are kept for the scan
  const reach = Math.min(K - 1, Math.max(1, Math.ceil(scale.mean + qnorm(Math.min(a2, 1)) * scale.sd + 0.1 * scale.sd + 3)));
  const CACHE = 8;
  // shifts: the outer point, then the midpoints from that end (index 0 .. reach)
  const lowerShift = (i: number): number => (i === 0 ? A[0]! - 1 : mid(i));
  const upperShift = (i: number): number => (i === 0 ? A[K - 1]! + 1 : mid(K - i));
  const planned: [Map<number, [number, string]>, Map<number, [number, string]>] = [new Map(), new Map()];
  {
    const seen = new Map<string, true>();
    let steps = 0;
    const evalSteps = EVAL_STEPS * nScores;
    for (const [side, shift] of [[0, lowerShift], [1, upperShift]] as const) {
      if (side === 0 ? !doLower : !doUpper) continue;
      for (let i = 0; i <= reach; i++) {
        steps += evalSteps;
        if (steps > MAX_EXACT_STEPS) throw tooLarge("interval");
        let s: Shifted;
        try {
          s = at(shift(i));
        } catch {
          // an undefined shift (infinite data): the scan may stop before it, as R's (which stops at it otherwise)
          break;
        }
        planned[side].set(i, [s.stat, s.key]);
        if (seen.has(s.key)) {
          seen.delete(s.key);
          seen.set(s.key, true);
          continue;
        }
        steps += cost(s.scores);
        if (steps > MAX_EXACT_STEPS) throw tooLarge("interval");
        seen.set(s.key, true);
        if (seen.size > CACHE) seen.delete(seen.keys().next().value!);
      }
    }
  }

  const cache = new Map<string, ScoreDistribution>();
  /** The statistic and its distribution at the i-th shift from one end */
  const evaluate = (side: 0 | 1, i: number): [number, ScoreDistribution] => {
    const t = side === 0 ? lowerShift(i) : upperShift(i);
    let p = planned[side].get(i);
    let scores: number[] | undefined;
    if (p === undefined) {
      const s = at(t);
      p = [s.stat, s.key];
      scores = s.scores;
    }
    const [stat, key] = p;
    let d = cache.get(key);
    if (d !== undefined) cache.delete(key);
    else {
      d = distribution(scores ?? at(t).scores);
      if (cache.size >= CACHE) cache.delete(cache.keys().next().value!);
    }
    cache.set(key, d);
    return [stat, d];
  };
  const upperAt = (i: number): number => {
    const [stat, d] = evaluate(0, i);
    return upperP(d, stat);
  };
  const lowerAt = (i: number): number => {
    const [stat, d] = evaluate(1, i);
    return lowerP(d, stat);
  };

  let lower = -Infinity;
  let lowerTailP = 0;
  if (doLower) {
    const p0 = upperAt(0);
    if (!(p0 > a2)) {
      let prev = p0;
      let k = 1;
      for (; k <= K - 1; k++) {
        const p = upperAt(k);
        if (p > a2) break;
        prev = p;
      }
      lower = A[k - 1]!;
      lowerTailP = prev;
    }
  }
  let upper = Infinity;
  let upperTailP = 0;
  if (doUpper) {
    const p0 = lowerAt(0);
    if (!(p0 > a2)) {
      let prev = p0;
      let k = K - 1;
      for (; k >= 1; k--) {
        const p = lowerAt(K - k);
        if (p > a2) break;
        prev = p;
      }
      upper = A[k]!;
      upperTailP = prev;
    }
  }
  return {
    confInt: [lower, upper],
    confLevel: 1 - (lowerTailP + upperTailP),
    estimate: sortedMedian(A),
    estimateNames,
  };
}

/**
 * e = x - t, in half units where a finite difference overflows; an error where one is NaN (Inf - Inf at an infinite
 * shift: R's statistic is then NA and R stops with "missing value where TRUE/FALSE needed")
 */
function shiftedValues(x: readonly number[], t: number): number[] {
  let e = x.map((v) => v - t);
  if (e.some((v) => Number.isNaN(v))) {
    throw new Error("cannot compute the exact confidence interval: the shifted data have undefined values (infinite observations)");
  }
  if (Number.isFinite(t) && e.some((v, i) => !Number.isFinite(v) && Number.isFinite(x[i]!))) e = x.map((v) => v / 2 - t / 2);
  return e;
}

/**
 * Exact conditional interval of the signed rank test (ties or zeros), from all observations (values equal to mu
 * included). At a shift t the ranks of |x - t| over all n values are the scores (a value equal to t keeps its score
 * and has a random sign), and v(t) is the sum over x - t > 0.
 *
 * R 4.6.2 rejects at the lower end where P(V > v) <= a' (a strict tail, where its two-sample interval uses
 * P(W >= w)), which puts the lower end one Walsh average too high (for data without ties above the classical
 * interval, at the same reported level) and never at -Inf. Here the lower end uses P(V >= v), and the tails reported
 * for ends at A_1 or A_K are those rejected there (as for two samples, conditionalCI): the classical interval for data without ties, at the level it
 * achieves (docs/differences-from-r.md)
 */
function signedRankConditionalCI(x: readonly number[], ctx: Context): CIPart {
  const n = x.length;
  const at = (t: number): Shifted => {
    const e = shiftedValues(x, t);
    const { ranks, key } = ranksAndKey(e.map(Math.abs));
    let v = 0;
    for (let i = 0; i < n; i++) if (e[i]! > 0) v += ranks[i]!;
    return { stat: v, scores: ranks, key };
  };
  const K = (n * (n + 1)) / 2;
  return conditionalCI(
    walshAverages(x),
    at,
    signedScoreDistribution,
    (s) => checkedCost(signedScoreCost(s), "interval"),
    (d, v) => upperTail(d, v - 0.25),
    lowerTail,
    { mean: K / 2, sd: Math.sqrt((n * (n + 1) * (2 * n + 1)) / 24) },
    n,
    ctx,
    "(pseudo)median",
  );
}

/**
 * Normal-approximation interval: the shifts d at which the standardised signed rank statistic of x - d crosses the
 * normal quantiles, and the estimate where it crosses 0 (found with uniroot, tolerance tolRoot)
 */
function signedRankNormalCI(x: readonly number[], ctx: Context): CIPart {
  const { alternative, confLevel, tolRoot } = ctx;
  const correct = ctx.correct >= 0;
  const n = x.length;
  if (n === 0) return noInterval(alternative, NaN);
  const lo = minOf(x);
  const hi = maxOf(x);
  if (!Number.isFinite(lo) || !Number.isFinite(hi) || n === 1 || lo === hi) {
    // R's statistic of x - lo has no non-zero values when all observations are equal (n = 1 included)
    if (Number.isFinite(lo) && lo === hi) ctx.warnings.add("cannot compute confidence interval when all observations are zero or tied");
    return noInterval(alternative, midpoint(lo, hi), "midrange");
  }
  const stat = (d: number, corr: boolean): number => {
    const [, centre, sigma] = signedRankStat(x.map((v) => v - d).filter((v) => v !== 0));
    return (centre - correction(centre, alternative, corr)) / sigma;
  };
  const sLo = stat(lo, correct);
  const sHi = stat(hi, correct);
  const zUpper = (p: number): number => -qnorm(p);
  const reachable = (a: number): boolean => {
    if (alternative === "greater") return !(sLo < zUpper(a));
    if (alternative === "less") return !(sHi > qnorm(a / 2));
    return !(sLo < zUpper(a / 2)) && !(sHi > qnorm(a / 2));
  };
  let a = 1 - confLevel;
  let enlarged = false;
  while (!reachable(a) && a < 1) {
    a *= 2;
    enlarged = true;
  }
  if (enlarged) ctx.warnings.add("requested conf.level not achievable");
  checkTolRoot(tolRoot);
  const crossing = (z: number): number =>
    uniroot((d) => stat(d, correct) - z, lo, hi, { tol: tolRoot, fLower: sLo - z, fUpper: sHi - z });
  let confInt: [number, number];
  if (a >= 1) {
    const med = sortedMedian([...x].sort(ascending));
    confInt = shape(alternative, med, med);
  } else if (alternative === "greater") confInt = [crossing(zUpper(a)), Infinity];
  else if (alternative === "less") confInt = [-Infinity, crossing(qnorm(a))];
  else confInt = [crossing(zUpper(a / 2)), crossing(qnorm(a / 2))];
  const estimate = uniroot((d) => stat(d, false), lo, hi, {
    tol: tolRoot,
    fLower: stat(lo, false),
    fUpper: stat(hi, false),
  });
  return {
    confInt,
    confLevel: enlarged ? 1 - Math.min(1, a) : confLevel,
    estimate,
    estimateNames: "(pseudo)median",
  };
}

// ---- Two-sample (rank sum test) ----

/** Rank sum statistic from the pooled mid-ranks r (x first): [W, W - expectation, standard deviation, ties] */
function rankSumFromRanks(r: readonly number[], nx: number): [number, number, number, boolean] {
  const N = r.length;
  const ny = N - nx;
  let s = 0;
  for (let i = 0; i < nx; i++) s += r[i]!;
  const W = s - (nx * (nx + 1)) / 2;
  let ties = 0;
  for (const t of tieCounts(r)) ties += t * t * t - t;
  const sigma = Math.sqrt(((nx * ny) / 12) * (N + 1 - ties / (N * (N - 1))));
  return [W, W - (nx * ny) / 2, sigma, ties > 0];
}

/** Rank sum statistic of x - d and y: [W, W - expectation, standard deviation] */
function rankSumStat(
  x: readonly number[],
  y: readonly number[],
): [number, number, number] {
  const [W, dz, sigma] = rankSumFromRanks(rank([...x, ...y]), x.length);
  return [W, dz, sigma];
}

/**
 * Pooled mid-ranks of x_i - d given in half units h_i = x_i / 2 - d / 2 (used where a finite x_i - d overflows, so
 * abs(d) >= 2^970) and y. y stays in its own units: h_i is compared with y_j / 2, which is exact except for a
 * subnormal y_j, and there h_i is 0 (compared with y_j itself) or of magnitude above 2^900, so the order is that of
 * the differences. Halving y would merge neighbouring subnormals
 */
function pooledRanksHalf(h: readonly number[], y: readonly number[]): number[] {
  const nx = h.length;
  const N = nx + y.length;
  // sign of 2 h - v (h in half units, v in units)
  const cmpHalf = (hv: number, v: number): number => {
    const w = hv === 0 || !Number.isFinite(hv) || !Number.isFinite(v) ? v : v / 2;
    return hv < w ? -1 : hv > w ? 1 : 0;
  };
  const cmp = (a: number, b: number): number => {
    if (a < nx && b < nx) return h[a]! < h[b]! ? -1 : h[a]! > h[b]! ? 1 : 0;
    if (a >= nx && b >= nx) return y[a - nx]! < y[b - nx]! ? -1 : y[a - nx]! > y[b - nx]! ? 1 : 0;
    return a < nx ? cmpHalf(h[a]!, y[b - nx]!) : -cmpHalf(h[b]!, y[a - nx]!);
  };
  const idx = Array.from({ length: N }, (_, i) => i);
  idx.sort((a, b) => cmp(a, b) || a - b);
  const r = new Array<number>(N);
  let i = 0;
  while (i < N) {
    let j = i;
    while (j + 1 < N && cmp(idx[j + 1]!, idx[i]!) === 0) j++;
    const avg = (i + j + 2) / 2;
    for (let k = i; k <= j; k++) r[idx[k]!] = avg;
    i = j + 1;
  }
  return r;
}

/**
 * Pooled mid-ranks of (x - d, y), in half units where a finite x_i - d overflows. An x_i - d that is NaN (Inf - Inf,
 * at an infinite shift of the conditional interval's search) is ranked after all others, in order, as R's rank does
 * there (na.last = TRUE)
 */
function pooledRanks(x: readonly number[], y: readonly number[], d: number): number[] {
  return pooledRanksAndKey(x, y, d).ranks;
}

/** pooledRanks with the key of their multiset (ranksAndKey's, or the sorted ranks on the rare paths) */
function pooledRanksAndKey(x: readonly number[], y: readonly number[], d: number): { ranks: number[]; key: string } {
  const e = x.map((v) => v - d);
  if (e.some((v) => Number.isNaN(v))) {
    const keep = e.map((v, i) => [v, i] as const).filter(([v]) => !Number.isNaN(v));
    const rk = rank([...keep.map(([v]) => v), ...y]);
    const r = new Array<number>(x.length + y.length);
    keep.forEach(([, i], k) => (r[i] = rk[k]!));
    y.forEach((_, j) => (r[x.length + j] = rk[keep.length + j]!));
    let next = keep.length + y.length;
    e.forEach((v, i) => {
      if (Number.isNaN(v)) r[i] = ++next;
    });
    return { ranks: r, key: scoreKey(r) };
  }
  if (Number.isFinite(d) && e.some((v, i) => !Number.isFinite(v) && Number.isFinite(x[i]!))) {
    const r = pooledRanksHalf(x.map((v) => v / 2 - d / 2), y);
    return { ranks: r, key: scoreKey(r) };
  }
  return ranksAndKey([...e, ...y]);
}

function rankSum(
  x: number[],
  y: number[],
  exactOpt: boolean | null,
  ctx: Context,
): WilcoxTestResult {
  const { alternative, mu } = ctx;
  const nx = x.length;
  const ny = y.length;
  const exact = exactOpt ?? (nx < 50 && ny < 50);
  const r = pooledRanks(x, y, mu);
  const [W, dz, sigma, ties] = rankSumFromRanks(r, nx);

  let pValue: number;
  let method: string;
  if (exact) {
    method = "Wilcoxon rank sum exact test";
    if (!ties) {
      pValue = rankSumExact(() => {
        if (alternative === "less") return pwilcox1(W, nx, ny, true, false);
        if (alternative === "greater") return pwilcox1(W - 1, nx, ny, false, false);
        // R 4.6: both tails, not the one on the side of the statistic
        return Math.min(2 * pwilcox1(W, nx, ny, true, false), 2 * pwilcox1(W - 1, nx, ny, false, false), 1);
      });
    } else {
      checkedCost(rankSumScoreCost(r, nx), "distribution");
      const dist = rankSumScoreDistribution(r, nx);
      if (alternative === "less") pValue = lowerTail(dist, W);
      else if (alternative === "greater") pValue = upperTail(dist, W - 0.25);
      else pValue = Math.min(2 * lowerTail(dist, W), 2 * upperTail(dist, W - 0.25), 1);
    }
  } else {
    method = `Wilcoxon rank sum test${ctx.correct >= 0 ? " with continuity correction" : ""}`;
    // the Edgeworth terms only without ties (R)
    const terms = ties ? Math.min(ctx.correct, 0) : ctx.correct;
    // all values tied: W always equals its expectation, so p = 1 (R: 0 / 0 = NaN, also R 4.6 with exact = FALSE; its
    // exact conditional test, the default for small samples, gives 1 too)
    const allTied = r.every((v) => v === r[0]);
    const z = (dz - correction(dz, alternative, terms >= 0)) / sigma;
    pValue = allTied ? 1 : normalP(z, alternative, terms >= 1 ? edgeworthRankSum(z, nx, ny, terms) : 0);
  }

  const result: WilcoxTestResult = {
    method,
    alternative,
    statistic: W,
    statisticName: "W",
    pValue,
    nullValue: mu,
    nullValueName: "location shift",
    warnings: ctx.warnings.list,
  };
  if (!ctx.confInt) return result;
  const ci = !exact
    ? rankSumNormalCI(x, y, ctx)
    : ties
      ? rankSumConditionalCI(x, y, ctx)
      : rankSumExact(() => rankSumExactCI(x, y, ctx));
  return { ...result, ...ci };
}

/**
 * f, with the RangeErrors of the exact distribution (a table too large or too long to build, or inaccurate near the
 * center of large samples) pointing to exact: false
 */
function rankSumExact<T>(f: () => T): T {
  try {
    return f();
  } catch (e) {
    if (e instanceof RangeError && e.message.startsWith("wilcox:")) throw new RangeError(`${e.message}: use exact: false`);
    throw e;
  }
}

/** Sorted differences x_i - y_j */
function differences(x: readonly number[], y: readonly number[], dropNaN: boolean): number[] {
  const diffs: number[] = [];
  for (const xi of x) {
    for (const yj of y) {
      const d = xi - yj;
      if (!(dropNaN && Number.isNaN(d))) diffs.push(d);
    }
  }
  return diffs.sort(ascending);
}

/** Classical exact interval from the order statistics of the differences x_i - y_j; the estimate their median */
function rankSumExactCI(x: readonly number[], y: readonly number[], ctx: Context): CIPart {
  const nx = x.length;
  const ny = y.length;
  return orderStatisticCI(
    differences(x, y, false),
    (q) => pwilcox1(q, nx, ny, true, false),
    (p) => qwilcox1(p, nx, ny, true, false),
    ctx,
    "difference in location",
  );
}

/**
 * Exact conditional interval of the rank sum test (ties), as R 4.6: at a shift t the pooled mid-ranks of (x - t, y)
 * are the scores and w(t) the statistic; the lower end from P(W >= w), the upper from P(W <= w). An end at the first
 * or last difference with the tail rejected there, where R 4.6.2 reports 0 (see conditionalCI)
 */
function rankSumConditionalCI(x: readonly number[], y: readonly number[], ctx: Context): CIPart {
  const nx = x.length;
  const ny = y.length;
  const at = (t: number): Shifted => {
    const { ranks, key } = pooledRanksAndKey(x, y, t);
    let w = 0;
    for (let i = 0; i < nx; i++) w += ranks[i]!;
    return { stat: w - (nx * (nx + 1)) / 2, scores: ranks, key };
  };
  return conditionalCI(
    differences(x, y, true),
    at,
    (s) => rankSumScoreDistribution(s, nx),
    (s) => checkedCost(rankSumScoreCost(s, nx), "interval"),
    (d, w) => upperTail(d, w - 0.25),
    lowerTail,
    { mean: (nx * ny) / 2, sd: Math.sqrt((nx * ny * (nx + ny + 1)) / 12) },
    nx + ny,
    ctx,
    "difference in location",
  );
}

/**
 * Normal-approximation interval: the shifts d at which the standardised rank sum statistic of (x - d, y) crosses the
 * normal quantiles (clamped to the range of the differences), and the estimate where it crosses 0
 */
function rankSumNormalCI(x: readonly number[], y: readonly number[], ctx: Context): CIPart {
  const { alternative, confLevel, tolRoot } = ctx;
  const correct = ctx.correct >= 0;
  const lo = minOf(x) - maxOf(y);
  const hi = maxOf(x) - minOf(y);
  if (!Number.isFinite(lo) || !Number.isFinite(hi)) {
    throw new Error("cannot compute the confidence interval because the differences are not finite");
  }
  const stat = (d: number, corr: boolean): number => {
    const [, centre, sigma] = rankSumStat(
      x.map((v) => v - d),
      y,
    );
    return (centre - correction(centre, alternative, corr)) / sigma;
  };
  const crossing = (z: number, corr: boolean): number => {
    const fLo = stat(lo, corr) - z;
    const fHi = stat(hi, corr) - z;
    if (Number.isNaN(fLo) || Number.isNaN(fHi)) {
      throw new Error("cannot compute the confidence interval because all observations are tied");
    }
    if (fLo <= 0) return lo;
    if (fHi >= 0) return hi;
    checkTolRoot(tolRoot);
    return uniroot((d) => stat(d, corr) - z, lo, hi, { tol: tolRoot, fLower: fLo, fUpper: fHi });
  };
  const a = 1 - confLevel;
  let confInt: [number, number];
  if (alternative === "greater") confInt = [crossing(-qnorm(a), correct), Infinity];
  else if (alternative === "less") confInt = [-Infinity, crossing(qnorm(a), correct)];
  else confInt = [crossing(-qnorm(a / 2), correct), crossing(qnorm(a / 2), correct)];
  return {
    confInt,
    confLevel,
    estimate: crossing(0, false),
    estimateNames: "difference in location",
  };
}
