/** The placements of the cases (V10, in the order of the cases) and of the controls (V01) */
function placements(curve: RocResult): { v10: number[]; v01: number[] } {
  const c = Float64Array.from(curve.controls).sort();
  const k = Float64Array.from(curve.cases).sort();
  const n = c.length;
  const m = k.length;
  // the number of values of s below v, and of those equal to v
  const split = (s: Float64Array, v: number): [number, number] => {
    let lo = 0;
    let hi = s.length;
    while (lo < hi) {
      const mid = (lo + hi) >> 1;
      if (s[mid]! < v) lo = mid + 1;
      else hi = mid;
    }
    let end = lo;
    while (end < s.length && s[end] === v) end++;
    return [lo, end - lo];
  };
  const lt = curve.direction === "<";
  const v10 = curve.cases.map((x) => {
    const [below, eq] = split(c, x);
    return (2 * (lt ? below : n - below - eq) + eq) / (2 * n);
  });
  const v01 = curve.controls.map((y) => {
    const [below, eq] = split(k, y);
    return (2 * (lt ? m - below - eq : below) + eq) / (2 * m);
  });
  return { v10, v01 };
}

/** DeLong's variance of the AUC, S = var(V10)/m + var(V01)/n */
function delongVariance(curve: RocResult): number {
  const { v10, v01 } = placements(curve);
  return variance(v10) / v10.length + variance(v01) / v01.length;
}

/** Whether the curve is perfect (AUC 1: a point with sensitivity and specificity 1) */
const isPerfect = (curve: RocResult): boolean => curve.sensitivities.some((s, i) => s === 1 && curve.specificities[i] === 1);

/** At least two observations in each class, for DeLong's variance and the stratified bootstrap */
function requireTwoPerClass(curve: RocResult, what: string): void {
  if (curve.controls.length < 2 || curve.cases.length < 2) {
    throw new Error(`${what} needs at least 2 controls and 2 cases`);
  }
}

/** z = qnorm(1 - alpha/2), from the upper tail for alpha/2 below 1e-8 (rule 10) */
function zOf(confLevel: number): number {
  const a2 = (1 - confLevel) / 2;
  return a2 < 1e-8 ? qnorm(a2, { lowerTail: false }) : qnorm(1 - a2);
}

function checkBootN(bootN: number): void {
  if (!(Number.isInteger(bootN) && bootN >= 1 && bootN <= 2 ** 24)) throw new RangeError("bootN must be an integer from 1 to 2^24");
}

/** R's sample(x, replace = TRUE) of a vector of length > 1: x[i] for size draws of R_unif_index(length) */
function resample<T>(x: readonly T[]): T[] {
  const out = new Array<T>(x.length);
  for (let i = 0; i < x.length; i++) out[i] = x[unifIndex(x.length)]!;
  return out;
}

/** The observations of a curve in their order: values and classes (c(controls, cases) without its data) */
function observations(curve: RocResult): { values: number[]; isCase: boolean[] } {
  const d = rocData(curve);
  if (d !== undefined) return { values: d.values, isCase: d.isCase };
  const values = [...curve.controls, ...curve.cases];
  return { values, isCase: values.map((_, i) => i >= curve.controls.length) };
}

/** The AUC of a non-stratified resample of the observations (NaN when a class is empty) */
function resampledAuc(values: readonly number[], isCase: readonly boolean[], idx: readonly number[], direction: RocDirection): number {
  const controls: number[] = [];
  const cases: number[] = [];
  for (const i of idx) (isCase[i] ? cases : controls).push(values[i]!);
  if (controls.length === 0 || cases.length === 0) return NaN;
  return aucOf(controls, cases, direction);
}

/** N draws of R_unif_index(N) (R's sample(1:N, replace = TRUE), 0-based) */
function drawIndices(n: number): number[] {
  const out = new Array<number>(n);
  for (let i = 0; i < n; i++) out[i] = unifIndex(n);
  return out;
}

