// Confidence intervals of the AUC and tests comparing two ROC curves (pROC's ci.auc and roc.test, DeLong's and
// bootstrap methods).
//
// Written for rStats.js from oracle/roc-behaviour.md (no ported code; the source of pROC was not read):
// - DeLong, DeLong and Clarke-Pearson (Biometrics 44, 1988): the placements V10 of the cases and V01 of the controls,
//   the variance S = var(V10)/m + var(V01)/n of the AUC, and the paired test of two curves on the same observations,
//   whose variance is computed here as that of the differences of the placements (the same as L'SL, without the
//   cancellation of S11 + S22 - 2 S12). The placements are mid-rank counts (Sun and Xu, IEEE Signal Processing Letters
//   21, 2014), exact multiples of 1/(2n) and 1/(2m) rounded once.
// - The unpaired test: (theta1 - theta2)/sqrt(S1 + S2) on pROC's Welch-Satterthwaite degrees of freedom.
// - The bootstrap (Robin et al., BMC Bioinformatics 12, 2011, the paper's description): the observations resampled
//   with R's sample() (src/random), stratified by class or not, the AUC of each resample, and the type-7 quantiles
//   (ciAuc) or the standard deviation of the differences (rocTest).

