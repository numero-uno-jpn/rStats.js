/**
 * Options for {@link ciAuc}.
 *
 * @category Hypothesis tests
 */
export interface CiAucOptions {
  /** Confidence level, in [0, 1]. Default `0.95`. */
  confLevel?: number;
  /** `"delong"` (default) or `"bootstrap"`; abbreviations are accepted. */
  method?: "delong" | "bootstrap" | (string & {});
  /** Number of bootstrap replicates. Default `2000`. */
  bootN?: number;
  /** Resample the controls and the cases separately (default `true`), or all observations together. */
  bootStratified?: boolean;
}

/**
 * Result of {@link ciAuc}.
 *
 * @category Hypothesis tests
 */
export interface CiAucResult {
  /** The AUC: DeLong's θ (the mean of the placements), or the curve's AUC for the bootstrap. */
  estimate: number;
  /** The interval `[lower, upper]`. */
  confInt: [number, number];
  /** The confidence level. */
  confLevel: number;
  /** The method, in full. */
  method: "delong" | "bootstrap";
  /** DeLong's variance of the AUC (pROC's `var(roc)`), or the variance of the bootstrap AUCs. */
  variance: number;
  /** R's warnings, each once, in R's order (an empty array when there are none). */
  warnings: string[];
}

/**
 * Confidence interval of the area under a ROC curve, by DeLong's method or the bootstrap. Equivalent to
 * `pROC::ci.auc()` in R.
 *
 * DeLong's interval is θ ∓ z√S (DeLong, DeLong and Clarke-Pearson 1988), clipped to [0, 1]; it needs at least two
 * controls and two cases (pROC: NA). The bootstrap draws R's random stream as pROC does (`setSeed` gives R's values):
 * `bootN` resamples of the controls then the cases (stratified, at least two of each) or of all observations, and
 * the type-7 quantiles α/2 and 1 − α/2 of their AUCs. A non-stratified resample without cases or without controls is
 * dropped with pROC's warning (pROC stops at one without controls).
 *
 * @param curve A curve from {@link roc}.
 * @param options See {@link CiAucOptions}.
 *
 * @example
 * ```ts
 * const r = roc({ controls: [1, 2, 2, 3, 5, 7], cases: [2, 4, 5, 5, 8, 9, 10] });
 * ciAuc(r).confInt; // [0.5272205221855736, 1]
 * ```
 *
 * @category Hypothesis tests
 */
export function ciAuc(curve: RocResult, options: CiAucOptions = {}): CiAucResult {
  checkOptions(options, CI_AUC_KEYS, "ciAuc"); // generated: option-keys.mjs
  const confLevel = options.confLevel ?? 0.95;
  checkConfLevel(confLevel);
  const method = matchChoice(options.method, ["delong", "bootstrap"] as const);
  const w = new Warnings();
  if (isPerfect(curve)) w.add("ci.auc() of a ROC curve with AUC == 1 is always 1-1 and can be misleading.");
  const alpha = 1 - confLevel;
  if (method === "delong") {
    requireTwoPerClass(curve, "DeLong's interval");
    const { v10, v01 } = placements(curve);
    const theta = curve.auc;
    const S = variance(v10) / v10.length + variance(v01) / v01.length;
    const sd = Math.sqrt(S);
    // qnorm(c(alpha/2, 1 - alpha/2), theta, sd), clipped to [0, 1]
    const clip = (v: number): number => Math.min(1, Math.max(0, v));
    // (the lower quantile from qnorm(alpha/2) as R; at level 1 the quantiles are -Inf and Inf whatever the sd, as R's
    // qnorm, which checks p = 0 and 1 before sd = 0)
    const a2 = alpha / 2;
    const confInt: [number, number] =
      confLevel === 1 ? [0, 1] : sd === 0 ? [theta, theta] : [clip(theta + qnorm(a2) * sd), clip(theta + zOf(confLevel) * sd)];
    return reported("ciAuc", { estimate: theta, confInt, confLevel, method, variance: S, warnings: w.list });
  }
  const bootN = options.bootN ?? 2000;
  checkBootN(bootN);
  const stratified = options.bootStratified ?? true;
  const aucs: number[] = [];
  let failed = 0;
  if (stratified) {
    requireTwoPerClass(curve, "a stratified bootstrap");
    for (let b = 0; b < bootN; b++) {
      const controls = resample(curve.controls);
      const cases = resample(curve.cases);
      aucs.push(aucOf(controls, cases, curve.direction));
    }
  } else {
    const { values, isCase } = observations(curve);
    for (let b = 0; b < bootN; b++) {
      const a = resampledAuc(values, isCase, drawIndices(values.length), curve.direction);
      if (Number.isNaN(a)) failed++;
      else aucs.push(a);
    }
  }
  if (failed > 0) w.add("NA value(s) produced during bootstrap were ignored.");
  if (aucs.length === 0) throw new Error("no bootstrap replicate had both controls and cases");
  const q = quantile(aucs, [alpha / 2, 1 - alpha / 2]);
  return reported("ciAuc", {
    estimate: curve.auc,
    confInt: [q[0]!, q[1]!],
    confLevel,
    method,
    variance: aucs.length > 1 ? variance(aucs) : NaN,
    warnings: w.list,
  });
}

