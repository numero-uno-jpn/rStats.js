/**
 * Options for {@link rocTest}.
 *
 * @category Hypothesis tests
 */
export interface RocTestOptions {
  /** `"delong"` (default) or `"bootstrap"`; abbreviations are accepted. */
  method?: "delong" | "bootstrap" | (string & {});
  /** The alternative for the difference AUC₁ − AUC₂. Default `"two.sided"`. */
  alternative?: Alternative | (string & {});
  /**
   * Whether the curves are paired (on the same observations). Default: paired when both come from the same response
   * (as pROC). `true` for curves that are not is an error; `false` for curves that are gives pROC's warning.
   */
  paired?: boolean;
  /** Confidence level of the interval of the paired DeLong test, in [0, 1]. Default `0.95`. */
  confLevel?: number;
  /** Number of bootstrap replicates. Default `2000`. */
  bootN?: number;
  /** Resample the controls and the cases separately (default `true`), or all observations together. */
  bootStratified?: boolean;
  /** With a response and two predictors: the control and case levels (see {@link RocOptions}). */
  levels?: readonly RocResponseValue[];
  /** With a response and two predictors: the direction of both curves (see {@link RocOptions}). */
  direction?: "auto" | RocDirection;
}

/**
 * Result of {@link rocTest}.
 *
 * @category Hypothesis tests
 */
export interface RocTestResult extends HTest {
  /** The AUCs of the two curves. */
  estimate: [number, number];
  /** `"AUC of roc1"` and `"AUC of roc2"`. */
  estimateNames: [string, string];
  /** The two curves compared (rebuilt on the observations where neither predictor is missing, when paired). */
  roc1: RocResult;
  /** The second curve. */
  roc2: RocResult;
  /** For the bootstrap: whether it was stratified. */
  bootStratified?: boolean;
}

/** Whether a value is a curve made by roc() */
const isCurve = (v: unknown): v is RocResult =>
  typeof v === "object" && v !== null && !Array.isArray(v) && "thresholds" in v && "sensitivities" in v;

const sameArray = <T>(a: readonly T[], b: readonly T[]): boolean => a.length === b.length && a.every((v, i) => v === b[i]);

/**
 * The paired versions of two curves (pROC's pairing): as they are when their responses after the removals are
 * identical, rebuilt on the observations where neither predictor nor the response is missing when their original
 * responses are; undefined when they are not paired
 */
function pairedCurves(r1: RocResult, r2: RocResult): [RocResult, RocResult] | undefined {
  const d1 = rocData(r1);
  const d2 = rocData(r2);
  if (d1?.labels == null || d2?.labels == null || !sameArray(r1.levels, r2.levels)) return undefined;
  const kept = (d: typeof d1): string[] => d.kept.map((i) => d.labels![i]!);
  if (sameArray(kept(d1), kept(d2)) && sameArray(d1.isCase, d2.isCase)) return [r1, r2];
  if (!sameArray(d1.labels, d2.labels)) return undefined;
  const rows = d1.labels.map((_, i) => i).filter((i) => d1.labels![i] !== null && !Number.isNaN(d1.predictor[i]!) && !Number.isNaN(d2.predictor[i]!));
  const rebuild = (r: RocResult, d: typeof d1): RocResult =>
    rocFromResponse(
      rows.map((i) => d.labels![i]!),
      rows.map((i) => d.predictor[i]!),
      { levels: r.levels, direction: r.direction },
    );
  return [rebuild(r1, d1), rebuild(r2, d2)];
}

/** Normal p-value of a statistic */
function normalP(z: number, alternative: Alternative): number {
  if (alternative === "two.sided") return 2 * pnorm(-Math.abs(z));
  return alternative === "greater" ? pnorm(z, { lowerTail: false }) : pnorm(z);
}

/**
 * Tests the difference of the areas under two ROC curves, by DeLong's method or the bootstrap. Equivalent to
 * `pROC::roc.test()` in R.
 *
 * Curves from the same response are paired, as pROC pairs them (identical responses; where a predictor is missing,
 * both curves are rebuilt on the observations where neither is). Paired DeLong: Z = (θ₁ − θ₂)/σ with σ² from the
 * placements' covariances (DeLong, DeLong and Clarke-Pearson 1988), Z = 0 when both are 0, and the interval θ₁ − θ₂ ∓
 * zσ. Unpaired DeLong: D = (θ₁ − θ₂)/√(S₁ + S₂) on pROC's Welch-Satterthwaite degrees of freedom (when both variances
 * are 0, D = 0 with p-value 1 if the AUCs are equal, and the degrees of freedom are NaN). Bootstrap: D = (AUC₁ −
 * AUC₂)/sd of the resampled differences, with R's random stream. DeLong's method needs at least two controls and two
 * cases in each curve, as does the stratified bootstrap. The method is DeLong's unless given (pROC switches to the
 * bootstrap silently for curves of different directions; here DeLong's test gives pROC's warning).
 *
 * @param roc1 The first curve, from {@link roc}.
 * @param roc2 The second curve.
 * @param options See {@link RocTestOptions}.
 *
 * @example
 * ```ts
 * const y = [0, 0, 0, 0, 1, 1, 1, 1];
 * const t = rocTest(roc(y, [1, 2, 3, 5, 4, 6, 7, 8]), roc(y, [2, 1, 5, 4, 3, 7, 6, 8]));
 * t.estimate;   // [0.9375, 0.875]
 * t.statistic;  // 0.7071067811865475
 * ```
 *
 * @category Hypothesis tests
 */
export function rocTest(roc1: RocResult, roc2: RocResult, options?: RocTestOptions): RocTestResult;
/**
 * Tests the difference of the areas under the ROC curves of two predictors of the same response (paired);
 * observations with a missing response or predictor are dropped from both.
 *
 * @param response The outcome (see {@link roc}).
 * @param predictor1 The first predictor.
 * @param predictor2 The second predictor.
 * @param options See {@link RocTestOptions}.
 */
export function rocTest(
  response: readonly RocResponseValue[] | Float64Array,
  predictor1: Sample,
  predictor2: Sample,
  options?: RocTestOptions,
): RocTestResult;
export function rocTest(
  a: RocResult | readonly RocResponseValue[] | Float64Array,
  b: RocResult | Sample,
  c?: Sample | RocTestOptions,
  d?: RocTestOptions,
): RocTestResult {
  if (isOptionsObject(c)) checkOptions(c, ROC_TEST_KEYS, "rocTest"); // generated: option-keys.mjs
  checkOptions(d, ROC_TEST_KEYS, "rocTest"); // generated: option-keys.mjs
  let options: RocTestOptions;
  const w = new Warnings();
  let r1: RocResult;
  let r2: RocResult;
  if (isCurve(a)) {
    if (!isCurve(b)) throw new TypeError("roc2 must be a curve from roc()");
    options = (c ?? {}) as RocTestOptions;
    if (options.levels !== undefined || options.direction !== undefined) {
      throw new RangeError("'levels' and 'direction' apply only to a response and two predictors");
    }
    r1 = a;
    r2 = b;
  } else {
    options = d ?? {};
    const response = Array.from(a as ArrayLike<RocResponseValue>);
    const p1 = Array.from(b as Sample);
    const p2 = Array.from(c as Sample);
    if (response.length !== p1.length || response.length !== p2.length) {
      throw new TypeError("the response and the predictors must have the same length");
    }
    const rows = response.map((_, i) => i).filter((i) => {
      const v = response[i];
      return v !== null && v !== undefined && !(typeof v === "number" && Number.isNaN(v)) && !Number.isNaN(p1[i]!) && !Number.isNaN(p2[i]!);
    });
    const resp = rows.map((i) => response[i]!);
    const curveOpts = { levels: options.levels, direction: options.direction };
    r1 = rocFromResponse(resp, rows.map((i) => p1[i]!), curveOpts);
    r2 = rocFromResponse(resp, rows.map((i) => p2[i]!), curveOpts);
    for (const m of r1.warnings) w.add(m);
  }
  const alternative = matchAlternative(options.alternative);
  const method = matchChoice(options.method, ["delong", "bootstrap"] as const);
  const confLevel = options.confLevel ?? 0.95;
  checkConfLevel(confLevel);
  if (isPerfect(r1) && isPerfect(r2)) w.add("roc.test() of two ROC curves with AUC == 1 has always p.value = 1 and can be misleading.");
  const pairs = pairedCurves(r1, r2);
  let paired: boolean;
  if (options.paired === true) {
    if (pairs === undefined) throw new RangeError("The paired ROC test cannot be applied to unpaired curves.");
    paired = true;
  } else if (options.paired === false) {
    if (pairs !== undefined) w.add("The ROC curves seem to be paired. Consider performing a paired roc.test.");
    paired = false;
  } else paired = pairs !== undefined;
  if (paired) [r1, r2] = pairs!;
  const common = {
    alternative,
    estimate: [r1.auc, r2.auc] as [number, number],
    estimateNames: ["AUC of roc1", "AUC of roc2"] as [string, string],
    nullValue: 0,
    nullValueName: "difference in AUC",
    roc1: r1,
    roc2: r2,
  };
  const diff = r1.auc - r2.auc;
  if (method === "delong") {
    if (r1.direction !== r2.direction) w.add("DeLong's test should not be applied to ROC curves with a different direction.");
    requireTwoPerClass(r1, "DeLong's test");
    requireTwoPerClass(r2, "DeLong's test");
    if (paired) {
      const p1 = placements(r1);
      const p2 = placements(r2);
      const d10 = p1.v10.map((v, i) => v - p2.v10[i]!);
      const d01 = p1.v01.map((v, i) => v - p2.v01[i]!);
      const sigma = Math.sqrt(variance(d10) / d10.length + variance(d01) / d01.length);
      const z = diff === 0 && sigma === 0 ? 0 : diff / sigma;
      const half = sigma === 0 ? 0 : zOf(confLevel) * sigma;
      return reported("rocTest", {
        method: "DeLong's test for two correlated ROC curves",
        statistic: z,
        statisticName: "Z",
        pValue: normalP(z, alternative),
        confInt: [diff - half, diff + half] as [number, number],
        confLevel,
        ...common,
        warnings: w.list,
      });
    }
    const s1 = delongVariance(r1);
    const s2 = delongVariance(r2);
    const n1 = r1.controls.length + r1.cases.length;
    const n2 = r2.controls.length + r2.cases.length;
    const s = s1 + s2;
    let D: number;
    let df: number;
    let pValue: number;
    if (s === 0) {
      // both variances 0 (pROC: 0/0, NaN throughout): D = 0 for equal AUCs, else its limit ±Inf
      D = diff === 0 ? 0 : diff > 0 ? Infinity : -Infinity;
      df = NaN;
      pValue = normalP(D, alternative);
    } else {
      D = diff / Math.sqrt(s);
      df = (s * s) / ((s1 * s1) / (n1 - 1) + (s2 * s2) / (n2 - 1));
      pValue =
        alternative === "two.sided" ? 2 * pt1(-Math.abs(D), df, true, false) : alternative === "greater" ? pt1(D, df, false, false) : pt1(D, df, true, false);
    }
    return reported("rocTest", {
      method: "DeLong's test for two ROC curves",
      statistic: D,
      statisticName: "D",
      parameter: df,
      parameterName: "df",
      pValue,
      ...common,
      warnings: w.list,
    });
  }
  // bootstrap
  const bootN = options.bootN ?? 2000;
  checkBootN(bootN);
  const stratified = options.bootStratified ?? true;
  const diffs: number[] = [];
  let failed = 0;
  if (stratified) {
    requireTwoPerClass(r1, "a stratified bootstrap");
    requireTwoPerClass(r2, "a stratified bootstrap");
    for (let k = 0; k < bootN; k++) {
      let a1: number;
      let a2: number;
      if (paired) {
        const ci = drawIndices(r1.controls.length);
        const ki = drawIndices(r1.cases.length);
        a1 = aucOf(ci.map((i) => r1.controls[i]!), ki.map((i) => r1.cases[i]!), r1.direction);
        a2 = aucOf(ci.map((i) => r2.controls[i]!), ki.map((i) => r2.cases[i]!), r2.direction);
      } else {
        a1 = aucOf(resample(r1.controls), resample(r1.cases), r1.direction);
        a2 = aucOf(resample(r2.controls), resample(r2.cases), r2.direction);
      }
      diffs.push(a1 - a2);
    }
  } else {
    const o1 = observations(r1);
    const o2 = observations(r2);
    for (let k = 0; k < bootN; k++) {
      let a1: number;
      let a2: number;
      if (paired) {
        const idx = drawIndices(o1.values.length);
        a1 = resampledAuc(o1.values, o1.isCase, idx, r1.direction);
        a2 = resampledAuc(o2.values, o2.isCase, idx, r2.direction);
      } else {
        a1 = resampledAuc(o1.values, o1.isCase, drawIndices(o1.values.length), r1.direction);
        a2 = resampledAuc(o2.values, o2.isCase, drawIndices(o2.values.length), r2.direction);
      }
      if (Number.isNaN(a1) || Number.isNaN(a2)) failed++;
      else diffs.push(a1 - a2);
    }
  }
  if (failed > 0) w.add(`${failed} NA value(s) produced during bootstrap were ignored.`);
  if (diffs.length < 2) throw new Error("fewer than 2 bootstrap replicates had both controls and cases");
  const sd = Math.sqrt(variance(diffs));
  const D = diff === 0 && sd === 0 ? 0 : diff / sd;
  return reported("rocTest", {
    method: paired ? "Bootstrap test for two correlated ROC curves" : "Bootstrap test for two ROC curves",
    statistic: D,
    statisticName: "D",
    parameter: bootN,
    parameterName: "boot.n",
    pValue: normalP(D, alternative),
    bootStratified: stratified,
    ...common,
    warnings: w.list,
  });
}
