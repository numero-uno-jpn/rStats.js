// Levene's test of equal variances as car's leveneTest computes it: the one-way analysis of variance of the absolute
// deviations of the values from the centre (median or mean) of their group (Brown and Forsythe's form with the
// median).
//
// Written for rStats.js from oracle/rm-tests-behaviour.md (no ported code; car's source was not read).

import { ldexp, mean, scaleToUnit } from "../internal/summary.js";
import { onewayTable } from "./aov.js";
import { labelledGroups, median, toGroups, type GroupLabel } from "./groups.js";
import { matchChoice } from "./power.js";
import type { Sample } from "./types.js";
// Generated by `node scripts/option-keys.mjs --write` from the option types; do not edit (begin)
import { checkOptions } from "../internal/checkOptions.js";
const LEVENE_TEST_KEYS = ["center"] as const;
// Generated by `node scripts/option-keys.mjs --write` (end)

const MIN_NORMAL = 2 ** -1022;

/**
 * Options for {@link leveneTest}.
 *
 * @category Hypothesis tests
 */
export interface LeveneTestOptions {
  /** The centre of each group: `"median"` (default) or `"mean"`. */
  center?: "median" | "mean" | (string & {});
}

/**
 * Result of {@link leveneTest}: car's table.
 *
 * @category Hypothesis tests
 */
export interface LeveneTestResult {
  /** `["Df", "F value", "Pr(>F)"]`. */
  colNames: string[];
  /** `["group", ""]` (the second row is the residuals). */
  rowNames: string[];
  /** One array per row; NaN where car prints nothing. */
  table: number[][];
}

/**
 * Levene's test for homogeneity of variance across groups. Equivalent to `car::leveneTest()` in R. Computes
 * `leveneTest(y ~ g, center = median)` (or `mean`). Pairs with a missing value are dropped; groups are ordered by
 * their sorted labels.
 *
 * @param y The values.
 * @param g Group labels, parallel to `y`.
 *
 * @example
 * ```ts
 * const g = ["a", "a", "a", "b", "b", "b", "c", "c", "c"];
 * leveneTest([4.2, 5.1, 6.3, 5.8, 7.9, 8.4, 6.6, 7.0, 5.5], g).table[0]; // [2, 0.15936952714535912, 0.8561748951935417]
 * ```
 *
 * @category Hypothesis tests
 */
export function leveneTest(y: Sample, g: readonly GroupLabel[], options: LeveneTestOptions = {}): LeveneTestResult {
  checkOptions(options, LEVENE_TEST_KEYS, "leveneTest"); // generated: option-keys.mjs
  const center = matchChoice(options.center ?? "median", ["median", "mean"] as const);
  const { groups } = labelledGroups(y, g);
  if (groups.length < 2) throw new RangeError("contrasts can be applied only to factors with 2 or more levels");
  // the absolute deviations of the data scaled by one power of 2 (exact), so that they cannot overflow; F does not
  // depend on the units
  const deviationsOf = (s: readonly number[]): number[] => {
    const c = center === "median" ? median(s) : mean(s);
    return s.map((v) => Math.abs(v - c));
  };
  let deviations = scaleToUnit(groups).groups.map(deviationsOf);
  const lost = (d: readonly number[], i: number): boolean =>
    d.some((v) => v > 0 && v < MIN_NORMAL) || (d.every((v) => v === 0) && groups[i]!.some((v) => v !== groups[i]![0]));
  if (deviations.some(lost)) {
    // the deviations of a group fall below the normal range on the common scale (#393; as #270): each group's
    // deviations on its own scale, then all on the scale of the largest deviation
    const own = groups.map((s) => {
      const r = scaleToUnit([s]);
      return { d: deviationsOf(r.groups[0]!), k: r.k };
    });
    const top = Math.max(...own.map((o) => (o.d.some((v) => v > 0) ? Math.floor(Math.log2(Math.max(...o.d))) + o.k : -Infinity)));
    const e = Number.isFinite(top) ? top : 0;
    deviations = own.map((o) => o.d.map((v) => ldexp(v, o.k - e)));
  }
  const r = onewayTable(toGroups(deviations));
  return {
    colNames: ["Df", "F value", "Pr(>F)"],
    rowNames: ["group", ""],
    table: [
      [r.df[0], r.fValue, r.pValue],
      [r.df[1], NaN, NaN],
    ],
  };
}
