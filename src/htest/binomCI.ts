import { checkOptions } from "../internal/checkOptions.js";
const BINOM_CI_KEYS = ["method", "confLevel", "sides"] as const;
// Generated by `node scripts/option-keys.mjs --write` (end)

/**
 * Which limits of a proportion's interval are kept (DescTools' `sides`): `"two.sided"` both, `"left"` the lower one
 * (the upper is the end of the range), `"right"` the upper one.
 *
 * @category Hypothesis tests
 */
export type CISides = "two.sided" | "left" | "right";

/**
 * Methods of {@link binomCI}.
 *
 * @category Hypothesis tests
 */
export type BinomCIMethod = "wilson" | "wald" | "wilsoncc" | "agresti-coull" | "jeffreys" | "clopper-pearson" | "midp";

const BINOM_CI_METHODS: readonly BinomCIMethod[] = ["wilson", "wald", "wilsoncc", "agresti-coull", "jeffreys", "clopper-pearson", "midp"];
const SIDES: readonly CISides[] = ["two.sided", "left", "right"];

/**
 * Options for {@link binomCI}.
 *
 * @category Hypothesis tests
 */
export interface BinomCIOptions {
  /** The interval: `"wilson"` (default), `"wald"`, `"wilsoncc"`, `"agresti-coull"`, `"jeffreys"`,
   *  `"clopper-pearson"` or `"midp"`. Unambiguous abbreviations are accepted. */
  method?: BinomCIMethod | (string & {});
  /** Confidence level, in (0, 1). Default `0.95`. */
  confLevel?: number;
  /** `"two.sided"` (default), `"left"` (lower limit only) or `"right"` (upper limit only); abbreviations accepted. */
  sides?: CISides | (string & {});
}

/**
 * A confidence interval for a proportion, a difference or a ratio of proportions.
 *
 * @category Hypothesis tests
 */
export interface ProportionCIResult<M extends string = string> {
  /** The point estimate. */
  estimate: number;
  /** `[lower, upper]`; with `sides: "left"` the upper end of the range, with `"right"` the lower end. */
  confInt: [number, number];
  /** The confidence level given (of the one-sided limit, for `sides` other than `"two.sided"`). */
  confLevel: number;
  /** The method, in full. */
  method: M;
  /** The sides, in full. */
  sides: CISides;
  /** Warnings (none so far: input without a defined result is an error). */
  warnings: string[];
}

/**
 * Result of {@link binomCI}.
 *
 * @category Hypothesis tests
 */
export type BinomCIResult = ProportionCIResult<BinomCIMethod>;

/** The level, alpha and kappa = qnorm(1 - alpha/2) of an interval, from the level given and the sides */
export interface IntervalLevel {
  sides: CISides;
  /** The two-sided level actually used: confLevel, or 1 - 2(1 - confLevel) for one side */
  level: number;
  alpha: number;
  kappa: number;
  /**
   * qchisq(level, 1), the bound of the score statistics. Not kappa^2: 1 - alpha/2 rounds, which moves kappa^2 by up to
   * 1e-11 relative at alpha = 1e-6 (the score intervals of DescTools and epiR use qchisq or solve for alpha itself)
   */
  chisq: number;
}

/** Checks the level and sides, and the two-sided level that a one-sided limit is computed at (as DescTools) */
export function intervalLevel(confLevel: number | undefined, sides: string | undefined): IntervalLevel {
  const s = matchChoice(sides, SIDES);
  const c = confLevel ?? 0.95;
  if (!(typeof c === "number" && c > 0 && c < 1)) throw new RangeError("'confLevel' must be a single number in (0, 1)");
  const level = s === "two.sided" ? c : 1 - 2 * (1 - c);
  if (!(level >= 0)) throw new RangeError("a one-sided 'confLevel' must be at least 0.5");
  // one-sided with alpha/2 below 1e-8 (rule 10), alpha from c (1 - c is exact for c >= 1/2), not from the rounded
  // level; otherwise 1 - level as DescTools
  const alpha = s !== "two.sided" && 1 - c < 1e-8 ? 2 * (1 - c) : 1 - level;
  return { ...levelOfAlpha(alpha, level), sides: s };
}

/**
 * The two-sided interval level of a given alpha, for callers that hold alpha itself (a test at 1 - 2 alpha: alpha
 * taken back as 1 - level is about eps / alpha relative off). `level` is 1 - alpha unless given
 */
export function levelOfAlpha(alpha: number, level = 1 - alpha): IntervalLevel {
  // (rule 10: for alpha/2 below 1e-8 the upper tails themselves, as 1 - alpha/2 and the level have lost their digits)
  const small = alpha / 2 < 1e-8;
  const kappa = small ? qnorm(alpha / 2, { lowerTail: false }) : qnorm(1 - alpha / 2);
  const chisq = small ? qchisq(alpha, 1, { lowerTail: false }) : qchisq(level, 1);
  return { sides: "two.sided", level, alpha, kappa, chisq };
}

/** A count: a nonnegative integer (within the slack of isCount), returned rounded */
export function checkCount(v: number, name: string): number {
  if (typeof v !== "number") throw new TypeError(`'${name}' must be a number`);
  if (!isCount(v)) throw new RangeError(`'${name}' must be a nonnegative integer`);
  // (+ 0 turns -0 into 0, which would otherwise reach an estimate or a limit as -0)
  return Math.round(v) + 0;
}

/** Successes and trials: integers with 0 <= x <= n and n > 0 */
export function checkTrials(x: number, n: number, xName: string, nName: string): [number, number] {
  const xs = checkCount(x, xName);
  const ns = checkCount(n, nName);
  if (ns === 0) throw new RangeError(`'${nName}' must be positive`);
  if (ns > 2 ** 53) throw new RangeError(`'${nName}' must be at most 2^53`);
  if (xs > ns) throw new RangeError(`'${xName}' must not be greater than '${nName}'`);
  return [xs, ns];
}

/**
 * Wilson's score limits of x/n at kappa. At x = 0 the lower limit and at x = n the upper are exactly 0 and 1 (the
 * formula gives them up to rounding: DescTools' upper limit of 10/10 at the 50% level is 0.99999999999999989).
 * The limits are the roots of (n + kappa^2) p^2 - (2x + kappa^2) p + x^2/n = 0. Where centre - half cancels (more than
 * half of the centre, small x or a level close to 1) the lower limit is taken from the product of the roots,
 * x^2 / (n (n + kappa^2)), divided by the upper: centre - half loses digits in proportion to centre / lower (350 eps
 * at 1/1e15 and the level 1 - 2^-53, 28 eps for wilsoncc at 1/1000 and 95%; DescTools has the same digits)
 */
export function wilsonLimits(x: number, n: number, kappa: number): [number, number] {
  const p = x / n;
  const q = 1 - p;
  const k2 = kappa * kappa;
  const centre = (x + k2 / 2) / (n + k2);
  const half = ((kappa * Math.sqrt(n)) / (n + k2)) * Math.sqrt(p * q + k2 / (4 * n));
  const up = centre + half;
  let lower = centre - half;
  if (x === 0) lower = 0;
  else if (lower < centre / 2) lower = (p * (x / (n + k2))) / up;
  return [lower, x === n ? 1 : up];
}

/** qbeta at alpha/2 in the lower or the upper tail (from the upper tail itself where alpha/2 < 1e-8, rule 10) */
function betaLimit(alpha: number, a: number, b: number, upper: boolean): number {
  if (!upper) return qbeta1(alpha / 2, a, b, true, false);
  return alpha / 2 < 1e-8 ? qbeta1(alpha / 2, a, b, false, false) : qbeta1(1 - alpha / 2, a, b, true, false);
}

/**
 * The mid-p limit of x/n (0 < x < n): for the lower limit the p with 1/2 P(X = x) + P(X > x) = alpha/2 (increasing in
 * p), for the upper the p with 1/2 P(X = x) + P(X < x) = alpha/2 (decreasing). Solved in u = log p by Brent's method,
 * from a bracket widened from the estimate x/n
 */
function midpLimit(x: number, n: number, alpha: number, upper: boolean): number {
  const half = alpha / 2;
  const g = upper
    ? (u: number): number => {
        const p = Math.exp(u);
        return 0.5 * dbinom1(x, n, p, false) + pbinom1(x - 1, n, p, true, false) - half;
      }
    : (u: number): number => {
        const p = Math.exp(u);
        return 0.5 * dbinom1(x, n, p, false) + pbinom1(x, n, p, false, false) - half;
      };
  // g increases in u for the lower limit and decreases for the upper; sign s makes it increasing
  const s = upper ? -1 : 1;
  const u0 = Math.log(x / n);
  const g0 = s * g(u0);
  if (g0 === 0) return x / n;
  if (g0 > 0) {
    // the root lies below u0: widen downwards
    let hi = u0;
    let gHi = g0;
    let step = 1;
    for (;;) {
      const lo = u0 - step;
      if (lo < -745) return 0;
      const gLo = s * g(lo);
      if (gLo <= 0) {
        if (gLo === 0) return Math.exp(lo);
        return Math.exp(uniroot((u) => s * g(u), lo, hi, { tol: 2 ** -60, fLower: gLo, fUpper: gHi }));
      }
      hi = lo;
      gHi = gLo;
      step *= 2;
    }
  }
  // the root lies between u0 and 0 (p = 1, where s g > 0 for 0 < x < n)
  const g1 = s * g(0);
  if (g1 <= 0) return 1;
  return Math.exp(uniroot((u) => s * g(u), u0, 0, { tol: 2 ** -60, fLower: g0, fUpper: g1 }));
}

/**
 * Confidence interval for a binomial proportion x/n. Equivalent to `DescTools::BinomCI()` in R.
 *
 * Methods (`method`): `"wilson"` (the default, Wilson's score interval), `"wald"`, `"wilsoncc"` (with continuity
 * correction), `"agresti-coull"`, `"jeffreys"`, `"clopper-pearson"` (the exact interval) and `"midp"` (the mid-p exact
 * interval). With `sides: "left"` or `"right"` only the lower or the upper limit is kept, at the one-sided level
 * `confLevel` (the two-sided interval at `1 - 2 (1 - confLevel)`), and the other end is 0 or 1. Limits are clipped to
 * [0, 1].
 *
 * The mid-p limits are the roots of their equations to the precision of the doubles; DescTools stops its search at
 * an absolute 1.22e-4, which leaves its limits up to 1e-4 off and gives 0 for lower limits below that. Unlike
 * DescTools, which returns NaN or numbers, x > n, a negative or non-integer count, n = 0 and a level outside (0, 1)
 * are errors.
 *
 * @param x Number of successes.
 * @param n Number of trials.
 * @param options See {@link BinomCIOptions}.
 * @returns The estimate x/n and the interval; see {@link BinomCIResult}.
 * @throws RangeError for counts that are not integers with 0 <= x <= n, n > 0, a level outside (0, 1) (at least 0.5
 *   one-sided), or an unknown method or sides.
 *
 * @example
 * ```ts
 * binomCI(37, 100).confInt; // [0.28182360534324535, 0.4677947041905709]
 * binomCI(37, 100, { method: "clopper-pearson" }).confInt; // [0.27556657961455155, 0.4723516405516831]
 * binomCI(1, 1000, { method: "midp", sides: "right" }).confInt; // [0, 0.004106205924199768]
 * ```
 *
 * @category Hypothesis tests
 */
export function binomCI(x: number, n: number, options: BinomCIOptions = {}): BinomCIResult {
  checkOptions(options, BINOM_CI_KEYS, "binomCI"); // generated: option-keys.mjs
  const method = matchChoice(options.method, BINOM_CI_METHODS);
  const lv = intervalLevel(options.confLevel, options.sides);
  const [xs, ns] = checkTrials(x, n, "x", "n");
  const { alpha, kappa } = lv;
  const p = xs / ns;
  const q = 1 - p;
  let lower: number;
  let upper: number;
  switch (method) {
    case "wald": {
      const half = kappa * Math.sqrt((p * q) / ns);
      [lower, upper] = [p - half, p + half];
      break;
    }
    case "wilson":
      [lower, upper] = wilsonLimits(xs, ns, kappa);
      break;
    case "wilsoncc": {
      const k2 = kappa * kappa;
      const den = 2 * (ns + k2);
      // the lower limit is the smaller root of (n + kappa^2) L^2 - (2x + kappa^2 - 1) L + (2x - 1)^2 / (4n) = 0;
      // where the difference cancels (more than half of the larger term) it is taken from the product of the roots
      // as (2x - 1)^2 / (2n (2x + kappa^2 - 1 + kappa sqrt(...))), without cancellation (as wilsonLimits)
      const bl = 2 * xs + k2 - 1;
      const rl = kappa * Math.sqrt(k2 - 2 - 1 / ns + 4 * p * (ns * q + 1));
      lower = p === 0 ? 0 : bl - rl < bl / 2 ? (((2 * xs - 1) / (2 * ns)) * (2 * xs - 1)) / (bl + rl) : (bl - rl) / den;
      upper = p === 1 ? 1 : (2 * xs + k2 + 1 + kappa * Math.sqrt(k2 + 2 - 1 / ns + 4 * p * (ns * q - 1))) / den;
      break;
    }
    case "agresti-coull": {
      const k2 = kappa * kappa;
      const nt = ns + k2;
      const pt = (xs + k2 / 2) / nt;
      const half = kappa * Math.sqrt((pt * (1 - pt)) / nt);
      [lower, upper] = [pt - half, pt + half];
      break;
    }
    case "jeffreys":
      lower = xs === 0 ? 0 : betaLimit(alpha, xs + 0.5, ns - xs + 0.5, false);
      upper = xs === ns ? 1 : betaLimit(alpha, xs + 0.5, ns - xs + 0.5, true);
      break;
    case "clopper-pearson":
      lower = xs === 0 ? 0 : betaLimit(alpha, xs, ns - xs + 1, false);
      upper = xs === ns ? 1 : betaLimit(alpha, xs + 1, ns - xs, true);
      break;
    case "midp":
      // closed forms at the ends: 1/2 p^n = alpha/2 and 1/2 (1 - p)^n = alpha/2
      lower = xs === 0 ? 0 : xs === ns ? Math.exp(Math.log(alpha) / ns) : midpLimit(xs, ns, alpha, false);
      upper = xs === ns ? 1 : xs === 0 ? -Math.expm1(Math.log(alpha) / ns) : midpLimit(xs, ns, alpha, true);
      break;
  }
  lower = Math.max(0, lower);
  upper = Math.min(1, upper);
  if (lv.sides === "left") upper = 1;
  else if (lv.sides === "right") lower = 0;
  return reported("binomCI", {
    estimate: p,
    confInt: [lower, upper],
    confLevel: options.confLevel ?? 0.95,
    method,
    sides: lv.sides,
    warnings: [],
  });
}
