// Confidence intervals for one binomial proportion (DescTools' BinomCI), for one case per call.
//
// Written for rStats.js from the published intervals and DescTools' documented behaviour (no R or package code): the
// level of a one-sided interval ("left": [lower, 1], "right": [0, upper]) is that of the two-sided interval at
// 1 - 2(1 - confLevel); kappa = qnorm(1 - alpha/2).
// - wald: p ∓ kappa sqrt(p q / n)
// - wilson (Wilson, JASA 22, 1927): (x + kappa^2/2)/(n + kappa^2) ∓ kappa sqrt(n)/(n + kappa^2) sqrt(p q + kappa^2/(4n))
// - wilsoncc: Wilson's interval with continuity correction (Newcombe, Statistics in Medicine 17, 1998, method 4)
// - agresti-coull (Agresti and Coull, The American Statistician 52, 1998): the Wald interval of
//   (x + kappa^2/2)/(n + kappa^2) with n + kappa^2 trials
// - jeffreys: the equal-tailed interval of the Beta(x + 1/2, n - x + 1/2) posterior (Brown, Cai and DasGupta,
//   Statistical Science 16, 2001), 0 at x = 0 and 1 at x = n
// - clopper-pearson (Clopper and Pearson, Biometrika 26, 1934): beta quantiles of the exact binomial tails
// - midp: the p with 1/2 P(X = x) + P(X > x) = alpha/2 (lower) and 1/2 P(X = x) + P(X < x) = alpha/2 (upper) (Lancaster,
//   JASA 56, 1961; Agresti and Gottard, Statistical Science 20, 2005), solved on the log scale of p to the precision of
//   the doubles; closed forms alpha^(1/n) and 1 - alpha^(1/n) at x = n and x = 0. DescTools solves with uniroot's
//   tolerance 1.22e-4 (absolute), which leaves its limits 1e-6 to 1e-4 off and those below 1e-4 grossly wrong.
// Limits are clipped to [0, 1]. Counts must be integers with 0 <= x <= n, n > 0; the level must lie in (0, 1) and,
// one-sided, give a two-sided level 1 - 2(1 - confLevel) >= 0.

