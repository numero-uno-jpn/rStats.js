/** The noncentrality with P(T(df, ncp) > t) = p (upperTail) or P(T(df, ncp) <= t) = p, as a root to the last bit */
function ncpRoot(t: number, df: number, p: number, upperTail: boolean): number {
  // (where t ± 1 both round to t, a step of 1 to 2 ulp of t, as cohensD)
  const h = t - 1 < t + 1 ? 1 : Math.abs(t) * Number.EPSILON;
  // P(T > t) increases with ncp, P(T <= t) decreases
  return unirootCore((ncp) => (pt(t, df, { ncp, lowerTail: !upperTail }) as number) - p, t - h, t + h, {
    tol: 0,
    maxiter: 5000,
    extendInt: upperTail ? "upX" : "downX",
  }).root;
}

/** The standardised difference of section 4.3 of the behaviour file, from |delta|, with the sign restored at the end */
function standardised(m: Moments, o: Settings): { label: string; denom: number; estimate: number; se: number; confInt: [number, number]; df: number; J: number } {
  const { alpha, smdCi } = o;
  const ad = Math.abs(m.delta);
  const g2 = (J: number, g: number, df: number): number => (1 - (df - 2) / (df * J * J)) * g * g;
  let label: string;
  let denom: number;
  let df: number; // the df of J (and of the t and z intervals)
  let J: number;
  let g: number;
  let seNct: number; // the standard error of the nct, t and z cases
  let tStat: number; // nct: |delta| over the standard error of the difference
  let dfNct: number;
  let hn: number; // nct: the limits are the noncentralities times sqrt(hn) J
  let c: number; // goulet: g/lambda
  let dfGoulet: number;
  let seGoulet: (g: number, J: number) => number;
  const bc = o.biasCorrection;
  if (m.design === "two") {
    const { n1, n2, s1, s2 } = m;
    const v1 = s1 * s1;
    const v2 = s2 * s2;
    const ntilde = (2 * n1 * n2) / (n1 + n2);
    if (o.glass !== undefined) {
      const first = o.glass === "glass1";
      const [sG, nG, sO, nO] = first ? [s1, n1, s2, n2] : [s2, n2, s1, n1];
      denom = sG;
      df = nG - 1;
      label = bc ? "Glass's delta(g)" : "Glass's delta(d)";
      J = bc ? hedgesJ(df) : 1;
      g = (J * ad) / denom;
      // (TOSTER's 1/n2 + s²/(n1 s²): 1/n1 + 1/n2 for either sample)
      hn = 1 / n2 + 1 / n1;
      const r = sO / sG;
      seNct = Math.sqrt((r * r) / (nO - 1) + 1 / (nG - 1) + (g * g) / (2 * (nG - 1)));
      tStat = ad / (sG * Math.sqrt(1 / nG + (r * r) / nO));
      // as TOSTER: the noncentral t of Glass's delta on n1 + n2 - 2 df
      dfNct = n1 + n2 - 2;
      c = Math.sqrt(2 / ntilde);
    } else if (o.varEqual) {
      denom = Math.sqrt(((n1 - 1) * v1 + (n2 - 1) * v2) / (n1 + n2 - 2));
      df = n1 + n2 - 2;
      label = bc ? "Hedges's g" : "Cohen's d";
      J = bc ? hedgesJ(df) : 1;
      g = (J * ad) / denom;
      hn = 1 / n1 + 1 / n2;
      seNct = Math.sqrt(1 / n1 + 1 / n2 + g2(J, g, df));
      tStat = ad / (denom * Math.sqrt(hn));
      dfNct = df;
      // as TOSTER: lambda = g sqrt(n1 n2 (s1² + s2²)/(2(n2 s1² + n1 s2²))) with the pooled SD
      c = Math.sqrt((2 * (n2 * v1 + n1 * v2)) / (n1 * n2 * (v1 + v2)));
    } else {
      denom = Math.sqrt((v1 + v2) / 2);
      // (the df of the average variance: (n1 - 1)(n2 - 1)(s1² + s2²)² / ((n2 - 1)s1⁴ + (n1 - 1)s2⁴))
      df = ((n1 - 1) * (n2 - 1) * (v1 + v2) ** 2) / ((n2 - 1) * v1 * v1 + (n1 - 1) * v2 * v2);
      label = bc ? "Hedges's g(av)" : "Cohen's d(av)";
      J = bc ? hedgesJ(df) : 1;
      g = (J * ad) / denom;
      hn = (2 * (n2 * v1 + n1 * v2)) / (n1 * n2 * (v1 + v2));
      const d4 = denom ** 4;
      seNct = Math.sqrt((g * g * ((v1 * v1) / (n1 - 1) + (v2 * v2) / (n2 - 1))) / (8 * d4) + (v1 / (n1 - 1) + v2 / (n2 - 1)) / (denom * denom));
      tStat = ad / Math.sqrt(v1 / n1 + v2 / n2);
      dfNct = df;
      c = Math.sqrt(2 / ntilde);
    }
    dfGoulet = df;
    seGoulet = (gg, JJ) => Math.sqrt((dfGoulet / (dfGoulet - 2)) * (2 / ntilde) * (1 + (gg * gg * ntilde) / 2) - (gg * gg) / (JJ * JJ));
  } else if (m.design === "paired") {
    const { n, s1, s2, sdif, oneMinusR } = m;
    const tag = o.glass !== undefined ? "" : o.rmCorrection ? "(rm)" : "(z)";
    if (o.glass !== undefined) denom = o.glass === "glass1" ? s1 : s2;
    else denom = o.rmCorrection ? sdif / Math.sqrt(2 * oneMinusR) : sdif;
    label = o.glass !== undefined ? (bc ? "Glass's delta(g)" : "Glass's delta(d)") : bc ? `Hedges's g${tag}` : `Cohen's d${tag}`;
    df = n - 1;
    dfGoulet = 2 * n - 2;
    J = bc ? hedgesJ(smdCi === "goulet" ? dfGoulet : df) : 1;
    g = (J * ad) / denom;
    hn = 1 / n;
    tStat = (ad * Math.sqrt(n)) / denom;
    dfNct = df;
    c = Math.sqrt((2 * oneMinusR) / n);
    seGoulet = (gg, JJ) => {
      const dfG = smdCi === "goulet" ? dfGoulet : df;
      const se = Math.sqrt((dfG / (dfG - 2)) * ((2 * oneMinusR) / n) * (1 + (gg * gg * n) / (2 * oneMinusR)) - (gg * gg) / (JJ * JJ));
      return o.rmCorrection ? se : se * Math.sqrt(2 * oneMinusR);
    };
    if (o.glass !== undefined) {
      const r = sdif / denom;
      seNct = Math.sqrt((r * r) / (n - 1) + (g * g) / (2 * (n - 1)));
    } else if (!o.rmCorrection && smdCi === "nct") seNct = Math.sqrt(1 / n + g2(J, g, df));
    else seNct = seGoulet(g, J);
  } else {
    const { n, s } = m;
    denom = s;
    df = n - 1;
    dfGoulet = df;
    label = bc ? "Hedges's g" : "Cohen's d";
    J = bc ? hedgesJ(df) : 1;
    g = (J * ad) / denom;
    hn = 1 / n;
    seNct = Math.sqrt(1 / n + (g * g) / (2 * n));
    tStat = (ad * Math.sqrt(n)) / s;
    dfNct = df;
    c = 1 / Math.sqrt(n);
    seGoulet = (gg, JJ) => Math.sqrt((df / (df - 2)) * (1 / n) * (1 + gg * gg * n) - (gg * gg) / (JJ * JJ));
  }
  let lo: number;
  let hi: number;
  let se: number;
  let dfOut = df;
  if (smdCi === "nct") {
    se = seNct;
    dfOut = dfNct;
    const L = ncpRoot(tStat, dfNct, alpha, true);
    const U = ncpRoot(tStat, dfNct, alpha, false);
    lo = L * Math.sqrt(hn) * J;
    hi = U * Math.sqrt(hn) * J;
  } else if (smdCi === "goulet") {
    se = seGoulet(g, J);
    dfOut = dfGoulet;
    // the quantiles of the noncentral t at lambda = g/c, times c (= g/lambda; continuous at g = 0)
    const lambda = g / c;
    lo = (qt(alpha, dfGoulet, { ncp: lambda }) as number) * c;
    hi = (qt(alpha, dfGoulet, { ncp: lambda, lowerTail: false }) as number) * c;
  } else {
    se = seNct;
    // a 1 - 2 alpha interval in every design (TOSTER's one-sample t and z limits are at 1 - alpha; decision 20)
    const q = smdCi === "t" ? qt1(alpha, df, false, false) : (qnorm(alpha, { lowerTail: false }) as number);
    lo = g - q * se;
    hi = g + q * se;
  }
  const neg = m.delta < 0;
  return { label, denom, estimate: neg ? -g : g, se, confInt: neg ? [-hi, -lo] : [lo, hi], df: dfOut, J };
}

/** A sample of tTOST: an array (or typed array) of numbers, NaN allowed (dropped), not infinite */
function checkSample(v: unknown, name: string): asserts v is Sample {
  if (!(Array.isArray(v) || ArrayBuffer.isView(v))) throw new TypeError(`'${name}' must be an array of numbers`);
  const a = v as ArrayLike<unknown>;
  for (let i = 0; i < a.length; i++) {
    const u = a[i];
    if (typeof u !== "number") throw new TypeError(`'${name}' must be numeric`);
    if (u === Infinity || u === -Infinity) throw new RangeError(`'${name}' must not contain infinite values`);
  }
}

/** The bounds [low, high] from eqb or lowEqbound/highEqbound */
function boundsOf(options: TTOSTOptions): [number, number] {
  const { eqb } = options;
  let b: [number, number];
  if (eqb !== undefined) {
    const v = typeof eqb === "number" ? [eqb] : Array.from(eqb);
    if (!v.every((e) => typeof e === "number")) throw new TypeError("'eqb' must be a number or an array of 1 or 2 numbers");
    if (v.length === 1) b = [-Math.abs(v[0]!), Math.abs(v[0]!)];
    else if (v.length === 2) b = [Math.min(v[0]!, v[1]!), Math.max(v[0]!, v[1]!)];
    else throw new RangeError("'eqb' must be a number or an array of 1 or 2 numbers");
  } else {
    if (options.lowEqbound === undefined || options.highEqbound === undefined) {
      throw new TypeError("the equivalence bounds are required: 'eqb', or 'lowEqbound' and 'highEqbound'");
    }
    b = [options.lowEqbound, options.highEqbound];
  }
  if (!b.every((v) => typeof v === "number" && Number.isFinite(v))) throw new RangeError("the equivalence bounds must be finite numbers");
  if (b[0] > b[1]) throw new RangeError("'lowEqbound' must not be greater than 'highEqbound'");
  return b;
}

/** The options shared by tTOST and tsumTOST, checked in TOSTER's order */
function settingsOf(options: TTOSTOptions): Settings & { hypothesis: "EQU" | "MET"; smdBounds: boolean; paired: boolean; mu: number } {
  const hypothesis = matchChoice(options.hypothesis, ["EQU", "MET"] as const);
  const smdBounds = matchChoice(options.eqboundType, ["raw", "SMD"] as const) === "SMD";
  const smdCi = matchChoice(options.smdCi, ["nct", "goulet", "t", "z"] as const);
  const glass = options.glass === undefined ? undefined : matchChoice(options.glass, ["glass1", "glass2"] as const);
  const alpha = options.alpha ?? 0.05;
  if (!(typeof alpha === "number" && alpha > 0 && alpha < 0.5)) throw new RangeError("'alpha' must be a single number in (0, 0.5)");
  const mu = options.mu ?? 0;
  if (!(typeof mu === "number" && Number.isFinite(mu))) throw new RangeError("'mu' must be a finite number");
  const flag = (v: boolean | undefined, name: string, def: boolean): boolean => {
    if (v !== undefined && typeof v !== "boolean") throw new TypeError(`'${name}' must be true or false`);
    return v ?? def;
  };
  return {
    hypothesis,
    smdBounds,
    smdCi,
    glass,
    alpha,
    mu,
    paired: flag(options.paired, "paired", false),
    varEqual: flag(options.varEqual, "varEqual", false),
    biasCorrection: flag(options.biasCorrection, "biasCorrection", true),
    rmCorrection: flag(options.rmCorrection, "rmCorrection", false),
  };
}

/**
 * The tests and effect sizes from the effect (the difference minus mu) and its standard error, in the units 2^kE and
 * 2^kSE (so that neither the t statistics nor the interval lose the scaling of the data), and the moments of the
 * standardised difference (in the units 2^kS)
 */
function tostCore(
  name: "tTOST" | "tsumTOST",
  effect: number,
  kE: number,
  se: number,
  kSE: number,
  df: number,
  method: string,
  m: Moments,
  kS: number,
  s: ReturnType<typeof settingsOf>,
  given: [number, number],
  warnings: string[],
): TTOSTResult {
  const { alpha, hypothesis } = s;
  const smd = standardised(m, s);
  const dDenom = ldexp(smd.denom, kS);
  const raw: [number, number] = s.smdBounds ? [given[0] * dDenom, given[1] * dDenom] : given;
  // each bound as a value of moderate size times 2^kb (the SMD bounds times the denominator, in the SDs' units kS)
  const boundOf = (g: number): [number, number] => {
    if (g === 0) return [0, kE];
    const tg = Math.floor(Math.log2(Math.abs(g)));
    const sg = ldexpWide(g, -tg);
    return s.smdBounds ? [sg * smd.denom, tg + kS] : [sg, tg];
  };
  const smdB: [number, number] = s.smdBounds ? given : [given[0] / dDenom, given[1] / dDenom];
  if (s.smdBounds) warnings.push(SMD_NOTE);
  if (!(raw[0] <= 0 && raw[1] >= 0)) warnings.push(ZERO_NOTE);
  // the effect is the difference minus mu throughout: the bound tests compare it with [low, high] (TOSTER compares the
  // difference itself), and the raw estimate, its interval and the SMD are those of it
  const tOf = (v: number): number => ldexp(v / se, kE - kSE);
  // effect - bound in the larger of their units, so that neither term leaves the double range where t does not (in
  // tsumTOST the means' units kE and the SDs' kS are independent: a bound converted to the units of tiny means
  // overflowed, t was Infinity)
  const tMinus = (g: number): number => {
    const [b, kb] = boundOf(g);
    const kc = Math.max(kE, kb);
    return ldexpWide((ldexpWide(effect, kE - kc) - ldexpWide(b, kb - kc)) / se, kc - kSE);
  };
  const t0 = tOf(effect);
  const tL = tMinus(given[0]);
  const tU = tMinus(given[1]);
  const seOut = ldexp(se, kSE);
  const equ = hypothesis === "EQU";
  const tTestRow: TTOSTTest = { t: t0, se: seOut, df, pValue: 2 * pt1(-Math.abs(t0), df, true, false) };
  // EQU: H0 effect <= low (alternative "greater") and diff >= high ("less"); MET the reverse
  const lower: TTOSTTest = { t: tL, se: seOut, df, pValue: pt1(tL, df, !equ, false) };
  const upper: TTOSTTest = { t: tU, se: seOut, df, pValue: pt1(tU, df, equ, false) };
  const pValue = equ ? Math.max(lower.pValue, upper.pValue) : Math.min(lower.pValue, upper.pValue);
  if (!equ && raw[0] <= 0 && raw[1] >= 0 && pValue <= tTestRow.pValue) warnings.push(MET_NOTE);
  const q = qt1(alpha, df, false, false);
  // the interval in the larger of the two units
  const kc = Math.max(kE, kSE);
  const [eC, sC] = [ldexp(effect, kE - kc), ldexp(se, kSE - kc)];
  return reported(name, {
    tTest: tTestRow,
    lower,
    upper,
    pValue,
    bounds: { raw, smd: smdB },
    raw: { estimate: ldexp(effect, kE), se: seOut, confInt: [ldexp(eC - q * sC, kc), ldexp(eC + q * sC, kc)] as [number, number] },
    smd: { label: smd.label, estimate: smd.estimate, se: smd.se, confInt: smd.confInt, df: smd.df, J: smd.J },
    confLevel: 1 - 2 * alpha,
    method,
    hypothesis,
    warnings,
  });
}

/**
 * Two one-sided t tests (TOST) of equivalence, or minimal-effect tests, for one sample, two samples or paired samples,
 * with the standardised mean difference and its interval. Equivalent to `TOSTER::t_TOST()` in R.
 *
 * With `hypothesis: "EQU"` (the default) equivalence, low < difference < high, is shown at level alpha when both the
 * test of the lower bound (alternative "greater") and that of the upper bound (alternative "less") reject; the
 * p-value is the larger of the two. With `"MET"` the alternatives are reversed and the p-value is the smaller. The
 * effect is the difference minus `mu`: mean(x) - mean(y) - mu (two samples, Welch's or pooled), the mean of x - y
 * minus mu (paired) or the mean of x minus mu (one sample). The bounds, the raw estimate and interval and the
 * standardised difference all refer to that effect. The intervals are 1 - 2 alpha intervals (90% for the default alpha
 * 0.05).
 *
 * The standardised difference is Hedges' g (Cohen's d without `biasCorrection`) with the average SD
 * `sqrt((s1² + s2²)/2)` for Welch's test, the pooled SD with `varEqual`, the SD of the differences for paired samples
 * (d_z, or d_rm with `rmCorrection`), the SD of one sample with `glass`, or the SD for one sample. Its interval is from
 * the noncentral t (`"nct"`, as exact roots; TOSTER's optimiser is about 1e-9 accurate), Goulet-Pelletier and
 * Cousineau's (`"goulet"`), or `g -+ q se` with a t or normal quantile (`"t"`, `"z"`).
 *
 * Differences from TOSTER (decisions 20-23 of oracle/methodcomparison-behaviour.md): `mu` is subtracted everywhere
 * (TOSTER tests the bounds on the difference itself, gives the raw interval of the difference, the two-sample SMD of
 * the difference plus mu and the paired SMD without mu); the one-sample `"t"` and `"z"` intervals of the standardised
 * difference are 1 - 2 alpha intervals (TOSTER's 1 - alpha); TOSTER's notes are warnings; alpha must be in (0, 0.5).
 * With `mu` 0 only the last three apply.
 *
 * With 2 observations (df 1) Hedges' correction J(1) is 0: the bias-corrected standardised difference is 0 (and its
 * `"nct"` interval), and some of its standard errors and intervals are NaN or infinite, as TOSTER's formulas give.
 *
 * @param x Sample (NaN values are dropped; for paired samples, the pairs with a NaN).
 * @param y Second sample (omit for one sample).
 * @param options See {@link TTOSTOptions}; the bounds are required.
 * @returns See {@link TTOSTResult}.
 * @throws TypeError without bounds, for options of the wrong type, or for samples that are not arrays of numbers
 *   (`null` or strings in them); RangeError for infinite values, alpha outside (0, 0.5), bounds that are not finite or
 *   in the wrong order, an unknown choice, or fewer than 2 observations in a sample; Error where the t test has too
 *   few observations or the data are essentially constant.
 *
 * @example
 * ```ts
 * const r = tTOST([5.1, 4.9, 5.6, 5.8, 6.0, 5.4, 5.2, 6.1], [5.3, 5.0, 5.5, 5.7, 5.9, 5.2, 4.8, 5.6, 5.0], { eqb: 0.5 });
 * r.pValue;      // 0.06280707532313813
 * r.raw.confInt; // [-0.16777332363212605, 0.5261066569654603] (90%)
 * r.smd.label;   // "Hedges's g(av)"
 * ```
 *
 * @category Hypothesis tests
 */
export function tTOST(x: Sample, y?: Sample, options: TTOSTOptions = {}): TTOSTResult {
  checkOptions(options, T_TOST_KEYS, "tTOST"); // generated: option-keys.mjs
  const s = settingsOf(options);
  const given = boundsOf(options);
  const { paired, varEqual, mu } = s;
  const oneSample = y === undefined;
  if (paired && oneSample) throw new TypeError("'y' is required when paired is true");
  checkSample(x, "x");
  if (!oneSample) checkSample(y, "y");
  // the t test: its errors, method and df (R's t.test)
  const tt = unreported(() => (oneSample ? tTest(x, { mu }) : tTest(x, y, { paired, varEqual, mu })));
  const df = tt.parameter!;
  // the effect, its standard error (as tTest's) and the moments of the standardised difference, on the data scaled by
  // the same power of 2 as in tTest (exact; the results are scaled back)
  let m: Moments;
  let k: number;
  let effect: number;
  let se: number;
  if (oneSample) {
    const sc = scaleToUnit([dropNaN(Array.from(x))]);
    k = sc.k;
    const v = sc.groups[0]!;
    const vv = variance(v);
    effect = mean(v) - ldexp(mu, -k);
    se = Math.sqrt(vv / v.length);
    m = { design: "one", n: v.length, delta: effect, s: Math.sqrt(vv) };
  } else if (paired) {
    const [a0, b0] = completePairs(Array.from(x), Array.from(y));
    const sc = scaleToUnit([a0, b0]);
    k = sc.k;
    const [a, b] = sc.groups as [number[], number[]];
    const d = a.map((v, i) => v - b[i]!);
    const s1 = Math.sqrt(variance(a));
    const s2 = Math.sqrt(variance(b));
    // the SD of the differences directly (s1² + s2² - 2 r s1 s2 cancels for r near 1), and 1 - r from it:
    // 1 - r = (sdif² - (s1 - s2)²) / (2 s1 s2)
    const vd = variance(d);
    const sdif = Math.sqrt(vd);
    const oneMinusR = ((sdif - (s1 - s2)) * (sdif + (s1 - s2))) / (2 * s1 * s2);
    effect = mean(d) - ldexp(mu, -k);
    se = Math.sqrt(vd / d.length);
    m = { design: "paired", n: d.length, delta: mean(a) - mean(b) - ldexp(mu, -k), s1, s2, sdif, oneMinusR };
  } else {
    const sc = scaleToUnit([dropNaN(Array.from(x)), dropNaN(Array.from(y))]);
    k = sc.k;
    const [a, b] = sc.groups as [number[], number[]];
    if (a.length < 2 || b.length < 2) throw new RangeError("not enough observations: at least 2 are needed in each sample");
    const [n1, n2, v1, v2] = [a.length, b.length, variance(a), variance(b)];
    effect = mean(a) - mean(b) - ldexp(mu, -k);
    // (tTest's forms)
    se = varEqual
      ? Math.sqrt((((n1 - 1) * v1 + (n2 - 1) * v2) / (n1 + n2 - 2)) * (1 / n1 + 1 / n2))
      : Math.sqrt(Math.sqrt(v1 / n1) ** 2 + Math.sqrt(v2 / n2) ** 2);
    m = { design: "two", n1, n2, delta: effect, s1: Math.sqrt(v1), s2: Math.sqrt(v2) };
  }
  return tostCore("tTOST", effect, k, se, k, df, tt.method, m, k, s, given, []);
}

/**
 * {@link tTOST} from summary statistics: means, standard deviations, sample sizes and, for paired samples, the
 * correlation of the pairs. Equivalent to `TOSTER::tsum_TOST()` in R.
 *
 * The tests and effect sizes are those of tTOST for data with these summaries (Welch's or pooled for two samples;
 * paired from the SD of the differences sqrt(sd1² + sd2² - 2 r12 sd1 sd2)). The one-sided p-values are upper tails
 * where TOSTER takes `1 - pt(t, df)`, so small ones keep their digits. For paired samples with n1 != n2 the smaller
 * is used, with TOSTER's warning `Unequal number of pairs; using smallest n`.
 *
 * @param stats See {@link TsumTOSTStatistics}.
 * @param options See {@link TTOSTOptions}; the bounds are required.
 * @returns See {@link TTOSTResult}.
 * @throws RangeError for sizes below 2 (or not integers), standard deviations that are not positive, a correlation
 *   outside (-1, 1), missing statistics of the second sample, or the errors of {@link tTOST}'s options.
 *
 * @example
 * ```ts
 * const r = tsumTOST({ m1: 5.5125, sd1: 0.4357, n1: 8, m2: 5.3333, sd2: 0.3536, n2: 9 }, { eqb: 0.5 });
 * r.pValue;      // 0.060568376615229305
 * r.smd.confInt; // [-0.35185844793775967, 1.1906849789772087]
 * ```
 *
 * @category Hypothesis tests
 */
export function tsumTOST(stats: TsumTOSTStatistics, options: TTOSTOptions = {}): TTOSTResult {
  checkOptions(stats, TSUM_TOST_KEYS_0, "tsumTOST"); // generated: option-keys.mjs
  checkOptions(options, TSUM_TOST_KEYS_1, "tsumTOST"); // generated: option-keys.mjs
  const s = settingsOf(options);
  const given = boundsOf(options);
  const { m1, sd1, n1, m2, sd2, n2, r12 } = stats;
  const num = (v: unknown, name: string): number => {
    if (typeof v !== "number" || !Number.isFinite(v)) throw new RangeError(`'${name}' must be a finite number`);
    return v;
  };
  const size = (v: unknown, name: string): number => {
    const n = num(v, name);
    if (!(Number.isInteger(n) && n >= 2)) throw new RangeError(`'${name}' must be an integer of at least 2`);
    return n;
  };
  const sdOf = (v: unknown, name: string): number => {
    const sd = num(v, name);
    if (!(sd > 0)) throw new RangeError(`'${name}' must be positive`);
    return sd;
  };
  num(m1, "m1");
  sdOf(sd1, "sd1");
  size(n1, "n1");
  const oneSample = m2 === undefined && sd2 === undefined && n2 === undefined;
  if (s.paired && oneSample) throw new TypeError("'m2', 'sd2' and 'n2' are required when paired is true");
  if (!oneSample) {
    num(m2, "m2");
    sdOf(sd2, "sd2");
    size(n2, "n2");
  }
  const warnings: string[] = [];
  // the means (with mu) and the SDs each scaled by one power of 2 of their own (exact): the SDs enter only through
  // ratios with the difference and through the df, so a mean far larger than the SDs leaves their squares in range.
  // The difference is in the units 2^kM, the SDs and the standard error in 2^kS; the moments in 2^kS
  const { groups: gm, k: kM } = scaleToUnit([[m1, ...(oneSample ? [] : [m2!]), s.mu]]);
  const { groups: gs, k: kS } = scaleToUnit([[sd1, ...(oneSample ? [] : [sd2!])]]);
  const [a1, a2 = NaN] = oneSample ? [gm[0]![0]!] : [gm[0]![0]!, gm[0]![1]!];
  const muS = gm[0]![gm[0]!.length - 1]!;
  const [b1, b2 = NaN] = gs[0]!;
  // the effect in the units of the SDs, for the standardised difference
  const inS = (v: number): number => ldexp(v, kM - kS);
  let effect: number;
  let se: number;
  let df: number;
  let method: string;
  let m: Moments;
  if (oneSample) {
    effect = a1! - muS;
    se = b1! / Math.sqrt(n1);
    df = n1 - 1;
    method = "One Sample t-test";
    m = { design: "one", n: n1, delta: inS(effect), s: b1! };
  } else if (s.paired) {
    const r = num(r12, "r12");
    if (!(r > -1 && r < 1)) throw new RangeError("'r12' must be in (-1, 1)");
    let n = n1;
    if (n1 !== n2) {
      warnings.push("Unequal number of pairs; using smallest n");
      n = Math.min(n1, n2!);
    }
    const sdif = Math.sqrt(b1! * b1! + b2 * b2 - 2 * r * b1! * b2);
    if (!(sdif > 0)) throw new RangeError("the standard deviation of the differences is 0");
    effect = a1! - a2 - muS;
    se = sdif / Math.sqrt(n);
    df = n - 1;
    method = "Paired t-test";
    m = { design: "paired", n, delta: inS(effect), s1: b1!, s2: b2, sdif, oneMinusR: 1 - r };
  } else {
    const n2v = n2!;
    const v1 = b1! * b1!;
    const v2 = b2 * b2;
    effect = a1! - a2 - muS;
    if (s.varEqual) {
      const v = ((n1 - 1) * v1 + (n2v - 1) * v2) / (n1 + n2v - 2);
      se = Math.sqrt(v * (1 / n1 + 1 / n2v));
      df = n1 + n2v - 2;
      method = " Two Sample t-test";
    } else {
      const w1 = v1 / n1;
      const w2 = v2 / n2v;
      se = Math.sqrt(w1 + w2);
      df = (w1 + w2) ** 2 / ((w1 * w1) / (n1 - 1) + (w2 * w2) / (n2v - 1));
      method = "Welch Two Sample t-test";
    }
    m = { design: "two", n1, n2: n2v, delta: inS(effect), s1: b1!, s2: b2 };
  }
  return tostCore("tsumTOST", effect, kM, se, kS, df, method, m, kS, s, given, warnings);
}
