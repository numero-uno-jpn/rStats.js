// Boschloo's exact unconditional test of two independent binomial proportions (2 x 2 table, rows fixed).
//
// Written for rStats.js from Boschloo (1970, Statistica Neerlandica 24, 1-9) and the description in
// oracle/contingency-behaviour.md section 4 (the behaviour of Exact::exact.test(method = "boschloo")):
// - Model: X1 ~ Bin(n1, pi1), X2 ~ Bin(n2, pi2) independent; H0 pi1 = pi2 = pi with pi unknown. The statistic of a
//   table (i, j) is Fisher's conditional p-value T(i, j): one-sided P(X1 <= i | X1 + X2 = i + j) ("less", pi1 < pi2),
//   P(X1 >= i | ...) ("greater"), or two-sided Fisher's p-value ("square", the sum of the conditional probabilities at
//   most (1 + 1e-7) times that of the table, as fisher.test). The rejection region is every table with
//   T <= (1 + 1e-7) T(observed) (the slack keeps tables whose statistic equals the observed one mathematically), and
//   the p-value is the supremum over pi in [0, 1] of the probability of the region,
//   P(pi) = sum over the region of b(i; n1, pi) b(j; n2, pi).
// - "central" (two-sided): the one-sided test in the direction of the data (greater where x1/n1 > x2/n2, else less),
//   p doubled and capped at 1 (as Exact).
// - The region is evaluated table by table (Exact assumes Barnard's convexity and takes shortcuts, which for the
//   two-sided "square" statistic can put tables with Fisher p-value 1 into the region: for 20/60 vs 9/25 its p-value
//   0.785623 exceeds the true 0.785614). The conditional distribution for each total s = i + j is formed once from log
//   factorials and normalised; the one-sided statistics are its cumulative sums from the near end, the two-sided one
//   the sum of both tails below the cut (the distribution is unimodal, so the tails are found by bisection).
// - The supremum: P(pi) is a polynomial of degree N = n1 + n2 that can have several local maxima, so neither Exact's
//   100-point grid with optimise (rounded to 12 digits) nor exact2x2's 98-point grid maximum gives it to more than about
//   8 digits. Here P is evaluated on a grid uniform in theta with pi = sin^2(theta) (the binomial's variance-stabilising
//   scale, where every peak has a width of about 1/sqrt(2 N) or more) of max(1000, 32 sqrt(N)) points plus both ends,
//   and every grid local maximum within 10% of the largest is refined by Brent's localmin (src/optim/localmin.ts) to
//   the precision of the doubles.
// - Each evaluation uses the region as runs of j in each row i: runs that start at 0 or end at n2 are cumulative sums of
//   b(.; n2, pi) from that end (one-sided regions are such tails), others are summed directly. The binomial vectors are
//   dbinom at the mode and the exact ratios of neighbours from there.

