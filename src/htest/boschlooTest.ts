/**
 * Two-sided method of {@link boschlooTest}: `"square"` (Boschloo's original: Fisher's two-sided p-value as the
 * statistic) or `"central"` (twice the one-sided p-value in the direction of the data).
 *
 * @category Hypothesis tests
 */
export type BoschlooTsMethod = "square" | "central";

const TS_METHODS: readonly BoschlooTsMethod[] = ["square", "central"];

/**
 * Options for {@link boschlooTest}.
 *
 * @category Hypothesis tests
 */
export interface BoschlooTestOptions {
  /**
   * Alternative hypothesis, in Exact's orientation: `"less"` means pi1 < pi2 (the proportion of row 1 below that of
   * row 2). Default `"two.sided"`. Unambiguous abbreviations are accepted.
   */
  alternative?: Alternative | "two" | "l" | "g";
  /** Two-sided method: `"square"` (the default, as Exact) or `"central"`. Ignored for one-sided tests. */
  tsmethod?: BoschlooTsMethod | (string & {});
}

/**
 * Result of {@link boschlooTest}.
 *
 * @category Hypothesis tests
 */
export interface BoschlooTestResult extends HTest {
  /** The common proportion pi under the null hypothesis at which the supremum (the p-value) is attained. */
  nuisanceParameter: number;
}

/** Fine grid: at least this many interior points */
const MIN_GRID = 1000;
/** Points of the grid per sqrt(N): the spacing is about 1/14 of the narrowest peak width 1/sqrt(2 N) in theta (a grid of 60 points refined gives the same suprema to 1e-14 on 1600 random tables) */
const GRID_PER_SQRT_N = 32;
/** Grid local maxima within this fraction of the largest grid value are refined */
const CANDIDATE_RATIO = 0.9;
/** Relative slack of "T <= T(observed)" (fisher.test's for its two-sided p-value) */
const SLACK = 1 + 1e-7;
/** Largest number of tables (n1 + 1)(n2 + 1) (one array of the region; design rule 4) */
const MAX_TABLES = 2 ** 24;
/** Largest number of steps of the evaluations of P on the grid (about 10 s; design rule 4) */
const MAX_WORK = 2 ** 32;

/**
 * Boschloo's exact unconditional test (`method = "boschloo"`) for a 2 x 2 table whose rows are two independent
 * binomial samples. Equivalent to `Exact::exact.test()` in R.
 *
 * The rows are the groups and column 1 counts the events: `[[x1, n1 - x1], [x2, n2 - x2]]`. The statistic is Fisher's
 * exact p-value of each possible table (one-sided, or two-sided for `tsmethod: "square"`), and the p-value is the
 * largest probability, over the common proportion pi under the null hypothesis, of the tables whose statistic is at
 * most the observed one (Boschloo 1970). `alternative: "less"` means pi1 < pi2 (Exact's orientation; exact2x2's
 * `boschloo()` uses the opposite one). `"central"` doubles the one-sided p-value in the direction of the data.
 *
 * The p-value is the true supremum, from a fine grid and a refinement of every candidate maximum; Exact maximises
 * over 100 points refined by `optimise` and rounds to 12 digits (about 1e-9 relative off), and its two-sided
 * `"square"` region can contain tables that do not belong there (docs/differences-from-r.md). `statistic` is the
 * observed Fisher p-value (one-sided in the direction tested, or two-sided for `"square"`), `estimate` the difference
 * of the proportions x1/n1 - x2/n2, and `nuisanceParameter` the pi at which the supremum is attained.
 *
 * A table with more than 2^24 possible outcomes ((n1 + 1)(n2 + 1)) is a RangeError, as is one whose grid would take
 * more than about 10 seconds.
 *
 * @param table A 2 x 2 table of counts: rows are the groups, column 1 the events.
 * @param options See {@link BoschlooTestOptions}.
 * @returns The test result; see {@link BoschlooTestResult}.
 *
 * @example
 * ```ts
 * const r = boschlooTest([[3, 7], [8, 2]], { alternative: "less" });
 * r.pValue;    // 0.020694732666015625 (Exact: 0.020694732666)
 * r.statistic; // 0.034889259347463675 (Fisher's one-sided p-value)
 * r.estimate;  // -0.5
 * ```
 *
 * @category Hypothesis tests
 */
export function boschlooTest(table: readonly Counts[], options: BoschlooTestOptions = {}): BoschlooTestResult {
  checkOptions(options, BOSCHLOO_TEST_KEYS, "boschlooTest"); // generated: option-keys.mjs
  if (table.length !== 2 || table.some((r) => r.length !== 2)) throw new TypeError("'table' must be a 2 x 2 table");
  const alternative = matchAlternative(options.alternative);
  const tsmethod = matchChoice(options.tsmethod, TS_METHODS);
  const t = table.map((r, i) => Array.from(r, (v, j) => checkCount(v, `table[${i}][${j}]`)));
  const [[x1, y1], [x2, y2]] = t as [[number, number], [number, number]];
  const n1 = x1 + y1;
  const n2 = x2 + y2;
  if (n1 === 0 || n2 === 0) throw new RangeError("each row (group) of 'table' must have at least one observation");
  if ((n1 + 1) * (n2 + 1) > MAX_TABLES) {
    throw new RangeError(`Boschloo's test of these group sizes has ${(n1 + 1) * (n2 + 1)} possible tables, more than 2^24`);
  }
  const N = n1 + n2;
  const grid = Math.max(MIN_GRID, Math.ceil(GRID_PER_SQRT_N * Math.sqrt(N)));
  if (grid * (n1 + 3 * n2 + 4) > MAX_WORK) {
    throw new RangeError(`Boschloo's test of these group sizes (${n1} and ${n2}) would take too long`);
  }

  // the statistic: which tail of X1 given X1 + X2 (two-sided: both)
  const estimate = x1 / n1 - x2 / n2;
  let kind: "less" | "greater" | "square";
  if (alternative !== "two.sided") kind = alternative;
  else if (tsmethod === "square") kind = "square";
  else kind = estimate > 0 ? "greater" : "less";
  const s0 = x1 + x2;
  let statistic: number;
  if (kind === "less") statistic = phyper1(x1, n1, n2, s0, true, false);
  else if (kind === "greater") statistic = phyper1(x1 - 1, n1, n2, s0, false, false);
  else statistic = unreported(() => fisherTest(t)).pValue;

  const region = rejectionRegion(n1, n2, x1, x2, kind);
  const { value, at } = supremum(region, n1, n2, grid);
  const pValue = alternative === "two.sided" && tsmethod === "central" ? Math.min(1, 2 * value) : value;
  return reported("boschlooTest", {
    method: "Boschloo's Exact Test",
    alternative,
    statistic,
    statisticName: "test statistic",
    pValue,
    estimate,
    estimateNames: "difference in proportion",
    nullValue: 0,
    nullValueName: "difference in proportion",
    nuisanceParameter: at,
    warnings: [],
  });
}

/** The rejection region as runs [from, to] of j in each row i: runs from starts[i] to starts[i + 1] - 1 */
interface Region {
  starts: Int32Array;
  from: Int32Array;
  to: Int32Array;
}

/**
 * The tables (i, j) whose statistic T(i, j) is at most (1 + 1e-7) T(x1, x2). For each total s the conditional
 * distribution of X1 (hypergeometric) is formed from log factorials (relative error about 1e-12 for the sizes allowed,
 * far within the slack) and normalised by its sum
 */
function rejectionRegion(n1: number, n2: number, x1: number, x2: number, kind: "less" | "greater" | "square"): Region {
  const N = n1 + n2;
  const lf = new Float64Array(N + 1);
  for (let k = 2; k <= N; k++) lf[k] = lfactorial(k);
  const w1 = n2 + 1;
  // statistics of every table, column by column of totals; T[i * w1 + j]
  const T = new Float64Array((n1 + 1) * w1);
  const len = Math.min(n1, n2) + 1;
  const d = new Float64Array(len);
  const left = new Float64Array(len);
  const right = new Float64Array(len);
  for (let s = 0; s <= N; s++) {
    const lo = Math.max(0, s - n2);
    const hi = Math.min(s, n1);
    const m = hi - lo + 1;
    let top = -Infinity;
    for (let k = 0; k < m; k++) {
      const i = lo + k;
      const v = -lf[i]! - lf[n1 - i]! - lf[s - i]! - lf[n2 - s + i]!;
      d[k] = v;
      if (v > top) top = v;
    }
    let total = 0;
    for (let k = 0; k < m; k++) {
      d[k] = Math.exp(d[k]! - top);
      total += d[k]!;
    }
    for (let k = 0; k < m; k++) d[k] = d[k]! / total;
    // cumulative sums from each end (each tail summed from its own end keeps small tails accurate)
    let acc = 0;
    for (let k = 0; k < m; k++) left[k] = acc += d[k]!;
    acc = 0;
    for (let k = m - 1; k >= 0; k--) right[k] = acc += d[k]!;
    if (kind === "less") for (let k = 0; k < m; k++) T[(lo + k) * w1 + s - lo - k] = left[k]!;
    else if (kind === "greater") for (let k = 0; k < m; k++) T[(lo + k) * w1 + s - lo - k] = right[k]!;
    else {
      // the mode (the first largest value): d increases up to it and decreases after it
      let mode = 0;
      for (let k = 1; k < m; k++) if (d[k]! > d[mode]!) mode = k;
      for (let k = 0; k < m; k++) {
        const cut = d[k]! * SLACK;
        // the last a < mode with d[a] <= cut (-1 if none), the first b > mode with d[b] <= cut (m if none)
        let a0 = -1;
        let a1 = mode;
        while (a1 - a0 > 1) {
          const mid = (a0 + a1) >> 1;
          if (d[mid]! <= cut) a0 = mid;
          else a1 = mid;
        }
        let b0 = mode;
        let b1 = m;
        while (b1 - b0 > 1) {
          const mid = (b0 + b1) >> 1;
          if (d[mid]! <= cut) b1 = mid;
          else b0 = mid;
        }
        const p = d[mode]! <= cut ? 1 : (a0 >= 0 ? left[a0]! : 0) + (b1 < m ? right[b1]! : 0);
        T[(lo + k) * w1 + s - lo - k] = Math.min(1, p);
      }
    }
  }
  const cut = T[x1 * w1 + x2]! * SLACK;
  // runs of the region in each row
  const starts = new Int32Array(n1 + 2);
  const from: number[] = [];
  const to: number[] = [];
  for (let i = 0; i <= n1; i++) {
    starts[i] = from.length;
    let j = 0;
    while (j <= n2) {
      if (T[i * w1 + j]! <= cut) {
        const begin = j;
        while (j + 1 <= n2 && T[i * w1 + j + 1]! <= cut) j++;
        from.push(begin);
        to.push(j);
      }
      j++;
    }
  }
  starts[n1 + 1] = from.length;
  return { starts, from: Int32Array.from(from), to: Int32Array.from(to) };
}

/** b(.; n, p) into out: dbinom at the mode and the ratios of neighbours outward */
function binomialVector(n: number, p: number, out: Float64Array): void {
  if (p === 0 || p === 1) {
    out.fill(0);
    out[p === 0 ? 0 : n] = 1;
    return;
  }
  const mode = Math.min(n, Math.floor((n + 1) * p));
  out[mode] = dbinom1(mode, n, p, false);
  const up = p / (1 - p);
  const down = (1 - p) / p;
  for (let i = mode + 1; i <= n; i++) out[i] = out[i - 1]! * (((n - i + 1) / i) * up);
  for (let i = mode - 1; i >= 0; i--) out[i] = out[i + 1]! * (((i + 1) / (n - i)) * down);
}

/** The supremum over pi in [0, 1] of the probability of the region, and a pi where it is attained */
function supremum(region: Region, n1: number, n2: number, grid: number): { value: number; at: number } {
  const { starts, from, to } = region;
  const b1 = new Float64Array(n1 + 1);
  const b2 = new Float64Array(n2 + 1);
  const below = new Float64Array(n2 + 1);
  const above = new Float64Array(n2 + 1);
  const probability = (p: number): number => {
    binomialVector(n1, p, b1);
    binomialVector(n2, p, b2);
    let acc = 0;
    for (let j = 0; j <= n2; j++) below[j] = acc += b2[j]!;
    acc = 0;
    for (let j = n2; j >= 0; j--) above[j] = acc += b2[j]!;
    let total = 0;
    for (let i = 0; i <= n1; i++) {
      const w = b1[i]!;
      if (w === 0) continue;
      let row = 0;
      for (let r = starts[i]!; r < starts[i + 1]!; r++) {
        const f = from[r]!;
        const e = to[r]!;
        if (f === 0) row += below[e]!;
        else if (e === n2) row += above[f]!;
        else for (let j = f; j <= e; j++) row += b2[j]!;
      }
      total += w * row;
    }
    return Math.min(1, total);
  };
  const half = Math.PI / 2;
  const piOf = (theta: number): number => (theta <= 0 ? 0 : theta >= half ? 1 : Math.sin(theta) ** 2);
  // theta_k = (pi / 2) k / (grid + 1), k = 0..grid + 1 (the ends pi = 0 and 1 included: the supremum over the open
  // interval is the maximum of the continuous P on the closed one)
  const values = new Float64Array(grid + 2);
  let best = 0;
  for (let k = 0; k <= grid + 1; k++) {
    values[k] = probability(piOf((half * k) / (grid + 1)));
    if (values[k]! > values[best]!) best = k;
  }
  let value = values[best]!;
  let bestAt = piOf((half * best) / (grid + 1));
  if (value >= 1) return { value: 1, at: bestAt };
  const threshold = CANDIDATE_RATIO * value;
  for (let k = 0; k <= grid + 1; k++) {
    const v = values[k]!;
    if (v < threshold) continue;
    // a local maximum (strict on the left, so that a plateau is refined once)
    if ((k > 0 && !(v > values[k - 1]!)) || (k <= grid && !(v >= values[k + 1]!))) continue;
    const lower = (half * Math.max(0, k - 1)) / (grid + 1);
    const upper = (half * Math.min(grid + 1, k + 1)) / (grid + 1);
    const m = localMin((theta) => -probability(piOf(theta)), lower, upper, 1e-14);
    const refined = probability(piOf(m.x));
    if (refined > value) {
      value = refined;
      bestAt = piOf(m.x);
    }
  }
  return { value, at: bestAt };
}
