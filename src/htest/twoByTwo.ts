// Two independent binomial proportions and the 2 x 2 table: confidence intervals for the difference (DescTools'
// BinomDiffCI), the ratio (DescTools' BinomRatioCI) and the odds ratio (epitools' oddsratio, with epiR's score
// interval as an extra method).
//
// Written for rStats.js from the published methods and the packages' documented behaviour (no R or package code):
// - Difference: Wald; Agresti and Caffo (The American Statistician 54, 2000: one success and one failure added to each
//   group); Newcombe's hybrid score interval (Statistics in Medicine 17, 1998, method 10: the Wilson limits of both
//   proportions combined); Miettinen and Nurminen (Statistics in Medicine 4, 1985) and Farrington-Manning / Mee
//   (Statistics in Medicine 9, 1990; Biometrics 40, 1984) score intervals, whose limits are the roots of the score
//   statistic (src/htest/core/twoProportions.ts). DescTools finds the mn limits by a bisection stopped at 1e-7 and the
//   mee limits with uniroot's tolerance 1.22e-4; the roots here are to the precision of the doubles.
// - Ratio: Katz et al. (Biometrics 34, 1978) log interval, with 0.5 put for a zero count (and n - 0.5 for both counts
//   when both are full), as DescTools; Koopman's score interval (Biometrics 40, 1984) as the roots of his statistic.
// - Odds ratio: Wald (Woolf); the conditional MLE and Fisher's exact interval (fisherTest); the median-unbiased
//   estimate and the mid-p exact interval (Rothman, Greenland and Lash, Modern Epidemiology, 2008, ch. 14): with X
//   the (1, 1) cell under Fisher's noncentral hypergeometric distribution given the margins, the estimate solves
//   P(X <= a) = P(X >= a), the lower limit P(X > a) + 1/2 P(X = a) = alpha/2 and the upper P(X < a) + 1/2 P(X = a) =
//   alpha/2, solved on the log scale to the precision of the doubles (epitools uses uniroot on [0, 1000] with the
//   tolerance 1.22e-4 and fails beyond); the score interval of the odds ratio (Miettinen and Nurminen without
//   N/(N - 1), as epiR). The p-values are epitools': the doubled one-sided mid-p, Fisher's two-sided p and Pearson's
//   chi-squared without continuity correction.

