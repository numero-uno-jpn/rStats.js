/** Katz's log interval of (x1/n1)/(x2/n2) at z, centred at that ratio */
function katzInterval(x1: number, n1: number, x2: number, n2: number, z: number): [number, number] {
  const ratio = x1 / n1 / (x2 / n2);
  const half = z * Math.sqrt(1 / x1 - 1 / n1 + 1 / x2 - 1 / n2);
  return [ratio * Math.exp(-half), ratio * Math.exp(half)];
}

/**
 * Confidence interval for the ratio p1/p2 of two independent proportions x1/n1 and x2/n2 (the risk ratio). Equivalent
 * to `DescTools::BinomRatioCI()` in R.
 *
 * Methods (`method`): `"katz.log"` (the default; Katz's log interval, with 0.5 put for a zero count, and n - 0.5 for
 * both counts when both groups are all successes, as DescTools) and `"koopman"` (Koopman's score interval, also epiR's
 * score interval of the risk ratio), whose limits are the roots of Koopman's statistic to the precision of the
 * doubles. With `sides: "left"` or `"right"` only the lower or the upper limit is kept, at the one-sided level
 * `confLevel`, and the other end is Infinity or 0 (DescTools computes the one-sided level but keeps both limits).
 * With x1 = x2 = 0 the estimate is 0 and the interval [0, Infinity], as DescTools.
 *
 * @param x1 Successes in group 1.
 * @param n1 Trials in group 1.
 * @param x2 Successes in group 2.
 * @param n2 Trials in group 2.
 * @param options See {@link BinomRatioCIOptions}.
 * @returns The estimate p1/p2 and the interval; see {@link BinomRatioCIResult}.
 * @throws RangeError for counts that are not integers with 0 <= x <= n, n > 0, a level outside (0, 1) (at least 0.5
 *   one-sided), or an unknown method or sides.
 *
 * @example
 * ```ts
 * binomRatioCI(56, 70, 48, 80).confInt; // [1.076626422763193, 1.6512485112663868]
 * binomRatioCI(56, 70, 48, 80, { method: "koopman" }).confInt; // [1.0798215063618983, 1.6708055780191118]
 * ```
 *
 * @category Hypothesis tests
 */
export function binomRatioCI(x1: number, n1: number, x2: number, n2: number, options: BinomRatioCIOptions = {}): BinomRatioCIResult {
  checkOptions(options, BINOM_RATIO_CI_KEYS, "binomRatioCI"); // generated: option-keys.mjs
  const method = matchChoice(options.method, RATIO_METHODS);
  const lv = intervalLevel(options.confLevel, options.sides);
  const [a1, m1] = checkTrials(x1, n1, "x1", "n1");
  const [a2, m2] = checkTrials(x2, n2, "x2", "n2");
  const z = lv.kappa;
  // as DescTools, 0 (not NaN) for 0/0
  const est = a1 === 0 ? 0 : a1 / m1 / (a2 / m2);
  let lower: number;
  let upper: number;
  if (a1 === 0 && a2 === 0) [lower, upper] = [0, Infinity];
  else if (method === "katz.log") {
    if (a1 === 0) [lower, upper] = [0, katzInterval(0.5, m1, a2, m2, z)[1]];
    else if (a2 === 0) [lower, upper] = [katzInterval(a1, m1, 0.5, m2, z)[0], Infinity];
    else if (a1 === m1 && a2 === m2) [lower, upper] = katzInterval(m1 - 0.5, m1, m2 - 0.5, m2, z);
    else [lower, upper] = katzInterval(a1, m1, a2, m2, z);
  } else {
    [lower, upper] = ratioScoreLimits(a1, m1, a2, m2, lv.chisq);
  }
  if (lv.sides === "left") upper = Infinity;
  else if (lv.sides === "right") lower = 0;
  return reported("binomRatioCI", {
    estimate: est,
    confInt: [lower, upper],
    confLevel: options.confLevel ?? 0.95,
    method,
    sides: lv.sides,
    warnings: [],
  });
}

