/**
 * The two-sided limits of binomDiffCI for checked counts at the level lv (also used by binomDiffEquivalenceTest, with
 * the level built from its alpha)
 */
export function binomDiffLimits(a1: number, m1: number, a2: number, m2: number, method: BinomDiffCIMethod, lv: IntervalLevel): [number, number] {
  const { kappa } = lv;
  const p1 = a1 / m1;
  const p2 = a2 / m2;
  const est = p1 - p2;
  let lower: number;
  let upper: number;
  switch (method) {
    case "wald": {
      const half = kappa * Math.sqrt((p1 * (1 - p1)) / m1 + (p2 * (1 - p2)) / m2);
      [lower, upper] = [Math.max(-1, est - half), Math.min(1, est + half)];
      break;
    }
    case "ac": {
      const q1 = (a1 + 1) / (m1 + 2);
      const q2 = (a2 + 1) / (m2 + 2);
      const centre = q1 - q2;
      const half = kappa * Math.sqrt((q1 * (1 - q1)) / (m1 + 2) + (q2 * (1 - q2)) / (m2 + 2));
      [lower, upper] = [Math.max(-1, centre - half), Math.min(1, centre + half)];
      break;
    }
    case "score": {
      const [l1, u1] = wilsonLimits(a1, m1, kappa);
      const [l2, u2] = wilsonLimits(a2, m2, kappa);
      lower = est - kappa * Math.sqrt((l1 * (1 - l1)) / m1 + (u2 * (1 - u2)) / m2);
      upper = est + kappa * Math.sqrt((u1 * (1 - u1)) / m1 + (l2 * (1 - l2)) / m2);
      break;
    }
    case "mn":
    case "mee":
      [lower, upper] = diffScoreLimits(a1, m1, a2, m2, lv.chisq, method);
      break;
  }
  return [Math.min(lower, upper), Math.max(lower, upper)];
}

/**
 * Confidence interval for the difference p1 - p2 of two independent proportions x1/n1 and x2/n2. Equivalent to
 * `DescTools::BinomDiffCI()` in R.
 *
 * Methods (`method`): `"ac"` (Agresti-Caffo, the default as in DescTools: the Wald interval with one success and one
 * failure added to each group), `"wald"`, `"score"` (Newcombe's hybrid score interval, his method 10), `"mn"`
 * (Miettinen-Nurminen score interval) and `"mee"` (Farrington-Manning / Mee: the same without the factor N/(N - 1);
 * epiR's score interval of the attributable risk). With `sides: "left"` or `"right"` only the lower or the upper limit
 * is kept, at the one-sided level `confLevel`, and the other end is 1 or -1. The `"mn"` and `"mee"` limits are the
 * roots of the score statistic to the precision of the doubles (DescTools stops at about 1e-7 and 1e-4).
 *
 * @param x1 Successes in group 1.
 * @param n1 Trials in group 1.
 * @param x2 Successes in group 2.
 * @param n2 Trials in group 2.
 * @param options See {@link BinomDiffCIOptions}.
 * @returns The estimate p1 - p2 and the interval; see {@link BinomDiffCIResult}.
 * @throws RangeError for counts that are not integers with 0 <= x <= n, n > 0, a level outside (0, 1) (at least 0.5
 *   one-sided), or an unknown method or sides.
 *
 * @example
 * ```ts
 * binomDiffCI(56, 70, 48, 80).confInt; // [0.05245292663805373, 0.3357584554757674]
 * binomDiffCI(56, 70, 48, 80, { method: "mn" }).confInt; // [0.05282971324584462, 0.33817294001586834]
 * ```
 *
 * @category Hypothesis tests
 */
export function binomDiffCI(x1: number, n1: number, x2: number, n2: number, options: BinomDiffCIOptions = {}): BinomDiffCIResult {
  checkOptions(options, BINOM_DIFF_CI_KEYS, "binomDiffCI"); // generated: option-keys.mjs
  const method = matchChoice(options.method, DIFF_METHODS);
  const lv = intervalLevel(options.confLevel, options.sides);
  const [a1, m1] = checkTrials(x1, n1, "x1", "n1");
  const [a2, m2] = checkTrials(x2, n2, "x2", "n2");
  const est = a1 / m1 - a2 / m2;
  let [lower, upper] = binomDiffLimits(a1, m1, a2, m2, method, lv);
  if (lv.sides === "left") upper = 1;
  else if (lv.sides === "right") lower = -1;
  return reported("binomDiffCI", {
    estimate: est,
    confInt: [lower, upper],
    confLevel: options.confLevel ?? 0.95,
    method,
    sides: lv.sides,
    warnings: [],
  });
}

