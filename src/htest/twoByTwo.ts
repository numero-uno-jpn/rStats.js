/**
 * Largest support of the (1, 1) cell for the exact estimate and interval ("midp", "fisher"): the three root searches
 * evaluate the density over the support some 50 to 100 times each (2^23 values take about 6 s, 2^24 about 12 s)
 */
const MAX_EXACT_SUPPORT = 2 ** 23;
/** Largest support for Fisher's p-value from the array of the density (fisherTest's way, about 0.1 s at 2^20) */
const MAX_ARRAY_PVALUE = 2 ** 20;

/** Double-double sum of v[from..to] */
function sumRange(v: Float64Array, from: number, to: number): number {
  let acc: DD = [0, 0];
  for (let i = Math.max(0, from); i <= Math.min(to, v.length - 1); i++) if (v[i] !== 0) acc = ddAdd(acc, [v[i]!, 0]);
  return acc[0];
}

/**
 * Odds ratio of a 2 x 2 table with its confidence interval and three p-values of independence. Equivalent to
 * `epitools::oddsratio()` in R.
 *
 * The table is in epitools' orientation: rows are the exposure (row 1 the reference level) and columns the outcome
 * (column 1 without the disease); the odds ratio x11 x22 / (x12 x21) is the same for the transposed table.
 *
 * Methods (`method`): `"midp"` (the default, as epitools: the median-unbiased estimate and the mid-p exact interval
 * from Fisher's noncentral hypergeometric distribution of x11 given the margins), `"fisher"` (the conditional MLE and
 * the exact interval of {@link fisherTest}), `"wald"` (the sample odds ratio and Woolf's interval on the log scale;
 * as epitools, no zero-cell correction: a zero cell gives an estimate of 0 or Infinity and NaN for the limit that is
 * not defined) and `"score"` (the sample odds ratio and the score interval of epiR's `epi.2by2`, Miettinen-Nurminen
 * without the factor N/(N - 1)). The mid-p and score limits are the roots of their equations to the precision of the
 * doubles (epitools solves with uniroot's tolerance on [0, 1000] and fails beyond and for zero cells; epiR steps by
 * 0.1%). With a zero cell the mid-p estimate and limits follow the conventions of exact2x2: 0 or Infinity at the end
 * of the support.
 *
 * `pValue` has epitools' three p-values: the two-sided mid-p (twice the smaller one-sided mid-p value), Fisher's
 * exact test and Pearson's chi-squared without continuity correction (with R's warning "Chi-squared approximation may
 * be incorrect" where an expected count is below 5).
 *
 * @param table A 2 x 2 table of counts as an array of rows.
 * @param options See {@link OddsRatioOptions}.
 * @returns See {@link OddsRatioResult}.
 * Limits: the exact methods (`"midp"`, `"fisher"`) need the support of x11 given the margins (min(x11, x22) +
 * min(x12, x21) + 1 values) to be at most 2^23 (about 6 s), and `"fisher"` counts of at most 2^31 - 1 (as
 * `fisherTest`); the p-values of every method need phyper within its 2^26 terms (counts up to about 1e12).
 *
 * @throws TypeError if the table is not 2 x 2; RangeError for negative or non-integer counts, a table of zeros, a
 *   level outside (0, 1), an unknown method, or a table beyond the limits above.
 *
 * @example
 * ```ts
 * const r = oddsRatio([[56, 14], [48, 32]]);
 * r.estimate; // 2.6364237331551914
 * r.confInt;  // [1.276159154292712, 5.670866460839431]
 * r.pValue;   // { midp: 0.008449442679452648, fisher: 0.012521129749209155, chiSquare: 0.00804508136819659 }
 * ```
 *
 * @category Hypothesis tests
 */
export function oddsRatio(table: readonly Counts[], options: OddsRatioOptions = {}): OddsRatioResult {
  checkOptions(options, ODDS_RATIO_KEYS, "oddsRatio"); // generated: option-keys.mjs
  const method = matchChoice(options.method, OR_METHODS);
  if (table.length !== 2 || table.some((r) => r.length !== 2)) throw new TypeError("'table' must be a 2 x 2 table");
  const confLevel = options.confLevel ?? 0.95;
  const { alpha, kappa, chisq } = intervalLevel(confLevel, undefined);
  const t = table.map((r, i) => Array.from(r, (v, j) => checkCount(v, `table[${i}][${j}]`)));
  const [[a, b], [c, d]] = t as [[number, number], [number, number]];

  const n = a + b + c + d;
  if (n === 0) throw new RangeError("all entries of the table are zero");
  // (the hypergeometric p-values need exact margins)
  if (!(n <= 2 ** 53)) throw new RangeError("the total of the table must be at most 2^53");
  // the support of the (1, 1) cell given the margins (min(a, d) + min(b, c) + 1 values)
  const lo = Math.max(0, a - d);
  const hi = a + Math.min(b, c);
  const size = hi - lo + 1;
  if (method === "midp" || method === "fisher") {
    if (size > MAX_EXACT_SUPPORT) {
      throw new RangeError(`the exact distribution of the 2 x 2 table has ${size} values, more than 2^23: use method "wald" or "score"`);
    }
    // (fisherTest's limit, as R's fisher.test)
    if (method === "fisher" && Math.max(a, b, c, d) > 2147483647) {
      throw new RangeError("'table' has entries too large for the conditional MLE (above 2^31 - 1): use method \"wald\" or \"score\"");
    }
  }

  // ---- p-values ----
  // (from the central hypergeometric distribution by phyper: no array of the support for the closed-form methods.
  // phyper's limit of 2^26 terms, met with counts of about 1e13, bounds every method: 2 s at counts of 1e12)
  let below: number;
  let above: number;
  let fisherP: number;
  try {
    below = phyper1(a - 1, a + c, b + d, a + b, true, false) + 0.5 * dhyper1(a, a + c, b + d, a + b, false);
    above = phyper1(a, a + c, b + d, a + b, false, false) + 0.5 * dhyper1(a, a + c, b + d, a + b, false);
    // Fisher's two-sided p-value: from the density over the support as fisherTest where it is small enough to hold
    // (R's bits), from two tails by phyper beyond (counts of 1e9: fisherTest stops at entries above 2^31 - 1)
    fisherP =
      size <= MAX_ARRAY_PVALUE
        ? twoSidedPValue(new OddsRatioDistribution(a + c, b + d, a + b), a, 1)
        : twoSidedPValueUnimodal(a, a + c, b + d, a + b);
  } catch (e) {
    if (e instanceof RangeError) throw new RangeError(`the exact p-values of the table are beyond reach: ${e.message}`);
    throw e;
  }
  const midp = 2 * Math.min(below, above);
  const rows = [a + b, c + d];
  const cols = [a + c, b + d];
  // Pearson's statistic summed in R's (column) order, with expected counts r_i c_j / n
  let x2 = 0;
  let small = false;
  for (let j = 0; j < 2; j++) {
    for (let i = 0; i < 2; i++) {
      const e = (rows[i]! * cols[j]!) / n;
      if (e < 5) small = true;
      const dev = Math.abs(t[i]![j]! - e);
      x2 += (dev * dev) / e;
    }
  }
  const chiSquare = pgamma1(x2, 0.5, 2, false, false);

  // ---- estimate and interval ----
  let estimate: number;
  let confInt: [number, number];
  switch (method) {
    case "wald": {
      estimate = (a * d) / (b * c);
      const half = kappa * Math.sqrt(1 / a + 1 / b + 1 / c + 1 / d);
      confInt = [Math.exp(Math.log(estimate) - half), Math.exp(Math.log(estimate) + half)];
      break;
    }
    case "fisher": {
      const fisher = unreported(() => fisherTest(t, { confLevel }));
      estimate = fisher.estimate as number;
      confInt = fisher.confInt!;
      break;
    }
    case "score": {
      estimate = (a * d) / (b * c);
      // group 1 = row 1 (x1 = a of n1 = a + b), group 2 = row 2. With zero cells that put the estimate at both 0 and
      // Infinity (a zero row or column, or a = b = 0, ...) the statistic does not depend on the odds ratio: [0, Infinity]
      const atZero = a === 0 || d === 0;
      const atInf = b === 0 || c === 0;
      confInt = atZero && atInf ? [0, Infinity] : oddsRatioScoreLimits(a, a + b, c, c + d, chisq);
      break;
    }
    case "midp": {
      const dist = new OddsRatioDistribution(a + c, b + d, a + b);
      // the mid-p tails P(X < a) + P(X = a)/2 and P(X > a) + P(X = a)/2 at psi (direct sums, no 1 - x)
      const tails = (psi: number): [number, number] => {
        if (psi === 1) return [below, above];
        const dens = dist.density(psi);
        const j = a - lo;
        const half = 0.5 * dens[j]!;
        return [sumRange(dens, 0, j - 1) + half, sumRange(dens, j + 1, dens.length - 1) + half];
      };
      const root = (f: (psi: number) => number, increasing: boolean): number => {
        const f1 = f(1);
        if (f1 === 0) return 1;
        return logScaleRoot(f, increasing ? f1 > 0 : f1 < 0);
      };
      // P(X <= a) - P(X >= a) = 0, i.e. the lower mid-p tail = 1/2 (decreasing in psi)
      estimate = a === lo ? 0 : a === hi ? Infinity : root((psi) => tails(psi)[0] - 0.5, false);
      const lower = a === lo ? 0 : root((psi) => tails(psi)[1] - alpha / 2, true);
      const upper = a === hi ? Infinity : root((psi) => tails(psi)[0] - alpha / 2, false);
      confInt = [lower, upper];
      break;
    }
  }
  return reported("oddsRatio", {
    estimate,
    confInt,
    confLevel,
    method: OR_DESCRIPTIONS[method],
    pValue: { midp, fisher: fisherP, chiSquare },
    warnings: small ? ["Chi-squared approximation may be incorrect"] : [],
  });
}

