// Method comparison regression, as mcr's mcreg: Deming regression, weighted Deming regression (constant coefficient
// of variation) and Passing-Bablok regression, with analytical, jackknife and bootstrap intervals of the intercept
// and slope (quantile, Student, BCa and bootstrap-t, the last with nested resamples), and the CUSUM statistic of
// linearity of Passing and Bablok.
//
// Written for rStats.js from oracle/methodcomparison-behaviour.md (section 2) and the published methods (no R or
// package code was read):
// - Deming: Cornbleet PJ, Gochman N (1979), Incorrect least-squares regression coefficients in method-comparison
//   analysis, Clin Chem 25:432-438, and Linnet K (1990), Estimation of the linear relationship between the
//   measurements of two methods with proportional errors, Stat Med 9:1463-1473 (λ = error variance of x over that of
//   y, as mcr's error.ratio): the slope is the positive-discriminant root of λ p b² - (λq - u) b - p = 0 with u, q, p
//   the centred sums of squares and products. Its analytical standard error is Strike PW (1991), Statistical Methods
//   in Laboratory Medicine.
// - Weighted Deming: Linnet (1990), the iteration of the Deming fit with the weights 1/((x̂ + λŷ)/(1 + λ))² of the
//   points projected on the current line; mcr's stopping rule (an absolute threshold on both coefficients).
// - Passing H, Bablok W (1983), A new biometrical procedure for testing the equality of measurements from two
//   different analytical methods, J Clin Chem Clin Biochem 21:709-720: the shifted median of the pairwise slopes
//   (slopes of -1 left out, the median shifted by the number K of slopes below -1), the rank interval with
//   C = z sqrt(N(N - 1)(2N + 5)/18), the intercept as the median of y - b x, and the cumulative sum of the signs of the
//   residuals ordered by their projection on the line (linearity). mcr stores each slope as an angle and averages
//   two middle angles (or two slopes, "tangent").
// - Linnet K (1993), Evaluation of regression procedures for methods comparison studies, Clin Chem 39:424-432: the
//   jackknife standard errors and intervals.
// - Efron B, Tibshirani RJ (1993), An Introduction to the Bootstrap: the bootstrap percentile, BCa (bias correction
//   z0 and the jackknife acceleration) and bootstrap-t intervals.
//
// The data are divided by one power of 2 first (src/internal/summary.ts), so that the sums of squares and the 1e-12
// tie rule of Passing-Bablok can neither overflow nor underflow; the slope has no units, the intercept and its
// interval are scaled back at the end (exact).

