/**
 * a - b, set to 0 when |a - b| < 1e-12 (|a| + |b|)/2: mcr's rule for ties of Passing-Bablok (and of 1 - r² in Deming's
 * standard error). Applied to data scaled to [1, 2), so the sum cannot overflow
 */
function tieDiff(a: number, b: number): number {
  const d = a - b;
  return Math.abs(d) < (1e-12 * (Math.abs(a) + Math.abs(b))) / 2 ? 0 : d;
}

/** Centred sums of squares and products (double-double) and the means of x and y */
function moments(x: readonly number[], y: readonly number[]): { u: DD; q: DD; p: DD; mx: DD; my: DD } {
  const mx = meanDD(x);
  const my = meanDD(y);
  let u: DD = [0, 0];
  let q: DD = [0, 0];
  let p: DD = [0, 0];
  for (let i = 0; i < x.length; i++) {
    const dx = ddSub([x[i]!, 0], mx);
    const dy = ddSub([y[i]!, 0], my);
    u = ddAdd(u, ddMul(dx, dx));
    q = ddAdd(q, ddMul(dy, dy));
    p = ddAdd(p, ddMul(dx, dy));
  }
  return { u, q, p, mx, my };
}

/**
 * The Deming slope from the sums u (x), q (y), p (cross products) and λ: the root of λ p b² - (λq - u) b - p = 0 of
 * the sign of p, (a + R)/(2λp) with a = λq - u and R = sqrt(a² + 4λp²), or 2p/(R - a) where a < 0 (the same root
 * without cancellation: mcr's form gives slope 0 for λ = 1e-300). For λ > 1 the equation is divided by λ first, so
 * that λq and λp² cannot overflow (λ = 1e300). NaN for p = 0 (no linear relation: the root is 0, infinite or
 * undefined), as mcr
 */
function demingSlope(u: number, q: number, p: number, lambda: number): number {
  if (p === 0) return NaN;
  if (lambda <= 1) {
    const a = lambda * q - u;
    const r = Math.sqrt(a * a + 4 * lambda * p * p);
    return a >= 0 ? (a + r) / (2 * lambda * p) : (2 * p) / (r - a);
  }
  // p b² - (q - u/λ) b - p/λ = 0
  const a = q - u / lambda;
  const r = Math.sqrt(a * a + (4 * p * p) / lambda);
  return a >= 0 ? (a + r) / (2 * p) : (2 * p) / lambda / (r - a);
}

/** Deming regression with Strike's analytical standard errors, on scaled data */
function demingFit(x: readonly number[], y: readonly number[], lambda: number): DemingFit {
  const n = x.length;
  const { u, q, p, mx, my } = moments(x, y);
  const b1 = demingSlope(u[0], q[0], p[0], lambda);
  const b0 = ddSub(my, ddMul([b1, 0], mx))[0];
  // 1 - r² = (uq - p²)/(uq), formed in double-double (mcr's 1 - p²/(uq) loses digits for r near 1), set to 0 by the
  // tie rule as mcr does (an exact line has standard errors 0)
  const uq = ddMul(u, q);
  const r2 = (p[0] * p[0]) / (u[0] * q[0]);
  let omr2 = ddSub(uq, ddMul(p, p))[0] / (uq[0] + uq[1]);
  if (Math.abs(omr2) < (1e-12 * (1 + r2)) / 2) omr2 = 0;
  const se1 = Math.sqrt((b1 * b1 * omr2) / r2 / (n - 2));
  let sx2: DD = [0, 0];
  for (const v of x) sx2 = ddAdd(sx2, ddMul([v, 0], [v, 0]));
  const se0 = Math.sqrt(se1 * se1 * ddDivNum(sx2, n)[0]);
  return { b0, b1, se0, se1, xmean: mx[0] };
}

/**
 * Weighted Deming regression (Linnet 1990) with mcr's stopping rule, on x scaled by 2^-kx and y by 2^-ky, with the
 * error ratio of the scaled data (lambda) and mix = errorRatio 2^(ky - kx): the level m = (x̂ + errorRatio ŷ)/(1 +
 * errorRatio) of a point is, up to one constant factor, x̂ + mix ŷ in the scaled units. The weights 1/m² enter only
 * through the weighted means (with the weights divided by the largest, so that they cannot overflow) and the sums
 * of (dx/m)², (dy/m)² and dx dy/m², which do not depend on that factor (the slope is homogeneous in them); mcr's
 * weights 1/m², which overflow for data spanning more than about 1e154, are formed only for output
 */
function wdemingFit(
  x: readonly number[],
  y: readonly number[],
  lambda: number,
  mix: number,
  errorRatio: number,
  iterMax: number,
  threshold: number,
  kx: number,
  ky: number,
): Fit & { xmean: number; weights: number[]; converged: boolean } {
  const n = x.length;
  const start = demingFit(x, y, lambda);
  let b0 = start.b0;
  let b1 = start.b1;
  let xmean = NaN;
  // m up to the factor (mix > 1 ? mix : 1)/(1 + errorRatio) 2^kx: x̂ + mix ŷ, or x̂/mix + ŷ for mix > 1
  const m = new Array<number>(n);
  let count = iterMax;
  for (let i = 0; i < iterMax; i++) {
    const f = 1 + lambda * b1 * b1;
    let mMin = Infinity;
    for (let j = 0; j < n; j++) {
      const d = y[j]! - (b0 + b1 * x[j]!);
      const xh = x[j]! + (lambda * b1 * d) / f;
      const yh = y[j]! - d / f;
      m[j] = mix > 1 ? xh / mix + yh : xh + mix * yh;
      mMin = Math.min(mMin, Math.abs(m[j]!));
    }
    let sw: DD = [0, 0];
    let swx: DD = [0, 0];
    let swy: DD = [0, 0];
    for (let j = 0; j < n; j++) {
      // the weight relative to the largest, (mMin/m)^2 <= 1
      const r = mMin / m[j]!;
      const wj: DD = [r * r, 0];
      sw = ddAdd(sw, wj);
      swx = ddAdd(swx, ddMul(wj, [x[j]!, 0]));
      swy = ddAdd(swy, ddMul(wj, [y[j]!, 0]));
    }
    const xw = ddDivNum(swx, sw[0] + sw[1]);
    const yw = ddDivNum(swy, sw[0] + sw[1]);
    let u: DD = [0, 0];
    let q: DD = [0, 0];
    let p: DD = [0, 0];
    for (let j = 0; j < n; j++) {
      const dx = ddDivNum(ddSub([x[j]!, 0], xw), m[j]!);
      const dy = ddDivNum(ddSub([y[j]!, 0], yw), m[j]!);
      u = ddAdd(u, ddMul(dx, dx));
      q = ddAdd(q, ddMul(dy, dy));
      p = ddAdd(p, ddMul(dx, dy));
    }
    const B1 = demingSlope(u[0], q[0], p[0], lambda);
    const B0 = ddSub(yw, ddMul([B1, 0], xw))[0];
    xmean = xw[0];
    // the threshold is absolute, on the slope and the intercept in the units of the data
    const done = ldexp(Math.abs(b1 - B1), ky - kx) < threshold && ldexp(Math.abs(b0 - B0), ky) < threshold;
    b0 = B0;
    b1 = B1;
    if (done) {
      count = i + 1;
      break;
    }
  }
  // mcr's weights 1/m² in the units of the data (Infinity or 0 where they leave the double range). The true level is
  // m (errorRatio/(1 + errorRatio)) 2^ky for mix > 1 and m/(1 + errorRatio) 2^kx otherwise; the powers of 2 of
  // errorRatio, 1 + errorRatio and the units are carried apart from the products, which would overflow or underflow
  // where x and y have very different units although the weight itself is representable
  const [sR, tR] = split(errorRatio);
  const [s1, t1] = split(1 + errorRatio);
  const weights = m.map((v) =>
    mix > 1 ? ldexpWide((s1 / (sR * v)) ** 2, 2 * (t1 - tR - ky)) : ldexpWide((s1 / v) ** 2, 2 * (t1 - kx)),
  );
  // as mcr: the warning also when the last allowed iteration converged
  return { b0, b1, xmean, weights, converged: count < iterMax };
}

/** A positive finite v as [s, t] with v = s 2^t exactly, s in [1/2, 4) */
function split(v: number): [number, number] {
  const t = Math.floor(Math.log2(v));
  return [ldexpWide(v, -t), t];
}

/** The angle of a slope (±π/2 for a vertical pair) */
const angle = (s: number): number => Math.atan(s);
/** The slope of an entry of the sorted list: dy/dx itself, tan(±π/2) for a vertical pair (as mcr's tan of the angle) */
const slopeOf = (s: number): number => (Number.isFinite(s) ? s : Math.tan(angle(s)));

/** Passing-Bablok's sorted slopes and the counts of the shifted median */
interface PabaSlopes {
  sorted: Float64Array;
  /** Offset O of the positions (2K + E with a positive correlation, -(2K + E) otherwise) */
  offset: number;
  /** Number E of slopes exactly -1 (+1 with a negative correlation) */
  e: number;
}

/**
 * The pairwise slopes of Passing-Bablok, sorted. Differences below a relative 1e-12 are 0 (mcr's rule); a vertical pair
 * is +Infinity for a positive (or zero) Kendall correlation and -Infinity otherwise, a pair with both differences 0
 * is left out. The counts compare the angles atan(dy/dx) with ∓π/4, as mcr
 */
function pabaSlopes(x: readonly number[], y: readonly number[]): PabaSlopes {
  const n = x.length;
  // Kendall's S: its sign is that of tau_b
  let s = 0;
  for (let j = 0; j < n; j++) {
    for (let k = j + 1; k < n; k++) s += Math.sign(x[k]! - x[j]!) * Math.sign(y[k]! - y[j]!);
  }
  const posCor = s >= 0;
  const slopes = new Float64Array((n * (n - 1)) / 2);
  let m = 0;
  let e = 0;
  let kk = 0;
  const quarter = Math.PI / 4;
  for (let j = 0; j < n; j++) {
    for (let k = j + 1; k < n; k++) {
      const dx = tieDiff(x[k]!, x[j]!);
      const dy = tieDiff(y[k]!, y[j]!);
      let v: number;
      if (dx !== 0) v = dy / dx;
      else if (dy !== 0) v = posCor ? Infinity : -Infinity;
      else continue;
      slopes[m++] = v;
      const t = angle(v);
      if (posCor) {
        if (t === -quarter) e++;
        else if (t < -quarter) kk++;
      } else if (t === quarter) e++;
      else if (t > quarter) kk++;
    }
  }
  const sorted = slopes.subarray(0, m).sort();
  return { sorted, offset: posCor ? 2 * kk + e : -(2 * kk + e), e };
}

/**
 * The slope at the shifted median position m (1-based, of the sorted list): the entry (m + 1)/2 for odd m, the mean of
 * the entries m/2 and m/2 + 1 for even m (tan of the mean angle, or the mean slope). NaN if a position is outside
 */
function pabaAt(sorted: Float64Array, m: number, tangent: boolean): number {
  const len = sorted.length;
  if (m % 2 !== 0) {
    const j = (m + 1) / 2;
    return j >= 1 && j <= len ? slopeOf(sorted[j - 1]!) : NaN;
  }
  const j = m / 2;
  if (j < 1 || j + 1 > len) return NaN;
  const l = sorted[j - 1]!;
  const r = sorted[j]!;
  return tangent ? (slopeOf(l) + slopeOf(r)) / 2 : Math.tan((angle(l) + angle(r)) / 2);
}

/** The median (R's: the mean of the two middle values for an even count) */
function median(v: number[]): number {
  const s = Float64Array.from(v).sort();
  const h = s.length >> 1;
  return s.length % 2 === 1 ? s[h]! : (s[h - 1]! + s[h]!) / 2;
}

/** median(y - b x) with the tie rule (Passing-Bablok's intercept); ∓Infinity for a slope of ±Infinity */
function pabaIntercept(x: readonly number[], y: readonly number[], b: number): number {
  if (!Number.isFinite(b)) return -b;
  return median(x.map((v, i) => tieDiff(y[i]!, b * v)));
}

/** Passing-Bablok's estimates, on scaled data */
function pabaFit(x: readonly number[], y: readonly number[], tangent: boolean): Fit & { slopes: PabaSlopes } {
  const slopes = pabaSlopes(x, y);
  const b1 = pabaAt(slopes.sorted, slopes.sorted.length + slopes.offset, tangent);
  return { b0: Number.isNaN(b1) ? NaN : pabaIntercept(x, y, b1), b1, slopes };
}

/**
 * Passing-Bablok's rank interval of the slope at the normal quantile z, and the intercept's: [-Inf, Inf] for both
 * where either end is not defined (too few points), with defined false
 */
function pabaInterval(
  x: readonly number[],
  y: readonly number[],
  slopes: PabaSlopes,
  z: number,
  tangent: boolean,
): { slope: [number, number]; intercept: [number, number]; defined: boolean } {
  const n = x.length;
  const { sorted, offset, e } = slopes;
  const len = sorted.length;
  // (Math.round rounds halves up, which for positive values is C's round, away from zero)
  const c = Math.round(z * Math.sqrt((n * (n - 1) * (2 * n + 5)) / 18));
  const end = (m: number, lower: boolean): number => {
    // C's integer division: truncation toward 0
    const j = Math.trunc((m + 1) / 2);
    if (lower ? j < 2 * e + 1 : j > len) return NaN;
    if (m % 2 === 0) {
      if (j + 1 > len) return NaN;
      const l = sorted[j - 1]!;
      const r = sorted[j]!;
      return tangent ? (slopeOf(l) + slopeOf(r)) / 2 : Math.tan((angle(l) + angle(r)) / 2);
    }
    return slopeOf(sorted[j - 1]!);
  };
  const lo = end(len - c + offset, true);
  const hi = end(len + c + offset, false);
  if (Number.isNaN(lo) || Number.isNaN(hi)) return { slope: [-Infinity, Infinity], intercept: [-Infinity, Infinity], defined: false };
  return { slope: [lo, hi], intercept: [pabaIntercept(x, y, hi), pabaIntercept(x, y, lo)], defined: true };
}

/**
 * Passing and Bablok's linearity statistic for the fit (b0, b1): the scores +sqrt(L/l) of the l points above the line
 * and -sqrt(l/L) of the L below (0 on it), cumulated in the order of the projections (y + x/b1 - b0)/sqrt(1 + 1/b1²)
 * (ties in the data order)
 */
function cusumOf(x: readonly number[], y: readonly number[], b0: number, b1: number): { nPos: number; nNeg: number; maxCusum: number } {
  const n = x.length;
  const r = x.map((v, i) => y[i]! - b0 - b1 * v);
  const l = r.filter((v) => v > 0).length;
  const L = r.filter((v) => v < 0).length;
  const up = Math.sqrt(L / l);
  const down = -Math.sqrt(l / L);
  const d = x.map((v, i) => (y[i]! + v / b1 - b0) / Math.sqrt(1 + 1 / (b1 * b1)));
  const order = Array.from({ length: n }, (_, i) => i).sort((a, b) => d[a]! - d[b]! || a - b);
  let s = 0;
  let max = 0;
  for (const i of order) {
    const v = r[i]!;
    s += v > 0 ? up : v < 0 ? down : 0;
    max = Math.max(max, Math.abs(s));
  }
  return { nPos: l, nNeg: L, maxCusum: max };
}

/** Whether all values are equal */
const constant = (v: readonly number[]): boolean => v.every((u) => u === v[0]);

/** A positive integer option */
function positiveInteger(v: number, name: string): number {
  if (!(typeof v === "number" && Number.isInteger(v) && v >= 1)) throw new RangeError(`'${name}' must be a positive integer`);
  return v;
}

/** Type 7 quantile of the values at p in [0, 1] */
const q7 = (v: readonly number[], p: number): number => quantile(v, p);

/** Standard deviation without the NaN values (R's sd(na.rm = TRUE)) */
const sdNaRm = (v: readonly number[]): number => standardDeviation(v.filter((u) => !Number.isNaN(u)));

/**
 * Method comparison regression of y (test method) on x (reference method): Deming, weighted Deming or Passing-Bablok
 * regression with analytical, jackknife or bootstrap intervals. Equivalent to `mcr::mcreg()` in R.
 *
 * - **Deming** (`"Deming"`): the slope minimises the squared distances in the metric of the error variances, λ =
 *   `errorRatio` = σ²(x)/σ²(y) (mcr's convention; λ → 0 gives the least-squares slope of y on x). The analytical
 *   standard errors are Strike's (1991), with t intervals on n - 2 degrees of freedom.
 * - **Weighted Deming** (`"WDeming"`): Linnet's (1990) iteration for errors proportional to the level (constant
 *   coefficient of variation), stopped as mcr when both coefficients change by less than `threshold` (absolute), with
 *   a warning when `iterMax` iterations are reached. No analytical interval (jackknife by default). Values must be
 *   positive. Since the threshold is absolute, data of very large magnitude (around 1e150) may not converge and
 *   data of very small magnitude (around 1e-150) stop after the first iteration; choose `threshold` in the units of
 *   the data.
 * - **Passing-Bablok** (`"PaBa"`): the shifted median of the n(n - 1)/2 pairwise slopes and the rank interval of
 *   Passing and Bablok (1983); the intercept is the median of y - b x and its limits those of the slope's limits.
 *   Differences below a relative 1e-12 count as ties (mcr's rule; a pair tied in x only is vertical), so data with a
 *   large offset (1e12 + O(1)) have most differences set to 0; the mean of two middle slopes is tan of the mean angle
 *   (`slopeMeasure: "radian"`, mcr's default; it changes when y is rescaled, as angles do not scale) or the mean slope
 *   (`"tangent"`). Where the interval is not defined (too few points, always for n <= 4) its limits and the
 *   intercept's are -Infinity and Infinity, with a warning. Values must not be negative. The result has the CUSUM
 *   statistic of linearity (`cusum`; no test decision).
 * - **jackknife**: the leave-one-out estimates, the standard error sd(pseudo-values)/sqrt(n) and the interval estimate
 *   ± t se on n - 2 degrees of freedom (Linnet 1993); the estimates are those of all the data.
 * - **bootstrap**: `nsamples` resamples of the pairs with replacement; `"quantile"` the percentile interval,
 *   `"Student"` estimate ± t sd(B), `"BCa"` the bias-corrected and accelerated interval (jackknife acceleration),
 *   `"tBoot"` the bootstrap-t interval with the analytical standard errors (Deming) or, with `"nestedbootstrap"`, the
 *   standard deviation of `nnested` inner resamples of each resample. Resamples with constant x or y are dropped
 *   with mcr's warning (an error when more than 5% are). The resamples are drawn as R's `sample(1:n, n, replace =
 *   TRUE)` from the current random stream, or from `set.seed(rngSeed)` as mcr's `rng.seed` (the generator's state is
 *   then restored if it had one), so the values are mcr's for the same seed. With very few points (n = 5) the
 *   bootstrap-t limits can be infinite or huge, because resamples of 2 or 3 distinct points have standard errors 0.
 *
 * Unlike mcr, the default interval is `"analytical"` (`"jackknife"` for weighted Deming) rather than a random
 * bootstrap; `confLevel` replaces mcr's `alpha` (= 1 - confLevel); 2 or fewer points, constant x or y, infinite
 * values and data whose Deming covariance is 0 are errors. Passing-Bablok's odd-position slopes are dy/dx (mcr: tan of
 * its angle, a few ulps off). PaBaLarge, LinReg, WLinReg, PBequi and TS are not offered.
 *
 * @param x Measurements by the reference method.
 * @param y Measurements by the test method, paired with `x`.
 * @param options See {@link McregOptions}.
 * @returns See {@link McregResult}.
 * @throws TypeError if `x` and `y` differ in length; RangeError for missing values without `naRm`, infinite values,
 *   fewer than 3 pairs, constant x or y, negative values (Passing-Bablok), values that are not positive (weighted
 *   Deming), more than 5793 points (Passing-Bablok), an analytical interval for weighted Deming, a bootstrap-t
 *   interval without nested resamples for Passing-Bablok or weighted Deming, too many degenerate resamples, a zero
 *   covariance (Deming), or an invalid option.
 *
 * @example
 * ```ts
 * const x = [1, 2, 3, 4, 5, 6, 7];
 * const y = [1.2, 1.9, 3.2, 3.8, 5.1, 6.4, 6.6];
 * const d = mcreg(x, y, { methodReg: "Deming" });
 * d.slope.estimate; // 0.97547950725034482
 * d.slope.confInt;  // [0.83267195599246846, 1.1182870585082212]
 * const pb = mcreg(x, y);  // Passing-Bablok
 * pb.slope.estimate;      // 0.95
 * pb.intercept.confInt;   // [-0.8524794459077718, 0.80365513709218339]
 * ```
 *
 * @category Agreement, reliability and factor analysis
 */
export function mcreg(x: Sample, y: Sample, options: McregOptions = {}): McregResult {
  checkOptions(options, MCREG_KEYS, "mcreg"); // generated: option-keys.mjs
  const methodReg = matchChoice(options.methodReg, METHODS);
  const methodCi = matchChoice(options.methodCi ?? (methodReg === "WDeming" ? "jackknife" : "analytical"), CI_METHODS);
  const bootstrap = methodCi === "bootstrap" || methodCi === "nestedbootstrap";
  const methodBootstrapCi = matchChoice(options.methodBootstrapCi, BOOT_METHODS);
  const confLevel = options.confLevel ?? 0.95;
  if (!(typeof confLevel === "number" && confLevel > 0 && confLevel < 1)) throw new RangeError("'confLevel' must be a single number in (0, 1)");
  const slopeMeasure = matchChoice(options.slopeMeasure, ["radian", "tangent"] as const);
  const tangent = slopeMeasure === "tangent";
  const deming = methodReg !== "PaBa";
  const errorRatio = deming ? (options.errorRatio ?? 1) : 1;
  if (deming && !(typeof errorRatio === "number" && errorRatio > 0 && errorRatio < Infinity)) {
    throw new RangeError("'errorRatio' must be a positive finite number");
  }
  const nsamples = positiveInteger(options.nsamples ?? 999, "nsamples");
  const nnested = positiveInteger(options.nnested ?? 25, "nnested");
  const iterMax = positiveInteger(options.iterMax ?? 30, "iterMax");
  const threshold = options.threshold ?? 1e-6;
  if (!(typeof threshold === "number" && threshold >= 0 && threshold < Infinity)) throw new RangeError("'threshold' must be a nonnegative number");
  if (methodReg === "WDeming" && methodCi === "analytical") {
    throw new RangeError("there is no analytical interval for weighted Deming regression (use methodCi \"jackknife\" or a bootstrap)");
  }
  if (methodCi === "bootstrap" && methodBootstrapCi === "tBoot" && methodReg !== "Deming") {
    throw new RangeError(`the bootstrap-t interval of ${methodReg} needs methodCi "nestedbootstrap" (there is no analytical standard error)`);
  }

  // the data
  if (x.length !== y.length) throw new TypeError("'x' and 'y' must have the same length");
  const xa: number[] = [];
  const ya: number[] = [];
  for (let i = 0; i < x.length; i++) {
    const u = x[i]!;
    const v = y[i]!;
    if (typeof u !== "number" || typeof v !== "number") throw new TypeError("'x' and 'y' must be numeric");
    if (Number.isNaN(u) || Number.isNaN(v)) {
      if (options.naRm === true) continue;
      throw new RangeError("'x' or 'y' has missing values (use naRm: true to drop the incomplete pairs)");
    }
    if (!Number.isFinite(u) || !Number.isFinite(v)) throw new RangeError("'x' and 'y' must not contain infinite values");
    xa.push(u);
    ya.push(v);
  }
  const n = xa.length;
  if (n <= 2) throw new RangeError("mcreg needs at least 3 complete pairs");
  if (constant(xa) || constant(ya)) throw new RangeError("'x' and 'y' must not be constant");
  if (methodReg === "PaBa") {
    if (xa.some((v) => v < 0) || ya.some((v) => v < 0)) throw new RangeError("Passing-Bablok regression needs nonnegative values");
    if (n > PABA_MAX_N) throw new RangeError(`Passing-Bablok regression is limited to ${PABA_MAX_N} points (2^24 pairwise slopes)`);
    // rule 4: about 0.1 µs per slope, so 2^27 slopes over all the fits take about 10 s
    const fits =
      1 +
      (methodCi === "jackknife" || (bootstrap && methodBootstrapCi === "BCa") ? n : 0) +
      (bootstrap ? nsamples * (1 + (methodCi === "nestedbootstrap" ? nnested : 0)) : 0);
    if (fits * ((n * (n - 1)) / 2) > PABA_MAX_SLOPES) {
      throw new RangeError("the Passing-Bablok fits would take more than 2^27 pairwise slopes in all (reduce nsamples or nnested)");
    }
  }
  if (methodReg === "WDeming" && (xa.some((v) => v <= 0) || ya.some((v) => v <= 0))) {
    throw new RangeError("weighted Deming regression needs positive values");
  }

  // the data scaled by powers of 2 (exact): Deming and weighted Deming scale x and y separately (x by 2^-kx, y by
  // 2^-ky, the error ratio by 2^(2(ky - kx))), so that data in very different units keep their sums of squares in
  // range; Passing-Bablok scales both by one power (its tie rule and angles compare dy with dx). The slope is
  // scaled back by 2^(ky - kx), the intercept by 2^ky
  const common = scaleToUnit([xa, ya]);
  const [kx, ky] = deming ? [scaleToUnit([xa]).k, scaleToUnit([ya]).k] : [common.k, common.k];
  const xs = deming ? xa.map((v) => ldexp(v, -kx)) : common.groups[0]!;
  const ys = deming ? ya.map((v) => ldexp(v, -ky)) : common.groups[1]!;
  // the scaled error ratio, kept from 0 and Infinity (a ratio beyond 2^±1000 of the scaled data is the limit itself to
  // far below the rounding of the sums)
  const lambda = Math.min(Math.max(ldexpWide(errorRatio, 2 * (ky - kx)), Number.MIN_VALUE), 2 ** 1000);
  const mix = ldexpWide(errorRatio, ky - kx);
  const warnings = new Set<string>();
  const noConvergence = `no konvergence after ${iterMax} iterations`;

  /** The estimates for the points idx (in the scaled units), and the analytical standard errors for Deming */
  const fitOf = (xv: readonly number[], yv: readonly number[]): Fit & { se0?: number; se1?: number } => {
    if (methodReg === "Deming") return demingFit(xv, yv, lambda);
    if (methodReg === "WDeming") {
      const f = wdemingFit(xv, yv, lambda, mix, errorRatio, iterMax, threshold, kx, ky);
      if (!f.converged) warnings.add(noConvergence);
      return f;
    }
    return pabaFit(xv, yv, tangent);
  };

  // the estimates of all the data
  let global: Fit;
  let xmean = NaN;
  let weights: number[] | undefined;
  let analytic: [number, number] | undefined;
  let pabaSlopesAll: PabaSlopes | undefined;
  if (methodReg === "Deming") {
    const f = demingFit(xs, ys, lambda);
    global = f;
    xmean = ldexp(f.xmean, kx);
    analytic = [f.se0, f.se1];
  } else if (methodReg === "WDeming") {
    const f = wdemingFit(xs, ys, lambda, mix, errorRatio, iterMax, threshold, kx, ky);
    if (!f.converged) warnings.add(noConvergence);
    global = f;
    xmean = ldexp(f.xmean, kx);
    weights = f.weights;
  } else {
    const f = pabaFit(xs, ys, tangent);
    global = f;
    pabaSlopesAll = f.slopes;
  }
  if (!Number.isFinite(global.b1)) {
    throw new RangeError(
      methodReg === "PaBa" ? "the Passing-Bablok slope is not defined for these data" : "the covariance of x and y is 0: the Deming slope is not defined",
    );
  }

  const alpha = 1 - confLevel;
  // t and normal quantiles of 1 - alpha/2, from the upper tail (rule 10)
  const tq = qt1(alpha / 2, n - 2, false, false);
  const zq = qnorm(alpha / 2, { lowerTail: false });
  const est: [number, number] = [global.b0, global.b1];
  const se: [number, number] = [NaN, NaN];
  const ci: [[number, number], [number, number]] = [
    [NaN, NaN],
    [NaN, NaN],
  ];
  let jack: [number[], number[]] | undefined;
  let jackSe: [number, number] | undefined;
  let boot: McregResult["bootstrap"];

  const jackknife = (): void => {
    const j0: number[] = [];
    const j1: number[] = [];
    for (let i = 0; i < n; i++) {
      const f = fitOf(
        xs.filter((_, j) => j !== i),
        ys.filter((_, j) => j !== i),
      );
      j0.push(f.b0);
      j1.push(f.b1);
    }
    jack = [j0, j1];
    // sd of the pseudo-values n θ - (n - 1) θ_(i) is (n - 1) sd(θ_(i)), without the cancellation of the pseudo-values
    jackSe = [((n - 1) * standardDeviation(j0)) / Math.sqrt(n), ((n - 1) * standardDeviation(j1)) / Math.sqrt(n)];
  };

  if (methodCi === "analytical") {
    if (methodReg === "Deming") {
      for (const c of [0, 1] as const) {
        se[c] = analytic![c];
        ci[c] = [est[c] - tq * se[c], est[c] + tq * se[c]];
      }
    } else {
      const iv = pabaInterval(xs, ys, pabaSlopesAll!, zq, tangent);
      if (!iv.defined) warnings.add("the Passing-Bablok interval is not defined for so few points: its limits are -Inf and Inf");
      ci[0] = iv.intercept;
      ci[1] = iv.slope;
    }
  } else if (methodCi === "jackknife") {
    jackknife();
    for (const c of [0, 1] as const) {
      se[c] = jackSe![c];
      ci[c] = [est[c] - tq * se[c], est[c] + tq * se[c]];
    }
  } else {
    if (methodBootstrapCi === "BCa") {
      jackknife();
      if (jack!.some((v) => v.some(Number.isNaN))) throw new RangeError("Too many identical data points!");
    }
    // the standard errors of all the data: Deming's analytical ones, the jackknife's for weighted Deming with BCa
    const globSigma: [number, number] =
      methodReg === "Deming" ? analytic! : methodReg === "WDeming" && jackSe !== undefined ? jackSe : [NaN, NaN];
    const nested = methodCi === "nestedbootstrap";
    const b0: number[] = [];
    const b1: number[] = [];
    const s0: number[] = [];
    const s1: number[] = [];
    let dropped = 0;
    const draw = (): number[] => Array.from({ length: n }, () => unifIndex(n));
    const resample = (idx: readonly number[]): Fit & { se0?: number; se1?: number } => {
      const xv = idx.map((i) => xs[i]!);
      const yv = idx.map((i) => ys[i]!);
      if (constant(xv) || constant(yv)) {
        if (methodReg === "PaBa") {
          warnings.add(
            "Resampling PaBa regression: x or y coordinates of all data points in subsample identical - regression coefficients undetermined!",
          );
          return { b0: NaN, b1: NaN };
        }
        // mcr warns and fits on; the slope is then NaN (a covariance of 0)
        warnings.add("Resampling Deming regression: all x coordinates in subsample identical - regression coefficients undetermined!");
      }
      return fitOf(xv, yv);
    };
    const run = (): void => {
      for (let b = 0; b < nsamples; b++) {
        const idx = draw();
        const f = resample(idx);
        let sig: [number, number];
        if (nested) {
          const i0: number[] = [];
          const i1: number[] = [];
          for (let r = 0; r < nnested; r++) {
            const inner = resample(draw().map((i) => idx[i]!));
            i0.push(inner.b0);
            i1.push(inner.b1);
          }
          sig = [sdNaRm(i0), sdNaRm(i1)];
        } else if (methodReg === "Deming") sig = [f.se0!, f.se1!];
        else sig = globSigma;
        if (Number.isNaN(f.b0) || Number.isNaN(f.b1)) {
          dropped++;
          continue;
        }
        b0.push(f.b0);
        b1.push(f.b1);
        s0.push(sig[0]);
        s1.push(sig[1]);
      }
    };
    if (options.rngSeed !== undefined) {
      // R's set.seed(rngSeed, kind = "Mersenne-Twister"), and the previous state restored afterwards if there was one,
      // as mcr (which restores .Random.seed only where it existed: in a session that never drew a random number nor
      // set a kind with RNGkind, the stream of set.seed(rngSeed) continues after the call)
      const saved = isRandomSeeded() ? getRandomSeed() : undefined;
      try {
        RNGkind({ kind: "Mersenne-Twister" });
        setSeed(options.rngSeed);
        run();
      } finally {
        if (saved !== undefined) setRandomSeed(saved);
      }
    } else run();
    if (dropped > 0.05 * nsamples) throw new RangeError("There were too many resamples with undetermined regression coefficients!");
    const kept = b0.length;
    const boots: [number[], number[]] = [b0, b1];
    const sigmas: [number[], number[]] = [s0, s1];
    for (const c of [0, 1] as const) {
      const B = boots[c];
      const th = est[c];
      if (methodBootstrapCi === "quantile") {
        ci[c] = [q7(B, alpha / 2), q7(B, 1 - alpha / 2)];
      } else if (methodBootstrapCi === "Student") {
        se[c] = standardDeviation(B);
        ci[c] = [th - tq * se[c], th + tq * se[c]];
      } else if (methodBootstrapCi === "BCa") {
        let p = B.filter((v) => v < th).length;
        if (B.every((v) => v === th)) p = kept / 2;
        else if (p === 0) p = 0.5;
        else if (p === kept) p = kept - 0.5;
        const z0 = qnorm(p / kept);
        const jk = jack![c];
        const jm = jk.reduce((a, v) => a + v, 0) / jk.length;
        let s2 = 0;
        let s3 = 0;
        for (const v of jk) {
          const dv = jm - v;
          s2 += dv * dv;
          s3 += dv * dv * dv;
        }
        const acc = s2 === 0 ? 0 : s3 / (6 * s2 ** 1.5);
        const zL = -zq;
        const zU = zq;
        const iu = pnorm(z0 - (zL - z0) / (1 + acc * (zL - z0)));
        const il = pnorm(z0 - (zU - z0) / (1 + acc * (zU - z0)));
        ci[c] = [q7(B, il), q7(B, iu)];
      } else {
        // bootstrap-t
        const t = B.map((v, i) => (v - th) / sigmas[c][i]!);
        const sHat = Number.isNaN(globSigma[c]) ? standardDeviation(B) : globSigma[c];
        se[c] = sHat;
        ci[c] = [th - q7(t, 1 - alpha / 2) * sHat, th - q7(t, alpha / 2) * sHat];
      }
    }
    boot = {
      intercept: b0.map((v) => ldexp(v, ky)),
      slope: b1.map((v) => ldexp(v, ky - kx)),
      sigmaIntercept: s0.map((v) => ldexp(v, ky)),
      sigmaSlope: s1.map((v) => ldexp(v, ky - kx)),
      globalSigma: [ldexp(globSigma[0], ky), ldexp(globSigma[1], ky - kx)],
      nsamples: kept,
    };
  }

  const coef = (c: 0 | 1): McregCoefficient => {
    const back = (v: number): number => ldexp(v, c === 0 ? ky : ky - kx);
    return { estimate: back(est[c]), se: back(se[c]), confInt: [back(ci[c][0]), back(ci[c][1])] };
  };
  const result: McregResult = {
    methodReg,
    methodCi,
    ...(bootstrap ? { methodBootstrapCi } : {}),
    confLevel,
    errorRatio,
    n,
    intercept: coef(0),
    slope: coef(1),
    xmean,
    ...(weights === undefined ? {} : { weights }),
    ...(jack === undefined ? {} : { jackknife: { intercept: jack[0].map((v) => ldexp(v, ky)), slope: jack[1].map((v) => ldexp(v, ky - kx)) } }),
    ...(boot === undefined ? {} : { bootstrap: boot }),
    ...(methodReg === "PaBa" ? { cusum: cusumOf(xs, ys, global.b0, global.b1) } : {}),
    warnings: [...warnings],
  };
  return reported("mcreg", result);
}
