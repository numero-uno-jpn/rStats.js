// Tests of equivalence: the two one-sided t tests (TOST) of the package equivalence's tost, and a test of equivalence
// of two proportions on counts with the score statistics of the difference.
//
// Written for rStats.js from the published methods and the package's documented behaviour (no R or package code):
// - TOST (Schuirmann, Journal of Pharmacokinetics and Biopharmaceutics 15, 1987): equivalence of the means within
//   (-epsilon, epsilon) is shown at level alpha when both H01: d <= -epsilon and H02: d >= epsilon are rejected by
//   one-sided t tests at alpha; the larger one-sided p-value is P(T > (epsilon - |d|)/se) on the df of the t test, and
//   the dual interval is d -+ qt(1 - alpha, df) se, a 1 - 2 alpha interval. The mean difference, its standard error
//   and the df are tTest's (Welch's, pooled or paired).
// - Two proportions: the same pair of one-sided hypotheses about p1 - p2, tested with the score statistic
//   z(delta0) = (p1 - p2 - delta0) / sqrt(var(delta0)) at delta0 = -epsilon and +epsilon, var at the maximum likelihood
//   estimate under p1 - p2 = delta0 (Farrington and Manning, Statistics in Medicine 9, 1990, 1447-1454), times
//   N/(N - 1) for Miettinen and Nurminen (Statistics in Medicine 4, 1985, 213-226), or at the observed proportions
//   (Wald). The statistics and the restricted MLE are those of src/htest/core/twoProportions.ts; the dual 1 - 2 alpha
//   interval is binomDiffCI's with the same method.

