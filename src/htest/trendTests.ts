/**
 * Chi-squared test for trend in proportions. Equivalent to R's `prop.trend.test(x, n, score)`. The scores are the
 * third argument or the option `score` (giving both is a RangeError).
 *
 * @param x Numbers of events.
 * @param n Numbers of trials.
 * @param score Scores of the groups. Default `1, 2, ..., k`. A group with a NaN score is left out of the regression
 *   (as R's `lm` omits it), but its counts stay in the pooled proportion and the weights, as in R. Other scores must
 *   be finite, with at least two distinct values. With no events or only events (all proportions 0, or all 1) the test is not defined (an error, as in R).
 *
 * @example
 * ```ts
 * propTrendTest([15, 10, 8, 4], [30, 30, 30, 30]).statistic; // 9.573428850537288
 * ```
 *
 * @category Hypothesis tests
 */
export function propTrendTest(x: Sample, n: Sample, score?: Sample): PropTrendTestResult;
/**
 * Chi-squared test for trend in proportions, with the scores in the options:
 * `propTrendTest(x, n, { score: [0, 1, 2, 4] })`.
 *
 * @example
 * ```ts
 * propTrendTest([15, 10, 8, 4], [30, 30, 30, 30], { score: [1, 2, 3, 4] }).statistic; // 9.573428850537288
 * ```
 */
export function propTrendTest(x: Sample, n: Sample, options: PropTrendTestOptions): PropTrendTestResult;
export function propTrendTest(x: Sample, n: Sample, ...args: unknown[]): PropTrendTestResult {
  checkOptions(optionsIn(args), PROP_TREND_TEST_KEYS, "propTrendTest"); // generated: option-keys.mjs
  const { score } = optionalArgs<PropTrendTestOptions>(["score"], args);
  const xs = Array.from(x);
  const ns = Array.from(n);
  const k = xs.length;
  const s = score === undefined ? xs.map((_, i) => i + 1) : Array.from(score);
  if (ns.length !== k || s.length !== k) throw new RangeError("'x', 'n' and 'score' must have the same length");
  if (ns.some((v) => !(v > 0 && v < Infinity))) throw new RangeError("elements of 'n' must be positive and finite");
  if (xs.some((v, i) => !(v >= 0 && v <= ns[i]!))) throw new RangeError("elements of 'x' must be between 0 and 'n'");
  // With no events or only events the pooled proportion is 0 or 1, the weights n / (p (1 - p)) are infinite and every
  // proportion is the same: no trend to test (R's lm: "NA/NaN/Inf in 'x'"; this returned NaN, #319)
  if (xs.every((v) => v === 0) || xs.every((v, i) => v === ns[i]!)) {
    throw new RangeError("all proportions are 0 or all are 1: the test for trend is not defined");
  }
  const sumN = ns.reduce((a, v) => a + v, 0);
  const p = xs.reduce((a, v) => a + v, 0) / sumN;
  const w = ns.map((v) => v / (p * (1 - p)));
  const f = xs.map((v, i) => v / ns[i]!);
  // the weighted regression of f on the scores, over the groups with a score
  const rows = s.flatMap((v, i) => (Number.isNaN(v) ? [] : [i]));
  if (rows.length === 0) throw new RangeError("no non-missing scores");
  // An infinite score made the centred scores Inf - Inf and the statistic NaN (R's lm: "NA/NaN/Inf in 'x'"; #317)
  if (rows.some((i) => !Number.isFinite(s[i]!))) throw new RangeError("non-missing scores must be finite");
  // One distinct score (all equal, or one group with a score) leaves no slope: sxx = sxy = 0 and the statistic 0 / 0
  // (R's NA; NaN before, #318)
  if (rows.every((i) => s[i] === s[rows[0]!])) throw new RangeError("at least 2 distinct non-missing scores are needed");
  let sc = s;
  let { sw, sxy, sxx } = trendRegression(w, f, sc, rows);
  if (!(sxx >= 2 ** -1022 && sxx < Infinity && Math.abs(sxy) < Infinity)) {
    // Scores far from 1 (0 and 1e200, or 0 and 2^-700): sxx overflowed or underflowed, and the statistic was 0 or
    // Infinity. The statistic does not change when the scores are multiplied by a constant, so it is formed from the
    // scores divided by a power of 2 that brings the largest into [1, 2) (#389). Otherwise the same bits as before
    const scaled = scaleToUnit([rows.map((i) => s[i]!)]);
    if (scaled.k !== 0) {
      sc = s.slice();
      rows.forEach((i, j) => (sc[i] = scaled.groups[0]![j]!));
      ({ sw, sxy, sxx } = trendRegression(w, f, sc, rows));
    }
  }
  let statistic = squareOver(sxy, sxx);
  if (!(sumN < Infinity) || (p > 0 && p < 1 && !(sw < Infinity && Math.abs(sxy) < Infinity && sxx < Infinity))) {
    // The totals or the weights overflow although the counts are finite: the pooled proportion from the counts
    // scaled by 2^-k, and the regression with the weights n_i 2^-k (the common factor 1 / (p (1 - p)) cancels in the
    // means), the statistic sxy^2 / sxx / (p (1 - p)) multiplied back by 2^k
    const {
      groups: [xu, nu],
      k,
    } = scaleToUnit([xs, ns]);
    const pu = xu!.reduce((a, v) => a + v, 0) / nu!.reduce((a, v) => a + v, 0);
    const u = trendRegression(nu!, f, sc, rows);
    statistic = ldexp((u.sxy / pu) * (u.sxy / u.sxx / (1 - pu)), k);
  }
  return {
    method: "Chi-squared Test for Trend in Proportions",
    statistic,
    statisticName: "X-squared",
    parameter: 1,
    parameterName: "df",
    pValue: pgamma1(statistic, 0.5, 2, false, false),
    warnings: [],
  };
}

/** Weighted sums of the regression of f on the scores s over the given rows: the total weight and the centred sums */
function trendRegression(
  w: readonly number[],
  f: readonly number[],
  s: readonly number[],
  rows: readonly number[],
): { sw: number; sxy: number; sxx: number } {
  const sw = rows.reduce((a, i) => a + w[i]!, 0);
  const sBar = rows.reduce((a, i) => a + w[i]! * s[i]!, 0) / sw;
  const fBar = rows.reduce((a, i) => a + w[i]! * f[i]!, 0) / sw;
  let sxy = 0;
  let sxx = 0;
  for (const i of rows) {
    const ds = s[i]! - sBar;
    sxy += w[i]! * ds * (f[i]! - fBar);
    sxx += w[i]! * ds * ds;
  }
  return { sw, sxy, sxx };
}

/**
 * Alternative of {@link jonckheereTest}.
 *
 * @category Hypothesis tests
 */
export type JonckheereAlternative = "two.sided" | "increasing" | "decreasing";

/**
 * Options for {@link jonckheereTest}.
 *
 * @category Hypothesis tests
 */
export interface JonckheereTestOptions {
  /** `"two.sided"` (default), `"increasing"` or `"decreasing"` (unambiguous abbreviations accepted). */
  alternative?: JonckheereAlternative | (string & {});
  /**
   * The exact p-value (`"DescTools"` only). Default: exact when there are no ties and at most 100 observations. With
   * ties the normal approximation is used anyway, with a warning. The exact distribution is the convolution of the
   * Mann-Whitney distributions; where it would have more than 2^24 values or take more than 2^32 multiply-adds
   * (three equal groups of 216, about 8 s), `exact: true` is a RangeError (R computes it however long it takes).
   */
  exact?: boolean;
  /** `"DescTools"` (default: `JonckheereTerpstraTest`) or `"clinfun"` (`jonckheere.test`). */
  variant?: "DescTools" | "clinfun";
  /** The order of the groups. Default: the labels sorted (numbers as numbers, strings by code point). */
  levels?: readonly GroupLabel[];
}

/**
 * Result of {@link jonckheereTest}.
 *
 * @category Hypothesis tests
 */
export interface JonckheereTestResult extends Omit<HTest, "alternative"> {
  /** Alternative hypothesis: `"two.sided"`, `"increasing"` or `"decreasing"`. */
  alternative: JonckheereAlternative;
  /** The packages' warnings (normal approximation). */
  warnings: string[];
}

/** Largest length (as #232's 2^24) and number of multiply-adds (three equal groups of 216: about 8 s) of the exact JT distribution (#321) */
const MAX_EXACT_LENGTH = 2 ** 24;
const MAX_EXACT_WORK = 2 ** 32;
const NOT_EXACT = "Sample size > 100 or data with ties \n p-value based on normal approximation. Specify nperm for permutation p-value";
const TIES = "Sample data with ties \n p-value based on normal approximation. Specify nperm for permutation p-value.";

/**
 * The groups in order: the labels sorted (numbers as numbers, strings by code point) or as `levels`. Pairs with a NaN
 * are dropped, and with `finiteOnly` also those with an infinite value or numeric label
 */
function orderedGroups(x: Sample, g: readonly GroupLabel[], levels: readonly GroupLabel[] | undefined, finiteOnly = false): number[][] {
  const xs = Array.from(x);
  if (xs.length !== g.length) throw new RangeError("'x' and 'g' must have the same length");
  const bad = (v: unknown): boolean => typeof v === "number" && (finiteOnly ? !Number.isFinite(v) : Number.isNaN(v));
  const keep = xs.flatMap((v, i) => (bad(v) || bad(g[i]) ? [] : [i]));
  // numeric labels with the same 15-digit text are one level, as in R's factor() (only without given levels, which
  // are matched by their text)
  if (levels === undefined) g = numberLevels(g);
  let order: string[];
  if (levels !== undefined) order = levels.map(levelText);
  else {
    const distinct = [...new Set(keep.map((i) => g[i]!))];
    order = distinct.every((l) => typeof l === "number")
      ? (distinct as number[]).sort((a, b) => a - b).map(levelText)
      : [...new Set(distinct.map(levelText))].sort(compareCodePoints);
  }
  const groups = order.map((): number[] => []);
  const index = new Map(order.map((l, k) => [l, k]));
  for (const i of keep) {
    const k = index.get(levelText(g[i]!));
    if (k === undefined) throw new RangeError(`the group '${levelText(g[i])}' is not among 'levels'`);
    groups[k]!.push(xs[i]!);
  }
  return groups;
}

/**
 * The null variance of JT under ties (Hollander & Wolfe): the variance of the permutation distribution given the
 * group sizes n_i and the sizes t_j of the groups of tied values. The packages (clinfun, DescTools) use the variance
 * without ties there, which is too large (review 59)
 */
function tiedVariance(groupSizes: readonly number[], all: readonly number[]): number {
  const counts = new Map<number, number>();
  for (const v of all) counts.set(v, (counts.get(v) ?? 0) + 1);
  const t = [...counts.values()];
  const N = all.length;
  const s1 = (a: readonly number[], f: (v: number) => number): number => a.reduce((acc, v) => acc + f(v), 0);
  const first =
    (N * (N - 1) * (2 * N + 5) - s1(groupSizes, (v) => v * (v - 1) * (2 * v + 5)) - s1(t, (v) => v * (v - 1) * (2 * v + 5))) / 72;
  const second =
    N < 3 ? 0 : (s1(groupSizes, (v) => v * (v - 1) * (v - 2)) * s1(t, (v) => v * (v - 1) * (v - 2))) / (36 * N * (N - 1) * (N - 2));
  const third = (s1(groupSizes, (v) => v * (v - 1)) * s1(t, (v) => v * (v - 1))) / (8 * N * (N - 1));
  return first + second + third;
}

/**
 * Jonckheere-Terpstra test of equal distributions against ordered alternatives. Equivalent to
 * `DescTools::JonckheereTerpstraTest()` in R. Computes `JonckheereTerpstraTest(x, g, alternative, exact)` (with `g`
 * an ordered factor) or, with `variant: "clinfun"`, clinfun's `jonckheere.test(x, g, alternative)` (whose
 * two-sided p-value is `2 min(p_increasing, p_decreasing, 0.5)`; DescTools caps it at 1 instead of 0.5). Pairs with a missing value are dropped (with `variant: "clinfun"`, also those with an infinite value, as clinfun does).
 *
 * @param x The values.
 * @param g Group labels, parallel to `x`, in the order of the alternative.
 *
 * @example
 * ```ts
 * jonckheereTest([1.1, 2.0, 2.4, 3.5, 3.1, 4.6], [1, 1, 2, 2, 3, 3], { alternative: "increasing" }).statistic; // 11
 * ```
 *
 * @category Hypothesis tests
 */
export function jonckheereTest(x: Sample, g: readonly GroupLabel[], options: JonckheereTestOptions = {}): JonckheereTestResult {
  checkOptions(options, JONCKHEERE_TEST_KEYS, "jonckheereTest"); // generated: option-keys.mjs
  const alternative = matchChoice(options.alternative, ["two.sided", "increasing", "decreasing"] as const);
  const variant = options.variant ?? "DescTools";
  if (variant !== "DescTools" && variant !== "clinfun") throw new RangeError(`invalid variant "${String(variant)}"`);
  if (variant === "clinfun" && options.exact !== undefined) throw new TypeError("clinfun's jonckheere.test has no option 'exact'");
  // clinfun keeps only the pairs where both values are finite
  const groups = orderedGroups(x, g, options.levels, variant === "clinfun");
  // with fewer than 2 nonempty groups there is no pair to compare (the packages' errors)
  if (groups.filter((gi) => gi.length > 0).length < 2)
    throw new RangeError(variant === "clinfun" ? "only one group has non-missing data" : "all observations are in the same group");
  const all = groups.flat();
  const nTotal = all.length;
  const ties = new Set(all).size < nTotal;
  // JT, and the sizes n_i and m_i (observations after group i)
  let jt = 0;
  const sizes: [number, number][] = [];
  let after = nTotal;
  groups.forEach((gi, i) => {
    after -= gi.length;
    sizes.push([gi.length, after]);
    for (let j = i + 1; j < groups.length; j++) {
      for (const a of gi) for (const b of groups[j]!) jt += a < b ? 1 : a === b ? 0.5 : 0;
    }
  });
  const warnings: string[] = [];
  let exact = !ties && nTotal <= 100;
  if (variant === "DescTools" && options.exact !== undefined) {
    exact = options.exact;
    if (exact && ties) {
      exact = false;
      warnings.push(TIES);
    }
  } else if (!exact) warnings.push(NOT_EXACT);
  let lower: number;
  let upper: number;
  if (exact) {
    // the length of the convolution and its multiply-adds, checked before anything is built (#321)
    let len = 1;
    let work = 0;
    for (const [ni, mi] of sizes) {
      if (ni === 0 || mi === 0) continue;
      work += len * (ni * mi + 1);
      len += ni * mi;
    }
    if (len > MAX_EXACT_LENGTH || work > MAX_EXACT_WORK) {
      throw new RangeError(`the exact distribution of JT has ${len} values and needs ${work} steps, too many: use exact: false`);
    }
    // the convolution of the Mann-Whitney distributions
    let dist = [1];
    for (const [ni, mi] of sizes) {
      if (ni === 0 || mi === 0) continue;
      const mw = Array.from({ length: ni * mi + 1 }, (_, v) => dwilcox1(v, ni, mi, false));
      const next = new Array<number>(dist.length + mw.length - 1).fill(0);
      dist.forEach((a, u) => mw.forEach((b, v) => (next[u + v]! += a * b)));
      dist = next;
    }
    lower = 0;
    upper = 0;
    dist.forEach((pr, v) => {
      if (v <= jt) lower += pr;
      if (v >= jt) upper += pr;
    });
  } else {
    const mean = sizes.reduce((a, [ni, mi]) => a + ni * mi, 0) / 2;
    const variance = ties ? tiedVariance(groups.map((gi) => gi.length), all) : sizes.reduce((a, [ni, mi]) => a + (ni * mi * (ni + mi + 1)) / 12, 0);
    const z = (jt - mean) / Math.sqrt(variance);
    lower = pnorm(z);
    upper = 1 - lower;
    // 1 - pnorm loses the small upper tail (0 beyond z ~ 8.3); below 1e-8 take it directly,
    // elsewhere the packages' expression (the same bits) (#280)
    if (upper < 1e-8) upper = pnorm(z, { lowerTail: false });
  }
  const cap = variant === "clinfun" ? 0.5 : 1;
  const pValue = alternative === "increasing" ? upper : alternative === "decreasing" ? lower : Math.min(1, 2 * Math.min(upper, lower, cap)); // (DescTools can exceed 1)
  return reported("jonckheereTest", { method: "Jonckheere-Terpstra test", alternative, statistic: jt, statisticName: "JT", pValue, warnings });
}
