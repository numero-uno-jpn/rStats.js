// Binomial distribution dbinom / pbinom / qbinom.
//
// Probabilities use Loader's (2000) dbinomRaw; the distribution function is
//   P[X <= x] = 1 - I_p(x + 1, n - x)   (regularized incomplete beta function)
// Quantiles use an integer search from a Cornish-Fisher starting value.

import { vectorize, type Vectorizable, type VectorResult } from "../internal/vectorize.js";
import { d0, dt0, dt1, quantileBoundaries, type DensityOptions, type TailOptions } from "../internal/dpq.js";
import { discreteQuantile } from "../internal/discrete.js";
import { betaInc } from "../special/incbet.js";
import { dbinomRawDD } from "../special/loader.js";
import { twoSum, type DD } from "../special/dd.js";
import { logAddExp, logSubExp } from "../internal/ddexp.js";
import { qnorm } from "./normal.js";
import { nonInteger } from "./poisson.js";
import { countAtMost, roundHalfEven } from "../internal/integer.js";
// Generated by `node scripts/option-keys.mjs --write` from the option types; do not edit (begin)
import { checkOptions } from "../internal/checkOptions.js";
const DBINOM_KEYS = ["log"] as const;
const PBINOM_KEYS = ["lowerTail", "logP"] as const;
const QBINOM_KEYS = ["lowerTail", "logP"] as const;
// Generated by `node scripts/option-keys.mjs --write` (end)

function badParams(size: number, prob: number): boolean {
  return nonInteger(size) || size < 0 || !Number.isFinite(size) || prob < 0 || prob > 1;
}

export function dbinom1(x: number, size: number, prob: number, log: boolean): number {
  if (Number.isNaN(x) || Number.isNaN(size) || Number.isNaN(prob)) return NaN;
  // size Inf (as in R 4.5; pbinom and qbinom take it as invalid): no mass at any x, except at 0 when prob = 0
  if (size === Infinity && prob >= 0 && prob <= 1) return prob === 0 && x === 0 ? (log ? 0 : 1) : d0(log);
  if (badParams(size, prob)) return NaN;
  if (nonInteger(x) || x < 0 || !Number.isFinite(x)) return d0(log);
  // q = 1 - prob is formed exactly in double-double (rounding in q would be amplified n - x times)
  const xr = Math.round(x);
  const n = Math.round(size);
  if (xr > n) return d0(log);
  const pd: DD = prob <= 0.5 ? [prob, 0] : twoSum(1, -(1 - prob));
  const qd: DD = prob <= 0.5 ? twoSum(1, -prob) : [1 - prob, 0];
  return dbinomRawDD(xr, n - xr, pd, qd, log, n);
}

/** P[X <= x] (lower) / P[X > x] (!lower). x an integer, 0 <= x < n */
function pbinomRaw(x: number, n: number, prob: number, lower: boolean, log: boolean): number {
  // P[X <= x] = 1 - I_p(x + 1, n - x)
  if (x + 1 - x === 1) return betaInc(x + 1, n - x, prob, 1 - prob, !lower, log);
  // Beyond 2^53, x + 1 rounds (to x, or up to x + 2) (pbinom(1e16, 2e16, 0.5) was 0.5, the symmetric I_p(x, x); R too). Without x + 1:
  // I_p(x + 1, n - x) = I_p(x, n - x) - (n - x)/n dbinom(x; n, p). With n - x itself rounded, no parameters are right
  const [b, err] = twoSum(n, -x);
  if (err !== 0) return NaN;
  let v: number;
  let term: number;
  if (!log) {
    const t = betaInc(x, b, prob, 1 - prob, !lower, false);
    term = (b / n) * dbinom1(x, n, prob, false);
    v = lower ? t + term : t - term;
  } else {
    const lt = betaInc(x, b, prob, 1 - prob, !lower, true);
    term = Math.log(b / n) + dbinom1(x, n, prob, true);
    v = lower ? logAddExp(lt, term) : logSubExp(lt, term);
  }
  if (Number.isNaN(term)) return NaN;
  // The upper tail as a difference: where the term is not resolved against it (deep tails, where both logs round to the
  // same value), one unit of x is below the resolution of the result, and the rounded x + 1 serves (round 55)
  if (lower || (log ? Number.isFinite(v) : v > 0)) return v;
  return betaInc(x + 1, b, prob, 1 - prob, !lower, log);
}

export function pbinom1(q: number, size: number, prob: number, lowerTail: boolean, logP: boolean): number {
  if (Number.isNaN(q) || Number.isNaN(size) || Number.isNaN(prob)) return NaN;
  if (badParams(size, prob)) return NaN;
  const n = Math.round(size);
  if (q < 0) return dt0(lowerTail, logP);
  const x = countAtMost(q);
  if (n <= x) return dt1(lowerTail, logP);
  if (prob === 0) return dt1(lowerTail, logP);
  if (prob === 1) return dt0(lowerTail, logP);
  return pbinomRaw(x, n, prob, lowerTail, logP);
}

export function qbinom1(p: number, size: number, prob: number, lowerTail: boolean, logP: boolean): number {
  if (Number.isNaN(p) || Number.isNaN(size) || Number.isNaN(prob)) return NaN;
  if (!Number.isFinite(size) || !Number.isFinite(prob)) return NaN;
  // As R (R_forceint), a non-integer size is rounded half to even (10.5 is 10, -0.1 is -0), as in qhyper, qsignrank and
  // qwilcox; dbinom and pbinom give NaN for it, as R
  const n = roundHalfEven(size);
  if (prob < 0 || prob > 1 || n < 0) return NaN;
  const b = quantileBoundaries(p, 0, n, lowerTail, logP);
  if (b !== undefined) return b;
  if (prob === 0 || n === 0) return 0;
  if (prob === 1) return n;
  const q = 1 - prob;
  const mu = n * prob;
  const sigma = Math.sqrt(n * prob * q);
  const gamma = (q - prob) / sigma;
  const z = qnorm(p, { lowerTail, logP });
  const y0 = mu + sigma * (z + (gamma * (z * z - 1)) / 6);
  return discreteQuantile({
    p,
    lowerTail,
    logP,
    cdf: (y, l, lg) => (y >= n ? dt1(l, lg) : pbinomRaw(y, n, prob, l, lg)),
    y0: Number.isFinite(y0) ? y0 : mu,
    lo: 0,
    hi: n,
  });
}

/**
 * Probability mass function of the binomial distribution. Equivalent to R's `dbinom(x, size, prob, log = FALSE)`.
 *
 * @param x - Value(s) at which to evaluate: a number, `number[]` or `Float64Array`. The result has the same shape.
 * @param size - Number of trials.
 * @param prob - Probability of success on each trial.
 * @param options - `log` (see {@link DensityOptions}).
 * @returns The probability (or log probability).
 *
 * @example
 * ```ts
 * dbinom(3, 10, 0.5);      // 0.1171875
 * dbinom([0, 5], 10, 0.5); // [0.0009765625, 0.24609375]
 * ```
 *
 * @category Distributions
 */
export function dbinom<T extends Vectorizable>(
  x: T,
  size: number,
  prob: number,
  options: DensityOptions = {},
): VectorResult<T> {
  checkOptions(options, DBINOM_KEYS, "dbinom"); // generated: option-keys.mjs
  const log = options.log ?? false;
  return vectorize(x, (v) => dbinom1(v, size, prob, log));
}

/**
 * Distribution function of the binomial distribution. Equivalent to R's `pbinom(q, size, prob, lower.tail = TRUE, log.p = FALSE)`.
 *
 * @param q - Quantile(s): a number, `number[]` or `Float64Array`. The result has the same shape.
 * @param size - Number of trials.
 * @param prob - Probability of success on each trial.
 * @param options - `lowerTail` and `logP` (see {@link TailOptions}).
 * @returns The probability (or log probability).
 *
 * @example
 * ```ts
 * pbinom(3, 10, 0.5);      // 0.171875
 * pbinom([3, 5], 10, 0.5); // [0.171875, 0.623046875]
 * ```
 *
 * @category Distributions
 */
export function pbinom<T extends Vectorizable>(
  q: T,
  size: number,
  prob: number,
  options: TailOptions = {},
): VectorResult<T> {
  checkOptions(options, PBINOM_KEYS, "pbinom"); // generated: option-keys.mjs
  const { lowerTail = true, logP = false } = options;
  return vectorize(q, (v) => pbinom1(v, size, prob, lowerTail, logP));
}

/**
 * Quantile function of the binomial distribution. Equivalent to R's `qbinom(p, size, prob, lower.tail = TRUE, log.p = FALSE)`.
 *
 * @param p - Probability (or log probability with `logP`): a number, `number[]` or `Float64Array`. The result has the same shape.
 * @param size - Number of trials.
 * @param prob - Probability of success on each trial.
 * @param options - `lowerTail` and `logP` (see {@link TailOptions}).
 * @returns The quantile(s).
 *
 * @example
 * ```ts
 * qbinom(0.5, 10, 0.3);          // 3
 * qbinom([0.025, 0.975], 10, 0.3); // [0, 6]
 * ```
 *
 * @category Distributions
 */
export function qbinom<T extends Vectorizable>(
  p: T,
  size: number,
  prob: number,
  options: TailOptions = {},
): VectorResult<T> {
  checkOptions(options, QBINOM_KEYS, "qbinom"); // generated: option-keys.mjs
  const { lowerTail = true, logP = false } = options;
  return vectorize(p, (v) => qbinom1(v, size, prob, lowerTail, logP));
}
