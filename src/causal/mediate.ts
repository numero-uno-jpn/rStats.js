/**
 * A model for {@link mediate}: a formula fit of {@link lm}, or of {@link glm} with the binomial family and the logit or
 * probit link.
 *
 * @category Causal inference
 */
export type MediationModel = LmFormulaResult | GlmFormulaResult;

/**
 * Options for {@link mediate}.
 *
 * @category Causal inference
 */
export interface MediateOptions {
  /** The treatment: a numeric variable of both models. */
  treat: string;
  /** The mediator: the mediator model's response and a numeric variable of the outcome model. */
  mediator: string;
  /** The treatment's value for the treated condition (default 1). */
  treatValue?: number;
  /** The treatment's value for the control condition (default 0). */
  controlValue?: number;
  /** Covariates held at the given values in every observation's prediction (R's `covariates`); numeric variables. */
  covariates?: Record<string, number>;
  /** Number of simulations or bootstrap replicates (default 1000). */
  sims?: number;
  /** Nonparametric bootstrap instead of the quasi-Bayesian approximation (default `false`). */
  boot?: boolean;
  /** The bootstrap intervals: `"perc"` (percentile, the default) or `"bca"` (bias-corrected and accelerated). */
  bootCiType?: "perc" | "bca";
  /** Confidence level of the intervals (default 0.95). */
  confLevel?: number;
  /** Heteroskedasticity-consistent (HC3) covariances for the quasi-Bayesian draws (default `false`). */
  robustSE?: boolean;
}

/**
 * One effect of {@link mediate}: its estimate, interval, p-value and draws.
 *
 * @category Causal inference
 */
export interface MediateEffect {
  /** The estimate (R's `d0`, `z0`, `tau.coef`, ...). */
  estimate: number;
  /** The confidence interval (R's `d0.ci`, ...). */
  ci: [number, number];
  /** The two-sided p-value, `2 min(mean(draws > 0), mean(draws < 0))` (R's `d0.p`, ...). */
  p: number;
  /** The simulation or bootstrap draws (R's `d0.sims`, ...). */
  sims: number[];
}

/**
 * Result of {@link mediate}. `d` are the average causal mediation effects (ACME), `z` the average direct effects (ADE),
 * `n` the proportions mediated, `0` under control and `1` under treatment.
 *
 * @category Causal inference
 */
export interface MediateResult {
  /** ACME under control: the mean of Y(t0, M(t1)) − Y(t0, M(t0)). */
  d0: MediateEffect;
  /** ACME under treatment: the mean of Y(t1, M(t1)) − Y(t1, M(t0)). */
  d1: MediateEffect;
  /** ADE under control: the mean of Y(t1, M(t0)) − Y(t0, M(t0)). */
  z0: MediateEffect;
  /** ADE under treatment: the mean of Y(t1, M(t1)) − Y(t0, M(t1)). */
  z1: MediateEffect;
  /** The total effect: the mean of Y(t1, M(t1)) − Y(t0, M(t0)). */
  tau: MediateEffect;
  /** Proportion mediated under control, d0 / tau. */
  n0: MediateEffect;
  /** Proportion mediated under treatment, d1 / tau. */
  n1: MediateEffect;
  /** The average ACME, (d0 + d1) / 2. */
  dAvg: MediateEffect;
  /** The average ADE, (z0 + z1) / 2. */
  zAvg: MediateEffect;
  /** The average proportion mediated, (n0 + n1) / 2. */
  nAvg: MediateEffect;
  /** The treated and control values used. */
  treatValue: number;
  controlValue: number;
  /** Number of observations. */
  nobs: number;
  /** Number of simulations or replicates. */
  sims: number;
  /** Whether the bootstrap was used, and its interval type. */
  boot: boolean;
  bootCiType: "perc" | "bca";
  confLevel: number;
  robustSE: boolean;
  /** Whether the outcome model has an interaction of the treatment and the mediator (R's `INT`). */
  INT: boolean;
  /** R's warnings. */
  warnings: string[];
}

/** A model prepared for prediction */
interface Prepared {
  fit: MediationModel;
  isGlm: boolean;
  formula: string;
  options: Readonly<Record<string, unknown>>;
  coef: number[];
  names: string[];
  linkinv: (eta: number) => number;
  /** The model's design on the data (the rows it used) */
  d: Design;
  rows: number[];
}

function prepare(fit: MediationModel, data: DataFrame, role: "mediator" | "outcome"): Prepared {
  const options = fitOptions(fit);
  if (options === undefined || typeof (fit as { formula?: unknown }).formula !== "string")
    throw new TypeError(`the ${role} model must be a formula fit of lm or glm`);
  if (options.weights !== undefined || options.offset !== undefined) throw new RangeError(`weights and offsets are not supported (the ${role} model)`);
  const isGlm = "family" in fit;
  let linkinv = (eta: number) => eta;
  if (isGlm) {
    const g = fit as GlmFormulaResult;
    if (g.family === "binomial" && (g.link === "logit" || g.link === "probit")) linkinv = familyOf(g).linkinv;
    else if (!(g.family === "gaussian" && g.link === "identity")) throw new RangeError(`the ${role} model's family is not supported (binomial with logit or probit, or gaussian)`);
  }
  if (fit.coefficients.some((c) => Number.isNaN(c))) throw new RangeError(`the ${role} model has aliased coefficients`);
  const formula = (fit as { formula: string }).formula;
  const d = design(parseFormula(formula, false, false, true), data, {
    ...(options.contrasts === undefined ? {} : { contrasts: options.contrasts as never }),
    ...(options.levels === undefined ? {} : { levels: options.levels as never }),
    dropUnusedLevels: true,
    anyResponse: true,
  });
  const rows = isGlm ? (fit as GlmFormulaResult).model.rows : (fit as LmFormulaResult).rows;
  const names = isGlm ? (fit as GlmFormulaResult).model.columnNames : (fit as LmFormulaResult).coefNames;
  if (d.frame.rows.length !== rows.length || d.frame.rows.some((r, i) => r !== rows[i]) || d.colNames.join("\u0000") !== names.join("\u0000"))
    throw new RangeError(`the data do not give the ${role} model's rows and columns (pass the data it was fitted on)`);
  return { fit, isGlm, formula, options, coef: fit.coefficients.slice(), names, linkinv, d, rows };
}

/** Index of a variable among the design's variables, which must be numeric */
function numericVariable(p: Prepared, name: string, role: string, required: boolean): number {
  const j = p.d.terms.variables.indexOf(name);
  if (j < 0) {
    if (required) throw new RangeError(`'${name}' is not a variable of the ${role} model`);
    return -1;
  }
  if (p.d.frame.variables[j]!.kind !== "numeric") throw new RangeError(`'${name}' must be numeric in the ${role} model`);
  return j;
}

/** Design rows for set values of some variables (each an array over the observations, or a constant) */
function rowsWith(p: Prepared, set: ReadonlyMap<number, number | readonly number[]>, n: number): number[][] {
  const vars: FrameVariable[] = p.d.frame.variables.map((v, j) => {
    const s = set.get(j);
    if (s === undefined) return v;
    return { kind: "numeric", values: typeof s === "number" ? new Array<number>(n).fill(s) : s.slice() };
  });
  return p.d.rowsOf(vars, n);
}

const dot = (row: readonly number[], b: readonly number[]): number => {
  let s = 0;
  for (let k = 0; k < row.length; k++) s += row[k]! * b[k]!;
  return s;
};

/**
 * Rows of normals filled by row, times the symmetric square root of V, plus mu: R's parameter draws. A covariance whose
 * entries leave the double range (variables on scales beyond about 1e+-150 make variances of 1e+-300 and more) cannot
 * be decomposed: an error, where R errors or gives meaningless draws (experiments/mediation116-edge.R)
 */
function drawParameters(mu: readonly number[], V: readonly (readonly number[])[], sims: number, role: string): number[][] {
  const p = mu.length;
  const MIN = 2 ** -1022, MAX = Number.MAX_VALUE;
  if (V.some((r, i) => r.some((v) => !Number.isFinite(v)) || !(r[i]! >= MIN && r[i]! <= MAX)))
    throw new RangeError(`the ${role} model's coefficient covariance is out of the double range (rescale the variables, or use boot: true)`);
  const R = symmetricSqrt(V);
  const z = rnorm(sims * p);
  const out: number[][] = [];
  for (let j = 0; j < sims; j++) {
    const row: number[] = [];
    for (let c = 0; c < p; c++) {
      let s = 0;
      for (let k = 0; k < p; k++) s += z[j * p + k]! * R[k]![c]!;
      row.push(mu[c]! + s);
    }
    out.push(row);
  }
  return out;
}

interface Context {
  m: Prepared;
  y: Prepared;
  treat: string;
  mediator: string;
  t1: number;
  t0: number;
  n: number;
  /** Indices of the variables to set in each model */
  mTreat: number;
  yTreat: number;
  yMed: number;
  mCov: [number, number][];
  yCov: [number, number][];
}

type Effects = [d0: number, d1: number, z0: number, z1: number, tau: number];

/** The mediator model's design rows with the treatment at t */
function mediatorRows(ctx: Context, t: number): number[][] {
  const set = new Map<number, number | readonly number[]>(ctx.mCov);
  set.set(ctx.mTreat, t);
  return rowsWith(ctx.m, set, ctx.n);
}

/** The outcome model's design rows at treatment t and mediator values m */
function outcomeRows(ctx: Context, t: number, m: readonly number[]): number[][] {
  const set = new Map<number, number | readonly number[]>(ctx.yCov);
  set.set(ctx.yTreat, t);
  set.set(ctx.yMed, m);
  return rowsWith(ctx.y, set, ctx.n);
}

/** The predicted outcomes (inverse link) at treatment t and mediator values m */
function outcomeMeans(ctx: Context, t: number, m: readonly number[], b: readonly number[]): number[] {
  return outcomeRows(ctx, t, m).map((row) => ctx.y.linkinv(dot(row, b)));
}

const meanDiff = (a: readonly number[], b: readonly number[]): number => meanDD(a.map((v, i) => v - b[i]!));

function effectsFrom(ctx: Context, m1: readonly number[], m0: readonly number[], b: readonly number[]): Effects {
  if (isLinear(ctx.y)) {
    // a linear outcome: the differences of the design rows times b, so that rows equal in the two conditions give
    // exactly 0 (R's differences of predictions keep rounding residues of either sign, see oracle/mediation-behaviour.md)
    const r01 = outcomeRows(ctx, ctx.t0, m1), r00 = outcomeRows(ctx, ctx.t0, m0);
    const r11 = outcomeRows(ctx, ctx.t1, m1), r10 = outcomeRows(ctx, ctx.t1, m0);
    const diff = (a: number[][], c: number[][]) => meanDD(a.map((row, i) => {
      let s = 0;
      for (let k = 0; k < row.length; k++) s += (row[k]! - c[i]![k]!) * b[k]!;
      return s;
    }));
    return [diff(r01, r00), diff(r11, r10), diff(r10, r00), diff(r11, r01), diff(r11, r00)];
  }
  const y01 = outcomeMeans(ctx, ctx.t0, m1, b), y00 = outcomeMeans(ctx, ctx.t0, m0, b);
  const y11 = outcomeMeans(ctx, ctx.t1, m1, b), y10 = outcomeMeans(ctx, ctx.t1, m0, b);
  return [meanDiff(y01, y00), meanDiff(y11, y10), meanDiff(y10, y00), meanDiff(y11, y01), meanDiff(y11, y00)];
}

/** One original-data (or one replicate's) draw of the mediator and the effects, for coefficients a, b */
function effectsOnce(ctx: Context, a: readonly number[], sigma: number, b: readonly number[]): Effects {
  const n = ctx.n;
  const x1 = mediatorRows(ctx, ctx.t1).map((r) => dot(r, a)), x0 = mediatorRows(ctx, ctx.t0).map((r) => dot(r, a));
  let m1: number[], m0: number[];
  if (isLinear(ctx.m)) {
    const e = rnorm(n, { sd: sigma });
    m1 = x1.map((v, i) => v + e[i]!);
    m0 = x0.map((v, i) => v + e[i]!);
  } else {
    m1 = x1.map((v) => rbinom1(1, ctx.m.linkinv(v)));
    m0 = x0.map((v) => rbinom1(1, ctx.m.linkinv(v)));
  }
  return effectsFrom(ctx, m1, m0, b);
}

const isLinear = (p: Prepared): boolean => !p.isGlm || (p.fit as GlmFormulaResult).family === "gaussian";
const sigmaOf = (p: Prepared): number => (p.isGlm ? Math.sqrt(dispersion(p.fit as GlmFormulaResult)) : (p.fit as LmFormulaResult).sigma);
function dispersion(fit: GlmFormulaResult): number {
  // the Pearson dispersion of a gaussian glm: the residual sum of squares over the residual degrees of freedom
  let s = 0;
  for (let i = 0; i < fit.residuals.length; i++) s += fit.weights[i]! * fit.residuals[i]! ** 2;
  return s / fit.dfResidual;
}

/** The quantile of type 7 at two probabilities */
const q7 = (v: readonly number[], lo: number, hi: number): [number, number] => {
  const q = quantile(v, [lo, hi], { type: 7 });
  return [q[0]!, q[1]!];
};

/**
 * Causal mediation analysis. Equivalent to R's `mediation::mediate()` for linear and binomial (logit or probit)
 * mediator and outcome models.
 *
 * The average causal mediation effects (ACME, `d0` and `d1`), the average direct effects (ADE, `z0` and `z1`), the total
 * effect (`tau`) and the proportions mediated (`n0`, `n1`) with their averages, by the quasi-Bayesian Monte Carlo
 * approximation (the default) or the nonparametric bootstrap (`boot: true`), as in Imai, Keele and Tingley (2010).
 * With the same {@link setSeed} the draws, estimates, intervals and p-values equal R's: the parameters are drawn with
 * the symmetric square root of their covariance, then the mediator for every simulation and observation (normal errors
 * with the residual standard error for a linear mediator, binomial draws for a binary one).
 *
 * Quasi-Bayesian estimates are the means of the draws (the proportions mediated: their medians; `nAvg` the average of
 * the two medians); bootstrap estimates come from a final draw on the original data, after the replicates, as in R.
 * Intervals are quantiles of type 7 of the draws (with `bootCiType: "bca"`: the bias-corrected and accelerated levels,
 * the bias measured against the draws' mean and the acceleration from their skewness, as R).
 *
 * The models must be formula fits of {@link lm} or {@link glm} (binomial with logit or probit, or gaussian) on `data`,
 * on the same rows, without weights or offsets; the treatment and the mediator are numeric variables.
 *
 * @param modelM The mediator model (its response is the mediator).
 * @param modelY The outcome model (it includes the treatment and the mediator).
 * @param data The data both models were fitted on.
 * @param options See {@link MediateOptions}; `treat` and `mediator` are required.
 * @returns See {@link MediateResult}.
 * @throws TypeError or RangeError for unsupported models, data that do not reproduce the fits, a treatment or mediator
 *   that is not a numeric variable of the models, models on different rows, `sims` below 2, or
 *   `confLevel` outside (0, 1).
 *
 * @example
 * ```ts
 * const m = lm("M ~ X + C", data), y = lm("Y ~ X + M + C", data);
 * setSeed(1234);
 * const r = mediate(m, y, data, { treat: "X", mediator: "M", sims: 500 });
 * r.d0.estimate; r.d0.ci; r.n0.estimate;
 * ```
 *
 * @category Causal inference
 */
export function mediate(modelM: MediationModel, modelY: MediationModel, data: DataFrame, options: MediateOptions): MediateResult {
  checkOptions(options, MEDIATE_KEYS, "mediate"); // generated: option-keys.mjs
  const { treat, mediator } = options;
  if (typeof treat !== "string" || typeof mediator !== "string") throw new TypeError("'treat' and 'mediator' are required");
  const t1 = options.treatValue ?? 1, t0 = options.controlValue ?? 0;
  if (!Number.isFinite(t1) || !Number.isFinite(t0)) throw new RangeError("treatValue and controlValue must be finite");
  const sims = Math.trunc(options.sims ?? 1000);
  const boot = options.boot ?? false;
  const ciType = options.bootCiType ?? "perc";
  if (ciType !== "perc" && ciType !== "bca") throw new RangeError("bootCiType must be \"perc\" or \"bca\"");
  const level = options.confLevel ?? 0.95;
  if (!(level > 0 && level < 1)) throw new RangeError("confLevel must be in (0, 1)");
  const robust = options.robustSE ?? false;
  // R's mediate fails with sims = 1 ("dim(X) must have a positive length"; always without the bootstrap, for some
  // models with it), so 2 is the least
  if (!(sims >= 2)) throw new RangeError("sims must be at least 2");
  const warnings: string[] = [];
  if (boot && robust) warnings.push("'robustSE' is ignored for nonparametric bootstrap");
  const m = prepare(modelM, data, "mediator"), y = prepare(modelY, data, "outcome");
  if (!isLinear(m) && (modelM as GlmFormulaResult).family !== "binomial") throw new RangeError("unsupported mediator model");
  if (m.d.terms.variables[0] !== mediator) throw new RangeError(`the mediator model's response must be '${mediator}'`);
  if (m.rows.length !== y.rows.length || m.rows.some((r, i) => r !== y.rows[i]))
    throw new RangeError("number of observations do not match between mediator and outcome models");
  const n = m.rows.length;
  const covariates = Object.entries(options.covariates ?? {});
  for (const [, v] of covariates) if (!Number.isFinite(v)) throw new RangeError("covariate values must be finite");
  const ctx: Context = {
    m, y, treat, mediator, t1, t0, n,
    mTreat: numericVariable(m, treat, "mediator", true),
    yTreat: numericVariable(y, treat, "outcome", true),
    yMed: numericVariable(y, mediator, "outcome", true),
    mCov: covariates.map(([k, v]) => [numericVariable(m, k, "mediator", false), v] as [number, number]).filter(([j]) => j >= 0),
    yCov: covariates.map(([k, v]) => [numericVariable(y, k, "outcome", false), v] as [number, number]).filter(([j]) => j >= 0),
  };
  if (covariates.some(([k]) => !m.d.terms.variables.includes(k) && !y.d.terms.variables.includes(k)))
    throw new RangeError("covariates must be variables of the models");
  const linearM = isLinear(m);

  let draws: Effects[];
  let point: Effects | undefined;
  if (!boot) {
    const vm = robust ? vcovHC(modelM, { type: "HC3" }).vcov : modelCovariance(modelM).vcov;
    const vy = robust ? vcovHC(modelY, { type: "HC3" }).vcov : modelCovariance(modelY).vcov;
    const A = drawParameters(m.coef, vm, sims, "mediator"), B = drawParameters(y.coef, vy, sims, "outcome");
    const x1 = mediatorRows(ctx, t1), x0 = mediatorRows(ctx, t0);
    // the mediator for all simulations at once, a sims x n matrix filled by column
    const M1: number[][] = Array.from({ length: sims }, () => new Array<number>(n));
    const M0: number[][] = Array.from({ length: sims }, () => new Array<number>(n));
    if (linearM) {
      const e = rnorm(sims * n, { sd: sigmaOf(m) });
      for (let i = 0; i < n; i++) for (let j = 0; j < sims; j++) {
        M1[j]![i] = dot(x1[i]!, A[j]!) + e[i * sims + j]!;
        M0[j]![i] = dot(x0[i]!, A[j]!) + e[i * sims + j]!;
      }
    } else {
      for (let i = 0; i < n; i++) for (let j = 0; j < sims; j++) M1[j]![i] = rbinom1(1, m.linkinv(dot(x1[i]!, A[j]!)));
      for (let i = 0; i < n; i++) for (let j = 0; j < sims; j++) M0[j]![i] = rbinom1(1, m.linkinv(dot(x0[i]!, A[j]!)));
    }
    draws = A.map((_, j) => effectsFrom(ctx, M1[j]!, M0[j]!, B[j]!));
  } else {
    const idx = sampleInt(n, { size: n * sims, replace: true });
    const variables = [...new Set([...m.d.terms.variables, ...y.d.terms.variables])];
    const sigmaM = linearM ? sigmaOf(m) : NaN;
    // the original-data draw that R makes before the replicates (its value is not used)
    effectsOnce(ctx, m.coef, sigmaM, y.coef);
    draws = [];
    for (let j = 0; j < sims; j++) {
      const take = Array.from({ length: n }, (_, i) => m.rows[idx[j + i * sims]!]!);
      const resample: DataFrame = Object.fromEntries(variables.map((v) => {
        const col = data[v]!;
        return [v, take.map((r) => col[r]!)];
      }));
      const fm = refit(m, resample), fy = refit(y, resample);
      draws.push(effectsOnce(ctx, aligned(fm, m), linearM ? sigmaOf({ ...m, fit: fm, isGlm: "family" in fm }) : NaN, aligned(fy, y)));
    }
    point = effectsOnce(ctx, m.coef, sigmaM, y.coef);
  }

  // the draws of every effect, then the summaries
  const col = (k: number) => draws.map((e) => e[k]!);
  const d0 = col(0), d1 = col(1), z0 = col(2), z1 = col(3), tau = col(4);
  const n0 = d0.map((v, j) => v / tau[j]!), n1 = d1.map((v, j) => v / tau[j]!);
  const dAvg = d0.map((v, j) => (v + d1[j]!) / 2), zAvg = z0.map((v, j) => (v + z1[j]!) / 2), nAvg = n0.map((v, j) => (v + n1[j]!) / 2);
  const lo = (1 - level) / 2, hi = (1 + level) / 2;
  const summarise = (v: number[], est: number): MediateEffect => {
    let ci: [number, number];
    if (boot && ciType === "bca") {
      const mv = meanDD(v);
      let s2 = 0, s3 = 0, below = 0;
      for (const x of v) { const u = mv - x; s2 += u * u; s3 += u * u * u; if (x < mv) below++; }
      const a = s3 / (6 * s2 ** 1.5);
      const z0b = qnorm(below / v.length);
      const level = (zq: number) => pnorm(z0b + (z0b + zq) / (1 - a * (z0b + zq)));
      ci = q7(v, level(qnorm(lo)), level(qnorm(hi)));
    } else ci = q7(v, lo, hi);
    let pos = 0, neg = 0;
    for (const x of v) { if (x > 0) pos++; else if (x < 0) neg++; }
    return { estimate: est, ci, p: 2 * Math.min(pos / v.length, neg / v.length), sims: v };
  };
  let est: number[];
  if (point === undefined) {
    const mn0 = median(n0), mn1 = median(n1);
    est = [meanDD(d0), meanDD(d1), meanDD(z0), meanDD(z1), meanDD(tau), mn0, mn1, meanDD(dAvg), meanDD(zAvg), (mn0 + mn1) / 2];
  } else {
    const [p0, p1, q0, q1, pt] = point;
    est = [p0, p1, q0, q1, pt, p0 / pt, p1 / pt, (p0 + p1) / 2, (q0 + q1) / 2, (p0 / pt + p1 / pt) / 2];
  }
  const INT = y.d.terms.termLabels.some((l) => {
    const parts = l.split(":");
    return parts.length > 1 && parts.includes(treat) && parts.includes(mediator);
  });
  return reported("mediate", {
    d0: summarise(d0, est[0]!), d1: summarise(d1, est[1]!), z0: summarise(z0, est[2]!), z1: summarise(z1, est[3]!),
    tau: summarise(tau, est[4]!), n0: summarise(n0, est[5]!), n1: summarise(n1, est[6]!), dAvg: summarise(dAvg, est[7]!),
    zAvg: summarise(zAvg, est[8]!), nAvg: summarise(nAvg, est[9]!),
    treatValue: t1, controlValue: t0, nobs: n, sims, boot, bootCiType: ciType, confLevel: level, robustSE: robust && !boot, INT,
    warnings,
  });
}

/** Refits a prepared model on a resample with its own options (warnings of the refits are not reported, as R's are only printed) */
function refit(p: Prepared, resample: DataFrame): MediationModel {
  const opts = { ...p.options } as Record<string, unknown>;
  return unreported(() => (p.isGlm ? glm(p.formula, resample, opts as never) : lm(p.formula, resample, opts as never)));
}

/** A refit's coefficients in the original model's column order (a column the resample lost is an error) */
function aligned(fit: MediationModel, p: Prepared): number[] {
  const names = "family" in fit ? (fit as GlmFormulaResult).model.columnNames : (fit as LmFormulaResult).coefNames;
  return p.names.map((nm) => {
    const k = names.indexOf(nm);
    if (k < 0 || Number.isNaN(fit.coefficients[k]!)) throw new RangeError(`a bootstrap resample cannot estimate '${nm}'`);
    return fit.coefficients[k]!;
  });
}
