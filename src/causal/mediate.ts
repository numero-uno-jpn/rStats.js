// Causal mediation analysis: mediation's mediate (Imai, Keele & Tingley 2010, Algorithms 1 and 2) for lm and binomial
// glm models. The behaviour is in oracle/mediation-behaviour.md, from the package's documentation and published output
// (experiments/mediation116*.R; every attempt, the failed ones too, in experiments/mediation116-log.md). Written for
// rStats.js (no ported code).
//
// - Quasi-Bayesian (boot false): the mediator model's coefficients, then the outcome model's, are drawn as rows of
//   normals times the symmetric square root of their covariance; then the mediator is drawn for every simulation and
//   observation (normal errors shared by M(t1) and M(t0) for an lm mediator, rbinom for M(t1) then M(t0) for a
//   binomial one); the effects are means over the observations of differences of predicted outcomes
// - Bootstrap (boot true): one sample(n, n * sims, replace) as a sims x n matrix by column (replicate = row), an
//   original-data draw whose value R does not use, each replicate refitted on its resample and evaluated on the
//   original data, and a last original-data draw that gives the point estimates
// - The same values as R under the same setSeed (the symmetric square root does not depend on eigenvector signs)

