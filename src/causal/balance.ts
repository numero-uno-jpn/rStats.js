/**
 * The weight of each unit after matching: every pair adds its weight `1 / M` to both of its units; unmatched units
 * weigh 0. Equivalent to `cobalt::get.w()` in R. The call followed is `get.w(m)` for a `Match` object `m`.
 * @category Causal inference
 * @example
 * ```ts
 * matchWeights(match([1, 0, 1, 0, 0], [0.2, 0.1, 1.5, 1.4, 3])); // [1, 1, 1, 1, 0]
 * ```
 */
export function matchWeights(m: MatchResult): number[] {
  const w = new Array<number>(m.nobs).fill(0);
  m.indexTreated.forEach((t, i) => {
    w[t - 1]! += m.weights[i]!;
    w[m.indexControl[i]! - 1]! += m.weights[i]!;
  });
  return w;
}

/** Options of {@link balTab}. Equivalent to the arguments of cobalt's `bal.tab()` for a `Match` or `weightit` object.
 * @category Causal inference
 */
export interface BalTabOptions {
  /**
   * The result of {@link match}: gives the weights ({@link matchWeights}), the estimand and, with a caliper, the
   * discarded units. Alternative to `weights` and `estimand`.
   */
  match?: MatchResult;
  /**
   * The result of {@link weightit}: gives the weights, the estimand and the propensity score (the first row,
   * `"prop.score"`, when the method has one). Alternative to `match`, `weights` and `estimand`.
   */
  weightit?: WeightitResult;
  /** The weights after matching or weighting; without them only the unadjusted columns are filled. */
  weights?: readonly number[];
  /** The estimand, which chooses the SD of the denominator (default `"ATT"`); `"ATO"` needs the weights. */
  estimand?: WeightitEstimand;
  /** The order of the levels of string covariates (R's factor levels); default code-point order. */
  levels?: Readonly<Record<string, readonly string[]>>;
  /** Binary covariates: `"raw"` difference in proportions (default, as cobalt) or `"std"` standardised. */
  binary?: "raw" | "std";
}

/** Result of {@link balTab}: one entry per covariate, in the order given (cobalt's `Balance` table), and the counts.
 * @category Causal inference
 */
export interface BalTabResult {
  /** Covariate names (`"prop.score"` first for a weightit result with a score; a string covariate gives a row
   * `name_level` per level, one row for the second level when it has two). */
  rows: string[];
  /** `"Distance"` (the propensity score), `"Contin."` or `"Binary"` (two distinct values, 0 and 1). */
  type: ("Distance" | "Contin." | "Binary")[];
  /** Difference treated − control before matching: standardised (continuous, or binary with `binary: "std"`) or raw. */
  diffUn: number[];
  /** The same after matching (weighted); NaN without weights. */
  diffAdj: number[];
  /** Variance ratio treated / control before matching (NaN for binary covariates). */
  vRatioUn: number[];
  /** The same after matching, with weighted variances; NaN for binary covariates or without weights. */
  vRatioAdj: number[];
  /**
   * Sample sizes of the control and treated groups (cobalt's `Observations`): all (effective sample size, the same as
   * the count), all (unweighted), matched (effective sample size `(sum w)^2 / sum w^2`), matched (unweighted:
   * `w > 0`), unmatched (`w = 0`) and, when `match` has a caliper, discarded (its `indexDropped`, not counted as unmatched). The
   * matched rows are NaN without weights. For a weightit result: unadjusted (the count)
   * and adjusted (the effective sample size).
   */
  observations: {
    /** Row names, in the order of the counts. */
    rows: string[];
    /** Counts of the control group. */
    control: number[];
    /** Counts of the treated group. */
    treated: number[];
  };
}

function isTreated(t: number | boolean, i: number): boolean {
  if (t === true || t === 1) return true;
  if (t === false || t === 0) return false;
  throw new RangeError(`'tr' must be 0 or 1 (element ${i + 1})`);
}

/** Weighted mean and variance (divisor sum(w) - sum(w^2) / sum(w), cobalt's), over the units with g === group. */
function moments(v: readonly number[], w: readonly number[] | null, g: readonly boolean[], group: boolean): [number, number] {
  let sw = 0, sw2 = 0, swx = 0;
  for (let i = 0; i < v.length; i++) {
    if (g[i] !== group) continue;
    const wi = w === null ? 1 : w[i]!;
    sw += wi; sw2 += wi * wi; swx += wi * v[i]!;
  }
  const mean = swx / sw;
  let ss = 0;
  for (let i = 0; i < v.length; i++) {
    if (g[i] !== group) continue;
    const wi = w === null ? 1 : w[i]!;
    ss += wi * (v[i]! - mean) * (v[i]! - mean);
  }
  return [mean, ss / (sw - sw2 / sw)];
}

/**
 * Covariate balance of two groups before and after matching or weighting: standardised mean differences and variance
 * ratios. Equivalent to `cobalt::bal.tab()` in R. The calls followed are
 * `bal.tab(m, formula = tr ~ ..., data, un = TRUE, disp.v.ratio = TRUE, binary)` for a `Match` object `m` and
 * `bal.tab(w, stats = c("mean.diffs", "variance.ratios"), un = TRUE, binary)` for a `weightit` object `w`.
 *
 * The difference is `(mean treated − mean control) / s`, with means weighted after adjustment. The SD `s` is the same
 * before and after: of the unadjusted treated for ATT, of the unadjusted controls for ATC, `sqrt((s1² + s0²) / 2)` for
 * ATE; for ATO that of the whole sample weighted by the (overlap) weights (weighted variance with divisor
 * `sum w − sum w² / sum w`). For a binary covariate (with `binary: "std"`) `p(1 − p)` takes the place of the variance.
 * Variance ratios are treated / control. A string covariate is a factor: one binary row per level.
 * @category Causal inference
 * @example
 * ```ts
 * const tr = [1, 0, 1, 0, 0, 1, 0, 0];
 * const age = [52, 40, 61, 58, 33, 47, 50, 45];
 * const m = match(tr, [0.4, -0.9, 1.2, 1.0, -1.5, 0.1, 0.3, -0.2]);
 * const b = balTab(tr, { age }, { match: m });
 * b.diffUn; // [1.1464120051932525]
 * b.diffAdj; // [0.32888869001445803]
 * ```
 */
export function balTab(tr: readonly (number | boolean)[],
  covariates: Readonly<Record<string, readonly number[] | readonly string[]>>, options: BalTabOptions = {}): BalTabResult {
    checkOptions(options, BAL_TAB_KEYS, "balTab"); // generated: option-keys.mjs
  const { match: m, weightit: wi, binary = "raw", levels = {} } = options;
  if (m !== undefined && wi !== undefined) throw new RangeError("give 'match' or 'weightit', not both");
  const weights = m !== undefined ? matchWeights(m) : wi !== undefined ? wi.weights : options.weights;
  const estimand = m?.estimand ?? wi?.estimand ?? options.estimand ?? "ATT";
  const discarded = new Set(m?.indexDropped ?? []);
  const withDiscarded = m !== undefined && m.caliper !== null;
  const n = tr.length;
  const g = tr.map(isTreated);
  if (!g.includes(true) || !g.includes(false)) throw new RangeError("'tr' must contain both groups");
  if (weights !== undefined && weights.length !== n) throw new RangeError("'weights' must have the length of 'tr'");
  if (estimand === "ATO" && weights === undefined) throw new RangeError("estimand 'ATO' needs the weights");
  // the rows: the propensity score, then the covariates with a string covariate split into its levels
  const columns: [string, readonly number[], "Distance" | null][] = [];
  if (wi?.ps) columns.push(["prop.score", wi.ps, "Distance"]);
  for (const [name, col] of Object.entries(covariates)) {
    if (col.length !== n) throw new RangeError(`covariate '${name}' must have the length of 'tr'`);
    if (col.every((x) => typeof x === "number")) { columns.push([name, col as readonly number[], null]); continue; }
    if (!col.every((x) => typeof x === "string")) throw new TypeError(`covariate '${name}' must be all numbers or all strings`);
    const lev = levels[name] ?? [...new Set(col as readonly string[])].sort(compareCodePoints);
    if ((col as readonly string[]).some((x) => !lev.includes(x))) throw new RangeError(`covariate '${name}' has values not among its levels`);
    // cobalt shows a two-level factor as its second level only
    for (const lv of lev.length === 2 ? lev.slice(1) : lev) columns.push([`${name}_${lv}`, col.map((x) => (x === lv ? 1 : 0)), null]);
  }
  const everyone = g.map(() => true);
  const adjustedRows = wi !== undefined;
  const result: BalTabResult = {
    rows: columns.map(([name]) => name), type: [], diffUn: [], diffAdj: [], vRatioUn: [], vRatioAdj: [],
    observations: {
      rows: adjustedRows ? ["Unadjusted", "Adjusted"]
        : ["All (ESS)", "All (Unweighted)", "Matched (ESS)", "Matched (Unweighted)", "Unmatched", ...(withDiscarded ? ["Discarded"] : [])],
      control: [], treated: [],
    },
  };
  for (const [name, v, kind] of columns) {
    if (v.some((x) => !Number.isFinite(x))) throw new RangeError(`covariate '${name}' has missing or infinite values`);
    const isBinary = kind === null && new Set(v).size <= 2 && v.every((x) => x === 0 || x === 1);
    // a continuous covariate rescaled exactly: its standardised differences and variance ratios do not change
    const vs = isBinary ? v : rescaled(v).values;
    const [m1, var1] = moments(vs, null, g, true);
    const [m0, var0] = moments(vs, null, g, false);
    let s: number;
    if (estimand === "ATO") {
      // the SD of the whole sample under the overlap weights
      const [mw, vw] = moments(vs, weights!, everyone, true);
      s = Math.sqrt(isBinary ? mw * (1 - mw) : vw);
    } else {
      const spread = isBinary ? [m1 * (1 - m1), m0 * (1 - m0)] : [var1, var0];
      s = estimand === "ATT" ? Math.sqrt(spread[0]!) : estimand === "ATC" ? Math.sqrt(spread[1]!)
        : Math.sqrt((spread[0]! + spread[1]!) / 2);
    }
    const scale = isBinary && binary === "raw" ? 1 : s;
    result.type.push(kind ?? (isBinary ? "Binary" : "Contin."));
    // a difference of 0 is 0 (cobalt's, also for a constant covariate whose SD is 0)
    result.diffUn.push(m1 === m0 ? 0 : (m1 - m0) / scale);
    // a zero control variance gives NA in cobalt (not Inf)
    result.vRatioUn.push(isBinary || var0 === 0 ? NaN : var1 / var0);
    if (weights === undefined) { result.diffAdj.push(NaN); result.vRatioAdj.push(NaN); continue; }
    const [a1, av1] = moments(vs, weights, g, true);
    const [a0, av0] = moments(vs, weights, g, false);
    result.diffAdj.push(a1 === a0 ? 0 : (a1 - a0) / scale);
    result.vRatioAdj.push(isBinary || av0 === 0 ? NaN : av1 / av0);
  }
  for (const group of [false, true]) {
    let count = 0, sw = 0, sw2 = 0, positive = 0, gone = 0;
    for (let i = 0; i < n; i++) {
      if (g[i] !== group) continue;
      count++;
      if (discarded.has(i + 1)) gone++;
      if (weights === undefined) continue;
      const wi = weights[i]!;
      sw += wi; sw2 += wi * wi;
      if (wi > 0) positive++;
    }
    const side = group ? result.observations.treated : result.observations.control;
    if (adjustedRows) { side.push(count, sw * sw / sw2); continue; }
    const matched = weights === undefined ? [NaN, NaN, NaN] : [sw * sw / sw2, positive, count - positive - gone];
    if (withDiscarded) matched.push(gone);
    side.push(count, count, ...matched);
  }
  return result;
}

/** Options of {@link tableOneSmd}.
 * @category Causal inference
 */
export interface TableOneSmdOptions {
  /** Treat `x` as categorical (tableone's `factorVars`): numbers or strings as levels. Default false. */
  factor?: boolean;
}

/**
 * Standardised mean difference of one variable between two groups. Equivalent to `tableone::ExtractSmd()` in R. The
 * call followed is `ExtractSmd(CreateTableOne(vars, strata, data, factorVars))` with two groups. Missing values (`NaN`,
 * `null`) are left out.
 *
 * Numeric: `|mean1 − mean0| / sqrt((s1² + s0²) / 2)` with the groups' SDs (divisor `n − 1`). Categorical
 * (`factor: true`): Yang and Dalton's `sqrt(d' S⁻¹ d)`, `d` the differences of the proportions of the levels after the
 * first, `S` the mean of the two groups' multinomial covariance matrices `p_k (δ_kl − p_l)`; with two levels
 * `|p1 − p0| / sqrt((p1(1 − p1) + p0(1 − p0)) / 2)`. 0 when both the difference and the spread are 0. When `S` is
 * singular (a level in one group only) the generalised inverse is used, as tableone; when `S` is 0 (one level in each
 * group) the result is NaN, as tableone.
 * @category Causal inference
 * @example
 * ```ts
 * tableOneSmd([1, 2, 3, 2, 5, 4], [0, 0, 0, 1, 1, 1]); // 1.2909944487358056
 * tableOneSmd(["a", "b", "a", "b", "b", "b"], [0, 0, 0, 1, 1, 1], { factor: true }); // 2
 * ```
 */
export function tableOneSmd(x: readonly (number | string | null)[], group: readonly (number | string | boolean)[],
  options: TableOneSmdOptions = {}): number {
    checkOptions(options, TABLE_ONE_SMD_KEYS, "tableOneSmd"); // generated: option-keys.mjs
  const { factor = false } = options;
  if (x.length !== group.length) throw new RangeError("'x' and 'group' must have the same length");
  const glev = [...new Set(group)].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  if (glev.length !== 2) throw new RangeError("'group' must have exactly two levels");
  const keep = (v: number | string | null): boolean => v !== null && !(typeof v === "number" && Number.isNaN(v));
  const parts = glev.map((lv) => x.filter((v, i) => group[i] === lv && keep(v)));
  if (!factor) {
    if (parts.flat().some((e) => typeof e !== "number")) throw new TypeError("'x' must be numeric unless factor: true");
    // rescaled exactly as one column (the SMD does not change)
    const all = rescaled(parts.flat() as number[]).values;
    const split = [all.slice(0, parts[0]!.length), all.slice(parts[0]!.length)];
    const stats = split.map((v) => {
      const mean = v.reduce((s, e) => s + e, 0) / v.length;
      return [mean, v.reduce((s, e) => s + (e - mean) * (e - mean), 0) / (v.length - 1)] as const;
    });
    const diff = stats[1]![0] - stats[0]![0];
    const sd = Math.sqrt((stats[0]![1] + stats[1]![1]) / 2);
    return diff === 0 ? 0 : Math.abs(diff) / sd;
  }
  const levels = [...new Set(parts.flat())].sort((a, b) => (typeof a === "number" && typeof b === "number" ? a - b
    : String(a) < String(b) ? -1 : String(a) > String(b) ? 1 : 0));
  const props = parts.map((p) => levels.slice(1).map((lv) => p.filter((e) => e === lv).length / p.length));
  const d = props[1]!.map((q, k) => q - props[0]![k]!);
  if (d.every((e) => e === 0)) return 0;
  const K = d.length;
  const S = Array.from({ length: K }, (_, k) => Array.from({ length: K }, (_, l) => {
    const c = (p: number[]): number => (k === l ? p[k]! * (1 - p[k]!) : -p[k]! * p[l]!);
    return (c(props[0]!) + c(props[1]!)) / 2;
  }));
  // S is singular when a level is in one group only: tableone's value is then that of the generalised inverse
  // (MASS::ginv's; experiments/psm112-edge.json factorAbsent), and NaN when S is 0 (each group has one level)
  if (S.every((row) => row.every((v) => v === 0))) return NaN;
  const Si = ginv(S);
  let q = 0;
  for (let k = 0; k < K; k++) for (let l = 0; l < K; l++) q += d[k]! * Si[k]![l]! * d[l]!;
  return Math.sqrt(q);
}
