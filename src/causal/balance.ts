// Covariate balance before and after matching: the standardised mean differences and variance ratios of cobalt's
// bal.tab (for a Match object) and the standardised mean differences of tableone's CreateTableOne / ExtractSmd. The
// definitions are in oracle/match-behaviour.md, from the packages' documentation and published output; Yang & Dalton
// (2012), "A unified approach to measuring the effect size between two groups using SAS", SAS Global Forum 335, for
// the categorical SMD. Written for rStats.js (no ported code).
