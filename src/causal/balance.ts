/**
 * The weight of each unit after matching, as cobalt's `get.w()` of a `Match` object: every pair adds its weight
 * (1 / M) to both of its units; unmatched units weigh 0.
 * @category Causal inference
 * @example
 * ```ts
 * import { match, matchWeights } from "rstats-js/causal";
 * matchWeights(match([1, 0, 1, 0, 0], [0.2, 0.1, 1.5, 1.4, 3])); // [1, 1, 1, 1, 0]
 * ```
 */
export function matchWeights(m: MatchResult): number[] {
  const w = new Array<number>(m.nobs).fill(0);
  m.indexTreated.forEach((t, i) => {
    w[t - 1]! += m.weights[i]!;
    w[m.indexControl[i]! - 1]! += m.weights[i]!;
  });
  return w;
}

/** Options of {@link balTab}. Equivalent to the arguments of cobalt's `bal.tab()` for a `Match` object.
 * @category Causal inference
 */
export interface BalTabOptions {
  /**
   * The result of {@link match}: gives the weights ({@link matchWeights}), the estimand and, with a caliper, the
   * discarded units. Alternative to `weights` and `estimand`.
   */
  match?: MatchResult;
  /** The weights after matching (from {@link matchWeights}); without them only the unadjusted columns are filled. */
  weights?: readonly number[];
  /** The estimand, which chooses the SD of the denominator (default `"ATT"`). */
  estimand?: MatchEstimand;
  /** Binary covariates: `"raw"` difference in proportions (default, as cobalt) or `"std"` standardised. */
  binary?: "raw" | "std";
}

/** Result of {@link balTab}: one entry per covariate, in the order given (cobalt's `Balance` table), and the counts.
 * @category Causal inference
 */
export interface BalTabResult {
  /** Covariate names. */
  rows: string[];
  /** `"Contin."` or `"Binary"` (a covariate with two distinct values, 0 and 1). */
  type: ("Contin." | "Binary")[];
  /** Difference treated − control before matching: standardised (continuous, or binary with `binary: "std"`) or raw. */
  diffUn: number[];
  /** The same after matching (weighted); NaN without weights. */
  diffAdj: number[];
  /** Variance ratio treated / control before matching (NaN for binary covariates). */
  vRatioUn: number[];
  /** The same after matching, with weighted variances; NaN for binary covariates or without weights. */
  vRatioAdj: number[];
  /**
   * Sample sizes of the control and treated groups (cobalt's `Observations`): all (effective sample size, the same as
   * the count), all (unweighted), matched (effective sample size (sum w)^2 / sum w^2), matched (unweighted: w > 0),
   * unmatched (w = 0) and, when `match` has a caliper, discarded (its `indexDropped`, not counted as unmatched). The
   * matched rows are NaN without weights.
   */
  observations: {
    rows: string[];
    control: number[];
    treated: number[];
  };
}

function isTreated(t: number | boolean, i: number): boolean {
  if (t === true || t === 1) return true;
  if (t === false || t === 0) return false;
  throw new RangeError(`'tr' must be 0 or 1 (element ${i + 1})`);
}

/** Weighted mean and variance (divisor sum(w) - sum(w^2) / sum(w), cobalt's), over the units with g === group. */
function moments(v: readonly number[], w: readonly number[] | null, g: readonly boolean[], group: boolean): [number, number] {
  let sw = 0, sw2 = 0, swx = 0;
  for (let i = 0; i < v.length; i++) {
    if (g[i] !== group) continue;
    const wi = w === null ? 1 : w[i]!;
    sw += wi; sw2 += wi * wi; swx += wi * v[i]!;
  }
  const mean = swx / sw;
  let ss = 0;
  for (let i = 0; i < v.length; i++) {
    if (g[i] !== group) continue;
    const wi = w === null ? 1 : w[i]!;
    ss += wi * (v[i]! - mean) * (v[i]! - mean);
  }
  return [mean, ss / (sw - sw2 / sw)];
}

/**
 * Covariate balance of two groups before and after matching: standardised mean differences and variance ratios.
 * Equivalent to cobalt's `bal.tab(m, formula = tr ~ ..., data, un = TRUE, disp.v.ratio = TRUE, binary)` for a
 * `Match` object `m`, with `weights` from {@link matchWeights}.
 *
 * The difference is (mean treated − mean control) / s, with means weighted after matching. The SD s is always that of
 * the unmatched sample: of the treated for ATT, of the controls for ATC, sqrt((s1² + s0²) / 2) for ATE; for a binary
 * covariate (with `binary: "std"`) sqrt(p(1 − p)) in place of the SD (the mean of p1(1 − p1) and p0(1 − p0) for ATE).
 * Variance ratios are treated / control. Factor covariates are not split: give one 0/1 column per level.
 * @category Causal inference
 * @example
 * ```ts
 * import { balTab, match, matchWeights } from "rstats-js/causal";
 * const tr = [1, 0, 1, 0, 0, 1, 0, 0];
 * const age = [52, 40, 61, 58, 33, 47, 50, 45];
 * const m = match(tr, [0.4, -0.9, 1.2, 1.0, -1.5, 0.1, 0.3, -0.2]);
 * const b = balTab(tr, { age }, { weights: matchWeights(m) });
 * b.diffUn; // [0.8183100977315137]
 * b.diffAdj; // [0.11081074240114... (close to 0 after matching)
 * ```
 */
export function balTab(tr: readonly (number | boolean)[], covariates: Readonly<Record<string, readonly number[]>>,
  options: BalTabOptions = {}): BalTabResult {
  const { match: m, binary = "raw" } = options;
  const weights = m === undefined ? options.weights : matchWeights(m);
  const estimand = m?.estimand ?? options.estimand ?? "ATT";
  const discarded = new Set(m?.indexDropped ?? []);
  const withDiscarded = m !== undefined && m.caliper !== null;
  const n = tr.length;
  const g = tr.map(isTreated);
  if (!g.includes(true) || !g.includes(false)) throw new RangeError("'tr' must contain both groups");
  if (weights !== undefined && weights.length !== n) throw new RangeError("'weights' must have the length of 'tr'");
  const rows = Object.keys(covariates);
  const result: BalTabResult = {
    rows, type: [], diffUn: [], diffAdj: [], vRatioUn: [], vRatioAdj: [],
    observations: {
      rows: ["All (ESS)", "All (Unweighted)", "Matched (ESS)", "Matched (Unweighted)", "Unmatched", ...(withDiscarded ? ["Discarded"] : [])],
      control: [], treated: [],
    },
  };
  for (const name of rows) {
    const v = covariates[name]!;
    if (v.length !== n) throw new RangeError(`covariate '${name}' must have the length of 'tr'`);
    if (v.some((x) => !Number.isFinite(x))) throw new RangeError(`covariate '${name}' has missing or infinite values`);
    const isBinary = new Set(v).size <= 2 && v.every((x) => x === 0 || x === 1);
    const [m1, var1] = moments(v, null, g, true);
    const [m0, var0] = moments(v, null, g, false);
    const spread = isBinary ? [m1 * (1 - m1), m0 * (1 - m0)] : [var1, var0];
    const s = estimand === "ATT" ? Math.sqrt(spread[0]!) : estimand === "ATC" ? Math.sqrt(spread[1]!)
      : Math.sqrt((spread[0]! + spread[1]!) / 2);
    const scale = isBinary && binary === "raw" ? 1 : s;
    result.type.push(isBinary ? "Binary" : "Contin.");
    result.diffUn.push((m1 - m0) / scale);
    // a zero control variance gives NA in cobalt (not Inf)
    result.vRatioUn.push(isBinary || var0 === 0 ? NaN : var1 / var0);
    if (weights === undefined) { result.diffAdj.push(NaN); result.vRatioAdj.push(NaN); continue; }
    const [a1, av1] = moments(v, weights, g, true);
    const [a0, av0] = moments(v, weights, g, false);
    result.diffAdj.push((a1 - a0) / scale);
    result.vRatioAdj.push(isBinary || av0 === 0 ? NaN : av1 / av0);
  }
  for (const group of [false, true]) {
    let count = 0, sw = 0, sw2 = 0, positive = 0, gone = 0;
    for (let i = 0; i < n; i++) {
      if (g[i] !== group) continue;
      count++;
      if (discarded.has(i + 1)) gone++;
      if (weights === undefined) continue;
      const wi = weights[i]!;
      sw += wi; sw2 += wi * wi;
      if (wi > 0) positive++;
    }
    const matched = weights === undefined ? [NaN, NaN, NaN] : [sw * sw / sw2, positive, count - positive - gone];
    if (withDiscarded) matched.push(gone);
    (group ? result.observations.treated : result.observations.control).push(count, count, ...matched);
  }
  return result;
}

/** Options of {@link tableOneSmd}.
 * @category Causal inference
 */
export interface TableOneSmdOptions {
  /** Treat `x` as categorical (tableone's `factorVars`): numbers or strings as levels. Default false. */
  factor?: boolean;
}

/**
 * Standardised mean difference of one variable between two groups, as tableone's `ExtractSmd(CreateTableOne(vars,
 * strata, data, factorVars))` with two groups. Missing values (NaN, null) are left out.
 *
 * Numeric: |mean1 − mean0| / sqrt((s1² + s0²) / 2) with the groups' SDs (divisor n − 1). Categorical (`factor: true`):
 * Yang and Dalton's sqrt(d' S⁻¹ d), d the differences of the proportions of the levels after the first, S the mean of
 * the two groups' multinomial covariance matrices p_k(δ_kl − p_l); with two levels |p1 − p0| / sqrt((p1(1 − p1) +
 * p0(1 − p0)) / 2). 0 when both the difference and the spread are 0.
 * @category Causal inference
 * @example
 * ```ts
 * import { tableOneSmd } from "rstats-js/causal";
 * tableOneSmd([1, 2, 3, 2, 5, 4], [0, 0, 0, 1, 1, 1]); // 1.6329931618554523
 * tableOneSmd(["a", "b", "a", "b", "b", "b"], [0, 0, 0, 1, 1, 1], { factor: true }); // 1.0690449676496976
 * ```
 */
export function tableOneSmd(x: readonly (number | string | null)[], group: readonly (number | string | boolean)[],
  options: TableOneSmdOptions = {}): number {
  const { factor = false } = options;
  if (x.length !== group.length) throw new RangeError("'x' and 'group' must have the same length");
  const glev = [...new Set(group)].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  if (glev.length !== 2) throw new RangeError("'group' must have exactly two levels");
  const keep = (v: number | string | null): boolean => v !== null && !(typeof v === "number" && Number.isNaN(v));
  const parts = glev.map((lv) => x.filter((v, i) => group[i] === lv && keep(v)));
  if (!factor) {
    const stats = parts.map((p) => {
      const v = p as number[];
      if (v.some((e) => typeof e !== "number")) throw new TypeError("'x' must be numeric unless factor: true");
      const mean = v.reduce((s, e) => s + e, 0) / v.length;
      return [mean, v.reduce((s, e) => s + (e - mean) * (e - mean), 0) / (v.length - 1)] as const;
    });
    const diff = stats[1]![0] - stats[0]![0];
    const sd = Math.sqrt((stats[0]![1] + stats[1]![1]) / 2);
    return diff === 0 ? 0 : Math.abs(diff) / sd;
  }
  const levels = [...new Set(parts.flat())].sort((a, b) => (typeof a === "number" && typeof b === "number" ? a - b
    : String(a) < String(b) ? -1 : String(a) > String(b) ? 1 : 0));
  const props = parts.map((p) => levels.slice(1).map((lv) => p.filter((e) => e === lv).length / p.length));
  const d = props[1]!.map((q, k) => q - props[0]![k]!);
  if (d.every((e) => e === 0)) return 0;
  const K = d.length;
  const S = Array.from({ length: K }, (_, k) => Array.from({ length: K }, (_, l) => {
    const c = (p: number[]): number => (k === l ? p[k]! * (1 - p[k]!) : -p[k]! * p[l]!);
    return (c(props[0]!) + c(props[1]!)) / 2;
  }));
  const y = solve(S, d);
  return Math.sqrt(d.reduce((s, e, k) => s + e * y[k]!, 0));
}
