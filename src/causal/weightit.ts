// Inverse probability of treatment weighting: WeightIt's weightit (methods glm, cbps, ipt and ebal for a binary
// treatment), trim and the weight summary of summary.weightit. The behaviour is in oracle/weightit-behaviour.md, from the
// packages' documentation and published output; Imai & Ratkovic (2014) for the just-identified covariate balancing
// propensity score, Graham, Pinto & Egel (2012) for inverse probability tilting, Hainmueller (2012) for entropy
