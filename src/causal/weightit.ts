/** The estimand of {@link weightit}: the population whose average treatment effect the weights target.
 * @category Causal inference
 */
export type WeightitEstimand = "ATE" | "ATT" | "ATC" | "ATO";

/** The method of {@link weightit} (WeightIt's `method`; `"ps"` is an alias of `"glm"`).
 * @category Causal inference
 */
export type WeightitMethod = "glm" | "ps" | "cbps" | "ipt" | "ebal";

/** Options of {@link weightit}. Equivalent to the arguments of WeightIt's `weightit()`.
 * @category Causal inference
 */
export interface WeightitOptions {
  /** How the weights are estimated (default `"glm"`): see {@link weightit}. */
  method?: WeightitMethod;
  /** The link of the propensity score model: `"logit"` (default), `"probit"`, `"cauchit"` or `"cloglog"` for glm,
   * `"logit"` or `"probit"` for cbps, `"logit"` for ipt; ebal has none. */
  link?: "logit" | "probit" | "cauchit" | "cloglog";
  /** The estimand (default `"ATE"`). ipt and ebal do not allow `"ATO"`. */
  estimand?: WeightitEstimand;
  /** Multiply the weights by the share of the unit's group in the sample (glm with ATE only; ignored with a warning
   * by the other methods, an error with another estimand, as R). Default false. */
  stabilize?: boolean;
}

/** Result of {@link weightit}.
 * @category Causal inference
 */
export interface WeightitResult {
  /** The weights, one per unit, in the order of `tr`. */
  weights: number[];
  /** The propensity scores (null for ebal, which has none): for ipt the score of the tilting that weights the unit's
   * group (ATE), or of the weighted group for all units (ATT: the controls' tilting; ATC: the treated's). */
  ps: number[] | null;
  /** The treatment, 0 or 1 per unit. */
  treat: number[];
  /** The estimand. */
  estimand: WeightitEstimand;
  /** The method as R reports it (`"glm"` for `"ps"`). */
  method: "glm" | "cbps" | "ipt" | "ebal";
  /** The link (null for ebal). */
  link: string | null;
  /** Whether the weights were stabilised. */
  stabilized: boolean;
  /** The focal group of ATT (`1`) and ATC (`0`), null otherwise: its weights are 1. */
  focal: 0 | 1 | null;
  /** The columns of the model matrix after the intercept: the numeric covariates and, for a string covariate, one 0/1
   * column per level after the first (R's treatment contrasts, levels in code-point order). */
  columnNames: string[];
  /** Whether the estimation converged (the glm, or the solution of the balance conditions). */
  converged: boolean;
  /** R's warnings, each once. */
  warnings: string[];
}

/** A covariate: numbers, or strings (a factor with its levels in code-point order). */
export type CovariateColumn = readonly number[] | readonly string[];

const EPS = Number.EPSILON;

function treatment(tr: readonly (number | boolean)[]): number[] {
  return tr.map((t, i) => {
    if (t === true || t === 1) return 1;
    if (t === false || t === 0) return 0;
    throw new RangeError(`'tr' must be 0 or 1 (element ${i + 1})`);
  });
}

/** The model matrix without its intercept: one column per numeric covariate, k - 1 indicator columns per factor */
export function covariateColumns(covariates: Readonly<Record<string, CovariateColumn>>, n: number):
  { names: string[]; columns: number[][]; factors: Record<string, string[]> } {
  const names: string[] = [], columns: number[][] = [], factors: Record<string, string[]> = {};
  for (const [name, col] of Object.entries(covariates)) {
    if (col.length !== n) throw new RangeError(`covariate '${name}' must have the length of 'tr'`);
    if (col.every((v) => typeof v === "number")) {
      const v = col as readonly number[];
      if (v.some((x) => !Number.isFinite(x))) throw new RangeError(`covariate '${name}' has missing or infinite values`);
      names.push(name); columns.push(v.slice());
      continue;
    }
    if (!col.every((v) => typeof v === "string")) throw new TypeError(`covariate '${name}' must be all numbers or all strings`);
    const v = col as readonly string[];
    const levels = [...new Set(v)].sort(compareCodePoints);
    factors[name] = levels;
    for (const lv of levels.slice(1)) { names.push(name + lv); columns.push(v.map((s) => (s === lv ? 1 : 0))); }
  }
  return { names, columns, factors };
}

/** Columns centred at their mean and divided by their largest deviation: with an intercept in the model, the balance
 * conditions (and so the weights and scores) are unchanged by this affine map, and Newton's method is well scaled */
function standardised(columns: number[][]): number[][] {
  return columns.map((c) => {
    const m = c.reduce((a, v) => a + v, 0) / c.length;
    const s = c.reduce((a, v) => Math.max(a, Math.abs(v - m)), 0);
    return c.map((v) => (s > 0 ? (v - m) / s : 0));
  });
}

/**
 * The columns that are not constant nor combinations of the intercept and earlier columns (Gram-Schmidt with R's qr
 * tolerance 1e-7 on the relative residual norm): those R's model fit keeps, the others being aliased
 */
function independent(columns: number[][]): number[][] {
  const n = columns[0]?.length ?? 0;
  const basis: number[][] = [new Array<number>(n).fill(1 / Math.sqrt(n))];
  const kept: number[][] = [];
  for (const c of columns) {
    const norm0 = Math.sqrt(c.reduce((a, v) => a + v * v, 0));
    const r = c.slice();
    for (let pass = 0; pass < 2; pass++) for (const q of basis) {
      const dot = r.reduce((a, v, i) => a + v * q[i]!, 0);
      for (let i = 0; i < n; i++) r[i]! -= dot * q[i]!;
    }
    const norm = Math.sqrt(r.reduce((a, v) => a + v * v, 0));
    if (!(norm > 1e-7 * norm0)) continue;
    basis.push(r.map((v) => v / norm));
    kept.push(c);
  }
  return kept;
}

/** Solves A x = b (Gaussian elimination with partial pivoting); null when A is singular */
function solve(A: number[][], b: number[]): number[] | null {
  const p = b.length;
  const M = A.map((r, i) => [...r, b[i]!]);
  let scale = 0;
  for (const r of A) for (const v of r) scale = Math.max(scale, Math.abs(v));
  for (let k = 0; k < p; k++) {
    let piv = k;
    for (let i = k + 1; i < p; i++) if (Math.abs(M[i]![k]!) > Math.abs(M[piv]![k]!)) piv = i;
    if (!(Math.abs(M[piv]![k]!) > 1e-13 * scale)) return null;
    [M[k], M[piv]] = [M[piv]!, M[k]!];
    for (let i = k + 1; i < p; i++) {
      const f = M[i]![k]! / M[k]![k]!;
      if (f !== 0) for (let j = k; j <= p; j++) M[i]![j]! -= f * M[k]![j]!;
    }
  }
  const x = new Array<number>(p).fill(0);
  for (let i = p - 1; i >= 0; i--) {
    let s = M[i]![p]!;
    for (let j = i + 1; j < p; j++) s -= M[i]![j]! * x[j]!;
    x[i] = s / M[i]![i]!;
  }
  return x;
}

/** Rows of [1, z...] for every unit */
function design(z: number[][], n: number): number[][] {
  return Array.from({ length: n }, (_, i) => [1, ...z.map((c) => c[i]!)]);
}

/**
 * Exponential tilting: beta with sum over `rows` of exp(x_i beta) x_i = target (x with its intercept), the minimum of the
 * convex sum exp(x_i beta) - target' beta. Returns the linear predictor of every unit, and whether it converged.
 */
function tilt(X: number[][], rows: readonly number[], target: number[]): { eta: number[]; converged: boolean } {
  const p = target.length;
  const beta = new Array<number>(p).fill(0);
  beta[0] = Math.log(target[0]! / rows.length);
  const objective = (b: number[]): number => {
    let s = 0;
    for (const i of rows) s += Math.exp(X[i]!.reduce((a, v, j) => a + v * b[j]!, 0));
    return s - target.reduce((a, t, j) => a + t * b[j]!, 0);
  };
  let f = objective(beta);
  let converged = false;
  const tol = 1e-13 * Math.max(1, Math.abs(target[0]!));
  for (let it = 0; it < 200; it++) {
    const g = target.map((t) => -t);
    const H = Array.from({ length: p }, () => new Array<number>(p).fill(0));
    for (const i of rows) {
      const x = X[i]!;
      const e = Math.exp(x.reduce((a, v, j) => a + v * beta[j]!, 0));
      for (let j = 0; j < p; j++) { g[j]! += e * x[j]!; for (let k = 0; k <= j; k++) H[j]![k]! += e * x[j]! * x[k]!; }
    }
    for (let j = 0; j < p; j++) for (let k = j + 1; k < p; k++) H[j]![k] = H[k]![j]!;
    const gmax = Math.max(...g.map(Math.abs));
    if (gmax <= tol) { converged = true; break; }
    const step = solve(H, g.map((v) => -v));
    if (step === null || step.some((v) => !Number.isFinite(v))) break;
    let t = 1, next = beta.map((b, j) => b + step[j]!), fn = objective(next);
    while (!(fn <= f) && t > 1e-10) { t /= 2; next = beta.map((b, j) => b + t * step[j]!); fn = objective(next); }
    if (!(fn <= f)) break;
    const moved = step.some((v, j) => Math.abs(t * v) > 1e-15 * Math.max(1, Math.abs(beta[j]!)));
    beta.splice(0, p, ...next); f = fn;
    if (!moved) { converged = gmax <= 1e-9 * Math.max(1, Math.abs(target[0]!)); break; }
  }
  return { eta: X.map((x) => x.reduce((a, v, j) => a + v * beta[j]!, 0)), converged };
}

interface LinkFns { p: (eta: number) => number; q: (eta: number) => number; d: (eta: number) => number }
const LINKS: Record<"logit" | "probit", LinkFns> = {
  logit: { p: (e) => plogis(e), q: (e) => plogis(-e), d: (e) => plogis(e) * plogis(-e) },
  probit: { p: (e) => pnorm(e), q: (e) => pnorm(-e), d: (e) => dnorm(e) },
};

/** The just-identified CBPS: beta with sum c_i x_i = 0, c_i the treated weight or minus the control weight */
function cbps(X: number[][], tr: number[], estimand: WeightitEstimand, link: LinkFns, start: number[]):
  { eta: number[]; converged: boolean } {
  const n = tr.length, p = start.length;
  let beta = start.slice();
  const parts = (b: number[]): { g: number[]; J: number[][] | null } => {
    const g = new Array<number>(p).fill(0);
    const J = Array.from({ length: p }, () => new Array<number>(p).fill(0));
    for (let i = 0; i < n; i++) {
      const x = X[i]!, eta = x.reduce((a, v, j) => a + v * b[j]!, 0);
      const P = link.p(eta), Q = link.q(eta), D = link.d(eta), t = tr[i]!;
      let c: number, dc: number;
      if (estimand === "ATE") { c = t ? 1 / P : -1 / Q; dc = t ? -D / (P * P) : -D / (Q * Q); }
      else if (estimand === "ATT") { c = t ? 1 : -P / Q; dc = t ? 0 : -D / (Q * Q); }
      else if (estimand === "ATC") { c = t ? Q / P : -1; dc = t ? -D / (P * P) : 0; }
      else { c = t ? Q : -P; dc = -D; }
      for (let j = 0; j < p; j++) { g[j]! += c * x[j]!; for (let k = 0; k < p; k++) J[j]![k]! += dc * x[j]! * x[k]!; }
    }
    return { g, J };
  };
  const norm = (g: number[]): number => g.reduce((a, v) => a + v * v, 0);
  let { g, J } = parts(beta);
  let f = norm(g), converged = false;
  const tol = 1e-12 * n;
  for (let it = 0; it < 200; it++) {
    if (Math.max(...g.map(Math.abs)) <= tol) { converged = true; break; }
    const step = solve(J!, g.map((v) => -v));
    if (step === null || step.some((v) => !Number.isFinite(v))) break;
    let t = 1, next = beta.map((b, j) => b + step[j]!), pn = parts(next), fn = norm(pn.g);
    while (!(fn < f) && t > 1e-10) { t /= 2; next = beta.map((b, j) => b + t * step[j]!); pn = parts(next); fn = norm(pn.g); }
    if (!(fn < f)) { converged = Math.max(...g.map(Math.abs)) <= 1e-8 * n; break; }
    beta = next; g = pn.g; J = pn.J; f = fn;
  }
  return { eta: X.map((x) => x.reduce((a, v, j) => a + v * beta[j]!, 0)), converged };
}

/** Weights of the estimand from the propensity score p (q = 1 - p, computed apart for accuracy) */
function psWeight(estimand: WeightitEstimand, t: number, p: number, q: number): number {
  switch (estimand) {
    case "ATE": return t ? 1 / p : 1 / q;
    case "ATT": return t ? 1 : p / q;
    case "ATC": return t ? q / p : 1;
    default: return t ? q : p;
  }
}

/** R's warnings when the estimation does not converge (WeightIt's wording, the lines of the cli message joined) */
const NOT_CONVERGED = {
  glm: "glm.fit: algorithm did not converge",
  cbps: "The covariate balancing conditions could not be solved, so the covariates will not be exactly balanced.",
  ipt: "The optimization failed to converge; consider using fewer covariates or a different link function.",
  ebal: "The estimated weights do not balance the covariates, indicating the optimization arrived at a degenerate " +
    "solution. Try decreasing the number of variables supplied to the optimization.",
} as const;

const METHOD_NAME = { cbps: "covariate balancing propensity score weighting", ipt: "inverse probability tilting",
  ebal: "entropy balancing" } as const;

/**
 * Balancing weights for a binary treatment. Equivalent to `WeightIt::weightit()` in R. The call followed is
 * `weightit(tr ~ covariates, data, method, link, estimand, stabilize)`.
 *
 * - `"glm"` (`"ps"`): the propensity score `p` of a binomial glm with the link, and the weights 1/p and 1/(1 − p)
 *   (ATE), 1 and p/(1 − p) (ATT), (1 − p)/p and 1 (ATC), 1 − p and p (ATO, the overlap weights).
 * - `"cbps"`: the just-identified covariate balancing propensity score: the score whose weights (the same formulas)
 *   make the weighted means of every covariate column equal in the two groups (ATT: the controls' to the treated's).
 * - `"ipt"`: inverse probability tilting, a logistic score per weighted group whose weights move the group's means to
 *   the target (ATE: the whole sample's). Not ATO.
 * - `"ebal"`: entropy balancing: the weights closest to uniform in entropy with the target means, summing to the
 *   target size. No propensity score; not ATO.
 *
 * cbps, ipt and ebal are solved exactly (Newton's method on the balance conditions); R stops its optimisers earlier, so
 * those weights agree with R's to about 1e-8 relative. A string covariate is a factor (levels in code-point order);
 * missing values are an error (R drops or imputes them depending on the method).
 * @category Causal inference
 * @example
 * ```ts
 * const tr = [1, 0, 1, 0, 0, 1, 0, 0, 1, 0];
 * const age = [52, 40, 61, 58, 33, 47, 50, 45, 39, 44];
 * const w = weightit(tr, { age }, { estimand: "ATE" });
 * w.weights[0]; // 1 / w.ps[0]
 * ```
 */
export function weightit(tr: readonly (number | boolean)[], covariates: Readonly<Record<string, CovariateColumn>>,
  options: WeightitOptions = {}): WeightitResult {
    checkOptions(options, WEIGHTIT_KEYS, "weightit"); // generated: option-keys.mjs
  const { method: given = "glm", estimand = "ATE", stabilize = false } = options;
  const method = given === "ps" ? "glm" : given;
  if (!["glm", "cbps", "ipt", "ebal"].includes(method)) throw new RangeError(`unknown method '${String(given)}'`);
  if (!["ATE", "ATT", "ATC", "ATO"].includes(estimand)) throw new RangeError(`unknown estimand '${String(estimand)}'`);
  const link = method === "ebal" ? null : options.link ?? "logit";
  const allowed: Record<string, readonly string[]> = { glm: ["logit", "probit", "cauchit", "cloglog"],
    cbps: ["logit", "probit"], ipt: ["logit"] };
  if (link !== null && !allowed[method]!.includes(link)) throw new RangeError(`link '${link}' is not available for method '${method}'`);
  if ((method === "ipt" || method === "ebal") && estimand === "ATO") {
    throw new RangeError(`"ATO" is not an allowable estimand for ${METHOD_NAME[method]} with a binary treatment. ` +
      `Only "ATE", "ATT", and "ATC" are allowed.`);
  }
  const warnings: string[] = [];
  if (stabilize && method === "glm" && estimand !== "ATE") throw new RangeError("`stabilize` can only be supplied when `estimand = \"ATE\"`.");
  if (stabilize && method !== "glm") warnings.push(`\`stabilize\` cannot be used with ${METHOD_NAME[method as "cbps"]} and will be ignored.`);
  const t = treatment(tr);
  const n = t.length;
  if (!t.includes(0) || !t.includes(1)) throw new RangeError("The treatment must have at least two unique values.");
  const { names, columns: raw } = covariateColumns(covariates, n);
  if (raw.length === 0) throw new RangeError("'covariates' must have at least one column");
  // each column rescaled exactly (by a power of 2, then less its first value): with the intercept the scores and
  // weights do not change, while a column like 1e15 + small differences keeps its digits and one near 1e-300 does not
  // underflow; constant and aliased columns are left out (R's fit drops them)
  const columns = independent(raw.map((c) => rescaled(c).values));
  const treated = t.flatMap((v, i) => (v ? [i] : [])), control = t.flatMap((v, i) => (v ? [] : [i]));
  const all = t.map((_, i) => i);
  const focal = estimand === "ATT" ? 1 : estimand === "ATC" ? 0 : null;
  let ps: number[] | null = null, weights: number[], converged = true;

  if (method === "glm") {
    const fit = unreported(() => glm(design(columns, n).map((r) => r.slice(1)), t, { family: "binomial", link: link! }));
    converged = fit.converged;
    ps = fit.fittedValues;
    // from the score as R does (1 - p, not a separately computed complement)
    weights = t.map((v, i) => psWeight(estimand, v, ps![i]!, 1 - ps![i]!));
    if (ps.some((p) => p <= 10 * EPS || p >= 1 - 10 * EPS)) {
      warnings.push("Propensity scores numerically equal to 0 or 1 were estimated, indicating perfect separation. These " +
        "may yield problems with inference. See `?method_glm` (`?WeightIt::method_glm()`) for details.");
    }
  } else if (method === "cbps") {
    const z = standardised(columns);
    const X = design(z, n);
    // start: the glm of the same link on the standardised columns
    const start = unreported(() => glm(X.map((r) => r.slice(1)), t, { family: "binomial", link: link! })).coefficients
      .map((b) => (Number.isFinite(b) ? b : 0));
    const fn = LINKS[link as "logit" | "probit"];
    const r = cbps(X, t, estimand, fn, start);
    converged = r.converged;
    // R keeps the scores within [eps, 1 - eps] (a score of 1e-19 is reported as 2.2e-16) and weighs by them
    const bounded = (x: number): number => Math.min(Math.max(x, EPS), 1 - EPS);
    ps = r.eta.map((e) => bounded(fn.p(e)));
    weights = t.map((v, i) => psWeight(estimand, v, ps![i]!, bounded(fn.q(r.eta[i]!))));
  } else {
    // a tilting of the controls towards the treated means (beta_C) and of the treated towards the controls' (beta_T):
    // with an intercept, the ATE conditions of each group are the same equations
    const z = standardised(columns);
    const X = design(z, n);
    const sums = (rows: readonly number[]): number[] => X[0]!.map((_, j) => rows.reduce((s, i) => s + X[i]![j]!, 0));
    const need = { C: estimand !== "ATC", T: estimand !== "ATT" };
    const target = method === "ebal" && estimand === "ATE" ? { C: sums(all), T: sums(all) }
      : { C: sums(treated), T: sums(control) };
    const C = need.C ? tilt(X, control, target.C) : null, T = need.T ? tilt(X, treated, target.T) : null;
    converged = (C?.converged ?? true) && (T?.converged ?? true);
    if (method === "ebal") {
      weights = t.map((v, i) => (v ? (T ? Math.exp(T.eta[i]!) : 1) : (C ? Math.exp(C.eta[i]!) : 1)));
    } else {
      // ipt: controls weigh 1 + exp(eta_C) (ATE) or exp(eta_C) (ATT); the treated 1 + exp(eta_T) or exp(eta_T) (ATC),
      // their scores plogis(eta_C) and plogis(-eta_T)
      const add = estimand === "ATE" ? 1 : 0;
      weights = t.map((v, i) => (v ? (T ? add + Math.exp(T.eta[i]!) : 1) : (C ? add + Math.exp(C.eta[i]!) : 1)));
      ps = t.map((v, i) => (estimand === "ATT" ? plogis(C!.eta[i]!) : estimand === "ATC" ? plogis(-T!.eta[i]!)
        : v ? plogis(-T!.eta[i]!) : plogis(C!.eta[i]!)));
    }
  }
  if (!converged) warnings.push(NOT_CONVERGED[method]);
  if (stabilize && method === "glm") {
    const share = [control.length / n, treated.length / n];
    weights = weights.map((w, i) => w * share[t[i]!]!);
  }
  if (weights.every((w) => Math.abs(w - 1) < Math.sqrt(EPS))) {
    warnings.push("All weights are 1, possibly indicating an estimation failure.");
  }
  return reported("weightit", {
    weights, ps, treat: t, estimand, method, link, stabilized: stabilize && method === "glm", focal, columnNames: names,
    converged, warnings,
  });
}

/** Options of {@link trimWeights}. Equivalent to the arguments of WeightIt's `trim()`.
 * @category Causal inference
 */
export interface TrimWeightsOptions {
  /** Below 1: the quantile (type 3) of the weights at which they are capped (0.99 caps the top 1%); 1 or more: the
   * number of largest weights set to the next largest. */
  at: number;
  /** Also raise the weights below the quantile 1 − `at` (or the `at` smallest) to it. Default false. */
  lower?: boolean;
  /** For a plain vector of weights: the treatment (only informative with a focal group, which a vector has not). */
  treat?: readonly (number | boolean)[];
}

/** The weights with the extremes of the units in `rows` capped as trim() does */
function trimmed(w: readonly number[], rows: readonly number[], at: number, lower: boolean): number[] {
  const out = w.slice();
  if (rows.length === 0) return out;
  const v = rows.map((i) => w[i]!);
  let hi: number, lo: number;
  if (at < 1) {
    hi = quantile(v, at, { type: 3 });
    lo = quantile(v, 1 - at, { type: 3 });
  } else {
    if (!Number.isInteger(at)) throw new RangeError("'at' must be below 1 or a whole number");
    const s = v.slice().sort((a, b) => a - b);
    const k = Math.min(at, s.length - 1);
    hi = s[s.length - 1 - k]!;
    lo = s[k]!;
  }
  for (const i of rows) {
    if (w[i]! > hi) out[i] = hi;
    if (lower && w[i]! < lo) out[i] = lo;
  }
  return out;
}

/**
 * Trims (winsorises) extreme weights: those above a quantile, and with `lower` those below the opposite one, are set to
 * it. Equivalent to `WeightIt::trim()` in R. The call followed is `trim(w, at, lower = TRUE)` for a weightit result or a
 * vector of weights.
 *
 * The quantile is R's type 3 of the weights that are not fixed by the estimand: all units for ATE and ATO, the controls
 * for ATT, the treated for ATC. The other weights do not change (no renormalisation). For a weightit result the
 * returned object is a copy with the trimmed weights.
 * @category Causal inference
 */
export function trimWeights(w: WeightitResult, options: TrimWeightsOptions): WeightitResult;
export function trimWeights(w: readonly number[], options: TrimWeightsOptions): number[];
export function trimWeights(w: WeightitResult | readonly number[], options: TrimWeightsOptions): WeightitResult | number[] {
    checkOptions(options, TRIM_WEIGHTS_KEYS, "trimWeights"); // generated: option-keys.mjs
  const { at, lower = false } = options;
  if (!(at > 0) || !Number.isFinite(at)) throw new RangeError("'at' must be a positive number");
  if (Array.isArray(w) || ArrayBuffer.isView(w)) {
    const v = Array.from(w as readonly number[]);
    if (options.treat !== undefined && options.treat.length !== v.length) throw new RangeError("'treat' must have the length of 'w'");
    return trimmed(v, v.map((_, i) => i), at, lower);
  }
  const fit = w as WeightitResult;
  const rows = fit.treat.flatMap((t, i) => (fit.focal === null || t !== fit.focal ? [i] : []));
  return { ...fit, weights: trimmed(fit.weights, rows, at, lower), warnings: fit.warnings.slice() };
}

/** One group's part of {@link weightSummary}.
 * @category Causal inference
 */
export interface WeightSummaryGroup {
  /** Smallest and largest weight. */
  range: [number, number];
  /** The (up to) 5 largest weights in increasing order, and their units (1-based); among equal weights the earliest
   * units, as R lists them. */
  top: { index: number[]; weights: number[] };
  /** Mean weight (R prints it for stabilised weights only). */
  mean: number;
  /** Coefficient of variation: SD (divisor n − 1) / mean. */
  coefOfVar: number;
  /** Mean absolute deviation of w / mean(w) from 1. */
  scaledMad: number;
  /** Mean of r log r, r = w / mean(w). */
  negativeEntropy: number;
  /** Number of zero weights (below 1e-10, as R counts them). */
  numZeros: number;
  /** Number of units. */
  n: number;
  /** Kish's effective sample size (sum w)² / sum w². */
  ess: number;
}

/** Result of {@link weightSummary}.
 * @category Causal inference
 */
export interface WeightSummaryResult {
  /** The treated group's summary. */
  treated: WeightSummaryGroup;
  /** The control group's summary. */
  control: WeightSummaryGroup;
  /** Whether the weights were stabilised (R shows the mean weights then). */
  stabilized: boolean;
}

function groupSummary(w: readonly number[], index: readonly number[]): WeightSummaryGroup {
  const v = index.map((i) => w[i]!);
  const n = v.length;
  let sum = 0, sum2 = 0;
  for (const x of v) { sum += x; sum2 += x * x; }
  const mean = sum / n;
  const ss = v.reduce((a, x) => a + (x - mean) * (x - mean), 0);
  const r = v.map((x) => x / mean);
  const order = v.map((_, k) => k).sort((a, b) => v[b]! - v[a]! || a - b).slice(0, 5).reverse();
  return {
    range: [Math.min(...v), Math.max(...v)],
    top: { index: order.map((k) => index[k]! + 1), weights: order.map((k) => v[k]!) },
    mean, coefOfVar: Math.sqrt(ss / (n - 1)) / mean, scaledMad: r.reduce((a, x) => a + Math.abs(x - 1), 0) / n,
    negativeEntropy: r.reduce((a, x) => a + (x > 0 ? x * Math.log(x) : 0), 0) / n,
    // R counts the weights below about 1e-10 as zeros (weightit.json: 7.9e-11 counted, 1.7e-10 not)
    numZeros: v.filter((x) => Math.abs(x) < 1e-10).length, n, ess: (sum * sum) / sum2,
  };
}

/**
 * Summary of balancing weights by group: range, largest weights, coefficient of variation, scaled MAD, negative
 * entropy, zeros and Kish's effective sample size. Equivalent to `summary()` of a weightit object in R.
 * @category Causal inference
 */
export function weightSummary(w: WeightitResult): WeightSummaryResult {
  const treated = w.treat.flatMap((t, i) => (t ? [i] : [])), control = w.treat.flatMap((t, i) => (t ? [] : [i]));
  return { treated: groupSummary(w.weights, treated), control: groupSummary(w.weights, control), stabilized: w.stabilized };
}
