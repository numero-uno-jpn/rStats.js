// Moderation: simple slopes and the Johnson-Neyman interval (interactions' sim_slopes and johnson_neyman) for lm and
// binomial glm models with a two-way interaction. The behaviour is in oracle/mediation-behaviour.md, from the package's
// documentation and published output (experiments/mediation116-slopes.R; every attempt in
// experiments/mediation116-log.md); Bauer & Curran (2005) for the interval. Written for rStats.js (no ported code).
//
// - The slope of the predictor at a moderator value w is b_X + b_XW w, its variance V_XX + 2 w V_XW + w^2 V_WW
// - Intervals and p-values use t on the residual degrees of freedom for lm and the normal distribution for glm; the
//   Johnson-Neyman bounds use t on the residual degrees of freedom for both (as interactions does)
// - robust "HC3": sandwich's vcovHC with type HC3

