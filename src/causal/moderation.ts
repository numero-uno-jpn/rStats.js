interface Parts {
  b1: number;
  b3: number;
  v11: number;
  v13: number;
  v33: number;
  df: number;
  isGlm: boolean;
  w: number[];
}

/** The coefficients and covariances of the predictor and the interaction, and the moderator's values on the model's rows */
function parts(fit: ModerationModel, data: DataFrame, pred: string, modx: string, robust: false | "HC3"): Parts {
  if (typeof pred !== "string" || typeof modx !== "string") throw new TypeError("'pred' and 'modx' are required");
  if (robust !== false && robust !== "HC3") throw new RangeError("robust must be false or \"HC3\"");
  const isGlm = "family" in fit;
  const names = isGlm ? (fit as GlmFormulaResult).model.columnNames : (fit as LmFormulaResult).coefNames;
  if (names === undefined) throw new TypeError("the model must be a formula fit of lm or glm");
  if (isGlm && (fit as GlmFormulaResult).family !== "binomial" && (fit as GlmFormulaResult).family !== "gaussian")
    throw new RangeError("the model's family is not supported (binomial or gaussian)");
  const inter = [`${pred}:${modx}`, `${modx}:${pred}`].find((k) => names.includes(k));
  if (!names.includes(pred) || inter === undefined) throw new RangeError(`the model has no coefficients '${pred}' and '${pred}:${modx}'`);
  const cov = robust === "HC3" ? vcovHC(fit, { type: "HC3" }) : modelCovariance(fit);
  const i1 = cov.names.indexOf(pred), i3 = cov.names.indexOf(inter);
  if (i1 < 0 || i3 < 0) throw new RangeError("the predictor's or the interaction's coefficient is aliased");
  const c = fit.coefficients;
  const rows = isGlm ? (fit as GlmFormulaResult).model.rows : (fit as LmFormulaResult).rows;
  const col = data[modx];
  if (col === undefined) throw new RangeError(`object '${modx}' not found`);
  const w = rows.map((r) => Number(col[r]));
  if (w.some((v) => !Number.isFinite(v))) throw new RangeError(`'${modx}' must be numeric`);
  return {
    b1: c[names.indexOf(pred)]!, b3: c[names.indexOf(inter)]!, v11: cov.vcov[i1]![i1]!, v13: cov.vcov[i1]![i3]!,
    v33: cov.vcov[i3]![i3]!, df: fit.dfResidual, isGlm: isGlm && (fit as GlmFormulaResult).family === "binomial", w,
  };
}

function jn(q: Parts, alpha: number): JohnsonNeymanResult {
  if (!(alpha > 0 && alpha < 1)) throw new RangeError("alpha must be in (0, 1)");
  const crit = qt(1 - alpha / 2, q.df) as number;
  const c2 = crit * crit;
  const A = q.b3 * q.b3 - c2 * q.v33, B = 2 * (q.b1 * q.b3 - c2 * q.v13), C = q.b1 * q.b1 - c2 * q.v11;
  const disc = B * B - 4 * A * C;
  const lo = Math.min(...q.w), hi = Math.max(...q.w);
  const modrange: [number, number] = [lo, hi];
  let bounds: [number, number], failed = false;
  if (!(disc >= 0)) { bounds = [-Infinity, Infinity]; failed = true; }
  else {
    const s = Math.sqrt(disc);
    // the root without cancellation, then the other from the product of the roots
    const r1 = (-B - Math.sign(B || 1) * s) / (2 * A);
    const r2 = r1 === 0 ? (-B + Math.sign(B || 1) * s) / (2 * A) : C / (A * r1);
    bounds = r1 <= r2 ? [r1, r2] : [r2, r1];
  }
  // interactions reports inside = FALSE when the interval could not be found
  const inside = !failed && A < 0;
  const allSig = !(bounds[0] > lo && bounds[0] < hi) && !(bounds[1] > lo && bounds[1] < hi);
  return { bounds, inside, failed, allSig, modrange, alpha };
}

/**
 * The Johnson-Neyman interval: the moderator values at which the predictor's slope stops being significant.
 * Equivalent to R's `interactions::johnson_neyman()` (the bounds, `inside`, `failed` and `all_sig`; no plot).
 *
 * The bounds solve (b_X + b_XW w)² = t² Var(b_X + b_XW w), with the t quantile on the model's residual degrees of
 * freedom (for a glm too, as interactions does). The slope is significant inside the bounds when the quadratic's
 * leading coefficient is negative, else outside them.
 *
 * @param fit A formula fit of {@link lm} or {@link glm} with the interaction `pred:modx`.
 * @param data The data it was fitted on (for the moderator's observed range).
 * @param options See {@link JohnsonNeymanOptions}.
 * @returns See {@link JohnsonNeymanResult}.
 * @throws RangeError if the model lacks the coefficients or the moderator is not numeric.
 *
 * @example
 * ```ts
 * const fit = lm("Y ~ X * W", data);
 * johnsonNeyman(fit, data, { pred: "X", modx: "W" }).bounds;
 * ```
 *
 * @category Causal inference
 */
export function johnsonNeyman(fit: ModerationModel, data: DataFrame, options: JohnsonNeymanOptions): JohnsonNeymanResult {
  checkOptions(options, JOHNSON_NEYMAN_KEYS, "johnsonNeyman"); // generated: option-keys.mjs
  return jn(parts(fit, data, options.pred, options.modx, options.robust ?? false), options.alpha ?? 0.05);
}

/**
 * Simple slopes of a predictor at values of a moderator, with the Johnson-Neyman interval. Equivalent to R's
 * `interactions::sim_slopes()` (with `confint = TRUE`; the slopes table and the Johnson-Neyman results).
 *
 * The slope at w is b_X + b_XW w with standard error sqrt(V_XX + 2 w V_XW + w² V_WW), from the model's covariance or
 * its HC3 sandwich; intervals and p-values use t on the residual degrees of freedom for lm and the normal distribution
 * for glm. `"mean-plus-minus"` takes the moderator's mean and mean ± SD on the model's rows.
 *
 * @param fit A formula fit of {@link lm} or {@link glm} (binomial or gaussian) with the interaction `pred:modx`.
 * @param data The data it was fitted on.
 * @param options See {@link SimSlopesOptions}.
 * @returns See {@link SimSlopesResult}.
 * @throws RangeError if the model lacks the coefficients, the moderator is not numeric or the levels are outside (0, 1).
 *
 * @example
 * ```ts
 * const fit = lm("Y ~ X * W + C", data);
 * const s = simSlopes(fit, data, { pred: "X", modx: "W" });
 * s.estimate; s.p; s.jn?.bounds;
 * ```
 *
 * @category Causal inference
 */
export function simSlopes(fit: ModerationModel, data: DataFrame, options: SimSlopesOptions): SimSlopesResult {
  checkOptions(options, SIM_SLOPES_KEYS, "simSlopes"); // generated: option-keys.mjs
  const q = parts(fit, data, options.pred, options.modx, options.robust ?? false);
  const width = options.ciWidth ?? 0.95;
  if (!(width > 0 && width < 1)) throw new RangeError("ciWidth must be in (0, 1)");
  const mv = options.modxValues ?? "mean-plus-minus";
  let values: number[];
  if (mv === "mean-plus-minus") {
    const m = meanDD(q.w), s = Math.sqrt(variance(q.w));
    values = [m - s, m, m + s];
  } else if (Array.isArray(mv) && mv.every((v) => Number.isFinite(v))) values = [...mv];
  else throw new RangeError("modxValues must be \"mean-plus-minus\" or finite numbers");
  const crit = q.isGlm ? (qnorm((1 + width) / 2) as number) : (qt((1 + width) / 2, q.df) as number);
  const estimate = values.map((w) => q.b1 + q.b3 * w);
  const se = values.map((w) => Math.sqrt(q.v11 + 2 * w * q.v13 + w * w * q.v33));
  const statistic = estimate.map((e, i) => e / se[i]!);
  const p = statistic.map((t) => 2 * (q.isGlm ? (pnorm(-Math.abs(t)) as number) : (pt(-Math.abs(t), q.df) as number)));
  const out: SimSlopesResult = {
    values, estimate, se, lower: estimate.map((e, i) => e - crit * se[i]!), upper: estimate.map((e, i) => e + crit * se[i]!),
    statistic, statisticName: q.isGlm ? "z" : "t", p,
  };
  if (options.johnsonNeyman ?? true) out.jn = jn(q, options.jnAlpha ?? 0.05);
  return out;
}
