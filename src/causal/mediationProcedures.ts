// ReactiveStat's mediation procedures outside R's functions (scripts/多変量/媒介分析.php and 調整媒介分析.php): the
// Sobel test, the Monte Carlo method on the coefficients, and moderated mediation with the index of moderated mediation
// (Hayes 2015). The behaviour is in oracle/mediation-behaviour.md. Written for rStats.js (no ported code).
//
// - Sobel: a b / sqrt(b² sa² + a² sb²) against the normal distribution
// - Monte Carlo (mediation): a ~ rnorm(nmc, a, sa), then (b, c') ~ mvrnorm(nmc, ...) of the outcome model (2 dimensions:
//   R's values under the same setSeed)
// - Moderated mediation: with linear models, mvrnorm of all the coefficients of both models (3 or more dimensions: R's
//   distribution, not R's values, see src/random/mvrnorm.ts); otherwise mediate at the moderator's low and high values
//   on the same random stream

