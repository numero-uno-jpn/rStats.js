// Plot data for survival curves and ROC curves (1.21.0): what R's plot.survfit (survival), plot.cuminc (cmprsk) and
// plot.roc (pROC) draw, from the fits rStats.js returns. Written for rStats.js from the documented behaviour of those
// plots: a survival curve is a step function that starts at time 0 with survival 1 and marks the censoring times
// (?plot.survfit's mark.time), fun = "event" plots 1 - S, "cloglog" log(-log S) against log time.
import type { SurvfitResult } from "../models/survival.js";
import type { CumincResult } from "../models/competingRisks.js";
import type { RocResult } from "../htest/roc.js";
import { pretty } from "../descriptive/hist.js";
// Generated by `node scripts/option-keys.mjs --write` from the option types; do not edit (begin)
import { checkOptions } from "../internal/checkOptions.js";
const SURV_PLOT_DATA_KEYS = ["fun", "riskTimes"] as const;
// Generated by `node scripts/option-keys.mjs --write` (end)

/**
 * Options for {@link survPlotData}.
 *
 * @category Plot data
 */
export interface SurvPlotDataOptions {
  /**
   * What to plot: `"surv"` (default) the survival S(t); `"event"` the cumulative incidence 1 - S(t); `"cumhaz"` the
   * fit's cumulative hazard (no band); `"cloglog"` log(-log S(t)) against log t (as R's `fun`).
   */
  fun?: "surv" | "event" | "cumhaz" | "cloglog";
  /** Times of the risk table. Default: R's `pretty()` of 0 and the last time. */
  riskTimes?: readonly number[];
}

/**
 * The rows of a survival curve: one per change point of the step function (draw them as steps after each point:
 * Observable Plot's `curve: "step-after"`, Plotly's `line.shape: "hv"`).
 *
 * @category Plot data
 */
export interface SurvStepRow {
  [key: string]: number | string;
  /** The time. */
  x: number;
  /** The curve's value from this time on. */
  y: number;
  /** The lower and upper confidence limits (NaN where there are none). */
  ymin: number;
  ymax: number;
  /** The stratum's label. */
  group: string;
}

/**
 * Plot data for Kaplan-Meier (or other) survival curves from {@link survfit} or {@link survfitCoxph}: the steps with
 * their confidence band, the censoring marks and a risk table. Each stratum starts at time 0 (or its first time if
 * that is negative) with S = 1, as R's `plot.survfit`.
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layers: `steps` (`x`, `y`, `ymin`, `ymax`, `group`); `censor` (`x`, `y`, `group`, `n`: the number censored);
 * `riskTable` (`x`, `group`, `nRisk`).
 *
 * @example
 * ```ts
 * const fit = survfit([5, 8, 12, 12, 20], [1, 0, 1, 1, 0]);
 * const { layers } = survPlotData(fit);
 * layers.steps[0]; // { x: 0, y: 1, ymin: 1, ymax: 1, group: "all" }
 * ```
 *
 * @category Plot data
 */
export function survPlotData(
  fit: SurvfitResult,
  options: SurvPlotDataOptions = {},
) {
  checkOptions(options, SURV_PLOT_DATA_KEYS, "survPlotData"); // generated: option-keys.mjs
  const fun = options.fun ?? "surv";
  if (!["surv", "event", "cumhaz", "cloglog"].includes(fun)) throw new RangeError(`unknown 'fun': ${fun}`);
  const groups = [...new Set(fit.strata)];
  const steps: SurvStepRow[] = [], censor: Record<string, number | string>[] = [], risk: Record<string, number | string>[] = [];
  const tr = (s: number): number =>
    fun === "event" ? 1 - s : fun === "cloglog" ? Math.log(-Math.log(s)) : fun === "cumhaz" ? -Math.log(s) : s;
  const lastTime = Math.max(0, ...fit.time.filter(Number.isFinite));
  const riskTimes = options.riskTimes ?? pretty([0, lastTime]).filter((t) => t <= lastTime);
  for (const g of groups) {
    const rows = fit.strata.flatMap((s, i) => (s === g ? [i] : []));
    const value = (i: number): number => (fun === "cumhaz" ? fit.cumhaz[i]! : tr(fit.surv[i]!));
    // the band in the transformed scale: 1 - S reverses the limits; the cumulative hazard has none (as R's fun is
    // applied to the limits, cloglog keeps their order reversed too)
    const band = (i: number): [number, number] => {
      if (fun === "cumhaz") return [NaN, NaN];
      const a = tr(fit.lower[i]!), b = tr(fit.upper[i]!);
      return a <= b ? [a, b] : [b, a];
    };
    if (fun !== "cloglog") {
      const t0 = Math.min(0, fit.time[rows[0]!]!);
      const y0 = fun === "surv" ? 1 : 0;
      steps.push({ x: t0, y: y0, ymin: y0, ymax: y0, group: g });
    }
    for (const i of rows) {
      const t = fit.time[i]!;
      const x = fun === "cloglog" ? Math.log(t) : t;
      const [ymin, ymax] = band(i);
      steps.push({ x, y: value(i), ymin, ymax, group: g });
      if (fit.nCensor[i]! > 0) censor.push({ x, y: value(i), group: g, n: fit.nCensor[i]! });
    }
    for (const t of riskTimes) {
      const at = rows.find((i) => fit.time[i]! >= t);
      // the number at risk just before t: that of the first time at or after t; none after the last time
      risk.push({ x: t, group: g, nRisk: at === undefined ? 0 : fit.nRisk[at]! });
    }
  }
  const yLabel = { surv: "Survival probability", event: "Cumulative incidence", cumhaz: "Cumulative hazard", cloglog: "log(-log(S))" }[fun];
  return {
    layers: { steps, censor, riskTable: risk },
    meta: { xLabel: fun === "cloglog" ? "log(time)" : "Time", yLabel, groups },
  };
}

/**
 * Plot data for cumulative incidence curves of competing risks from {@link cuminc}: one step function per group and
 * cause (as `plot.cuminc` of cmprsk), with the pointwise standard error.
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layer `steps`: `x` (time), `y` (the estimate), `se` (the square root of its variance), `group` (the curve's name),
 * `cause`, `stratum`.
 *
 * @example
 * ```ts
 * cumincPlotData(cuminc([1, 2, 3, 4], [1, 2, 1, 0])).layers.steps;
 * ```
 *
 * @category Plot data
 */
export function cumincPlotData(fit: CumincResult) {
  const steps = fit.curves.flatMap((c) =>
    c.time.map((t, i) => ({ x: t, y: c.est[i]!, se: Math.sqrt(c.var[i]!), group: c.name, cause: c.cause, stratum: c.group })),
  );
  return { layers: { steps }, meta: { xLabel: "Time", yLabel: "Cumulative incidence" } };
}

/**
 * Plot data for an ROC curve from {@link roc}: the curve with false positive rate (1 - specificity) and sensitivity,
 * ordered for drawing as a line from (0, 0) to (1, 1), the chance diagonal, and the point of the largest Youden index
 * (sensitivity + specificity - 1; the first such point).
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layers: `curve` (`x` = 1 - specificity, `y` = sensitivity, `specificity`, `threshold`); `diagonal`; `best`.
 * `meta.auc` is the area under the curve.
 *
 * @example
 * ```ts
 * const r = roc([0, 0, 1, 1, 0, 1], [0.1, 0.4, 0.35, 0.8, 0.2, 0.9]);
 * rocPlotData(r).meta.auc; // r.auc
 * ```
 *
 * @category Plot data
 */
export function rocPlotData(fit: RocResult) {
  const curve = fit.thresholds.map((th, i) => ({
    x: 1 - fit.specificities[i]!, y: fit.sensitivities[i]!, specificity: fit.specificities[i]!, threshold: th,
  }));
  curve.sort((a, b) => a.x - b.x || a.y - b.y);
  let best = curve[0];
  for (const r of curve) if (best === undefined || r.y - r.x > best.y - best.x) best = r;
  return {
    layers: {
      curve,
      diagonal: [{ x: 0, y: 0 }, { x: 1, y: 1 }],
      best: best === undefined ? [] : [{ ...best, youden: best.y - best.x }],
    },
    meta: { xLabel: "1 - Specificity", yLabel: "Sensitivity", auc: fit.auc, direction: fit.direction },
  };
}
