// Plot data for meta-analyses (1.21.0): forest and funnel plots of meta's results (metagen, metabin, metacont, ...) and
// of metafor's rma, and the network graph of netmeta. Written for rStats.js from the documented content of those
// plots (meta's forest and funnel, metafor's forest.rma and funnel.rma, netmeta's netgraph): the study estimates with
// intervals estimate +- z_{(1 + level) / 2} se, the weights in percent, the pooled estimates as diamonds, the pseudo
// confidence region estimate +- z se of a funnel plot.
import { qnorm } from "../distributions/normal.js";
import type { MetaResult } from "../meta/metagen.js";
import type { RmaResult } from "../models/metaAnalysis.js";
import { levelCheck } from "./types.js";
// Generated by `node scripts/option-keys.mjs --write` from the option types; do not edit (begin)
import { checkOptions } from "../internal/checkOptions.js";
const FOREST_PLOT_DATA_KEYS = ["labels", "level", "transform", "common", "random", "prediction"] as const;
const FUNNEL_PLOT_DATA_KEYS = ["level", "reference", "contours", "contourCentre", "n"] as const;
// Generated by `node scripts/option-keys.mjs --write` (end)

/**
 * Options for {@link forestPlotData}.
 *
 * @category Plot data
 */
export interface ForestPlotDataOptions {
  /** The study labels. Default `"Study 1"`, `"Study 2"`, ... */
  labels?: readonly string[];
  /** The level of the study intervals. Default `0.95` (the pooled intervals are the fit's). */
  level?: number;
  /** A transformation of the estimates and limits, such as `Math.exp` for log odds ratios. Default none. */
  transform?: (x: number) => number;
  /** Show the common effect estimate (meta's results only). Default `true`. */
  common?: boolean;
  /** Show the random effects estimate (meta's results only). Default `true`. */
  random?: boolean;
  /** Show the prediction interval (meta's results only). Default `false`. */
  prediction?: boolean;
}

const z = (level: number): number => qnorm((1 + levelCheck(level)) / 2);
const isRma = (fit: MetaResult | RmaResult): fit is RmaResult => "yi" in fit && "vi" in fit;
const scalar = (v: number | number[]): number => (Array.isArray(v) ? v[0]! : v);

/** The diamond of a pooled estimate as a closed polygon around row y */
function diamond(label: string, y: number, est: number, lo: number, hi: number, half = 0.35) {
  return [
    { x: lo, y, group: label }, { x: est, y: y + half, group: label }, { x: hi, y, group: label },
    { x: est, y: y - half, group: label }, { x: lo, y, group: label },
  ];
}

/**
 * Plot data for a forest plot of a meta-analysis from {@link metagen} (and the other meta functions that return a
 * {@link MetaResult}) or of an intercept-only {@link rma} fit: one row per study (from the top: `y` = k, k - 1, ...,
 * 1), then the pooled estimates below 0.
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layers: `studies` (`label`, `y`, `estimate`, `lower`, `upper`, `se`, `weight` in percent: the random effects
 * weights when the random effects estimate is shown, else the common effect ones; for rma 1 / (vi + tau2));
 * `pooled` (`label`, `y`, `estimate`, `lower`, `upper`, `type`: "common", "random", "prediction"); `diamonds`
 * (closed polygons `x`, `y`, `group`, one per pooled estimate). `meta` carries tau2, I2, Q and its p-value.
 *
 * @example
 * ```ts
 * const m = metagen([0.2, 0.5, -0.1], [0.1, 0.2, 0.15]);
 * forestPlotData(m, { labels: ["A", "B", "C"] }).layers.studies[0].label; // "A"
 * ```
 *
 * @throws RangeError for a meta-regression (rma with moderators) or a label count that differs from the studies.
 * @category Plot data
 */
export function forestPlotData(
  fit: MetaResult | RmaResult,
  options: ForestPlotDataOptions = {},
) {
  checkOptions(options, FOREST_PLOT_DATA_KEYS, "forestPlotData"); // generated: option-keys.mjs
  const zq = z(options.level ?? 0.95);
  const tf = options.transform ?? ((x: number) => x);
  const rma = isRma(fit);
  const te = rma ? fit.yi : fit.TE;
  const se = rma ? fit.vi.map(Math.sqrt) : fit.seTE;
  const k = te.length;
  const labels = options.labels ?? te.map((_, i) => `Study ${i + 1}`);
  if (labels.length !== k) throw new RangeError("'labels' must have one label per study");
  const showCommon = !rma && (options.common ?? true);
  const showRandom = !rma && (options.random ?? true);
  let w: number[];
  if (rma) {
    if (fit.p !== 1 || !fit.intercept) throw new RangeError("forestPlotData: a meta-regression has no single pooled estimate");
    w = fit.vi.map((v) => 1 / (v + fit.tau2));
  } else w = showRandom ? fit["w.random"] : fit["w.common"];
  const wsum = w.reduce((s, v) => s + v, 0);
  const studies = te.map((t, i) => {
    const [a, b] = [tf(t - zq * se[i]!), tf(t + zq * se[i]!)];
    return { label: labels[i]!, y: k - i, estimate: tf(t), lower: Math.min(a, b), upper: Math.max(a, b), se: se[i]!, weight: (100 * w[i]!) / wsum };
  });
  const pooled: { label: string; y: number; estimate: number; lower: number; upper: number; type: string }[] = [];
  const add = (label: string, type: string, est: number, lo: number, hi: number) => {
    const [a, b] = [tf(lo), tf(hi)];
    pooled.push({ label, y: -pooled.length - 1, estimate: tf(est), lower: Math.min(a, b), upper: Math.max(a, b), type });
  };
  if (rma) add("RE Model", "random", fit.beta.rows[0]![0]!, scalar(fit["ci.lb"]), scalar(fit["ci.ub"]));
  else {
    if (showCommon) add("Common effect model", "common", fit["TE.common"], fit["lower.common"], fit["upper.common"]);
    if (showRandom) add("Random effects model", "random", fit["TE.random"], fit["lower.random"], fit["upper.random"]);
    if (options.prediction ?? false) add("Prediction interval", "prediction", fit["TE.random"], fit["lower.predict"], fit["upper.predict"]);
  }
  const diamonds = pooled.filter((p) => p.type !== "prediction").flatMap((p) => diamond(p.label, p.y, p.estimate, p.lower, p.upper));
  const meta = rma
    ? { tau2: fit.tau2, I2: fit.I2, Q: fit.QE, pvalQ: fit.QEp, xLabel: "Estimate" }
    : { tau2: fit.tau2, I2: fit.I2, Q: fit.Q, pvalQ: fit["pval.Q"], xLabel: "Estimate" };
  return { layers: { studies, pooled, diamonds }, meta };
}

/**
 * Options for {@link funnelPlotData}.
 *
 * @category Plot data
 */
export interface FunnelPlotDataOptions {
  /** The level of the pseudo confidence region. Default `0.95`. */
  level?: number;
  /** The centre of the region: `"common"` (default, as meta's funnel), `"random"`, or a number. */
  reference?: "common" | "random" | number;
  /**
   * Levels of a contour-enhanced funnel plot (Peters et al. 2008), around `contourCentre`, such as `[0.9, 0.95,
   * 0.99]`. Default none.
   */
  contours?: readonly number[];
  /** The centre of the contours (the null effect). Default `0`. */
  contourCentre?: number;
  /** The number of standard errors of the region's outline. Default `50`. */
  n?: number;
}

/**
 * Plot data for a funnel plot from a {@link MetaResult} or an {@link rma} fit: the studies' estimates against their
 * standard errors (plot the y axis reversed, 0 at the top), the reference line and the pseudo confidence region
 * reference +- z se for se from 0 to the largest standard error.
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layers: `studies` (`x` = estimate, `y` = standard error); `region` (`y`, `xmin`, `xmax`); `reference` (two points
 * of the vertical line); `contours` (`level`, `y`, `xmin`, `xmax`).
 *
 * @example
 * ```ts
 * funnelPlotData(metagen([0.2, 0.5, -0.1, 0.3], [0.1, 0.2, 0.15, 0.3])).layers.region.length; // 50
 * ```
 *
 * @category Plot data
 */
export function funnelPlotData(
  fit: MetaResult | RmaResult,
  options: FunnelPlotDataOptions = {},
) {
  checkOptions(options, FUNNEL_PLOT_DATA_KEYS, "funnelPlotData"); // generated: option-keys.mjs
  const zq = z(options.level ?? 0.95);
  const rma = isRma(fit);
  const te = rma ? fit.yi : fit.TE;
  const se = rma ? fit.vi.map(Math.sqrt) : fit.seTE;
  const refOpt = options.reference ?? "common";
  let ref: number;
  if (typeof refOpt === "number") ref = refOpt;
  else if (rma) ref = fit.beta.rows[0]![0]!;
  else ref = refOpt === "random" ? fit["TE.random"] : fit["TE.common"];
  const n = options.n ?? 50;
  if (!(Number.isInteger(n) && n >= 2)) throw new RangeError("'n' must be an integer of at least 2");
  const maxSe = Math.max(...se.filter(Number.isFinite));
  const grid = Array.from({ length: n }, (_, i) => (maxSe * i) / (n - 1));
  const region = grid.map((s) => ({ y: s, xmin: ref - zq * s, xmax: ref + zq * s }));
  const centre = options.contourCentre ?? 0;
  const contours = (options.contours ?? []).flatMap((lv) => {
    const zc = z(lv);
    return grid.map((s) => ({ level: lv, y: s, xmin: centre - zc * s, xmax: centre + zc * s }));
  });
  return {
    layers: {
      studies: te.map((t, i) => ({ x: t, y: se[i]! })),
      region,
      reference: [{ x: ref, y: 0 }, { x: ref, y: maxSe }],
      contours,
    },
    meta: { xLabel: "Estimate", yLabel: "Standard error", reference: ref },
  };
}

/**
 * The comparisons netgraph needs from a {@link netmeta} fit.
 *
 * @category Plot data
 */
export interface NetgraphInput {
  trts: readonly string[];
  studlab: readonly string[];
  treat1: readonly string[];
  treat2: readonly string[];
}

/**
 * Plot data for the network graph of a network meta-analysis from {@link netmeta}: the treatments on a circle (in
 * the fit's order, starting at the top and going clockwise, netgraph's default circle layout) and one edge per pair of
 * treatments compared directly, with the number of studies that compare them (netgraph's default line width).
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layers: `nodes` (`label`, `x`, `y`); `edges` (`from`, `to`, `x1`, `y1`, `x2`, `y2`, `studies`).
 *
 * @example
 * ```ts
 * const fit = netmeta([0.3, 0.5, 0.2, 0.4], [0.1, 0.2, 0.15, 0.2], ["A", "A", "B", "A"], ["B", "C", "C", "B"],
 *   ["s1", "s2", "s3", "s4"]);
 * netgraphData(fit).layers.edges.map((e) => e.studies); // [2, 1, 1]
 * ```
 *
 * @category Plot data
 */
export function netgraphData(fit: NetgraphInput) {
  const k = fit.trts.length;
  const pos = new Map(fit.trts.map((t, i) => {
    const a = Math.PI / 2 - (2 * Math.PI * i) / k;
    return [t, { x: Math.cos(a), y: Math.sin(a) }] as const;
  }));
  const pairs = new Map<string, { from: string; to: string; studies: Set<string> }>();
  fit.treat1.forEach((a, i) => {
    const b = fit.treat2[i]!;
    const [from, to] = fit.trts.indexOf(a) <= fit.trts.indexOf(b) ? [a, b] : [b, a];
    const key = `${from}\u0000${to}`;
    const e = pairs.get(key) ?? { from, to, studies: new Set<string>() };
    e.studies.add(fit.studlab[i]!);
    pairs.set(key, e);
  });
  const edges = [...pairs.values()].map((e) => {
    const p = pos.get(e.from)!, q = pos.get(e.to)!;
    return { from: e.from, to: e.to, x1: p.x, y1: p.y, x2: q.x, y2: q.y, studies: e.studies.size };
  });
  return {
    layers: { nodes: fit.trts.map((t) => ({ label: t, ...pos.get(t)! })), edges },
    meta: { treatments: k },
  };
}
