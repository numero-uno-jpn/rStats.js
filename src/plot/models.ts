export interface ForecastPlotDataOptions {
  /** The time of the first observation. Default `1`. */
  start?: number;
  /** Observations per unit of time (12 for monthly data with yearly time). Default `1`. */
  frequency?: number;
}

/**
 * Plot data for a forecast fan, as forecast's `plot.forecast`: the observed series, the point forecasts and their
 * prediction intervals (one band per level, widest first), from a forecast of rStats.js ({@link forecast},
 * {@link forecastArima}, {@link forecastEts}, ...).
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layers: `history` (`x` = time, `y`); `mean` (`x`, `y`); `intervals` (`x`, `level`, `lower`, `upper`).
 *
 * @example
 * ```ts
 * const y = [1, 3, 2, 5, 4, 6, 5, 8, 7, 9];
 * const d = forecastPlotData(y, forecast(arima(y, { order: [1, 0, 0] }), { h: 3 }), { start: 2000 });
 * d.layers.mean.map((r) => r.x); // [2010, 2011, 2012]
 * ```
 *
 * @category Plot data
 */
export function forecastPlotData(
  history: Sample,
  fc: ForecastResult,
  options: ForecastPlotDataOptions = {},
) {
  checkOptions(options, FORECAST_PLOT_DATA_KEYS, "forecastPlotData"); // generated: option-keys.mjs
  const start = options.start ?? 1, freq = options.frequency ?? 1;
  if (!(freq > 0)) throw new RangeError("'frequency' must be positive");
  const t = (i: number): number => start + i / freq;
  const y = Array.from(history);
  const n = y.length;
  const levels = fc.level.map((lv, j) => [lv, j] as const).sort((a, b) => b[0] - a[0]);
  return {
    layers: {
      history: y.map((v, i) => ({ x: t(i), y: v })),
      mean: fc.mean.map((v, h) => ({ x: t(n + h), y: v })),
      intervals: levels.flatMap(([level, j]) => fc.mean.map((_, h) => ({ x: t(n + h), level, lower: fc.lower[h]![j]!, upper: fc.upper[h]![j]! }))),
    },
    meta: { title: `Forecasts from ${fc.method}`, levels: fc.level },
  };
}
