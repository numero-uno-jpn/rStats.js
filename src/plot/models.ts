/**
 * Options for {@link lmDiagnosticsData}.
 *
 * @category Plot data
 */
export interface LmDiagnosticsDataOptions {
  /** How many of the most extreme points each panel flags (R's `id.n`). Default `3`. */
  idN?: number;
  /** The levels of Cook's distance contours. Default `[0.5, 1]`. */
  cookLevels?: readonly number[];
  /** The span of the lowess smooths (panel.smooth's). Default `2/3`. */
  span?: number;
}

/** The indices of the n largest values of score (NaN last), as a set */
function topN(score: readonly number[], n: number): Set<number> {
  const idx = score.map((_, i) => i).filter((i) => Number.isFinite(score[i]!));
  idx.sort((a, b) => score[b]! - score[a]!);
  return new Set(idx.slice(0, Math.max(0, n)));
}

/** lowess of the finite pairs, as panel.smooth (rows `x`, `y`) */
function smooth(x: readonly number[], y: readonly number[], f: number): { x: number; y: number }[] {
  const keep = x.map((_, i) => i).filter((i) => Number.isFinite(x[i]!) && Number.isFinite(y[i]!));
  if (keep.length === 0) return [];
  const s = lowess(keep.map((i) => x[i]!), keep.map((i) => y[i]!), { f, iter: 3 });
  return s.x.map((v, i) => ({ x: v, y: s.y[i]! }));
}

/**
 * Plot data for the four default diagnostic plots of a linear model ({@link lm}), as R's `plot.lm` (`which = c(1, 2,
 * 3, 5)`), for the rows of non-zero weight (the residuals weighted as in R).
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layers (`index` is the row of the fit, `extreme` flags the `idN` most extreme points as R labels them):
 * `residualsFitted` (`x` = fitted, `y` = residual) and its `residualsFittedSmooth`; `qq` (`x` = theoretical
 * quantile, `y` = standardized residual); `scaleLocation` (`x` = fitted, `y` = sqrt |standardized residual|) and
 * `scaleLocationSmooth`; `leverage` (`x` = leverage, `y` = standardized residual, `cooks`) and `leverageSmooth`;
 * `cookContours` (`level`, `side` +1 or -1, `x`, `y`: the curves where Cook's distance equals each level). Rows of
 * leverage 1 are left out of the panels that need standardized residuals (R does the same, with a warning).
 *
 * @example
 * ```ts
 * const d = lmDiagnosticsData(lm([1, 2, 3, 4, 10], [1.1, 1.9, 3.2, 3.9, 7]));
 * d.layers.leverage.length; // 5
 * ```
 *
 * @category Plot data
 */
export function lmDiagnosticsData(
  fit: LmResult,
  options: LmDiagnosticsDataOptions = {},
) {
  checkOptions(options, LM_DIAGNOSTICS_DATA_KEYS, "lmDiagnosticsData"); // generated: option-keys.mjs
  const idN = options.idN ?? 3;
  const span = options.span ?? 2 / 3;
  const rowsAll = fit.rows ?? fit.residuals.map((_, i) => i);
  const used = fit.residuals.flatMap((_, i) => ((fit.weights?.[i] ?? 1) > 0 ? [i] : []));
  const index = used.map((i) => rowsAll[i] ?? i);
  const fitted = used.map((i) => fit.fittedValues[i]!);
  const res = used.map((i) => Math.sqrt(fit.weights?.[i] ?? 1) * fit.residuals[i]!);
  const h = lmHatvalues(fit);
  const rs = lmRstandard(fit);
  const cooks = lmCooksDistance(fit);
  const ext1 = topN(res.map(Math.abs), idN);
  const extR = topN(rs.map(Math.abs), idN);
  const extC = topN(cooks, idN);
  const ok = rs.map(Number.isFinite);
  const residualsFitted = fitted.map((x, i) => ({ x, y: res[i]!, index: index[i]!, extreme: ext1.has(i) }));
  // an exact fit (or every leverage 1) leaves no standardized residual: those panels are then empty
  const q = ok.some(Boolean) ? qqnorm(rs.map((v) => (Number.isFinite(v) ? v : NaN))).x : rs.map(() => NaN);
  const qq = rs.flatMap((v, i) => (ok[i] ? [{ x: q[i]!, y: v, index: index[i]!, extreme: extR.has(i) }] : []));
  const sl = rs.map((v) => Math.sqrt(Math.abs(v)));
  const scaleLocation = fitted.flatMap((x, i) => (ok[i] ? [{ x, y: sl[i]!, index: index[i]!, extreme: extR.has(i) }] : []));
  const leverage = h.flatMap((x, i) => (ok[i] ? [{ x, y: rs[i]!, cooks: cooks[i]!, index: index[i]!, extreme: extC.has(i) }] : []));
  const p = fit.rank;
  const hmax = Math.max(0, ...h.filter((v, i) => ok[i]));
  const cookContours = (options.cookLevels ?? [0.5, 1]).flatMap((level) =>
    [1, -1].flatMap((side) =>
      Array.from({ length: 100 }, (_, j) => {
        const x = (hmax * (j + 1)) / 100;
        return { level, side, x, y: side * Math.sqrt((level * p * (1 - x)) / x) };
      }),
    ),
  );
  return {
    layers: {
      residualsFitted,
      residualsFittedSmooth: smooth(fitted, res, span),
      qq,
      scaleLocation,
      scaleLocationSmooth: smooth(fitted.filter((_, i) => ok[i]), sl.filter((_, i) => ok[i]), span),
      leverage,
      leverageSmooth: smooth(h.filter((_, i) => ok[i]), rs.filter((_, i) => ok[i]), span),
      cookContours,
    },
    meta: {
      titles: ["Residuals vs Fitted", "Q-Q Residuals", "Scale-Location", "Residuals vs Leverage"],
      rank: p,
    },
  };
}

/**
 * Plot data for a coefficient plot of a linear model: each coefficient with its confidence interval ({@link confint}).
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layer `coefficients`: `term`, `estimate`, `lower`, `upper`, `y` (from the top: the number of coefficients down to 1).
 *
 * @example
 * ```ts
 * coefPlotData(lm([1, 2, 3, 4, 10], [1.1, 1.9, 3.2, 3.9, 7])).layers.coefficients[1].term; // "x1"
 * ```
 *
 * @category Plot data
 */
export function coefPlotData(
  fit: LmResult & { coefNames?: readonly string[] },
  options: { level?: number; intercept?: boolean } = {},
) {
  checkOptions(options, COEF_PLOT_DATA_KEYS, "coefPlotData"); // generated: option-keys.mjs
  const ci = confint(fit, { level: levelCheck(options.level ?? 0.95) });
  const names = fit.coefNames ?? fit.coefficients.map((_, i) => (fit.intercept ? (i === 0 ? "(Intercept)" : `x${i}`) : `x${i + 1}`));
  const keep = fit.coefficients.map((_, i) => i).filter((i) => (options.intercept ?? true) || names[i] !== "(Intercept)");
  const coefficients = keep.map((i, j) => ({
    term: names[i]!, estimate: fit.coefficients[i]!, lower: ci.lower[i]!, upper: ci.upper[i]!, y: keep.length - j,
  }));
  return { layers: { coefficients }, meta: { xLabel: "Estimate" } };
}

/**
 * Plot data for the fitted line of a linear model with its confidence band (for the mean) and prediction band (for a
 * new observation), from {@link predict}, over the given new predictor values.
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layer `band`: `x` (the first predictor's value), `fit`, `confLower`, `confUpper`, `predLower`, `predUpper`.
 *
 * @example
 * ```ts
 * const fit = lm([1, 2, 3, 4, 5], [1.1, 1.9, 3.2, 3.9, 5.1]);
 * predictionBandData(fit, [1, 2, 3, 4, 5]).layers.band.length; // 5
 * ```
 *
 * @category Plot data
 */
export function predictionBandData(fit: LmResult, newdata: MatrixInput | Sample, options: { level?: number } = {}) {
  checkOptions(options, PREDICTION_BAND_DATA_KEYS, "predictionBandData"); // generated: option-keys.mjs
  const level = levelCheck(options.level ?? 0.95);
  const c = predict(fit, newdata, { interval: "confidence", level });
  const p = predict(fit, newdata, { interval: "prediction", level });
  const xs = Array.from(newdata as ArrayLike<number | readonly number[]>, (r) => (typeof r === "number" ? r : r[0]!));
  const band = xs.map((x, i) => ({
    x, fit: c.fit[i]!, confLower: c.lwr![i]!, confUpper: c.upr![i]!, predLower: p.lwr![i]!, predUpper: p.upr![i]!,
  }));
  return { layers: { band }, meta: { level } };
}

/**
 * Plot data for an autocorrelation plot from {@link acf} (or {@link pacf}, {@link ccf}): the bars and the band
 * +- qnorm((1 + ci) / 2) / sqrt(n.used) of R's `plot.acf` (white noise).
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layers: `bars` (`lag`, `acf`); `band` (`lag`, `lower`, `upper`, over the lags). `meta.clim` is the band's half-width.
 *
 * @example
 * ```ts
 * acfPlotData(acf([1, 3, 2, 5, 4, 6, 5, 8, 7, 9])).meta.clim;
 * ```
 *
 * @category Plot data
 */
export function acfPlotData(a: AcfResult) {
  const bars = a.lag.map((lag, i) => ({ lag, acf: a.acf[i]! }));
  const band = a.lag.map((lag) => ({ lag, lower: -a.clim, upper: a.clim }));
  return { layers: { bars, band }, meta: { xLabel: "Lag", yLabel: a.type === "partial" ? "Partial ACF" : "ACF", clim: a.clim } };
}

