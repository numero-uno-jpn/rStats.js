// Plot data for multivariate results (1.21.0): dendrograms of hierarchical clusterings (R's plot.hclust) and biplots of
// principal components (R's biplot.prcomp). Written for rStats.js from the documented content of those plots
// (?plot.hclust: the leaves in the order of `order`, each merge at its height, `hang`; ?biplot.prcomp: the variables
// scaled by lambda^scale and the observations by lambda^(1 - scale), lambda the singular values, and pc.biplot), with
// the positions of the merges checked against R's dendrogram midpoints (experiments/plot121-log.md, experiment 4).
import type { HclustFit } from "../multivariate/hclust.js";
import type { PrcompResult } from "../linalg/lu.js";
// Generated by `node scripts/option-keys.mjs --write` from the option types; do not edit (begin)
import { checkOptions } from "../internal/checkOptions.js";
const DENDROGRAM_DATA_KEYS = ["hang"] as const;
const BIPLOT_DATA_KEYS = ["choices", "scale", "pcBiplot", "variableNames"] as const;
// Generated by `node scripts/option-keys.mjs --write` (end)

/**
 * Options for {@link dendrogramData}.
 *
 * @category Plot data
 */
export interface DendrogramDataOptions {
  /**
   * The fraction of the height range by which a leaf hangs below the merge that takes it in (R's `hang`). Default
   * `0.1`, as `plot.hclust`; a negative value puts every leaf at height 0.
   */
  hang?: number;
}

/**
 * Plot data for the dendrogram of a hierarchical clustering ({@link hclust}): the leaves at x = 1, ..., n in the
 * clustering's order, each merge at its height and centred over the two clusters it joins, as R's `plot.hclust`.
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layers: `segments` (`x1`, `y1`, `x2`, `y2`: the vertical and horizontal lines of the tree, `merge`: the merge's
 * row, 1-based); `leaves` (`x`, `y`: the end of the leaf's line, `label`, `index`: the observation, 1-based);
 * `nodes` (`x`, `y`, `merge`).
 *
 * @example
 * ```ts
 * const hc = hclust(dist([[1], [2], [6], [7], [15]]));
 * dendrogramData(hc).layers.leaves.map((l) => l.x); // [1, 2, 3, 4, 5]
 * ```
 *
 * @category Plot data
 */
export function dendrogramData(fit: HclustFit, options: DendrogramDataOptions = {}) {
  checkOptions(options, DENDROGRAM_DATA_KEYS, "dendrogramData"); // generated: option-keys.mjs
  const n = fit.order.length;
  const hang = options.hang ?? 0.1;
  const heights = fit.height;
  const span = heights.length > 0 ? Math.max(...heights) - Math.min(...heights) : 0;
  const leafPos = new Array<number>(n).fill(0);
  fit.order.forEach((obs, k) => {
    leafPos[obs - 1] = k + 1;
  });
  const nodeX: number[] = [];
  const segments: { x1: number; y1: number; x2: number; y2: number; merge: number }[] = [];
  const leafTop = new Array<number>(n).fill(0);
  const xOf = (m: number): number => (m < 0 ? leafPos[-m - 1]! : nodeX[m - 1]!);
  fit.merge.forEach(([a, b], j) => {
    const h = heights[j]!;
    const xa = xOf(a!), xb = xOf(b!);
    nodeX.push((xa + xb) / 2);
    for (const [m, x] of [[a!, xa], [b!, xb]] as const) {
      let y0: number;
      if (m < 0) {
        y0 = hang < 0 ? 0 : h - hang * span;
        leafTop[-m - 1] = y0;
      } else y0 = heights[m - 1]!;
      segments.push({ x1: x, y1: y0, x2: x, y2: h, merge: j + 1 });
    }
    segments.push({ x1: xa, y1: h, x2: xb, y2: h, merge: j + 1 });
  });
  const labels = fit.labels ?? Array.from({ length: n }, (_, i) => String(i + 1));
  const leaves = fit.order.map((obs) => ({ x: leafPos[obs - 1]!, y: leafTop[obs - 1]!, label: labels[obs - 1]!, index: obs }));
  const nodes = nodeX.map((x, j) => ({ x, y: heights[j]!, merge: j + 1 }));
  return { layers: { segments, leaves, nodes }, meta: { yLabel: "Height", method: fit.method } };
}

/**
 * Options for {@link biplotData}.
 *
 * @category Plot data
 */
export interface BiplotDataOptions {
  /** The two components, 1-based. Default `[1, 2]`. */
  choices?: readonly [number, number];
  /** The variables are scaled by lambda^scale, the observations by lambda^(1 - scale). Default `1` (as R). */
  scale?: number;
  /** Gabriel's principal component biplot: lambda = 1, observations times sqrt(n), variables over sqrt(n). Default `false`. */
  pcBiplot?: boolean;
}

/**
 * Plot data for a biplot of principal components ({@link prcomp}), as R's `biplot.prcomp`: the observations' scores and
 * the variables' loadings (draw these as arrows from the origin, usually on axes of their own), with lambda the
 * components' singular values sdev * sqrt(n).
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layers: `observations` (`x`, `y`, `index`, 1-based); `variables` (`x`, `y`, `variable`: 1-based or the name given).
 *
 * @example
 * ```ts
 * biplotData(prcomp([[1, 2], [2, 3.5], [3, 3], [4, 6]])).layers.variables.length; // 2
 * ```
 *
 * @throws RangeError for components out of range.
 * @category Plot data
 */
export function biplotData(
  fit: PrcompResult,
  options: BiplotDataOptions & { variableNames?: readonly string[] } = {},
) {
  checkOptions(options, BIPLOT_DATA_KEYS, "biplotData"); // generated: option-keys.mjs
  const [c1, c2] = options.choices ?? [1, 2];
  const p = fit.sdev.length;
  for (const c of [c1, c2]) if (!(Number.isInteger(c) && c >= 1 && c <= p)) throw new RangeError("'choices' must be components of the fit");
  const n = fit.x.length;
  const scale = options.scale ?? 1;
  const pc = options.pcBiplot ?? false;
  const lam = [c1, c2].map((c) => {
    let l = fit.sdev[c - 1]! * Math.sqrt(n);
    l = scale !== 0 ? l ** scale : 1;
    return pc ? l / Math.sqrt(n) : l;
  });
  const observations = fit.x.map((row, i) => ({ x: row[c1 - 1]! / lam[0]!, y: row[c2 - 1]! / lam[1]!, index: i + 1 }));
  const variables = fit.rotation.map((row, j) => ({
    x: row[c1 - 1]! * lam[0]!, y: row[c2 - 1]! * lam[1]!, variable: options.variableNames?.[j] ?? String(j + 1),
  }));
  return {
    layers: { observations, variables },
    meta: { xLabel: `PC${c1}`, yLabel: `PC${c2}` },
  };
}
