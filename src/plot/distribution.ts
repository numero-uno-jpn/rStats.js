/**
 * Plot data for a normal Q-Q plot: the points (theoretical quantile, value) of {@link qqnorm} and the line of
 * {@link qqline} through the quartiles, drawn across the range of the theoretical quantiles.
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layers: `points` (`x`, `y`, `index`: the position in the data); `line` (two points). `meta.intercept` and
 * `meta.slope` give the line. Missing values are left out.
 *
 * @example
 * ```ts
 * qqPlotData([3.1, 1.2, 5.5, 1.2, 9.0]).layers.points.length; // 5
 * ```
 *
 * @category Plot data
 */
export function qqPlotData(y: Sample) {
  const q = qqnorm(y);
  const points = q.x.flatMap((x, i) => (Number.isNaN(x) ? [] : [{ x, y: q.y[i]!, index: i }]));
  const { intercept, slope } = qqline(y);
  const xs = points.map((p) => p.x);
  const lo = Math.min(...xs), hi = Math.max(...xs);
  return {
    layers: { points, line: [{ x: lo, y: intercept + slope * lo }, { x: hi, y: intercept + slope * hi }] },
    meta: { xLabel: "Theoretical quantiles", yLabel: "Sample quantiles", intercept, slope },
  };
}

/**
 * Plot data for a kernel density curve from {@link density}, with a rug of the data.
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layers: `curve` (`x`, `y`); `rug` (`x`: the finite values). `meta.bw` and `meta.n` as R's plot title shows them.
 *
 * @example
 * ```ts
 * densityPlotData([1.2, 2.3, 2.9, 3.1, 4.8]).layers.curve.length; // 512
 * ```
 *
 * @category Plot data
 */
export function densityPlotData(x: Sample, options: KernelDensityOptions = {}) {
  checkOptions(options, DENSITY_PLOT_DATA_KEYS, "densityPlotData"); // generated: option-keys.mjs
  const d = density(x, options);
  return {
    layers: { curve: d.x.map((v, i) => ({ x: v, y: d.y[i]! })), rug: Array.from(x).filter(Number.isFinite).map((v) => ({ x: v })) },
    meta: { xLabel: `N = ${d.n}   Bandwidth = ${Number(d.bw.toPrecision(4))}`, yLabel: "Density", bw: d.bw, n: d.n, kernel: d.kernel, warnings: d.warnings },
  };
}

/**
 * Plot data for box plots of one or more groups, from {@link boxplotStats} (as R's `boxplot()`): a sample, or an
 * object of named samples (one box each, in the object's order).
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layers: `boxes` (`group`, `lower` whisker, `q1`, `median`, `q3`, `upper` whisker, `n`, `notchLower`,
 * `notchUpper`); `outliers` (`group`, `y`).
 *
 * @example
 * ```ts
 * boxplotData({ a: [1, 2, 3, 4, 40], b: [2, 3, 3, 5] }).layers.outliers; // [{ group: "a", y: 40 }]
 * ```
 *
 * @category Plot data
 */
export function boxplotData(
  groups: Sample | Readonly<Record<string, Sample>>,
  options: BoxplotStatsOptions = {},
) {
  checkOptions(options, BOXPLOT_DATA_KEYS, "boxplotData"); // generated: option-keys.mjs
  const named: [string, Sample][] = Array.isArray(groups) || groups instanceof Float64Array
    ? [["", groups as Sample]]
    : Object.entries(groups as Record<string, Sample>);
  const boxes = [], outliers = [];
  for (const [group, v] of named) {
    const b = boxplotStats(v, options);
    const [lower, q1, median, q3, upper] = b.stats;
    boxes.push({ group, lower, q1, median, q3, upper, n: b.n, notchLower: b.conf[0] ?? NaN, notchUpper: b.conf[1] ?? NaN });
    for (const y of b.out) outliers.push({ group, y });
  }
  return { layers: { boxes, outliers }, meta: {} };
}

/**
 * Plot data for the empirical distribution function of a sample (as R's `plot(ecdf(x))`): the steps at the distinct
 * values (draw them as steps after each point), each with the fraction of values at or below it.
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layer `steps`: `x`, `y`. Missing values are left out.
 *
 * @example
 * ```ts
 * ecdfPlotData([3, 1, 2, 2]).layers.steps; // [{ x: 1, y: 0.25 }, { x: 2, y: 0.75 }, { x: 3, y: 1 }]
 * ```
 *
 * @category Plot data
 */
export function ecdfPlotData(x: Sample) {
  const v = Array.from(x).filter((t) => !Number.isNaN(t)).sort((a, b) => a - b);
  const n = v.length;
  const steps: { x: number; y: number }[] = [];
  v.forEach((t, i) => {
    if (i + 1 < n && v[i + 1] === t) return;
    steps.push({ x: t, y: (i + 1) / n });
  });
  return { layers: { steps }, meta: { xLabel: "x", yLabel: "Fn(x)" } };
}

/**
 * Plot data for a histogram: the bars of {@link hist} (from a sample, with hist's options, or from its result).
 * Not an R function. R's plots draw these values without returning them.
 *
 * Layer `bars`: `x0`, `x1` (the cell's ends), `mid`, `count`, `density`.
 *
 * @example
 * ```ts
 * histPlotData([1, 2, 2, 3, 3, 3, 4]).layers.bars.length;
 * ```
 *
 * @category Plot data
 */
export function histPlotData(x: Sample | HistResult, options: HistOptions = {}) {
  checkOptions(options, HIST_PLOT_DATA_KEYS, "histPlotData"); // generated: option-keys.mjs
  const h = "breaks" in x && "counts" in x ? (x as HistResult) : hist(x as Sample, options);
  const bars = h.counts.map((c, i) => ({ x0: h.breaks[i]!, x1: h.breaks[i + 1]!, mid: h.mids[i]!, count: c, density: h.density[i]! }));
  return { layers: { bars }, meta: { yLabel: "Frequency" } };
}
