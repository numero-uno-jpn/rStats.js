function maxAbs(values: readonly number[]): number {
  let result = 0;
  for (const value of values) result = Math.max(result, Math.abs(value));
  return result;
}

function newtonPolish(
  start: readonly number[], evaluate: (theta: number[]) => PolrDerivatives, scoreTolerance: number,
): PolrDerivatives & { theta: number[] } {
  let theta = Array.from(start);
  let current = evaluate(theta);
  for (let iteration = 0; iteration < 30 && maxAbs(current.gradient) > scoreTolerance; iteration++) {
    let inverse: number[][];
    try {
      inverse = chol2inv(chol(current.hessian));
    } catch {
      break;
    }
    const direction = inverse.map((row) => -row.reduce((sum, v, j) => sum + v * current.gradient[j]!, 0));
    const slope = direction.reduce((sum, v, j) => sum + v * current.gradient[j]!, 0);
    if (!(slope < 0) || !Number.isFinite(slope)) break;
    const currentScore = maxAbs(current.gradient);
    let step = 1;
    let accepted = false;
    for (let backtrack = 0; backtrack < 50; backtrack++, step *= 0.5) {
      const candidate = theta.map((v, j) => v + step * direction[j]!);
      const trial = evaluate(candidate);
      if (!Number.isFinite(trial.value)) continue;
      const armijo = trial.value <= current.value + 1e-4 * step * slope;
      // Close to the optimum, the predicted decrease can be below one ulp of the
      // total negative log likelihood. In that regime, accept a genuine score
      // reduction if the objective has not increased beyond its rounding error.
      const roundingAllowance = 16 * Number.EPSILON * Math.max(1, Math.abs(current.value), Math.abs(trial.value));
      const scoreImproved = maxAbs(trial.gradient) <= 0.5 * currentScore
        && trial.value <= current.value + roundingAllowance;
      if (armijo || scoreImproved) {
        theta = candidate;
        current = trial;
        accepted = true;
        break;
      }
    }
    if (!accepted) break;
  }
  return { ...current, theta };
}

function rowPredictors(x: readonly (readonly number[])[], beta: readonly number[], offset: readonly number[]): number[] {
  return x.map((row, i) => {
    let value = offset[i]!;
    for (let j = 0; j < beta.length; j++) value += row[j]! * beta[j]!;
    return value;
  });
}

function probabilities(eta: readonly number[], cuts: readonly number[], method: PolrMethod): number[][] {
  return eta.map((z) => {
    const logs = Array.from({ length: cuts.length + 1 }, (_, j) => categoryLogProbability(z, cuts, j, method));
    const values = logs.map((v) => Math.exp(v));
    const total = values.reduce((a, b) => a + b, 0);
    return values.map((v) => v / total);
  });
}

function covarianceFromHessian(hessian: number[][], p: number, k: number, theta: readonly number[]): number[][] {
  const upper = chol(hessian);
  const rawCov = chol2inv(upper);
  const n = p + k - 1;
  const jacobian: number[][] = Array.from({ length: n }, () => new Array<number>(n).fill(0));
  for (let i = 0; i < p; i++) jacobian[i]![i] = 1;
  for (let j = 0; j < k - 1; j++) {
    jacobian[p + j]![p] = 1;
    for (let m = 1; m <= j; m++) jacobian[p + j]![p + m] = Math.exp(theta[p + m]!);
  }
  return Array.from({ length: n }, (_, i) =>
    Array.from({ length: n }, (_, j) => {
      let sum = 0;
      for (let a = 0; a < n; a++) for (let b = 0; b < n; b++) sum += jacobian[i]![a]! * rawCov[a]![b]! * jacobian[j]![b]!;
      return sum;
    }),
  );
}

function offsetFormula(formula: string): { formula: string; column?: string } {
  const match = /\s*\+\s*offset\(\s*([A-Za-z.][\w.]*)\s*\)/.exec(formula);
  if (match === null) return { formula };
  return { formula: formula.replace(match[0], ""), column: match[1]! };
}

/**
 * Fit a cumulative-link ordinal regression. Equivalent to R's `MASS::polr()`.
 *
 * @param formula A formula such as `"rating ~ treatment + age"`.
 * @param data The data frame: an object of columns.
 * @param options The link, weights, offset, starts, contrasts and optimisation controls.
 * @returns The fitted slopes, cut-points, fitted probabilities and likelihood statistics.
 *
 * @example
 * ```ts
 * const fit = polr("rating ~ dose", { rating: ["low", "medium", "high", "low", "medium", "high"], dose: [0, 1, 2, 0, 1, 2] });
 * fit.zeta;
 * ```
 *
 * @category Regression
 */
export function polr(formula: string, data: DataFrame, options: PolrOptions = {}): PolrResult {
  checkOptions(options, POLR_KEYS, "polr"); // generated: option-keys.mjs
  const method = options.method ?? "logistic";
  if (!["logistic", "probit", "cloglog", "loglog", "cauchit"].includes(method)) {
    throw new RangeError(`unknown method '${String(method)}'`);
  }
  const extracted = offsetFormula(formula);
  if (extracted.column !== undefined && options.offset !== undefined) throw new RangeError("specify the offset in the formula or options, not both");
  const parsed = parseFormula(extracted.formula);
  if (parsed.response === undefined) throw new TypeError("the formula must have a response");
  const designOptions: Parameters<typeof design>[2] = {};
  if (options.weights !== undefined) designOptions.weights = options.weights;
  if (options.levels !== undefined) designOptions.levels = options.levels;
  if (options.contrasts !== undefined) designOptions.contrasts = options.contrasts;
  designOptions.anyResponse = true;
  const d = design(parsed, data, designOptions);
  const response = d.frame.variables[0];
  if (response === undefined || response.kind !== "factor") throw new TypeError("response must be a factor");
  const responseLevels = response.levels;
  if (responseLevels.length < 3) throw new Error("response must have 3 or more levels");
  const weights = d.frame.weights ?? new Array<number>(d.frame.rows.length).fill(1);
  for (let j = 0; j < responseLevels.length; j++) {
    if (!weights.some((w, i) => w > 0 && response.codes[i]! === j)) {
      throw new Error(`response level '${responseLevels[j]}' has no positive-weight observations`);
    }
  }
  if (weights.some((w) => !Number.isFinite(w) || w < 0)) throw new RangeError("weights must be finite and non-negative");
  const x = d.x.map((row) => row.slice(d.terms.intercept ? 1 : 0));
  const columnNames = d.colNames.slice(d.terms.intercept ? 1 : 0);
  const offsetSource = options.offset ?? (extracted.column === undefined ? undefined : data[extracted.column]);
  const offset = offsetSource === undefined
    ? new Array<number>(d.frame.rows.length).fill(0)
    : d.frame.rows.map((row) => Number(offsetSource[row]));
  if (offset.some((v) => !Number.isFinite(v))) throw new RangeError("offset must contain finite values");
  const y = response.codes;
  const p = columnNames.length;
  const k = responseLevels.length;
  const theta0 = options.start === undefined
    ? [...new Array<number>(p).fill(0), ...initialValues(y, weights, k, method)]
    : rawStart(Array.from(options.start), p, k);
  const objective = (theta: number[]): number => {
    const beta = theta.slice(0, p);
    const cuts = cutpointsFrom(theta, p, k);
    const eta = rowPredictors(x, beta, offset);
    let logLikelihood = 0;
    for (let i = 0; i < y.length; i++) {
      if (weights[i] === 0) continue;
      const lp = categoryLogProbability(eta[i]!, cuts, y[i]!, method);
      if (!Number.isFinite(lp)) return Number.MAX_VALUE;
      logLikelihood -= weights[i]! * lp;
    }
    return logLikelihood;
  };
  const evaluate = (theta: number[]) => polrDerivatives(x, y, weights, offset, k, method, theta);
  const fit = optim(theta0, objective, {
    method: "BFGS",
    gr: (theta) => evaluate(theta).gradient,
    control: { maxit: options.maxit ?? 2000, reltol: options.reltol ?? 1e-15 },
  });
  // BFGS supplies a robust starting point; the exact score and observed Hessian finish the fit.
  // Its iteration-limit code is not decisive if the Newton refinement reaches the score tolerance.
  // The score is a sum of weighted row contributions, so its absolute scale
  // grows linearly with total prior weight. Use a per-unit-weight tolerance.
  const scoreTolerance = 1e-9 * Math.max(1, weights.reduce((sum, weight) => sum + weight, 0));
  const polished = newtonPolish(fit.par, evaluate, scoreTolerance);
  if (maxAbs(polished.gradient) > scoreTolerance) {
    throw new Error(`ordinal regression score did not converge (max |score| = ${maxAbs(polished.gradient)})`);
  }
  const theta = polished.theta;
  const beta = theta.slice(0, p);
  const cuts = cutpointsFrom(theta, p, k);
  const hessian = polished.hessian;
  const cov = covarianceFromHessian(hessian, p, k, theta);
  const eta = rowPredictors(x, beta, offset);
  const fitted = probabilities(eta, cuts, method);
  const names = [...columnNames, ...cuts.map((_, j) => `${responseLevels[j]}|${responseLevels[j + 1]}`)];
  const coefficients = Object.fromEntries(columnNames.map((name, i) => [name, beta[i]!]));
  const zeta = Object.fromEntries(names.slice(p).map((name, i) => [name, cuts[i]!]));
  const logLik = -polished.value;
  const edf = p + k - 1;
  const nobs = weights.reduce((a, b) => a + b, 0);
  const warnings = [...d.warnings, ...fit.warnings];
  const factorLevels: Record<string, readonly string[]> = {};
  for (let i = 1; i < d.terms.variables.length; i++) {
    const variable = d.frame.variables[i];
    if (variable?.kind === "factor") factorLevels[d.terms.variables[i]!] = variable.levels;
  }
  const model: PolrModel = {
    formula, rhs: parsed.rhs, predictorVariables: d.terms.variables.slice(1), factorLevels,
    contrasts: options.contrasts ?? {},
    ...(extracted.column === undefined ? {} : { offsetColumn: extracted.column }),
    externalOffset: options.offset !== undefined,
    response: parsed.response, x, columnNames, y, responseLevels, weights, offset,
    rows: d.frame.rows, method, logLikelihood: logLik, theta, rawHessian: hessian,
  };
  const result: PolrResult = {
    coefficients, zeta, fittedValues: fitted, linearPredictors: eta, deviance: -2 * logLik,
    logLik, aic: -2 * logLik + 2 * edf, bic: -2 * logLik + Math.log(nobs) * edf,
    edf, nobs, converged: true, convergence: 0, warnings, model,
  };
  // Keep the covariance on the public result without exposing optimisation coordinates.
  COVARIANCE.set(result, cov);
  return reported("polr", result);
}

const COVARIANCE = new WeakMap<PolrResult, number[][]>();

const POLR_PREDICT_KEYS = ["newdata", "rowNames", "type"] as const;

/**
 * Predict ordinal categories or their probabilities for new observations. Equivalent to R's `predict.polr()`.
 *
 * @param fit A fit returned by {@link polr}.
 * @param options New predictor columns, optional row labels, and the prediction type.
 * @returns Predicted category labels, or a matrix with one probability column per response level.
 *
 * @example
 * ```ts
 * const fit = polr("rating ~ dose", { rating: ["low", "medium", "high", "low", "medium", "high"], dose: [0, 1, 2, 0, 1, 2] });
 * polrPredict(fit, { newdata: { dose: [0, 1, 2] } });
 * ```
 *
 * @category Regression
 */
export function polrPredict(fit: PolrResult, options: PolrPredictOptions = {}): PolrPredictResult {
  checkOptions(options, POLR_PREDICT_KEYS, "polrPredict"); // generated: option-keys.mjs
  const type = options.type ?? "class";
  if (type !== "class" && type !== "probs") throw new RangeError(`unknown prediction type '${String(type)}'`);

  const model = fit.model;
  let x: number[][];
  let offsets: number[];
  let rowIndices: number[];
  let rowNames: string[];
  let warnings = fit.warnings;

  if (options.newdata === undefined) {
    x = model.x;
    offsets = model.offset;
    rowIndices = Array.from({ length: x.length }, (_, i) => i);
    rowNames = options.rowNames === undefined
      ? model.rows.map((row) => String(row + 1))
      : Array.from(options.rowNames);
  } else {
    if (model.externalOffset) throw new TypeError("newdata prediction requires the offset in the formula");
    const data = options.newdata;
    const n = dataRowCount(data, model.predictorVariables);
    if (n === undefined) throw new TypeError("cannot determine the number of rows in newdata");
    rowNames = options.rowNames === undefined
      ? Array.from({ length: n }, (_, i) => String(i + 1))
      : Array.from(options.rowNames);
    if (rowNames.length !== n) throw new RangeError("rowNames must have the same length as newdata");

    for (const [name, levels] of Object.entries(model.factorLevels)) {
      const column = data[name];
      if (column === undefined) throw new RangeError(`object '${name}' not found`);
      for (const raw of column) {
        if (raw === null || (typeof raw === "number" && Number.isNaN(raw))) continue;
        const value = typeof raw === "boolean" ? (raw ? "TRUE" : "FALSE") : String(raw);
        if (!levels.includes(value)) throw new RangeError(`factor ${name} has new level ${value}`);
      }
    }

    const designOptions: Parameters<typeof design>[2] = {
      levels: model.factorLevels,
      contrasts: model.contrasts,
    };
    if (model.offsetColumn !== undefined) designOptions.extraVariables = [model.offsetColumn];
    const d = design({ response: undefined, rhs: model.rhs }, data, designOptions);
    const first = d.terms.intercept ? 1 : 0;
    const names = d.colNames.slice(first);
    if (names.length !== model.columnNames.length || names.some((name, i) => name !== model.columnNames[i])) {
      throw new RangeError("newdata does not produce the fitted model matrix columns");
    }
    x = d.x.map((row) => row.slice(first));
    rowIndices = d.frame.rows;
    offsets = model.offsetColumn === undefined
      ? new Array<number>(rowIndices.length).fill(0)
      : rowIndices.map((i) => Number(data[model.offsetColumn!]![i]));
    if (offsets.some((value) => !Number.isFinite(value))) throw new RangeError("offset must contain finite values");
    warnings = [...fit.warnings, ...d.warnings];
  }

  if (options.newdata === undefined && rowNames.length !== x.length) {
    throw new RangeError("rowNames must have the same length as the fitted observations");
  }
  const beta = Object.values(fit.coefficients);
  const cuts = Object.values(fit.zeta);
  const eta = rowPredictors(x, beta, offsets);
  const predicted = probabilities(eta, cuts, model.method);
  const n = rowNames.length;
  const full: (number | null)[][] = Array.from(
    { length: n }, () => new Array<number | null>(model.responseLevels.length).fill(null),
  );
  rowIndices.forEach((original, i) => { full[original] = predicted[i]!; });

  if (type === "class") {
    const classes = full.map((values) => {
      if (values[0] === null) return null;
      let best = 0;
      for (let j = 1; j < values.length; j++) if (values[j]! > values[best]!) best = j;
      return model.responseLevels[best]!;
    });
    return reported("polrPredict", { value: classes, warnings }, fit).value;
  }
  const result: PolrPredictProbs = {
    rows: rowNames,
    columns: model.responseLevels,
    values: full,
    warnings,
  };
  return reported("polrPredict", result, fit);
}

/**
 * Summary table of the slope and cut-point estimates. Equivalent to R's `summary.polr()`.
 *
 * @param fit A fit returned by {@link polr}.
 * @returns Estimates, standard errors and Wald t statistics.
 *
 * @category Regression
 */
export function polrSummary(fit: PolrResult): PolrSummaryResult {
  const names = [...Object.keys(fit.coefficients), ...Object.keys(fit.zeta)];
  const estimates = [...Object.values(fit.coefficients), ...Object.values(fit.zeta)];
  const covariance = COVARIANCE.get(fit);
  if (covariance === undefined) throw new TypeError("fit was not created by polr");
  const values = estimates.map((estimate, i) => {
    const se = Math.sqrt(covariance[i]![i]!);
    return [estimate, se, estimate / se];
  });
  return reported("polrSummary", { rows: names, columns: ["Value", "Std. Error", "t value"], values, warnings: fit.warnings }, fit);
}

/**
 * Covariance matrix of the slopes and cut-points. Equivalent to R's `vcov.polr()`.
 *
 * @param fit A fit returned by {@link polr}.
 * @returns The covariance matrix in slope-then-cut-point order.
 *
 * @category Regression
 */
export function polrVcov(fit: PolrResult): PolrVcovResult {
  const covariance = COVARIANCE.get(fit);
  if (covariance === undefined) throw new TypeError("fit was not created by polr");
  const names = [...Object.keys(fit.coefficients), ...Object.keys(fit.zeta)];
  return reported("polrVcov", { rows: names, columns: names, values: covariance, warnings: fit.warnings }, fit);
}


const POLR_CONFINT_KEYS = ["method", "level", "parm"] as const;

/** Indices of requested slopes, preserving the caller's order. */
function confintParameterIndices(names: readonly string[], parm: PolrConfintOptions["parm"]): number[] {
  const requested = parm === undefined ? Array.from({ length: names.length }, (_, i) => i + 1)
    : Array.isArray(parm) ? Array.from(parm) : [parm as string | number];
  return requested.map((value) => {
    if (typeof value === "number") {
      if (!Number.isInteger(value) || value < 1 || value > names.length) {
        throw new RangeError(`'parm' must identify a slope from 1 to ${names.length}`);
      }
      return value - 1;
    }
    const index = names.indexOf(value);
    if (index < 0) throw new RangeError(`unknown slope parameter '${value}'`);
    return index;
  });
}

type ProfilePoint = { value: number; fixedScore: number; theta: number[] };

function profileConstrainedFit(
  fit: PolrResult, fixedIndex: number, fixedValue: number, startTheta: readonly number[],
): ProfilePoint {
  const model = fit.model;
  const theta = Array.from(startTheta);
  theta[fixedIndex] = fixedValue;
  const freeIndices = theta.map((_, i) => i).filter((i) => i !== fixedIndex);
  const evaluate = (point: readonly number[]): PolrDerivatives => {
    const full = Array.from(theta);
    for (let i = 0; i < freeIndices.length; i++) full[freeIndices[i]!] = point[i]!;
    const d = polrDerivatives(model.x, model.y, model.weights, model.offset,
      model.responseLevels.length, model.method, full);
    return {
      value: d.value,
      gradient: freeIndices.map((i) => d.gradient[i]!),
      hessian: freeIndices.map((i) => freeIndices.map((j) => d.hessian[i]![j]!)),
    };
  };
  let point = freeIndices.map((i) => theta[i]!);
  let current = evaluate(point);
  const scoreTolerance = 2e-11 * Math.max(1, model.weights.reduce((sum, w) => sum + w, 0));
  let usedBfgs = false;
  const bfgsFallback = (): boolean => {
    try {
      const result = optim(point, (candidate) => evaluate(candidate).value, {
        method: "BFGS",
        gr: (candidate) => evaluate(candidate).gradient,
        control: { maxit: 1000, reltol: 1e-14 },
      });
      if (!result.par.every(Number.isFinite)) return false;
      point = result.par;
      current = evaluate(point);
      usedBfgs = true;
      return Number.isFinite(current.value);
    } catch {
      return false;
    }
  };
  for (let iteration = 0; iteration < 40 && maxAbs(current.gradient) > scoreTolerance; iteration++) {
    let inverse: number[][];
    try {
      inverse = chol2inv(chol(current.hessian));
    } catch {
      if (!usedBfgs && bfgsFallback()) continue;
      break;
    }
    const direction = inverse.map((row) => -row.reduce((sum, value, j) => sum + value * current.gradient[j]!, 0));
    const slope = direction.reduce((sum, value, j) => sum + value * current.gradient[j]!, 0);
    if (!(slope < 0) || !Number.isFinite(slope)) {
      if (!usedBfgs && bfgsFallback()) continue;
      break;
    }
    let step = 1;
    let accepted = false;
    for (let backtrack = 0; backtrack < 40; backtrack++, step *= 0.5) {
      const candidate = point.map((value, j) => value + step * direction[j]!);
      const trial = evaluate(candidate);
      const allowance = 16 * Number.EPSILON * Math.max(1, Math.abs(current.value), Math.abs(trial.value));
      if (Number.isFinite(trial.value)
        && (trial.value <= current.value + 1e-4 * step * slope
          || (maxAbs(trial.gradient) < maxAbs(current.gradient) && trial.value <= current.value + allowance))) {
        point = candidate;
        current = trial;
        accepted = true;
        break;
      }
    }
    if (!accepted) {
      if (!usedBfgs && bfgsFallback()) continue;
      break;
    }
  }
  const full = Array.from(theta);
  for (let i = 0; i < freeIndices.length; i++) full[freeIndices[i]!] = point[i]!;
  const final = polrDerivatives(model.x, model.y, model.weights, model.offset,
    model.responseLevels.length, model.method, full);
  return { value: final.value, fixedScore: final.gradient[fixedIndex]!, theta: full };
}

function profileEndpoint(
  fit: PolrResult, parameterIndex: number, target: number, standardError: number,
): number {
  const estimate = Object.values(fit.coefficients)[parameterIndex]!;
  const centre = -fit.logLik;
  let warmTheta = Array.from(fit.model.theta);
  const evaluate = (value: number): { x: number; g: number; r: number; score: number } | null => {
    const point = profileConstrainedFit(fit, parameterIndex, value, warmTheta);
    if (!Number.isFinite(point.value) || !Number.isFinite(point.fixedScore)) return null;
    warmTheta = point.theta;
    const r = Math.sign(value - estimate) * Math.sqrt(Math.max(0, 2 * (point.value - centre)));
    return { x: value, g: r - target, r, score: point.fixedScore };
  };

  // The estimate itself has r=0, so start from the corresponding Wald endpoint,
  // not from a Newton step at the singular point.
  const centreValue = { x: estimate, g: -target, r: 0, score: 0 };
  let inside = centreValue;
  let distance = Math.max(Math.abs(target) * standardError, standardError, 1e-6);
  let outside = evaluate(estimate + Math.sign(target) * distance);
  for (let iteration = 0; iteration < 60 && (outside === null || inside.g * outside.g > 0); iteration++) {
    distance *= 2;
    outside = evaluate(estimate + Math.sign(target) * distance);
  }
  if (outside === null || inside.g * outside.g > 0) return NaN;

  let low = inside;
  let high = outside;
  if (low.x > high.x) [low, high] = [high, low];
  let current = outside;
  for (let iteration = 0; iteration < 80; iteration++) {
    if (Math.abs(current.g) <= 2e-10) return current.x;
    if (low.g * current.g <= 0) high = current;
    else low = current;
    if (low.x > high.x) [low, high] = [high, low];

    // The stored gradient is for negative log likelihood, hence dr/db = score/r.
    // Newton is used only away from r=0 and only while it remains inside the bracket.
    const derivative = current.r === 0 ? NaN : current.score / current.r;
    let candidate = current.x - current.g / derivative;
    const width = high.x - low.x;
    const guard = 0.05 * width;
    if (!Number.isFinite(candidate) || candidate <= low.x + guard || candidate >= high.x - guard) {
      // A secant step is cheaper than a profile refit and is safe only inside the bracket.
      candidate = low.x - low.g * (high.x - low.x) / (high.g - low.g);
    }
    if (!Number.isFinite(candidate) || candidate <= low.x + guard || candidate >= high.x - guard) {
      candidate = low.x + width / 2;
    }
    if (candidate === low.x || candidate === high.x || candidate === current.x) return NaN;
    const next = evaluate(candidate);
    if (next === null) return NaN;
    current = next;
  }
  return NaN;
}

/**
 * Equivalent to R's `confint.polr()`.
 *
 * @param fit A fit returned by {@link polr}.
 * @param options The interval method, confidence level and selected slope parameters.
 * @returns A table of lower and upper confidence limits; cut-points are not included.
 *
 * @example
 * ```ts
 * const fit = polr("rating ~ dose", { rating: ["low", "medium", "high", "low", "medium", "high"], dose: [0, 1, 2, 0, 1, 2] });
 * polrConfint(fit, { method: "wald", level: 0.95 });
 * ```
 *
 * @category Regression
 */
export function polrConfint(fit: PolrResult, options: PolrConfintOptions = {}): PolrConfintResult {
  checkOptions(options, POLR_CONFINT_KEYS, "polrConfint"); // generated: option-keys.mjs
  const method = options.method ?? "profile";
  if (method !== "profile" && method !== "wald") throw new RangeError(`unknown confidence-interval method '${String(method)}'`);
  const level = options.level ?? 0.95;
  if (!(level > 0 && level < 1) || !Number.isFinite(level)) {
    throw new RangeError("'level' must be between 0 and 1");
  }
  const names = Object.keys(fit.coefficients);
  const indices = confintParameterIndices(names, options.parm);
  const alpha = (1 - level) / 2;
  const lowerPercent = String(Number((100 * alpha).toPrecision(12)));
  const upperPercent = String(Number((100 * (1 - alpha)).toPrecision(12)));
  const columns = [`${lowerPercent} %`, `${upperPercent} %`];
  const covariance = COVARIANCE.get(fit);
  if (covariance === undefined) throw new TypeError("fit was not created by polr");
  const z = qnorm(1 - alpha) as number;
  const warnings: string[] = [];
  const values = indices.map((index) => {
    const estimate = Object.values(fit.coefficients)[index]!;
    const se = Math.sqrt(covariance[index]![index]!);
    if (method === "wald") return [estimate - z * se, estimate + z * se];
    const lower = profileEndpoint(fit, index, -z, se);
    const upper = profileEndpoint(fit, index, z, se);
    if (!Number.isFinite(lower) || !Number.isFinite(upper)) {
      warnings.push(`profile confidence limit could not be found for '${names[index]}'`);
    }
    return [lower, upper];
  });
  return reported("polrConfint", {
    rows: indices.map((index) => names[index]!),
    columns,
    values,
    warnings: [...new Set(warnings)],
  }, fit);
}
