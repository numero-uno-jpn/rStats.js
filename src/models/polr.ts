const softplus = (x: number): number => x > 0 ? x + Math.log1p(Math.exp(-x)) : Math.log1p(Math.exp(x));

function log1mexp(x: number): number {
  if (x > 0) return NaN;
  if (x === 0) return -Infinity;
  return x < -Math.LN2 ? Math.log1p(-Math.exp(x)) : Math.log(-Math.expm1(x));
}

function logCdf(z: number, method: PolrMethod, upper = false): number {
  if (method === "logistic") return upper ? -softplus(z) : -softplus(-z);
  if (method === "probit") return pnorm(z, { lowerTail: !upper, logP: true }) as number;
  if (method === "cauchit") {
    // F(t) = 1/2 + atan(t)/pi. Evaluate the smaller tail directly.
    const t = upper ? -z : z;
    if (t === 0) return -Math.LN2;
    if (t > 0) {
      const reciprocal = 1 / t;
      const smallTail = reciprocal === 0 ? 0 : Math.atan(reciprocal) / Math.PI;
      return Math.log1p(-smallTail);
    }
    const reciprocal = -1 / t;
    if (reciprocal === 0) return -Infinity;
    return Math.log(Math.atan(reciprocal)) - Math.log(Math.PI);
  }
  if (method === "cloglog") return upper ? -Math.exp(z) : log1mexp(-Math.exp(z));
  return upper ? log1mexp(-Math.exp(-z)) : -Math.exp(-z);
}

function logDifference(a: number, b: number): number {
  if (b === -Infinity) return a;
  if (!(a > b)) return -Infinity;
  return a + log1mexp(b - a);
}

function categoryLogProbability(z: number, cutpoints: readonly number[], category: number, method: PolrMethod): number {
  const upper = cutpoints.map((c) => logCdf(c - z, method));
  if (category === 0) return upper[0]!;
  if (category === cutpoints.length) return logCdf(cutpoints[cutpoints.length - 1]! - z, method, true);
  return logDifference(upper[category]!, upper[category - 1]!);
}

function inverseCdf(p: number, method: PolrMethod): number {
  if (method === "logistic") return qlogis(p) as number;
  if (method === "probit") return qnorm(p) as number;
  if (method === "cauchit") return qcauchy(p) as number;
  if (method === "cloglog") return Math.log(-Math.log1p(-p));
  return -Math.log(-Math.log(p));
}

function cutpointsFrom(theta: readonly number[], p: number, k: number): number[] {
  const out = new Array<number>(k - 1);
  out[0] = theta[p]!;
  for (let j = 1; j < k - 1; j++) out[j] = out[j - 1]! + Math.exp(theta[p + j]!);
  return out;
}

function rawStart(values: readonly number[], p: number, k: number): number[] {
  if (values.length !== p + k - 1) throw new RangeError(`length of 'start' must be ${p + k - 1}`);
  const out = values.slice(0, p);
  out.push(values[p]!);
  for (let j = 1; j < k - 1; j++) {
    const gap = values[p + j]! - values[p + j - 1]!;
    if (!(gap > 0)) throw new RangeError("'start' cut-points must be strictly increasing");
    out.push(Math.log(gap));
  }
  return out;
}

function initialValues(y: readonly number[], weights: readonly number[], levels: number, method: PolrMethod): number[] {
  const counts = new Array<number>(levels).fill(0);
  for (let i = 0; i < y.length; i++) {
    const j = y[i]!;
    counts[j] = (counts[j] ?? 0) + weights[i]!;
  }
  const total = counts.reduce((a, b) => a + b, 0);
  const cuts: number[] = [];
  let cumulative = 0;
  for (let j = 0; j < levels - 1; j++) {
    cumulative += counts[j]!;
    cuts.push(inverseCdf(cumulative / total, method));
  }
  const transformed = [cuts[0]!];
  for (let j = 1; j < cuts.length; j++) transformed.push(Math.log(cuts[j]! - cuts[j - 1]!));
  return transformed;
}

type PolrDerivatives = { value: number; gradient: number[]; hessian: number[][] };

function linkDensity(t: number, method: PolrMethod): number {
  if (!Number.isFinite(t)) return 0;
  if (method === "logistic") {
    const logF = -softplus(-t);
    const logS = -softplus(t);
    return Math.exp(logF + logS);
  }
  if (method === "probit") return Math.exp(-0.5 * t * t - 0.5 * Math.log(2 * Math.PI));
  if (method === "cauchit") return 1 / (Math.PI * (1 + t * t));
  if (method === "cloglog") {
    const et = Math.exp(t);
    return et === 0 || !Number.isFinite(et) ? 0 : Math.exp(t - et);
  }
  const emt = Math.exp(-t);
  return emt === 0 || !Number.isFinite(emt) ? 0 : Math.exp(-t - emt);
}

function linkDensityDerivative(t: number, method: PolrMethod): number {
  const f = linkDensity(t, method);
  if (f === 0) return 0;
  if (method === "logistic") return f * (1 - 2 / (1 + Math.exp(-t)));
  if (method === "probit") return -t * f;
  if (method === "cauchit") return -2 * t * f / (1 + t * t);
  if (method === "cloglog") return f * (1 - Math.exp(t));
  return f * (Math.exp(-t) - 1);
}

/** Negative log likelihood and its exact first and second derivatives in the unconstrained coordinates. */
function polrDerivatives(
  x: readonly (readonly number[])[], y: readonly number[], weights: readonly number[],
  offset: readonly number[], levels: number, method: PolrMethod, theta: readonly number[],
): PolrDerivatives {
  const p = x[0]?.length ?? 0;
  const n = p + levels - 1;
  const beta = theta.slice(0, p);
  const cuts = cutpointsFrom(theta, p, levels);
  const gradientNatural = new Array<number>(n).fill(0);
  const hessianNatural: number[][] = Array.from({ length: n }, () => new Array<number>(n).fill(0));
  let value = 0;

  for (let i = 0; i < y.length; i++) {
    const w = weights[i]!;
    if (w === 0) continue;
    let eta = offset[i]!;
    for (let r = 0; r < p; r++) eta += x[i]![r]! * beta[r]!;
    const category = y[i]!;
    const lowerT = category === 0 ? -Infinity : cuts[category - 1]! - eta;
    const upperT = category === levels - 1 ? Infinity : cuts[category]! - eta;
    const logP = categoryLogProbability(eta, cuts, category, method);
    const probability = Math.exp(logP);
    if (!(probability > 0) || !Number.isFinite(probability)) {
      return { value: Number.MAX_VALUE, gradient: new Array<number>(n).fill(0), hessian: hessianNatural };
    }

    const fl = linkDensity(lowerT, method);
    const fu = linkDensity(upperT, method);
    const fpl = linkDensityDerivative(lowerT, method);
    const fpu = linkDensityDerivative(upperT, method);
    // For P = F(u) - F(l), with u/l = cut-point - eta:
    // P_eta = f(l) - f(u), P_eta,eta = f'(u) - f'(l).
    const pEta = fl - fu;
    const pEtaEta = fpu - fpl;
    const pGradient = new Array<number>(n).fill(0);
    const pHessian: number[][] = Array.from({ length: n }, () => new Array<number>(n).fill(0));

    for (let r = 0; r < p; r++) pGradient[r] = pEta * x[i]![r]!;
    if (category < levels - 1) pGradient[p + category] = fu;
    if (category > 0) pGradient[p + category - 1] = -fl;

    for (let r = 0; r < p; r++) {
      for (let c = 0; c < p; c++) pHessian[r]![c] = pEtaEta * x[i]![r]! * x[i]![c]!;
      if (category < levels - 1) {
        pHessian[r]![p + category] = -fpu * x[i]![r]!;
        pHessian[p + category]![r] = -fpu * x[i]![r]!;
      }
      if (category > 0) {
        pHessian[r]![p + category - 1] = fpl * x[i]![r]!;
        pHessian[p + category - 1]![r] = fpl * x[i]![r]!;
      }
    }
    if (category < levels - 1) pHessian[p + category]![p + category] = fpu;
    if (category > 0) pHessian[p + category - 1]![p + category - 1] = -fpl;

    value -= w * logP;
    for (let a = 0; a < n; a++) {
      gradientNatural[a] = gradientNatural[a]! - w * pGradient[a]! / probability;
      for (let b = 0; b < n; b++) {
        hessianNatural[a]![b] = hessianNatural[a]![b]! - w * (
          pHessian[a]![b]! / probability
          - pGradient[a]! * pGradient[b]! / (probability * probability)
        );
      }
    }
  }

  // Map derivatives from (beta, cut-points) to (beta, alpha_1, log-gap_2, ...).
  const jacobian: number[][] = Array.from({ length: n }, () => new Array<number>(n).fill(0));
  for (let j = 0; j < p; j++) jacobian[j]![j] = 1;
  for (let j = 0; j < levels - 1; j++) {
    jacobian[p + j]![p] = 1;
    for (let m = 1; m <= j; m++) jacobian[p + j]![p + m] = Math.exp(theta[p + m]!);
  }
  const gradient = new Array<number>(n).fill(0);
  const hessian: number[][] = Array.from({ length: n }, () => new Array<number>(n).fill(0));
  for (let a = 0; a < n; a++) {
    for (let u = 0; u < n; u++) gradient[a] = gradient[a]! + jacobian[u]![a]! * gradientNatural[u]!;
    for (let b = 0; b < n; b++) {
      for (let u = 0; u < n; u++) for (let v = 0; v < n; v++) {
        hessian[a]![b] = hessian[a]![b]! + jacobian[u]![a]! * hessianNatural[u]![v]! * jacobian[v]![b]!;
      }
    }
  }
  for (let m = 1; m < levels - 1; m++) {
    const gap = Math.exp(theta[p + m]!);
    let contribution = 0;
    for (let j = m; j < levels - 1; j++) contribution += gradientNatural[p + j]!;
    hessian[p + m]![p + m] = hessian[p + m]![p + m]! + gap * contribution;
  }
  return { value, gradient, hessian };
}

