// Generated by `node scripts/option-keys.mjs --write` from the option types; do not edit (begin)
const POLR_KEYS = ["method", "weights", "offset", "start", "contrasts", "levels", "maxit", "reltol"] as const;
// Generated by `node scripts/option-keys.mjs --write` (end)

/** Cumulative distribution used by an ordinal regression. */
export type PolrMethod = "logistic" | "probit" | "cloglog" | "loglog" | "cauchit";

/**
 * Options for {@link polr}.
 *
 * @category Regression
 */
export interface PolrOptions {
  /** Cumulative link. Default `"logistic"`. */
  method?: PolrMethod;
  /** Non-negative prior weights, or the name of a data column. */
  weights?: Sample | string;
  /** Offset added to the linear predictor. */
  offset?: Sample;
  /** Initial slopes followed by the ordered cut-points. */
  start?: Sample;
  /** Contrasts for categorical predictors. */
  contrasts?: Record<string, "contr.treatment" | "contr.sum" | "contr.helmert">;
  /** Explicit response and predictor levels. */
  levels?: Record<string, readonly string[]>;
  /** Maximum optimisation iterations. Default `1000`. */
  maxit?: number;
  /** Relative optimisation tolerance. Default `1e-12`. */
  reltol?: number;
}

/** The stored design and observations needed by prediction, profiling and model comparison. */
export interface PolrModel {
  formula: string;
  response: string;
  x: number[][];
  columnNames: string[];
  y: number[];
  responseLevels: string[];
  weights: number[];
  offset: number[];
  rows: number[];
  method: PolrMethod;
  logLikelihood: number;
  theta: number[];
  rawHessian: number[][];
}

/**
 * Result of {@link polr}: cumulative-link estimates and their observed-information covariance.
 *
 * @category Regression
 */
export interface PolrResult {
  /** Named slope estimates, excluding the cut-points. */
  coefficients: Record<string, number>;
  /** Named ordered cut-points, separately from the slopes. */
  zeta: Record<string, number>;
  /** Fitted category probabilities, one row per retained observation. */
  fittedValues: number[][];
  /** Linear predictors, offset included. */
  linearPredictors: number[];
  /** Residual deviance, `-2 logLik`. */
  deviance: number;
  /** Maximised log likelihood. */
  logLik: number;
  /** Akaike information criterion. */
  aic: number;
  /** Bayesian information criterion. */
  bic: number;
  /** Number of estimated slopes and cut-points. */
  edf: number;
  /** Sum of the positive case weights. */
  nobs: number;
  /** Whether the numerical optimisation converged. */
  converged: boolean;
  /** Optimiser convergence code. */
  convergence: number;
  /** Distinct warnings in first-occurrence order. */
  warnings: string[];
  /** Data and numerical state retained for the companion methods. */
  model: PolrModel;
}

/** Summary table of slopes and cut-points. */
export interface PolrSummaryResult {
  rows: string[];
  columns: ["Value", "Std. Error", "t value"];
  values: number[][];
  warnings: string[];
}

/** Complete covariance matrix in slope-then-cut-point order. */
export interface PolrVcovResult {
  rows: string[];
  columns: string[];
  values: number[][];
  warnings: string[];
}

const softplus = (x: number): number => x > 0 ? x + Math.log1p(Math.exp(-x)) : Math.log1p(Math.exp(x));

function log1mexp(x: number): number {
  if (x > 0) return NaN;
  if (x === 0) return -Infinity;
  return x < -Math.LN2 ? Math.log1p(-Math.exp(x)) : Math.log(-Math.expm1(x));
}

function logCdf(z: number, method: PolrMethod, upper = false): number {
  if (method === "logistic") return upper ? -softplus(z) : -softplus(-z);
  if (method === "probit") return pnorm(z, { lowerTail: !upper, logP: true }) as number;
  if (method === "cauchit") return pcauchy(z, { lowerTail: !upper, logP: true }) as number;
  if (method === "cloglog") return upper ? -Math.exp(z) : log1mexp(-Math.exp(z));
  return upper ? log1mexp(-Math.exp(-z)) : -Math.exp(-z);
}

function logDifference(a: number, b: number): number {
  if (b === -Infinity) return a;
  if (!(a > b)) return -Infinity;
  return a + log1mexp(b - a);
}

function categoryLogProbability(z: number, cutpoints: readonly number[], category: number, method: PolrMethod): number {
  const upper = cutpoints.map((c) => logCdf(c - z, method));
  if (category === 0) return upper[0]!;
  if (category === cutpoints.length) return logCdf(cutpoints[cutpoints.length - 1]! - z, method, true);
  return logDifference(upper[category]!, upper[category - 1]!);
}

function inverseCdf(p: number, method: PolrMethod): number {
  if (method === "logistic") return qlogis(p) as number;
  if (method === "probit") return qnorm(p) as number;
  if (method === "cauchit") return qcauchy(p) as number;
  if (method === "cloglog") return Math.log(-Math.log1p(-p));
  return -Math.log(-Math.log(p));
}

function cutpointsFrom(theta: readonly number[], p: number, k: number): number[] {
  const out = new Array<number>(k - 1);
  out[0] = theta[p]!;
  for (let j = 1; j < k - 1; j++) out[j] = out[j - 1]! + Math.exp(theta[p + j]!);
  return out;
}

function rawStart(values: readonly number[], p: number, k: number): number[] {
  if (values.length !== p + k - 1) throw new RangeError(`length of 'start' must be ${p + k - 1}`);
  const out = values.slice(0, p);
  out.push(values[p]!);
  for (let j = 1; j < k - 1; j++) {
    const gap = values[p + j]! - values[p + j - 1]!;
    if (!(gap > 0)) throw new RangeError("'start' cut-points must be strictly increasing");
    out.push(Math.log(gap));
  }
  return out;
}

function initialValues(y: readonly number[], weights: readonly number[], levels: number, method: PolrMethod): number[] {
  const counts = new Array<number>(levels).fill(0);
  for (let i = 0; i < y.length; i++) counts[y[i]!] += weights[i]!;
  const total = counts.reduce((a, b) => a + b, 0);
  const cuts: number[] = [];
  let cumulative = 0;
  for (let j = 0; j < levels - 1; j++) {
    cumulative += counts[j]!;
    cuts.push(inverseCdf(cumulative / total, method));
  }
  const transformed = [cuts[0]!];
  for (let j = 1; j < cuts.length; j++) transformed.push(Math.log(cuts[j]! - cuts[j - 1]!));
  return transformed;
}

function rowPredictors(x: readonly (readonly number[])[], beta: readonly number[], offset: readonly number[]): number[] {
  return x.map((row, i) => {
    let value = offset[i]!;
    for (let j = 0; j < beta.length; j++) value += row[j]! * beta[j]!;
    return value;
  });
}

function probabilities(eta: readonly number[], cuts: readonly number[], method: PolrMethod): number[][] {
  return eta.map((z) => {
    const logs = Array.from({ length: cuts.length + 1 }, (_, j) => categoryLogProbability(z, cuts, j, method));
    const values = logs.map((v) => Math.exp(v));
    const total = values.reduce((a, b) => a + b, 0);
    return values.map((v) => v / total);
  });
}

function covarianceFromHessian(hessian: number[][], p: number, k: number, theta: readonly number[]): number[][] {
  const upper = chol(hessian);
  const rawCov = chol2inv(upper);
  const n = p + k - 1;
  const jacobian: number[][] = Array.from({ length: n }, () => new Array<number>(n).fill(0));
  for (let i = 0; i < p; i++) jacobian[i]![i] = 1;
  for (let j = 0; j < k - 1; j++) {
    jacobian[p + j]![p] = 1;
    for (let m = 1; m <= j; m++) jacobian[p + j]![p + m] = Math.exp(theta[p + m]!);
  }
  return Array.from({ length: n }, (_, i) =>
    Array.from({ length: n }, (_, j) => {
      let sum = 0;
      for (let a = 0; a < n; a++) for (let b = 0; b < n; b++) sum += jacobian[i]![a]! * rawCov[a]![b]! * jacobian[j]![b]!;
      return sum;
    }),
  );
}

function offsetFormula(formula: string): { formula: string; column?: string } {
  const match = /\s*\+\s*offset\(\s*([A-Za-z.][\w.]*)\s*\)/.exec(formula);
  if (match === null) return { formula };
  return { formula: formula.replace(match[0], ""), column: match[1] };
}

/**
 * Fit a cumulative-link ordinal regression. Equivalent to R's `MASS::polr()`.
 *
 * @param formula A formula such as `"rating ~ treatment + age"`.
 * @param data The data frame: an object of columns.
 * @param options The link, weights, offset, starts, contrasts and optimisation controls.
 * @returns The fitted slopes, cut-points, fitted probabilities and likelihood statistics.
 *
 * @example
 * ```ts
 * const fit = polr("rating ~ dose", { rating: ["low", "medium", "high", "low", "medium", "high"], dose: [0, 1, 2, 0, 1, 2] });
 * fit.zeta;
 * ```
 *
 * @category Regression
 */
export function polr(formula: string, data: DataFrame, options: PolrOptions = {}): PolrResult {
  checkOptions(options, POLR_KEYS, "polr"); // generated: option-keys.mjs
  const method = options.method ?? "logistic";
  if (!["logistic", "probit", "cloglog", "loglog", "cauchit"].includes(method)) {
    throw new RangeError(`unknown method '${String(method)}'`);
  }
  const extracted = offsetFormula(formula);
  if (extracted.column !== undefined && options.offset !== undefined) throw new RangeError("specify the offset in the formula or options, not both");
  const parsed = parseFormula(extracted.formula);
  if (parsed.response === undefined) throw new TypeError("the formula must have a response");
  const designOptions: Parameters<typeof design>[2] = {};
  if (options.weights !== undefined) designOptions.weights = options.weights;
  if (options.levels !== undefined) designOptions.levels = options.levels;
  if (options.contrasts !== undefined) designOptions.contrasts = options.contrasts;
  const d = design(parsed, data, designOptions);
  const response = d.frame.variables[0];
  if (response === undefined || response.kind !== "factor") throw new TypeError("response must be a factor");
  const responseLevels = response.levels;
  if (responseLevels.length < 3) throw new Error("response must have 3 or more levels");
  const weights = d.frame.weights ?? new Array<number>(d.frame.rows.length).fill(1);
  for (let j = 0; j < responseLevels.length; j++) {
    if (!weights.some((w, i) => w > 0 && response.codes[i] === j)) {
      throw new Error(`response level '${responseLevels[j]}' has no positive-weight observations`);
    }
  }
  if (weights.some((w) => !Number.isFinite(w) || w < 0)) throw new RangeError("weights must be finite and non-negative");
  const x = d.x.map((row) => row.slice(d.terms.intercept ? 1 : 0));
  const columnNames = d.colNames.slice(d.terms.intercept ? 1 : 0);
  const offsetSource = options.offset ?? (extracted.column === undefined ? undefined : data[extracted.column]);
  const offset = offsetSource === undefined
    ? new Array<number>(d.frame.rows.length).fill(0)
    : d.frame.rows.map((row) => Number(offsetSource[row]));
  if (offset.some((v) => !Number.isFinite(v))) throw new RangeError("offset must contain finite values");
  const y = response.codes;
  const p = columnNames.length;
  const k = responseLevels.length;
  const theta0 = options.start === undefined
    ? [...new Array<number>(p).fill(0), ...initialValues(y, weights, k, method)]
    : rawStart(options.start, p, k);
  const objective = (theta: number[]): number => {
    const beta = theta.slice(0, p);
    const cuts = cutpointsFrom(theta, p, k);
    const eta = rowPredictors(x, beta, offset);
    let logLikelihood = 0;
    for (let i = 0; i < y.length; i++) {
      if (weights[i] === 0) continue;
      const lp = categoryLogProbability(eta[i]!, cuts, y[i]!, method);
      if (!Number.isFinite(lp)) return Number.MAX_VALUE;
      logLikelihood -= weights[i]! * lp;
    }
    return logLikelihood;
  };
  const fit = optim(theta0, objective, {
    method: "BFGS",
    hessian: true,
    control: { maxit: options.maxit ?? 1000, reltol: options.reltol ?? 1e-12 },
  });
  if (fit.convergence !== 0 || fit.hessian === undefined) {
    throw new Error(`ordinal regression did not converge (code ${fit.convergence})`);
  }
  const theta = fit.par;
  const beta = theta.slice(0, p);
  const cuts = cutpointsFrom(theta, p, k);
  const hessian = fit.hessian;
  const cov = covarianceFromHessian(hessian, p, k, theta);
  const eta = rowPredictors(x, beta, offset);
  const fitted = probabilities(eta, cuts, method);
  const names = [...columnNames, ...cuts.map((_, j) => `${responseLevels[j]}|${responseLevels[j + 1]}`)];
  const coefficients = Object.fromEntries(columnNames.map((name, i) => [name, beta[i]!]));
  const zeta = Object.fromEntries(names.slice(p).map((name, i) => [name, cuts[i]!]));
  const logLik = -fit.value;
  const edf = p + k - 1;
  const nobs = weights.reduce((a, b) => a + b, 0);
  const warnings = [...d.warnings, ...fit.warnings];
  const model: PolrModel = {
    formula, response: parsed.response, x, columnNames, y, responseLevels, weights, offset,
    rows: d.frame.rows, method, logLikelihood: logLik, theta, rawHessian: hessian,
  };
  const result: PolrResult = {
    coefficients, zeta, fittedValues: fitted, linearPredictors: eta, deviance: -2 * logLik,
    logLik, aic: -2 * logLik + 2 * edf, bic: -2 * logLik + Math.log(nobs) * edf,
    edf, nobs, converged: true, convergence: fit.convergence, warnings, model,
  };
  // Keep the covariance on the public result without exposing optimisation coordinates.
  COVARIANCE.set(result, cov);
  return reported("polr", result);
}

const COVARIANCE = new WeakMap<PolrResult, number[][]>();

/**
 * Summary table of the slope and cut-point estimates. Equivalent to R's `summary.polr()`.
 *
 * @param fit A fit returned by {@link polr}.
 * @returns Estimates, standard errors and Wald t statistics.
 *
 * @category Regression
 */
export function polrSummary(fit: PolrResult): PolrSummaryResult {
  const names = [...Object.keys(fit.coefficients), ...Object.keys(fit.zeta)];
  const estimates = [...Object.values(fit.coefficients), ...Object.values(fit.zeta)];
  const covariance = COVARIANCE.get(fit);
  if (covariance === undefined) throw new TypeError("fit was not created by polr");
  const values = estimates.map((estimate, i) => {
    const se = Math.sqrt(covariance[i]![i]!);
    return [estimate, se, estimate / se];
  });
  return reported("polrSummary", { rows: names, columns: ["Value", "Std. Error", "t value"], values, warnings: fit.warnings }, fit);
}

/**
 * Covariance matrix of the slopes and cut-points. Equivalent to R's `vcov.polr()`.
 *
 * @param fit A fit returned by {@link polr}.
 * @returns The covariance matrix in slope-then-cut-point order.
 *
 * @category Regression
 */
export function polrVcov(fit: PolrResult): PolrVcovResult {
  const covariance = COVARIANCE.get(fit);
  if (covariance === undefined) throw new TypeError("fit was not created by polr");
  const names = [...Object.keys(fit.coefficients), ...Object.keys(fit.zeta)];
  return reported("polrVcov", { rows: names, columns: names, values: covariance, warnings: fit.warnings }, fit);
}
