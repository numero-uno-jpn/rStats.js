// Heteroskedasticity-consistent and clustered covariance matrices of the coefficients of lm and glm fits: the
// sandwich package's vcovHC and vcovCL.
//
// Written for rStats.js (no ported code) from oracle/robust-behaviour.md (a description of the behaviour of sandwich
// 3.1-3) and the published methods: White (1980), "A heteroskedasticity-consistent covariance matrix estimator and a
// direct test for heteroskedasticity", Econometrica 48, 817-838 (HC0 and the sandwich); MacKinnon and White (1985),
// "Some heteroskedasticity-consistent covariance matrix estimators with improved finite sample properties", J.
// Econometrics 29, 305-325 (HC1, HC2, HC3); Long and Ervin (2000), "Using heteroscedasticity consistent standard errors
// in the linear regression model", Am. Stat. 54, 217-224; Cribari-Neto (2004), "Asymptotic inference under
// heteroskedasticity of unknown form", CSDA 45, 215-233 (HC4); Cribari-Neto, Souza and Vasconcellos (2007), "Inference
// under heteroskedasticity and leveraged data", Comm. Stat. Theory Methods 36, 1877-1888 (HC5); Cribari-Neto and da
// Silva (2011), "A new heteroskedasticity-consistent covariance matrix estimator for the linear regression model",
// AStA 95, 129-146 (HC4m); Zeileis (2004), "Econometric computing with HC and HAC covariance matrix estimators", JSS
// 11(10) (the omega framework, type "const"); Zeileis (2006), "Object-oriented computation of sandwich estimators",
// JSS 16(9) (estimating functions and bread of lm and glm); Zeileis, Köll and Graham (2020), "Various versatile
// variances: an object-oriented implementation of clustered covariances in R", JSS 95(1) (vcovCL: the cluster
// adjustment G/(G - 1), HC1's (n - 1)/(n - k), multi-way clustering, multi0, the eigenvalue fix, clustered HC2/HC3);
// Cameron, Gelbach and Miller (2011), "Robust inference with multiway clustering", JBES 29, 238-249 (inclusion-exclusion
// over the clustering dimensions, the fix of negative eigenvalues); Bell and McCaffrey (2002), "Bias reduction in
// standard errors for linear regression with multi-stage samples", Survey Methodology 28, 169-181, and Pustejovsky and
// Tipton (2018), "Small-sample methods for cluster-robust variance estimation and hypothesis testing in fixed effects
// models", JBES 36, 672-683 (the symmetric adjustment of clustered HC2/HC3 for weighted fits).
//
// The pieces (Zeileis 2006): with the n rows of non-zero prior weight, the k non-aliased columns x_i of the unweighted
// model matrix, A = (X'WX)^-1 from the fit's QR factor (lm: W the prior weights; glm: the working weights), the
// estimating functions psi_i = res_i x_i with res_i = w_i e_i (lm) or W_i z_i / phi_s (glm: z the working residuals,
// phi_s = sum (W z)^2 / sum W except for binomial and poisson, where it is 1), the meat M = (1/n) sum omega_i x_i x_i'
// (HC) or the cluster sums, and the sandwich V = n phi_s^2 A M A.

