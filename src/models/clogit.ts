// Conditional logistic regression, after survival's clogit(case ~ x + strata(set), method): "exact" maximises the
// exact conditional likelihood (Gail, Lubin & Rubinstein (1981), "Likelihood calculations for matched case-control
// studies and survival studies with tied death times", Biometrika 68, 703-707), "approximate" (= "breslow") is the
// Cox partial likelihood with Breslow's ties on equal times (coxph). Newton-Raphson as coxph (Therneau & Grambsch
// 2000, chapter 3). Written for rStats.js from the documentation and the published output (no ported code).
