/** Options of {@link clogit}. Equivalent to the arguments of survival's `clogit()`.
 * @category Survival analysis
 */
export interface ClogitOptions {
  /** The likelihood: `"exact"` (default, R's), or `"approximate"` / `"breslow"` (the Cox likelihood with Breslow's ties). */
  method?: "exact" | "approximate" | "breslow";
  /** Confidence level of the intervals of exp(coef). Default 0.95. */
  confLevel?: number;
  /** Convergence: relative change of the log likelihood (default 1e-9) and the most iterations (default 20). */
  control?: {
    /** Tolerance of the relative change of the log likelihood. Default 1e-9. */
    eps?: number;
    /** Most iterations. Default 20. */
    iterMax?: number;
  };
}

/** Result of {@link clogit}: the fields of R's `clogit` fit and of its `summary()`.
 * @category Survival analysis
 */
export interface ClogitResult {
  /** Coefficients. */
  coefficients: number[];
  /** Variance matrix of the coefficients (array of rows). */
  var: number[][];
  /** Log conditional likelihood at 0 and at the end. */
  loglik: [number, number];
  /** Score test statistic at 0. */
  score: number;
  /** Wald statistic. */
  wald: number;
  /** Number of iterations. */
  iter: number;
  /** Number of observations. */
  n: number;
  /** Number of cases. */
  nevent: number;
  /** `"exact"` or `"breslow"` (R's `method`). */
  method: "exact" | "breslow";
  /** Standard errors. */
  se: number[];
  /** Wald z statistics. */
  z: number[];
  /** Two-sided p-values. */
  p: number[];
  /** Lower confidence limits of exp(coef). */
  lower: number[];
  /** Upper confidence limits of exp(coef). */
  upper: number[];
  /** Likelihood ratio test. */
  logtest: CoxphTest;
  /** Score test. */
  sctest: CoxphTest;
  /** Wald test (the statistic unrounded; R's `summary()` prints it rounded to 2 decimals). */
  waldtest: CoxphTest;
  /** Warnings (R's, e.g. when the iterations ran out). */
  warnings: string[];
}

type Label = GroupLabel;

/** Log likelihood, score and information of the exact conditional likelihood at beta (covariates centred). */
function evaluateExact(sets: { x: number[][]; cases: number }[], beta: readonly number[]):
  { loglik: number; score: number[]; info: number[][] } {
  const p = beta.length;
  let loglik = 0;
  const score = new Array<number>(p).fill(0);
  const info = Array.from({ length: p }, () => new Array<number>(p).fill(0));
  for (const { x, cases: d } of sets) {
    const m = x.length;
    if (d === 0 || d === m) continue; // a set of cases only or controls only carries no information
    // the cases are the first d rows; B[k] is the sum over subsets of size k of the product of r, with its derivatives
    const eta = x.map((row) => row.reduce((s, v, j) => s + v * beta[j]!, 0));
    // scale r by exp(-max eta) per subset member to keep B in range: B_k then carries the factor exp(-k max)
    const top = Math.max(...eta);
    const r = eta.map((e) => Math.exp(e - top));
    let B = new Array<number>(d + 1).fill(0); B[0] = 1;
    let D = Array.from({ length: d + 1 }, () => new Array<number>(p).fill(0));
    let H = Array.from({ length: d + 1 }, () => Array.from({ length: p }, () => new Array<number>(p).fill(0)));
    for (let i = 0; i < m; i++) {
      const xi = x[i]!;
      const nb = B.slice(); const nd = D.map((v) => v.slice()); const nh = H.map((a) => a.map((v) => v.slice()));
      for (let k = 1; k <= Math.min(d, i + 1); k++) {
        nb[k]! += r[i]! * B[k - 1]!;
        for (let a = 0; a < p; a++) {
          nd[k]![a]! += r[i]! * (xi[a]! * B[k - 1]! + D[k - 1]![a]!);
          for (let b = 0; b < p; b++) {
            nh[k]![a]![b]! += r[i]! * (xi[a]! * xi[b]! * B[k - 1]! + xi[a]! * D[k - 1]![b]! + xi[b]! * D[k - 1]![a]! + H[k - 1]![a]![b]!);
          }
        }
      }
      B = nb; D = nd; H = nh;
    }
    let num = 0;
    for (let i = 0; i < d; i++) num += eta[i]! - top;
    loglik += num - Math.log(B[d]!);
    for (let a = 0; a < p; a++) {
      let sx = 0;
      for (let i = 0; i < d; i++) sx += x[i]![a]!;
      const ma = D[d]![a]! / B[d]!;
      score[a]! += sx - ma;
      for (let b = 0; b < p; b++) info[a]![b]! += H[d]![a]![b]! / B[d]! - ma * (D[d]![b]! / B[d]!);
    }
  }
  return { loglik, score, info };
}

/** Solves info * s = u by Gaussian elimination with partial pivoting; also returns the inverse. */
function solveAndInvert(a: readonly (readonly number[])[], u: readonly number[]): { step: number[]; inverse: number[][] } {
  const p = u.length;
  const m = a.map((row, i) => [...row, ...u.slice(i, i + 1), ...Array.from({ length: p }, (_, j) => (i === j ? 1 : 0))]);
  for (let c = 0; c < p; c++) {
    let piv = c;
    for (let r = c + 1; r < p; r++) if (Math.abs(m[r]![c]!) > Math.abs(m[piv]![c]!)) piv = r;
    [m[c], m[piv]] = [m[piv]!, m[c]!];
    const d = m[c]![c]!;
    for (let j = 0; j < m[c]!.length; j++) m[c]![j]! /= d;
    for (let r = 0; r < p; r++) {
      if (r === c) continue;
      const f = m[r]![c]!;
      if (f !== 0) for (let j = 0; j < m[r]!.length; j++) m[r]![j]! -= f * m[c]![j]!;
    }
  }
  return { step: m.map((row) => row[p]!), inverse: m.map((row) => row.slice(p + 1)) };
}

function test(statistic: number, df: number): CoxphTest {
  return { statistic, df, pValue: pchisq(statistic, df, { lowerTail: false }) };
}

/**
 * Conditional logistic regression for matched sets (1:1, 1:M or several cases per set). Equivalent to
 * `survival::clogit()` in R. The call followed is `clogit(y ~ x1 + ... + strata(set), method)`.
 *
 * `y` is 1 for a case and 0 for a control, `x` one row of covariates per observation, `strata` the matched set of
 * each observation (for matched pairs from {@link match}, the pair number). Sets with only cases or only controls
 * carry no information. `"exact"` (R's default) uses the exact conditional likelihood, summing over the subsets of each
 * set with as many members as it has cases; `"approximate"` is Breslow's approximation, the same as {@link coxph}
 * with equal times, `ties: "breslow"` and these strata.
 * @category Survival analysis
 * @example
 * ```ts
 * const y = [1, 0, 1, 0, 1, 0, 0, 1];
 * const x = [[1], [0], [1], [0], [0], [0], [1], [0]];
 * const fit = clogit(y, x, [1, 1, 2, 2, 3, 3, 4, 4]);
 * fit.coefficients; // [0.6931471805599454] (log 2: two discordant pairs for x, one against)
 * ```
 */
export function clogit(y: readonly number[], x: readonly (readonly number[])[], strata: readonly Label[],
  options: ClogitOptions = {}): ClogitResult {
    checkOptions(options, CLOGIT_KEYS, "clogit"); // generated: option-keys.mjs
    checkOptions(nestedOptions(options, "control"), CLOGIT_CONTROL_KEYS, "clogit", "control"); // generated: option-keys.mjs
  const { method = "exact", confLevel = 0.95, control = {} } = options;
  const { eps = 1e-9, iterMax = 20 } = control;
  const n = y.length;
  if (x.length !== n || strata.length !== n) throw new RangeError("'y', 'x' and 'strata' must have the same length");
  if (method !== "exact" && method !== "approximate" && method !== "breslow") throw new RangeError(`invalid 'method': ${String(method)}`);
  y.forEach((v, i) => { if (v !== 0 && v !== 1) throw new RangeError(`'y' must be 0 or 1 (element ${i + 1})`); });
  const p = x[0]?.length ?? 0;
  if (p === 0 || x.some((row) => row.length !== p || row.some((v) => !Number.isFinite(v)))) {
    throw new RangeError("'x' must have the same positive number of finite covariates in every row");
  }
  const zq = qnorm((1 + confLevel) / 2);
  const finish = (coefficients: number[], variance: number[][], loglik: [number, number], score: number, wald: number,
    iter: number, m: "exact" | "breslow", warnings: string[]): ClogitResult => {
    const se = variance.map((row, i) => Math.sqrt(row[i]!));
    const z = coefficients.map((c, i) => c / se[i]!);
    return {
      coefficients, var: variance, loglik, score, wald, iter, n, nevent: y.reduce((s, v) => s + v, 0), method: m, se, z,
      p: z.map((v) => pchisq(v * v, 1, { lowerTail: false })),
      lower: coefficients.map((c, i) => Math.exp(c - zq * se[i]!)), upper: coefficients.map((c, i) => Math.exp(c + zq * se[i]!)),
      logtest: test(2 * (loglik[1] - loglik[0]), p), sctest: test(score, p), waldtest: test(wald, p), warnings,
    };
  };

  if (method !== "exact") {
    const fit = coxph(new Array<number>(n).fill(1), y, x, { ties: "breslow", strata, confLevel, control: { eps, iterMax } });
    return finish(fit.coefficients, fit.var, fit.loglik, fit.score, fit.wald, fit.iter, "breslow", fit.warnings);
  }

  // matched sets with the cases first; covariates centred on the overall means (the likelihood does not change)
  const means = Array.from({ length: p }, (_, j) => x.reduce((s, row) => s + row[j]!, 0) / n);
  const groups = new Map<Label, { cases: number[][]; controls: number[][] }>();
  for (let i = 0; i < n; i++) {
    let g = groups.get(strata[i]!);
    if (g === undefined) { g = { cases: [], controls: [] }; groups.set(strata[i]!, g); }
    (y[i] === 1 ? g.cases : g.controls).push(x[i]!.map((v, j) => v - means[j]!));
  }
  const sets = [...groups.values()].map((g) => ({ x: [...g.cases, ...g.controls], cases: g.cases.length }));

  let beta = new Array<number>(p).fill(0);
  let ev = evaluateExact(sets, beta);
  const loglik: [number, number] = [ev.loglik, ev.loglik];
  let { step, inverse } = solveAndInvert(ev.info, ev.score);
  const score = ev.score.reduce((s, u, i) => s + u * step[i]!, 0);
  const warnings: string[] = [];
  let iter = 0;
  let best = ev.loglik;
  let next = beta.map((b, i) => b + step[i]!);
  let halvings = 0;
  let converged = false;
  for (iter = 1; iter <= iterMax; iter++) {
    ev = evaluateExact(sets, next);
    const finite = Number.isFinite(ev.loglik) && ev.score.every(Number.isFinite);
    if (finite && (ev.loglik === best || Math.abs(1 - best / ev.loglik) <= eps)) {
      converged = true;
      loglik[1] = ev.loglik;
      beta = next;
      ({ inverse } = solveAndInvert(ev.info, ev.score));
      break;
    }
    if (!finite || ev.loglik < best) {
      halvings++;
      next = next.map((b, i) => (b + halvings * beta[i]!) / (halvings + 1));
    } else {
      halvings = 0;
      best = ev.loglik;
      loglik[1] = best;
      ({ step } = solveAndInvert(ev.info, ev.score));
      beta = next;
      next = next.map((b, i) => b + step[i]!);
    }
  }
  if (!converged) {
    iter = iterMax + 1;
    ev = evaluateExact(sets, beta);
    loglik[1] = ev.loglik;
    ({ inverse } = solveAndInvert(ev.info, ev.score));
    warnings.push("Ran out of iterations and did not converge");
  }
  let wald = 0;
  // Wald statistic beta' var^-1 beta: var^-1 is the information at the end
  const infoEnd = evaluateExact(sets, beta).info;
  for (let a = 0; a < p; a++) for (let b = 0; b < p; b++) wald += beta[a]! * infoEnd[a]![b]! * beta[b]!;
  return finish(beta, inverse, loglik, score, wald, iter, "exact", warnings);
}
