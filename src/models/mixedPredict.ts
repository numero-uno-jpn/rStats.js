// Predictions of mixed models fitted by lmer and glmer (lme4's predict.merMod): at the fit's rows or at new data, with
// all, some or none of the random-effects terms, the random part only, on the link or the response scale, with the
// standard errors from the conditional covariance of (b, β).
//
// Written for rStats.js (no ported code) from oracle/glmer-behaviour.md ("Prediction: glmerPredict and lmerPredict
// (stage 4)" and "rStats.js's choices", G14, G16, G17) and the notation of D. Bates, M. Mächler, B. Bolker, S. Walker
// (2015), "Fitting Linear Mixed-Effects Models Using lme4", Journal of Statistical Software 67(1).
//
// The prediction of a row is η = o + x'β̂ + Σ_t z_t' b̂(t, level) over the random-effects terms t selected, x the
// row of the fixed-effects model matrix built from the row as the fit built X (the fit's terms, contrasts, factor
// levels and dropped columns), z_t the row of the term's left-hand side model matrix and the level that of the row's
// grouping factor. The standard error (se.fit) is √(v'Cv) with v = (z, x), z the row's columns of the fit's Z, and
// C = σ² A K⁻¹ A', K = [Λ'Z'WZΛ + I, Λ'Z'WX; X'WZΛ, X'WX], A = diag(Λ, I) (W the Fisher weights at the conditional
// mode, 1 for lmer), computed from the sparse factor L of Λ'Z'WZΛ + I, C_X = L⁻¹Λ'Z'WX and R_X:
// v'Cv = σ² (‖c‖² + ‖R_X⁻ᵀ(x − C_X'c)‖²) with c = L⁻¹Λ'z.

