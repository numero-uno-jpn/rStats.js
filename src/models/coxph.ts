/** Log partial likelihood, score and information (lower triangle filled into the upper) at the scaled coefficients */
interface Evaluation {
  loglik: number;
  score: number[];
  info: number[][];
}

const MIN_NORMAL = 2 ** -1022;

/** Distance of eta from the shift of the risk sums beyond which exp would leave (or near) the doubles (e^709.8 overflows) */
const SHIFT_LIMIT = 700;

function evaluate(data: SortedData, beta: readonly number[], efron: boolean): Evaluation {
  const { time, event, weight, x, stratumEnd } = data;
  const n = time.length;
  const p = beta.length;
  const zeros = (): number[] => new Array<number>(p).fill(0);
  const zeroMatrix = (): number[][] => Array.from({ length: p }, zeros);
  const score = zeros();
  const info = zeroMatrix();
  let loglik = 0;
  let riskSum = 0;
  let riskX = zeros();
  let riskXX = zeroMatrix();
  const deathX = zeros();
  const deathXX = zeroMatrix();
  let deathRisk = 0;
  // The risk sums (and the sums of the deaths at one time) are held as e^-shift times their values. shift stays 0,
  // and the arithmetic is the plain one, unless a finite exp(eta) would overflow (or, with the sums still empty,
  // underflow): then the sums are rescaled to the new shift, so a log partial likelihood that is finite is not lost
  // to Inf (issue #367). The means and the information are ratios of the sums and do not depend on the shift
  let shift = 0;
  const rescale = (to: number): void => {
    const f = Math.exp(shift - to);
    riskSum *= f;
    deathRisk *= f;
    for (let i = 0; i < p; i++) {
      riskX[i]! *= f;
      deathX[i]! *= f;
      const row = riskXX[i]!;
      const drow = deathXX[i]!;
      for (let l = 0; l <= i; l++) {
        row[l]! *= f;
        drow[l]! *= f;
      }
    }
    shift = to;
  };
  for (let k = n - 1; k >= 0; ) {
    if (stratumEnd[k]) {
      shift = 0;
      riskSum = 0;
      riskX = zeros();
      riskXX = zeroMatrix();
    }
    const t = time[k]!;
    let deaths = 0;
    let deathWeight = 0;
    deathRisk = 0;
    let j = k;
    do {
      const xj = x[j]!;
      let eta = 0;
      for (let i = 0; i < p; i++) eta += beta[i]! * xj[i]!;
      const w = weight[j]!;
      if (Number.isFinite(eta)) {
        if (eta - shift > SHIFT_LIMIT) rescale(eta);
        else if (eta - shift < -SHIFT_LIMIT && riskSum === 0 && deathRisk === 0) shift = eta;
      }
      const r = Math.exp(eta - shift) * w;
      if (!event[j]) {
        riskSum += r;
        for (let i = 0; i < p; i++) {
          riskX[i]! += r * xj[i]!;
          const row = riskXX[i]!;
          for (let l = 0; l <= i; l++) row[l]! += r * xj[i]! * xj[l]!;
        }
      } else {
        deaths++;
        deathWeight += w;
        deathRisk += r;
        loglik += w * eta;
        for (let i = 0; i < p; i++) {
          score[i]! += w * xj[i]!;
          deathX[i]! += r * xj[i]!;
          const row = deathXX[i]!;
          for (let l = 0; l <= i; l++) row[l]! += r * xj[i]! * xj[l]!;
        }
      }
      j--;
    } while (j >= 0 && time[j] === t && !stratumEnd[j]);
    if (deaths > 0) {
      const steps = efron ? deaths : 1;
      const share = efron ? deaths : 1;
      const stepWeight = deathWeight / steps;
      for (let s = 0; s < steps; s++) {
        riskSum += efron ? deathRisk / share : deathRisk;
        loglik -= stepWeight * (Math.log(riskSum) + shift);
        for (let i = 0; i < p; i++) {
          riskX[i]! += efron ? deathX[i]! / share : deathX[i]!;
          const mean = riskX[i]! / riskSum;
          score[i]! -= stepWeight * mean;
          const row = riskXX[i]!;
          const drow = deathXX[i]!;
          const irow = info[i]!;
          for (let l = 0; l <= i; l++) {
            row[l]! += efron ? drow[l]! / share : drow[l]!;
            const dev = row[l]! - mean * riskX[l]!;
            const term = stepWeight * dev;
            // stepWeight and dev both carry the scale of the weights, so the product leaves the doubles for weights
            // around 2^+-512 although the term does not: there (only) the quotient first, which does not change the
            // bits of the ordinary case
            irow[l]! +=
              (term < Infinity && term > -Infinity && (Math.abs(term) >= MIN_NORMAL || dev === 0)) || !Number.isFinite(stepWeight)
                ? term / riskSum
                : stepWeight * (dev / riskSum);
          }
        }
      }
      deathX.fill(0);
      for (const row of deathXX) row.fill(0);
    }
    k = j;
  }
  for (let i = 0; i < p; i++) for (let l = 0; l < i; l++) info[l]![i] = info[i]![l]!;
  return { loglik, score, info };
}

/**
 * The (unweighted) score residuals of every observation at the coefficients `beta`, in the units of `data.x` and the
 * sorted order (oracle/robust-behaviour.md 5.2; Therneau and Grambsch 2000, section 4.6). For each event time t of a
 * stratum with risk set R, deaths D (d of them, weight dw), S0 = sum_R w r, S1 = sum_R w r x and E0, E1 the same sums
 * over D, the time is split into M steps (M = d for Efron's ties, else 1); step m (f = m / M) has the risk sum
 * S0 - f E0, the mean xbar_m = (S1 - f E1) / (S0 - f E0) and the hazard increment lambda_m = (dw / M) / (S0 - f E0).
 * An observation j at risk but not dying at t gets -r_j sum_m lambda_m (x_j - xbar_m); a death gets
 * sum_m [(x_j - xbar_m) / M - (1 - f) r_j lambda_m (x_j - xbar_m)]. The increments of the times before an
 * observation's own are accumulated forward in time (C0 = sum lambda, C1 = sum lambda xbar), so that each residual
 * costs O(p) and not O(n p). Sum_j w_j s_j is the score vector.
 *
 * Each risk set is shifted by its own largest linear predictor M (as evaluate shifts the risk sums): S0 and S1 of a
 * time are held as e^-M times their values, and C0 and C1 in the units e^-M of the current time. A shift by the
 * stratum's largest linear predictor alone made every r of the later risk sets 0 once the linear predictors spanned
 * more than about 745 (an early death with a large one): S0 = 0 and the residuals NaN. M does not increase forward in
 * time, so the rescaling factors of C0 and C1 are at most 1 and only the negligible early terms can underflow. The
 * residuals do not depend on the scale of the weights, which are therefore taken in units of a power of 2 (exact)
 */
function scoreResiduals(data: SortedData, beta: readonly number[], efron: boolean): number[][] {
  const { time, event, x, stratumEnd } = data;
  const weight = scaleToUnit([data.weight]).groups[0]!;
  const n = time.length;
  const p = beta.length;
  const out = Array.from({ length: n }, () => new Array<number>(p).fill(0));
  const etaOf = (j: number): number => {
    let e = 0;
    for (let i = 0; i < p; i++) e += beta[i]! * x[j]![i]!;
    return e;
  };
  for (let start = 0; start < n; ) {
    let end = start;
    while (!stratumEnd[end]) end++;
    const eta: number[] = [];
    for (let j = start; j <= end; j++) eta.push(etaOf(j));
    // the first row of each group of tied times, and the risk sums at it (accumulated from the end of the stratum) in
    // units of e^-shift[g], shift[g] the largest linear predictor of the risk set (0 if it is not finite)
    const groupStart: number[] = [];
    for (let j = start; j <= end; j++) if (j === start || time[j] !== time[j - 1]) groupStart.push(j);
    const groupEnd = (g: number): number => (g + 1 < groupStart.length ? groupStart[g + 1]! : end + 1);
    const riskSum: number[] = new Array<number>(groupStart.length);
    const riskX: number[][] = new Array<number[]>(groupStart.length);
    const shift: number[] = new Array<number>(groupStart.length);
    let top = -Infinity;
    let s0 = 0;
    const s1 = new Array<number>(p).fill(0);
    for (let g = groupStart.length - 1; g >= 0; g--) {
      const before = Number.isFinite(top) ? top : 0;
      for (let j = groupStart[g]!; j < groupEnd(g); j++) top = Math.max(top, eta[j - start]!);
      const m = Number.isFinite(top) ? top : 0;
      // (nothing to rescale at the last time, where `before` is only a placeholder)
      if (g < groupStart.length - 1 && m !== before) {
        const f = Math.exp(before - m);
        s0 *= f;
        for (let i = 0; i < p; i++) s1[i]! *= f;
      }
      for (let j = groupStart[g]!; j < groupEnd(g); j++) {
        const wr = weight[j]! * Math.exp(eta[j - start]! - m);
        s0 += wr;
        for (let i = 0; i < p; i++) s1[i]! += wr * x[j]![i]!;
      }
      riskSum[g] = s0;
      riskX[g] = s1.slice();
      shift[g] = m;
    }
    // C0 = sum lambda and C1 = sum lambda xbar over the earlier event times, in units of e^-shift[g]
    let c0 = 0;
    const c1 = new Array<number>(p).fill(0);
    for (let g = 0; g < groupStart.length; g++) {
      const m = shift[g]!;
      if (g > 0 && m !== shift[g - 1]) {
        const f = Math.exp(m - shift[g - 1]!);
        c0 *= f;
        for (let i = 0; i < p; i++) c1[i]! *= f;
      }
      const from = groupStart[g]!;
      const to = groupEnd(g);
      // r_j in units of e^shift[g] (eta_j <= shift[g] for every j at risk)
      const r: number[] = [];
      for (let j = from; j < to; j++) r.push(Math.exp(eta[j - start]! - m));
      let d = 0;
      let dw = 0;
      let e0 = 0;
      const e1 = new Array<number>(p).fill(0);
      for (let j = from; j < to; j++) {
        if (!event[j]) continue;
        const wr = weight[j]! * r[j - from]!;
        d++;
        dw += weight[j]!;
        e0 += wr;
        for (let i = 0; i < p; i++) e1[i]! += wr * x[j]![i]!;
      }
      // the part of the earlier event times: -r_j (x_j C0 - C1)
      for (let j = from; j < to; j++) {
        const rj = r[j - from]!;
        const xj = x[j]!;
        const sj = out[j]!;
        for (let i = 0; i < p; i++) sj[i] = -rj * (xj[i]! * c0 - c1[i]!);
      }
      if (d === 0) continue;
      const steps = efron ? d : 1;
      for (let k = 0; k < steps; k++) {
        const f = k / steps;
        const s0m = riskSum[g]! - f * e0;
        const xbar = riskX[g]!.map((v, i) => (v - f * e1[i]!) / s0m);
        const lambda = dw / steps / s0m;
        for (let j = from; j < to; j++) {
          const rj = r[j - from]!;
          const xj = x[j]!;
          const sj = out[j]!;
          if (event[j]) {
            for (let i = 0; i < p; i++) {
              const dx = xj[i]! - xbar[i]!;
              sj[i]! += dx / steps - (1 - f) * rj * dx * lambda;
            }
          } else {
            for (let i = 0; i < p; i++) sj[i]! -= rj * (xj[i]! - xbar[i]!) * lambda;
          }
        }
        c0 += lambda;
        for (let i = 0; i < p; i++) c1[i]! += lambda * xbar[i]!;
      }
    }
    start = end + 1;
  }
  return out;
}

/**
 * Generalised Cholesky factorisation M = L D L' in place (D on the diagonal, L below it), pivots below the tolerance
 * set to 0. Returns the rank (negative when M is not non-negative definite).
 */
function cholFactor(m: number[][], tol: number): number {
  const p = m.length;
  let scale = 0;
  let anyPositive = false;
  for (let i = 0; i < p; i++) {
    const d = m[i]![i]!;
    if (d > 0) {
      if (!anyPositive || d > scale) scale = d;
      anyPositive = true;
    }
  }
  const limit = anyPositive ? scale * tol : tol;
  let rank = 0;
  let nonNegative = true;
  for (let i = 0; i < p; i++) {
    const pivot = m[i]![i]!;
    if (!Number.isFinite(pivot) || pivot < limit) {
      m[i]![i] = 0;
      if (pivot < -8 * limit) nonNegative = false;
      // the column dropped as a whole: its residual cross-products below were left (as survival's cholesky2) and the
      // forward substitution of cholSolve and cholInverse used them, so a nearly aliased column still entered the
      // solution and the variance (by about the tolerance; issue #13). With them 0 the fit is that without the column
      for (let j = i + 1; j < p; j++) m[j]![i] = 0;
      continue;
    }
    rank++;
    for (let j = i + 1; j < p; j++) {
      const t = m[j]![i]! / pivot;
      m[j]![i] = t;
      m[j]![j]! -= t * t * pivot;
      for (let k = j + 1; k < p; k++) m[k]![j]! -= t * m[k]![i]!;
    }
  }
  return nonNegative ? rank : -rank;
}

/** Solves M y = b with the factor of {@link cholFactor} (0 for the dropped pivots) */
function cholSolve(m: readonly number[][], b: readonly number[]): number[] {
  const p = m.length;
  const y = b.slice();
  for (let i = 0; i < p; i++) {
    let v = y[i]!;
    for (let j = 0; j < i; j++) v -= y[j]! * m[i]![j]!;
    y[i] = v;
  }
  for (let i = p - 1; i >= 0; i--) {
    if (m[i]![i] === 0) {
      y[i] = 0;
      continue;
    }
    let v = y[i]! / m[i]![i]!;
    for (let j = i + 1; j < p; j++) v -= y[j]! * m[j]![i]!;
    y[i] = v;
  }
  return y;
}

/** The (generalised) inverse from the factor of {@link cholFactor}, in place; returns the full symmetric matrix */
function cholInverse(m: number[][]): number[][] {
  const p = m.length;
  for (let i = 0; i < p; i++) {
    if (!(m[i]![i]! > 0)) continue;
    m[i]![i] = 1 / m[i]![i]!;
    for (let j = i + 1; j < p; j++) {
      m[j]![i] = -m[j]![i]!;
      for (let k = 0; k < i; k++) m[j]![k]! += m[j]![i]! * m[i]![k]!;
    }
  }
  for (let i = 0; i < p; i++) {
    if (m[i]![i] === 0) {
      for (let j = 0; j < p; j++) {
        m[i]![j] = 0;
        m[j]![i] = 0;
      }
      continue;
    }
    for (let j = i + 1; j < p; j++) {
      const t = m[j]![i]! * m[j]![j]!;
      m[i]![j] = t;
      for (let k = i; k < j; k++) m[i]![k]! += t * m[j]![k]!;
    }
  }
  for (let i = 0; i < p; i++) for (let j = 0; j < i; j++) m[i]![j] = m[j]![i]!;
  return m;
}

/** A test statistic with its upper chi-squared tail */
const chisqTest = (statistic: number, df: number): CoxphTest => ({
  statistic,
  df,
  pValue: pchisq(statistic, df, { lowerTail: false }),
});

/** R's result for data without events (survival's coxph returns it before fitting), with summary(fit)'s values */
function zeroEventResult(rows: readonly (readonly number[])[], p: number, warnings: string[]): CoxphResult {
  const n = rows.length;
  const nans = (): number[] => new Array<number>(p).fill(NaN);
  const test = chisqTest(0, 0);
  const se = new Array<number>(p).fill(0);
  const z = nans();
  const pz = nans();
  return {
    coefficients: nans(),
    var: Array.from({ length: p }, () => new Array<number>(p).fill(0)),
    loglik: [0, 0],
    score: 0,
    wald: 0,
    iter: 0,
    means: Array.from({ length: p }, (_, j) => mean(rows.map((row) => row[j]!))),
    n,
    nevent: 0,
    linearPredictors: new Array<number>(n).fill(0),
    se,
    z,
    p: pz,
    stdError: se,
    zValue: z,
    pValue: pz,
    lower: nans(),
    upper: nans(),
    logtest: test,
    sctest: { ...test },
    waldtest: { ...test },
    rsq: { rsq: 0, maxrsq: 0 },
    usedRobust: false,
    warnings,
  };
}

/**
 * Cox proportional hazards regression. Equivalent to R's `survival::coxph()`. As
 * `coxph(Surv(time, status) ~ x [+ strata(strata)], weights, ties, init, robust, cluster, control)` for right-censored
 * data, with the values of `summary(fit)`.
 *
 * With `robust` (by default when `cluster` is given or a case weight is not an integer) the variance is the robust
 * (Lin-Wei sandwich) one, summed over the clusters (each observation its own cluster without `cluster`), as R:
 * `var` is the robust variance and `naiveVar` the model-based one; `se` (and `stdError`) stay the model-based standard
 * errors (R's `se(coef)`), while `z`, `p`, the intervals `lower`/`upper`, `wald` and `waldtest` use the robust ones
 * (`robustSe`); `robscore` is the robust score test at `init`. The likelihood ratio and score tests and the R^2 ignore
 * the clustering.
 *
 * Rows with a missing time, status, covariate, weight or stratum are dropped. Times within sqrt(eps) of each other are
 * treated as tied. Covariates whose values all lie in `nocenter` are not centred; the others are centred by their
 * weighted means, which only shifts the linear predictors. R's warnings (non-convergence, possibly infinite
 * coefficients) are returned in `warnings`.
 *
 * @param time Follow-up times.
 * @param status 1 for an event, 0 for a censored time.
 * @param x The covariate matrix, one row per observation (at least one column).
 * @param options See {@link CoxphOptions}.
 * @throws TypeError if `robust` is not a boolean. RangeError for invalid arguments, among them an infinite weight
 * and a robust variance with fewer than two clusters.
 *
 * @example
 * ```ts
 * const fit = coxph([5, 3, 8, 1, 9, 4], [1, 1, 0, 1, 0, 1], [[1.2], [0.3], [-0.5], [2], [0.7], [0.1]]);
 * fit.coefficients;   // [1.0324]
 * fit.logtest.pValue; // 0.18817
 * ```
 *
 * @category Survival analysis
 */
export function coxph(
  time: readonly number[],
  status: readonly number[],
  x: readonly (readonly number[])[],
  options: CoxphOptions = {},
): CoxphResult {
  checkOptions(options, COXPH_KEYS, "coxph"); // generated: option-keys.mjs
  checkOptions(nestedOptions(options, "control"), COXPH_CONTROL_KEYS, "coxph", "control"); // generated: option-keys.mjs
  return reported("coxph", fitCoxph(time, status, x, options).result);
}

/**
 * The fit of {@link coxph}, and with the robust variance also the residuals it was made from (for the tests; not
 * exported from the package): R's `residuals(fit, type = "score")` (unweighted) and `residuals(fit, type =
 * "dfbeta")` (weighted), one row per observation used, in input order.
 *
 * @internal
 */
export function fitCoxph(
  time: readonly number[],
  status: readonly number[],
  x: readonly (readonly number[])[],
  options: CoxphOptions = {},
): { result: CoxphResult; scoreResiduals?: number[][]; dfbeta?: number[][] } {
  const { ties = "efron", weights, strata, init, control = {}, nocenter = [-1, 0, 1], confLevel = 0.95, robust, cluster } =
    options;
  const { eps = 1e-9, iterMax = 20, tolerChol = 2 ** -39 } = control;
  const tolerInf = control.tolerInf ?? Math.sqrt(eps);
  if (ties !== "efron" && ties !== "breslow") throw new RangeError(`invalid 'ties': ${String(ties)}`);
  if (!(eps > 0 && eps < Infinity)) throw new RangeError("'eps' must be a positive finite number");
  if (!(tolerChol > 0 && tolerChol < Infinity)) throw new RangeError("'tolerChol' must be a positive finite number");
  if (!(tolerInf > 0 && tolerInf < Infinity)) throw new RangeError("'tolerInf' must be a positive finite number");
  if (!(Number.isInteger(iterMax) && iterMax >= 0)) throw new RangeError("'iterMax' must be a non-negative integer");
  if (!(confLevel > 0 && confLevel < 1)) throw new RangeError("'confLevel' must be between 0 and 1");
  const nIn = time.length;
  if (status.length !== nIn || x.length !== nIn) throw new RangeError("'time', 'status' and 'x' must have the same length");
  if (weights !== undefined && weights.length !== nIn) throw new RangeError("'weights' must have the same length as 'time'");
  if (strata !== undefined && strata.length !== nIn) throw new RangeError("'strata' must have the same length as 'time'");
  if (cluster !== undefined && cluster.length !== nIn) throw new RangeError("'cluster' must have the same length as 'time'");
  if (robust !== undefined && typeof robust !== "boolean") throw new TypeError("'robust' must be true or false");
  const p = nIn === 0 ? 0 : x[0]!.length;
  if (p < 1) throw new RangeError("'x' must have at least one column");
  if (x.some((row) => row.length !== p)) throw new RangeError("the rows of 'x' must have the same length");
  if (init !== undefined && init.length !== p) throw new RangeError("'init' must have one value per column of 'x'");
  if (init?.some((v) => !Number.isFinite(v))) throw new RangeError("'init' must contain finite values");

  // 1. the rows used
  const keep: number[] = [];
  for (let i = 0; i < nIn; i++) {
    if (Number.isNaN(time[i]!) || Number.isNaN(status[i]!) || x[i]!.some((v) => Number.isNaN(v))) continue;
    if (weights !== undefined && Number.isNaN(weights[i]!)) continue;
    if (strata !== undefined && isMissingLabel(strata[i])) continue;
    if (cluster !== undefined && isMissingLabel(cluster[i])) continue;
    const s = status[i]!;
    if (s !== 0 && s !== 1) throw new RangeError("'status' must be 0 (censored) or 1 (event)");
    // a subject censored at Infinity is at risk throughout (R stops on any infinite time); an event cannot happen at an
    // infinite time, nor anything at -Infinity (as survdiff and survfit)
    if (time[i] === -Infinity || (time[i] === Infinity && s === 1)) throw new RangeError("event times must be finite");
    keep.push(i);
  }
  const n = keep.length;
  if (n === 0) throw new RangeError("no observations without missing values");
  if (keep.some((i) => x[i]!.some((v) => !Number.isFinite(v)))) throw new RangeError("'x' contains infinite values");
  const w = keep.map((i) => (weights === undefined ? 1 : weights[i]!));
  if (w.some((v) => !(v > 0))) throw new RangeError("Invalid weights, must be >0");
  // an infinite weight passes R's check (> 0) and counts as an integer there; the fit cannot use it (the sums become
  // Inf or NaN: NaN coefficients and a misleading "coefficient may be infinite" before this check)
  if (w.some((v) => v === Infinity)) throw new RangeError("'weights' must be finite");
  const warnings = new Warnings();
  // R's default: the robust variance with a cluster or a weight that is not an integer (silently)
  const useRobust = robust ?? (cluster !== undefined || w.some((v) => !Number.isInteger(v)));
  if (cluster !== undefined && !useRobust) warnings.add("cluster specified with robust=FALSE, cluster ignored");
  let nevent = 0;
  for (const i of keep) nevent += status[i]!;
  // no events: R's coxph returns before the fit (issue #472) with NA coefficients, a zero variance, zero log likelihood,
  // score, Wald statistic and iterations, and the unweighted column means of all covariates (nocenter ignored); `init`
  // is not an estimate here
  if (nevent === 0) return { result: zeroEventResult(keep.map((i) => x[i]!), p, warnings.list) };
  const mergedTime = mergeTiedTimes(keep.map((i) => time[i]!));
  let stratumOf = new Array<number>(n).fill(0);
  if (strata !== undefined) {
    // numeric labels with the same 15-digit text are one stratum, as in R's factor()
    const sl = numberLevels(strata);
    const labels = Array.from(new Set(keep.map((i) => sl[i] as GroupLabel))).sort(compareLabels);
    const index = new Map<GroupLabel, number>();
    labels.forEach((l, k) => index.set(l, k));
    stratumOf = keep.map((i) => index.get(sl[i] as GroupLabel)!);
  }
  const order = Array.from({ length: n }, (_, k) => k).sort(
    (a, b) => stratumOf[a]! - stratumOf[b]! || mergedTime[a]! - mergedTime[b]! || a - b,
  );

  // 2. centring and scaling (sums over the sorted observations)
  let totalWeight = 0;
  for (const v of w) totalWeight += v;
  const sortedW = order.map((k) => w[k]!);
  const xs = order.map((k) => x[keep[k]!]!.slice());
  const means = new Array<number>(p).fill(0);
  // the scale of column j is scales[j] 2^-shift[j]
  const scales = new Array<number>(p).fill(1);
  const shift = new Array<number>(p).fill(0);
  const exempt = new Set(nocenter);
  for (let j = 0; j < p; j++) {
    if (xs.every((row) => exempt.has(row[j]!))) continue;
    const column = xs.map((row) => row[j]!);
    const centreScale = (col: readonly number[]): { m: number; s: number; d: number[]; ok: boolean } => {
      let sum = 0;
      for (let k = 0; k < n; k++) sum += sortedW[k]! * col[k]!;
      const m = sum / totalWeight;
      let absSum = 0;
      const d = col.map((v, k) => {
        absSum += sortedW[k]! * Math.abs(v - m);
        return v - m;
      });
      const s = absSum === 0 ? 1 : totalWeight / absSum;
      return { m, s, d, ok: Number.isFinite(m) && s >= 2 ** -1022 && s < Infinity };
    };
    let fit = centreScale(column);
    // the sums overflow for covariates around 1e308, and the scale for subnormal ones (#87; the column became 0 or
    // NaN): then in the units 2^c of the column's largest value, where the scaled column (x - m) s is the same
    if (!fit.ok) {
      const { groups, k: c } = scaleToUnit([column]);
      fit = centreScale(groups[0]!);
      shift[j] = c;
    }
    for (let k = 0; k < n; k++) xs[k]![j] = fit.d[k]! * fit.s;
    means[j] = ldexp(fit.m, shift[j]!);
    scales[j] = fit.s;
  }
  const data: SortedData = {
    time: order.map((k) => mergedTime[k]!),
    event: order.map((k) => status[keep[k]!] === 1),
    weight: sortedW,
    x: xs,
    stratumEnd: order.map((k, r) => r === n - 1 || stratumOf[order[r + 1]!] !== stratumOf[k]),
  };
  const efron = ties === "efron";

  // 3.-5. Newton-Raphson on the scaled coefficients
  let beta = init === undefined ? new Array<number>(p).fill(0) : init.map((v, j) => ldexp(v / scales[j]!, shift[j]!));
  let ev = evaluate(data, beta, efron);
  const loglik: [number, number] = [ev.loglik, ev.loglik];
  let factor = ev.info.map((row) => row.slice());
  let rank = cholFactor(factor, tolerChol);
  let step = cholSolve(factor, ev.score);
  let scoreTest = 0;
  for (let i = 0; i < p; i++) scoreTest += ev.score[i]! * step[i]!;
  let iter = 0;
  let inverse: number[][];
  let ranOut = false;
  if (iterMax === 0 || !Number.isFinite(ev.loglik)) {
    inverse = cholInverse(factor);
  } else {
    let best = ev.loglik;
    let next = beta.map((b, i) => b + step[i]!);
    let halvings = 0;
    let converged = false;
    for (iter = 1; iter <= iterMax; iter++) {
      ev = evaluate(data, next, efron);
      factor = ev.info.map((row) => row.slice());
      rank = cholFactor(factor, tolerChol);
      const finite =
        Number.isFinite(ev.loglik) && ev.score.every(Number.isFinite) && ev.info.every((row) => row.every(Number.isFinite));
      // an unchanged log likelihood is converged too (both 0, as for coxph([1], [1], [[0]]), made the ratio 0/0 = NaN and
      // ran out of iterations, as R)
      if (finite && (ev.loglik === best || Math.abs(1 - best / ev.loglik) <= eps)) {
        converged = true;
        loglik[1] = ev.loglik;
        beta = next;
        break;
      }
      if (!finite || ev.loglik < best) {
        halvings++;
        next = next.map((b, i) => (b + halvings * beta[i]!) / (halvings + 1));
      } else {
        halvings = 0;
        best = ev.loglik;
        loglik[1] = best;
        step = cholSolve(factor, ev.score);
        beta = next;
        next = next.map((b, i) => b + step[i]!);
      }
    }
    if (converged) {
      inverse = cholInverse(factor);
    } else {
      iter = iterMax + 1;
      ranOut = true;
      if (iterMax > 1) {
        // R recomputes at the last accepted point and applies the inverse step without factorising: that step reads
        // the triangle the accumulation leaves at zero, so only the diagonal survives (off-diagonal entries -0)
        ev = evaluate(data, beta, efron);
        loglik[1] = ev.loglik;
        inverse = ev.info.map((row, i) => row.map((_, j) => (i === j ? (row[i]! > 0 ? 1 / row[i]! : 0) : -0)));
      } else {
        inverse = cholInverse(factor);
      }
    }
  }

  // back to the original scale. Each column's scale s_j is split as s~_j 2^e_j (s~_j in [1, 2)): the coefficients,
  // the variance and the score are first formed in units of 2^e_j, where they stay in range whatever the units of the
  // covariates, and scaled back by powers of 2 only for the output. Unitless quantities (z, the Wald test, the check
  // for infinite coefficients) are computed in these units: the same bits as in the original units when nothing
  // overflows, and the Wald test's Cholesky pivots are not dropped because the covariates have different units
  const scaleExpo = scales.map((s) => Math.floor(Math.log2(s)));
  const mant = scales.map((s, j) => ldexp(s, -scaleExpo[j]!));
  const expo = scaleExpo.map((e, j) => e - shift[j]!);
  const coefUnit = beta.map((b, j) => b * mant[j]!);
  const uUnit = ev.score.map((v, j) => v / mant[j]!);
  const varUnit = inverse.map((row, i) => row.map((v, j) => v * mant[i]! * mant[j]!));
  const internal = coefUnit.map((c, j) => ldexp(c, expo[j]!));
  const variance = varUnit.map((row, i) => row.map((v, j) => ldexp(v, expo[i]! + expo[j]!)));

  // 6. output
  const coefficients = internal.slice();
  if (iterMax > 0 && Math.abs(rank) < p) {
    for (let j = 0; j < p; j++) if (inverse[j]![j] === 0) coefficients[j] = NaN;
  }
  let centre = 0;
  for (let j = 0; j < p; j++) centre += internal[j]! * means[j]!;
  const linearPredictors = keep.map((i) => {
    let s = 0;
    for (let j = 0; j < p; j++) s += x[i]![j]! * internal[j]!;
    return s - centre;
  });
  if (iterMax > 1) {
    // abs(u' var) in units of 2^-e_j
    const infinity = varUnit.map((_, j) => {
      let s = 0;
      for (let i = 0; i < p; i++) s += uUnit[i]! * varUnit[i]![j]!;
      return Math.abs(s);
    });
    if (ranOut) {
      warnings.add("Ran out of iterations and did not converge");
      if (maxOf(linearPredictors) > 500 || infinity.some((f) => !Number.isFinite(f))) {
        warnings.add("one or more coefficients may be infinite");
      }
    } else {
      const flagged: number[] = [];
      for (let j = 0; j < p; j++) {
        const f = infinity[j]!;
        if (!Number.isFinite(uUnit[j]!) || (ldexp(f, expo[j]!) > eps && f > tolerInf * Math.abs(coefUnit[j]!))) flagged.push(j + 1);
      }
      if (flagged.length > 0) {
        warnings.add(`Loglik converged before variable  ${flagged.join(",")} ; coefficient may be infinite. `);
      }
    }
  }

  // 7. the robust variance (oracle/robust-behaviour.md 5.3, 5.4; Lin and Wei 1989; Therneau and Grambsch 2000,
  // chapter 7), skipped (as R) when every coefficient is NaN. Formed in the units of 2^e_j as the naive variance: a
  // score residual in those units is the scaled one divided by the mantissa of the scale (as the score above)
  const used = coefficients.map((c, j) => (Number.isNaN(c) ? -1 : j)).filter((j) => j >= 0);
  const k = used.length;
  let robustUnit: number[][] | undefined;
  let rscore = 0;
  let residuals: { scoreResiduals: number[][]; dfbeta: number[][] } | undefined;
  if (useRobust && k > 0) {
    // the cluster of each sorted observation (each its own without a cluster); numeric labels as R's factor()
    let clusterOf: number[] = order.map((_, r) => r);
    let nClusters = n;
    if (cluster !== undefined) {
      const cl = numberLevels(cluster);
      const index = new Map<GroupLabel, number>();
      clusterOf = order.map((kk) => {
        const label = cl[keep[kk]!] as GroupLabel;
        let c = index.get(label);
        if (c === undefined) {
          c = index.size;
          index.set(label, c);
        }
        return c;
      });
      nClusters = index.size;
    }
    // R fails here with an unrelated message ("(subscript) logical subscript too long")
    if (nClusters < 2) throw new RangeError("at least two clusters are needed for the robust variance");
    const toUnit = (rows: number[][]): number[][] => rows.map((row) => row.map((v, j) => v / mant[j]!));
    // dfbeta_j = w_j s_j' V_naive (V_naive with zero rows and columns for NaN coefficients), summed by cluster
    const sUnit = toUnit(scoreResiduals(data, beta, efron));
    const dfbeta = sUnit.map((s, r) =>
      varUnit.map((_, l) => {
        let v = 0;
        for (let i = 0; i < p; i++) v += s[i]! * varUnit[i]![l]!;
        return sortedW[r]! * v;
      }),
    );
    const clusterSums = (rows: readonly number[][]): number[][] => {
      const sums = Array.from({ length: nClusters }, () => new Array<number>(p).fill(0));
      rows.forEach((row, r) => {
        const sum = sums[clusterOf[r]!]!;
        for (let i = 0; i < p; i++) sum[i]! += row[i]!;
      });
      return sums;
    };
    const crossProduct = (rows: readonly number[][]): number[][] => {
      const m = Array.from({ length: p }, () => new Array<number>(p).fill(0));
      for (const row of rows) for (let i = 0; i < p; i++) for (let j = 0; j < p; j++) m[i]![j]! += row[i]! * row[j]!;
      return m;
    };
    robustUnit = crossProduct(clusterSums(dfbeta));
    // the robust score test at init (0 without it): T_c = the cluster sums of w_j s_j(init), u = sum_c T_c,
    // rscore = u' (sum_c T_c T_c')^- u by the generalised Cholesky factorisation (over all p columns, as R). rscore
    // does not depend on the scale of the weights, and u u' and T_c T_c' scale as its square (overflowing or
    // underflowing for weights around 2^+-512): T_c is formed from the weights in units of a power of 2 (exact)
    const wUnit = scaleToUnit([sortedW]).groups[0]!;
    const beta0 = init === undefined ? new Array<number>(p).fill(0) : init.map((v, j) => ldexp(v / scales[j]!, shift[j]!));
    const t = clusterSums(toUnit(scoreResiduals(data, beta0, efron)).map((s, r) => s.map((v) => wUnit[r]! * v)));
    const u = new Array<number>(p).fill(0);
    for (const row of t) for (let i = 0; i < p; i++) u[i]! += row[i]!;
    const sMatrix = crossProduct(t);
    if (p === 1) {
      rscore = (u[0]! * u[0]!) / sMatrix[0]![0]!;
    } else {
      cholFactor(sMatrix, tolerChol);
      const y = cholSolve(sMatrix, u);
      for (let i = 0; i < p; i++) rscore += u[i]! * y[i]!;
    }
    // the residuals in the original units and the input order
    const scoreOut: number[][] = new Array<number[]>(n);
    const dfbetaOut: number[][] = new Array<number[]>(n);
    order.forEach((kk, r) => {
      scoreOut[kk] = sUnit[r]!.map((v, j) => ldexp(v, -expo[j]!));
      dfbetaOut[kk] = dfbeta[r]!.map((v, j) => ldexp(v, expo[j]!));
    });
    residuals = { scoreResiduals: scoreOut, dfbeta: dfbetaOut };
  }
  const usedRobust = robustUnit !== undefined;
  // the variance of z, p, the intervals and the Wald test: the robust one when used (the se stays the naive one, as R)
  const testUnit = robustUnit ?? varUnit;

  // 8. tests and the summary
  // (in units of 2^e_j)
  const b = used.map((j) => coefUnit[j]! - (init === undefined ? 0 : ldexp(init[j]!, -expo[j]!)));
  let wald = 0;
  if (k === 1) {
    wald = (b[0]! * b[0]!) / testUnit[used[0]!]![used[0]!]!;
  } else if (k > 1) {
    const v = used.map((i) => used.map((j) => testUnit[i]![j]!));
    cholFactor(v, tolerChol);
    const y = cholSolve(v, b);
    for (let i = 0; i < k; i++) wald += b[i]! * y[i]!;
  }
  // (for alpha below 1e-8 the upper probability itself: 1 - alpha loses its digits and rounds to 1 below 1.1e-16; review 58)
  const a2 = (1 - confLevel) / 2;
  const q = a2 < 1e-8 ? qnorm(a2, { lowerTail: false }) : qnorm((1 + confLevel) / 2);
  const seOf = (vUnit: readonly number[][]): { unit: number[]; se: number[] } => {
    const unit = vUnit.map((row, j) => Math.sqrt(row[j]!));
    return { unit, se: unit.map((v, j) => ldexp(v, expo[j]!)) };
  };
  const se = seOf(varUnit).se;
  const { unit: testSeUnit, se: testSe } = seOf(testUnit);
  const z = coefficients.map((c, j) => (Number.isNaN(c) ? c : coefUnit[j]!) / testSeUnit[j]!);
  const pz = z.map((v) => pchisq(v * v, 1, { lowerTail: false }));
  const lower = coefficients.map((c, j) => Math.exp(c - q * testSe[j]!));
  const upper = coefficients.map((c, j) => Math.exp(c + q * testSe[j]!));
  const lr = -2 * (loglik[0] - loglik[1]);
  const robustVariance = robustUnit?.map((row, i) => row.map((v, j) => ldexp(v, expo[i]! + expo[j]!)));
  const result: CoxphResult = {
    coefficients,
    var: robustVariance ?? variance,
    loglik,
    score: scoreTest,
    wald,
    iter,
    means,
    n,
    nevent,
    linearPredictors,
    se,
    z,
    p: pz,
    stdError: se,
    zValue: z,
    pValue: pz,
    lower,
    upper,
    logtest: chisqTest(lr, k),
    sctest: chisqTest(scoreTest, k),
    waldtest: chisqTest(wald, k),
    rsq: { rsq: 1 - Math.exp(-lr / n), maxrsq: 1 - Math.exp((2 * loglik[0]) / n) },
    usedRobust,
    ...(usedRobust ? { naiveVar: variance, robustSe: testSe, rscore, robscore: chisqTest(rscore, k) } : {}),
    warnings: warnings.list,
  };
  return { result, ...residuals };
}
