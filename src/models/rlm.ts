type PsiOutput = number | boolean;
type PsiInput = number | Sample;
type PsiResult = PsiOutput | PsiOutput[];

/** Huber's psi function. Equivalent to R's `MASS::psi.huber()`.
*
* @param u Standardised residuals.
* @param options Tuning constant and output selection.
* @returns The IRLS weight psi(u)/u, or psi'(u) when deriv is 1.
*
* @example
* ```ts
* psiHuber([-2, 0, 1, 2]); // [0.6725, 1, 1, 0.6725]
* ```
*
* @category Regression
*/
export function psiHuber(u: PsiInput, options: RlmPsiHuberOptions = {}): PsiResult {
 checkOptions(options, PSI_HUBER_KEYS, "psiHuber"); // generated: option-keys.mjs
 const k = options.k ?? 1.345;
 if (!(k > 0) || !Number.isFinite(k)) throw new RangeError("k must be positive and finite");
 const one = (v: number): PsiOutput => options.deriv === 1
   ? Math.abs(v) <= k
   : (v === 0 || Math.abs(v) <= k ? 1 : k / Math.abs(v));
 return typeof u === "number" ? one(u) : Array.from(u, one);
}

/** Hampel's three-part psi function. Equivalent to R's `MASS::psi.hampel()`.
*
* @param u Standardised residuals.
* @param options Three tuning points and output selection.
* @returns The IRLS weight psi(u)/u, or psi'(u) when deriv is 1.
*
* @example
* ```ts
* psiHampel([-5, -2, 0, 5, 9]); // [0.6, 1, 1, 0.5, 0]
* ```
*
* @category Regression
*/
export function psiHampel(u: PsiInput, options: RlmPsiHampelOptions = {}): number | number[] {
 checkOptions(options, PSI_HAMPEL_KEYS, "psiHampel"); // generated: option-keys.mjs
 const a = options.a ?? 2, b = options.b ?? 4, c = options.c ?? 8;
 if (!(a > 0 && a < b && b < c) || ![a, b, c].every(Number.isFinite)) {
   throw new RangeError("psiHampel requires 0 < a < b < c");
 }
 const one = (v: number): number => {
   const z = Math.abs(v);
   if (options.deriv === 1) {
     if (z <= a) return 1;
     if (z <= b) return 0;
     if (z < c) return -a / (c - b);
     return 0;
   }
   if (z === 0 || z <= a) return 1;
   if (z <= b) return a / z;
   if (z < c) return a * (c - z) / ((c - b) * z);
   return 0;
 };
 return typeof u === "number" ? one(u) : Array.from(u, one);
}

/** Tukey's bisquare psi function. Equivalent to R's `MASS::psi.bisquare()`.
*
* @param u Standardised residuals.
* @param options Tuning constant and output selection.
* @returns The IRLS weight psi(u)/u, or psi'(u) when deriv is 1.
*
* @example
* ```ts
* psiBisquare([-5, 0, 2]); // [0, 1, 0.668733411888633]
* ```
*
* @category Regression
*/
export function psiBisquare(u: PsiInput, options: RlmPsiBisquareOptions = {}): number | number[] {
 checkOptions(options, PSI_BISQUARE_KEYS, "psiBisquare"); // generated: option-keys.mjs
 const c = options.c ?? 4.685;
 if (!(c > 0) || !Number.isFinite(c)) throw new RangeError("c must be positive and finite");
 const one = (v: number): number => {
   const t = v / c, z = Math.abs(t);
   if (!(z < 1)) return 0;
   const q = 1 - t * t;
   return options.deriv === 1 ? q * (1 - 5 * t * t) : q * q;
 };
 return typeof u === "number" ? one(u) : Array.from(u, one);
}

