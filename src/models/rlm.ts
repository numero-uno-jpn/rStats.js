function median(values: readonly number[]): number {
 if (values.length === 0) return NaN;
 const sorted = Array.from(values).sort((a, b) => a - b);
 const m = Math.floor(sorted.length / 2);
 return sorted.length % 2 ? sorted[m]! : (sorted[m - 1]! + sorted[m]!) / 2;
}

function weightedMedian(values: readonly number[], weights: readonly number[]): number {
 const pairs = values.map((value, i) => ({ value, weight: weights[i]! })).filter((p) => p.weight > 0);
 pairs.sort((a, b) => a.value - b.value);
 const total = pairs.reduce((sum, p) => sum + p.weight, 0);
 let cumulative = 0;
 for (let i = 0; i < pairs.length; i++) {
   const p = pairs[i]!;
   cumulative += p.weight;
   if (cumulative > total / 2) return p.value;
   if (cumulative === total / 2) {
     const next = pairs[i + 1];
     return next === undefined ? p.value : (p.value + next.value) / 2;
   }
 }
 return pairs[pairs.length - 1]?.value ?? NaN;
}

function psiWeight(psi: RlmPsi, u: number, options: RlmModel): number {
 if (psi === "huber") return Number(psiHuber(u, { k: options.k }));
 if (psi === "hampel") return psiHampel(u, { a: options.a, b: options.b, c: options.c }) as number;
 return psiBisquare(u, { c: options.c }) as number;
}

function psiScore(psi: RlmPsi, u: number, model: RlmModel): number {
 return u * psiWeight(psi, u, model);
}

function psiDerivative(psi: RlmPsi, u: number, model: RlmModel): number {
 if (psi === "huber") return psiHuber(u, { k: model.k, deriv: 1 }) ? 1 : 0;
 if (psi === "hampel") return psiHampel(u, { a: model.a, b: model.b, c: model.c, deriv: 1 }) as number;
 return psiBisquare(u, { c: model.c, deriv: 1 }) as number;
}

function effectiveResiduals(residuals: readonly number[], weights: readonly number[], method: "inv" | "case"): { u: number[]; q: number[]; n: number } {
 if (method === "inv") return { u: residuals.map((r, i) => Math.sqrt(weights[i]!) * r), q: weights.map(() => 1), n: residuals.length };
 return { u: residuals.slice(), q: weights.slice(), n: weights.reduce((sum, w) => sum + w, 0) };
}

function proposal2Constant(k: number): number {
  const upper = pnorm(k) as number;
  const density = Math.exp(-0.5 * k * k) / Math.sqrt(2 * Math.PI);
  return 2 * upper - 1 - 2 * k * density + 2 * k * k * (1 - upper);
}

function proposalScale(residuals: readonly number[], weights: readonly number[], method: "inv" | "case", k2: number, p: number): number {
 const transformed = effectiveResiduals(residuals, weights, method);
 const absolute = transformed.u.map(Math.abs);
 const q = transformed.q;
 const denominator = transformed.n - p;
 if (!(denominator > 0)) return NaN;
 const target = proposal2Constant(k2);
 // The supplied stackloss-scale-huber check distinguishes the divisor: MASS fitTight
 // satisfies sum(chi)/(n-p) - beta = -1.1e-15, while sum(chi)/n - beta = -0.135.
 // The rStats.js fit satisfies the latter equation (2.2e-16) and has the wrong scale.
 // Thus Proposal 2 uses the residual degrees of freedom, not the raw observation count.
 // Weighted case/inverse extensions (N-p / n-p respectively) are mathematically natural
 // but are not directly covered by a weighted Proposal 2 fixture.
 const meanChi = (scale: number): number => {
   let sum = 0;
   for (let i = 0; i < absolute.length; i++) {
     const z = absolute[i]! / scale;
     sum += q[i]! * Math.min(z * z, k2 * k2);
   }
   return sum / denominator;
 };
 let lo = 0, hi = Math.max(1, median(absolute));
 if (!(hi > 0)) return 0;
 while (meanChi(hi) > target && hi < Number.MAX_VALUE / 4) hi *= 2;
 for (let i = 0; i < 100; i++) {
   const mid = lo + (hi - lo) / 2;
   if (meanChi(mid) > target) lo = mid;
   else hi = mid;
 }
 return (lo + hi) / 2;
}

function robustScale(residuals: readonly number[], weights: readonly number[], method: "inv" | "case", scaleEst: "MAD" | "Huber" | "proposal 2", k2: number, p: number): number {
 if (scaleEst === "MAD") {
   const transformed = effectiveResiduals(residuals, weights, method);
   const values = transformed.u.map(Math.abs);
   const m = method === "case" ? weightedMedian(values, transformed.q) : median(values);
   // The recorded reference fits use the rounded normal-consistency constant 0.6745:
   // their public scale agrees with median(|residual|) / 0.6745 to the fixture's full precision.
   return m / 0.6745;
 }
 return proposalScale(residuals, weights, method, k2, p);
}

function weightedLeastSquares(x: readonly (readonly number[])[], y: readonly number[], weights: readonly number[]): number[] {
 const rows: number[][] = [];
 const response: number[] = [];
 for (let i = 0; i < x.length; i++) {
   const w = weights[i]!;
   if (!(w > 0)) continue;
   const sw = Math.sqrt(w);
   rows.push(x[i]!.map((v) => v * sw));
   response.push(y[i]! * sw);
 }
 if (rows.length < (x[0]?.length ?? 0)) throw new Error("'x' is singular: singular fits are not implemented in 'rlm'");
 const decomposition = qr(rows, { tol: 1e-12 });
 const p = x[0]?.length ?? 0;
 if (decomposition.rank !== p) throw new Error("'x' is singular: singular fits are not implemented in 'rlm'");
 return qrCoef(decomposition, response) as number[];
}

function crossProduct(x: readonly (readonly number[])[], weights: readonly number[]): number[][] {
 const p = x[0]?.length ?? 0;
 const out = Array.from({ length: p }, () => new Array<number>(p).fill(0));
 for (let i = 0; i < x.length; i++) {
   const w = weights[i]!;
   if (w === 0) continue;
   for (let j = 0; j < p; j++) for (let k = 0; k <= j; k++) {
     out[k]![j] = out[k]![j]! + w * x[i]![k]! * x[i]![j]!;
   }
 }
 for (let j = 0; j < p; j++) for (let k = 0; k < j; k++) out[j]![k] = out[k]![j]!;
 return out;
}

function covarianceScale(residuals: readonly number[], scale: number, weights: readonly number[], model: RlmModel, p: number): { stddev: number; covUnscaled: number[][] } {
 const { u, q, n } = effectiveResiduals(residuals, weights, model.wtMethod);
 const d = u.map((v) => psiDerivative(model.psi, v / scale, model));
 const meanD = q.reduce((sum, w, i) => sum + w * d[i]!, 0) / n;
 let varianceD = 0;
 for (let i = 0; i < d.length; i++) varianceD += q[i]! * (d[i]! - meanD) ** 2;
 varianceD /= n - 1;
 const kappa = 1 + (p / n) * varianceD / (meanD * meanD);
 let score2 = 0;
 for (let i = 0; i < u.length; i++) score2 += q[i]! * psiScore(model.psi, u[i]! / scale, model) ** 2;
 const stddev = scale * kappa * Math.sqrt(score2 / (n - p)) / meanD;
 const designWeights = weights;
 const covUnscaled = chol2inv(chol(crossProduct(model.x, designWeights)));
 return { stddev, covUnscaled };
}


const S_RHO_C = 1.547;
const MAX_SUBSET_CANDIDATES = 1024;
const MAX_CANDIDATE_ROW_EVALUATIONS = 250_000;

interface RobustStart {
 coefficients: number[];
 objective: number;
 evaluated: number;
 total: bigint;
 warning?: string;
}

function binomial(n: number, k: number): bigint {
 if (k < 0 || k > n) return 0n;
 const m = Math.min(k, n - k);
 let value = 1n;
 for (let i = 1; i <= m; i++) value = value * BigInt(n - m + i) / BigInt(i);
 return value;
}

function unrankSubset(n: number, p: number, initialRank: bigint): number[] {
 let rank = initialRank;
 const subset: number[] = [];
 let first = 0;
 for (let position = 0; position < p; position++) {
   const remaining = p - position - 1;
   let selected = false;
   for (let candidate = first; candidate <= n - remaining - 1; candidate++) {
     const count = binomial(n - candidate - 1, remaining);
     if (rank < count) {
       subset.push(candidate);
       first = candidate + 1;
       selected = true;
       break;
     }
     rank -= count;
   }
   if (!selected) throw new RangeError("invalid deterministic subset rank");
 }
 return subset;
}

function deterministicSubsets(n: number, p: number): { subsets: number[][]; total: bigint; exhaustive: boolean } {
 const total = binomial(n, p);
 const budget = Math.max(1, Math.min(MAX_SUBSET_CANDIDATES, Math.floor(MAX_CANDIDATE_ROW_EVALUATIONS / n)));
 const count = total < BigInt(budget) ? Number(total) : budget;
 const subsets: number[][] = [];
 for (let i = 0; i < count; i++) {
   const rank = count === 1 ? 0n : BigInt(i) * (total - 1n) / BigInt(count - 1);
   subsets.push(unrankSubset(n, p, rank));
 }
 return { subsets, total, exhaustive: BigInt(count) === total };
}

function residualVector(x: readonly (readonly number[])[], y: readonly number[], coefficients: readonly number[]): number[] {
 return y.map((value, i) => value - x[i]!.reduce((sum, v, j) => sum + v * coefficients[j]!, 0));
}

function effectiveAbsoluteResiduals(residuals: readonly number[], weights: readonly number[], wtMethod: "inv" | "case"): number[] {
 return residuals.map((value, i) => Math.abs(wtMethod === "inv" ? Math.sqrt(weights[i]!) * value : value));
}

function ltsObjective(residuals: readonly number[], h: number, weights: readonly number[], wtMethod: "inv" | "case"): number {
 const squares = effectiveAbsoluteResiduals(residuals, weights, wtMethod).map((value) => value * value);
 squares.sort((a, b) => a - b);
 let total = 0;
 for (let i = 0; i < h; i++) total += squares[i]!;
 return total;
}

function ltsStart(
 x: readonly (readonly number[])[],
 y: readonly number[],
 observationWeights: readonly number[],
 wtMethod: "inv" | "case",
): RobustStart {
 if (wtMethod === "case" && observationWeights.some((value) => value !== 1)) {
   throw new RangeError("deterministic LTS initialization does not support case weights");
 }
 const n = y.length, p = x[0]?.length ?? 0;
 const h = Math.floor((n + p) / 2);
 if (h < p) throw new RangeError("not enough observations for a high-breakdown LTS start");
 const search = deterministicSubsets(n, p);
 const candidates: { coefficients: number[]; objective: number; rank: number }[] = [];
 for (let rank = 0; rank < search.subsets.length; rank++) {
   const indices = search.subsets[rank]!;
   try {
     const beta = weightedLeastSquares(
       indices.map((i) => x[i]!),
       indices.map((i) => y[i]!),
       indices.map((i) => observationWeights[i]!),
     );
     const objective = ltsObjective(residualVector(x, y, beta), h, observationWeights, wtMethod);
     if (Number.isFinite(objective)) candidates.push({ coefficients: beta, objective, rank });
   } catch {
     // A singular elemental subset cannot identify the regression coefficients.
   }
 }
 candidates.sort((a, b) => a.objective - b.objective || a.rank - b.rank);
 let best: { coefficients: number[]; objective: number } | undefined;
 for (const candidate of candidates.slice(0, 16)) {
   let beta = candidate.coefficients;
   let objective = candidate.objective;
   for (let iteration = 0; iteration < 50; iteration++) {
     const residuals = residualVector(x, y, beta);
     const order = effectiveAbsoluteResiduals(residuals, observationWeights, wtMethod)
       .map((value, index) => ({ value, index }))
       .sort((a, b) => a.value - b.value || a.index - b.index);
     const selected = order.slice(0, h).map((entry) => entry.index).sort((a, b) => a - b);
     let next: number[];
     try {
       next = weightedLeastSquares(
         selected.map((i) => x[i]!),
         selected.map((i) => y[i]!),
         selected.map((i) => observationWeights[i]!),
       );
     } catch {
       break;
     }
     const nextObjective = ltsObjective(residualVector(x, y, next), h, observationWeights, wtMethod);
     if (nextObjective > objective + 1e-12 * Math.max(1, objective)) break;
     const same = next.every((value, j) => Math.abs(value - beta[j]!) <= 1e-12 * Math.max(1, Math.abs(value)));
     beta = next;
     objective = nextObjective;
     if (same) break;
   }
   if (best === undefined || objective < best.objective) best = { coefficients: beta, objective };
 }
 if (best === undefined) throw new Error("deterministic LTS search found no full-rank subset");
 return {
   ...best,
   evaluated: search.subsets.length,
   total: search.total,
   ...(search.exhaustive ? {} : {
     warning: "deterministic LTS search examined " + search.subsets.length + " of " + search.total.toString() + " elemental subsets; a high-breakdown start is not certified",
   }),
 };
}

function sRhoValue(u: number): number {
 const absolute = Math.abs(u);
 const cap = S_RHO_C * S_RHO_C;
 if (absolute >= S_RHO_C) return cap / 6;
 const ratio = u / S_RHO_C;
 const square = ratio * ratio;
 return (u * u / 2) * (1 - square + square * square / 3);
}

function sRhoConstant(): number {
 const c = S_RHO_C;
 const density = Math.exp(-0.5 * c * c) / Math.sqrt(2 * Math.PI);
 const inside = 2 * (pnorm(c) as number) - 1;
 const moment2 = inside - 2 * c * density;
 const moment4 = 3 * inside - 2 * (c ** 3 + 3 * c) * density;
 const moment6 = 15 * inside - 2 * (c ** 5 + 5 * c ** 3 + 15 * c) * density;
 return moment2 / 2 - moment4 / (2 * c * c) + moment6 / (6 * c ** 4) + c * c / 6 * (1 - inside);
}

function sRhoScale(residuals: readonly number[], weights: readonly number[], wtMethod: "inv" | "case"): number {
 const absolute = effectiveAbsoluteResiduals(residuals, weights, wtMethod);
 const target = sRhoConstant();
 const n = absolute.length;
 if (n === 0) return NaN;
 const maximumMean = absolute.filter((value) => value > 0).length * S_RHO_C * S_RHO_C / (6 * n);
 if (maximumMean <= target) return 0;
 const equation = (scale: number): number => {
   let sum = 0;
   for (const value of absolute) sum += sRhoValue(value / scale);
   return sum / n - target;
 };
 let lo = 0;
 let hi = Math.max(1, median(absolute));
 while (equation(hi) > 0 && hi < Number.MAX_VALUE / 4) hi *= 2;
 if (!Number.isFinite(hi)) return NaN;
 for (let iteration = 0; iteration < 64; iteration++) {
   const mid = lo + (hi - lo) / 2;
   if (equation(mid) > 0) lo = mid;
   else hi = mid;
 }
 return (lo + hi) / 2;
}

function sStart(
 x: readonly (readonly number[])[],
 y: readonly number[],
 observationWeights: readonly number[],
 wtMethod: "inv" | "case",
): RobustStart {
 if (wtMethod === "case" && observationWeights.some((value) => value !== 1)) {
   throw new RangeError("MM estimation does not support case weights");
 }
 const n = y.length, p = x[0]?.length ?? 0;
 if (n <= p) throw new RangeError("not enough observations for a high-breakdown S start");
 const search = deterministicSubsets(n, p);
 const candidates: { coefficients: number[]; objective: number; rank: number }[] = [];
 for (let rank = 0; rank < search.subsets.length; rank++) {
   const indices = search.subsets[rank]!;
   try {
     const beta = weightedLeastSquares(
       indices.map((i) => x[i]!),
       indices.map((i) => y[i]!),
       indices.map((i) => observationWeights[i]!),
     );
     const scale = sRhoScale(residualVector(x, y, beta), observationWeights, wtMethod);
     if (Number.isFinite(scale)) candidates.push({ coefficients: beta, objective: scale, rank });
   } catch {
     // A singular elemental subset cannot identify the regression coefficients.
   }
 }
 candidates.sort((a, b) => a.objective - b.objective || a.rank - b.rank);
 let best: { coefficients: number[]; objective: number } | undefined;
 for (const candidate of candidates.slice(0, 16)) {
   let beta = candidate.coefficients;
   let scale = candidate.objective;
   for (let iteration = 0; iteration < 50; iteration++) {
     if (!(scale > 0)) break;
     const residuals = residualVector(x, y, beta);
     const absolute = effectiveAbsoluteResiduals(residuals, observationWeights, wtMethod);
     const refinementWeights = absolute.map((value, i) => {
       const ratio = value / (scale * S_RHO_C);
       return ratio < 1 ? (1 - ratio * ratio) ** 2 * observationWeights[i]! : 0;
     });
     if (refinementWeights.filter((value) => value > 0).length < p) break;
     let next: number[];
     try {
       next = weightedLeastSquares(x, y, refinementWeights);
     } catch {
       break;
     }
     const nextScale = sRhoScale(residualVector(x, y, next), observationWeights, wtMethod);
     if (!(nextScale >= 0) || nextScale > scale + 1e-12 * Math.max(1, scale)) break;
     const same = next.every((value, j) => Math.abs(value - beta[j]!) <= 1e-12 * Math.max(1, Math.abs(value)));
     beta = next;
     scale = nextScale;
     if (same) break;
   }
   if (best === undefined || scale < best.objective) best = { coefficients: beta, objective: scale };
 }
 if (best === undefined) throw new Error("deterministic S search found no full-rank subset");
 return {
   ...best,
   evaluated: search.subsets.length,
   total: search.total,
   ...(search.exhaustive ? {} : {
     warning: "deterministic S search examined " + search.subsets.length + " of " + search.total.toString() + " elemental subsets; a high-breakdown start is not certified",
   }),
 };
}

/** Robust M regression. Equivalent to R's `MASS::rlm()`.
*
* @param formula A formula such as `"y ~ x1 + x2"`.
* @param data Columns of equal-length observations.
* @param options Psi, scale, initial values, observation weights and iteration controls.
* @returns Coefficients, fitted values, residuals, robust weights, scale and covariance diagnostics.
*
* @example
* ```ts
* rlm("y ~ x", { y: [1, 2, 2.9, 4.2, 5], x: [1, 2, 3, 4, 5] }).coefficients;
* ```
*
* @category Regression
*/
export function rlm(formula: string, data: DataFrame, options: RlmOptions = {}): RlmResult {
 checkOptions(options, RLM_KEYS, "rlm"); // generated: option-keys.mjs
 const method = options.method ?? "M";
 if (method !== "M" && method !== "MM") throw new RangeError("method must be 'M' or 'MM'");
 const psi = options.psi ?? (method === "MM" ? "bisquare" : "huber");
 if (psi !== "huber" && psi !== "hampel" && psi !== "bisquare") throw new RangeError("unknown psi function");
 if (method === "MM" && psi === "huber") throw new RangeError("MM estimation requires a redescending psi function");
 const scaleEst = options.scaleEst ?? "MAD";
 if (scaleEst !== "MAD" && scaleEst !== "Huber" && scaleEst !== "proposal 2") throw new RangeError("unknown scale estimator");
 const wtMethod = options.wtMethod ?? "inv";
 if (wtMethod !== "inv" && wtMethod !== "case") throw new RangeError("wtMethod must be 'inv' or 'case'");
 if (method === "MM" && wtMethod === "case" && options.weights !== undefined) {
   throw new RangeError("MM estimation does not support case weights");
 }
 if (method === "MM" && options.init !== undefined) {
   throw new RangeError("MM estimation always uses its deterministic S-estimator start");
 }
 const k = options.k ?? 1.345, a = options.a ?? 2, b = options.b ?? 4;
 const c = options.c ?? (psi === "bisquare" ? 4.685 : 8), k2 = options.k2 ?? 1.345;
 const maxit = options.maxit ?? 1000, acc = options.acc ?? 1e-10;
 if (!(k > 0 && k2 > 0) || ![k, k2].every(Number.isFinite)) throw new RangeError("k and k2 must be positive and finite");
 if (!(a > 0 && a < b && b < c) || ![a, b, c].every(Number.isFinite)) {
   if (psi === "hampel") throw new RangeError("Hampel psi requires 0 < a < b < c");
 }
 if (psi === "bisquare" && (!(c > 0) || !Number.isFinite(c))) throw new RangeError("bisquare c must be positive and finite");
 if (!Number.isInteger(maxit) || maxit < 1) throw new RangeError("maxit must be a positive integer");
 if (!(acc > 0) || !Number.isFinite(acc)) throw new RangeError("acc must be positive and finite");

 const parsed = parseFormula(formula);
 if (parsed.response === undefined) throw new TypeError("formula must have a response");
 const designOptions: Parameters<typeof design>[2] = {};
 if (options.weights !== undefined) designOptions.weights = options.weights;
 const d = design(parsed, data, designOptions);
 if (d.y === undefined) throw new TypeError("response must be numeric");
 const x = d.x;
 const y = d.y;
 const observationWeights = d.frame.weights ?? new Array<number>(y.length).fill(1);
 if (observationWeights.some((w) => !Number.isFinite(w) || w < 0)) throw new RangeError("weights must be finite and non-negative");
 if (!x.every((row) => row.every(Number.isFinite)) || !y.every(Number.isFinite)) throw new RangeError("NA/NaN/Inf in model matrix or response");
 const p = x[0]?.length ?? 0;
 if (p === 0) throw new Error("model has no coefficients");
 const model: RlmModel = {
   formula, x, y, columnNames: d.colNames, observationWeights, wtMethod, psi, scaleEst,
   k, a, b, c, k2, rows: d.frame.rows,
 };
 const searchWarnings: string[] = [];
 let coefficients: number[];
 let fixedScale: number | undefined;
 let initialization: RlmResult["initialization"];
 if (method === "MM") {
   const start = sStart(x, y, observationWeights, wtMethod);
   coefficients = start.coefficients;
   fixedScale = start.objective;
   initialization = {
     method: "S", objective: start.objective, candidatesEvaluated: start.evaluated,
     candidateCount: start.total.toString(), exhaustive: start.warning === undefined,
   };
   if (start.warning !== undefined) searchWarnings.push(start.warning);
 } else if (options.init === "lts") {
   const start = ltsStart(x, y, observationWeights, wtMethod);
   coefficients = start.coefficients;
   initialization = {
     method: "LTS", objective: start.objective, candidatesEvaluated: start.evaluated,
     candidateCount: start.total.toString(), exhaustive: start.warning === undefined,
   };
   if (start.warning !== undefined) searchWarnings.push(start.warning);
 } else if (options.init === undefined || options.init === "ls") {
   coefficients = weightedLeastSquares(x, y, observationWeights);
 } else if (typeof options.init === "string") {
   throw new RangeError("init must be 'ls', 'lts' or a numeric coefficient vector");
 } else {
   coefficients = Array.from(options.init);
   if (coefficients.length !== p || !coefficients.every(Number.isFinite)) throw new RangeError("init must have " + p + " finite coefficients");
 }

 const convergence: number[] = [];
 let converged = false;
 let scale = fixedScale ?? NaN;
 let robustWeights = new Array<number>(y.length).fill(1);
 let workingWeights = observationWeights.slice();
 let iterations = 0;
 const effectiveObsWeights = (residuals: readonly number[], s: number): number[] => {
   const u = residuals.map((r, i) => (wtMethod === "inv" ? Math.sqrt(observationWeights[i]!) * r : r) / s);
   return u.map((v, i) => psiWeight(psi, v, model) * observationWeights[i]!);
 };
 for (let iteration = 1; iteration <= maxit; iteration++) {
   iterations = iteration;
   const residuals = residualVector(x, y, coefficients);
   scale = fixedScale ?? robustScale(residuals, observationWeights, wtMethod, scaleEst, k2, p);
   if (!(scale > 0) || !Number.isFinite(scale)) {
     if (scale === 0) { converged = true; break; }
     throw new Error("robust scale is not positive and finite");
   }
   robustWeights = residuals.map((r, i) => {
     const u = (wtMethod === "inv" ? Math.sqrt(observationWeights[i]!) * r : r) / scale;
     return psiWeight(psi, u, model);
   });
   workingWeights = effectiveObsWeights(residuals, scale);
   const irls = weightedLeastSquares(x, y, workingWeights);
   // Redescending scores can make full IRLS updates oscillate between distinct roots.
   // A fixed half-step is deterministic and keeps the iteration inside the basin of the
   // robust start; monotone scores (Huber) retain the full update.
   const damping = psi === "huber" ? 1 : 0.5;
   const next = coefficients.map((value, j) => value + damping * (irls[j]! - value));
   const nextResiduals = residualVector(x, y, next);
   const nextScale = fixedScale ?? robustScale(nextResiduals, observationWeights, wtMethod, scaleEst, k2, p);
   if (!(nextScale > 0) || !Number.isFinite(nextScale)) {
     if (nextScale === 0) { coefficients = next; scale = 0; converged = true; break; }
     throw new Error("robust scale is not positive and finite");
   }
   let scoreNorm = 0;
   for (let j = 0; j < p; j++) {
     let score = 0, magnitude = 0;
     for (let i = 0; i < y.length; i++) {
       const rootWeight = wtMethod === "inv" ? Math.sqrt(observationWeights[i]!) : observationWeights[i]!;
       const u = (wtMethod === "inv" ? Math.sqrt(observationWeights[i]!) * nextResiduals[i]! : nextResiduals[i]!) / nextScale;
       const contribution = rootWeight * x[i]![j]! * psiScore(psi, u, model);
       score += contribution;
       magnitude += Math.abs(contribution);
     }
     scoreNorm = Math.max(scoreNorm, magnitude === 0 ? Math.abs(score) : Math.abs(score) / magnitude);
   }
   const scaleNorm = fixedScale === undefined
     ? Math.abs(nextScale - scale) / Math.max(Math.abs(nextScale), Math.abs(scale), Number.MIN_VALUE)
     : 0;
   const residual = Math.max(scoreNorm, scaleNorm);
   convergence.push(residual);
   coefficients = next;
   scale = nextScale;
   if (residual <= acc) { converged = true; break; }
 }
 const fittedValues = x.map((row) => row.reduce((sum, v, j) => sum + v * coefficients[j]!, 0));
 const residuals = y.map((v, i) => v - fittedValues[i]!);
 scale = fixedScale ?? robustScale(residuals, observationWeights, wtMethod, scaleEst, k2, p);
 robustWeights = residuals.map((r, i) => {
   const u = (wtMethod === "inv" ? Math.sqrt(observationWeights[i]!) * r : r) / scale;
   return psiWeight(psi, u, model);
 });
 workingWeights = effectiveObsWeights(residuals, scale);
 const covariance = covarianceScale(residuals, scale, observationWeights, model, p);
 const warnings = [...d.warnings, ...searchWarnings];
 if (!converged) warnings.push("'rlm' failed to converge in " + maxit + " steps");
 const result: RlmResult = {
   coefficients: Object.fromEntries(d.colNames.map((name, i) => [name, coefficients[i]!])),
   fittedValues, residuals, robustWeights, workingWeights,
   scale, stddev: covariance.stddev,
   covariance: covariance.covUnscaled.map((row) => row.map((v) => v * covariance.stddev ** 2)),
   covarianceUnscaled: covariance.covUnscaled,
   converged, iterations, convergence, warnings, model,
   ...(initialization === undefined ? {} : { initialization }),
 };
 return reported("rlm", result);
}

/** Coefficient table of a robust fit. Equivalent to R's `summary.rlm()`.
*
* @param fit A fit returned by {@link rlm}.
* @returns Coefficients, standard errors and t statistics.
*
* @example
* ```ts
* rlmSummary(rlm("y ~ x", { y: [1, 2, 2.9, 4.2, 5], x: [1, 2, 3, 4, 5] }));
* ```
*
* @category Regression
*/
export function rlmSummary(fit: RlmResult, options: Record<string, never> = {}): RlmSummaryResult {
 checkOptions(options, RLM_SUMMARY_KEYS, "rlmSummary"); // generated: option-keys.mjs
 const rows = fit.model.columnNames;
 const values = rows.map((_, i) => {
   const se = Math.sqrt(fit.covariance[i]![i]!);
   const value = fit.coefficients[rows[i]!]!;
   return [value, se, value / se];
 });
 return reported("rlmSummary", { rows, columns: ["Value", "Std. Error", "t value"], values, warnings: fit.warnings }, fit);
}

/** Covariance matrix of robust-regression coefficients. Equivalent to R's `vcov.rlm()`.
*
* @param fit A fit returned by {@link rlm}.
* @returns The covariance matrix in coefficient order.
*
* @example
* ```ts
* rlmVcov(rlm("y ~ x", { y: [1, 2, 2.9, 4.2, 5], x: [1, 2, 3, 4, 5] }));
* ```
*
* @category Regression
*/
export function rlmVcov(fit: RlmResult, options: Record<string, never> = {}): RlmVcovResult {
 checkOptions(options, RLM_VCOV_KEYS, "rlmVcov"); // generated: option-keys.mjs
 return reported("rlmVcov", {
   rows: fit.model.columnNames, columns: fit.model.columnNames,
   values: fit.covariance, warnings: fit.warnings,
 }, fit);
}
