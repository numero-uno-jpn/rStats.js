/**
 * Predictions of a multinomial logistic regression: probabilities of the levels, or the most probable level. Equivalent
 * to `nnet::predict.multinom()` in R.
 *
 * Ties are broken as R's `max.col`: probabilities within 1e-5 (relative) of the row's largest are tied, and the k-th
 * tied level replaces the choice when k u < 1, u a uniform of {@link runif} (one per tie after the first), so the
 * classes are R's after the same `setSeed`.
 * @category Regression
 */
export function multinomPredict(fit: MultinomResult, options: MultinomPredictOptions = {}): string[] | number[][] {
  checkOptions(options, MULTINOM_PREDICT_KEYS, "multinomPredict"); // generated: option-keys.mjs
  const type = options.type ?? "class";
  if (type !== "class" && type !== "probs") throw new RangeError(`unknown prediction type '${String(type)}'`);
  let probs: number[][];
  if (options.newdata === undefined) probs = fit.fittedValues.map((r) => r.slice());
  else {
    const model = fit.model, data = options.newdata;
    if (dataRowCount(data, model.predictorVariables) === undefined) throw new TypeError("cannot determine the number of rows in newdata");
    for (const [name, levels] of Object.entries(model.factorLevels)) {
      const column = data[name];
      if (column === undefined) throw new RangeError(`object '${name}' not found`);
      for (const raw of column) {
        if (raw === null || (typeof raw === "number" && Number.isNaN(raw))) continue;
        const value = typeof raw === "boolean" ? (raw ? "TRUE" : "FALSE") : String(raw);
        if (!levels.includes(value)) throw new RangeError(`factor ${name} has new level ${value}`);
      }
    }
    const d = design({ response: undefined, rhs: model.rhs }, data, { levels: model.factorLevels, contrasts: model.contrasts });
    const columns = fit.columnNames.map((name) => d.colNames.indexOf(name));
    if (columns.some((j) => j < 0)) throw new RangeError("newdata does not produce the fitted model matrix columns");
    const { centre, exps, kept, intercept, scaledCoef } = model.internal;
    probs = probabilities(d.x.map((row) => kept.map((j) => {
      const v = row[columns[j]!]!;
      return j === intercept ? v : ldexp(v - centre[j]!, -exps[j]!);
    })), scaledCoef);
  }
  if (type === "probs") return probs;
  return probs.map((r) => {
    const top = Math.max(...r.map(Math.abs));
    const tol = 1e-5 * top;
    let best = 0, ties = 1;
    for (let j = 1; j < r.length; j++) {
      if (r[j]! > r[best]! + tol) { best = j; ties = 1; }
      else if (r[j]! >= r[best]! - tol) { ties++; if (ties * runif(1)[0]! < 1) best = j; }
    }
    return fit.levels[best]!;
  });
}

/**
 * Result of {@link multinomAnova}: one row per model, in increasing order of the number of coefficients.
 *
 * @category Regression
 */
export interface MultinomAnovaResult {
  /** The right-hand sides of the formulas (`"1"` for the intercept-only model). */
  model: string[];
  /** Residual degrees of freedom, n (K − 1) − edf. */
  residDf: number[];
  /** Deviances. */
  residDev: number[];
  /** `"1 vs 2"`, ... (`""` for the first). */
  test: string[];
  /** Degrees of freedom of each test (NaN for the first). */
  df: number[];
  /** Likelihood-ratio statistics, the differences of deviances (NaN for the first). */
  lrStat: number[];
  /** Upper chi-squared p-values (NaN for the first). */
  pValue: number[];
}

/**
 * Likelihood-ratio tests of nested multinomial logistic regressions. Equivalent to `nnet::anova.multinom()` in R: the
 * models are ordered by their residual degrees of freedom (largest first), whatever the order given.
 * @category Regression
 */
export function multinomAnova(...fits: MultinomResult[]): MultinomAnovaResult {
  if (fits.length < 2) throw new RangeError("give at least two fits");
  const n = fits[0]!.n, K = fits[0]!.levels.length;
  if (fits.some((f) => f.n !== n || f.levels.length !== K)) throw new RangeError("the models must be fitted to the same data");
  const rows = fits.map((f) => ({ f, residDf: n * (K - 1) - f.edf }))
    .sort((a, b) => b.residDf - a.residDf);
  const out: MultinomAnovaResult = { model: [], residDf: [], residDev: [], test: [], df: [], lrStat: [], pValue: [] };
  rows.forEach(({ f, residDf }, i) => {
    const rhs = f.model.formula.slice(f.model.formula.indexOf("~") + 1).trim().replace(/\s+/g, " ");
    out.model.push(rhs); out.residDf.push(residDf); out.residDev.push(f.deviance);
    if (i === 0) { out.test.push(""); out.df.push(NaN); out.lrStat.push(NaN); out.pValue.push(NaN); return; }
    const prev = rows[i - 1]!;
    const df = prev.residDf - residDf, lr = prev.f.deviance - f.deviance;
    out.test.push(`${i} vs ${i + 1}`); out.df.push(df); out.lrStat.push(lr);
    out.pValue.push(pchisq(lr, df, { lowerTail: false }));
  });
  return out;
}
