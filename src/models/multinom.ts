/**
 * Wald confidence intervals of the coefficients of a multinomial logistic regression. Equivalent to
 * `nnet::confint.multinom()` in R: coefficient ± qnorm((1 + level) / 2) se.
 * @category Regression
 */
export function multinomConfint(fit: MultinomResult, options: MultinomConfintOptions = {}): MultinomConfintResult {
  checkOptions(options, MULTINOM_CONFINT_KEYS, "multinomConfint"); // generated: option-keys.mjs
  const { level = 0.95 } = options;
  if (!(level > 0 && level < 1)) throw new RangeError("'level' must be between 0 and 1");
  const z = qnorm((1 + level) / 2);
  return {
    lower: fit.coefficients.map((row, k) => row.map((c, j) => c - z * fit.se[k]![j]!)),
    upper: fit.coefficients.map((row, k) => row.map((c, j) => c + z * fit.se[k]![j]!)),
    level,
  };
}

