/** The penalised −log L, its gradient and Hessian (unpenalised and penalised) at the coefficients `b` (category-major) */
function evaluate(x: number[][], y: number[], w: number[], K: number, b: number[], penalty: number[][]) {
  const p = x[0]!.length, P = (K - 1) * p;
  let f = 0;
  const g = new Array<number>(P).fill(0);
  const H = Array.from({ length: P }, () => new Array<number>(P).fill(0));
  const prob = new Array<number>(K);
  for (let i = 0; i < x.length; i++) {
    const wi = w[i]!;
    if (wi === 0) continue;
    const xi = x[i]!;
    // softmax with the reference's logit 0, shifted by the largest
    let top = 0;
    const eta = [0];
    for (let k = 1; k < K; k++) {
      let e = 0;
      for (let j = 0; j < p; j++) e += xi[j]! * b[(k - 1) * p + j]!;
      eta.push(e);
      if (e > top) top = e;
    }
    let s = 0;
    for (let k = 0; k < K; k++) { prob[k] = Math.exp(eta[k]! - top); s += prob[k]!; }
    for (let k = 0; k < K; k++) prob[k]! /= s;
    f -= wi * (eta[y[i]!]! - top - Math.log(s));
    for (let k = 1; k < K; k++) {
      const r = wi * (prob[k]! - (y[i] === k ? 1 : 0));
      for (let j = 0; j < p; j++) g[(k - 1) * p + j]! += r * xi[j]!;
      for (let l = 1; l < K; l++) {
        const c = wi * ((k === l ? prob[k]! : 0) - prob[k]! * prob[l]!);
        if (c === 0) continue;
        for (let j = 0; j < p; j++) {
          const row = H[(k - 1) * p + j]!, cj = c * xi[j]!;
          for (let jj = 0; jj < p; jj++) row[(l - 1) * p + jj]! += cj * xi[jj]!;
        }
      }
    }
  }
  // the decay penalty b_k^T Pen b_k for each category's block
  const Hp = H.map((row) => row.slice());
  for (let k = 0; k < K - 1; k++) for (let a = 0; a < p; a++) for (let c = 0; c < p; c++) {
    const v = penalty[a]![c]!;
    if (v === 0) continue;
    f += b[k * p + a]! * v * b[k * p + c]!;
    g[k * p + a]! += 2 * v * b[k * p + c]!;
    Hp[k * p + a]![k * p + c]! += 2 * v;
  }
  return { f, g, H, Hp };
}

/** Inverse of a symmetric positive definite matrix by Cholesky; null when it is not positive definite */
function spdInverse(A: number[][]): number[][] | null {
  const n = A.length;
  const L = Array.from({ length: n }, () => new Array<number>(n).fill(0));
  for (let i = 0; i < n; i++) {
    for (let j = 0; j <= i; j++) {
      let s = A[i]![j]!;
      for (let k = 0; k < j; k++) s -= L[i]![k]! * L[j]![k]!;
      if (i === j) {
        if (!(s > 1e-14 * Math.abs(A[i]![i]!)) || !Number.isFinite(s)) return null;
        L[i]![i] = Math.sqrt(s);
      } else L[i]![j] = s / L[j]![j]!;
    }
  }
  // inverse of L, then L^-T L^-1
  const Li = Array.from({ length: n }, () => new Array<number>(n).fill(0));
  for (let i = 0; i < n; i++) {
    Li[i]![i] = 1 / L[i]![i]!;
    for (let j = 0; j < i; j++) {
      let s = 0;
      for (let k = j; k < i; k++) s -= L[i]![k]! * Li[k]![j]!;
      Li[i]![j] = s / L[i]![i]!;
    }
  }
  const V = Array.from({ length: n }, () => new Array<number>(n).fill(0));
  for (let i = 0; i < n; i++) for (let j = 0; j <= i; j++) {
    let s = 0;
    for (let k = i; k < n; k++) s += Li[k]![i]! * Li[k]![j]!;
    V[i]![j] = s; V[j]![i] = s;
  }
  return V;
}

/** Indices of the columns that are neither constant nor in the span of the intercept and the earlier ones */
function estimable(x: readonly (readonly number[])[], intercept: number): number[] {
  const n = x.length, p = x[0]?.length ?? 0;
  const basis: number[][] = intercept >= 0 ? [new Array<number>(n).fill(1 / Math.sqrt(n))] : [];
  const kept: number[] = intercept >= 0 ? [intercept] : [];
  for (let j = 0; j < p; j++) {
    if (j === intercept) continue;
    const v = x.map((row) => row[j]!);
    const norm0 = Math.hypot(...v);
    for (let pass = 0; pass < 2; pass++) for (const e of basis) {
      let dot = 0;
      for (let i = 0; i < n; i++) dot += e[i]! * v[i]!;
      for (let i = 0; i < n; i++) v[i]! -= dot * e[i]!;
    }
    const norm = Math.hypot(...v);
    if (!(norm0 > 0) || !(norm > 1e-7 * norm0)) continue;
    basis.push(v.map((e) => e / norm));
    kept.push(j);
  }
  return kept.sort((a, c) => a - c);
}

/** Probabilities of every level at the coefficients (original units) for rows x */
function probabilities(x: readonly (readonly number[])[], coef: readonly (readonly number[])[]): number[][] {
  return x.map((xi) => {
    const eta = [0, ...coef.map((row) => row.reduce((a, c, j) => a + c * xi[j]!, 0))];
    const top = Math.max(...eta);
    const e = eta.map((v) => Math.exp(v - top));
    const s = e.reduce((a, v) => a + v, 0);
    return e.map((v) => v / s);
  });
}

/**
 * Multinomial logistic regression: baseline-category logits for a response with two or more levels, the first level
 * the reference. Equivalent to `nnet::multinom()` in R. The call followed is
 * `multinom(y ~ ..., data, weights, decay, Hess = TRUE)`.
 *
 * The coefficients maximise the (weighted) log-likelihood less `decay` times the sum of squares of all coefficients,
 * by Newton's method to machine precision; R's BFGS stops earlier (by default about 1e-5 from the maximum). The
 * standard errors come from the Hessian of −log L (without the decay term, as R). A numeric response is made a factor;
 * an unused level is dropped with R's warning; rows with missing values are dropped.
 * @category Regression
 * @example
 * ```ts
 * const data = { y: ["a", "b", "c", "a", "b", "c", "b", "a", "c", "c"], x: [1, 2, 3, 1.5, 2.2, 2.8, 1.9, 1.2, 3.1, 2.5] };
 * const fit = multinom("y ~ x", data);
 * fit.coefficients; // rows b and c: [intercept, x]
 * ```
 */
export function multinom(formula: string, data: DataFrame, options: MultinomOptions = {}): MultinomResult {
  checkOptions(options, MULTINOM_KEYS, "multinom"); // generated: option-keys.mjs
  const { decay = 0, maxit = 100 } = options;
  if (!(decay >= 0) || !Number.isFinite(decay)) throw new RangeError("'decay' must be a non-negative number");
  if (!Number.isInteger(maxit) || maxit < 1) throw new RangeError("'maxit' must be a positive integer");
  const parsed = parseFormula(formula);
  if (parsed.response === undefined) throw new TypeError("the formula must have a response");
  const designOptions: Parameters<typeof design>[2] = { anyResponse: true };
  if (options.weights !== undefined) designOptions.weights = options.weights;
  if (options.levels !== undefined) designOptions.levels = options.levels;
  if (options.contrasts !== undefined) designOptions.contrasts = options.contrasts;
  const d = design(parsed, data, designOptions);
  const response = d.frame.variables[0];
  if (response === undefined) throw new TypeError("the formula must have a response");
  // a numeric response becomes a factor of its sorted distinct values, as R's as.factor
  let levels: string[], codes: number[];
  if (response.kind === "factor") { levels = response.levels.slice(); codes = response.codes.slice(); }
  else {
    const distinct = [...new Set(response.values)].sort((a, b) => a - b);
    levels = distinct.map(String);
    codes = response.values.map((v) => distinct.indexOf(v));
  }
  const weights = d.frame.weights ?? new Array<number>(codes.length).fill(1);
  if (weights.some((v) => !Number.isFinite(v) || v < 0)) throw new RangeError("weights must be finite and non-negative");
  // unused levels are dropped, as R ("group ‘D’ is empty")
  const warnings = [...d.warnings];
  const used = levels.map((_, k) => codes.some((c) => c === k));
  for (let k = 0; k < levels.length; k++) if (!used[k]) warnings.push(`group ‘${levels[k]}’ is empty`);
  const remap = levels.map((_, k) => used.slice(0, k).filter(Boolean).length);
  levels = levels.filter((_, k) => used[k]);
  const y = codes.map((c) => remap[c]!);
  const K = levels.length;
  if (K < 2) throw new RangeError("need two or more classes to fit a multinom model");
  const x = d.x;
  if (x.some((row) => row.some((v) => !Number.isFinite(v)))) throw new RangeError("NA/NaN/Inf in the model matrix");
  const p = x[0]?.length ?? 0;
  if (p === 0) throw new RangeError("the model has no coefficients");
  const intercept = d.terms.intercept ? 0 : -1;
  // each column other than the intercept is centred (with an intercept) and divided by a power of 2: the fit is well
  // scaled for columns near 1e300 or 1e-300 and for a large common offset (1e15 + small differences); the original
  // coefficients follow exactly in the scale, and the intercept absorbs the centring
  const centre = Array.from({ length: p }, (_, j) => (j === intercept || intercept < 0 ? 0 : x.reduce((a, r) => a + r[j]!, 0) / x.length));
  const exps = Array.from({ length: p }, (_, j) => {
    if (j === intercept) return 0;
    let top = 0;
    for (const row of x) top = Math.max(top, Math.abs(row[j]! - centre[j]!));
    return top > 0 ? Math.floor(Math.log2(top)) : 0;
  });
  const scaled = x.map((row) => row.map((v, j) => (j === intercept ? v : ldexp(v - centre[j]!, -exps[j]!))));
  // the estimable columns: not constant and not in the span of the intercept and the earlier columns (R's fit cannot
  // identify them; rStats.js leaves them out with NaN coefficients, as polr)
  const kept = estimable(scaled, intercept);
  const dropped = d.colNames.filter((_, j) => !kept.includes(j));
  if (dropped.length > 0) warnings.push(`design appears to be rank-deficient, so dropping some coefs: ${dropped.join(", ")}`);
  const q = kept.length, Q = (K - 1) * q;
  const xs = scaled.map((row) => kept.map((j) => row[j]!));
  // original coefficients of a category: b_j = b'_j 2^-e_j (j not the intercept), b_0 = b'_0 - sum_j c_j b_j; the decay
  // penalty decay |b|^2 is the quadratic form decay b'^T M^T M b' with M that map
  const M = kept.map((ja) => kept.map((jb) => {
    if (ja === jb) return ja === intercept ? 1 : ldexp(1, -exps[ja]!);
    if (ja === intercept && jb !== intercept) return -centre[jb]! * ldexp(1, -exps[jb]!);
    return 0;
  }));
  const pen = kept.map((_, a) => kept.map((__, b) => (decay === 0 ? 0 : decay * M.reduce((sum, row) => sum + row[a]! * row[b]!, 0))));
  // start: the intercepts at the log odds of the levels against the reference (weighted), the rest 0
  const counts = new Array<number>(K).fill(0);
  y.forEach((c, i) => { counts[c]! += weights[i]!; });
  let b = new Array<number>(Q).fill(0);
  const ii = kept.indexOf(intercept);
  if (ii >= 0 && counts.every((c) => c > 0)) for (let k = 1; k < K; k++) b[(k - 1) * q + ii] = Math.log(counts[k]! / counts[0]!);
  const totalWeight = weights.reduce((a, v) => a + v, 0);
  const tol = 1e-10 * totalWeight;
  let cur = evaluate(xs, y, weights, K, b, pen);
  let converged = false, iter = 0;
  for (; iter < maxit; iter++) {
    if (Math.max(...cur.g.map(Math.abs)) <= tol) { converged = true; break; }
    const Hi = spdInverse(cur.Hp);
    if (Hi === null) break;
    const step = Hi.map((row) => -row.reduce((a, v, r) => a + v * cur.g[r]!, 0));
    // the decrease near the maximum falls below the rounding of the objective: a rise within it is accepted
    const slack = 1e-12 * Math.abs(cur.f);
    let t = 1, next = b.map((v, r) => v + step[r]!), nxt = evaluate(xs, y, weights, K, next, pen);
    while (!(nxt.f <= cur.f + slack) && t > 1e-10) { t /= 2; next = b.map((v, r) => v + t * step[r]!); nxt = evaluate(xs, y, weights, K, next, pen); }
    if (!(nxt.f <= cur.f + slack)) break;
    const moved = step.some((v, r) => Math.abs(t * v) > 1e-15 * Math.max(1, Math.abs(b[r]!)));
    b = next; cur = nxt;
    if (!moved) { converged = Math.max(...cur.g.map(Math.abs)) <= 1e-7 * totalWeight; iter++; break; }
  }
  // separated data: the likelihood rises towards a limit as some coefficients grow without bound, and the fitted
  // probabilities reach 0 or 1 numerically (glm's test); the maximum does not exist
  const fittedScaled = probabilities(xs, Array.from({ length: K - 1 }, (_, k) => b.slice(k * q, (k + 1) * q)));
  if (converged && fittedScaled.some((r) => r.some((v) => v < 10 * Number.EPSILON))) {
    converged = false;
    warnings.push("fitted probabilities numerically 0 or 1 occurred: the maximum of the likelihood does not exist (separated data)");
  } else if (!converged) warnings.push("the Newton iterations did not converge: the maximum of the likelihood may not exist (separated data)");
  // back to the original units (NaN for the dropped columns)
  const orig = (k: number): number[] => kept.map((_, a) => M[a]!.reduce((sum, m, c) => sum + m * b[k * q + c]!, 0));
  const coefficients = Array.from({ length: K - 1 }, (_, k) => {
    const o = orig(k);
    return Array.from({ length: p }, (_, j) => (kept.includes(j) ? o[kept.indexOf(j)]! : NaN));
  });
  // the Hessian and the variance in the original units: H = Minv^T H' Minv, V = M V' M^T (block by block), with
  // Minv[0][j] = c_j and Minv[j][j] = 2^e_j; a standard error from its own scaled variance (no under- or overflow)
  const Minv = kept.map((ja) => kept.map((jb) => (ja === jb ? (ja === intercept ? 1 : ldexp(1, exps[ja]!))
    : ja === intercept && jb !== intercept ? centre[jb]! : 0)));
  const P = (K - 1) * p;
  const full = (k: number, j: number): number => k * p + j;
  const hessian = Array.from({ length: P }, () => new Array<number>(P).fill(NaN));
  const vcov = Array.from({ length: P }, () => new Array<number>(P).fill(NaN));
  const Vs = spdInverse(cur.H);
  for (let k = 0; k < K - 1; k++) for (let l = 0; l < K - 1; l++) {
    for (let a = 0; a < q; a++) for (let c = 0; c < q; c++) {
      let h = 0, v = 0;
      for (let u = 0; u < q; u++) for (let w2 = 0; w2 < q; w2++) {
        const hu = cur.H[k * q + u]![l * q + w2]!;
        if (Minv[u]![a] !== 0 && Minv[w2]![c] !== 0) h += Minv[u]![a]! * hu * Minv[w2]![c]!;
        if (Vs !== null && M[a]![u] !== 0 && M[c]![w2] !== 0) v += M[a]![u]! * Vs[k * q + u]![l * q + w2]! * M[c]![w2]!;
      }
      hessian[full(k, kept[a]!)]![full(l, kept[c]!)] = h;
      vcov[full(k, kept[a]!)]![full(l, kept[c]!)] = Vs === null ? NaN : v;
    }
  }
  const se = coefficients.map((row, k) => row.map((_, j) => {
    const a = kept.indexOf(j);
    if (a < 0 || Vs === null) return NaN;
    const vs = Vs[k * q + a]![k * q + a]!;
    return j === intercept ? Math.sqrt(vcov[full(k, j)]![full(k, j)]!) : ldexp(Math.sqrt(vs), -exps[j]!);
  }));
  const value = cur.f;
  const edf = Q;
  // probabilities from the internal units (a column 1e15 + small differences keeps its digits)
  const scaledCoef = Array.from({ length: K - 1 }, (_, k) => b.slice(k * q, (k + 1) * q));
  const factorLevels: Record<string, readonly string[]> = {};
  for (let i = 1; i < d.terms.variables.length; i++) {
    const variable = d.frame.variables[i];
    if (variable?.kind === "factor") factorLevels[d.terms.variables[i]!] = variable.levels;
  }
  return reported("multinom", {
    levels, columnNames: d.colNames.slice(), coefficients, se, vcov, hessian,
    parameterNames: levels.slice(1).flatMap((lv) => d.colNames.map((c) => `${lv}:${c}`)),
    value, deviance: 2 * value, logLik: -value, edf, aic: 2 * value + 2 * edf,
    fittedValues: probabilities(xs, scaledCoef), n: y.length, decay, converged, iter,
    model: { formula, rhs: parsed.rhs, predictorVariables: d.terms.variables.slice(1), factorLevels,
      contrasts: (options.contrasts ?? {}) as Record<string, DesignContrast>, x, y, weights, rows: d.frame.rows,
      internal: { centre, exps, kept, intercept, scaledCoef } },
    warnings,
  });
}

/**
 * Result of {@link multinomSummary}.
 *
 * @category Regression
 */
export interface MultinomSummaryResult {
  /** Coefficients (rows the non-reference levels). */
  coefficients: number[][];
  /** Standard errors. */
  se: number[][];
  /** Wald z statistics, coefficient / standard error (R's `Wald.ratios`). */
  zValue: number[][];
  /** Two-sided p-values 2 (1 − Φ(|z|)). */
  pValue: number[][];
  /** exp(coefficients): the odds ratios against the reference level. */
  oddsRatios: number[][];
  /** Deviance, AIC and log-likelihood of the fit (R's). */
  deviance: number;
  aic: number;
  logLik: number;
  /** The log-likelihood of the intercept-only model on the same rows and weights. */
  nullLogLik: number;
  /** McFadden's pseudo R²: 1 − logLik / nullLogLik. */
  mcFadden: number;
  /** Cox and Snell's: 1 − exp(2 (nullLogLik − logLik) / n). */
  coxSnell: number;
  /** Nagelkerke's: Cox and Snell's / (1 − exp(2 nullLogLik / n)). */
  nagelkerke: number;
}

/**
 * Summary of a multinomial logistic regression: Wald tests of the coefficients, odds ratios and pseudo R². Equivalent
 * to `nnet::summary.multinom()` in R. The call followed is `summary(fit, Wald.ratios = TRUE)`, with the p-values, odds
 * ratios and pseudo R² as ReactiveStat computes them (the null model `multinom(y ~ 1)` on the same rows, n the number
 * of rows).
 * @category Regression
 */
export function multinomSummary(fit: MultinomResult): MultinomSummaryResult {
  const { coefficients, se } = fit;
  const zValue = coefficients.map((row, k) => row.map((c, j) => c / se[k]![j]!));
  const nullFit = unreported(() => multinomNull(fit));
  const n = fit.n, ll = fit.logLik, l0 = nullFit;
  const coxSnell = 1 - Math.exp((2 / n) * (l0 - ll));
  return {
    coefficients: coefficients.map((r) => r.slice()), se: se.map((r) => r.slice()), zValue,
    pValue: zValue.map((row) => row.map((z) => 2 * pnorm(-Math.abs(z)))),
    oddsRatios: coefficients.map((row) => row.map(Math.exp)),
    deviance: fit.deviance, aic: fit.aic, logLik: ll, nullLogLik: l0, mcFadden: 1 - ll / l0, coxSnell,
    nagelkerke: coxSnell / (1 - Math.exp((2 / n) * l0)),
  };
}

/** The maximised log-likelihood of the intercept-only model: the weighted proportions of the levels */
function multinomNull(fit: MultinomResult): number {
  const K = fit.levels.length, w = fit.model.weights, y = fit.model.y;
  const counts = new Array<number>(K).fill(0);
  y.forEach((c, i) => { counts[c]! += w[i]!; });
  const total = counts.reduce((a, v) => a + v, 0);
  return counts.reduce((a, c) => (c > 0 ? a + c * Math.log(c / total) : a), 0);
}

