interface Obs {
  time: number;
  event: boolean;
  group: number;
}

const isMissing = (v: GroupLabel | null | undefined): boolean =>
  v === null || v === undefined || (typeof v === "number" && Number.isNaN(v));

/** Observations with no missing value, the sorted labels and the group index of each */
function prepare(
  time: readonly number[],
  status: readonly number[],
  group: readonly (GroupLabel | null)[] | undefined,
): { obs: Obs[]; labels: string[] } {
  if (time.length !== status.length) throw new RangeError("'time' and 'status' must have the same length");
  if (group !== undefined && group.length !== time.length) throw new RangeError("'group' must have the same length as 'time'");
  const keep: number[] = [];
  for (let i = 0; i < time.length; i++) {
    if (Number.isNaN(time[i]!) || Number.isNaN(status[i]!) || (group !== undefined && isMissing(group[i]))) continue;
    const s = status[i]!;
    if (s !== 0 && s !== 1) throw new RangeError("'status' must be 0 (censored) or 1 (event)");
    // a subject censored at Infinity is at risk throughout (R stops on any infinite time); an event cannot happen at an
    // infinite time, nor anything at -Infinity
    if (time[i] === -Infinity || (time[i] === Infinity && s === 1)) throw new RangeError("event times must be finite");
    keep.push(i);
  }
  if (keep.length === 0) throw new RangeError("no observations without missing values");
  let labels: GroupLabel[] = [];
  const index = new Map<GroupLabel, number>();
  // numeric labels with the same 15-digit text are one group, as in R's factor()
  if (group !== undefined) group = numberLevels(group);
  if (group !== undefined) {
    labels = Array.from(new Set(keep.map((i) => group[i] as GroupLabel))).sort((a, b) =>
      typeof a === "number" && typeof b === "number" ? a - b : String(a) < String(b) ? -1 : String(a) > String(b) ? 1 : 0,
    );
    labels.forEach((l, k) => index.set(l, k));
  }
  // times within rounding error are one time, as R's timefix = TRUE (1 and 1 + 1e-9 were two times, so a subject
  // censored at 1 left the risk set before the event at 1 + 1e-9)
  const merged = mergeTiedTimes(keep.map((i) => time[i]!));
  const obs = keep.map((i, k) => ({
    time: merged[k]!,
    event: status[i] === 1,
    group: group === undefined ? 0 : index.get(group[i] as GroupLabel)!,
  }));
  obs.sort((a, b) => a.time - b.time);
  return { obs, labels: labels.map((l) => `group=${levelText(l)}`) };
}

/**
 * Test of the difference between survival curves: the G-rho family of Harrington and Fleming, the log-rank test for
 * `rho = 0`. Equivalent to R's `survival::survdiff()`. As `survdiff(Surv(time, status) ~ group, rho = rho)`.
 *
 * Rows with a missing time, status or group are dropped.
 *
 * @param time Follow-up times.
 * @param status 1 for an event, 0 for a censored time.
 * @param group Group labels, one per observation.
 * @param options See {@link SurvdiffOptions}.
 *
 * @example
 * ```ts
 * const r = survdiff([1, 2, 3, 4, 5, 6], [1, 1, 0, 1, 1, 1], ["a", "b", "a", "b", "a", "b"]);
 * r.chisq;  // 0.073903
 * r.pvalue; // 0.78574
 * ```
 *
 * @category Survival analysis
 */
export function survdiff(
  time: readonly number[],
  status: readonly number[],
  group: readonly (GroupLabel | null)[],
  options: SurvdiffOptions = {},
): SurvdiffResult {
  checkOptions(options, SURVDIFF_KEYS, "survdiff"); // generated: option-keys.mjs
  const { rho = 0 } = options;
  if (!Number.isFinite(rho)) throw new RangeError("'rho' must be a finite number");
  const { obs, labels } = prepare(time, status, group);
  const k = labels.length;
  if (k < 2) throw new RangeError("there is only 1 group");
  const n = new Array<number>(k).fill(0);
  for (const o of obs) n[o.group]!++;
  const observed = new Array<number>(k).fill(0);
  const expected = new Array<number>(k).fill(0);
  const V = Array.from({ length: k }, () => new Array<number>(k).fill(0));
  // at risk per group (time >= t); obs is sorted by time
  const atRisk = n.slice();
  let total = obs.length;
  let km = 1; // pooled Kaplan-Meier estimate just before the current time
  for (let i = 0; i < obs.length; ) {
    const t = obs[i]!.time;
    let j = i;
    const dg = new Array<number>(k).fill(0);
    const leaving = new Array<number>(k).fill(0);
    let d = 0;
    while (j < obs.length && obs[j]!.time === t) {
      const o = obs[j]!;
      leaving[o.group]!++;
      if (o.event) {
        dg[o.group]!++;
        d++;
      }
      j++;
    }
    if (d > 0) {
      const w = rho === 0 ? 1 : km ** rho;
      for (let g = 0; g < k; g++) {
        observed[g]! += w * dg[g]!;
        expected[g]! += (w * d * atRisk[g]!) / total;
      }
      if (total > 1) {
        const f = (w * w * d * (total - d)) / (total * (total - 1));
        for (let g = 0; g < k; g++) {
          for (let h = 0; h < k; h++) {
            V[g]![h]! += f * atRisk[g]! * ((g === h ? 1 : 0) - atRisk[h]! / total);
          }
        }
      }
      km *= 1 - d / total;
    }
    for (let g = 0; g < k; g++) atRisk[g]! -= leaving[g]!;
    total -= j - i;
    i = j;
  }
  // chi-squared on the groups with a positive expected count, dropping the first of them
  const used = expected.map((e, g) => (e > 0 ? g : -1)).filter((g) => g >= 0);
  let chisq = 0;
  let df = Math.max(used.length - 1, 0);
  if (used.length >= 2) {
    const r = used.slice(1);
    const u = r.map((g) => observed[g]! - expected[g]!);
    const Vr = r.map((g) => r.map((h) => V[g]![h]!));
    try {
      const x = solve(Vr, u);
      chisq = u.reduce((s, ui, a) => s + ui * x[a]!, 0);
    } catch {
      // A singular variance matrix (all at risk failing at once, or groups that carry no information): u' V^- u with
      // the generalized inverse, on rank(V) degrees of freedom, which is the chi-squared statistic of the contrasts
      // the data inform (R stops: "system is exactly singular")
      ({ chisq, df } = pseudoQuadratic(Vr, u));
    }
  }
  const pvalue = df === 0 ? NaN : pchisq(chisq, df, { lowerTail: false });
  return { n, groups: labels, obs: observed, exp: expected, var: V, chisq, df, pvalue, pValue: pvalue, warnings: [] };
}

/**
 * u' V^- u for a symmetric positive semi-definite V by its eigen decomposition, over the eigenvalues above 1e-10 of the
 * largest (rank 0, chisq 0 when there are none), and that rank
 */
function pseudoQuadratic(V: number[][], u: number[]): { chisq: number; df: number } {
  const e = eigen(V, { symmetric: true });
  const values = e.values;
  const top = values.reduce((a, b) => Math.max(a, b), 0);
  let chisq = 0;
  let df = 0;
  values.forEach((l, k) => {
    if (!(top > 0 && l > 1e-10 * top)) return;
    const q = u.reduce((s, ui, i) => s + ui * e.vectors![i]![k]!, 0);
    chisq += (q * q) / l;
    df++;
  });
  return { chisq, df };
}

/**
 * The median of a curve over the rows of a stratum, as survival's survmean (minmin): of the points that are not NaN
 * and lie below 0.5 + sqrt(eps), the first time, or, if the curve equals 0.5 (within sqrt(eps)) there and a later such
 * point is lower, the midpoint between that time and the time of the first lower point. NaN if there is no such point.
 */
function curveMedian(time: readonly number[], curve: readonly number[]): number {
  const tol = Math.sqrt(Number.EPSILON);
  const first = curve.findIndex((c) => c < 0.5 + tol);
  if (first < 0) return NaN;
  const c1 = curve[first]!;
  if (Math.abs(c1 - 0.5) < tol) {
    // a NaN point compares false and is skipped, as R drops it before looking for a lower one
    for (let j = first + 1; j < curve.length; j++) if (curve[j]! < c1) return midpoint(time[first]!, time[j]!);
  }
  return time[first]!;
}

/**
 * Kaplan-Meier or exponential cumulative-hazard estimate with pointwise confidence intervals, medians and restricted means.
 * Equivalent to R's `survival::survfit()`. Supports Nelson-Aalen and Fleming-Harrington cumulative hazards,
 * integer case weights, infinitesimal-jackknife standard errors and all six confidence transformations.
 *
 * Rows with a missing time, status, group or weight are dropped.
 *
 * @param time Follow-up times.
 * @param status 1 for an event, 0 for a censored time.
 * @param options See {@link SurvfitOptions}.
 * @returns Time-row estimates, pointwise limits, per-stratum medians and restricted-mean summaries.
 *
 * @example
 * ```ts
 * survfit([1, 2, 2, 3, 4], [1, 1, 0, 1, 0]).surv; // [0.8, 0.6, 0.3, 0.3]
 * ```
 *
 * @category Survival analysis
 */
export function survfit(time: readonly number[], status: readonly number[], options: SurvfitOptions = {}): SurvfitResult {
  checkOptions(options, SURVFIT_KEYS, "survfit"); // generated: option-keys.mjs
  const { group, weights, ctype = 1, stype = 1, robust = false, rmean = "common",
    confType: confTypeInput = "log", confInt = 0.95 } = options;
  if (typeof confTypeInput !== "string") throw new TypeError("confType must be a string");
  const confTypes = ["log", "log-log", "plain", "none", "logit", "arcsin"] as const;
  const confMatches = typeof confTypeInput === "string"
    ? confTypes.filter(value => value.startsWith(confTypeInput))
    : [];
  const confType = confTypes.includes(confTypeInput as typeof confTypes[number]) ? confTypeInput :
    confMatches.length === 1 ? confMatches[0]! : confTypeInput;
  if (typeof ctype !== "number") throw new TypeError("ctype must be a number");
  if (typeof stype !== "number") throw new TypeError("stype must be a number");
  if (ctype !== 1 && ctype !== 2) throw new RangeError("ctype must be 1 or 2");
  if (stype !== 1 && stype !== 2) throw new RangeError("stype must be 1 or 2");
  if (!confTypes.some(value => value === confType)) {
    throw new RangeError("'arg' should be one of “log”, “log-log”, “plain”, “none”, “logit”, “arcsin”");
  }
  if (typeof confInt !== "number") throw new TypeError("confInt must be a number");
  if (!(confInt > 0 && confInt < 1)) throw new RangeError("confidence intervals must be between 0 and 1");
  if (time.length !== status.length) throw new RangeError("'time' and 'status' must have the same length");
  if (group !== undefined && group.length !== time.length) throw new RangeError("'group' must have the same length as 'time'");
  if (weights !== undefined && !Array.isArray(weights)) throw new TypeError("'weights' must be an array");
  if (weights !== undefined && weights.length !== time.length) throw new RangeError("'weights' must have the same length as 'time'");
  if (typeof robust !== "boolean") throw new TypeError("'robust' must be a boolean");
  if (typeof rmean !== "number" && typeof rmean !== "string") throw new TypeError("rmean must be a number or string");
  if (typeof rmean === "number" && !Number.isFinite(rmean)) throw new RangeError("'rmean' must be finite");
  if (typeof rmean !== "number" && rmean !== "none" && rmean !== "common" && rmean !== "individual") {
    throw new RangeError("'arg' should be one of “none”, “common”, “individual”");
  }
  const keep: number[] = [];
  for (let i = 0; i < time.length; i++) {
    const rawWeight = weights?.[i];
    if (weights && rawWeight != null && typeof rawWeight !== "number") throw new TypeError("weights must contain numbers");
    if (weights && (rawWeight == null || Number.isNaN(rawWeight))) continue;
    const w = rawWeight ?? 1;
    if (!Number.isFinite(w)) throw new RangeError("weights must be finite");
    if (w < 0) throw new RangeError("weights must be non-negative");
    if (!Number.isSafeInteger(w)) throw new RangeError("weights must be non-negative safe integers");
    if (time[i] != null && typeof time[i] !== "number") throw new TypeError("'time' must contain numbers");
    if (status[i] != null && typeof status[i] !== "number") throw new TypeError("'status' must contain numbers");
    if (time[i] == null || status[i] == null || Number.isNaN(time[i]!) || Number.isNaN(status[i]!) ||
        (group !== undefined && isMissing(group[i]))) continue;
    if (status[i] !== 0 && status[i] !== 1) throw new RangeError("'status' must be 0 (censored) or 1 (event)");
    if (time[i] === -Infinity || (time[i] === Infinity && status[i] === 1)) throw new RangeError("event times must be finite");
    keep.push(i);
  }
  if (keep.length === 0) throw new RangeError("no observations without missing values");
  const gvals = group === undefined ? [] : numberLevels(group);
  const labels = group === undefined ? ["all"] : Array.from(new Set(keep.map(i => gvals[i]!))).sort((a,b) =>
    typeof a === "number" && typeof b === "number" ? a-b : String(a)<String(b)?-1:String(a)>String(b)?1:0).map(v => `group=${levelText(v)}`);
  const gindex = new Map<GroupLabel, number>();
  if (group !== undefined) Array.from(new Set(keep.map(i=>gvals[i]!))).sort((a,b) =>
    typeof a === "number" && typeof b === "number" ? a-b : String(a)<String(b)?-1:String(a)>String(b)?1:0).forEach((v,i)=>gindex.set(v,i));
  const merged = mergeTiedTimes(keep.map(i=>time[i]!));
  const obs = keep.map((i,k)=>({time:merged[k]!, event:status[i]===1, group:group===undefined?0:gindex.get(gvals[i]!)!, weight:weights?.[i]??1})).sort((a,b)=>a.time-b.time);
  const names = labels;
  const allTimes = obs.map(o=>o.time);
  const globalMin = Math.min(...allTimes), t0 = Math.min(0,globalMin);
  if (typeof rmean === "number" && rmean <= t0) throw new RangeError("'rmean' must be greater than the integration origin");
  const a2=(1-confInt)/2, z=a2<1e-8?qnorm(a2,{lowerTail:false}):qnorm(1-a2);
  const stdErr:number[]=[];
  const out: SurvfitResult = {strata:[],time:[],nRisk:[],nEvent:[],nCensor:[],surv:[],stdErr,stdError:stdErr,
    lower:[],upper:[],cumhaz:[],stdChaz:[],logse:!robust||ctype===2,n:[],records:[],nMax:[],nStart:[],events:[],
    rmean:[],seRmean:[],median:[],medianRows:names,table:{colNames:[],rowNames:names,table:[]},warnings:[]};
  if(weights!==undefined) out.counts={nRisk:[],nEvent:[],nCensor:[]};
  const tableRows:number[][]=[];
  for(let g=0;g<names.length;g++){
    const rows=obs.filter(o=>o.group===g);
    if(!rows.some(o=>o.weight>0)) throw new Error("a group has no positive weight");
    let totalWeight=0;
    for(const o of rows){
      totalWeight+=o.weight;
      if(!Number.isSafeInteger(totalWeight)) throw new RangeError("total case weight per group must be a safe integer");
    }
    const start=out.time.length, records=rows.length, maxTime=Math.max(...rows.map(o=>o.time));
    let nRisk=totalWeight, nUnweighted=rows.length, S=1,H=0,green=0,varH=0;
    const events:number[]=[];
    const curveEvents:{t:number;n:number;d:number;S:number;H:number;A?:number}[]=[];
    const eventRows:{t:number;d:number;n:number;e:number;S:number}[]=[];
    for(let i=0;i<rows.length;){
      const t=rows[i]!.time;let j=i,d=0,e=0,c=0,uwRisk=nUnweighted;
      while(j<rows.length&&rows[j]!.time===t){const o=rows[j]!;if(o.event){d+=o.weight;e++;}else c+=o.weight;j++;}
      const unEvent=rows.slice(i,j).filter(o=>o.event).length, unCensor=j-i-unEvent;
      let inc=0, incVar=0;
      if(d>0){
        if(ctype===1){inc=d/nRisk;incVar=d/(nRisk*nRisk);}
        else {for(let k=0;k<e;k++){const a=d/e,den=nRisk-k*a;inc+=a/den;incVar+=a/(den*den);}}
        H+=inc;varH+=incVar;
        if(stype===1){S*=1-d/nRisk;green+=d<nRisk?d/(nRisk*(nRisk-d)):Infinity;}
        else S=Math.exp(-H);
        eventRows.push({t,d,n:nRisk,e,S});
      }
      const sigma=stype===1?Math.sqrt(green):Math.sqrt(varH);
      let robustS=0, robustH=0;
      if (robust) {
        let vS=0,vH=0;
        for (const subject of rows) {
          let dS=0,dH=0;
          for (const ev of eventRows) {
            if (ev.t>t) break;
            const atRisk=subject.time>=ev.t, event=subject.time===ev.t && subject.event;
            const h=ev.d/ev.n;
            if (ctype===1) dH+=(Number(event)-Number(atRisk)*h)/ev.n;
            else {
              let fd=0,fn=0;
              for(let k=0;k<ev.e;k++){const a=ev.d/ev.e,den=ev.n-k*a;fd+=(den+ k*a)/(ev.e*den*den);fn-=a/(den*den);}
              dH+=fd*Number(event)+fn*Number(atRisk);
            }
            if(stype===1 && h<1) dS-=S*(Number(event)-Number(atRisk)*h)/((1-h)*ev.n);
          }
          vS+=(subject.weight*dS)**2;vH+=(subject.weight*dH)**2;
        }
        robustS=Math.sqrt(vS);robustH=Math.sqrt(vH);
      }
      // Robust stype 1 uses the KM influence variance; stype 2 uses the cumulative-hazard influence variance.
      // With ctype 2, log-scale limits use the IJ scale selected by logse:
      // KM influence for stype 1, FH influence for stype 2. The public stdErr is
      // always on the survival scale, so multiply by S when logse is true.
      const seLog=robust
        ? (ctype===2 ? (stype===1?robustS:robustH) : stype===1 ? (S===0?NaN:robustS/S) : robustH)
        : sigma;
      const seS=robust
        ? (ctype===2 ? S*(stype===1?robustS:robustH) : stype===1 ? robustS : S*robustH)
        : S*sigma;
      let lo=NaN,up=NaN;
      if(confType!=="none"){
        if(confType==="log"){lo=S===0?(seS===0?0:NaN):S*Math.exp(-z*seLog);up=S===0?(seS===0?0:NaN):Math.min(1,S*Math.exp(z*seLog));}
        else if(confType==="log-log"){if(S===0||S===1){lo=seS===0?S:NaN;up=lo;}else{const m=Math.log(-Math.log(S));lo=Math.exp(-Math.exp(m-z*seLog/Math.log(S)));up=Math.exp(-Math.exp(m+z*seLog/Math.log(S)));}}
        else if(confType==="plain"){if(S===0&&seS===Infinity){lo=NaN;up=NaN;}else{lo=Math.max(0,S-z*seS);up=Math.min(1,S+z*seS);}}
        else if(confType==="logit"){if(S===0||S===1){lo=seS===0?S:NaN;up=lo;}else{const l=Math.log(S/(1-S)),h=z*seS/(S*(1-S));lo=1-1/(1+Math.exp(l-h));up=1-1/(1+Math.exp(l+h));}}
        else {if(S>0&&S<1){const a=Math.asin(Math.sqrt(S)),h=z*seS/(2*Math.sqrt(S*(1-S)));lo=Math.sin(Math.max(0,a-h))**2;up=Math.sin(Math.min(Math.PI/2,a+h))**2;}else{lo=NaN;up=NaN;}}
      }
      const rowRisk=nRisk;
      out.strata.push(names[g]!);out.time.push(t);out.nRisk.push(rowRisk);out.nEvent.push(d);out.nCensor.push(c);
      out.surv.push(S);out.cumhaz.push(H);out.stdChaz.push(robust?robustH:Math.sqrt(varH));
      out.stdErr.push(robust
        ? (ctype===2 ? S*(stype===1?robustS:robustH) : stype===1 ? robustS : S*robustH)
        : S*sigma);
      out.lower.push(lo);out.upper.push(up);
      if(out.counts){out.counts.nRisk.push(uwRisk);out.counts.nEvent.push(unEvent);out.counts.nCensor.push(unCensor);}
      nRisk-=d+c;nUnweighted-=j-i;i=j;
    }
    const tt=out.time.slice(start), ss=out.surv.slice(start), ll=out.lower.slice(start), uu=out.upper.slice(start);
    out.median.push([curveMedian(tt,ss),confType==="none"?NaN:curveMedian(tt,ll),confType==="none"?NaN:curveMedian(tt,uu)]);
    out.n.push(records);out.records.push(records);
    const risks=out.nRisk.slice(start);out.nMax.push(Math.max(...risks));out.nStart.push(risks[0]??0);
    out.events.push(rows.reduce((v,o)=>v+ (o.event?o.weight:0),0));
    const tau= rmean==="none"?NaN:rmean==="common"?Math.max(...allTimes):rmean==="individual"?maxTime:rmean;
    if(rmean!=="none"&&!Number.isFinite(tau)) throw new RangeError("'rmean' must be finite");
    const areaSum=wideSum();
    const survAt=(t:number)=>{let x=1;for(const ev of eventRows){if(ev.t<=t)x=ev.S;else break;}return x;};
    const cuts=Array.from(new Set([t0,...eventRows.map(e=>e.t).filter(t=>t>t0&&t<tau),tau])).sort((a,b)=>a-b);
    for(let k=0;k<cuts.length-1;k++){const l=cuts[k]!,u=cuts[k+1]!;wideSumAdd(areaSum,survAt(l)*(u-l),cuts.length+1);}
    const area=wideSumValue(areaSum);
    const varianceSum=wideSum();
    const finiteTimes=rows.filter(o=>Number.isFinite(o.time)).map(o=>Math.abs(o.time));
    const largestTime=Number.isFinite(tau)?Math.max(Math.abs(tau),Math.abs(t0),...finiteTimes):0;
    const exponent=Math.max(-1074,Math.min(1023,Math.floor(Math.log2(largestTime))));
    const timeScale=largestTime===0?1:2**exponent;
    if(Number.isFinite(tau)){
      for(const ev of eventRows){if(ev.t>tau||ev.n<=ev.d)continue;
        const aSum=wideSum();const c2=Array.from(new Set([ev.t,...eventRows.map(e=>e.t).filter(t=>t>ev.t&&t<tau),tau])).sort((a,b)=>a-b);
        for(let k=0;k<c2.length-1;k++) wideSumAdd(aSum,survAt(c2[k]!)*((c2[k+1]!-c2[k]!)/timeScale),c2.length+1);
        const A=wideSumValue(aSum);
        wideSumAdd(varianceSum,A*A*ev.d/(ev.n*(ev.n-ev.d)),eventRows.length+1);
      }
    }
    const varianceScaled=wideSumValue(varianceSum);
    out.rmean.push(rmean==="none"?NaN:area);out.seRmean.push(rmean==="none"?NaN:Math.sqrt(varianceScaled)*timeScale);
    tableRows.push(rmean==="none"
      ? (confType==="none"?[records,out.nMax[g]!,out.nStart[g]!,out.events[g]!,out.median[g]![0]!]
        :[records,out.nMax[g]!,out.nStart[g]!,out.events[g]!,out.median[g]![0]!,out.median[g]![1]!,out.median[g]![2]!])
      : (confType==="none"?[records,out.nMax[g]!,out.nStart[g]!,out.events[g]!,area,Math.sqrt(varianceScaled)*timeScale,out.median[g]![0]!]
        :[records,out.nMax[g]!,out.nStart[g]!,out.events[g]!,area,Math.sqrt(varianceScaled)*timeScale,out.median[g]![0]!,out.median[g]![1]!,out.median[g]![2]!]));
  }
  out.table={colNames:[...(rmean==="none"?["records","n.max","n.start","events","median"]:["records","n.max","n.start","events","rmean","se(rmean)","median"]),
    ...(confType==="none"?[]:[`${confInt}LCL`,`${confInt}UCL`])],rowNames:names,table:tableRows};
  return reported("survfit", out);
}
