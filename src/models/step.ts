/**
 * A formula fit that the stepwise functions take: the result of {@link lm} or {@link glm} with a formula.
 *
 * @category Model selection
 */
export type StepModel = LmFormulaResult | GlmFormulaResult;

/**
 * Options of {@link extractAIC}.
 *
 * @category Model selection
 */
