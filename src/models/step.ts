/**
 * The criterion of a fit for model selection: `[edf, criterion]`. Equivalent to R's `extractAIC()`. lm: n log(RSS / n) + k edf, or with `scale > 0`
 * Mallows' Cp = RSS / scale − n + k edf; glm: AIC + (k − 2) edf. n counts the rows used (weight-0 rows included) and
 * edf = n − the residual degrees of freedom, so that with weight-0 rows edf exceeds the rank by their number, as in R.
 *
 * @param fit A fit of {@link lm} or {@link glm} with a formula.
 *
 * @example
 * ```ts
 * const data = { y: [1.2, 2.3, 2.9, 4.1, 5.2, 5.8], x: [1, 2, 3, 4, 5, 6] };
 * extractAIC(lm("y ~ x", data)); // [2, -19.211]
 * ```
 *
 * @category Model selection
 */
export function extractAIC(fit: StepModel, options: ExtractAicOptions = {}): [number, number] {
  checkOptions(options, EXTRACT_AIC_KEYS, "extractAIC"); // generated: option-keys.mjs
  const k = checkNumber(options.k ?? 2, "k");
  const scale = checkNumber(options.scale ?? 0, "scale", true);
  return criterionOf(fit, k, scale);
}

/**
 * The models with one term dropped, for lm and glm. Equivalent to R's `drop1()`. With the change of the residual sum of squares or
 * the deviance, the criterion of {@link extractAIC} (edf the rank) and optionally a test. As in R, each model is the
 * fit's model matrix without the columns of the term, on the rows of `fit` (not a refit of a formula). By default
 * only the terms not contained in another term of the model are dropped (marginality).
 *
 * @param fit A fit of {@link lm} or {@link glm} with a formula.
 * @param data The data frame the fit was made from.
 *
 * @example
 * ```ts
 * const data = { y: [1.2, 2.3, 2.9, 4.1, 5.2, 5.8, 7.1, 7.9], x: [1, 2, 3, 4, 5, 6, 7, 8], z: [5, 3, 8, 1, 9, 2, 7, 4] };
 * drop1(lm("y ~ x + z", data), data, { test: "F" }).term; // ["<none>", "x", "z"]
 * ```
 *
 * @category Model selection
 */
export function drop1(fit: StepModel, data: DataFrame, options: AddDropOptions = {}): AddDropTable {
  checkOptions(options, DROP1_KEYS, "drop1"); // generated: option-keys.mjs
  const ctx = contextOf(fit, data, "drop1");
  const k = checkNumber(options.k ?? 2, "k");
  const scale = ctx.glm ? 0 : checkNumber(options.scale ?? 0, "scale", true);
  const model = termsOfFit(fit);
  const drops = options.scope === undefined ? dropScope(model, []) : termsOfScope(options.scope, data, "drop1").map((t) => {
    const m = model.find((u) => u.key === t.key);
    if (m === undefined) throw new RangeError(`scope is not a subset of term labels`);
    return m;
  });
  const warnings = new Warnings();
  addWarnings(warnings, fit);
  const rows = dropRows(fit, drops, k, scale, warnings);
  const table = tableOf(rows, ctx.glm, scale, warnings);
  if (options.test !== undefined && options.test !== "none") Object.assign(table, { test: options.test === "F" ? "F" : "Chisq" }, testColumns(rows, options.test === "F" ? "F" : "Chisq", false));
  table.warnings = warnings.list.filter((m) => !fit.warnings.includes(m));
  return reported("drop1", table, fit);
}

/**
 * The models with one term added, for lm and glm. Equivalent to R's `add1()`. With the change of the residual sum of squares or the
 * deviance, the criterion of {@link extractAIC} (edf the rank) and optionally a test. The terms are those of `scope`
 * that can be added respecting marginality. Every model is refitted on the rows complete in the variables of the
 * model and of all the terms; when these are fewer than the fit's rows the current model is refitted on them too,
 * with R's warning "using the m/n rows from a combined fit".
 *
 * @param fit A fit of {@link lm} or {@link glm} with a formula.
 * @param data The data frame the fit was made from.
 *
 * @example
 * ```ts
 * const data = { y: [1.2, 2.3, 2.9, 4.1, 5.2, 5.8, 7.1, 7.9], x: [1, 2, 3, 4, 5, 6, 7, 8], z: [5, 3, 8, 1, 9, 2, 7, 4] };
 * add1(lm("y ~ 1", data), data, { scope: "~ x + z" }).term; // ["<none>", "x", "z"]
 * ```
 *
 * @category Model selection
 */
export function add1(fit: StepModel, data: DataFrame, options: AddDropOptions = {}): AddDropTable {
  checkOptions(options, ADD1_KEYS, "add1"); // generated: option-keys.mjs
  const ctx = contextOf(fit, data, "add1");
  if (options.scope === undefined) throw new TypeError("no terms in scope for adding to object");
  const k = checkNumber(options.k ?? 2, "k");
  const scale = ctx.glm ? 0 : checkNumber(options.scale ?? 0, "scale", true);
  const adds = addScope(termsOfFit(fit), termsOfScope(options.scope, data, "add1"));
  const warnings = new Warnings();
  addWarnings(warnings, fit);
  const rows = addRows(ctx, fit, adds, k, scale, warnings);
  const table = tableOf(rows, ctx.glm, scale, warnings);
  if (options.test !== undefined && options.test !== "none") Object.assign(table, { test: options.test === "F" ? "F" : "Chisq" }, testColumns(rows, options.test === "F" ? "F" : "Chisq", true));
  table.warnings = warnings.list.filter((m) => !fit.warnings.includes(m));
  return reported("add1", table, fit);
}

function search<F extends StepModel>(fit: F, data: DataFrame, options: StepOptions, caller: "step" | "stepAIC"): StepResult<F> {
  const ctx = contextOf(fit, data, caller);
  const direction = options.direction ?? "both";
  if (!["both", "backward", "forward"].includes(direction)) throw new RangeError(`'direction' should be one of "both", "backward", "forward"`);
  const k = checkNumber(options.k ?? 2, "k");
  const scale = ctx.glm ? 0 : checkNumber(options.scale ?? 0, "scale", true);
  const steps = checkNumber(options.steps ?? 1000, "steps", true);
  const model0 = termsOfFit(fit);

  // the scope: lower and upper terms (the default upper is the start model; a one-sided formula is the upper)
  // (without a scope "both" may add back a term it dropped: the upper scope is the start model)
  let lower: Term[] = [];
  let upper: Term[] = model0;
  const scope = options.scope;
  if (scope === undefined) {
    // the start model's terms
  } else if (typeof scope === "string") upper = termsOfScope(scope, data, "upper");
  else if (typeof scope === "object" && scope !== null) {
    if (scope.lower !== undefined) lower = termsOfScope(scope.lower, data, "lower");
    if (scope.upper !== undefined) upper = termsOfScope(scope.upper, data, "upper");
  } else throw new TypeError("scope must be a formula or { lower, upper }");
  for (const t of model0) if (!upper.some((u) => u.key === t.key)) throw new RangeError(`upper scope has term ‘${t.label}’ not included in model`);
  for (const t of lower) if (!model0.some((u) => u.key === t.key)) throw new RangeError(`lower scope has term ‘${t.label}’ not included in model`);
  const backward = direction !== "forward";
  const forward = direction !== "backward";

  const warnings = new Warnings();
  addWarnings(warnings, fit);
  let current: StepModel = fit;
  let [, aic] = criterionOf(current, k, scale);
  if (Number.isNaN(aic)) throw new RangeError(`AIC is not defined for this model, so '${caller === "step" ? "step" : "stepAIC"}' cannot proceed`);
  if (aic === -Infinity) throw new RangeError(`AIC is -infinity for this model, so '${caller === "step" ? "step" : "stepAIC"}' cannot proceed`);
  const n0 = nObs(current);
  const anova = { step: [""], df: [NaN], deviance: [NaN], residDf: [nObs(current) - criterionOf(current, k, scale)[0]], residDeviance: [devianceOf(current)], aic: [aic] };
  const visits: StepVisit[] = [{ formula: formulaOf(ctx, current.termLabels), termLabels: [...current.termLabels], aic }];
  const move = (next: StepModel, label: string, dropped: boolean): void => {
    // the refit of the chosen model on its own rows: R stops when that changes the number of rows used
    if (nObs(next) !== n0) throw new RangeError("number of rows in use has changed: remove missing values?");
    const [edf, a] = criterionOf(next, k, scale);
    const dfChange = next.dfResidual - current.dfResidual;
    anova.step.push(label);
    anova.df.push(caller === "step" ? dfChange : Math.abs(dfChange));
    anova.deviance.push(dropped ? devianceOf(next) - devianceOf(current) : devianceOf(current) - devianceOf(next));
    anova.residDf.push(nObs(next) - edf);
    anova.residDeviance.push(devianceOf(next));
    anova.aic.push(a);
    current = next;
    aic = a;
    visits.push({ formula: formulaOf(ctx, current.termLabels), termLabels: [...current.termLabels], aic });
  };

  let moves = 0;
  while (moves < steps) {
    const terms = termsOfFit(current);
    // a term whose columns are all aliased is removed first, without a table, the last such term first
    const aliased = terms.filter((_, j) => {
      const cols = (isGlmFit(current) ? current.coefNames : current.coefNames).map((_, c) => c).filter((c) => current.assign[c] === j + 1);
      return cols.length > 0 && cols.every((c) => Number.isNaN(current.coefficients[c]!));
    });
    if (aliased.length > 0) {
      const t = aliased[aliased.length - 1]!;
      const next = refitTerms(ctx, current.termLabels.filter((l) => l !== t.label));
      addWarnings(warnings, next);
      move(next, `- ${t.label}`, true);
      moves++;
      continue;
    }
    const drops = backward ? dropScope(terms, lower) : [];
    const adds = forward ? addScope(terms, upper) : [];
    let rows: Row[] = [];
    if (drops.length > 0) rows = dropRows(current, drops, k, scale, warnings).map((r, i) => (i === 0 ? r : { ...r, label: `- ${r.label}` }));
    if (adds.length > 0) {
      const a = addRows(ctx, current, adds, k, scale, warnings).map((r, i) => (i === 0 ? r : { ...r, label: `+ ${r.label}` }));
      // adds whose term would bring no column are not offered
      rows = rows.length === 0 ? a.filter((r, i) => i === 0 || r.df > 0) : [...rows, ...a.slice(1).filter((r) => r.df > 0)];
    }
    if (rows.length === 0) break;
    // sorted by the criterion, the table order kept among equal values (<none> first, then drops, then adds)
    const order = rows.map((_, i) => i).sort((i, j) => cmp(rows[i]!.aic, rows[j]!.aic) || i - j);
    const sorted = order.map((i) => rows[i]!);
    const last = visits[visits.length - 1]!;
    last.table = {
      move: sorted.map((r) => r.label),
      df: sorted.map((r) => r.df),
      deviance: sorted.map((r) => r.deviance),
      aic: sorted.map((r) => r.aic),
    };
    if (!ctx.glm) last.table.sumOfSq = sorted.map((r) => r.sumOfSq);
    if (order[0] === 0) break;
    const best = sorted[0]!;
    const dropped = best.label.startsWith("- ");
    const label = best.label.slice(2);
    const next = dropped ? refitTerms(ctx, current.termLabels.filter((l) => l !== label)) : refitTerms(ctx, [...current.termLabels, label]);
    addWarnings(warnings, next);
    move(next, best.label, dropped);
    moves++;
  }
  const result: StepResult<F> = { fit: current as F, anova, criterion: scale > 0 && !ctx.glm ? "Cp" : "AIC", visits, warnings: warnings.list.filter((m) => !fit.warnings.includes(m)) };
  return reported(caller, result, fit);
}

/** Ascending, NaN last */
const cmp = (a: number, b: number): number => (Number.isNaN(a) ? (Number.isNaN(b) ? 0 : 1) : Number.isNaN(b) ? -1 : a - b);

/**
 * Stepwise selection of the terms of a linear or generalized linear model by AIC. Equivalent to R's `step()`. From the start model,
 * each step examines the models with one term dropped (respecting marginality, keeping the lower scope) and, with an
 * upper scope, one term added, and moves to the one with the smallest criterion of {@link extractAIC} when it is
 * strictly below the current model's; it stops when no move improves it, or after `steps` moves. `k = Math.log(n)`
 * gives BIC. Terms whose columns are all aliased are removed first. The result holds the selected fit, the path
 * (R's `$anova`) and every table examined (R's printed trace).
 *
 * As in R, the models are refitted on their own rows: when a move changes the number of rows used (a variable with
 * missing values dropped or added) the search stops with an error, and the table of adds is computed on the rows
 * complete in all the candidates' variables (with a warning when those are fewer).
 *
 * @param fit The start model: a fit of {@link lm} or {@link glm} with a formula.
 * @param data The data frame the fit was made from.
 *
 * @example
 * ```ts
 * const data = { y: [1.2, 2.3, 2.9, 4.1, 5.2, 5.8, 7.1, 7.9], x: [1, 2, 3, 4, 5, 6, 7, 8], z: [5, 3, 8, 1, 9, 2, 7, 4] };
 * const s = step(lm("y ~ x + z", data), data);
 * s.fit.formula;  // "y ~ x"
 * s.anova.step;   // ["", "- z"]
 * ```
 *
 * @category Model selection
 */
export function step<F extends StepModel>(fit: F, data: DataFrame, options: StepOptions = {}): StepResult<F> {
  checkOptions(options, STEP_KEYS, "step"); // generated: option-keys.mjs
  checkOptions(nestedOptions(options, "scope"), STEP_SCOPE_KEYS, "step", "scope"); // generated: option-keys.mjs
  return search(fit, data, options, "step");
}

/**
 * Stepwise selection by AIC. Equivalent to `MASS::stepAIC()` in R. The same search as {@link step}; the only difference R shows is the
 * path's `df`, which stepAIC gives as the size of the term moved (positive) where step gives the change of the
 * residual degrees of freedom.
 *
 * @param fit The start model: a fit of {@link lm} or {@link glm} with a formula.
 * @param data The data frame the fit was made from.
 *
 * @example
 * ```ts
 * const data = { y: [1.2, 2.3, 2.9, 4.1, 5.2, 5.8, 7.1, 7.9], x: [1, 2, 3, 4, 5, 6, 7, 8], z: [5, 3, 8, 1, 9, 2, 7, 4] };
 * stepAIC(lm("y ~ 1", data), data, { scope: "~ x + z" }).anova.df; // [NaN, 1]
 * ```
 *
 * @category Model selection
 */
export function stepAIC<F extends StepModel>(fit: F, data: DataFrame, options: StepOptions = {}): StepResult<F> {
  checkOptions(options, STEP_AIC_KEYS, "stepAIC"); // generated: option-keys.mjs
  checkOptions(nestedOptions(options, "scope"), STEP_AIC_SCOPE_KEYS, "stepAIC", "scope"); // generated: option-keys.mjs
  return search(fit, data, options, "stepAIC");
}
