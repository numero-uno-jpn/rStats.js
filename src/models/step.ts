// The tables

interface Row {
  label: string;
  df: number;
  sumOfSq: number;
  deviance: number;
  aic: number;
  rank: number;
  dfResidual: number;
  /** lm: log of the RSS (see logRss) */
  logDev: number;
  /** The model's fit, for <none> and the adds (refitted from a formula); undefined for drops (fits of columns) */
  fit: StepModel | undefined;
}

/** lm: R's warning when the current model fits essentially perfectly (RSS below 1e-10 of the weighted Σ y²) */
function perfectFitCheck(fit: StepModel, warnings: Warnings): void {
  if (isGlmFit(fit)) return;
  const w = fit.weights;
  let ssy = 0;
  fit.y.forEach((y, i) => (ssy += (w?.[i] ?? 1) * y * y));
  if (fit.rss < 1e-10 * ssy) warnings.add("attempting model selection on an essentially perfect fit is nonsense");
}

/** The warnings of a refit, without lm's warning of summary() (R's step does not call summary) */
function addWarnings(warnings: Warnings, fit: StepModel): void {
  for (const m of fit.warnings) if (isGlmFit(fit) || m !== "essentially perfect fit: summary may be unreliable") warnings.add(m);
}

/** The rows of positive prior weight of a glm */
const positiveRows = (fit: GlmFormulaResult): number => fit.priorWeights.filter((w) => w > 0).length;
/** glm: the families whose dispersion is fixed at 1 */
const fixedDispersion = (fit: GlmFormulaResult): boolean => fit.family === "binomial" || fit.family === "poisson";

/**
 * The change of −2 log-likelihood from the current model `none` to a model of deviance `dev`, as R's drop1 / add1 for
 * glm: gaussian n log(dev / dev₀) (the dispersion profiled out); binomial and poisson the change of deviance; the other
 * families the change of deviance over the current model's (Pearson) dispersion, an approximation that R uses for the
 * AIC column as well (so that for Gamma the table's AIC is not that of the refitted model, nor is the selection)
 */
function scaledDeviance(none: GlmFormulaResult, dev: number): number {
  if (none.family === "gaussian") return positiveRows(none) * Math.log(dev / none.deviance);
  if (fixedDispersion(none)) return dev - none.deviance;
  return (dev - none.deviance) / glmDispersion(none);
}

/** The row of the current model */
function noneRow(fit: StepModel, k: number, scale: number): Row {
  const n = nResiduals(fit);
  // the table's edf is the rank (R's drop1 / add1), not extractAIC's n − df.residual
  const edf = rankOf(fit);
  const logDev = isGlmFit(fit) ? NaN : logRss(fit);
  const aic = isGlmFit(fit) ? fit.aic + (k - 2) * edf : scale > 0 ? fit.rss / scale - n + k * edf : n * (logDev - Math.log(n)) + k * edf;
  return { label: "<none>", df: NaN, sumOfSq: NaN, deviance: devianceOf(fit), aic, rank: edf, dfResidual: fit.dfResidual, logDev, fit };
}

/** A row from a model's deviance and rank, against the current model's row */
function candidateRow(none: Row, label: string, dev: number, rank: number, dfResidual: number, adding: boolean, k: number, scale: number, logDev = Math.log(dev), fit?: StepModel): Row {
  const base = none.fit!;
  const df = adding ? rank - none.rank : none.rank - rank;
  let aic: number;
  if (isGlmFit(base)) aic = none.aic + scaledDeviance(base, dev) + k * (rank - none.rank);
  else {
    const n = nResiduals(base);
    aic = scale > 0 ? dev / scale - n + k * rank : n * (logDev - Math.log(n)) + k * rank;
  }
  return { label, df, sumOfSq: adding ? none.deviance - dev : dev - none.deviance, deviance: dev, aic, rank, dfResidual, logDev, fit };
}

/**
 * drop1's rows: the current model and each term dropped, as R's drop1 fits them: the columns of the term taken out of
 * the current model matrix (on its rows), not a refit of a formula (dropping x1 from y ~ x1 * f keeps the columns of
 * x1:f as they are coded, so it removes a degree of freedom)
 */
/** glm: R computes the dispersion for the tables of the families without a fixed one (with its warnings) */
function dispersionWarnings(fit: StepModel, warnings: Warnings): void {
  if (isGlmFit(fit) && !fixedDispersion(fit)) glmDispersion(fit, warnings);
}

function dropRows(fit: StepModel, drops: readonly Term[], k: number, scale: number, warnings: Warnings): Row[] {
  perfectFitCheck(fit, warnings);
  dispersionWarnings(fit, warnings);
  const none = noneRow(fit, k, scale);
  const terms = termsOfFit(fit);
  const out = [none];
  for (const t of drops) {
    const j = terms.findIndex((u) => u.key === t.key) + 1;
    const cols = fit.assign.flatMap((a, c) => (a === j ? [] : [c]));
    if (isGlmFit(fit)) {
      const w = new Warnings();
      const r = refit(fit.model, cols, w);
      for (const m of w.list) warnings.add(m);
      out.push(candidateRow(none, t.label, r.fit.deviance, r.fit.rank, positiveRows(fit) - r.fit.rank, false, k, scale));
    } else {
      const core = fitLm(fit.x.map((row) => cols.map((c) => row[c]!)), fit.y, fit.weights, fit.coefNames[0] === "(Intercept)" && cols[0] === 0, true);
      out.push(candidateRow(none, t.label, core.rss, core.result.rank, core.result.dfResidual, false, k, scale, logRssCore(core)));
    }
  }
  return out;
}

/**
 * add1's rows: on the rows complete in the model's and all the candidates' variables (with R's warning when that is
 * fewer than the model's rows; the current model is then refitted on them too, so the table and the path differ)
 */
function addRows(ctx: Context, fit: StepModel, adds: readonly Term[], k: number, scale: number, warnings: Warnings): Row[] {
  let rows = rowsOf(fit);
  let base = fit;
  const extra = [...new Set(adds.flatMap((t) => t.vars))].filter((v) => !fit.variables.includes(v));
  if (extra.length > 0) {
    const levels = ctx.options.levels as Record<string, readonly string[]> | undefined;
    const sub = restrict(ctx, rows).data;
    const complete = modelFrame(sub, extra, levels === undefined ? {} : { levels }).rows.map((i) => rows[i]!);
    if (complete.length < rows.length) {
      warnings.add(`using the ${complete.length}/${rows.length} rows from a combined fit`);
      rows = complete;
      base = refitTerms(ctx, fit.termLabels, rows);
    }
  }
  perfectFitCheck(base, warnings);
  dispersionWarnings(base, warnings);
  const none = noneRow(base, k, scale);
  // glm on fewer rows: R keeps the current fit's own AIC for <none> and adds to it the scaled changes of deviance on
  // the rows of the combined fit (so the table mixes the two sets of rows); lm recomputes <none> on those rows
  if (isGlmFit(base) && base !== fit) none.aic = noneRow(fit, k, scale).aic;
  const out: Row[] = [none];
  for (const t of adds) {
    const m = refitTerms(ctx, [...fit.termLabels, t.label], rows);
    addWarnings(warnings, m);
    out.push(candidateRow(none, t.label, devianceOf(m), rankOf(m), m.dfResidual, true, k, scale, isGlmFit(m) ? NaN : logRss(m), m));
  }
  return out;
}

/** The tests of drop1 / add1 (the larger model of each comparison: the current one for drops, the candidate for adds) */
function testColumns(rows: readonly Row[], test: "F" | "Chisq", adding: boolean): { statistic: number[]; pValue: number[]; statisticName: string } {
  const none = rows[0]!;
  const base = none.fit!;
  const statistic = [NaN];
  const pValue = [NaN];
  for (const r of rows.slice(1)) {
    const big = adding ? r : none;
    const change = Math.abs(r.deviance - none.deviance);
    let s: number;
    let p: number;
    if (test === "F") {
      // the change per degree of freedom against the residual deviance per degree of freedom of the larger model
      s = change / r.df / (big.deviance / big.dfResidual);
      p = pf(s, r.df, big.dfResidual, { lowerTail: false });
    } else {
      s = isGlmFit(base) ? Math.abs(scaledDeviance(base, r.deviance)) : change / (big.deviance / big.dfResidual);
      p = pchisq(s, r.df, { lowerTail: false });
    }
    statistic.push(r.df === 0 ? NaN : s);
    pValue.push(r.df === 0 ? NaN : p);
  }
  const statisticName = test === "F" ? "F value" : isGlmFit(base) && fixedDispersion(base) ? "LRT" : "scaled dev.";
  return { statistic, pValue, statisticName };
}

function tableOf(rows: readonly Row[], glmFit: boolean, scale: number, warnings: Warnings): AddDropTable {
  const out: AddDropTable = {
    term: rows.map((r) => r.label),
    df: rows.map((r) => r.df),
    deviance: rows.map((r) => r.deviance),
    aic: rows.map((r) => r.aic),
    criterion: scale > 0 && !glmFit ? "Cp" : "AIC",
    warnings: warnings.list,
  };
  if (!glmFit) out.sumOfSq = rows.map((r) => r.sumOfSq);
  return out;
}

function checkNumber(v: unknown, name: string, positive = false): number {
  if (typeof v !== "number" || Number.isNaN(v)) throw new TypeError(`${name} must be a number`);
  if (positive ? !(v >= 0) : !Number.isFinite(v)) throw new RangeError(`${name} must be ${positive ? "non-negative" : "finite"}`);
  return v;
}

