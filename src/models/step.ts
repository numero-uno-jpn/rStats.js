// Terms and scopes

interface Term {
  label: string;
  /** Its variables, sorted (the identity of the term) */
  key: string;
  vars: string[];
}

function termsOfFit(fit: StepModel): Term[] {
  return fit.termLabels.map((label, j) => {
    const vars = fit.variables.filter((_, v) => (fit.factors[v]?.[j] ?? 0) !== 0);
    return { label, vars, key: [...vars].sort().join("\u0000") };
  });
}

function termsOfScope(scope: string, data: DataFrame, what: string): Term[] {
  if (typeof scope !== "string") throw new TypeError(`the ${what} scope must be a formula such as "~ x1 + x2"`);
  const text = scope.includes("~") ? scope : `~ ${scope}`;
  const parsed = parseFormula(text);
  const hasDot = (n: unknown): boolean =>
    typeof n === "object" && n !== null && ((n as { type?: string }).type === "dot" || Object.values(n).some((c) => typeof c === "object" && hasDot(c)));
  if (hasDot(parsed.rhs)) throw new RangeError(`'.' is not supported in the ${what} scope: list its terms`);
  const t = termsOf({ response: undefined, rhs: parsed.rhs }, Object.keys(data));
  return t.termLabels.map((label, j) => {
    const vars = t.variables.filter((_, v) => (t.factors[v]?.[j] ?? 0) !== 0);
    return { label, vars, key: [...vars].sort().join("\u0000") };
  });
}

const contains = (big: Term, small: Term): boolean => small.vars.length < big.vars.length && small.vars.every((v) => big.vars.includes(v));

/** The terms of the model that may be dropped: not in the lower scope, not contained in another term of the model */
function dropScope(model: readonly Term[], lower: readonly Term[]): Term[] {
  return model.filter((t) => !lower.some((l) => l.key === t.key) && !model.some((u) => contains(u, t)));
}

/** The terms of the upper scope that may be added: not in the model, every term of the upper scope inside it in the model */
function addScope(model: readonly Term[], upper: readonly Term[]): Term[] {
  const inModel = (t: Term): boolean => model.some((m) => m.key === t.key);
  return upper.filter((t) => !inModel(t) && upper.every((u) => !contains(t, u) || inModel(u)));
}

