// The models

/** What the refits of one search share */
interface Context {
  data: DataFrame;
  glm: boolean;
  /** The text of the response (left-hand side of the formula) */
  lhs: string;
  intercept: boolean;
  options: Readonly<Record<string, unknown>>;
  /** The variables that the frame of the start model dropped rows for besides the formula's (none) */
  nAll: number;
}

const isGlmFit = (fit: StepModel): fit is GlmFormulaResult => "linearPredictors" in fit;

function contextOf(fit: StepModel, data: DataFrame, caller: string): Context {
  if (typeof fit !== "object" || fit === null || typeof (fit as { formula?: unknown }).formula !== "string" || !Array.isArray((fit as { termLabels?: unknown }).termLabels)) {
    throw new TypeError(`${caller} needs a fit of lm or glm with a formula`);
  }
  if (typeof data !== "object" || data === null) throw new TypeError("data must be an object of columns");
  const g = isGlmFit(fit);
  const options = fitOptions(fit);
  if (options === undefined) {
    // a copy of a result: its options are not known; usable only when it had none that matter
    const weighted = g ? fit.model.priorGiven.some((w) => w !== 1) || fit.model.hasOffset : fit.weights !== undefined;
    if (weighted || g) throw new TypeError(`${caller} needs the fit as returned by lm or glm (its options are not known)`);
  }
  const tilde = fit.formula.indexOf("~");
  const lhs = fit.formula.slice(0, tilde).trim();
  const intercept = g ? fit.model.intercept : fit.coefNames[0] === "(Intercept)";
  const nAll = Object.values(data)[0]?.length ?? 0;
  return { data, glm: g, lhs, intercept, options: options ?? {}, nAll };
}

/** The formula of a model with these terms */
function formulaOf(ctx: Context, labels: readonly string[]): string {
  if (labels.length === 0) return `${ctx.lhs} ~ ${ctx.intercept ? "1" : "0"}`;
  return `${ctx.lhs} ~ ${labels.join(" + ")}${ctx.intercept ? "" : " - 1"}`;
}

/** The data (and the options' arrays) restricted to some rows */
function restrict(ctx: Context, rows: readonly number[]): { data: DataFrame; options: Record<string, unknown> } {
  const pick = (col: unknown): unknown => {
    if (col instanceof Float64Array) return Float64Array.from(rows, (i) => col[i]!);
    if (Array.isArray(col) && col.length === ctx.nAll) return rows.map((i) => col[i]);
    return col;
  };
  const data = Object.fromEntries(Object.entries(ctx.data).map(([k, c]) => [k, pick(c)])) as DataFrame;
  const options: Record<string, unknown> = { ...ctx.options };
  for (const key of ["weights", "offset"]) if (typeof options[key] === "object" && options[key] !== null) options[key] = pick(options[key]);
  return { data, options };
}

/** A refit with these terms, on all rows or on some */
function refitTerms(ctx: Context, labels: readonly string[], rows?: readonly number[]): StepModel {
  const { data, options } = rows === undefined ? { data: ctx.data, options: { ...ctx.options } } : restrict(ctx, rows);
  const formula = formulaOf(ctx, labels);
  const fit = unreported(() => (ctx.glm ? glm(formula, data, options) : lm(formula, data, options)));
  if (rows !== undefined) {
    // the rows in the indices of the whole data
    const used = ctx.glm ? (fit as GlmFormulaResult).model.rows : (fit as LmFormulaResult).rows;
    const mapped = used.map((i) => rows[i]!);
    if (ctx.glm) (fit as GlmFormulaResult).model.rows = mapped;
    else (fit as LmFormulaResult).rows = mapped;
  }
  return fit;
}

const rowsOf = (fit: StepModel): number[] => (isGlmFit(fit) ? fit.model.rows : fit.rows);
/** The number of residuals (rows used, weight-0 rows included) */
const nResiduals = (fit: StepModel): number => rowsOf(fit).length;
/** The rows of positive weight (R's nobs) */
const nObs = (fit: StepModel): number => (isGlmFit(fit) ? fit.priorWeights.filter((w) => w > 0).length : fit.nObs);
const devianceOf = (fit: StepModel): number => (isGlmFit(fit) ? fit.deviance : fit.rss);
const rankOf = (fit: StepModel): number => fit.rank;

/**
 * log RSS of an lm fit: log(rss) while the sum is in range; otherwise (a response of 1e±300 overflows or underflows
 * the squares) from the residuals and weights in the log domain, so that the criterion stays finite where R's is
 * Inf (no move) or −Inf (an error). R gives the same values wherever its own are finite
 */
function logRss(fit: LmFormulaResult): number {
  const rss = fit.rss;
  if (rss > 1e-290 && rss < Infinity) return Math.log(rss);
  const w = fit.weights;
  const a: number[] = [];
  fit.residuals.forEach((r, i) => {
    const wi = w?.[i] ?? 1;
    if (wi > 0 && r !== 0) a.push(Math.log(Math.abs(r)) + 0.5 * Math.log(wi));
  });
  if (a.length === 0) return -Infinity;
  const m = Math.max(...a);
  return 2 * m + Math.log(a.reduce((t, v) => t + Math.exp(2 * (v - m)), 0));
}

/** log RSS of a fit of the matrix form (yScale: fitted to the response scaled by 2^-k) */
function logRssCore(core: { rss: number; yScale?: number; rssScaled?: number }): number {
  if (core.rss > 1e-290 && core.rss < Infinity) return Math.log(core.rss);
  if (core.yScale !== undefined && core.rssScaled !== undefined && core.rssScaled > 0) return Math.log(core.rssScaled) + 2 * core.yScale * Math.LN2;
  return Math.log(core.rss);
}

/** R's extractAIC: [edf, criterion] */
function criterionOf(fit: StepModel, k: number, scale: number): [number, number] {
  const n = nResiduals(fit);
  // edf = n − df.residual: with weight-0 rows (counted in n but not in the residual df) it exceeds the rank by their
  // number, as R's extractAIC (the selection is unchanged: every model of a search carries the same excess)
  const edf = n - fit.dfResidual;
  if (isGlmFit(fit)) return [edf, fit.aic + (k - 2) * edf];
  if (scale > 0) return [edf, fit.rss / scale - n + k * edf];
  return [edf, n * (logRss(fit) - Math.log(n)) + k * edf];
}

