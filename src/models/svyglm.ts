// survey's svyglm for the design of inverse probability weighting, svydesign(ids = ~1, weights = w): a glm with the
// weights rescaled to mean 1, the sandwich variance HC0 times n / (n - 1), and t tests on n - p degrees of freedom. The
// behaviour is in oracle/weightit-behaviour.md, from survey's documentation and published output; Lumley (2010),
// "Complex Surveys: A Guide to Analysis Using R", chapter 5. Written for rStats.js (no ported code).
import { glm, type GlmOptions, type GlmResult } from "./glm.js";
import { vcovHC } from "./sandwich.js";
import { pt } from "../distributions/t.js";
import type { MatrixInput } from "../linalg/matrix.js";
import type { Sample } from "../htest/types.js";
import { reported, unreported } from "../internal/warnings.js";
import { ldexp } from "../internal/summary.js";
// Generated by `node scripts/option-keys.mjs --write` from the option types; do not edit (begin)
import { checkOptions, nestedOptions } from "../internal/checkOptions.js";
const SVYGLM_KEYS = ["weights", "family", "link", "epsilon", "maxit"] as const;
const SVYGLM_FAMILY_KEYS = ["family", "link", "variance"] as const;
const SVYGLM_FAMILY_LINK_KEYS = ["power"] as const;
// Generated by `node scripts/option-keys.mjs --write` (end)

/**
 * Options for {@link svyglm}.
 *
 * @category Generalized linear models
 */
export interface SvyglmOptions {
  /** The sampling (inverse probability) weights, one per row, positive. */
  weights: Sample;
  /** The family, as {@link glm} (default `"gaussian"`). */
  family?: GlmOptions["family"];
  /** The link, as {@link glm}. */
  link?: GlmOptions["link"];
  /** Convergence tolerance, as {@link glm} (default `1e-8`). */
  epsilon?: number;
  /** Maximum number of iterations, as {@link glm} (default `25`). */
  maxit?: number;
}

/**
 * Result of {@link svyglm}: the rows of R's `summary(svyglm(...))$coefficients` and the fit.
 *
 * @category Generalized linear models
 */
export interface SvyglmResult {
  /** Column names: `"(Intercept)"`, `"x1"`, `"x2"`, ... */
  names: string[];
  /** Coefficients (the weighted glm's). */
  coefficients: number[];
  /** Standard errors, from `vcov`. */
  se: number[];
  /** t statistics. */
  tValue: number[];
  /** Two-sided p-values from the t distribution with `dfResidual` degrees of freedom. */
  pValue: number[];
  /** The design-based variance matrix (array of rows): sandwich HC0 times n / (n - 1). */
  vcov: number[][];
  /** Residual degrees of freedom of the design, n - p. */
  dfResidual: number;
  /** The dispersion R prints: the weighted variance of the Pearson residuals (about their weighted mean) times
   * n / (n - 1); it does not enter the standard errors. */
  dispersion: number;
  /** Deviance with the weights rescaled to mean 1 (R's). */
  deviance: number;
  /** Null deviance with the weights rescaled to mean 1 (R's). */
  nullDeviance: number;
  /** Fitted means. */
  fittedValues: number[];
  /** Linear predictors. */
  linearPredictors: number[];
  /** Iterations of the glm. */
  iter: number;
  /** Whether the glm converged. */
  converged: boolean;
  /** The weighted glm (weights rescaled to mean 1). */
  glm: GlmResult;
  /** R's warnings, each once. */
  warnings: string[];
}

/**
 * A generalised linear model for weighted data with design-based (sandwich) standard errors. Equivalent to
 * `survey::svyglm()` in R. The call followed is `summary(svyglm(y ~ ..., design, family))` for the design
 * `svydesign(ids = ~1, weights = ~w, data)`, the design of inverse probability of treatment weighting.
 *
 * The coefficients are those of `glm(y ~ ..., weights = w)`; the variance is the HC0 sandwich of that fit times
 * n / (n − 1), and the tests are t tests on n − p degrees of freedom. binomial and quasibinomial give the same table
 * (binomial warns about the non-integer successes, as R). AIC is not given (R gives NA).
 * @category Generalized linear models
 * @example
 * ```ts
 * const fit = svyglm([[1, 0.2], [0, 1.1], [1, -0.4], [0, 0.3], [1, 0.9], [0, -1.2]], [1, 0, 1, 1, 0, 0],
 *   { weights: [1.5, 2, 1.2, 3, 1.1, 2.5], family: "quasibinomial" });
 * fit.pValue; // [0.7799833144017342, 0.5461647344319471, 0.9579412581407588]
 * ```
 */
export function svyglm(x: MatrixInput | Sample, y: Sample, options: SvyglmOptions): SvyglmResult {
  checkOptions(options, SVYGLM_KEYS, "svyglm"); // generated: option-keys.mjs
  checkOptions(nestedOptions(options, "family"), SVYGLM_FAMILY_KEYS, "svyglm", "family"); // generated: option-keys.mjs
  checkOptions(nestedOptions(options, "family.link"), SVYGLM_FAMILY_LINK_KEYS, "svyglm", "family.link"); // generated: option-keys.mjs
  checkOptions(nestedOptions(options, "link"), SVYGLM_FAMILY_LINK_KEYS, "svyglm", "link"); // generated: option-keys.mjs
  const { weights, family, link, epsilon, maxit } = options;
  if (weights === undefined) throw new RangeError("'weights' must be given");
  const w = Array.from(weights);
  if (w.length !== y.length) throw new RangeError("'weights' must have the length of 'y'");
  if (w.some((v) => !(v > 0) || !Number.isFinite(v))) throw new RangeError("'weights' must be positive and finite");
  if (family === "quasi" || (typeof family === "object" && family !== null && family.family === "quasi")) {
    throw new RangeError("the quasi family is not available in svyglm (its variance function is not known here)");
  }
  const n = w.length;
  const mean = w.reduce((a, v) => a + v, 0) / n;
  // survey rescales the weights to mean 1: the deviance and glm's convergence test (|change| / (|dev| + 0.1)) are then R's
  const scaled = w.map((v) => v / mean);
  const fit = unreported(() => glm(x, y, {
    weights: scaled, ...(family === undefined ? {} : { family }), ...(link === undefined ? {} : { link }),
    ...(epsilon === undefined ? {} : { epsilon }), ...(maxit === undefined ? {} : { maxit }),
  }));
  // the variance from a fit on the columns (and a gaussian identity-link response) divided by powers of 2, exactly:
  // a coefficient's variance can be out of range (a column near 1e300 gives about 1e-600) while its standard error is
  // not; the scaled fit gives the standard errors, t values and p-values, the variance matrix is mapped back
  const rows = Array.isArray(x[0]) || ArrayBuffer.isView(x[0]) ? (x as MatrixInput).map((r) => Array.from(r as ArrayLike<number>))
    : Array.from(x as Sample, (v) => [v]);
  const exponent = (vals: ArrayLike<number>): number => {
    let top = 0;
    for (let i = 0; i < vals.length; i++) if (Number.isFinite(vals[i]!) && Math.abs(vals[i]!) > top) top = Math.abs(vals[i]!);
    return top > 0 ? Math.floor(Math.log2(top)) : 0;
  };
  const ex = (rows[0] ?? []).map((_, j) => exponent(rows.map((r) => r[j]!)));
  const fam = typeof family === "object" && family !== null ? family.family : family ?? "gaussian";
  const identity = fam === "gaussian" && (link === undefined || link === "identity") &&
    (typeof family !== "object" || family === null || family.link === undefined || family.link === "identity");
  const ey = identity ? exponent(y) : 0;
  const scaledFit = ex.every((e) => e === 0) && ey === 0 ? fit : unreported(() => glm(rows.map((r) => r.map((v, j) => ldexp(v, -ex[j]!))),
    Array.from(y, (v) => ldexp(v, -ey)), { weights: scaled, ...(family === undefined ? {} : { family }), ...(link === undefined ? {} : { link }),
      ...(epsilon === undefined ? {} : { epsilon }), ...(maxit === undefined ? {} : { maxit }) }));
  const hc0 = unreported(() => vcovHC(scaledFit, { type: "HC0" })).vcov;
  // the exponent of each coefficient: 2^(ey - e_j), the intercept's 2^ey
  const ec = [...(fit.coefficients.length > ex.length ? [ey] : []), ...ex.map((e) => ey - e)];
  const vcov = hc0.map((row, j) => row.map((v, k) => ldexp((v * n) / (n - 1), ec[j]! + ec[k]!)));
  const p = fit.coefficients.length;
  const dfResidual = n - p;
  const se = hc0.map((row, j) => ldexp(Math.sqrt((row[j]! * n) / (n - 1)), ec[j]!));
  const tValue = scaledFit.coefficients.map((b, j) => b / Math.sqrt((hc0[j]![j]! * n) / (n - 1)));
  const pValue = tValue.map((t) => 2 * pt(-Math.abs(t), dfResidual));
  // the dispersion: the design-based variance of the Pearson residuals (y - mu) / sqrt(V(mu)), weighted by the
  // rescaled weights about their weighted mean, times n / (n - 1)
  // from the scaled fit (a gaussian response divided by 2^ey), the result times 2^(2 ey)
  const mu = scaledFit.fittedValues, yy = scaledFit.y;
  const variance = fit.family === "binomial" || fit.family === "quasibinomial" ? (m: number) => m * (1 - m)
    : fit.family === "poisson" || fit.family === "quasipoisson" ? (m: number) => m
      : fit.family === "Gamma" ? (m: number) => m * m : fit.family === "inverse.gaussian" ? (m: number) => m * m * m : () => 1;
  const pearson = mu.map((m, i) => (yy[i]! - m) / Math.sqrt(variance(m)));
  const rbar = pearson.reduce((a, r, i) => a + scaled[i]! * r, 0) / n;
  let swr = 0;
  for (let i = 0; i < n; i++) swr += scaled[i]! * (pearson[i]! - rbar) ** 2;
  const dispersion = ldexp((swr / n) * (n / (n - 1)), 2 * ey);
  return reported("svyglm", {
    names: fit.model.columnNames.slice(), coefficients: fit.coefficients.slice(), se, tValue, pValue, vcov, dfResidual,
    dispersion, deviance: fit.deviance, nullDeviance: fit.nullDeviance, fittedValues: fit.fittedValues.slice(),
    linearPredictors: fit.linearPredictors.slice(), iter: fit.iter, converged: fit.converged, glm: fit,
    warnings: fit.warnings.slice(),
  });
}
