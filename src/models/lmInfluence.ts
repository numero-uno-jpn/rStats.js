// Influence measures of a linear model: R's hatvalues, rstandard, rstudent and cooks.distance for lm (stats).
//
// Written for rStats.js from the textbook definitions (Belsley, Kuh and Welsch 1980; Cook and Weisberg 1982), checked
// against R's output (experiments/plot121-log.md, experiments 1 and 2): with the weighted residuals r = sqrt(w) e,
// the leverages h (the diagonal of the hat matrix, from the fit's QR decomposition), s the residual standard error,
// p the rank and d the residual degrees of freedom,
//   rstandard = r / (s sqrt(1 - h)), the predictive type r / (1 - h),
//   rstudent = r / (s_(i) sqrt(1 - h)) with s_(i)^2 = (d s^2 - r^2 / (1 - h)) / (d - 1),
//   cooks.distance = rstandard^2 h / ((1 - h) p).
// As R, rows of zero weight are left out, a leverage within 10 machine epsilons of 1 is 1, and the measures of such
// a row are NaN.
import { qrQy } from "../linalg/qr.js";
import type { LmResult } from "./lm.js";
// Generated by `node scripts/option-keys.mjs --write` from the option types; do not edit (begin)
import { checkOptions } from "../internal/checkOptions.js";
const LM_RSTANDARD_KEYS = ["type"] as const;
// Generated by `node scripts/option-keys.mjs --write` (end)

const EPS = 2 ** -52;

/** The leverages and the weighted residuals of the rows of non-zero weight, in order */
function influenceRows(fit: LmResult): { h: number[]; r: number[]; e: number[] } {
  const q = fit.qr;
  const m = q.qr.length;
  let hq: number[] = new Array<number>(m).fill(0);
  if (fit.rank > 0) {
    const ident = Array.from({ length: m }, (_, i) => Array.from({ length: fit.rank }, (_, j) => (i === j ? 1 : 0)));
    const Q = qrQy(q, ident);
    hq = Q.map((row) => row.reduce((s, v) => s + v * v, 0));
  }
  const w = fit.weights;
  const h: number[] = [], r: number[] = [], e: number[] = [];
  let k = 0;
  fit.residuals.forEach((res, i) => {
    const wi = w?.[i] ?? 1;
    if (!(wi > 0)) return;
    const hi = hq[k++] ?? 0;
    h.push(hi > 1 - 10 * EPS ? 1 : hi);
    r.push(Math.sqrt(wi) * res);
    e.push(res);
  });
  return { h, r, e };
}

/**
 * The leverages (the diagonal of the hat matrix) of a linear model, one per row of non-zero weight. Equivalent to R's
 * `hatvalues()`. For an `lm` fit.
 *
 * @example
 * ```ts
 * const fit = lm([1, 2, 3, 4, 10], [1.1, 1.9, 3.2, 3.9, 7]);
 * lmHatvalues(fit); // the last point has the largest leverage
 * ```
 *
 * @category Linear models and ANOVA
 */
export function lmHatvalues(fit: LmResult): number[] {
  return influenceRows(fit).h;
}

/**
 * Options for {@link lmRstandard}.
 *
 * @category Linear models and ANOVA
 */
export interface LmRstandardOptions {
  /**
   * `"sd.1"` (default): the internally studentized residuals r / (s sqrt(1 - h)); `"predictive"`: the leave-one-out
   * prediction errors r / (1 - h) (r the residual times the square root of the weight) (as R's `type`).
   */
  type?: "sd.1" | "predictive";
}

/**
 * The standardized residuals of a linear model, one per row of non-zero weight. Equivalent to R's `rstandard()`. For
 * an `lm` fit; NaN for a row of leverage 1.
 *
 * @example
 * ```ts
 * lmRstandard(lm([1, 2, 3, 4, 10], [1.1, 1.9, 3.2, 3.9, 7]));
 * ```
 *
 * @throws RangeError for an unknown `type`.
 * @category Linear models and ANOVA
 */
export function lmRstandard(fit: LmResult, options: LmRstandardOptions = {}): number[] {
  checkOptions(options, LM_RSTANDARD_KEYS, "lmRstandard"); // generated: option-keys.mjs
  const type = options.type ?? "sd.1";
  if (type !== "sd.1" && type !== "predictive") throw new RangeError("'type' must be \"sd.1\" or \"predictive\"");
  const { h, r } = influenceRows(fit);
  if (type === "predictive") return r.map((v, i) => (h[i]! < 1 ? v / (1 - h[i]!) : NaN));
  return r.map((v, i) => (h[i]! < 1 ? v / (fit.sigma * Math.sqrt(1 - h[i]!)) : NaN));
}

/**
 * The externally studentized residuals of a linear model (each scaled by the residual standard error of the fit
 * without that row), one per row of non-zero weight. Equivalent to R's `rstudent()`. For an `lm` fit; NaN for a row of
 * leverage 1, and where the deleted fit has no residual degrees of freedom.
 *
 * @example
 * ```ts
 * lmRstudent(lm([1, 2, 3, 4, 10], [1.1, 1.9, 3.2, 3.9, 7]));
 * ```
 *
 * @category Linear models and ANOVA
 */
export function lmRstudent(fit: LmResult): number[] {
  const { h, r } = influenceRows(fit);
  const d = fit.dfResidual;
  const s = fit.sigma;
  return r.map((v, i) => {
    const hi = h[i]!;
    if (!(hi < 1)) return NaN;
    // in units of s, so that residuals near 1e200 do not overflow when squared
    const u = v / s;
    const si = s * Math.sqrt((d - (u * u) / (1 - hi)) / (d - 1));
    return v / (si * Math.sqrt(1 - hi));
  });
}

/**
 * Cook's distances of a linear model, one per row of non-zero weight. Equivalent to R's `cooks.distance()`. For an
 * `lm` fit; NaN for a row of leverage 1.
 *
 * @example
 * ```ts
 * lmCooksDistance(lm([1, 2, 3, 4, 10], [1.1, 1.9, 3.2, 3.9, 7]));
 * ```
 *
 * @category Linear models and ANOVA
 */
export function lmCooksDistance(fit: LmResult): number[] {
  const { h, r } = influenceRows(fit);
  return r.map((v, i) => {
    const hi = h[i]!;
    if (!(hi < 1)) return NaN;
    const t = v / (fit.sigma * (1 - hi));
    return (t * t * hi) / fit.rank;
  });
}
