/**
 * Fine-Gray proportional subdistribution hazards regression. Equivalent to `cmprsk::crr()` in R.
 * The censoring distribution is estimated by the verified {@link survfit}; Newton-Raphson
 * solves the weighted estimating equations and the variance is the subject-level sandwich.
 *
 * @param time Follow-up times (finite; negative values are allowed).
 * @param status Event codes.
 * @param cov1 Baseline covariate matrix (rows are observations); pass undefined when using only cov2.
 * @param options See {@link CrrOptions}.
 * @returns Coefficients, information, sandwich variance, baseline subdistribution hazard and diagnostics.
 *
 * @example
 * ```ts
 * const fit = crr([1, 2, 3, 4, 5, 6], [1, 0, 1, 2, 0, 1], [[0], [1], [2], [1], [0], [2]]);
 * fit.coefficients;
 * ```
 *
 * @category Survival analysis
 */
export function crr(
  time: readonly number[],
  status: readonly GroupLabel[],
  cov1: readonly (readonly number[])[] | undefined,
  options: CrrOptions = {},
): CrrResult {
  checkOptions(options, CRR_KEYS, "crr"); // generated: option-keys.mjs
  const { cov2, tf, failcode = 1, cencode = 0, gtol = 1e-6, maxiter = 10, init, variance = true,
    confLevel = 0.95, names } = options;
  if (time.length !== status.length) throw new RangeError("'time' and 'status' must have the same length");
  if (cov1 !== undefined && cov1.length !== time.length) throw new RangeError("'cov1' must have one row per observation");
  if (cov2 !== undefined && cov2.length !== time.length) throw new RangeError("'cov2' must have one row per observation");
  if (cov2 !== undefined && tf === undefined) throw new TypeError("'tf' is required when 'cov2' is supplied");
  if (!(gtol > 0) || !Number.isFinite(gtol)) throw new RangeError("'gtol' must be finite and positive");
  if (!Number.isInteger(maxiter) || maxiter < 0) throw new RangeError("'maxiter' must be a non-negative integer");
  if (!(confLevel > 0 && confLevel < 1)) throw new RangeError("'confLevel' must be between 0 and 1");
  const p1 = cov1?.[0]?.length ?? 0, p2 = cov2?.[0]?.length ?? 0, p = p1 + p2;
  if (p === 0) throw new RangeError("at least one covariate is required");
  if (cov1 !== undefined && cov1.some((r) => r.length !== p1)) throw new RangeError("rows of 'cov1' must have equal length");
  if (cov2 !== undefined && cov2.some((r) => r.length !== p2)) throw new RangeError("rows of 'cov2' must have equal length");
  if (init !== undefined && init.length !== p) throw new RangeError("'init' must have one value per coefficient");
  if (names !== undefined && names.length !== p) throw new RangeError("'names' must have one name per coefficient");
  const keep: number[] = [];
  for (let i = 0; i < time.length; i++) {
    const missing = Number.isNaN(time[i]!) || missingLabel(status[i]) ||
      (cov1 !== undefined && cov1[i]!.some(Number.isNaN)) || (cov2 !== undefined && cov2[i]!.some(Number.isNaN));
    if (missing) continue;
    if (!Number.isFinite(time[i]!)) throw new RangeError("'time' must contain only finite values");
    if ((cov1 !== undefined && !cov1[i]!.every(Number.isFinite)) || (cov2 !== undefined && !cov2[i]!.every(Number.isFinite))) {
      throw new RangeError("covariates must be finite");
    }
    keep.push(i);
  }
  const nMissing = time.length - keep.length;
  if (keep.length === 0) throw new RangeError("no complete observations");
  const t = keep.map((i) => time[i]!);
  const statusValues = factorLabels([...keep.map((i) => status[i]!), cencode, failcode]);
  const s = statusValues.slice(0, keep.length);
  const cencodeValue = statusValues[statusValues.length - 2]!;
  const failcodeValue = statusValues[statusValues.length - 1]!;
  const x1 = keep.map((i) => cov1 === undefined ? [] : Array.from(cov1[i]!));
  const x2 = keep.map((i) => cov2 === undefined ? [] : Array.from(cov2[i]!));
  const uftime = Array.from(new Set(t.filter((_, i) => s[i] === failcodeValue))).sort((a, b) => a - b);
  if (uftime.length === 0) throw new RangeError("no observations of 'failcode'");
  const tfs = p2 === 0 ? [[0]] : tf!(uftime).map((r) => Array.from(r));
  if (p2 > 0 && (tfs.length !== uftime.length || tfs.some((r) => r.length !== p2) || !finiteMatrix(tfs))) {
    throw new RangeError("'tf' must return a finite matrix with one row per unique failure time and one column per cov2 column");
  }
  const zByTime = uftime.map((_, j) => t.map((__, i) => [...x1[i]!, ...x2[i]!.map((v, k) => v * (tfs[j]![k] ?? 0))]));
  // Preserve distinct very small time values despite survfit's absolute timefix tolerance.
  const maxAbsTime = t.reduce((m, v) => Math.max(m, Math.abs(v)), 0);
  const timeScale = maxAbsTime > 0 && maxAbsTime < 1
    ? 2 ** Math.min(1023, Math.ceil(-Math.log2(maxAbsTime))) : 1;
  const censorFit = survfit(t.map((v) => v * timeScale), s.map((v) => (v === cencodeValue ? 1 : 0)));
  const censorBefore = (u: number): number => {
    const scaledU = u * timeScale;
    let g = 1;
    for (let j = 0; j < censorFit.time.length; j++) {
      if (censorFit.time[j]! >= scaledU) break;
      g = censorFit.surv[j]!;
    }
    return g;
  };
  const weights = uftime.map((u) => t.map((tj, i) => {
    if (tj >= u) return 1;
    if (s[i] === cencodeValue || s[i] === failcodeValue) return 0;
    const den = censorBefore(tj);
    return den === 0 ? 0 : censorBefore(u) / den;
  }));
  // Every failure at u belongs to its own Fine-Gray risk set, including the terminal
  // failure time when the censoring KM has already reached zero.
  for (let j = 0; j < uftime.length; j++) {
    for (let i = 0; i < t.length; i++) {
      if (t[i] === uftime[j] && s[i] === failcodeValue) weights[j]![i] = 1;
    }
  }
  const evaluate = (beta: readonly number[]): CrrState => {
    const scoreTerms = Array.from({ length: p }, () => [] as number[]);
    const infTerms = Array.from({ length: p }, () => Array.from({ length: p }, () => [] as number[]));
    const loglikTerms: number[] = [];
    const res = zeros(uftime.length, p), bfitj: number[] = [], means: number[][] = [], riskFactors: number[][] = [];
    for (let j = 0; j < uftime.length; j++) {
      const u = uftime[j]!;
      const dIndices = t.map((v, i) => v === u && s[i] === failcodeValue ? i : -1).filter((i) => i >= 0);
      const d = dIndices.length;
      const zz = zByTime[j]!;
      const lp = zz.map((row) => dot(beta, row));
      // Reassert the model definition locally: every failure at u is in its own risk set,
      // independently of the censoring KM (which may be zero after the last censoring time).
      const riskWeights = weights[j]!.slice();
      for (const i of dIndices) riskWeights[i] = 1;
      const maxLp = Math.max(...lp.map((v, i) => riskWeights[i]! > 0 ? v : -Infinity));
      if (maxLp === -Infinity) throw new Error("empty Fine-Gray risk set");
      // Match the direct exp/sum/log operation order of the estimating equations when safe.
      // Fall back to a common exponential scale only near overflow/underflow.
      const direct = maxLp < 500 && maxLp > -500;
      const rf = direct
        ? lp.map((v, i) => riskWeights[i]! * Math.exp(v))
        : lp.map((v, i) => riskWeights[i]! * Math.exp(v - maxLp));
      const s0 = sum(rf);
      const s1 = Array.from({ length: p }, (_, a) =>
        sum(rf.map((w, i) => w * zz[i]![a]!)));
      if (!(s0 > 0)) throw new Error("empty Fine-Gray risk set");
      const meanZ = s1.map((v) => v / s0);
      const needsCentering = Array.from({ length: p }, (_, a) => {
        const anchor = zz[0]![a]!;
        let spread = 0, magnitude = 0;
        for (const row of zz) {
          spread = Math.max(spread, Math.abs(row[a]! - anchor));
          magnitude = Math.max(magnitude, Math.abs(row[a]!));
        }
        return spread > 0 && magnitude / spread > 1e6;
      });
      const useCentered = needsCentering.some(Boolean);
      // Allocate centered columns only for the exceptional large-offset path; ordinary inputs
      // retain the original second-moment calculation and its operation order.
      const centered = useCentered
        ? Array.from({ length: p }, (_, a) => zz.map(row => row[a]! - zz[0]![a]!))
        : [];
      const centeredMean = useCentered
        ? centered.map(column => sum(column.map((v, i) => rf[i]! * v)) / s0)
        : [];
      const s2 = useCentered ? undefined : Array.from({ length: p }, (_, a) =>
        Array.from({ length: p }, (_, b) =>
          sum(rf.map((w, i) => w * zz[i]![a]! * zz[i]![b]!))));
      means.push(meanZ); riskFactors.push(rf.map((v) => v / s0));
      const b = direct ? d / s0 : (d * Math.exp(-maxLp)) / s0;
      bfitj.push(b);
      loglikTerms.push(sum(dIndices.map((i) => dot(beta, zz[i]!))) - d * (direct ? Math.log(s0) : maxLp + Math.log(s0)));
      for (let a = 0; a < p; a++) {
        // Sum the failures first, then subtract d times the risk-set mean. This avoids
        // repeatedly rounding the same mean subtraction for tied failures.
        const failureSum = sum(dIndices.map((i) => zz[i]![a]!));
        const increment = failureSum - d * meanZ[a]!;
        scoreTerms[a]!.push(increment);
        res[j]![a] = increment;
      }
      for (let a = 0; a < p; a++) for (let b0 = 0; b0 < p; b0++) {
        const covariance = useCentered
          ? sum(rf.map((w, i) => w * (centered[a]![i]! - centeredMean[a]!) *
              (centered[b0]![i]! - centeredMean[b0]!))) / s0
          : s2![a]![b0]! / s0 - meanZ[a]! * meanZ[b0]!;
        infTerms[a]![b0]!.push(d * covariance);
      }
    }
    const eta = zeros(t.length, p);
    for (let j = 0; j < uftime.length; j++) {
      const zz = zByTime[j]!, rf = riskFactors[j]!, meanZ = means[j]!;
      const u = uftime[j]!;
      for (let i = 0; i < t.length; i++) {
        const isFail = t[i] === u && s[i] === failcodeValue ? 1 : 0;
        const d = t.filter((v, k) => v === u && s[k] === failcodeValue).length;
        const mult = isFail - rf[i]! * d;
        for (let a = 0; a < p; a++) eta[i]![a]! += (zz[i]![a]! - meanZ[a]!) * mult;
      }
    }
    const score = scoreTerms.map(sum);
    const inf = infTerms.map((row) => row.map(sum));
    const loglik = sum(loglikTerms);
    return { loglik, score, inf, bfitj, res, eta, means, riskFactors, zByTime };
  };
  const initial = init === undefined ? new Array<number>(p).fill(0) : Array.from(init);
  if (!initial.every(Number.isFinite)) throw new RangeError("'init' must contain finite values");
  let beta = initial.slice(), state = evaluate(beta), converged = false, iterations = 0;
  const criterion = (st: CrrState, b: readonly number[]) =>
    Math.max(...st.score.map((u, j) => Math.abs(u) * Math.max(Math.abs(b[j]!), 1))) <
    gtol * Math.max(Math.abs(st.loglik), 1);
  for (;;) {
    if (criterion(state, beta)) { converged = true; break; }
    if (iterations >= maxiter) break;
    const step = solve(state.inf, state.score, { tol: 0 });
    beta = beta.map((v, j) => v + step[j]!);
    iterations++;
    state = evaluate(beta);
  }
  // The R algorithm tests once more at the final beta after maxiter steps; the loop above does so naturally.
  const invinf = solve(state.inf);
  let varianceMatrix = zeros(p);
  if (variance) {
    const meat = zeros(p);
    const n = t.length;
    const times = Array.from(new Set(t)).sort((a, b) => a - b);
    const dLambda = times.map((v) => {
      const risk = t.filter((x) => x >= v).length;
      const d = t.filter((x, i) => x === v && s[i] === cencodeValue).length;
      return risk === 0 ? 0 : d / risk;
    });
    const psi = zeros(n, p);
    for (let vi = 0; vi < times.length; vi++) {
      const v = times[vi]!;
      let q = new Array<number>(p).fill(0);
      for (let i = 0; i < n; i++) {
        if (!(t[i]! < v) || s[i] === cencodeValue || s[i] === failcodeValue) continue;
        for (let j = 0; j < uftime.length; j++) {
          if (uftime[j]! < v) continue;
          const rf = state.riskFactors[j]![i]!;
          const d = t.filter((v, k) => v === uftime[j] && s[k] === failcodeValue).length;
          const zz = state.zByTime[j]![i]!;
          const meanZ = state.means[j]!;
          for (let a = 0; a < p; a++) q[a]! += (zz[a]! - meanZ[a]!) * rf * d;
        }
      }
      const risk = t.filter((x) => x >= v).length;
      if (risk === 0) continue;
      for (let i = 0; i < n; i++) {
        const indicator = t[i] === v && s[i] === cencodeValue ? 1 : 0;
        const compensator = t[i]! >= v ? dLambda[vi]! : 0;
        for (let a = 0; a < p; a++) psi[i]![a]! += (q[a]! / risk) * (indicator - compensator);
      }
    }
    for (let i = 0; i < n; i++) addOuter(meat, state.eta[i]!.map((v, a) => v + psi[i]![a]!), state.eta[i]!.map((v, a) => v + psi[i]![a]!), 1);
    varianceMatrix = zeros(p);
    const left = multiply(invinf, meat);
    varianceMatrix = multiply(left, invinf);
  } else {
    varianceMatrix = zeros(p).map((r) => r.map(() => NaN));
  }
  const se = variance ? varianceMatrix.map((r, i) => Math.sqrt(r[i]!)) : undefined;
  const z = se === undefined ? undefined : beta.map((v, i) => v / se[i]!);
  const pValue = z === undefined ? undefined : z.map((v) => 2 * pnorm(-Math.abs(v)));
  const q = variance ? qnorm((1 + confLevel) / 2) : undefined;
  const lower = q === undefined ? undefined : beta.map((v, i) => Math.exp(v - q * se![i]!));
  const upper = q === undefined ? undefined : beta.map((v, i) => Math.exp(v + q * se![i]!));
  const expCoef = variance ? beta.map(Math.exp) : undefined;
  const coefNames = names === undefined
    ? [...Array.from({ length: p1 }, (_, i) => `cov1${i + 1}`),
      ...Array.from({ length: p2 }, (_, i) => `cov2${i + 1}*tf${i + 1}`)]
    : Array.from(names);
  return reported("crr", {
    coefficients: beta, names: coefNames, var: varianceMatrix,
    ...(se === undefined ? {} : { se, z: z!, pValue: pValue!, lower: lower!, upper: upper!, expCoef: expCoef! }),
    loglik: state.loglik, loglikNull: evaluate(new Array<number>(p).fill(0)).loglik,
    logtest: { statistic: 2 * (state.loglik - evaluate(new Array<number>(p).fill(0)).loglik), df: p },
    score: state.score, inf: variance ? state.inf : zeros(p).map((r) => r.map(() => NaN)),
    invinf: variance ? invinf : zeros(p).map((r) => r.map(() => NaN)),
    converged, iterations, n: keep.length, nMissing, uftime, bfitj: state.bfitj, res: variance ? state.res : null,
    tfs, warnings: [], covariateDimensions: [p1, p2] as [number, number],
  });
}

/** Matrix product for the small information matrices of Fine-Gray regression. */
function multiply(a: readonly (readonly number[])[], b: readonly (readonly number[])[]): number[][] {
  const out = zeros(a.length, b[0]?.length ?? 0);
  for (let i = 0; i < a.length; i++) for (let j = 0; j < (b[0]?.length ?? 0); j++) {
    for (let k = 0; k < b.length; k++) out[i]![j]! += a[i]![k]! * b[k]![j]!;
  }
  return out;
}

/**
 * Predict cumulative incidence from a Fine-Gray fit. Equivalent to `cmprsk::predict.crr()` in R.
 *
 * @param fit Result of {@link crr}.
 * @param cov1 New baseline covariate matrix.
 * @param cov2 New time-varying covariate matrix, when the fit used cov2.
 * @returns A matrix whose first column is failure time and remaining columns are predicted incidences.
 *
 * @example
 * ```ts
 * const fit = crr([1, 2, 3, 4, 5, 6], [1, 0, 1, 2, 0, 1], [[0], [1], [2], [1], [0], [2]]);
 * predictCrr(fit, [[0], [1]]);
 * ```
 *
 * @category Survival analysis
 */
export function predictCrr(
  fit: CrrResult,
  cov1: readonly (readonly number[])[] | undefined,
  cov2?: readonly (readonly number[])[],
): number[][] {
  const [p1, p2] = fit.covariateDimensions;
  if (p1 > 0 && cov1 === undefined) throw new TypeError("'cov1' is required by this fit");
  if (p2 > 0 && cov2 === undefined) throw new TypeError("'cov2' is required by this fit");
  if (p1 > 0 && cov1!.some((r) => r.length !== p1)) throw new RangeError("'cov1' has the wrong number of columns");
  if (p2 > 0 && cov2!.some((r) => r.length !== p2)) throw new RangeError("'cov2' has the wrong number of columns");
  if (p1 > 0 && p2 > 0 && cov1!.length !== cov2!.length) throw new RangeError("'cov1' and 'cov2' must have the same number of rows");
  const n = p1 > 0 ? cov1!.length : cov2!.length;
  const tfs = p2 === 0 ? fit.uftime.map(() => [0]) : fit.tfs;
  const out = fit.uftime.map((u, j) => {
    const row = [u];
    for (let i = 0; i < n; i++) {
      let cumulative = 0;
      for (let k = 0; k <= j; k++) {
        const z = [...(p1 === 0 ? [] : cov1![i]!), ...(p2 === 0 ? [] : cov2![i]!.map((v, h) => v * tfs[k]![h]!))];
        const baseline = fit.bfitj[k]!;
        const eta = dot(fit.coefficients, z);
        const direct = baseline * Math.exp(eta);
        const increment = Number.isFinite(direct) && (direct !== 0 || baseline === 0)
          ? direct
          : baseline === 0 ? 0 : Math.exp(Math.log(baseline) + eta);
        cumulative += increment;
      }
      row.push(-Math.expm1(-cumulative));
    }
    return row;
  });
  return out;
}
