/** Eigenvalues of the Hessian within this of 0 (or below) are left out of its inverse and warned about */
const HESSIAN_TOLERANCE = 1e-8;
/** Eigenvalues of L V L' at most this times the largest are left out of a joint test */
const RANK_TOLERANCE = Math.sqrt(Number.EPSILON);
/** Satterthwaite's degrees of freedom of a joint test are averaged when they differ by less than this */
const EQUAL_DF_TOLERANCE = 1e-8;

/**
 * The Satterthwaite quantities of a fit (internal): the variance parameters varpar = (θ, σ), the Hessian H of the
 * deviance in them with its eigenvalues, their asymptotic covariance A = 2 H⁺ (lmerTest's `vcov_varpar`), the fixed
 * effects β̂ with their covariance V = C(varpar) and its Jacobians J_k = ∂C/∂varpar_k, and the warnings of the Hessian.
 */
export interface LmerSatterthwaite {
  varpar: number[];
  hessian: number[][];
  hessianEigenvalues: number[];
  vcovVarpar: number[][];
  beta: number[];
  sigma: number;
  vcov: number[][];
  jacobian: number[][][];
  warnings: string[];
  /**
   * The quantities above are those of the response divided by 2^scale (0 unless its squares overflow or underflow; issue
   * #9): estimates, standard errors and right-hand sides are scaled by it in the tests, sums of squares by 4^scale
   */
  scale: number;
  /**
   * The quantities above are also those of X with column k divided by 2^xScale[k] (β, vcov and the jacobian in the
   * units of β'_k = 2^xScale[k] β_k): 0 unless the column's largest |value| is beyond 2^±500, where the cross-products
   * of X overflow or underflow (predictors times 1e-160 gave a vcov of Infinity and standard errors NaN). The tests
   * take their contrasts to these units (L β = (L D⁻¹) β' with D = diag(2^xScale))
   */
  xScale: number[];
}

/** A contrast in the units of the scaled columns of X (see LmerSatterthwaite.xScale) */
function scaledContrast(s: LmerSatterthwaite, l: readonly number[]): readonly number[] {
  return s.xScale.every((e) => e === 0) ? l : l.map((v, k) => ldexp(v, -s.xScale[k]!));
}

const satterthwaiteByFit = new WeakMap<LmerResult, LmerSatterthwaite>();

/** A number as C's printf("%1.1e") writes it: "-3.2e-04" */
function formatE1(v: number): string {
  if (!Number.isFinite(v)) return Number.isNaN(v) ? "nan" : v > 0 ? "inf" : "-inf";
  const [mantissa, exponent] = v.toExponential(1).split("e") as [string, string];
  const e = Number(exponent);
  return `${mantissa}e${e < 0 ? "-" : "+"}${String(Math.abs(e)).padStart(2, "0")}`;
}

/** The warnings about the Hessian's eigenvalues (negative, or close to 0; internal) */
export function hessianWarnings(values: readonly number[]): string[] {
  const out: string[] = [];
  const negative = values.filter((v) => v < -HESSIAN_TOLERANCE);
  const zero = values.filter((v) => Math.abs(v) < HESSIAN_TOLERANCE);
  const plural = (k: number): string => (k === 1 ? "eigenvalue" : "eigenvalues");
  if (negative.length > 0) {
    out.push(`Model failed to converge with ${negative.length} negative ${plural(negative.length)}: ${negative.map(formatE1).join(" ")}`);
  }
  if (zero.length > 0) {
    out.push(`Model may not have converged with ${zero.length} ${plural(zero.length)} close to zero: ${zero.map(formatE1).join(" ")}`);
  }
  return out;
}

/**
 * The Satterthwaite quantities of a fit by {@link lmer} (see {@link LmerSatterthwaite}), computed once per fit.
 * Internal: the summary, the contrasts and the ANOVA tables use it.
 */
export function lmerSatterthwaite(fit: LmerResult): LmerSatterthwaite {
  const cached = satterthwaiteByFit.get(fit);
  if (cached !== undefined) return cached;
  const internals = lmerInternals(fit);
  const result = satterthwaiteAt(internals.structure, internals.theta, internals.reml, internals.beta0);
  satterthwaiteByFit.set(fit, result);
  return result;
}

/**
 * The Satterthwaite quantities at any θ (σ from the penalised residual sum of squares there), `beta0` added to the
 * fixed effects (those of a fit's structure, whose response is y − X β₀). Internal: the test evaluates them at lme4's
 * optimum too, to compare with lmerTest's numerical derivatives at the same point.
 */
export function satterthwaiteAt(
  structure: MixedModelStructure,
  theta: readonly number[],
  reml: boolean,
  beta0: readonly number[] = [],
): LmerSatterthwaite {
  // a response whose squares overflow or underflow: the derivatives of the response divided by 2^scale (as lmer fits it)
  let top = 0;
  for (const v of structure.y) top = Math.max(top, Math.abs(v));
  const scale = top > 2 ** 500 || top < 2 ** -500 ? Math.floor(Math.log2(top)) : 0;
  const scaledY = scale === 0 ? structure : { ...structure, y: structure.y.map((v) => ldexp(v, -scale)) };
  // columns of X of extreme scale divided by powers of 2 (exact; see LmerSatterthwaite.xScale): otherwise nothing changes
  const xScale = extremeColumnExponents(structure.x, structure.xColNames.length);
  const st = xScale.every((e) => e === 0) ? scaledY : { ...scaledY, x: scaledY.x.map((row) => row.map((v, k) => ldexp(v, -xScale[k]!))) };
  const d = varparDerivatives(st, theta, reml);
  const m = d.varpar.length;
  // The Hessian in coordinates of comparable scale, D H D: θ_k times 2^e_k (the columns of Z of its row; see
  // thetaColumnExponents) and σ over a power of 2 near σ̂. Its eigenvalues are cut at the tolerance there, A' = 2 H'⁺
  // and A = D A' D. In (θ, σ) themselves the curvature in σ scales as 1/σ² and that in θ with the columns of Z, so the
  // absolute cut dropped directions by the units alone (response × 1e6: the df of x 7.4e8 for 31, as lmerTest's;
  // issue #10)
  const sigmaHat = d.varpar[m - 1]!;
  const kSigma = sigmaHat > 0 && Number.isFinite(sigmaHat) ? Math.round(Math.log2(sigmaHat)) : 0;
  const ex = [...thetaColumnExponents(structure).theta.map((v) => -v), kSigma];
  const hScaled = d.hessian.map((row, i) => row.map((v, j) => ldexp(v, ex[i]! + ex[j]!)));
  const e = eigen(hScaled, { symmetric: true });
  const values = e.values;
  const vectors = e.vectors!;
  const vcovVarpar = Array.from({ length: m }, () => new Array<number>(m).fill(0));
  values.forEach((lambda, k) => {
    if (!(lambda > HESSIAN_TOLERANCE)) return;
    for (let i = 0; i < m; i++) {
      const vi = (2 * vectors[i]![k]!) / lambda;
      for (let j = 0; j < m; j++) vcovVarpar[i]![j]! += vi * vectors[j]![k]!;
    }
  });
  vcovVarpar.forEach((row, i) => row.forEach((v, j) => (row[j] = ldexp(v, ex[i]! + ex[j]!))));
  return {
    varpar: d.varpar,
    hessian: d.hessian,
    hessianEigenvalues: values,
    vcovVarpar,
    beta: d.beta.map((b, k) => b + ldexp(beta0[k] ?? 0, xScale[k]! - scale)),
    sigma: d.varpar[m - 1]!,
    vcov: d.vcov,
    jacobian: d.jacobian,
    warnings: hessianWarnings(values),
    scale,
    xScale,
  };
}

const quadraticForm = (l: readonly number[], m: readonly (readonly number[])[]): number => {
  let s = 0;
  for (let i = 0; i < l.length; i++) {
    const li = l[i]!;
    if (li === 0) continue;
    const row = m[i]!;
    for (let j = 0; j < l.length; j++) s += li * row[j]! * l[j]!;
  }
  return s;
};
const dot = (a: readonly number[], b: readonly number[]): number => a.reduce((s, v, i) => s + v * b[i]!, 0);

/** The one-dimensional test of a contrast l (internal) */
export interface TRow {
  estimate: number;
  stdError: number;
  df: number;
  tValue: number;
  pValue: number;
}

/** l'β̂ − rhs over its standard error, with Satterthwaite's degrees of freedom 2 var² / (g'Ag), g_k = l'J_k l */
export function tTestOf(s: LmerSatterthwaite, l0: readonly number[], rhs0: number): TRow {
  return tTestScaled(s, scaledContrast(s, l0), rhs0, s.beta);
}

/** {@link tTestOf} with l in the units of the scaled columns of X (see LmerSatterthwaite.xScale) */
function tTestScaled(s: LmerSatterthwaite, l0: readonly number[], rhs0: number, beta: readonly number[]): TRow {
  if (l0.some(Number.isNaN) || Number.isNaN(rhs0)) return { estimate: NaN, stdError: NaN, df: NaN, tValue: NaN, pValue: NaN };
  // a contrast of extreme magnitude (1e160, 1e-200) divided by 2^k with its rhs: the test does not depend on it, and
  // l'Vl overflowed or underflowed (#58); the estimate and the standard error are scaled back by 2^k
  const k = rangeExponent(l0);
  const l = k === 0 ? l0 : l0.map((v) => ldexp(v, -k));
  const rhs = ldexp(rhs0, -k);
  // (in the units of the scaled response, the estimate and the standard error scaled back; see LmerSatterthwaite.scale)
  const estimate = dot(l, beta);
  const variance = quadraticForm(l, s.vcov);
  const stdError = Math.sqrt(variance);
  const g = s.jacobian.map((j) => quadraticForm(l, j));
  const df = (2 * variance * variance) / quadraticForm(g, s.vcovVarpar);
  const tValue = (estimate - ldexp(rhs, -s.scale)) / stdError;
  const pValue = 2 * pt1(Math.abs(tValue), df, false, false);
  return { estimate: ldexp(estimate, s.scale + k), stdError: ldexp(stdError, s.scale + k), df, tValue, pValue };
}

/** One row of an F table (internal): lmerTest's `Sum Sq`, `Mean Sq`, `NumDF`, `DenDF`, `F value`, `Pr(>F)` */
export interface LmerFRow {
  sumSq: number;
  meanSq: number;
  numDF: number;
  denDF: number;
  F: number;
  pValue: number;
}

function fRowOf(s: LmerSatterthwaite, f: number, numDF: number, denDF: number): LmerFRow {
  const s2 = s.sigma * s.sigma;
  return { sumSq: ldexp(f * s2 * numDF, 2 * s.scale), meanSq: ldexp(f * s2, 2 * s.scale), numDF, denDF, F: f, pValue: pf1(f, numDF, denDF, false, false) };
}

/** The denominator degrees of freedom of a joint test from those of its rotated contrasts (exported for the tests) */
export function jointDenDF(nu: readonly number[]): number {
  if (nu.length === 1) return nu[0]!;
  // (equal infinite df are equal: Inf - Inf is NaN, and all Inf gave NaN, an error in lmerTest)
  if (nu.every((v, i) => i === 0 || v === nu[i - 1] || Math.abs(v - nu[i - 1]!) < EQUAL_DF_TOLERANCE)) return nu.reduce((a, b) => a + b, 0) / nu.length;
  if (nu.some((v) => v <= 2)) return 2;
  // (as lmerTest: with every ν > 2 each term ν/(ν − 2) exceeds 1, so e > nu.length and the result is positive; the term
  // of an infinite ν is its limit 1, where Inf / Inf was NaN)
  const e = nu.reduce((sum, v) => sum + (v === Infinity ? 1 : v / (v - 2)), 0);
  return (2 * e) / (e - nu.length);
}

/**
 * The joint F-test of the rows of L (r × p) with Satterthwaite's denominator degrees of freedom (internal; the ANOVA
 * tables use it): undefined when the rows have rank 0 (no test). `rhs` has one value per row (default 0); a non-zero
 * right-hand side with a rank-deficient L adds the warning to `warnings`.
 */
export function lmerFTest(fit: LmerResult, L: readonly (readonly number[])[], rhs: readonly number[] | undefined, warnings: Warnings): LmerFRow | undefined {
  return fTestOf(lmerSatterthwaite(fit), L, rhs, warnings);
}

/** {@link lmerFTest} with the Satterthwaite quantities given (internal) */
export function fTestOf(s: LmerSatterthwaite, L0: readonly (readonly number[])[], rhs: readonly number[] | undefined, warnings: Warnings): LmerFRow | undefined {
  const r = L0.length;
  if (r === 0) return undefined;
  // L of extreme magnitude and its rhs divided by one power of 2 (the test does not depend on it; the same factor for
  // every row keeps the eigenvectors of L V L', and with them the rotated contrasts and the df). L V L' overflowed or
  // underflowed (#58)
  const L1 = L0.map((row) => scaledContrast(s, row));
  const k = rangeExponent(L1.flat());
  const L = k === 0 ? L1 : L1.map((row) => row.map((v) => ldexp(v, -k)));
  // (the right-hand side in the units of the scaled response: tTestOf scales its own, the joint test below uses these)
  const given = (rhs ?? new Array<number>(r).fill(0)).map((v) => ldexp(v, -k));
  const right = given.map((v) => ldexp(v, -s.scale));
  if (r === 1) {
    // A contrast of rank 0 (L V L' = 0, such as a row of zeros) has no hypothesis to test, as for several rows below
    const l = L[0]!;
    if (!l.some(Number.isNaN) && !(l.reduce((sum, v, j) => sum + v * l.reduce((t, w, k) => t + s.vcov[j]![k]! * w, 0), 0) > 0)) return undefined;
    const t = tTestScaled(s, l, given[0]!, s.beta);
    return fRowOf(s, t.tValue * t.tValue, 1, t.df);
  }
  if (L.some((row) => row.some(Number.isNaN)) || right.some(Number.isNaN)) return fRowOf(s, NaN, NaN, NaN);
  // L V L' and its eigendecomposition
  const lv = L.map((row) => s.vcov.map((_, j) => row.reduce((sum, v, k) => sum + v * s.vcov[k]![j]!, 0)));
  const e = eigen(
    lv.map((a) => L.map((rj) => dot(a, rj))),
    { symmetric: true },
  );
  const d = e.values;
  const cut = Math.max(RANK_TOLERANCE * d[0]!, 0);
  let kept = 0;
  while (kept < r && d[kept]! > cut) kept++;
  if (kept === 0) return undefined;
  if (kept < r && right.some((v) => v !== 0)) warnings.add("Contrast is rank deficient and test may be affected");
  // β̂ − b0 with b0 = ginv(L) rhs, the minimum-norm solution of L b0 = rhs
  let beta = s.beta;
  if (right.some((v) => v !== 0)) {
    const g = ginv(L.map((row) => [...row]));
    beta = s.beta.map((b, i) => b - dot(g[i]!, right));
  }
  const p = s.beta.length;
  const rotated = Array.from({ length: kept }, (_, k) =>
    Array.from({ length: p }, (_, j) => L.reduce((sum, row, i) => sum + e.vectors![i]![k]! * row[j]!, 0)),
  );
  if (kept === 1) {
    const t = tTestScaled(s, rotated[0]!, 0, beta);
    return fRowOf(s, t.tValue * t.tValue, 1, t.df);
  }
  let f = 0;
  const nu: number[] = [];
  rotated.forEach((row, i) => {
    f += dot(row, beta) ** 2 / d[i]!;
    const g = s.jacobian.map((j) => quadraticForm(row, j));
    nu.push((2 * d[i]! * d[i]!) / quadraticForm(g, s.vcovVarpar));
  });
  return fRowOf(s, f / kept, kept, jointDenDF(nu));
}

