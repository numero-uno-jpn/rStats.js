/** Options of {@link confintLmer} and {@link confintGlmer}. */
export interface MixedConfintOptions {
  /** Two-sided confidence level. Default 0.95. */
  level?: number;
  /** "profile" (default) or "Wald" (fixed effects only). */
  method?: "profile" | "Wald";
  /** Parameter names, one-based positions, "theta_" (variance parameters), or "beta_" (fixed effects). */
  parm?: string | number | readonly (string | number)[];
  /** Use lme4's .sig01 names (default), or descriptive standard-deviation and correlation names. */
  signames?: boolean | number;
}

/** Confidence intervals from a mixed-model fit. Missing limits are NaN. */
export interface MixedConfintResult {
  /** Parameter names in the same order as the limits. */
  names: string[];
  /** Lower confidence limits. */
  lower: number[];
  /** Upper confidence limits. */
  upper: number[];
  /** Warnings from profiling or parameter selection. */
  warnings: string[];
}

type ParameterKind = "sd" | "cor" | "sigma" | "beta";
interface Parameter {
  name: string;
  descriptive: string;
  kind: ParameterKind;
  value: number;
  term?: number;
  row?: number;
  col?: number;
  beta?: number;
}

interface ParameterSet {
  parameters: Parameter[];
  varianceCount: number;
  betaStart: number;
}

function parameterSet(
  terms: readonly RandomEffectsTerm[],
  groups: readonly { name: string }[],
  varCorr: readonly { sd: number[]; corr: number[][] }[],
  beta: readonly number[],
  sigma: number | undefined,
): ParameterSet {
  const parameters: Parameter[] = [];
  let serial = 1;
  for (let t = 0; t < terms.length; t++) {
    const term = terms[t]!;
    const vc = varCorr[t]!;
    for (let i = 0; i < term.columns.length; i++) {
      parameters.push({
        name: `.sig${String(serial++).padStart(2, "0")}`,
        descriptive: `sd_${term.columns[i]}|${groups[term.group]!.name}`,
        kind: "sd",
        value: vc.sd[i]!,
        term: t,
        row: i,
      });
    }
    for (let i = 1; i < term.columns.length; i++) {
      for (let j = 0; j < i; j++) {
        parameters.push({
          name: `.sig${String(serial++).padStart(2, "0")}`,
          descriptive: `cor_${term.columns[i]}.${term.columns[j]}|${groups[term.group]!.name}`,
          kind: "cor",
          value: Number.isFinite(vc.corr[i]![j]!) ? vc.corr[i]![j]! : 0,
          term: t,
          row: i,
          col: j,
        });
      }
    }
  }
  const varianceCount = parameters.length;
  if (sigma !== undefined) {
    parameters.push({ name: ".sigma", descriptive: "sigma", kind: "sigma", value: sigma });
  }
  const betaStart = parameters.length;
  beta.forEach((value, i) => {
    const name = (arguments[0] as never) as never;
    void name;
    parameters.push({ name: "", descriptive: "", kind: "beta", value, beta: i });
  });
  return { parameters, varianceCount, betaStart };
}

function nameParameters(set: ParameterSet, fixefNames: readonly string[], signames: boolean): string[] {
  return set.parameters.map((p) => {
    if (p.kind === "beta") return fixefNames[p.beta!]!;
    return signames ? p.name : p.descriptive;
  });
}

function transform(p: Parameter, value = p.value): number {
  if (p.kind === "sd" || p.kind === "sigma") return Math.log(Math.max(value, 1e-14));
  if (p.kind === "cor") return Math.atanh(Math.max(-1 + 1e-12, Math.min(1 - 1e-12, value)));
  return value;
}

function inverseTransform(p: Parameter, value: number): number {
  if (p.kind === "sd" || p.kind === "sigma") return Math.exp(value);
  if (p.kind === "cor") return Math.tanh(value);
  return value;
}

function choleskyCorrelation(corr: number[][]): number[][] | undefined {
  const n = corr.length;
  const l = Array.from({ length: n }, () => new Array<number>(n).fill(0));
  for (let i = 0; i < n; i++) {
    for (let j = 0; j <= i; j++) {
      let value = corr[i]![j]!;
      for (let k = 0; k < j; k++) value -= l[i]![k]! * l[j]![k]!;
      if (i === j) {
        if (!(value > 0) || !Number.isFinite(value)) return undefined;
        l[i]![j] = Math.sqrt(value);
      } else {
        if (l[j]![j] === 0) return undefined;
        l[i]![j] = value / l[j]![j]!;
      }
    }
  }
  return l;
}

function thetaOf(
  terms: readonly RandomEffectsTerm[],
  parameters: readonly Parameter[],
  values: readonly number[],
  sigma: number,
  scaleBySigma: boolean,
): number[] | undefined {
  const theta: number[] = [];
  for (let t = 0; t < terms.length; t++) {
    const nc = terms[t]!.columns.length;
    const sd = new Array<number>(nc);
    const corr = Array.from({ length: nc }, (_, i) => Array.from({ length: nc }, (_, j) => (i === j ? 1 : 0)));
    for (let k = 0; k < parameters.length; k++) {
      const p = parameters[k]!;
      if (p.term !== t) continue;
      if (p.kind === "sd") sd[p.row!] = values[k]!;
      else if (p.kind === "cor") corr[p.row!]![p.col!] = corr[p.col!]![p.row!] = values[k]!;
    }
    const l = choleskyCorrelation(corr);
    if (l === undefined) return undefined;
    const scale = scaleBySigma ? sigma : 1;
    for (let j = 0; j < nc; j++) {
      for (let i = j; i < nc; i++) theta.push((sd[i]! / scale) * l[i]![j]!);
    }
  }
  return theta;
}

function chooseParameters(names: readonly string[], raw: MixedConfintOptions["parm"], warnings: string[]): number[] {
  if (raw === undefined) return names.map((_, i) => i);
  const requested = Array.isArray(raw) ? raw : [raw];
  const selected = new Set<number>();
  for (const item of requested) {
    if (typeof item === "number" || (typeof item === "string" && /^\d+$/.test(item))) {
      const index = typeof item === "number" ? Math.trunc(item) - 1 : Number(item) - 1;
      if (index >= 0 && index < names.length) selected.add(index);
      continue;
    }
    if (typeof item !== "string") continue;
    if (item === "theta_") {
      names.forEach((_, i) => { if (i < names.length && !/^\(/.test(names[i]!)) selected.add(i); });
      continue;
    }
    if (item === "beta_") {
      names.forEach((name, i) => { if (name.startsWith("(") || /^[A-Za-z]/.test(name)) selected.add(i); });
      continue;
    }
    const index = names.indexOf(item);
    if (index >= 0) selected.add(index);
    else warnings.push(`Nothing selected by 'which="${item}"'`);
  }
  return [...selected].sort((a, b) => a - b);
}

function profileOptimizer(
  parameters: readonly Parameter[],
  terms: readonly RandomEffectsTerm[],
  scaleBySigma: boolean,
  evaluate: (values: readonly number[], target: number, targetValue: number) => number,
  target: number,
  targetValue: number,
  kind: "lmer" | "glmer",
): number {
  const free = parameters.map((p, i) => (i === target || (kind === "lmer" && p.kind === "beta") ? -1 : i)).filter((i) => i >= 0);
  const start = free.map((i) => transform(parameters[i]!));
  const valueAt = (x: readonly number[]): number => {
    const values = parameters.map((p) => p.value);
    free.forEach((i, j) => (values[i] = inverseTransform(parameters[i]!, x[j]!)));
    values[target] = targetValue;
    const sigmaIndex = parameters.findIndex((p) => p.kind === "sigma");
    const sigma = sigmaIndex < 0 ? 1 : values[sigmaIndex]!;
    const theta = thetaOf(terms, parameters, values, sigma, scaleBySigma);
    return theta === undefined ? Infinity : evaluate(values, target, targetValue);
  };
  if (free.length === 0) return valueAt([]);
  const problem: MinimiserProblem = {
    evaluate: (x) => {
      const f = valueAt(x);
      const g = x.map((v, j) => {
        const h = 2e-5 * Math.max(1, Math.abs(v));
        const a = x.slice();
        const b = x.slice();
        a[j] = v + h;
        b[j] = v - h;
        const fa = valueAt(a);
        const fb = valueAt(b);
        if (Number.isFinite(fa) && Number.isFinite(fb)) return (fa - fb) / (2 * h);
        if (Number.isFinite(fa) && Number.isFinite(f)) return (fa - f) / h;
        if (Number.isFinite(fb) && Number.isFinite(f)) return (f - fb) / h;
        return 0;
      });
      return { f, g };
    },
    diagonal: new Array<boolean>(free.length).fill(false),
    columns: [],
    settings: LMER_SETTINGS,
    rejectNonFinite: true,
    failure: "mixed-model profile minimisation did not converge",
    robust: true,
  };
  try {
    return minimiseWithRestarts(problem, start, []).f;
  } catch {
    return Infinity;
  }
}

function profileLimit(
  estimate: number,
  parameter: Parameter,
  targetDeviance: number,
  direction: -1 | 1,
  profile: (value: number) => number,
): number {
  const cutoff = targetDeviance;
  const boundary = parameter.kind === "sd" ? 0 : parameter.kind === "cor" ? (direction < 0 ? -1 : 1) : parameter.kind === "sigma" ? 0 : undefined;
  if (boundary !== undefined && estimate === boundary) return boundary;
  const at = (x: number): number => profile(x) - cutoff;
  let inside = estimate;
  let outside = estimate + direction * Math.max(parameter.kind === "beta" ? 0.25 : Math.abs(estimate) * 0.2, parameter.kind === "cor" ? 0.05 : 0.05);
  if (boundary !== undefined && (direction < 0 ? outside < boundary : outside > boundary)) outside = boundary;
  let fOutside = at(outside);
  for (let i = 0; i < 18 && !(fOutside >= 0); i++) {
    if (boundary !== undefined && outside === boundary) return direction < 0 && parameter.kind === "sd" ? boundary : NaN;
    const step = Math.abs(outside - inside) * 1.8;
    outside = estimate + direction * step;
    if (boundary !== undefined) outside = direction < 0 ? Math.max(boundary, outside) : Math.min(boundary, outside);
    fOutside = at(outside);
  }
  if (!(fOutside >= 0)) {
    if (boundary !== undefined && parameter.kind === "sd" && direction < 0) return boundary;
    return NaN;
  }
  let lo = Math.min(inside, outside);
  let hi = Math.max(inside, outside);
  let flo = inside < outside ? -1 : 1;
  for (let i = 0; i < 34; i++) {
    const mid = lo + (hi - lo) / 2;
    const fm = at(mid);
    if (!Number.isFinite(fm)) return NaN;
    if ((direction < 0 && fm >= 0) || (direction > 0 && fm < 0)) hi = mid;
    else lo = mid;
    if (hi - lo <= 2e-10 * Math.max(1, Math.abs(mid))) break;
  }
  void flo;
  return lo + (hi - lo) / 2;
}

function profileIntervals(
  kind: "lmer" | "glmer",
  parameters: readonly Parameter[],
  terms: readonly RandomEffectsTerm[],
  scaleBySigma: boolean,
  targetFor: (values: readonly number[], target: number, targetValue: number) => number,
  indices: readonly number[],
  level: number,
  warnings: string[],
): { lower: number[]; upper: number[] } {
  const z = qnorm((1 + level) / 2) as number;
  const cutoff = z * z;
  const lower = new Array<number>(parameters.length).fill(NaN);
  const upper = new Array<number>(parameters.length).fill(NaN);
  const cache = new Map<string, number>();
  for (const index of indices) {
    const p = parameters[index]!;
    const estimate = p.value;
    const at = (value: number): number => {
      const key = `${index}:${value.toPrecision(16)}`;
      const cached = cache.get(key);
      if (cached !== undefined) return cached;
      const d = profileOptimizer(parameters, terms, scaleBySigma, targetFor, index, value, kind);
      cache.set(key, d);
      return d;
    };
    const dHat = at(estimate);
    if (!Number.isFinite(dHat)) {
      warnings.push(`NAs detected in profiling for ${p.name}`);
      continue;
    }
    const cutoffD = dHat + cutoff;
    const profile = (value: number): number => at(value) - cutoffD;
    lower[index] = profileLimit(estimate, p, cutoffD, -1, profile);
    upper[index] = profileLimit(estimate, p, cutoffD, 1, profile);
    if (Number.isNaN(lower[index]!) || Number.isNaN(upper[index]!)) warnings.push(`NAs detected in profiling for ${p.name}`);
  }
  return { lower, upper };
}

function resultOf(
  parameters: readonly Parameter[],
  names: string[],
  selected: readonly number[],
  level: number,
  method: "profile" | "Wald",
  profile: (() => { lower: number[]; upper: number[] }) | undefined,
  standardErrors: readonly number[],
  warnings: string[],
): MixedConfintResult {
  const lowerAll = new Array<number>(parameters.length).fill(NaN);
  const upperAll = new Array<number>(parameters.length).fill(NaN);
  if (method === "Wald") {
    const z = qnorm((1 + level) / 2) as number;
    parameters.forEach((p, i) => {
      if (p.kind !== "beta") return;
      const se = standardErrors[p.beta!]!;
      lowerAll[i] = p.value - z * se;
      upperAll[i] = p.value + z * se;
    });
  } else if (profile !== undefined) {
    const r = profile();
    r.lower.forEach((v, i) => (lowerAll[i] = v));
    r.upper.forEach((v, i) => (upperAll[i] = v));
  }
  if (!(level > 0 && level < 1)) {
    warnings.push("NaNs produced");
    selected.forEach((i) => { lowerAll[i] = NaN; upperAll[i] = NaN; });
  }
  return {
    names: selected.map((i) => names[i]!),
    lower: selected.map((i) => lowerAll[i]!),
    upper: selected.map((i) => upperAll[i]!),
    warnings,
  };
}

const lmerProfileCache = new WeakMap<LmerResult, Map<number, { lower: number[]; upper: number[] }>>();

function confintLmerImpl(fit: LmerResult, options: MixedConfintOptions): MixedConfintResult {
  const internals = lmerInternals(fit);
  const s = internals.structure;
  const set = parameterSet(s.terms, s.groups, fit.varCorr, fit.fixef, fit.sigma);
  const names = nameParameters(set, fit.fixefNames, logicalOption(options.signames, true));
  const warnings: string[] = [];
  const selected = chooseParameters(names, options.parm, warnings);
  const level = options.level ?? 0.95;
  const method = options.method ?? "profile";
  if (method !== "profile" && method !== "Wald") throw new RangeError(`invalid 'method': ${String(method)}`);
  const profile = (): { lower: number[]; upper: number[] } => {
    let byLevel = lmerProfileCache.get(fit);
    if (byLevel === undefined) { byLevel = new Map(); lmerProfileCache.set(fit, byLevel); }
    const cached = byLevel.get(level);
    if (cached !== undefined) return cached;
    const evaluate = (values: readonly number[], target: number, targetValue: number): number => {
      const sigmaIndex = set.parameters.findIndex((p) => p.kind === "sigma");
      const sigma = values[sigmaIndex]!;
      const theta = thetaOf(s.terms, set.parameters, values, sigma, true);
      if (theta === undefined) return Infinity;
      const targetParameter = set.parameters[target]!;
      let structure: MixedModelStructure = s;
      let reml = internals.reml;
      if (targetParameter.kind === "beta") {
        const j = targetParameter.beta!;
        const delta = targetValue - internals.beta0[j]!;
        structure = {
          ...s,
          y: s.y.map((v, i) => v - s.x[i]![j]! * delta),
          x: s.x.map((row) => row.filter((_, k) => k !== j)),
          xColNames: s.xColNames.filter((_, k) => k !== j),
        };
        reml = false;
      }
      const r = profiledDeviance(structure, theta, reml);
      const n = structure.y.length;
      const p = structure.xColNames.length;
      const df = reml ? n - p : n;
      return r.logDetL + (reml ? r.logDetRX : 0) + r.prss / (sigma * sigma) + df * Math.log(2 * Math.PI * sigma * sigma);
    };
    const r = profileIntervals("lmer", set.parameters, s.terms, true, evaluate, selected.filter((i) => set.parameters[i]!.kind !== "beta" || true), level, warnings);
    byLevel.set(level, r);
    return r;
  };
  const standardErrors = set.parameters.map((p) => (p.kind === "beta" ? fit.coefTable.stdError[p.beta!]! : NaN));
  const result = resultOf(set.parameters, names, selected, level, method, method === "profile" ? profile : undefined, standardErrors, warnings);
  reportWarnings("confintLmer", result.warnings);
  return result;
}

/**
 * Confidence intervals for a linear mixed-model fit. Equivalent to R's `lme4::confint.merMod()`.
 *
 * @category Mixed models
 */
export function confintLmer(fit: LmerResult, options: MixedConfintOptions = {}): MixedConfintResult {
  checkOptions(options, MIXED_CONFINT_KEYS, "confintLmer"); // generated: option-keys.mjs
  return confintLmerImpl(fit, options);
}

/**
 * Confidence intervals for a generalized linear mixed-model fit. Equivalent to R's `lme4::confint.merMod()`.
 *
 * @category Mixed models
 */
export function confintGlmer(fit: GlmerResult, options: MixedConfintOptions = {}): MixedConfintResult {
  checkOptions(options, MIXED_CONFINT_KEYS, "confintGlmer"); // generated: option-keys.mjs
  const internals = glmerInternals(fit);
  const s = internals.structure;
  const set = parameterSet(s.terms, s.groups, fit.varCorr, fit.fixef, undefined);
  const names = nameParameters(set, fit.fixefNames, logicalOption(options.signames, true));
  const warnings: string[] = [];
  const selected = chooseParameters(names, options.parm, warnings);
  const level = options.level ?? 0.95;
  const method = options.method ?? "profile";
  if (method !== "profile" && method !== "Wald") throw new RangeError(`invalid 'method': ${String(method)}`);
  if (method === "profile" && s.nAGQ !== 1) throw new RangeError("profile intervals for glmer require nAGQ = 1");
  const evaluate = (values: readonly number[], target: number, targetValue: number): number => {
    const theta = thetaOf(s.terms, set.parameters, values, 1, false);
    if (theta === undefined) return Infinity;
    const beta = set.parameters.filter((p) => p.kind === "beta").map((p) => values[set.parameters.indexOf(p)]!);
    const targetParameter = set.parameters[target]!;
    if (targetParameter.kind === "beta") beta[targetParameter.beta!] = targetValue;
    return glmerDeviance(s, theta, beta, 1).deviance;
  };
  const profile = (): { lower: number[]; upper: number[] } =>
    profileIntervals("glmer", set.parameters, s.terms, false, evaluate, selected, level, warnings);
  const standardErrors = set.parameters.map((p) => (p.kind === "beta" ? fit.coefTable.stdError[p.beta!]! : NaN));
  const result = resultOf(set.parameters, names, selected, level, method, method === "profile" ? profile : undefined, standardErrors, warnings);
  reportWarnings("confintGlmer", result.warnings);
  return result;
}
