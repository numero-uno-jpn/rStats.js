/** Options of {@link confintLmer} and {@link confintGlmer}.
 *
 * @category Mixed models
 */
export interface MixedConfintOptions {
  /** Two-sided confidence level. Default 0.95. */
  level?: number;
  /** "profile" (default) or "Wald" (fixed effects only). */
  method?: "profile" | "Wald";
  /** Parameter names, one-based positions, "theta_" (variance parameters), or "beta_" (fixed effects). */
  parm?: string | number | readonly (string | number)[];
  /** Use lme4's .sig01 names (default), or descriptive standard-deviation and correlation names. */
  signames?: boolean | number;
}

/** Confidence intervals from a mixed-model fit. Missing limits are NaN.
 *
 * @category Mixed models
 */
export interface MixedConfintResult {
  /** Parameter names in the same order as the limits. */
  names: string[];
  /** Lower confidence limits. */
  lower: number[];
  /** Upper confidence limits. */
  upper: number[];
  /** Warnings from profiling or parameter selection. */
  warnings: string[];
}

const GLMER_PROFILE_SETTINGS: MinimiserSettings = { ...LMER_SETTINGS, releaseTolerance: 1e-10 };

type ParameterKind = "sd" | "cor" | "sigma" | "beta";
interface Parameter {
  name: string;
  descriptive: string;
  kind: ParameterKind;
  value: number;
  term?: number;
  row?: number;
  col?: number;
  beta?: number;
}
interface ParameterSet { parameters: Parameter[] }

function parameterSet(
  terms: readonly RandomEffectsTerm[],
  groups: readonly { name: string }[],
  varCorr: readonly { sd: number[]; corr: number[][] }[],
  beta: readonly number[],
  fixefNames: readonly string[],
  sigma?: number,
): ParameterSet {
  const parameters: Parameter[] = [];
  let serial = 1;
  for (let t = 0; t < terms.length; t++) {
    const term = terms[t]!;
    const vc = varCorr[t]!;
    for (let i = 0; i < term.columns.length; i++) {
      parameters.push({
        name: `.sig${String(serial++).padStart(2, "0")}`,
        descriptive: `sd_${term.columns[i]}|${groups[term.group]!.name}`,
        kind: "sd",
        value: vc.sd[i]!,
        term: t,
        row: i,
      });
    }
    for (let i = 1; i < term.columns.length; i++) {
      for (let j = 0; j < i; j++) {
        parameters.push({
          name: `.sig${String(serial++).padStart(2, "0")}`,
          descriptive: `cor_${term.columns[i]}.${term.columns[j]}|${groups[term.group]!.name}`,
          kind: "cor",
          value: Number.isFinite(vc.corr[i]![j]!) ? vc.corr[i]![j]! : 0,
          term: t,
          row: i,
          col: j,
        });
      }
    }
  }
  if (sigma !== undefined) parameters.push({ name: ".sigma", descriptive: "sigma", kind: "sigma", value: sigma });
  beta.forEach((value, i) => parameters.push({
    name: fixefNames[i]!,
    descriptive: fixefNames[i]!,
    kind: "beta",
    value,
    beta: i,
  }));
  return { parameters };
}

function parameterNames(parameters: readonly Parameter[], signames: boolean): string[] {
  return parameters.map((p) => (p.kind === "beta" || !signames ? p.descriptive : p.name));
}

function transform(p: Parameter): number {
  if (p.kind === "sd" || p.kind === "sigma") return Math.log(Math.max(p.value, 1e-14));
  if (p.kind === "cor") return Math.atanh(Math.max(-1 + 1e-12, Math.min(1 - 1e-12, p.value)));
  return p.value;
}
function inverseTransform(p: Parameter, value: number): number {
  if (p.kind === "sd" || p.kind === "sigma") return Math.exp(value);
  if (p.kind === "cor") return Math.tanh(value);
  return value;
}

function choleskyCorrelation(corr: number[][]): number[][] | undefined {
  const n = corr.length;
  const l = Array.from({ length: n }, () => new Array<number>(n).fill(0));
  for (let i = 0; i < n; i++) {
    for (let j = 0; j <= i; j++) {
      let value = corr[i]![j]!;
      for (let k = 0; k < j; k++) value -= l[i]![k]! * l[j]![k]!;
      if (i === j) {
        if (value < -1e-12 || !Number.isFinite(value)) return undefined;
        l[i]![j] = Math.sqrt(Math.max(0, value));
      } else {
        const diagonal = l[j]![j]!;
        if (diagonal === 0) {
          if (Math.abs(value) > 1e-12) return undefined;
          l[i]![j] = 0;
        } else {
          l[i]![j] = value / diagonal;
        }
      }
    }
  }
  return l;
}

function thetaOf(
  terms: readonly RandomEffectsTerm[],
  parameters: readonly Parameter[],
  values: readonly number[],
  sigma: number,
  scaleBySigma: boolean,
): number[] | undefined {
  const theta: number[] = [];
  for (let t = 0; t < terms.length; t++) {
    const nc = terms[t]!.columns.length;
    const sd = new Array<number>(nc);
    const corr: number[][] = Array.from({ length: nc }, (_, i) => Array.from({ length: nc }, (_, j) => (i === j ? 1 : 0)));
    for (let k = 0; k < parameters.length; k++) {
      const p = parameters[k]!;
      if (p.term !== t) continue;
      if (p.kind === "sd") sd[p.row!] = values[k]!;
      else if (p.kind === "cor") corr[p.row!]![p.col!] = corr[p.col!]![p.row!] = values[k]!;
    }
    const l = choleskyCorrelation(corr);
    if (l === undefined) return undefined;
    const scale = scaleBySigma ? sigma : 1;
    for (let j = 0; j < nc; j++) for (let i = j; i < nc; i++) theta.push((sd[i]! / scale) * l[i]![j]!);
  }
  return theta;
}

function selectParameters(parameters: readonly Parameter[], names: readonly string[], raw: MixedConfintOptions["parm"], warnings: string[]): number[] {
  if (raw === undefined) return parameters.map((_, i) => i);
  const requested = Array.isArray(raw) ? raw : [raw];
  const selected = new Set<number>();
  for (const item of requested) {
    if (typeof item === "number" || (typeof item === "string" && /^\d+$/.test(item))) {
      const index = (typeof item === "number" ? Math.trunc(item) : Number(item)) - 1;
      if (index >= 0 && index < parameters.length) selected.add(index);
      continue;
    }
    if (item === "theta_") {
      parameters.forEach((p, i) => { if (p.kind !== "beta") selected.add(i); });
      continue;
    }
    if (item === "beta_") {
      parameters.forEach((p, i) => { if (p.kind === "beta") selected.add(i); });
      continue;
    }
    const index = typeof item === "string" ? names.indexOf(item) : -1;
    if (index >= 0) selected.add(index);
    else warnings.push(`Nothing selected by 'which="${String(item)}"'`);
  }
  return [...selected].sort((a, b) => a - b);
}

/** Minimise the profile criterion with one user-scale parameter fixed. */
function profileAt(
  kind: "lmer" | "glmer",
  parameters: readonly Parameter[],
  evaluate: (values: readonly number[], target: number, targetValue: number) => number,
  target: number,
  targetValue: number,
): number {
  const free = parameters.map((p, i) => (i === target || (kind === "lmer" && p.kind === "beta") ? -1 : i)).filter((i) => i >= 0);
  const start = free.map((i) => transform(parameters[i]!));
  const valueAt = (x: readonly number[]): number => {
    const values = parameters.map((p) => p.value);
    free.forEach((i, j) => (values[i] = inverseTransform(parameters[i]!, x[j]!)));
    values[target] = targetValue;
    return evaluate(values, target, targetValue);
  };
  if (free.length === 0) return valueAt([]);
  const problem: MinimiserProblem = {
    evaluate: (x) => {
      const f = valueAt(x);
      const g = x.map((v, j) => {
        const h = (kind === "glmer" ? 1e-4 : 2e-5) * Math.max(1, Math.abs(v));
        const plus = x.slice();
        const minus = x.slice();
        plus[j] = v + h;
        minus[j] = v - h;
        const fp = valueAt(plus);
        const fm = valueAt(minus);
        if (Number.isFinite(fp) && Number.isFinite(fm)) return (fp - fm) / (2 * h);
        if (Number.isFinite(fp) && Number.isFinite(f)) return (fp - f) / h;
        if (Number.isFinite(fm) && Number.isFinite(f)) return (f - fm) / h;
        return 0;
      });
      return { f, g };
    },
    diagonal: new Array<boolean>(free.length).fill(false),
    columns: [],
    settings: kind === "glmer" ? GLMER_PROFILE_SETTINGS : LMER_SETTINGS,
    rejectNonFinite: true,
    failure: "mixed-model profile minimisation did not converge",
    robust: true,
  };
  // A profile point can be harder to minimise than the fitted model. If the trust-region
  // iteration stalls, restart from its best finite point; never treat an unconverged value as a profile.
  let from = start;
  for (let attempt = 0; attempt < 2; attempt++) {
    try {
      const result = minimiseWithRestarts(problem, from, [], { bestOnFailure: true });
      if (result.converged) return result.f;
      if (result.theta.every((v, i) => v === from[i])) break;
      from = result.theta;
    } catch {
      return Infinity;
    }
  }
  return Infinity;
}

/** Find one profile endpoint by bracketing and bisection of the signed likelihood-root equation. */
function profileLimit(
  estimate: number,
  parameter: Parameter,
  cutoff: number,
  direction: -1 | 1,
  profile: (value: number) => number,
): number {
  // Standard deviations and sigma have only a lower boundary; their upper endpoints are unbounded.
  const boundary = parameter.kind === "sd" || parameter.kind === "sigma"
    ? (direction < 0 ? 0 : undefined)
    : parameter.kind === "cor" ? (direction < 0 ? -1 : 1) : undefined;
  if (boundary !== undefined && estimate === boundary) return boundary;
  const at = (x: number): number => profile(x) - cutoff;
  let inside = estimate;
  let step = Math.max(parameter.kind === "beta" ? 0.25 : Math.abs(estimate) * 0.2, 0.05);
  let outside = estimate + direction * step;
  if (boundary !== undefined) outside = direction < 0 ? Math.max(boundary, outside) : Math.min(boundary, outside);
  const fInside = at(inside);
  if (!Number.isFinite(fInside) || !(fInside < 0)) return NaN;
  let fOutside = at(outside);
  // A failed nuisance minimisation is not evidence that the profile crossed the cutoff. Move closer until
  // the profile is finite; only finite values below the cutoff justify expanding the bracket.
  for (let i = 0; i < 36 && !(Number.isFinite(fOutside) && fOutside >= 0); i++) {
    if (boundary !== undefined && outside === boundary) {
      return (parameter.kind === "sd" || parameter.kind === "sigma") && direction < 0 ? boundary : NaN;
    }
    const previous = outside;
    step = Number.isFinite(fOutside) ? step * 1.8 : step * 0.5;
    outside = estimate + direction * step;
    if (boundary !== undefined) outside = direction < 0 ? Math.max(boundary, outside) : Math.min(boundary, outside);
    if (outside === previous || outside === inside) break;
    fOutside = at(outside);
  }
  if (!Number.isFinite(fOutside) || !(fOutside >= 0)) {
    return (parameter.kind === "sd" || parameter.kind === "sigma") && direction < 0 ? 0 : NaN;
  }
  // Illinois' safeguarded secant method usually needs far fewer profile minimisations than bisection.
  // The bracket is retained; a bisection fallback guarantees the requested endpoint precision.
  let a = inside;
  let b = outside;
  let fa = fInside;
  let fb = fOutside;
  let wa = fa;
  let wb = fb;
  for (let i = 0; i < 24; i++) {
    let candidate = a - wa * (b - a) / (wb - wa);
    const low = Math.min(a, b);
    const high = Math.max(a, b);
    const margin = 0.05 * (high - low);
    if (!Number.isFinite(candidate) || candidate <= low + margin || candidate >= high - margin) {
      candidate = a + (b - a) / 2;
    }
    let fc = at(candidate);
    if (!Number.isFinite(fc)) {
      candidate = a + (b - a) / 2;
      fc = at(candidate);
      if (!Number.isFinite(fc)) return NaN;
    }
    if (fc === 0) return candidate;
    if (fc >= 0) {
      b = candidate;
      fb = fc;
      wb = fb;
      wa *= 0.5;
    } else {
      a = candidate;
      fa = fc;
      wa = fa;
      wb *= 0.5;
    }
    if (Math.abs(b - a) <= 2e-10 * Math.max(1, Math.abs(candidate))) return a + (b - a) / 2;
  }
  for (let i = 0; i < 56; i++) {
    const candidate = a + (b - a) / 2;
    const fc = at(candidate);
    if (!Number.isFinite(fc)) return NaN;
    if (fc >= 0) {
      b = candidate;
      fb = fc;
    } else {
      a = candidate;
      fa = fc;
    }
    if (Math.abs(b - a) <= 2e-10 * Math.max(1, Math.abs(candidate))) break;
  }
  const root = a + (b - a) / 2;
  if (Math.abs(b - a) > 2e-10 * Math.max(1, Math.abs(root))) return NaN;
  return root;
}

type IntervalCache = Map<number, [number, number]>;
function profileIntervals(
  kind: "lmer" | "glmer",
  parameters: readonly Parameter[],
  evaluate: (values: readonly number[], target: number, targetValue: number) => number,
  selected: readonly number[],
  level: number,
  cache: IntervalCache,
  warnings: string[],
): { lower: number[]; upper: number[] } {
  const z = qnorm((1 + level) / 2) as number;
  const lower = new Array<number>(parameters.length).fill(NaN);
  const upper = new Array<number>(parameters.length).fill(NaN);
  for (const index of selected) {
    const cached = cache.get(index);
    if (cached !== undefined) {
      lower[index] = cached[0];
      upper[index] = cached[1];
      if ((Number.isNaN(cached[0]) || Number.isNaN(cached[1])) && !warnings.includes("NAs detected in profiling")) warnings.push("NAs detected in profiling");
      continue;
    }
    const parameter = parameters[index]!;
    const estimate = parameter.value;
    const pointCache = new Map<number, number>();
    const profile = (value: number): number => {
      const cached = pointCache.get(value);
      if (cached !== undefined) return cached;
      const result = profileAt(kind, parameters, evaluate, index, value);
      pointCache.set(value, result);
      return result;
    };
    const dHat = profile(estimate);
    if (!Number.isFinite(dHat)) {
      if (!warnings.includes("NAs detected in profiling")) warnings.push("NAs detected in profiling");
      cache.set(index, [NaN, NaN]);
      continue;
    }
    const cutoff = dHat + z * z;
    const lo = profileLimit(estimate, parameter, cutoff, -1, profile);
    const hi = profileLimit(estimate, parameter, cutoff, 1, profile);
    lower[index] = lo;
    upper[index] = hi;
    cache.set(index, [lo, hi]);
    if ((Number.isNaN(lo) || Number.isNaN(hi)) && !warnings.includes("NAs detected in profiling")) warnings.push("NAs detected in profiling");
  }
  return { lower, upper };
}

function finish(
  parameters: readonly Parameter[],
  names: readonly string[],
  selected: readonly number[],
  level: number,
  method: "profile" | "Wald",
  profile: (() => { lower: number[]; upper: number[] }) | undefined,
  standardErrors: readonly number[],
  warnings: string[],
): MixedConfintResult {
  const lowerAll = new Array<number>(parameters.length).fill(NaN);
  const upperAll = new Array<number>(parameters.length).fill(NaN);
  if (!(level > 0 && level < 1)) {
    warnings.push("NaNs produced");
  } else if (method === "Wald") {
    const z = qnorm((1 + level) / 2) as number;
    parameters.forEach((p, i) => {
      if (p.kind !== "beta") return;
      const se = standardErrors[i]!;
      lowerAll[i] = p.value - z * se;
      upperAll[i] = p.value + z * se;
    });
  } else if (profile !== undefined && selected.length > 0) {
    const r = profile();
    r.lower.forEach((v, i) => (lowerAll[i] = v));
    r.upper.forEach((v, i) => (upperAll[i] = v));
  }
  return {
    names: selected.map((i) => names[i]!),
    lower: selected.map((i) => lowerAll[i]!),
    upper: selected.map((i) => upperAll[i]!),
    warnings,
  };
}

const lmerCache = new WeakMap<LmerResult, Map<number, IntervalCache>>();

function confintLmerImpl(fit: LmerResult, options: MixedConfintOptions): MixedConfintResult {
  const internals = lmerInternals(fit);
  const s = internals.structure;
  const set = parameterSet(s.terms, s.groups, fit.varCorr, fit.fixef, fit.fixefNames, fit.sigma);
  const signames = logicalOption(options.signames, true);
  const names = parameterNames(set.parameters, signames);
  const warnings: string[] = [];
  const selected = selectParameters(set.parameters, names, options.parm, warnings);
  const level = options.level ?? 0.95;
  const method = options.method ?? "profile";
  if (method !== "profile" && method !== "Wald") throw new RangeError(`invalid 'method': ${String(method)}`);
  const evaluate = (values: readonly number[], target: number, targetValue: number): number => {
    const sigmaIndex = set.parameters.findIndex((p) => p.kind === "sigma");
    const sigma = values[sigmaIndex]!;
    const theta = thetaOf(s.terms, set.parameters, values, sigma, true);
    if (theta === undefined) return Infinity;
    const targetParameter = set.parameters[target]!;
    let structure: MixedModelStructure = s;
    let reml = internals.reml;
    if (targetParameter.kind === "beta") {
      const j = targetParameter.beta!;
      const delta = targetValue - internals.beta0[j]!;
      structure = {
        ...s,
        y: s.y.map((v, i) => v - s.x[i]![j]! * delta),
        x: s.x.map((row) => row.filter((_, k) => k !== j)),
        xColNames: s.xColNames.filter((_, k) => k !== j),
        xAssign: s.xAssign.filter((_, k) => k !== j),
      };
      // A fixed-effect profile uses the ML criterion, including for a fit originally estimated by REML.
      reml = false;
    }
    const r = profiledDeviance(structure, theta, reml);
    const n = structure.y.length;
    const p = structure.xColNames.length;
    const df = reml ? n - p : n;
    return r.logDetL + (reml ? r.logDetRX : 0) + r.prss / (sigma * sigma) + df * Math.log(2 * Math.PI * sigma * sigma);
  };
  const byLevel = lmerCache.get(fit) ?? new Map<number, IntervalCache>();
  lmerCache.set(fit, byLevel);
  const cache = byLevel.get(level) ?? new Map<number, [number, number]>();
  byLevel.set(level, cache);
  const profile = (): { lower: number[]; upper: number[] } =>
    profileIntervals("lmer", set.parameters, evaluate, selected, level, cache, warnings);
  const standardErrors = set.parameters.map((p) => (p.kind === "beta" ? fit.coefTable.stdError[p.beta!]! : NaN));
  const result = finish(set.parameters, names, selected, level, method, profile, standardErrors, warnings);
  reportWarnings("confintLmer", result.warnings);
  return result;
}

/**
 * Confidence intervals for a linear mixed-model fit. Equivalent to `lme4::confint.merMod()` in R.
 *
 * @category Mixed models
 */
export function confintLmer(fit: LmerResult, options: MixedConfintOptions = {}): MixedConfintResult {
  checkOptions(options, CONFINT_LMER_KEYS, "confintLmer"); // generated: option-keys.mjs
  return confintLmerImpl(fit, options);
}

/**
 * Confidence intervals for a generalized linear mixed-model fit. Equivalent to R's `lme4::confint.merMod()`.
 *
 * @category Mixed models
 */
export function confintGlmer(fit: GlmerResult, options: MixedConfintOptions = {}): MixedConfintResult {
  checkOptions(options, CONFINT_GLMER_KEYS, "confintGlmer"); // generated: option-keys.mjs
  const level = options.level ?? 0.95;
  const method = options.method ?? "profile";
  if (method !== "profile" && method !== "Wald") throw new RangeError(`invalid 'method': ${String(method)}`);
  if (method === "profile" && fit.nAGQ !== 1) throw new RangeError("profile intervals for glmer require nAGQ = 1");
  const internals = glmerInternals(fit);
  const s = internals.structure;
  const set = parameterSet(s.terms, s.groups, fit.varCorr, fit.fixef, fit.fixefNames);
  const names = parameterNames(set.parameters, logicalOption(options.signames, true));
  const warnings: string[] = [];
  const selected = selectParameters(set.parameters, names, options.parm, warnings);
  const evaluate = (values: readonly number[], target: number, targetValue: number): number => {
    const theta = thetaOf(s.terms, set.parameters, values, 1, false);
    if (theta === undefined) return Infinity;
    const beta = set.parameters.filter((p) => p.kind === "beta").map((p) => values[set.parameters.indexOf(p)]!);
    const targetParameter = set.parameters[target]!;
    if (targetParameter.kind === "beta") beta[targetParameter.beta!] = targetValue;
    return glmerDeviance(s, theta, beta, 1).deviance;
  };
  const profile = (): { lower: number[]; upper: number[] } =>
    profileIntervals("glmer", set.parameters, evaluate, selected, level, new Map(), warnings);
  const standardErrors = set.parameters.map((p) => (p.kind === "beta" ? fit.coefTable.stdError[p.beta!]! : NaN));
  const result = finish(set.parameters, names, selected, level, method, profile, standardErrors, warnings);
  reportWarnings("confintGlmer", result.warnings);
  return result;
}
