# lm influence
infl <- function(f) {
  r <- run(list(hat = num(hatvalues(f)), rstandard = num(rstandard(f)), rstandardPred = num(rstandard(f, type = "predictive")),
                rstudent = num(rstudent(f)), cooks = num(cooks.distance(f)), dffits = num(dffits(f)), covratio = num(covratio(f))))
  r
}
