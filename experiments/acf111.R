out$ccf_numeric <- run(C(as.vector(mdeaths), as.vector(fdeaths), lag.max = 4))
out$ccf_partial <- run(C(mdeaths, fdeaths, type = "partial"))
out$ccf_self <- run(C(lh, lh, lag.max = 5))
x10 <- c(3, 1, 4, 1, 5, 9, 2, 6, 5, 3); y10 <- c(2, 7, 1, 8, 2, 8, 1, 8, 2, 8)
