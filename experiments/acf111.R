## the dotted lines of plot.acf (white noise): qnorm((1 + ci) / 2) / sqrt(n.used), recorded with n.used to compare
cl <- function(r, ci = 0.95) list(n.used = r$n.used, clim = qnorm((1 + ci) / 2) / sqrt(r$n.used))
out$clim_lh <- run(cl(acf(lh, plot = FALSE)))
out$clim_lh_99 <- run(cl(acf(lh, plot = FALSE), 0.99))
out$clim_presidents_pass <- run(cl(acf(presidents, na.action = na.pass, plot = FALSE)))

