# a matrix with one column is a univariate series; with two it is multivariate (out of scope, shapes only)
out$acf_matrix_1col <- run(A(matrix(as.vector(lh), ncol = 1)))
out$acf_matrix_2col <- run(A(cbind(a = as.vector(mdeaths), b = as.vector(fdeaths)), lag.max = 2))
