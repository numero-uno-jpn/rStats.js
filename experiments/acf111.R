library(jsonlite)
# Helpers (the same in each script): run() records the value, the warnings, the messages and the error of one call
run <- function(expr) {
  warns <- character(0); msgs <- character(0)
  value <- withCallingHandlers(
    tryCatch(expr, error = function(e) structure(list(message = conditionMessage(e)), class = "caught")),
    warning = function(w) { warns <<- c(warns, conditionMessage(w)); invokeRestart("muffleWarning") },
    message = function(m) { msgs <<- c(msgs, conditionMessage(m)); invokeRestart("muffleMessage") })
  if (inherits(value, "caught")) return(list(error = value$message, warnings = warns, messages = msgs))
  list(value = value, warnings = warns, messages = msgs)
}
# the documented components of an "acf" object: lag, acf (3-d arrays flattened for one series), type, n.used, snames
ac <- function(r) list(lag = as.vector(r$lag), acf = as.vector(r$acf), dim = dim(r$acf), type = r$type,
                       n.used = r$n.used, snames = r$snames)
A <- function(...) ac(acf(..., plot = FALSE))
P <- function(...) ac(pacf(..., plot = FALSE))
C <- function(...) ac(ccf(..., plot = FALSE))
out <- list()

