out$acf_nan <- run(A(c(1, 3, NaN, 2, 5, 4, 6), na.action = na.pass))
out$acf_inf <- run(A(c(1, 3, Inf, 2, 5, 4, 6)))
out$acf_all_na_pass <- run(A(c(NA, NA, NA, 1), na.action = na.pass))
# short and degenerate series
out$acf_n1 <- run(A(5))
out$acf_n2 <- run(A(c(1, 4)))
