out$acf_integer <- run(A(as.integer(c(3, 1, 4, 1, 5, 9, 2, 6, 5, 3))))
out$acf_logical <- run(A(c(TRUE, FALSE, TRUE, TRUE, FALSE)))
out$acf_character <- run(A(c("a", "b", "c")))
out$acf_empty <- run(A(numeric(0)))
out$acf_scale_big <- run(A(as.vector(lh) * 2^300, type = "covariance"))
out$acf_scale_big_cor <- run(A(as.vector(lh) * 2^300))
out$acf_scale_small <- run(A(as.vector(lh) * 2^-300))
