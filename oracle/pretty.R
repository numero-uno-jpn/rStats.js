source("/oracle/_htest.R")

# pretty(): break points from a range. Argument names are the JS names (minN for min.n, highUBias for high.u.bias,
# u5Bias for u5.bias). Inputs cover the ordinary case, zero and tiny ranges (relative to the magnitude), min.n
# widening on either side, the biases, non-finite values, subnormal and huge magnitudes.

cases <- list()
add <- function(...) cases[[length(cases) + 1]] <<- list(...)
add(x = I(c(0.3, 9.6)))
add(x = I(c(0, 1)))
add(x = I(c(-1.234, 5.67)))
add(x = I(c(0, 0)))
add(x = I(c(5, 5)))
add(x = I(c(1234, 1234)))
add(x = I(c(-12, -12)))
add(x = I(c(1e-300, 1e-300)))
add(x = I(c(-0.1, 0.1)))
add(x = I(c(1, 100)))
add(x = I(c(0.0011, 0.0049)))
add(x = I(c(-7, -3)))
add(x = I(c(0, 1)), n = 10)
add(x = I(c(0, 1)), n = 1)
add(x = I(c(0, 1)), n = 0)
add(x = I(c(0.1, 0.3)), n = 1, minN = 1)
add(x = I(c(17.3, 17.3000001)))
add(x = I(c(100, 100.00000000000003)))
add(x = I(c(-1e-12, 3e-12)))
add(x = I(c(1, 1e6)), n = 3)
add(x = I(c(2.1, 2.9)), n = 1, minN = 1)
add(x = I(c(0, 7)), n = 2)
add(x = I(c(10, 10)), minN = 3)
add(x = I(c(-5, 0)), n = 5, minN = 4)
add(x = I(c(-3, 0)), n = 8, minN = 8)
add(x = I(c(0, 3)), n = 8, minN = 8)
add(x = I(c(2, 3)), n = 5, minN = 5)
add(x = I(c(0.1, 0.7)))
add(x = I(c(-0.7, -0.1)))
add(x = I(c(1 / 3, 2 / 3)), n = 3)
add(x = I(c(-3, 0, 0, 2, 8, -1, 0, 5)), n = 4, minN = 1)
add(x = I(c(NaN, Inf, 1, 2)))
add(x = I(c(NaN, Inf)))
add(x = I(c(0, 1e-320)))
add(x = I(c(1e300, 1.0000000000001e300)))
add(x = I(c(-1, 1)), n = 2, minN = 2)
add(x = I(c(3, 3)), n = 1, minN = 1)
add(x = I(c(0.5, 0.5)), n = 1, minN = 1)
add(x = I(c(-0.001, 0.001)))
add(x = I(c(1.5, 2.5)), n = 2, highUBias = 0)
add(x = I(c(0, 15)), n = 2, highUBias = 0)
add(x = I(c(0, 15)), n = 2, highUBias = 3)
add(x = I(c(0, 13)), n = 2, u5Bias = 4)
add(x = I(c(-1e308, 1e308)))
# (added later, at the end) n must not be negative or NaN (checked after dropping the values that are not finite)
add(x = I(c(1, 10)), n = -1)
add(x = I(c(1, 10)), n = NaN)
add(x = I(c(NaN, Inf)), n = -1)
add(x = I(c(1, 10)), n = 2.7)
# n and min.n are truncated to integers; min.n (default n %/% 3 of the n given) must be in [0, n]
add(x = I(c(1, 10)), n = -0.5)
add(x = I(c(1, 10)), n = 2.9)
add(x = I(c(1, 10)), n = -0.2, minN = 0)
add(x = I(c(1, 10)), n = 3, minN = 4)
add(x = I(c(1, 10)), n = 3, minN = -1)
add(x = I(c(1, 10)), n = 5, minN = NaN)
add(x = I(c(1, 10)), n = 5, minN = 2.7)
add(x = I(c(1, 10)), n = 1e10)
write_htest_fixture("pretty", cases, function(a)
  list(value = I(num2str(call_with(pretty, list(x = a$x, n = a$n, min.n = a$minN, high.u.bias = a$highUBias,
                                                 u5.bias = a$u5Bias))))))
