// Issue #57: qr recomputes a remaining column norm when 1 - (|x|/norm)^2 < 1e-6, as R (review_fix_log_issue57.md).
import { describe, expect, it } from "vitest";
import { qr } from "../src/index.js";

describe("issue #57", () => {
  it("keeps the column whose remaining norm is just above the tolerance (R 4.5.2: rank 2)", () => {
    // LINPACK's test missed the cancellation: rank 1, the second column moved to the end
    const q = qr([
      [0.3, 0.3],
      [0, 3.00000003e-8],
      [0, 0],
    ]);
    expect(q.rank).toBe(2);
    expect(q.pivot).toEqual([0, 1]);
  });

  it("decides the rank as R near the tolerance", () => {
    // R 4.5.2's ranks (pivot 0, 1, 2 for all); x3 = x1 + 2 x2 + e 1e-7 |x1 + 2 x2| d (d orthogonal to x1, x2) with
    // e near 1, and the issue's matrix with 3e-8 scaled by 1.0000001 and 1.001. The old update got each of them wrong
    const cases: { x: number[][]; rank: number }[] = [
      {
        rank: 2,
        x: [
          [-1.5091234266003286, -1.03702585921071, -3.583175209388443],
          [0.2816896718217512, 0.5194053242681781, 1.3204997611771065],
          [-0.9057482622606846, -0.41825507264165135, -1.7422585508208683],
          [-0.4167724578873425, -0.0376536532305273, -0.49207968686416736],
          [-0.05831498530366864, 1.4403227314214704, 2.8223307004702445],
          [0.2806576688839199, 1.7981058652433102, 3.8768693134970635],
        ],
      },
      {
        rank: 2,
        x: [
          [1.9398974351787275, 2.774917714245807, 7.489732602409596],
          [-2.352934559608001, -0.5508925530833308, -3.4547199114205074],
          [1.24510313668227, 1.6830376560273634, 4.611178876235027],
          [0.6556905119536192, 1.0869665702112021, 2.829622930224567],
          [0.4183548390816167, -0.5982199948827185, -0.7780853996794223],
          [0.06701061741169195, -1.3160609720807144, -2.5651117113502027],
        ],
      },
      {
        rank: 2,
        x: [
          [0.6282390872557221, -0.1849818628548998, 0.25827558838274367],
          [-1.1871631591744871, -2.190101960680459, -5.567367136125385],
          [-0.07467177017213911, -0.3327440947658448, -0.7401597734264762],
          [-0.7630044737962002, 1.7465816442687594, 2.730159009900798],
          [-0.354556418666084, 0.43139855810012406, 0.50824017968924],
          [-1.0419413013793335, -0.6146888028438824, -2.271318687006564],
        ],
      },
      {
        rank: 3,
        x: [
          [-0.10500489994722355, 0.2683532984298957, 0.43170178716465235],
          [-0.15533540789706202, 0.8871008295873075, 1.6188665010155872],
          [0.9549679019942315, -0.4162141822926112, 0.12253957990121143],
          [-0.03799371666453056, 0.2377914132557599, 0.43758922365679115],
          [1.6949600897143364, 0.795029394453622, 3.2850187873938417],
          [-0.728767472091463, 0.7985985630348094, 0.8684294253142528],
        ],
      },
      {
        rank: 3,
        x: [
          [0.788094992209261, -0.20321599792821998, 0.3816632167552501],
          [-0.3633879785396183, 0.9438933343261586, 1.524398896388993],
          [-1.064956404331533, -1.8949697937593784, -4.854896480227594],
          [-1.1084450998936846, -0.6184260271158663, -2.3452971558932645],
          [-0.8539437167176744, 2.5498985240020304, 4.2458530855338985],
          [-1.7152112238824802, -0.9288312580272059, -3.5728732556474903],
        ],
      },
      {
        rank: 2,
        x: [
          [0.3, 0.3],
          [0, 3.0000003e-08],
          [0, 0],
        ],
      },
      {
        rank: 2,
        x: [
          [0.3, 0.3],
          [0, 3.002999999999999e-08],
          [0, 0],
        ],
      },
    ];
    for (const c of cases) {
      const q = qr(c.x);
      expect(q.rank).toBe(c.rank);
      expect(q.pivot).toEqual(c.x[0]!.map((_, j) => j));
    }
  });
});
