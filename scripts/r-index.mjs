// Prints the index "R function -> rStats.js function" as Markdown, one table per area (src/entries/), from the
// sentence naming R's counterpart that every exported function's doc comment has (checked by test/rNames.test.ts):
//
//   Equivalent to R's `t.test()`.          base R and the recommended packages
//   Equivalent to `car::Anova()` in R.     other packages
//   Not an R function.
//
//   node scripts/r-index.mjs > r-index.md
//
// Reads the source directly (no build, no TypeDoc). Needs Node 22.18 or later (loads a .ts helper).

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { collectFunctions, rSentences } from "../test/helpers/docComments.ts";

const root = fileURLToPath(new URL("..", import.meta.url));

/** The area's title: the first comment line of its entry file, up to the subpath in parentheses. */
function areaTitle(entry) {
  const first = readFileSync(`${root}src/entries/${entry}.ts`, "utf8").split("\n")[0];
  return first.replace(/^\/\/\s*/, "").replace(/\s*\(.*$/, "");
}

const sortKey = (name) => name.replace(/^[\w.]+::/, "").replace(/^[.%]/, "").toLowerCase();

const byEntry = new Map();
for (const f of collectFunctions(root)) {
  const { sentences, invalid } = rSentences(f.comments);
  if (sentences.length !== 1 || invalid.length > 0) {
    console.error(`${f.file}: ${f.name} needs exactly one sentence naming R's counterpart`);
    process.exitCode = 1;
    continue;
  }
  if (!byEntry.has(f.entry)) byEntry.set(f.entry, { rows: new Map(), none: [] });
  const area = byEntry.get(f.entry);
  const s = sentences[0];
  if (s.kind === "none") area.none.push(f.name);
  for (const r of s.names) {
    if (!area.rows.has(r)) area.rows.set(r, []);
    area.rows.get(r).push(f.name);
  }
}

const out = ["# R functions in rStats.js", ""];
out.push("Generated by `node scripts/r-index.mjs` from the doc comments. Functions of other packages are written");
out.push("`package::function()`. How the arguments are written: [the guide for JavaScript developers](guide-for-js-developers.md);");
out.push("each function in detail: [the API reference](https://numero-uno-jpn.github.io/rStats.js/api/).", "");
for (const [entry, area] of byEntry) {
  out.push(`## ${areaTitle(entry)} (\`rStats.js/${entry}\`)`, "", "| R | rStats.js |", "| --- | --- |");
  const rows = [...area.rows].sort(([a], [b]) => sortKey(a).localeCompare(sortKey(b)) || a.localeCompare(b));
  for (const [r, fns] of rows) out.push(`| \`${r.replace(/\|/g, "\\|")}\` | ${fns.map((f) => `\`${f}\``).join(", ")} |`);
  if (area.none.length > 0) out.push(`| (not in R) | ${area.none.map((f) => `\`${f}\``).join(", ")} |`);
  out.push("");
}
process.stdout.write(out.join("\n"));
