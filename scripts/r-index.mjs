// Prints the index "R function -> rStats.js function" as Markdown, one table per area (src/entries/), from the
// sentence naming R's counterpart that every exported function's doc comment has (checked by test/rNames.test.ts):
//
//   Equivalent to R's `t.test()`.          base R and the recommended packages
//   Equivalent to `car::Anova()` in R.     other packages
//   Not an R function.
//
//   node scripts/r-index.mjs > docs/r-functions.md
//   node scripts/r-index.mjs --ja > docs/ja/r-functions.md   (Japanese descriptions from docs/ja/r-functions.json)
//
// One row per rStats.js function: its R counterpart, its name, and a short description, the first sentence of its
// doc comment (in Japanese, the entry of docs/ja/r-functions.json, which must have one for every function).
//
// Reads the source directly (no build, no TypeDoc). Needs Node 22.18 or later (loads a .ts helper).

import { existsSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { collectFunctions, rSentences } from "../test/helpers/docComments.ts";

const root = fileURLToPath(new URL("..", import.meta.url));

/** The area's title: the first comment line of its entry file, up to the subpath in parentheses. */
function areaTitle(entry) {
  const first = readFileSync(`${root}src/entries/${entry}.ts`, "utf8").split("\n")[0];
  return first.replace(/^\/\/\s*/, "").replace(/\s*\(.*$/, "");
}

const sortKey = (name) => name.replace(/^[\w.]+::/, "").replace(/^[.%]/, "").toLowerCase();

const ja = process.argv.includes("--ja");
const jaPath = `${root}docs/ja/r-functions.json`;
const jaText = ja ? JSON.parse(readFileSync(jaPath, "utf8")) : {};

/** The first sentence of the first doc comment, as plain text ({@link x} → x, tags left out). */
function description(f) {
  const text = (f.comments[0] ?? "")
    .split("\n")
    .map((l) => l.replace(/^\s*\*\s?/, ""))
    .filter((l) => !l.startsWith("@"))
    .join(" ")
    .replace(/\{@link\s+([^}|\s]+)[^}]*\}/g, "`$1`")
    .replace(/\s+/g, " ")
    .trim();
  let first = text.split(/(?<=[.:])\s(?=[A-Z`(])/)[0].replace(/:$/, ".");
  // Leave out remarks in parentheses after a space ("Median (the mean of ...)."): only those with a word of three
  // or more letters, so that mathematics such as "on (a, b)" or "n! / (n - k)!" stays
  const remark = /\s\(([^()]*)\)/g;
  for (let prev = ""; prev !== first; ) {
    prev = first;
    first = first.replace(remark, (m, inner) => (/[A-Za-z]{3,}/.test(inner) ? "" : m));
  }
  return first;
}

const cell = (t) => t.replace(/\|/g, "\\|");

const byEntry = new Map();
for (const f of collectFunctions(root)) {
  const { sentences, invalid } = rSentences(f.comments);
  if (sentences.length !== 1 || invalid.length > 0) {
    console.error(`${f.file}: ${f.name} needs exactly one sentence naming R's counterpart`);
    process.exitCode = 1;
    continue;
  }
  const text = ja ? jaText[f.name] : description(f);
  if (text === undefined) {
    console.error(`docs/ja/r-functions.json has no description of ${f.name}`);
    process.exitCode = 1;
    continue;
  }
  if (!byEntry.has(f.entry)) byEntry.set(f.entry, []);
  const s = sentences[0];
  const rNames = s.kind === "none" ? [] : s.names;
  byEntry.get(f.entry).push({ r: rNames, name: f.name, text });
}

const out = ja
  ? [
      "# R の関数と rStats.js の関数",
      "",
      "R の関数から、rStats.js でそれに当たる関数を引くための一覧です (`node scripts/r-index.mjs --ja` で生成)。ほかのパッケージの",
      "関数は `package::function()` と書いています。引数の書き方は [JavaScript の開発者のための rStats.js](guide-for-js-developers.md) を、",
      "各関数の詳しい説明は [API リファレンス](https://numero-uno-jpn.github.io/rStats.js/api/) (英語) を参照してください。",
      "",
    ]
  : [
      "# R functions in rStats.js",
      "",
      "Generated by `node scripts/r-index.mjs` from the doc comments. Functions of other packages are written",
      "`package::function()`. How the arguments are written: [the guide for JavaScript developers](guide-for-js-developers.md);",
      "each function in detail: [the API reference](https://numero-uno-jpn.github.io/rStats.js/api/).",
      "",
    ];
const head = ja ? "| R | rStats.js | 説明 |" : "| R | rStats.js | Description |";
for (const [entry, rows] of byEntry) {
  out.push(`## ${ja ? (jaText[`#${entry}`] ?? areaTitle(entry)) : areaTitle(entry)} (\`rStats.js/${entry}\`)`, "", head, "| --- | --- | --- |");
  // Functions not in R last; the others by R's name
  const key = (row) => (row.r.length > 0 ? sortKey(row.r[0]) : row.name.toLowerCase());
  rows.sort((a, b) => Number(a.r.length === 0) - Number(b.r.length === 0) || key(a).localeCompare(key(b)) || a.name.localeCompare(b.name));
  for (const row of rows) {
    const r = row.r.length > 0 ? row.r.map((n) => `\`${cell(n)}\``).join(", ") : ja ? "(R にない)" : "(not in R)";
    out.push(`| ${r} | \`${row.name}\` | ${cell(row.text)} |`);
  }
  out.push("");
}
if (ja) {
  const known = new Set([...byEntry.values()].flat().map((r) => r.name));
  const extra = Object.keys(jaText).filter((k) => !k.startsWith("#") && !known.has(k));
  if (extra.length > 0) {
    console.error(`docs/ja/r-functions.json describes functions that are not exported: ${extra.join(", ")}`);
    process.exitCode = 1;
  }
}
process.stdout.write(out.join("\n"));
